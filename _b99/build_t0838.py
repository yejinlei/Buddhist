"【三兽喻·驴马】婆罗门！譬如有人乘三种兽欲诣宝所，虽所履之道随有差别，彼所向之处而无有异。其三兽者谓：驴、马、象。那驴乘者力势羸劣，由此因缘，是人虽至宝所，不能以其珍宝广施众生，但乐自利取证涅槃；那马乘者轻利快捷，由彼力故，是人虽至宝所，也不能以其珍宝广施众生，但与众生作净福田；【义解】以乘驴、马、象三种兽往宝所为喻：驴力劣，虽至宝所但乐自利取证涅槃（喻声闻）；马力捷，虽至宝所但为众生作净福田（喻缘觉）。",

"【三兽喻·象·大乘】那象乘者行步平正、勇健多力，由彼力故，是人得至一切宝聚广大城中，到了那城已即作此念：『三乘珍宝皆于此出，我当以此无量珍宝，普施无边一切众生，广为众生作大利乐。』婆罗门！三乘行人修三乘法，也是这样。【义解】象行步平正、勇健多力，能至一切宝聚大城，发愿以无量珍宝普施众生（喻大乘菩萨）。",

"【三乘配三兽·涅槃无别】那驴乘者即声闻乘；那马乘者即缘觉乘；那象乘者即是大乘。你今当知，那三乘道虽种种相，所证涅槃、所得解脱，无种种相也无差别。「婆罗门！又如世间有三士夫，俱欲过渡一条深大河。那第一人依一小叶浮水而渡；【义解】三乘配三兽：驴＝声闻，马＝缘觉，象＝大乘。三乘道虽相异，所证涅槃、解脱无别。下以渡河为喻。",

"【渡河喻·叶板船】那第二人而胜于前，依其板木浮水而渡；那第三人又胜于前，乘以大船与多人之众，安隐而渡得至彼岸，此又如世间长子，使其父母无所防护，于一切处离诸忧恼。婆罗门！那第一人依叶而渡者，当知即是声闻乘人；【义解】第一人依小叶渡、第二人依板木渡、第三人乘大船与众共渡（如长子护父母），喻三乘之别。",

"【渡河喻·配三乘】那第二人依其板木而得渡者，当知即是缘觉乘人；那第三人乘船得渡者，当知即是菩萨乘人，自所得度复度他人。婆罗门！是故当知，那三乘人所修行法虽种种相，而声闻、缘觉及彼如来所证涅槃无种种相。【义解】依叶渡＝声闻，依板木渡＝缘觉，乘船渡＝菩萨（自度度他）。三乘所修法虽相异，所证涅槃无有异相。",

"【偈颂·三乘涅槃同一】」那时，世尊欲重宣此义而说偈曰：「三乘证涅槃，同一涅槃法；证道虽差别，涅槃无二相。三世一切佛，得最上解脱；如是等法眼，正觉尊所说。是最上法智，出生诸方便；诸有修行者，应当如是学。」西天译经三藏、朝奉大夫、试光禄卿、传法大师、赐紫臣施护奉诏译。【义解】偈颂：三乘所证涅槃同一，涅槃无二相。末复出译人署名（与前文重复，原文如此）。",

"【问大乘行·四摄】那时，大婆罗门白佛言：「世尊！诸修大乘法者当行何行？」佛告婆罗门言：「如我今说，当如是行。婆罗门！你今当知，若有修大乘法者，自发阿耨多罗三藐三菩提心已，复劝他人发如是心，于此经法广为他人宣说教示，如是等人应当亲近尊重恭敬，是人以四摄法普摄众生。【义解】佛答：修大乘者自发心、复劝他发、广为他人宣说此经，以四摄法普摄众生。",

"【四摄·布施爱语】何等为四？所谓：布施、爱语、利行、同事。此中何名布施？所谓：于财施中若少若多，随其自力起广大心，以此所施摄彼悭贪，如是名为修大乘者布施所摄。何名爱语？所谓：于一切处见诸众生，应当面目熙怡、语言柔顺，以诸方便安慰善来，以此爱语摄彼粗恶，如是名为修大乘者爱语所摄。【义解】四摄：布施、爱语、利行、同事。布施摄悭贪，爱语摄粗恶。",

"【四摄·利行同事】何名利行？所谓：见诸善法昼夜勤作，于诸众生起慈愍心，以生净信摄诸无信，以持净戒摄诸毁禁，于一切处常乐利益，如是名为修大乘者利行所摄。何名同事？所谓：于一切处先同其事，复以方便教令精进坚固菩提，诸有智者于如是法当如是行，如是行者是为菩萨所修正行，若如是勇猛乃名最胜，得到彼岸悉能通达最上法门，如是名为修大乘者同事所摄。【义解】利行：令无信者信、毁禁者持戒，常乐利益。同事：先同其事，复令精进坚固菩提。如此名菩萨正行。",

"【问菩萨住处·三住】」那时，婆罗门白佛言：「世尊！诸菩萨摩诃萨依何而住，乃能得成二足尊果？住有几种？愿佛世尊广为宣说所有住法。如是说者，即同宣说菩提法门最上希有」。佛告婆罗门言：「你今当知住有三种。所谓：【义解】菩萨依何而住能成佛果？佛答：住有三种，下分说。",

"【天住】天住、梵住、圣住。此中何名天住？所谓：但修慈行。若人先于东方，身业行慈、语业行慈、意业行慈，广大炽盛，南西北方、四维上下也是这样，身业行慈、语业行慈、意业行慈，广大炽盛，此说名为天住。【义解】三种住：天住、梵住、圣住。天住者：以身、语、意慈业遍满十方，广大炽盛。",

"【梵住·圣住】何名梵住？所谓：修四无量行。何等为四？谓：慈、悲、喜、捨，此说名为梵住。何名圣住？所谓：修三解脱门。何等为三？所谓：空、无相、无愿，此说名为圣住，菩萨摩诃萨当依如是圣住中住。」那时，世尊欲重宣此义，说伽陀曰：【义解】梵住：四无量（慈悲喜捨）。圣住：三解脱门（空、无相、无愿）。菩萨当依圣住而住。",

"【偈颂·三住】「我所说三住，是勇猛胜法，为诸菩萨众，随所应宣说。若于一切时，如说而能行，我当称赞彼，是求菩提者。天住及梵住、圣住亦复然，于此三住中，随应而安住；若如是住者，当得无灭句。」那时，婆罗门白佛言：【义解】偈颂重宣三住：天住、梵住、圣住，随应安住者，当得「无灭句」（涅槃）。",

"【问菩提法门义·偈答】「世尊！菩提法门其义云何？未来世中若有众生问我此义，我无智慧，所有佛法不能通达，我于那时当云何答？愿佛世尊广为我说。」那时，世尊为婆罗门说伽陀曰：「婆罗门当知，我所为你说的；此广大正法，劝发菩提心。【义解】婆罗门问菩提法门之义，佛以偈答：此广大正法，唯在劝发菩提心。",

"【偈颂·闻法断疑·布施圆满】诸无智慧者，由此而获得；若了此法门，是即菩提义。此所说正法，劝发菩提心；随众生所问，一一能开示。此所说正法，劝发菩提心；邪见诸疑惑，一切皆能断。于后末世中，若有人得此，正法堕手者，是人若布施，谓广大财等，即圆满施行；【义解】了此法门即菩提义。末世得此正法者，若行布施，即圆满布施行。",

"【偈颂·持戒忍辱圆满】由施成就故，得到于彼岸。又复末世中，若有人得此，正法堕手者，是人若持戒，清净而无缺，即圆满戒行；由戒成就故，得到于彼岸。又复末世中，若有人得此，正法堕手者，是人若忍辱，安受诸娆恼，即圆满忍行；【义解】末世得此正法者，持戒、忍辱，即圆满戒行、忍行，得至彼岸。",

"【偈颂·精进禅定圆满】由忍成就故，得到于彼岸。又复末世中，若有人得此，正法堕手者，是人若精进，勇猛而发起，即精进行圆；由精进成就，得到于彼岸。又复末世中，若有人得此，正法堕手者，是人若修定，住三摩呬多，即圆满定行；【义解】「三摩呬多」即等引（定）。末世得此正法者，精进、修定，即圆满精进行、定行。",

"【偈颂·智慧圆满·近佛菩提】由定成就故，得到于彼岸。又复末世中，若有人得此，正法堕手者，是人若修慧，解了最胜法，即圆满胜慧；由慧成就故，得到于彼岸。又复末世中，若有人得此，正法堕手者，能尊重供养；当知如是人，名求菩提者，得近佛菩提，决定当成就。【义解】末世得此正法者，修慧圆满，能尊重供养，名求菩提者，得近佛菩提，决定成就。",

"【偈颂·八十俱胝佛加持·赞闻法者】八十俱胝佛，加持此正法；若得堕手者，获最上法聚。若现在佛前，闻此正法者；当知如是人，了知菩萨义。爱乐佛菩提，我知如是人，我见如是人，我念彼名字，我及一切佛，亦共所称赞。若人闻此法，不转为他说，彼生我慢心，造广大过失；【义解】「俱胝」即亿。八十亿佛加持此正法，得之者获最上法聚。闻此法而不为人说、生我慢者，造广大过失。",

"【偈颂·不重法之过·婆罗门赞】当知彼等人，不尊重正法。」那时，婆罗门白佛言：「善哉世尊！善说此法门，即是菩提义。若人于现世中，爱乐了知如是义者，是人不久于此世间得大勇猛，未来世中善说胜法安住菩提，广为多人作大利益。【义解】闻法不为人说者不重正法。婆罗门赞佛善说此法门即菩提义，并谓爱乐此法者当得大勇猛、安住菩提、利益多人。",

"【佛往昔求法·涕泪悲泣】」佛言：「婆罗门！你今已能得正智慧，能说如是利益语言。婆罗门！若有人今于我前闻是法已，我涅槃后于末世中，若能于此正法，书持、读诵者，当知是人爱乐圣道发菩提心。婆罗门！我于往昔求菩提时，于一阿兰若处遇一苾刍宣说此法，我当暂得闻是法时，涕泪悲泣即自思惟：【义解】佛赞婆罗门已得正智。末世书持、读诵此法者，爱乐圣道发菩提心。佛自述往昔求菩提时，于阿兰若（寂静处）遇一苾刍说此法，闻时涕泪悲泣。",

"【佛往昔·施食请法】『我宿世中以何业障，于此正法先不得闻？』作是念已，即取摶食施彼苾刍，后复白言：『如所闻法我不能知，我今乐闻，愿为广说。』那时，那苾刍如其所应为我宣说。婆罗门！我于那时闻是法已即发愿言：【义解】佛自念宿世业障故先不得闻此法，遂以抟食（食物）施彼比丘，请为广说，比丘为说，佛闻已发愿。",

"【发愿弘经·悲愍末世】『愿我当来以此正法，于末世中加持护念，广为众生宣布演说。』婆罗门！我时又念：『今此正法我于何时能为众生如应宣说？后末世中诸众生类，少能于此爱乐修习。』后彼彼时，此法在世佛不现前，我于是事深生悲愍。【义解】佛发愿当来以此正法于末世加持护念、广为宣说；又悲愍末世众生少有爱乐修习此法者，于佛不现前时深生悲愍。",

"【无量光佛·末世毁法】婆罗门！我当作是念时，有佛名无量光，发如是言：『以愿力故果报成就。』婆罗门！以是义故，我所悲愍一切众生，积集痴暗受轮回怖。后末世中有诸苾刍，于此正法起厌离心，毁坏禁戒作不律仪，以是缘故，不能宣通如是正法。【义解】「无量光」即阿弥陀（无量光佛）。彼佛言：以愿力故果报成就。佛悲愍众生积集痴暗受轮回怖；末世有比丘于此正法起厌离心、毁坏禁戒，故不能宣通正法。",

"【此经总摄四阿含】是故婆罗门！我为利益诸众生故广说此经。「你应当知，今此正法是广大法门，总摄四种阿含。何等为四？所谓：杂阿含、长阿含、中阿含、增一阿含。如是等总摄一切声闻藏法，诸声闻人若于是中修学者即为声闻藏，而能出生声闻乘果，亦摄声闻菩提分法。【义解】此经总摄四种阿含：杂阿含、长阿含、中阿含、增一阿含，总摄一切声闻藏法，出生声闻乘果及声闻菩提分法。",

"【此经为诸法之母·出一切法】又此经中摄彼一切最上所说菩萨藏法，是故得名诸法之母，所有毘奈耶藏、阿毘达磨藏也于此经摄，乃至八万四千法蕴，一一皆从此经中出。又此经法是即一切智智最上根本，而复出生声闻、缘觉之智，广大甚深不可思议，是大光明普照三有，此即从一切智根本出生诸佛菩提，所有布施功德、持戒、忍辱、精进、禅定、智慧及彼最胜解脱。【义解】此经摄菩萨藏法，故名诸法之母；毘奈耶藏（律）、阿毘达磨藏（论）乃至八万四千法蕴皆从此经出。此经为一切智智之最上根本，出生声闻缘觉之智，普照三有，出生诸佛菩提及六度解脱。",

"【此经说四圣谛·三法印】如是等众功德藏、悉于此经如理宣说。又复苦、集、灭、道四圣谛法，而亦于此经中演说。以要言之，此经总说：诸行无常、诸法无我、涅槃寂静。以是义故，若声闻乘、若缘觉乘、若大乘法，随其所应是中广说。【义解】此经宣说四圣谛（苦集灭道）及三法印（诸行无常、诸法无我、涅槃寂静），随三乘所应而广说。",

"【此经赞菩提心·三世不断】又此经者于诸法中，广大称赞彼菩提心，是故此经最上最胜。婆罗门！若有人现见诸佛亲闻是法者，当知是人已从先佛闻《宝严经》，于彼经中已闻此法，是故当知今此经法，于三世中曾无断绝，彼彼众生随应得闻。【义解】此经于诸法中广大称赞菩提心，故最上最胜。现见诸佛亲闻此法者，已于先佛所闻《宝严经》中闻此法；此经于三世中不断绝，众生随应得闻。",

"【希有·问无智众生何缘成就】」那时，婆罗门白佛言：「希有世尊！佛所说法最上甚深，若诸无智众生，得闻如是无量功德藏最上正法，不能深生爱乐心者，是人于阿耨多罗三藐三菩提当以何缘而能成就？又复世尊！何因缘故多有众生于此大乘最上法中心生疑惑？【义解】婆罗门叹希有，问：无智众生闻此最上正法不能深生爱乐，以何缘能成就无上菩提？又何以多有众生于此大乘心生疑惑？",

"【天魔障法】」佛言：「婆罗门！你今当知，此三千大千世界中，有百俱胝天魔宫殿、百俱胝魔王，一一各有百俱胝天魔眷属，常时于此最上法门，伺求其便起诸难事，不令众生书持读诵。何以故？此三千大千世界中，多有众生取证阿罗汉果。【义解】此三千大千世界有百亿天魔宫殿、魔王及眷属，常于最上法门伺求方便、起诸难事，不令众生书持读诵。何以故？下段以比较说明。",

"【发心胜阿罗汉·天魔障法】今得闻此大乘法门，有善男子善女人发阿耨多罗三藐三菩提心者，彼前功德称量较计，而不及此发菩提心。是故天魔伺求难事，魔为难故，多有众生以此因缘心生疑惑。婆罗门！又复此经为诸法中王，以是缘故多诸难事。【义解】证阿罗汉果之功德，比之闻此大乘法门而发菩提心者，亦不能及。故天魔伺求难事；以此经为诸法中王，故多诸难事。",

"【问降魔方便·破魔法门】」那时，婆罗门白佛言：「世尊！以何方便能令诸魔而自调伏？」佛言：「婆罗门！我有秘密总持法门名曰破魔。我若说此法门时，所有一切魔及魔众皆悉破坏。婆罗门！譬如日轮光明出照世间，一切暗冥皆悉隐没。【义解】婆罗门问降魔方便。佛言有「破魔」秘密总持法门，说时一切魔众皆破坏，如日出而暗冥隐没。",

