"【渡河喻·第三人·大船】第三人，造作大船乘之入河，在此船中载百千人。那第三人，又敕令长子安置守护这样的船舫：「所有众生来者，你从此岸渡到彼岸，为多人等作利益的缘故。」婆罗门！你意下如何？那彼岸有差别吗？」婆罗门说：【义解】第三人造大船载百千人，并嘱长子以此船渡众生，喻菩萨自度兼度众生。佛问彼岸是否有别。",

"【彼岸无别·乘有别】「没有。世尊！」佛又问：「婆罗门！你意下如何？那所乘之乘有差别吗？」婆罗门说：「所乘之乘确实有差别。」佛言：「如是如是。婆罗门！然而声闻乘、辟支佛乘、阿耨多罗三藐三菩提乘确实有差别。婆罗门！【义解】彼岸（解脱）无别，而所乘之乘（能行之法）有别。故三乘差别只在「乘」，不在所至之「岸」。",

"【三乘配三人】如第一人，依倚草筏从此岸到彼岸，独自一人、无二，声闻菩提应如是知；第二人，或倚皮囊及皮船，从此岸渡到彼岸，辟支佛菩提应如是知；婆罗门！如第三人，成就大船、共多人之众，从此岸到彼岸，如来菩提应如是知。【义解】三乘配三人：草筏喻声闻（独度）、皮囊皮船喻辟支佛、大船共众喻如来菩提（度众）。",

"【偈颂·取最胜乘】」那时，世尊欲重宣此义，而说偈言：「路及解脱无有上，诸乘皆悉有差别；智者如是应挍量，当取最胜最上乘。诸法教如是，正觉说此言；简择诸法已，胜者应当学。」那时，迦叶婆罗门又白佛言：「世尊！【义解】路（道）与解脱无有高下，而诸乘自有差别；智者当挍量简择，取最胜最上之乘（佛乘）。「挍量」即较量。",

"【问菩萨行·四摄】菩萨摩诃萨应当怎样行、怎样念住，才能到摩诃衍（大乘）？」那时，佛告诉迦叶婆罗门这样说：「婆罗门！你听此义：若诸菩萨摩诃萨如所念而修行，便至摩诃衍。婆罗门！若善男子善女人自发菩提心，也教他人发菩提心；自己乐修行，劝他人令修也令他安住，又为解释如是修多罗之义；【义解】「摩诃衍」即大乘。菩萨行大乘者：自发心亦教他发、自修亦劝他修、又为人解释此经之义。",

"【四摄法】像这样的富伽罗人，不来亲近承受接事，当以四摄而摄取之。何等为四？所谓布施、爱语、利益、同事。」那时，世尊欲重宣此义，而说偈言：「种种大布施，一切所有物，欲摄受他的缘故，菩萨无畏者。示现引接之道，众生不依而来，能以妙善之语，数数当安慰。【义解】「四摄」即布施、爱语、利益（利行）、同事，为菩萨摄受众生之法。偈颂：菩萨以布施、妙语、示道、安慰而引接众生。",

"【偈颂·四摄内容】为自他安乐，彼所生善处，昼夜常随顺，如是众生等。不信教令信，破戒令住戒，悭吝令布施，一切巧利益。教人行菩提，牢固常精进，同于利益事，智者如教行。如此智慧者，菩萨之导师；智慧所行者，常乐大乘法。【义解】四摄之实：令不信者信、破戒者住戒、悭吝者布施，巧施利益，教人行菩提、常精进、同事利益。如此智慧者即菩萨导师，常乐大乘法。",

"【偈颂·勇猛到彼岸·请法】勇猛是最胜，智者应当学，以那殊胜之法故，最胜到彼岸。」那时，迦叶婆罗门又以偈颂而白佛言：「大德示彼行，菩萨诸导师，当学彼所行，得至两足尊。为我说彼行，及行行所依，菩提深广大，慈愍愿为说。【义解】颂结：勇猛最胜，智者当学，以胜法到彼岸。迦叶请佛为说菩萨之行及行之所依。",

"【三行·天行】」那时，世尊告诉迦叶婆罗门说：「善哉婆罗门！诸菩萨有三种行。何等为三？所谓天行、梵行、圣行。婆罗门！其中什么名为天行？若有善男子善女人，以慈身业、以慈意业、以慈口业，遍满东方无量世界，慈行充满；【义解】菩萨三行：天行、梵行、圣行。天行者：以身、口、意三慈业遍满东方无量世界。",

"【天行·梵行】行此遍满已，又能善入南、西、北方，四维上下，都以慈身业、慈意业、慈口业普遍充满，这名为天行。其中什么名为梵行？所谓四无量——何等为四？慈、悲、喜、捨——这名为梵行。婆罗门！其中什么名为圣行？【义解】天行即以三慈业遍满十方。梵行即四无量心：慈、悲、喜、捨。",

"【圣行·三解脱门】所谓三解脱门——何等为三？空、无相、无愿——这名为圣行。」那时，世尊欲重宣此义，而说偈言：「勇猛行精进，菩萨之导师，若有具天行，是人乐菩提。圣行及梵行，是行圣所说，若有修行者，是人得不动。【义解】圣行即三解脱门：空、无相、无愿。偈颂：具天行、梵行、圣行者，乐菩提、得不动（不退）。",

"【迦叶请法·问未来集行】」那时，迦叶婆罗门又以偈而白佛言：「我乐深菩提，今问大导师，此等当来世，如何集诸行？为后众生等的缘故，故我问世尊，于佛菩提中，我意无分别，令我发道心，利益众生故。」那时，世尊又以偈颂报那迦叶婆罗门说：【义解】迦叶言：为未来众生故问——当来世众生如何集诸行？愿佛令我发道心、利益众生。佛以偈答。",

"【偈答·闻经发心之利】「说此修多罗，令发大菩提，梵志！佛菩提，未曾有分别。说此修多罗，令发大菩提，能断一切疑，随顺众生问。说此修多罗，令发大菩提，能断一切疑，称彼众生欲。得闻此经者，彼于未来世，能行大布施，至于檀彼岸。【义解】说此经能令发大菩提、断一切疑、随顺众生所问。闻此经者，未来世能行大布施，至布施（檀）彼岸。下段续颂六度。",

"【偈颂·六度彼岸】得闻此经者，彼于未来世，护持戒无缺，至于戒彼岸。得闻此经者，彼于未来世，行忍为众生，至于忍彼岸。得闻此经者，彼于未来世，精进为众生，至于精进岸。得闻此经者，彼于未来世，常入诸禅定，至于禅彼岸。【义解】闻经者未来世依次行持戒、忍辱、精进、禅定，各至彼岸。下段续说智慧彼岸。",

"【偈颂·智彼岸·供养得经】得闻此经者，彼于未来世，为众求胜智，至于智彼岸。已曾作供养，怜愍众生者，得闻此经典，后世到其手。比丘住兰若，意欲佛菩提，得闻此经者，于后最先得。过去数亿佛，已持此经典，为利诸菩萨，发起意欲故。【义解】闻经者未来为众求胜智、至智慧彼岸。曾供养、怜愍众生者，后世此经到其手；住兰若（寂静处）之比丘得此经最先。过去数亿佛已持此经，为利益菩萨而发起。",

"【偈颂·婆罗门得经·佛见无碍】若有婆罗门，欲乐佛菩提，那时得信已，是经至其手。我见彼众生，悉知彼所行；也知彼名字，我见悉无碍。一切颇能具说，恐迷惑未来人；惧怕彼起诸过，所以少分而说。」【义解】欲乐佛菩提之婆罗门，得信后此经到其手。佛以无碍之见，悉知彼众生所行及名字；因恐未来人迷惑、生过，故只少分而说。",

"【偈颂·授记·女人写经】那时，迦叶婆罗门又以偈而白佛言：「大德此善持，令生广大意，此世大丈夫，不久我当作。过去及未来，导师之所说，为彼生善利，故住于菩提。」那时，世尊又以偈报婆罗门言：「彼等住此智，为谁之所言说？已知彼心行，我今当记彼。所闻此经者，今现在我前，彼等于后世，此经当现前。若有诸女人，抄写此经典，此经当在手，能生大菩提。【义解】迦叶发愿不久当作大丈夫、住于菩提。佛为在会闻经者授记，并言：后世有女人抄写此经，经当在手、能生大菩提。下段续说。",

"【偈颂·比丘悲泣·宿业因缘】我于先已说，比丘乐兰若，手得此经典，于后当现前。比丘闻此经，悲泣而雨泪：『我先作何业，今世得此利？我于如是经，未曾善思惟，我已得受记，何业获此果？我昔婆罗门，依于比丘活，时比丘放逸，说此修多罗。【义解】佛言：乐兰若之比丘手得此经；比丘闻经悲泣，自问宿世何业得此利、何业获授记之果。下段续说其宿缘。",

"【偈颂·宿缘·泣泪发愿】梵志于彼闻，时至而乞食，泣泪已行出，是时心作愿。我于修多罗、钞义及文字，后世作证明，也复作拥护。』以彼善业的果报，于后后末世，得此修多罗，执持在其手。彼时有比丘，悲泣泪满目，当时作忏悔，后得此经法。【义解】宿缘：昔为梵志时，闻比丘说此经，泣泪出行、发愿——我于经义文字，后世作证明、作拥护；以此善业果，末世得此经执持在手。彼时比丘悲泣忏悔，后得此法。",

"【偈颂·业尽梦现·破戒之过】于先业灭尽，那时有相现，在其睡梦中，得此修多罗。生死诸流转，欺诳大恐怖，这都是由阿弥陀，愿力如是果。破戒诸比丘，为他人所轻贱，如是多诸过，流转大恐怖。如是多诸恶，由得闻此经，当至那边际，于后常显曜。【义解】宿业灭尽，则于梦中得此经。生死流转、欺诳恐怖，皆由阿弥陀（无量光佛）愿力如是之果；破戒比丘为他人轻贱、多过流转，由闻此经当至其边际、后常显曜（终得解脱）。",

"【偈颂·广为宣说·此经为阿含】」那时，迦叶婆罗门又以偈而白佛言：「此大修多罗，令发大道心，为我及未来，分别广宣说。」那时，世尊又以偈告迦叶种姓婆罗门言：「未来诸音声，乃至我所说，这是广经典，所以你当知。说此大经典，此当作《阿含》，当作秘密藏，声闻所修学。【义解】迦叶请佛为此经广为宣说。佛言：此大经当流布为《阿含》，为秘密藏，为声闻所修学。",

"【偈颂·诸经之母·阿含分教】此处之所说，及余得道者，这是诸经之母，梵志如此知。那时诸比丘！于我灭度后，《杂》及《长阿含》，又名为《中阿含》，那时有《阿含》，具数名《增一》；又说杂经典，箧藏声闻说，又当作毘尼（律），也作阿毘昙（论）；【义解】此经为诸经之母。佛灭度后，流出《杂阿含》《长阿含》《中阿含》《增一阿含》（四阿含），及杂经典、声闻所传箧藏、毘尼（律）、阿毘昙（论）。",

"【偈颂·三藏教法·功德根本】或于三箧藏，得名诸比丘！八万有四千，法聚我已说，一切从此出，名为最胜经。于此说声闻，及说独一觉，诸智之根本，不思议经典。世间之所有，三界未现者，诸福之根本，由发菩提心。施、戒等功德，忍辱、精进行，禅定胜功德，此经中善说；【义解】三藏（箧藏）之法、八万四千法聚皆从此经出，故名最胜经。此经说声闻、独一觉（缘觉）、诸智根本。三界未现之一切福之根本，皆由发菩提心；布施、持戒、忍辱、精进、禅定诸功德，此经中善说。",

"【偈颂·示现诸法·苦集灭道】智慧胜功德，解脱忍寂灭，一切都示现，此经中善说；苦、集及以道、寂灭于此现，诸法皆佛法，此经之所说；说诸苦无常，也说无我法，说寂静涅槃，在此修多罗。此处说声闻，所住诸因缘，大乘此经典，摄受一切法。【义解】智慧、解脱、忍、寂灭诸德皆于此经示现；苦、集、道、灭于此显现，诸法皆佛法。此经说苦无常、无我、寂静涅槃，说声闻所住因缘，此大乘经摄受一切法。",

"【偈颂·菩提心为最胜典·见佛闻法】诸法甚广大，在于菩提心，这是最胜之典，普说修多罗。现前见诸佛，及为彼说法，当时现前闻，都由此经典。三界诸众生，少有闻此经，闻已生爱乐，为求佛乘故。」那时，迦叶婆罗门又白佛言：「希有世尊！【义解】诸法广大，皆在菩提心，此经为最胜典。依此经能现前见佛、闻佛说法。三界众生少有闻此经者，闻已生爱乐，皆为求佛乘。",

"【希有·问虚过因缘】若诸众生没有智慧，若闻如是之无上无边——乃至像这样的众生当没有智慧——若如是等无边无上修多罗闻已，不能于此法中不生坚固乐欲。大德世尊！有何因缘，既有如是妙法，然而那些众生却当虚过（空过）呢？」那时，佛告诉那婆罗门说：【义解】迦叶叹希有，并问：既有如是妙法，何以有些众生闻之却不能生坚固乐欲而虚过？",

"【魔障此经·魔众眷属】「此三千大千世界，有百俱致（凡言俱致者，隋数千万）诸魔宫殿，那每一魔都有俱致数魔众眷属围绕，那些魔辈，常勤方便欲灭此经，作种种因缘，因那些因缘随所在处作诸障碍。为什么呢？若以三千大千世界所有众生，都得证阿罗汉果；【义解】「俱致」，隋译为数千万。此三千大千世界有百俱致魔宫殿，魔及眷属常欲灭此经、作诸障碍。何以故？下段以比较说明。",

"【魔勤灭经之因】若有善男子善女人闻此修多罗已，当发阿耨多罗三藐三菩提心。婆罗门！以是因缘，令俱致数诸魔勤求方便欲灭此经，为什么呢？婆罗门！此修多罗是一切诸法种性根本，以是义故，俱致诸魔勤求方便欲灭此经。【义解】纵令三千大千世界众生皆证阿罗汉果，也不及有人闻此经发菩提心。因此诸魔勤求方便欲灭此经——以此经是一切诸法种性根本故。",

"【破魔众会经·如日灭暗】」那时，佛告诉婆罗门：「今有一部修多罗，名叫『破魔众会』。你们受持读诵，即能破那魔天众会。婆罗门！譬如日轮出现之时，能灭一切幽冥黑暗。如是如是，婆罗门！说破魔众会修多罗时，一切诸魔隐没不现。【义解】佛别出「破魔众会」修多罗，令受持读诵以破魔众会。如日出灭暗，说此经时诸魔隐没。",

"【破魔众会陀罗尼（一）】婆罗门！什么名为破魔众会修多罗？」那时，世尊即说陀罗尼曰：「⟪多（上）緻他（一）　阿㝹謩大那（上）（二）　菩提三摩陀波那多（三）　伏哆（四）　紆伏哆（五）　怛怛羅伏哆（六）　尼興（蜎蠅反）伽魔（七）⟫【义解】此为「破魔众会」陀罗尼之首。依密咒体例，咒文但存音声、不作意译，故照录原音；「（上）」「（蜎蠅反）」等为原经所标读音注记，照录。",

"【破魔众会陀罗尼（二）】⟪波羅破（八）　多羅破（九）　哆噓（十）　哆隆（洛中反）伽磨伽魔那（十一）　毘唎磨（十二）　磨素磨（十三）系（上聲）履婆伽磨（十四）　毘達囉魔（十五）　大囉麴磨（十六）　阿邏彌邏（十七）　伊迦叉邏那喻（十八）⟫【义解】承上，续录「破魔众会」陀罗尼第八至第十八句。「（洛中反）」「（上聲）」为原经所标读音注记，照录。",

"【说陀罗尼·魔宫震动】「婆罗门！此陀罗尼是。过去、未来、现在诸佛世尊同说此破魔众会修多罗。婆罗门！说此破魔众会修多罗时，一切魔宫都震、动、大动、摇、大摇，一切诸魔各各从那本座颠倒堕落，不能言语。为什么呢？【义解】此陀罗尼为三世诸佛同说。说此经时，一切魔宫震动，诸魔从座颠倒堕落、不能言语。",

