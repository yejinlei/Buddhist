"【曼荼罗严饰·四线】半全璎珞并宝拂，七宝华鬘等严饰。坛中安布妙莲花，心曼拏罗为最上；楼阁即是真实智，智峰高显而起立。观彼坛相外四方，一切有情周遍出；慈悲喜舍四种心，此即表示四种线。所说四线若平等，于法正念即相应；【义解】半璎珞、全璎珞及宝拂，七宝华鬘等以为严饰。坛中安布妙莲花，心曼拏罗为最上；楼阁即是真实之智，智峰高显而起立。观彼坛相之外四方，一切有情周遍而出；慈悲喜舍四种心，此即表示四种线。所说四线若得平等，于法正念即得相应——下续。",

"【坛相表法（一）】若一切见不解脱，由智线故而得脱。坛中莲花所庄严，即表最上净戒行；四方中心五墙界，即表信等五胜根；曼拏罗门周遍说，即表八解脱法门；四门所有四楼阁，是即表于四正断；其坛所有四尾提，是即表于四念处；【义解】若一切见不解脱，由智线故而得解脱。坛中莲花所庄严，即表最上净戒之行；四方中心五墙界，即表信等五胜根；曼拏罗门周遍而说，即表八解脱法门；四门所有四楼阁，即表四正断；其坛所有四「尾提」，即表四念处——下续。",

"【坛相表法（二）】而彼四种祢逾贺，是即表于四神足；七宝华鬘妙庄严，是即表于七觉支；四门八柱所应知，是即表于八圣道。由彼三摩地智故，能令二障得解脱；坛中所有妙宝拂，是即表于胜道智。坛中全分璎珞者，即表全断诸烦恼；【义解】而彼四种「祢逾贺」，即表四神足；七宝华鬘妙庄严，即表七觉支；四门八柱所应知，即表八圣道。由彼三摩地智故，能令二障得解脱；坛中所有妙宝拂，即表胜道之智。坛中全分璎珞者，即表全断诸烦恼——下续。",

"【璎珞表法·智庄严】璎珞体即是胜智，故诸烦恼能除断。所有半分璎珞者，即表半断诸烦恼；自他二行相应故，盖缠烦恼半分断。无我平等如虚空，无贪妙智复最上；贪心净故亦无二，此即名为智庄严。若以无贪得菩提，菩提即与贪心异；【义解】璎珞之体即是胜智，故诸烦恼能得除断。所有半分璎珞者，即表半断诸烦恼；自他二行相应故，盖缠烦恼半分而断。无我平等犹如虚空，无贪妙智复为最上；贪心净故亦无二，此即名为智庄严。若以无贪得菩提，则菩提即与贪心相异——下续。",

"【贪无贪不二·印成就】菩提心体既无差，是故贪无贪不二。世间贪无贪二种，应以方便善观想；印成就法从贪生，及余一切皆成就。若住世间调伏心，乃起相应平等行；不调伏心既清净，此即贪亦是供养。所有广说诸行相，是即分别境界相；【义解】菩提心体既无差别，是故贪与无贪不二。世间贪、无贪二种，应以方便善加观想；印成就之法从贪而生，及余一切皆得成就。若住世间调伏之心，乃起相应平等之行；不调伏心既已清净，此即贪亦是供养。所有广说诸行之相，即是分别境界之相——下续。",

"【身语心印门·幖帜表法】若住身语心印门，所印即是真实智。观想此印若相应，于诸印中常自在；而此印法若了知，观想诸印皆成就。于诸境界相和合，知已相应平等行；如其诸相若相应，一切悉地皆圆满。一切秘密中幖帜，右即表示于慧门；【义解】若住身语心印门，所印即是真实之智。观想此印若得相应，于诸印中常得自在；而此印法若得了知，观想诸印皆得成就。于诸境界之相和合，知已则相应平等行；如其诸相若得相应，一切悉地皆得圆满。一切秘密中之幖帜，右即表示于慧门——下续。",

"【幖帜表法·五指】左为悲门义亦然，如其所表常观想。二手相合结印时，即表二种三摩地；二足所有幖帜相，即表自他二利行。五指平等若相应，表庄严五曼拏罗；五佛现成正等觉，其所表示如次第。中指即表虚空生；头指表示地天坛；【义解】左为悲门，其义亦然，如其所表常加观想。二手相合结印之时，即表二种三摩地；二足所有幖帜之相，即表自他二利之行。五指平等若得相应，表庄严五曼拏罗；五佛现成正等觉，其所表示如其次第。中指即表虚空生；头指表示地天坛——下续。",

"【指表五部·观想】无名指及大小指；水大风天坛如次。于脐轮处观想时，表示金刚界佛母！若复于心作观想，即表萨埵金刚尊！眉间表示宝金刚！颈上表示法金刚！顶表羯摩金刚尊！如其所表善观想。五佛现成正等觉，五智圆满皆成就；【义解】无名指及大小指，依次表水大、风天之坛。于脐轮处观想时，表示金刚界佛母；若复于心作观想，即表萨埵金刚尊；眉间表示宝金刚，颈上表示法金刚，顶表羯磨金刚尊——如其所表善加观想。五佛现成正等觉，五智圆满皆得成就——下续。",

"【五色五曼荼罗·声句前后】五种色相若相应，五曼拏罗而出现。若于前声有所闻，是即表于前名句；如其后声有所闻，此即表示于后义。又于前声有所闻，此即表示于因义；如其后声有所闻，此即表示于果义。诸佛世尊无二法，是中因果不可得；【义解】五种色相若得相应，五曼拏罗而出现。若于前声有所闻，即表于前之名句；如其后声有所闻，即表示于后之义。又于前声有所闻，即表示于因之义；如其后声有所闻，即表示于果之义。诸佛世尊无二之法，此中因果不可得——下续。",

"【诸法常住·自心即佛】根本无性法门中，是故诸法皆常住。自心觉了即是佛，能觉所觉心亦忘；诸佛如来境界中，而菩提心无有异。一切众生光明性，于一切处相平等；而众生性本清净，菩提由斯而建立。于心无动善关锁，而坚固性自成就；【义解】根本无性法门之中，是故诸法皆常住。自心觉了即是佛，能觉、所觉之心亦忘；诸佛如来境界之中，而菩提心无有异。一切众生光明之性，于一切处其相平等；而众生性本自清净，菩提由此而建立。于心无动善加关锁，而坚固性自然成就——下续。",

"【髻中住心·被甲·金刚语·那哩】髻中想住等引心，被甲护身常勇健。所有诸佛正了知，金刚语即是如来！二处三摩钵底门，毘卢遮那佛无异。法中十二岁那哩，所说即是佛如来！十六岁者即表示，金刚手等十六尊！二十岁者诸祢尾，即是秘密二十天！【义解】髻中观想住于等引之心，被甲护身常得勇健。所有诸佛正了知，金刚语即是如来。二处三摩钵底（等至）门，与毘卢遮那佛无异。法中十二岁之「那哩」，所说即是佛如来；十六岁者即表示金刚手等十六尊；二十岁者诸「祢尾」，即是秘密二十天。",

"【二十种供养·自他大明·心曼荼罗】作二十种供养事，彼二十众应如次。自那啰者本部生，即是所说自大明；他那啰者别部生，即是所说他大明。真实了知诸所作，心曼拏罗为最上；作诸供养要专精，当以身语心供养。自金刚杵莲花合，二处平等而出生；【义解】作二十种供养之事，彼二十众应如其次第。「自那啰」者本部所生，即是所说之「自大明」；「他那啰」者别部所生，即是所说之「他大明」。真实了知诸所作，心曼拏罗为最上；作诸供养要专精，当以身语心供养。自金刚杵与莲花合，二处平等而出生——下续。",

"【观自种相·曼荼罗分量】观自种相即佛相，金刚萨埵真供养。半全璎珞宝拂等，诸庄严相如前说；此中曼拏罗分量，应十二或十六肘。次复渐增二十肘，曼拏罗相当周遍；合用二十五肘时，即作二十五肘量。于曼拏罗门中分，九分分布如仪轨；【义解】观自种之相即佛之相，是金刚萨埵真供养。半璎珞、全璎珞、宝拂等，诸庄严相如前所说；此中曼拏罗之分量，应为十二或十六肘。次复渐增二十肘，曼拏罗相当周遍；合用二十五肘时，即作二十五肘之量。于曼拏罗门中分九分，分布如仪轨——下续。",

"【九分分布·四尾提·五色】随应分布祢逾贺，曼拏罗门善思察。内曼拏罗平等作，曼拏罗半祢逾贺；如是不离九分中，曼拏罗隅善安布。坛中四方所应用，四尾提相当安布；五色和合若相应，五曼拏罗为严饰。五眼观视净诸恶，五色即是五如来！【义解】随应分布「祢逾贺」，曼拏罗门善加思察。内曼拏罗平等而作，曼拏罗半「祢逾贺」；如是不离九分之中，曼拏罗隅善加安布。坛中四方所应用，四「尾提」相当加安布；五色和合若得相应，五曼拏罗以为严饰。五眼观视净诸恶，五色即是五如来。",

"【五色庄严·五方地色】五佛平等法相应，地分五色庄严相。当于五曼拏罗中，想安五佛依方位；五种功德悉周圆，五色即五三摩地。其坛中心地清净，月爱摩尼光妙色；东方地相大青色；南方黄色如仪轨；西方赤色随所应；北方曼𡁠瑟吒色。【义解】五佛平等与法相应，地分五色庄严之相。当于五曼拏罗中，观想安五佛依方位；五种功德悉皆周圆，五色即五三摩地。其坛中心地清净，为月爱摩尼光之妙色；东方地相大青色，南方黄色如仪轨，西方赤色随所应，北方「曼𡁠瑟吒」色。",

"【五方佛观想（一）】诸处皆用尾提相，唯门中道勿应用。坛中毘卢遮那佛！想现水精月光相；彼一切佛同一摄，此即无畏眼如来！东方观想阿閦佛！出现帝青光明相；一切金刚同一摄，此即金刚眼如来！南方观想宝生佛！出现阎浮金光相；【义解】诸处皆用「尾提」之相，唯门中之道勿用。坛中毘卢遮那佛，观想现水精月光之相；彼一切佛同一所摄，此即无畏眼如来。东方观想阿閦佛，出现帝青光明之相；一切金刚同一所摄，此即金刚眼如来。南方观想宝生佛，出现阎浮金光之相——下续。",

