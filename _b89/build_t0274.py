"【净命学方等十四亿卷·法比丘但宣一品空法】净命比丘学方等经十四亿卷，及修其余经六百万卷。「那时法比丘在仁贤城，惟只宣散一品法教，不知随时观其本行而讲说经法；不能觉了通达诸法界，专以空法而开化之，言一切法空、悉无所有，所可宣讲但论空法。【义解】净命广学方等及余经，法比丘则但宣一品、偏执空法，不观根机。「法界」指诸法实相。",
