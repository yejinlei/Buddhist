def build(tid, meta, intro, translator):
    src = json.load(open(os.path.join(TASKS, tid + ".json"), encoding="utf-8"))
    secs = src["translations"]
    assert len(secs) == len(meta), (tid, len(secs), len(meta))
    for s, (title, body, yj) in zip(secs, meta):
        p = s["original_preview"]
        b = body(p) if callable(body) else body
        s["modern"] = "【%s】%s【义解】%s" % (title, b, yj)
        s["section"] = title
    out = {
        "id": tid,
        "title": src["title"],
        "translator": translator,
        "mode": "baihua",
        "intro": intro,
        "sutraPath": "../sutras/%s.json" % tid,
        "translations": secs,
    }
    dst = os.path.join(OUT, tid + ".json")
    json.dump(out, open(dst, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("wrote", dst, "sections", len(secs))


