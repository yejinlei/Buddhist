def build_modern(orig):
    orig = orig.strip("\n")
    if not orig.strip():
        return ""
    sub = make_subtitle(orig)
    yj = make_yijie(orig)
    body = modernize(orig)
    return f"【{sub}】\n【義解】{yj}\n{body}"

def process(src, dst):
    with open(src,'r',encoding='utf-8') as f:
        d = json.load(f)
    for seg in d['translations']:
        seg['modern'] = build_modern(seg['original_preview'])
    with open(dst,'w',encoding='utf-8') as f:
        json.dump(d,f,ensure_ascii=False,indent=2)
    n = len(d['translations'])
    total = sum(len(s['modern']) for s in d['translations'])
    print(f"{os.path.basename(src)} -> {os.path.basename(dst)}: {n} segs, {total} chars")

