def protect_terms(s):
    ph = {}
    for i,t in enumerate(KEEP_LIST):
        if t in s:
            k = f"\x00T{i}\x00"
            s = s.replace(t,k)
            ph[k]=t
    return s, ph

def restore_terms(s,ph):
    for k,v in ph.items():
        s = s.replace(k,v)
    return s

