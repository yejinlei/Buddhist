def modernize(text):
    s = text
    for a,b in PHRASE_REPL:
        s = s.replace(a,b)
    s, ph = protect_terms(s)
    for a,b in WORD_REPL:
        s = s.replace(a,b)
    s = restore_terms(s,ph)
    # artifact cleanup
    s = s.replace("的的","的").replace("了了","了")
    s = s.replace("：：", "：").replace("，，", "，")
    return s

