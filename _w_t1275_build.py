def load(p):
    with open(p, encoding="utf-8") as f:
        return json.load(f)

def build(skel_path, out_path, intro, moderns):
    skel = load(skel_path)
    assert len(skel["translations"]) == len(moderns), (len(skel["translations"]), len(moderns))
    trs = []
    for i, t in enumerate(skel["translations"]):
        trs.append({
            "section": t.get("section", ""),
            "original_preview": t["original_preview"],
            "modern": moderns[i],
        })
    out = {
        "id": skel["id"],
        "title": skel["title"],
        "translator": skel["translator"],
        "mode": "baihua",
        "intro": intro,
        "sutraPath": "sutras/%s.json" % skel["id"],
        "translations": trs,
    }
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    print("wrote", out_path, "segments:", len(trs))

