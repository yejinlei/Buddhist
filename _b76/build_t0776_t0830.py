def build(sid):
    skel_path = os.path.join(ROOT, "data", "baihua-tasks", sid + ".json")
    out_path = os.path.join(ROOT, "data", "modern-translation", sid + ".json")
    d = json.load(open(skel_path, encoding="utf-8"))
    tr = d["translations"]
    mods = DATA[sid]["modern"]
    assert len(tr) == len(mods), f"{sid}: 段数不符 skel={len(tr)} modern={len(mods)}"
    # fill intro
    if not d.get("intro"):
        d["intro"] = DATA[sid]["intro"]
    # fill modern; preview untouched
    for i, t in enumerate(tr):
        assert t["modern"] == "", f"{sid}[{i}] modern 非空"
        m = mods[i]
        assert m.startswith("【"), f"{sid}[{i}] 未以【开头"
        assert "【义解】" in m, f"{sid}[{i}] 缺【义解】"
        assert not m.endswith("【义解】"), f"{sid}[{i}] 以【义解】结尾"
        t["modern"] = m
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"{sid} 写入完成 段={len(tr)}")

for sid in ["t0776", "t0830"]:
    build(sid)
