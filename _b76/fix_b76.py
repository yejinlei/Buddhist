def concat_modern(d): return ''.join(s['modern'] for s in d['translations'])

def main():
    cache = {}
    ok = 0; err = []
    for tid, old, new, exp in FIX:
        if tid not in cache: cache[tid] = load(tid)
        d = cache[tid]
        # 断言在 modern 里出现次数（不涉及 preview）
        cnt_all = sum(s['modern'].count(old) for s in d['translations'])
        if exp == 'ALL':
            if cnt_all == 0: err.append((tid, old, 'not found')); continue
            got = 0; n = cnt_all
            for s in d['translations']:
                if old in s['modern']:
                    s['modern'] = s['modern'].replace(old, new); got += 1
            print('  [ALL] %s  %r->%r  替换段数=%d, 命中=%d' % (tid, old, new, got, n)); ok += 1
        else:
            if cnt_all != exp:
                err.append((tid, old, 'count=%d expect=%d' % (cnt_all, exp))); continue
            done = 0
            for s in d['translations']:
                if old in s['modern']:
                    s['modern'] = s['modern'].replace(old, new, 1); done += 1
            if done != exp: err.append((tid, old, 'replaced=%d expect=%d' % (done, exp))); continue
            print('  [OK] %s  %r -> %r' % (tid, old[:24], new[:24])); ok += 1
    for tid, d in cache.items():
        save(tid, d)
    print('\n成功 %d 条，失败 %d 条' % (ok, len(err)))
    for e in err: print('  ✗', e)

if __name__ == '__main__':
    main()
