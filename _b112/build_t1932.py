 "豈覺不覺，不覺猶是不覺嗎？反謂所覺離於能覺嗎？客曰：若爾，至佛方會，凡離何乖？我說：子為學佛、為學凡呢？理本無殊，凡謂之離，故示眾生令覺不覺，故覺不覺自會一如。故知，覺無不覺不名佛性，不覺無覺法性不成。",
 "覺無不覺，佛性寧立？是則無佛性之法性，容在小宗；即法性之佛性，方曰大教。故今問子：諸經論中，法界、實際、實相、真性等，為同法性在無情中？為同真如分為兩派？若同真如，諸教不見無情法界及實際等；",
 "若在無情但名法性非佛性者，何故《華嚴．須彌山頂偈讚品》說「了知一切法，自性無所有。若能如是解，則見盧舍那。」豈非諸法本有舍那之性嗎？又說「法性本空寂，無取亦無見，性空即是佛，不可得思量。",
 "」又精進慧說：「法性本清淨，如空無有相。此亦無所修，能見大牟尼。」豈於無性又說無修能見牟尼？又真實慧說：「一切法無相，是則真佛體。」既真佛體在一切法，請子思之，當免迷教及迷佛性之進否。",
 "故真如隨緣即佛性隨緣，佛之一字即法佛，故法佛與真如體一名異。故《佛性論》第一說「佛性者，即人法二空所顯真如，當知真如即佛性異名。」《華嚴》又說「眾生非眾生，二俱無真實，如是諸法性，實義俱非有。",
 "」說眾生非眾生，豈非情與無情？二俱隨緣並皆不變，故俱非有。所以法界實際一切皆然，故知法性之名不專無情中之真如，以由世人共迷法相名異體一之故。然雖體同，不無小別。凡有性名者，多在凡在理，如說佛性、理性、真性、藏性、實性等。",
 "無性名者，多通凡聖因果事理，如說法界及實相等，如三昧、陀羅尼、波羅蜜等則唯在於果。所以因名佛性等者，眾生實未成佛得理證真開藏，以煩惱生死是佛等性，示令修習，名佛等性。而諸教之中諸名互立，《涅槃經》中多說佛性者，佛是果人。",
 "說一切眾生皆有果人之性，故偏言之。世人迷之故而不從果，說眾生有，故失體遍。又說遍者，以由煩惱心性體遍，說佛性遍。故知不識佛性遍者，實由不知煩惱性遍之故。唯心之言，豈唯真心？子尚且不知煩惱心遍，安能了知生死色遍？",
 "色何以遍？色即心之故。為什麼呢？依報共造、正報別造，豈信共遍、不信別遍嗎？能造所造既是唯心，心體不可局限方所之故，所以十方佛土皆有眾生理性心種。以性喻空，具如《涅槃》一十復次。故知不曉大小教門名體同異，此是學釋教者之大患。",
 "故身子說：「我等同入法性，及也得解脫」等。子初不達我之義旨，故聞之驚駭；為子申已，理合釋然。故知世人局限我遮那唯陰質之內，而直說諸法是無情者，則有二種不如外道：外道尚且說我大色小、我遍虛空；",
 "又外道猶計眾塵所成，也不直說無情而已。又有二種不如小乘：小乘尚且說猶業力造，造遍三界；又小乘猶知諸法無常，也不直說無情而已。又有二種不如共乘：共乘尚且知造心幻化，幻遍三界；又知諸法體性即真，若次第乘故非所擬。",
 "子聞是已，也合薄知教法權實、佛性進否。客曰：仁者善分別，實破重疑，信一切法皆正因性。而說正中三因種遍、修遍、果遍，又說一塵一心即一切生佛之心性，情猶未決。我說：實由自昔不善遍攬因果自他依正觀於己心心佛眾生，也由不閱諸教大旨，不曉佛說果德之意、不達佛現互融之由。",
 "我欲開導子之情懷，更以四十六問而問於子。子若能曉我之一問，則眾滯自消，法界融通釋然大觀，洞見法界生佛依正一念具足一塵不虧。問：佛性之名，從因從果？從因非佛，果不名性。問：佛性之名，常無常嗎？",
 "無常非性，常不應變。問：佛性之名，共嗎別嗎？別不名性，共不可分。問：佛性之名，大小教嗎？小無性名，大無無情。問：佛性之名，有權實嗎？對體辯異，其相何呢。問：無情之名，大小教嗎？大教大部有權實嗎？",
 "問：無情無者，無情為色為非色嗎？為二俱嗎？問：無情色等，佛見爾嗎？為生見嗎？為共見嗎？問：無情敗壞故無性者，陰也敗壞，性也然嗎？問：無情是色，法界處色為也無嗎？為復有嗎？問：唯心之言，子曾聞嗎？",
 "唯只是心，異不名唯。問：唯心之言，凡聖心嗎？若聖若凡，二俱有過。問：唯心名心，造無心嗎？唯造心嗎？二俱有過。問：唯心唯心，也唯色嗎？若不唯色，色非心嗎？問：唯心所造唯依與正，依正能所同嗎異嗎？",
 "問：眾生量異，性隨異嗎？不爾非內，爾不名性。問：眾生惑心，性遍不遍？神我四句，為同異嗎？問：眾生有性，唯應身性也法性嗎？也報性嗎？問：眾生本迷，迷佛悟嗎？佛既悟已，悟生迷嗎？問：眾生一身，幾佛性嗎？",
 "一佛身中，幾生性嗎？問：佛國土身為始本嗎？始本同嗎？為復異嗎？問：佛土佛身為一異嗎？一無能所，異則同凡。問：佛土界分，生也居嗎？為各所居？佛無土嗎？問：佛土所攝為遠近嗎？何土與生一異共別？",
 "問：佛佛土體為同異嗎？娑婆之處為共別嗎？問：佛成道時土也成嗎？成廣狹嗎？不成有過。問：佛成見性，與生見處為同異嗎？離二不可。問：佛成土成，與彼彼成、彼彼不成為一異嗎？問：佛成三身，與彼彼果及彼彼生為一異嗎？",
 "問：佛成身土，成何眼智？見自他境初後如何？問：真如所造互相攝嗎？不相攝嗎？二俱如何？問：真如之體通於修性，修性身土等不等嗎？問：真如隨緣變為無情，為永無嗎？何當有嗎？問：真如隨緣，隨已與真為同異嗎？",
 "為永隨嗎？問：真如本有？為本無嗎？與惑共住，同異如何？問：波水同異，前後得失。真妄同異，法譬如何？問：病眼見華，華處空處。同異存沒，法譬如何？問：鏡像明體本始同異，前後存沒法譬如何？",
 "問：帝網之譬唯譬果嗎？也譬因嗎？果無因嗎？問：如意珠身，身有土嗎？唯在果嗎？通因如何？問：行者觀心，心即境嗎？能所得名，同異如何？問：行者觀心，一嗎多嗎？一多心境，同異如何？問：",
 "行者觀心，為唯觀心？也觀身嗎？也觀土嗎？問：行者觀心在惑業苦，內嗎外嗎？同嗎異嗎？問：行者觀心，心內佛性為本淨嗎？為始淨嗎？問：行者觀心，心佛眾生因果身土法相融攝一切同嗎？如是設問不可窮盡，為斷子疑且至爾許。",
 "客曰：何以不多不少唯四十六？我說：攻惑攻疑、攻行攻理，通教通義、通自通他，一問也足。為對鈍根，故四十六。及對六即分證，離為四十一位，兼前及後故四十六。應知一問也皆能攻餘四十五，餘一一位仍須皆具四十六問，乃至無量也復如是。",
 "客曰：仁者所立義，灼然異於僕昔所聞。僕初聞之，乃說一草一木、一礫一塵，各一佛性、各一因果，具足緣了。若其如此，僕實不忍。為什麼呢？草木有生有滅、塵礫隨劫有無，豈唯不能修因得果，也乃佛性有滅有生。",
 "世皆謂此以為無情，故說無情不應有性。僕乃誤以世所傳習難仁者至理，失之甚矣！過莫大矣！我說：子何因猶存無情之名？客曰：乃僕重述初迷之見。今也粗知仁者所立之理，只是一一有情，心遍性遍、心具性具，猶如虛空，彼彼無礙、彼彼各遍，身土因果無所增減。",
 "故《法華》說「世間相常住」，世間之言，凡聖因果依正攝盡。我說：觀子所見，似知大旨。何不試答向之一問？客曰：仁者向來自己說「若思一問，眾滯自消。」僕若答者，即以一答遍答眾問，何一問之有呢？",
 "我說：請述其旨。客曰：僕還攬向諸問之意，若消眾滯即名為答，何假曲申一一問呢？為什麼呢？眾問豈不由僕不受無情有性之說。僕今受之，此即是答。我說：大略雖爾，未曉子情。客曰：仁者所立義，關涉諸大教，難可具陳。",
 "僕略論之，希望垂聽覽。豈非曉最後問三無差別，即知我心彼彼眾生，一一剎那無不與彼遮那果德身心依正，自他互融互入齊等。我及眾生皆有此性，故名佛性。其性遍造、遍變、遍攝，世人不了大教之體，唯說無情、不說有性。",
 "所以須說無情有性。了性遍已，則識佛果具自他之因性，我心具諸佛之果德。果上以佛眼佛智觀之，則唯佛無生；因中若實慧實眼冥符，也全生是佛無別果佛。故生外無佛，眾生以我執取之，即無佛唯生。",
 "初心能信教仰理也無生唯佛，亡之則無生無佛，照之則因果昭然。應知眾生但理、諸佛得事，眾生但事、諸佛證理。是則眾生唯有迷中之事理，諸佛具有悟中之事理，迷悟雖殊事理體一。故一佛成道，法界無非此佛之依正。",
 "一佛既爾，諸佛咸然。眾生自於佛依正中而生殊見，苦藥昇沈。一一皆計為己身土，淨穢宛然、成壞斯在。仁者所問之意，豈不略爾？我說：善哉善哉！快領斯旨，實可總知諸問綱格。此即已答百千萬問，何獨四十六呢！",
 "客曰：幾乎不遇仁者，此生空喪。必依此見，獲勝果嗎？我說：必欲修習，教法未周，若不善我一家宗途，未可委究行門始末，安能遍括教行事理、惑智因果、依正心法，用為凡夫初心觀首？然子所領似虛其情，計子觀道猶為罔象。",
 "客曰：觀道者何？仁者師誰呢？法依何呢？我說：子豈不聞，天台大師靈山親承，大蘇妙悟。是余師也。《摩訶止觀》，所承之法。以二十五法為前方便，十法成乘觀於十境，十境互發觀時進否。此觀道之大略。",
 "諸問且令識十乘初妙境而已，餘乘諸境不暇論之。客曰：善哉！僕當慕之，以為永劫之仗託。客曰：屢聞講說大乘諸師，猶以無情、佛性為一別見。為什麼呢？我說：此有由也。斯等曾覩小乘無情之名，又見大乘佛性之語，亡其所弘融通之譚，而棄《涅槃》虛空之喻，不達修性三因離合、不思生佛無差之旨，謬斆傳習無情之言，反難己宗唯心之教。",
 "專引《涅槃》瓦石之說，不測時部出沒之意。如福德子而無壽命，弱喪徒歸，猶迷本族；如受貴位不識祖宗，也如死人而著瓔珞，用此福為？用瓔珞為？法相徒施，全迷其本。忽遇斯等應以如上諸意問之，所弘之典大小乘嗎？",
 "尚且失於小乘，已如前說。客曰：斯失者眾。聞仁者所宗四教釋義，可得聞嗎？我說：此之四釋，關涉五時、牢籠八教，十方三世大小乘法咸攝其中。豈可率爾譚其始末？客曰：若爾，可能以四教略判佛性無情有無、心造心變、具不具嗎？",
 "我說：略示方隅，斯也可矣。為什麼呢？自《法華》前，藏通三乘俱未稟性，二乘憚教、菩薩不行。別人初心教權理實，以教權之故所稟未周。故此七人可說無情，不說有性。圓人始末知理不二，心外無境，誰情無情？",
 "法華會中一切不隔，草木與地四微何殊？舉足修途皆趣寶渚，彈指合掌咸成佛因，與一許三無乖先志，豈至今日說無情無？說心造心變咸出大宗，小乘有言而無其理。然諸乘中，其名雖同，義也少別，有共造依報、各造正報，有共造正報、各造依報。",
 "眾生迷之故，或說自然梵天等造，造已或說情與無情。故造名猶通，應說心變。心變復通，應說體具。以無始來心體本遍，故佛體遍由生性遍。遍有二種：一寬廣遍、二即狹遍。所以造通於四，變義唯二，即具唯圓及別後位，故藏通造六，別圓造十。",
 "此六及十，括大小乘教法罄盡，由觀解異，故十與六各分二別。藏見六實，通見無生，別見前後生滅，圓見事理一念具足。論生，兩教似等；明具，別教不詮。種具等義，非此可述。故別佛性，滅九方見；",
 "圓人即達九界三道，即見圓伊三德體遍。客曰：如何能攝依正因果？我說：一家所立不思議境，於一念中理具三千，故說念中具有因果、凡聖、大小、依正、自他，故所變處無非三千。而此三千性是中理，不當有無，有無自爾。",
 "為什麼呢？俱實相之故。實相法爾具足諸法，諸法法爾性本無生。故雖三千，有而不有，共而不雜、離也不分，雖一一遍也無所在。客曰：其理必然，僕深仰之。此為憑教，為通依諸部？為專在一經？我說：斯問甚善，能使其理永永不朽。",
 "雖則通依一切大部，指的妙境出自《法華》。故〈方便品〉初，佛歎十方三世諸佛所得微妙難解之法，所謂諸法實相如是相等。當知如是相等，即是轉釋諸法實相。以諸法之故，故有相等；以實相之故，相等皆是。",
 "實相無相，相等皆如。客曰：云何三千？我說：實相必諸法，諸法必十如，十如必十界，十界必身土。又依《大經》及以《大論》立三世界，故有三千。具如《止觀》及廣記中。故知因果凡聖恒具三千。所以歎說「唯佛與佛乃能究盡。",
 "十方世界稻麻二乘、如恒河沙不退菩薩，並不能知斯義少分。」即指前之七種人也。所以身子三請慇懃，十方三世諸佛開顯，釋迦仰同無復異趣，大車譬此、宿世示此，壽量久本唯證於此，根敗適復獲記由此。",
 "菩薩疑除損生增道，始初發心終訖補處，豈有餘途？並託於此。由前四時兼但對帶，部非究竟，故推功《法華》。《涅槃》兼權，意如前說。當知一乘十觀即法華三昧之正體，普現色身之所依。正因佛性由之果用，緣了行性由之能顯，性德緣了所開發，《涅槃》真伊之所喻，《法華》大車之所至。",
 "諸大乘意，準例可知。子得聞之，可謂久種，勤而習之無使焦敗。願未來世，諸佛會中與子相遇。於是野客悲喜交集說：投身莫報，粉骨寧酬？唯以此義隨方轉說，以報所聞。如何？我說：佛有誠誡，自可為規。",
 "經說「若但讚佛乘，眾生沒在苦。我寧不說法，疾入於涅槃。」尋思方便，先小後大，此乃以偏助圓方可為說。又說「當來世惡人，破法墮惡道。志求佛道者，廣讚一乘道。」此即簡人，方可為說。然末代施化復未知根，也可如〈安樂行〉中但以大答，也可如不輕、喜根而強毒之。",
