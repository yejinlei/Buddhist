 "」所以能於微塵現國土，國土微塵又示現，因此成其無盡復無盡。這就是法界緣起，如智如理、實德如此，非即變化對緣方便而說。若是大乘宗所明，即說神力變化之故大小得以相入，或說菩薩力故入，又說不二故入，不同於一乘之說。",
 "問：若此宗明相入不論神力，而說自體常如此者，這就渾然無疆界、無始無終，怎麼能辨因果、教義等呢？答：因隨智差別之故，舉一為主，餘則為伴。猶如帝網，舉一珠為首，眾珠現於其中。如一珠如此，一切珠現也如此。",
 "所以前經舉一菩薩為主，一切菩薩圍繞，一一菩薩都如此。又如諸方都來證誠，同其名號，一切十方證誠也都如此，因此成其無盡復無盡，而不失因果先後次第，而體無增減。所以經說：「一切眾生盡成佛，佛界亦不增，眾生界亦不減；",
 "若無一眾生成佛，眾生界亦不增，佛界亦不減。」第三祕密隱顯俱成門者，此約緣起而說，還具前教義十門。所說隱顯者，如《涅槃經》的半字及滿字。昔日說半字，故半字即顯、滿字即隱；今日說滿字，即滿字即顯、半字即隱。",
 "這是約緣而說隱顯。又如〈月喻品〉說：「此方見半，他方見滿，而彼月性實無虧盈，隨緣所見之故有增減。」這即是大乘宗中所說。若通宗辨者，不待說與不說，常半常滿、隱顯無別時。如那月性常滿而常半，半滿無異時。",
 "所以如來於一念中八相成道，生時即是滅時，同時俱成之故，所以稱祕密。如似十數，一即十，一即是顯，二三四至十即為隱。又眼根入正受即是顯，於色法中三昧起即名隱。此隱顯體無前後，所以說祕密。",
 "第四微細相容安立門者，此就相而說。如一微塵，這就是其小相。無量佛國、須彌金剛山等，即其大相。直以緣起實德無礙自在，致使相容，非是天人所作故而安立。如似一微塵中有穢國土，而即於此微塵中具有不可說的淨國，在此微塵中，而於那穢國不相妨礙，而此淨國之相仍也不失。",
 "乃至有諸國土，尸羅盆幢形、三方及四維等國，在此一微塵中，常不相妨礙。所以〈普賢品〉說：「一切諸世界入於一微塵中，世界不積聚，亦復不離散。」所以知道若與普相應，能於一微塵中見不可說國土，而不雜亂、不增不減，豈可須彌納芥子還當作難事呢？",
 "理事等十門安立相容也如此。問：此相容門與前因陀羅網門有何差別？答：諸門隱映、互相顯發、重重復重重成其無盡者，即是因陀羅網門中所攝。若諸門一時具顯、不相妨礙，即是相容門中所攝。第五十世隔法異成門者，此約三世而說。",
 "如〈離世間品〉說：十世者，過去說過去、過去說未來、過去說現在，現在說現在、現在說未來、現在說過去，未來說未來、未來說過去、未來說現在，三世為一念，合前九為十世。如此十世以緣起力之故，相即又相入，而不失三世，如以五指為拳不失指，十世雖同時而不失十世。",
 "所以經說：「過去劫入未來，現在劫入過去；現在劫入過去，未來劫入現在。」又說：「長劫入短劫，短劫入長劫；有劫入無劫，無劫入有劫。」又說：「過去是未來，未來是過去，現在是過去，菩薩悉了知。」又說：「無盡無數劫，能作一念頃，非長亦非短，解脫人所行。」",
 "」如此十世相入又相即，而不失先後短長之相，所以說隔法異成。教義、理事等十門相即相入，而不失先後差別之相，故名異成。第六諸藏純雜具德門者，此約諸度門而說。為什麼？如似就一施門說者，一切萬法都名為施，所以名純。",
 "而此施門即具諸度等行，故名為雜。如此純與雜不相妨礙，故名具德。如《大品經·一念品》明，從始至終不出一念，即名為純。而此一念之中具於萬行，即名為雜。雖然如此，卻與此中純雜義有別。為什麼？如那經的一念，同是無得相應，不明緣起德用。",
 "若此明純者，若約施門一切皆施，若說忍門一切皆忍。說忍門者，諸行如虛空，即名為純；而此忍門具足諸門，即名為雜。純雜不相亂，故名具德，所以不同於那〈念品〉。又問：這與六度相攝義有何差別？答：",
 "六度相攝義者，如似以施攝諸度，而諸度不是施。若此明者，以施攝諸門，無門不是施。以緣起力之故，不同於六度相攝，所以一攝於九十，而九十等都是一，是故名為純；而一內即具九十等，所以又名為雜。故知不同於相攝義。",
 "問：這與《大品》相資義又有何差別？那中說相資者，闕一即不成，此中十數闕一也不成。彼此二者不知有何差別？答：那說相資者，能非是所。今說十成一而一即是十，所以不同於資義。第七一多相容不同門者，此約理而說。",
 "以一入多、多入一故名相容，即體無先後，而不失一多之相，故說不同。這即是緣起實德，非天人所修。所以經說：「以一佛土滿十方，十方入一亦無餘，世界本相亦不壞，自在願力故能爾。」又如〈普賢品〉說：「一切眾生身入一眾生身，一眾生身入一切眾生身。」",
 "」又說：「一切諸世界，令入一塵中，世界不積聚，亦復不雜亂。」須彌入芥子，這裡就不說了。第八諸法相即自在門者，此約用而說。還就約教義、理事等十門，取其三種世間圓融無礙自在，所以一即攝一切，成其無盡復無盡。",
 "因其無盡之故，相即又相入，此約用而說。問：此明其無盡復無盡、相即復相入，與前因陀羅網及微細相容門有何差別？答：如譬說同體門中說者，若就隱映相應、互相顯發、重重復重重成其無盡者，即是因陀羅網門所攝。",
 "若諸門一時具顯、不相妨礙者，是相容門所攝。若就三世圓融無礙自在、相即又相入、成其無盡復無盡者，即是此門所攝。問：若如此相即又相入、成其無盡復無盡者，這就渾然無疆界，何始何終、何因何果呢？答：",
 "此據法界緣起體性而成其無盡復無盡，所以先後因果不失。雖不失先後，而先後相即又相入，故成其無盡。因先後相即又相入之故，初發心時便成正覺。如前章門，一即一切，無盡也復無盡，二三也如此。所以此經歎初發心功德說：「彼一念功德，深廣無邊際。",
 "如來分別說，窮劫不可盡。」此即明其一即一切、成其一切無盡。又說：「何況於無量，無數無邊劫，具足修諸度，諸地功德行。」此即是從二三至九十都成無盡。因此從十信終心，至十住、十行及十迴向地等，都明成佛者，實由始終相即又相入、成無盡之故。",
 "問：如前明果德絕於說相，為何十信終心即具佛果德用呢？若十信同於果德者，即果德是可說之相，為何不可說呢？答：因位菩薩有果德者，是要彰明果德是不可說。所以歎德文說：「菩薩在此一地，普攝一切諸地功德。」",
 "」問：若一地即攝一切諸地功德，一即一切、初即攝後者，一門即具，何用餘門呢？答：若無餘門，一門即不成之故。如一升即攝一斗，若無一升，此斗即不成。問：若無升即無斗者，今舉一升即得一斗嗎？",
 "若一升不得一斗，一行也就不得具一切行。答：十升合成一斗，既無其升時，將用什麼作斗？所以如無升即無斗，有升即有斗。今舉升即斗，斗升之外無別升斗，如龜毛兔角不可得。初心即成佛，成外無別修，其相如虛空。",
 "所以說初心成佛者，非謂不具諸功德。如經說：「普莊嚴童子一生具見佛聞法，即得三昧，即至後際見佛滅度後復得三昧。」如經一生得見聞、若熏習，二生成其解行，三生得入果海。同一緣起大樹，而此三生只在一念，猶如遠行到在初步。",
 "然而此初步之到，非謂沒有後步。明此童子得入果海，非不久植善根。問：既然說久修始得者，怎麼說一念得呢？答：說久修行善根者，即在三乘教所攝。從三乘入一乘，即是一念始終具足。所以經說：「初發心時便成正覺，乃至具足慧身不由他悟。」",
 "」譬如眾流入海，才入一滴即稱周大海、無始無終。若其餘江河水之深，不及入大海一滴，所以即用三乘中修。三乘多劫不及與一乘中一念，所以下面就明善財從文殊所發心求善知識，經歷一百一十城已，而不如一念得見普賢菩薩。",
 "故知得入此緣起大海，一念豈不成佛呢？至於如初坐用心之徒，只取靜心即說成佛者，這也說佛成在，而不得是圓極之成。如諸江河也得是水，未得同於大海之水。此中通辨一念成佛義者，若小乘說，要三大阿僧祇劫、滿百劫修行相好業才得成佛。",
 "行若滿，意欲不成佛也不得，故無一念成佛之義。若大乘明一念成佛義者，凡有二種：一是會緣以入實，性無多少，故明一念成佛義。如《大品經·一念品》之義。二者行行既滿，取最後念名為成佛。如人遠行，以後步為到，此也分用緣起。",
 "而明三僧祇劫修道，地前是一僧祇，初地至七地是二僧祇，八地至十地是三僧祇。然而也不定，由有一念成佛，故明知不定。若一乘明一念成佛，如大乘取最後一念成佛，即入一乘。以後望初，初念即是成。",
 "為什麼？以因果相即、同時相應之故。若欲論其成者，成復成、成復成。眾生欲在後成佛者，在後復在後、在後復在後。所以〈不思議品〉說：「諸佛如來非不先覺，為眾生故，於念念中新新斷結，亦不住學地而成正覺。」",
 "」所以今舉一念成者，即與佛同時位，未見究竟，故又有淺深之殊。如人始出門，及與久遊他土，雖同在空中，而遠近有別。所以信、住等位各各言成佛者，而又辨其淺深，這須善加思惟。第九唯心迴轉善成門者，此約心而說。",
 "所謂唯心迴轉者，前諸義教門等都是如來藏性清淨真心之所建立。若善若惡，隨心所轉，故說迴轉善成。心外無別境，故說唯心。若順轉即名涅槃，所以經說：「心造諸如來。」若逆轉即是生死，所以說：「三界虛妄，唯一心作。」",
 "」生死涅槃都不出心，所以不能定說性是淨及不淨。所以《涅槃》說：「佛性非淨亦非不淨，淨與不淨皆唯心。」故離心更無別法。所以《楞伽經》說：「心外無境界，無塵虛妄見。」問：若心外更無別境，有無都由心成者，如人先見障外有物，另有人去取那物，那時心仍謂有，而爾時物實無，怎麼叫由心成呢？",
 "答：若隨虛妄心中轉者，此障外之物也隨心之有無，這也是心隨去物、不去物而轉。若論如來藏性真實淨心說者，此物不動本處、體應十方，性恒常轉，縱移到他方而常不動本處。這即是緣起自在力，然而非是變化幻術所為，所以雖復七處九會，而不離寂滅道場。",
