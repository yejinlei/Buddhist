 "」以樓觀即是菩提相，所以說顯法生解。若大乘宗中所明，也託事以顯法，即以異事顯於異理之法。此中以事即法，故隨舉一事攝法無盡，所以前面舉旛幢等都說一切。所以不同於大乘之說。此中明因果者，如一乘說。",
