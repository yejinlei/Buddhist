def load(fid):
    with open(f"{IN}/{fid}.json", encoding="utf-8") as f:
        return json.load(f)


def apply(fid, entries):
    obj = load(fid)
    trs = obj["translations"]
    assert len(trs) == len(entries), (fid, len(trs), len(entries))
    for i, (tr, (sec, mod)) in enumerate(zip(trs, entries)):
        assert len(sec) <= 14, (fid, i, sec, len(sec))
        assert "【" not in sec and "】" not in sec and "《" not in sec
        assert mod.startswith("【" + sec + "】"), (fid, i, sec, mod[:24])
        assert "【义解】" in mod, (fid, i, sec)
        assert not mod.endswith("】"), (fid, i, sec)
        assert '"' not in mod and "'" not in mod, (fid, i, sec)
        tr["section"] = sec
        tr["modern"] = mod
    with open(f"{OUT}/modern_{fid}.json", "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
    print("wrote", fid, len(trs), "sections")


