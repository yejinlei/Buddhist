 "无有了期。但只存心一处，无有不得者，时节因缘到来，自然触著磕著、喷地醒去。○把自家心识缘世间尘劳的，回过来底在般若上，纵今生打未彻，临命终时定不为恶业所牵，来生出头定在般若中，见成受用。",
 "这是决定的事，无可疑者。○但自时时提撕：妄念起时，也不必将心止遏，只看个话头，行也提撕、坐也提撕，提撕来、提撕去，没滋味，那时便是好处，不得放舍。忽然心华发明、照十方刹，便能于一毛端。",
 "现宝王刹，坐微尘里转大法轮。评曰：师自云：他人先定而后慧，某甲先慧而后定。盖话头疑破，所谓休去歇去者，不期然而然矣。某年二十，知有此事，至三十二，请益十七八员长老，问他做工夫，都无端的。",
 "后参皖山长老，教看无字，十二时中要惺惺如猫捕鼠、如鸡抱卵，无令间断；未透彻时如鼠咬棺材，不可移易。如此做去，定有发明时节。于是昼夜孜孜体究，经十八日，吃茶次，忽会得世尊拈花、迦叶微笑。",
 "不胜欢喜，求决三四员长老，俱无一语，或教只以海印三昧一印印定、余俱莫管，便信此说。过了二载，景定五年六月，在四川重庆府患痢，昼夜百次，危剧濒死：全不得力，海印三昧也用不得，从前解会的。",
 "也用不得。有口说不得，有身动不得，有死而已。业缘境界俱时现前，怕怖慞惶、众苦交逼，遂强作主宰，分付后事，高著蒲团、装一炉香，徐起坐定，默祷三宝龙天，悔过从前诸不善业：若大限当尽，愿承般若力。",
 "正念托生，早早出家；若得病愈，便弃俗为僧，早得悟明、广度后学。作此愿已，提个无字、回光自看。未久之间，脏腑三四回动，只不管他；良久眼皮不动，又良久不见有身，只话头不绝，至晚方起。",
 "病退一半。复坐至三更四点，诸病尽退，身心轻安。八月至江陵落发。一年起单行脚，途中炊饭，悟得工夫须是一气做成、不可断续。到黄龙归堂，第一次睡魔来时，就座抖擞精神，轻轻敌退；第二次亦如是退。",
 "第三次睡魔重时，下地礼拜消遣，再上蒲团。规式已定，便趁此时打併睡魔：初用枕短睡、后用臂、后不放倒身。过二三夜，日夜皆倦，脚下浮逼逼地，忽然眼前如黑云开、自身如新浴出一般清快，心下疑团愈盛。",
 "不著用力，绵绵现前，一切声色、五欲、八风皆入不得，清净如银盆盛雪相似、如秋空气肃相似。却思工夫虽好、无可决择。起单入浙，在路辛苦、工夫退失，至承天孤蟾和尚处归堂，自誓未得悟明、断不起单。",
 "月余工夫复旧。其时遍身生疮也不顾，舍命趁逐工夫，自然得力，又做得病中工夫。因赴斋出门，提话头而行，不觉行过斋家，又做得动中工夫。到此却似透水月华，急滩之上、乱波之中，触不散、荡不失。",
 "活鱍鱍地。三月初六日坐中，正举无字，首座入堂烧香，打香盒作声，忽然㘞地一声，识得自己、捉败赵州，遂颂云：没兴路头穷，踏翻波是水，超群老赵州，面目只如此。秋间临安见雪岩、退耕、石坑、虚舟诸大老。",
 "舟劝往皖山。山问：光明寂照遍河沙，岂不是张拙秀才语？某开口，山便喝出。自此行坐饮食皆无意思，经六个月。次年春，因出城回，上石梯子，忽然胸次疑碍冰释，不知有身在路上行。乃见山，山又问前语。",
 "某便掀倒禅床，却将从前的数则极誵讹公案一一晓了。诸仁者，参禅大须仔细，山僧若不得重庆一病，几乎虚度。要紧在遇正知见人。所以古人朝参暮请、决择身心，孜孜切切、究明此事。评曰：他人因病而退惰。",
 "此老带病精修，终成大器，岂徒然哉。禅人病中，当以是痛自勉励。近来笃志参禅者少，才参个话头，便被昏、散二魔缠缚。不知昏散与疑情正相对治：信心重则疑情必重，疑情重则昏散自无。二六时中，随话头而行。",
 "随话头而住，随话头而坐，随话头而卧，心如棘栗蓬相似，不被一切人我、无明、五欲、三毒等之所吞啖。行住坐卧，通身是个疑团，疑来疑去、终日呆桩桩地，闻声睹色，管取㘞地一声去在。做工夫须要起大疑情。",
 "你工夫未有一月半月成片，若真疑现前、撼摇不动，自然不怕惑乱。只管勇猛忿去，终日如呆的汉子相似；到恁么时，不怕瓮中走鳖。时不待人，转眼便是来生，何不趁身强力健，打教彻去、讨教明白去？何幸又得在此名山大泽、神龙世界、祖师法窟，僧堂明净。",
 "粥饭清洁、汤火稳便，若不向这里打教彻、讨教明白去，是你自暴自弃、自甘陆沈，为下劣愚痴之汉。若果是茫无所知，何不博问先知？凡遇五参，见曲录床上老汉横说竖说，何不历在耳根、反复寻思：毕竟是个什么道理？○山僧五岁出家。",
 "在上人侍下，见与宾客交谈，便知有此事，便信得及，便学坐禅。十六为僧，十八行脚，在双林远和尚会下打十方，从朝至暮不出户庭；纵入众寮、至后架，袖手当胸、不左右顾，目前所视不过三尺。初看无字。",
 "忽于念头起处打一个返观，这一念当下冰冷，直是澄澄湛湛、不动不摇，过一日如弹指顷，都不闻钟鼓之声。十九在灵隐挂搭，见处州来书记说：钦禅，你这工夫是死水，不济事，动静二相打作两橛，参禅须是起疑情。",
 "小疑小悟，大疑大悟。被州说得著，便改了话头，看个干屎橛，一味东疑西疑、横看竖看，却被昏散交攻，顷刻洁净也不能得。移单过净慈，结甲七个兄弟坐禅，封被胁不沾席。外有修上座，每日在蒲团上。",
 "如个铁鐝子相似；地上行时开两眼、垂两臂，也如个铁鐝子相似，要与他亲近说话更不可得。因两年不倒身，捱得昏困，遂一放都放了；两月后，从前整顿得这一放，十分精神。元来要究明此事，不睡也不得。",
 "须是到中夜熟睡一觉，方有精神。一日廊下见修，方得亲近，却问：去年要与你说话，只管避我，如何？修云：真正办道人，无剪爪之工，更与你说话在？因问：即今昏散打屏不去。修云：你自不猛烈，须是高著蒲团。",
 "竖起脊梁，尽浑身併作一个话头，更讨甚昏散。依修做工夫，不觉身心俱忘，清清三昼夜、两眼不交睫。第三日午后，在三门下如坐而行，又撞见修，问：你在此做什么？答云：办道。修云：你唤什么作道？",
 "遂不能对，转加迷闷，即欲归堂坐禅。又撞见首座道：你但大开了眼，看是什么道理。又被提这一句，只欲归堂。才上蒲团，面前豁然一开，如地陷一般，是时呈似人不得、非世间一切相可喻。便下单寻修。",
 "修见便道：且喜且喜。握手门前柳堤上行一转。俯仰天地间，森罗万象眼见耳闻，向来所厌所弃之物与无明烦恼，元来都是自己妙明真性中流出。半月余动相不生。可惜不遇大手眼尊宿，不合向这里坐住。",
 "谓之见地不脱、碍正知见。每于睡著时打作两橛，公案有义路者则理会得，如银山铁壁者却又不会。虽在无准先师会下，多年入室升座，无一语打著心下事；经教语录上，亦无一语可解此病。如是碍在胸中者十年。",
 "一日在天目佛殿上行，抬眼见一株古柏，触目省发，向来所得境界、碍膺之物扑然而散，如暗室中出在白日。从此不疑生、不疑死、不疑佛、不疑祖，始得见径山老人立地处，好与三十拄杖。此事只要当人的有切心。",
 "才有切心，真疑便起，疑来疑去、不疑自疑，从朝至暮、粘头缀尾，打成一片，撼亦不动、趁亦不去，昭昭灵灵常现在前，此便是得力时也。更须确其正念、慎无二心，至于行不知行、坐不知坐，寒热饥渴。",
 "悉皆不知。此境界现前，即是到家消息，也巴得够、也撮得著，只待时刻而已。却不得见恁么说起一念精进心求之，又不得将心待之，又不得纵之弃之；但自坚凝正念，以悟为则。当此之时，有八万四千魔军。",
 "在你六根门头伺候，一切奇异善恶等事随你心现。你若瞥起毫厘著心，便堕他圈缋、被他作主、受他指挥，口说魔话、身行魔事，般若正因从兹永绝，菩提种子不复生芽。但莫起心，如个守尸鬼子。",
 "守来守去，疑团子歘然爆地一声，管取惊天动地。○某甲十五出家，二十更衣入净慈，立三年死限学禅。初参断桥和尚，令参「生从何来、死从何去」，意分两路、心不归一。后见雪岩和尚，教看无字，又令每日上来一转。",
 "如人行路、日日要见工程。因见说得有序，后竟不问做处，一入门便问：谁与你拕这死尸来？声未绝便打出。次后径山归堂，梦中忽忆「万法归一，一归何处」，自此疑情顿发，直得东西不辨、南北不分。",
 "第六日随众阁上讽经，抬头忽睹五祖演和尚真赞，末两句云：百年三万六千朝，返覆元来是这汉。日前拕死尸句子蓦然打破，直得魂飞胆丧、绝后再稣，何啻放下百二十斤担子。其时正二十四岁，满三年限。",
 "次后被问：日间浩浩作得主么？答曰：作得。又问：睡梦中作得主么？答云：作得。又问：正睡著无梦时，主在何处？于此无言可对、无理可伸。和尚嘱云：从今不要你学佛学法、穷古穷今，只饥来吃饭、困来打眠。",
 "才眠觉来，抖擞精神：我这一觉，主人公毕竟在什么处安身立命？自誓拼一生做个痴呆汉，定要见这一著子明白。经及五年，一日睡觉正疑此事，忽同宿道友推枕子落地作声，蓦然打破疑团，如在网罗中跳出。",
 "所有佛祖誵讹公案、古今差别因缘，无不了了。自此安邦定国、天下太平，一念无为、十方坐断。评曰：前示众做工夫一段，至为切要，学者宜书诸绅。其自叙中所云「饥来吃饭困来打眠」，是发明以后事。",
 "莫错会好。山僧十三岁知有佛法，十八出家，二十二为僧。先到石霜，记得祥庵主教时时观见鼻头白，遂得清净。后有僧自雪岩来，写得岩《坐禅箴》看，我做工夫却不曾从这里过，因到雪岩，依他所说做工夫。",
 "单提无字，至第四夜通身汗流、十分清爽，继得归堂，不与人说话，专一坐禅。后见妙高峰，教十二时中莫令有间：四更起来便摸索话头、顿在面前，略觉困睡便起身下地，也是话头；行时步步不离话头。",
 "开单展钵、拈匙放箸、随众等事，总不离话头，日间夜间亦复如是，打成片段，未有不发明者。依峰开示做工夫，果得成片。三月二十日，岩上堂云：兄弟家久在蒲团上瞌睡，须下地走一遭，冷水盥漱。",
 "洗开两眼，再上蒲团，竖起脊梁、壁立万仞，单提话头。如是用功，七日决定悟去，此是山僧四十年前已用之工。某即依他所说，便觉工夫异常。第二日，两眼欲闭而不能闭；第三日，此身如在虚空中行。",
 "第四日，曾不知有世间事。其夜倚栏杆少立，泯然无知；检点话头，又不打失。转身上蒲团，忽觉从头至足如劈破髑髅相似、如万丈井底被提在空中相似，此时无著欢喜处。举似岩，岩云：未在，更去做工夫。",
 "求得法语，末后云：绍隆佛祖向上事，脑后依前欠一槌。心下道：如何又欠一槌？不信此语，又似有疑，终不能决。每日堆堆坐禅，将及半载。一日因头痛煎药，遇觉赤鼻，问那吒太子拆骨还父、拆肉还母话。",
 "记得被悟知客问、不能对，忽然打破这疑团。后到蒙山，山问：参禅到什么地方是毕工处？遂不知头。山教再做定力工夫、洗荡尘习。每遇入室下语，只道「欠在」。一日晡时坐至更尽，以定力挨拶，直造幽微。",
 "出定见山说此境已，山问：哪个是你本来面目？正欲下语，山便闭门。自此工夫日有妙处。盖以离岩太早，不曾做得细密工夫，幸遇本色宗匠、乃得到此。元来工夫做得紧峭，则时时悟入、步步剥落。",
 "一日见壁上三祖《信心铭》云「归根得旨，随照失宗」，又剥了一层。山云：这事如剥珠相似，愈剥愈光、愈明愈净，剥一剥胜他几生工夫也。但下语犹只道「欠在」。一日定中，忽触著「欠」字，身心豁然、彻骨彻髓。",
 "如积雪卒然开霁，忍俊不禁，跳下地来擒住山云：我欠少个什么？山打三掌，某礼三拜。山云：铁山这一著子几年，今日方了。○暂时话头不在，如同死人。一切境界逼迫临身，但将话头与之抵当。时时检点话头。",
 "动中静中，得力不得力。又定中不可忘却话头，忘话头则成邪定；不得将心待悟，不得文字上取解会，不得些少觉触以为了事。但教如痴如呆去，佛法世法打成一片，施为举措只是寻常，惟改旧时行履处。",
 "古云：大道从来不属言，拟谈玄妙隔天渊；直须能所俱忘却，始可饥餐困则眠。",
 "直至今日，触著痛处、不觉泪流，岂似你们咬著些子苦味便掉头不顾？",
 "这一著子，是从上佛祖了生脱死的已验三昧，惟贵信得及、久远不退转，更无有不获其相应者。○看话头做工夫，最是立脚稳当、悟处亲切，纵此生不悟，但信心不退，不隔一生两生，更无有不获开悟者。○或三十年二十年。",
 "未即开悟，不须别求方便，但心不异缘、意绝诸妄，孜孜不舍，只向所参话上立定脚头，拼取生与同生、死与同死，谁管三生五生、十生百生？若不彻悟，决定不休。有此正因，不患大事之不了明也。○病中做工夫。",
 "也不要你精进勇猛，也不要你撑眉努目，只要你心如木石、意若死灰，将四大幻身撇向他方世界之外：由他病也得、活也得、死也得，有人看也得、无人看也得，香鲜也得、臭烂也得，医得健来、活到一百二十岁也得。",
 "如或便死、被宿业牵入镬汤炉炭里也得。如是境界中都不动摇，但切切将个没滋味话头，向药炉边枕头上默默咨参，不得放舍。评曰：此老千言万语，只教人看话头、做真实工夫，以期正悟，谆切透快。",
 "千载而下，如耳提面命，具存全书，自应遍览。生不知来处，谓之生大；死不知去处，谓之死大。腊月三十日到来，只落得手忙脚乱，何况前路茫茫、随业受报，正是要紧事在。这个是生死报境。若论生死业根。",
 "即今一念随声逐色、使得七颠八倒者便是。由是佛祖运大慈悲，或教你参禅、或教你念佛，令你扫除妄念、认取本来面目，做个洒洒落落大解脱汉。而今不获灵验者，有三种病：第一、不遇真善知识指示。",
