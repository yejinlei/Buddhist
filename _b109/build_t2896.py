 "作是语者，多劫受苦，无有出期。复次善男子，如是诸恶苾刍，为名利故，递相是非，灭我真实法律。不依师学，自心坐禅，自执己见，以非为是，不能分别是邪是正，向诸道俗常作是言：我解禅法，我能知实、",

 "我能见是。善男子，如是之人，灭我法眼，自堕地狱。复次善男子，我诸恶弟子，自言我解经律，彼实不解，自身破戒，不能会解我真实义，作如是言：世尊所说毗奈耶中，听许食肉。善男子，我若解说食肉之过，",

 "一切声闻、缘觉、初地菩萨，心皆迷闷、无所了知，情怀忧苦。善男子，如是等人虚妄谤我。善男子，毗奈耶中，为病患人听食三种清净肉者，皆是不可思议，汝应知之。善男子，吾从成佛已来乃至今日，",

 "我声闻弟子处处受肉食者，凡夫众生见彼食已，作是念言：实见食肉。不知我有善巧方便，颠倒妄说，获大重罪。复有众生，见诸病患苾刍食肉之时，深入无量智慧法门；复有无量见者，断下烦恼、断上烦恼、",

 "断中烦恼；复有苾刍，度脱众生，出离生死，入如来道，得达彼岸。何以故？善男子，此是如来教化说法不可思议，为欲调伏一切众生故，汝应知之。我声闻弟子未曾食啖众生肉也，况诸菩萨。我于毗奈耶中，",

 "为病苾刍，顺世间医，须食三种清净肉者，是何等肉？善男子，当知彼肉不从四大而生，不从胎生、不从卵生、不从湿生、不从化生，不与识合、不与命合，非实非虚。当知世间都无此肉，是我方便作如是说。",

 "不解我意，自损己身。复次善男子，未来世中，诸恶苾刍，于国国、城城、村村、寺寺、处处，讲说经律论等，随文取义，不达如来深密要义。善男子，我出于世，为大众说食众生肉，无有是处。若食肉者，无有慈悲。",

 "无慈悲者，非我弟子，我非彼师。何以故？此大众中，各有异性、各有异见，何况未来世者。善男子，今此众中，或见如来住世一劫，或见如来入般涅槃，或有或生都不见我，或见我身、或不见我身，或见我身倍长三人，",

 "或见如来光明之身，或见大身、或见化身，或见报身坐莲华藏师子之座，菩萨围绕，住于无量世界海中，随大众心而为说法；或有见我法身同于虚空，无有色像，周遍法界，清净无碍；或有见我住娑罗双树间。",

 "或不见者，或见此地土沙砾石，或见此地种种树林、土石、墙壁周匝围绕，或见此地及墙壁等俱是七宝，或见四宝庄严，或见众宝庄严，或见如来过去、未来、现在起行游化之处，见如是等不可思议希有之事。何以故？",

 "一切众生业行不同，是故所见各异。善男子，如来终无异相，应如是知。复次善男子，诸佛出世，令使一切依法行人皆悉远离染著世间，亦复不离世间，显示实相清净法界，以妙梵音说清净法，以种种方便摄诸众生。",

 "若有不解、依我法者，不得摄受、不得利益。所以者何？为一切众生业行意乐各各不同，为斯义故，于一切法中所解各异。一切声闻、缘觉，以自力故，不测佛意，何况未来愚痴等辈。善男子，如是如来佛之威力，",

 "不可思议，应如是知。复次善男子，像法时中，多有诸恶苾刍，不能解我善巧方便秘密之义，以彼愚痴，自在说法，随文取义、不得深意，又亦不求秘密之义，而自称言：我解佛所说甚深之义，我亦能说甚深之义。",

 "当知此人是三世诸佛怨家，灭我法眼，像法、正法亦能灭尽。善男子，诸佛所说有二种法：一是世谛、二是真谛。所闻法者，亦如是听、亦如是修。若不解者，远离真实，唯有像法。当尔之时，多有乐行恶行苾刍，",

 "不会真理，不信我所说教法，执云非佛所说。如是等人，为邪见故，堕大地狱，多劫受苦。复次善男子，未来世中，多有诸恶苾刍，自赞毁他，常作是言：我是法师、我是律师、我是头陀。此三种人，",

 "为自赞故能灭我法，更非余人。善男子，我之教法，一切外道而不能灭、魔王眷属亦不能灭；此三种人，以愚痴故尚灭像法，何况正法？如是等人，增上慢故，颠倒说法，是律非律，错教坐禅，以自高故，",

 "毁辱我法。如是等人，舍命之后，速疾堕于阿鼻地狱，譬如高山顶上射箭而下，如是等人亦复如是，经历多劫，受大苦恼。尔时常施菩萨白佛言：世尊，如是等人受地狱苦，罪恶众生何时得出？佛告常施菩萨言：",

 "善男子，汝应当知，我说此罪恶众生于地狱中多时受苦，余业不尽，难有出期。复次善男子，我灭度已一千五百年后，我教法中恶法渐兴，非法羯磨出现于世，实非沙门自称沙门，实非梵行，",

 "自称梵行。破戒苾刍遍赡部洲，处处充满，为利养故不修道德，弃舍我教、爱乐非法，多畜八种不净之物，自具十恶、不行十善，舍离律仪，未满十夏，畜二沙弥以承事己，与他小僧乐作依止，乐度俗人，",

 "出家将为弟子，乐作和上及阿阇梨耶，乐与他人受其大戒，以自高故，令诸道俗轻贱我法、不生敬重。如是苾刍，堕诸恶趣。复次善男子，未来世中，多诸道俗造诸寺舍、佛堂、塔庙，衢路道边，处处充满，",

 "及佛形像或在山林旷野、或在道边、或在巷路、多人阛闹臭秽恶处，破落毁坏，无有一人发心修理。设有见者，便自念言：修他故者不及造新。为名利故，遂造新寺及以塔庙。虽造塔寺，不生敬重，请僧在寺，",

 "不与饮食、衣服、卧具、汤药，反更于中借取乞贷，餐啖僧食，及借床敷、毡褥、奴婢、畜生、车乘、庄田，及诸珍宝金银等物，借貸不得即便驱逐。如是檀越，堕三恶趣，经历多时，受诸苦恼。善男子，未来世中，",

 "多诸官长，上中下类，如是官人不信罪福，取诸四方僧物，如是等人皆堕恶道。善男子，自今以后，不应取三宝财物，驱使三宝奴婢畜生，抑逼差科，乃至不应生一念之心，何况檛打驱使奴婢，更从索物，",

 "下至索一斗半斗。如其不与，及被嗔责，起是恶心，皆堕恶道。复次善男子，一切国王、王子、大臣、长者、居士、婆罗门等，教汝行法：若见众僧，莫问多少，勿简持戒、破戒及与大小，应生敬重，不得轻慢。若欲供养，",

 "随其力分。若能家内清净，设供备办饮食及净坐处，别有客僧入会，不禁门户，其心欢喜，若能如是普供养者，其福无量。若有俗人三业粗犷，打骂众僧，恶心系念，如是之人堕诸恶道；若能三业调柔，",

 "如法供养，即生善道。复次善男子，当尔之时，一切道俗，若有欲作大福业者，宜并齐心，为一切众生聚集施物，无碍施与一切老病贫穷悲田乞人，如是布施虽少，功德甚多。复次善男子，应修破寺、破塔、破像、破经，",

 "如前所说，得无量福。复次善男子，于未来世，我法之中，多有三宝被人轻贱，正以苾刍及苾刍尼不如法故：身披法服，经理俗务，市肆贩卖，涉路往来，或复营农、贮积粜籴，或复使人商贾求利，常行如是非法活命，",

 "或作种种工巧之业为财利故：或作画师、或作金师、或作木匠、或占候星宿、或作卜师、或占相男女种种吉凶、或作医师、或行咒術并结咒索、或自歌舞教他歌舞、或乐群聚竞夸饮兴，每常醉乱，",

 "酒酣无礼，不识尊卑，互相嘲谑；或时谄曲为他说法，以求人意；或时诊候他脉，针灸治眼；或复坐禅不能自正，以邪定法占睹吉凶；或策使鬼神说人祸福，专行此事以求衣食；或有苾刍托附俗官，",

 "为动弦管，并共棋博，或行媒媾令彼欢喜，或假他势力侵削道俗，所得财物分与俗官。如是苾刍尼等，专行如此非法之事，为衣食故以自活命，令诸俗人不生敬重，唯除菩萨利益众生及以怜愍此等人故。",

 "尔时世尊复告常施菩萨言：善男子，未来世中，一切道俗多造恶业，造佛形像及菩萨像，或时雕刻、或复彩画，将以贩卖。一切道俗为功德故，买归供养，行此事者，二俱得罪，堕于地狱，五百生中，",

 "常被他卖。何以故？为行非法买卖像故。复次善男子，未来世中，多有众生不知罪福，上祖已来，或自己身所造佛像、经书、幡花、伞盖，卖与他人，以活妻子及邪行处用。善男子，此亦不应买卖。当尔之时，",

 "一切国王、宰相、城主、县长有势力者，捉得此人，应重谪罚，驱令出国。复次善男子，未来世中，一切道俗造立形像皆不具足，即便废罢：或作半身、或手足不成，或有眼耳口鼻悉不成就，粗有影响而已，",

 "或造塔庙不安形像，或造寺宇亦不具足，彼若破坏不肯修理，如此人辈获无量罪。复次善男子，未来世中，诸恶苾刍于所住寺自共立制：若有四方客僧来住，莫令放入，令作食限，下至一日二日，",

 "设多饮食，惜不供食。善男子，是诸苾刍，命终之后堕于地狱、饿鬼、畜生。复次善男子，未来世中，苾刍、苾刍尼及以沙弥，以常住僧物如似己有，随意取用，非时食啖，或与亲友余残饮食。是诸苾刍，",

 "及以沙弥，乃至千佛出世，永不闻法，常在三途无忏悔处。若共此人同住居止、羯磨布萨、所作法事，悉不得成，复更得罪。复次善男子，若有具犯四重五逆，易救可忏；若侵损三宝乃至一毫一粟，自在取与，",

 "非时食啖，永沉苦海，终无出时；或现在世受诸病苦。若共此人同住语论、往来狎习，日夜得罪；若不忏悔，不能永舍，彼人命终之后堕于地狱。善男子，未来世中，多有苾刍及苾刍尼、邬波索迦、邬波斯迦、",

 "国王、太子、王子、大臣、官长、中宫妃后乃至家长，破戒恶行，无羞无耻、无惭无愧，不解忏悔，以是因缘令法秽浊，当知即是三恶趣人。我以方便，令彼罪人随所犯处，还从彼境殷勤忏悔，罪得除灭，",

 "而得解脱。复次善男子，未来世中，诸恶苾刍及苾刍尼，执著寺舍及所住处，如似俗人护己舍宅，不令他入，于我所说法毗奈耶藏，不能依法四月一移，恋著房舍如毗舍遮，见余苾刍住阿兰若，威仪具足，",

 "衣钵自随，于其住处四月一移，终不忘失。诸恶苾刍见是事已，而便轻笑，咸作是言：此之苾刍志性不定，𮜒扰多务，失心狂乱，如颠病人数作移动。彼恶苾刍自破戒行，见他行法而生讥诮，以是因缘，",

 "获大罪报，便堕地狱。复次善男子，未来恶时，若苾刍、苾刍尼及诸俗人，欲学大慈大悲心者，须忍受他恼、诽谤、打骂。若有人能起此心者，即是我弟子，我亦是彼师。何以故？应作是念：我过去世时，曾为一切众生父母，",

 "一切众生无始已来，亦曾与我而作父母、兄弟、姊妹、六亲眷属。善男子，以是义故，于一切众生而起慈悲愍念，自观己身秽恶危脆，不生爱著；当尔之时，不惜身命，种种方便救济一切苦厄众生。若有国主大臣、",

 "若城邑聚落主、若势力长者婆罗门等、天龙八部，宜应护持；及有苾刍，若男若女，应劝此人不令退转，助其势力，莫令恶人为作留难、不令恶人侵欺财物。如是助者，其人功德说不可尽。善男子，当尔之时若有施主，",

 "起慈悲心，布施贫穷孤老、一切受苦众生乃至蚁子，其人功德无有穷尽。善男子，吾说此布施悲田所有功德，我若广说，穷劫不尽。未来众生闻者欢喜，或复迷闷。涅槃时到，为汝略说，应如是知。说此语已，",

 "默然而住。尔时一切诸来大众，闻世尊说像法时事及像法末时，又闻涅槃时到，举体战栗，身毛皆竖，悲啼号哭不能自胜。尔时世尊起大悲心，告诸大众：止，勿悲哭。世间法尔，有生必灭，一切诸法，",

 "悉皆无常，无主无我，涅槃空寂，无有过者。更莫啼泣，以法自裁。复告常施菩萨：且置是事，汝以何相观如来耶？复以何相观众生乎？常施菩萨白佛言：世尊，我观如来，亦非过去、亦非未来、亦非现在，",

 "不住此岸、不到彼岸、不住中间，非有非无，不起不灭，非色非不色，非有为非无为，非断非常，非有漏非无漏，同虚空等法性；从初成道乃至涅槃，于其中间不见如来说一句法，非同众生见有出没、说法度人。",

 "如来境界不可思议，不可以识识、不可以智知，出过三界、不离三界，众生无能辄惟忖之，设对目前亦不能测。一切众生之相亦复如是，非有非无、非内非外、非聚非散，而常流转虚妄受苦。无始已来，",

 "执著我见，我见缚故，长夜受苦，无有穷尽。众生之性本来寂静，于未来世，一切众生亦皆空寂，有无俱空，如镜中像、如水中月、如热时炎、如健达缚城、如空中云、如梦如电、如幻如化、如响如泡。",

 "菩萨由是不舍众生四大之相，为若此也。执有我者，应如是观。世尊，一切众生（阙）皆一心作，更无余法。我观众生相貌如是，此是不可思议，唯有如来自觉之法，非诸声闻、缘觉及初地菩萨之所能量。",

 "当知如来于众生所有大悲心，应众生机，普为说法，无能过者。我今观佛及诸众生，为若此也。尔时会中无量天人闻此语已，成发无上正等觉心，及获圣果。尔时世尊告常施菩萨言：善哉善哉，善男子，",

 "汝之所说，正应如是。一切众生，于如是观；一切诸佛，亦如是观，得无上道。善男子，此经中说菩萨之法及观行法，应如是行四摄六度，应当如是观众生相。复次善男子，行布施时，不观福田及非福田，",

 "不求名闻，若见贫穷孤老一相苦相，应如是施、应如是观。不见施者、不见受者、不见施物，三事体空，平等无碍，无有住著。何以故？一切诸法无我，是真实法。所施之时，不望受报现在未来人天胜乐，",

 "为诸众生求无上道，令诸众生得无尽乐故，应如是施。为欲摄取诸恶众生令住善法而行布施，我亦如是摄诸众生而行布施。如汝先说，不应住于有无之相而行布施，如是布施最为殊胜。若有见闻随喜之者，",

 "彼人所获善巧方便及殊胜福，应如是知。复次善男子，譬如有人于夜梦中见种种事，或见自身而被系缚，受种种苦，生大忧恼，然后得脱，即便更见国人咸集，策立为王，势力自在，受大快乐。",

 "作是思惟：我先受苦，今复自在，受大快乐。作是念已，忽然睡觉，苦乐之事莫知所在。如此梦事，非有非无；一切诸法亦复如是。作是观者，名为正观。说是法已，无量菩萨证得无上正等菩提，无量菩萨",

