 "调达何殊。缘斯僻见，害于正法，忝为佛子，那不雌黄？乐求解脱、见佛闻法者，净土行门最为捷速；爱著三界、不求解脱者，随分安心以度时日。幸有智者思之察之，随所乐欲简而行之。禅师又云：念佛生净土者，",

 "著相修习，是虚妄法、非成佛因者，窃为未可。生死心中出此粗言，非顺圣教。如《大宝积经》第十七云：若有众生发菩提心，专念无量寿佛及修诸善、回向愿生，是人临终，无量寿佛与比丘众迎生彼国，",

 "得不退转，当证无上正等菩提。《大无量寿经》上卷云：一向专念无量寿佛，少多修善、奉持斋戒，乃至其人临终，无量寿佛化现其身，光明相好具如真佛，与诸大众现其人前，即随化佛往生其国，",

 "住不退转。《阿弥陀经》云：舍利弗，若有善男子、善女人闻说阿弥陀佛、执持名号，若一日、若二日、若三日、若四日、若五日、若六日、若七日，一心不乱，其人临命终时，阿弥陀佛与诸圣众现在其前。",

 "是人终时，心不颠倒，即得往生阿弥陀佛极乐国土；乃至若有人已发愿、欲生阿弥陀佛国者，是诸人等皆得不退转于阿耨多罗三藐三菩提。《观无量寿佛经》下文云：善男子、善女人，但闻佛名、二菩萨名，",

 "除无量亿劫生死之罪，何况忆念。若念佛者，当知此人是人中分陀利华，观世音菩萨、大势至菩萨为其胜友，当坐道场、生诸佛家。此等经文皆云念佛往生净土、当成正觉，如何禅师判为虚妄，",

 "非成佛因？岂不与此诸教相违？《法华经》第一〈方便品〉下偈云：我记如是人，来世成佛道，以深心念佛，修持净戒故；若人散乱心，入于塔庙中，一称南无佛，皆已成佛道。《华严经》六十二云：令安住力、念佛门，令入如来十力中故。",

 "《观佛三昧经》第一云：佛告父王，念佛之心亦复如是，以是心故，能得三种菩提之根。《观佛三昧经》第九云：释迦牟尼佛、弥勒菩萨过去于彼栴檀佛所修行念佛三昧，今乃成佛。又《观佛三昧》第十云：行念佛者，",

 "如大力士挽心王锁、断到慧彼岸。《文殊般若经》下卷云：若善男子、善女人，欲入一行三昧，应处空闲、舍诸乱意、不取相貌，系心一佛、专称名字，随佛方所、端身正向，能于一佛念念相续，即是念中能见过去、未来、现在诸佛。",

 "何以故？念一佛功德无量无边，亦与无量诸佛功德无二，不思议佛法等无差别，皆乘一如、成最正觉。如是等文，诚证非一，皆云念佛是菩提因。何忽专辄以凡情见解，违诸圣教，说为虚妄、非成佛因？",

 "一何孟浪！禅师复言：读诵大乘经典，著相虚妄、非成佛因者，此无义言甚于猛火，焚烧佛法、害人善根，众生眼目从冥入冥，长养三涂、断灭佛种。忝为种子，闻此粗言，那不痛切、彻于心髓？引经救义，",

 "挫彼邪徒、立破成败，须关典诰。所以广引圣教、示彼迷人，信若不生、诚死难救。请诸禅师侧耳细听：诸教定量皆世尊语、无虚妄说。即如《金刚般若经》云：须菩提，于意云何？若人满三千大千世界，",

 "七宝以用布施，乃至若复有人于此经中受持乃至四句偈等、为他人说，其福胜彼。何以故？须菩提，一切诸佛及诸佛阿耨多罗三藐三菩提，皆从此经出。下文又云：若有人能受持读诵、广为人说，如来悉知，",

 "是人悉见、是人皆得成就不可量、不可称、无有边、不可思议功德。如是人等，则为荷担如来阿耨多罗三藐三菩提。何以故？须菩提，若乐小法者，著我见、人见、众生见、寿者见，则于此经不能听受、为人解说。",

 "准此经文，不肯读诵、听闻解说、默然坐者，是乐小法人，著我见、人见、众生见、寿者见也。又云：复次须菩提，若善男子、善女人受持读诵此经，若为人轻贱，是人先世罪业应堕恶道，以今世人轻贱故，",

 "先世罪业则为消灭，当得阿耨多罗三藐三菩提。《涅槃经》第六云：譬如沙弥虽未具戒，即堕僧数；善男子，若有众生发心始学《涅槃经》书、持读诵，亦复如是，虽未具足位阶十住，则已堕于十住数中。或有众生，",

 "是佛弟子、或非弟子，若因恐怖、或因利养，听受具经乃至一偈，闻已不谤，当知是人则为已近阿耨多罗三藐三菩提。又云：若有能听如是经者，即不退转于阿耨多罗三藐三菩提，随其所愿悉能成就。",

 "如我今日所可宣说。又《涅槃经》说：雪山童子为求半偈，舍所爱身以餧罗刹，以此为因乃致作佛。《佛报恩经》第二云：转轮圣王为求半偈，剜身千灯，缘此胜因乃致作佛。《佛报恩经》第七云：菩萨勤求十二部经，",

 "所以者何？念佛重恩，为欲流布诸佛正法、为欲增长诸佛法故、为令世间信佛法故、为令一切无量众生悉得无上菩提故。《金光明经》第八云：是诸众生听斯经者，于未来世无量百千俱胝那庾多劫，天上人中，",

 "常受胜乐，得遇诸佛，速成阿耨多罗三藐三菩提。《金光明经》第九偈云：昔时宝积大法师，为彼善生说妙法，因彼开演经王故，东方见成不动佛；我昔闻经随喜善，所获福聚量难知，由斯福故证菩提，获得法身真妙智。《金光明经》第十云。",

 "汝等能于如是经王虔诚流布，乃至于我般涅槃后不令散灭，即是无上菩提正因。《法华经》第三云：若声闻、辟支佛及诸菩萨，信是十六菩萨所说经法、受持不毁者，是人皆当得阿耨多罗三藐三菩提、如来之慧。",

 "《法华经》第四偈云：其有欲疾得，一切种智慧，当受持是经。（佛时于一切法方便无碍，众生来生其国。三十七道品是菩萨净土，菩萨成佛时，念处、正勤、神足、根、力、觉、道众生来生其国。回向心是菩萨净土，菩萨成佛时，）",

 "得一切具足功德国土，乃至十善道是菩萨净土，菩萨成佛时，命不中夭、大富梵行、所言诚谛、常以软语、眷属不离、善和诤讼、言必饶益、不嫉不恚、正见众生来生其国。《华严经》第十三云：尔时文殊师利菩萨，",

 "问智首菩萨言：佛子，于佛法中智为上首。如来何故，或为众生赞叹布施，或赞持戒，或赞堪忍，或赞精进，或赞禅定，或赞智慧，或复赞叹慈悲喜舍，而终无有唯以一法而得出离、成阿耨多罗三藐三菩提者？",

 "时智首菩萨以颂答曰。",

 "佛子甚希有，能知众生心，如仁所问义，谛听我言说：过去未来世、现在诸导师，无有说一法而得于道者；佛知众生心、性分各不同，随其所应度，如是而说法：悭者为赞施，毁禁者赞戒，多瞋为赞忍，好懈赞精进，乱意赞禅定，愚痴赞智慧，怒害赞大悲，忧戚为赞喜，曲心赞叹舍，如是次第修，渐具诸佛法；如先立基堵，而后造宫室，施戒亦复然，菩萨众行本；譬如建城郭，为护诸人众，忍进亦如是，防护诸菩萨；譬如大力王，率土咸戴仰，定慧亦如是，菩萨所依赖；亦如转轮王，能与一切乐，四等亦如是，与诸菩萨乐。",

 "如是等经，广说诸行是成佛因，非但六度。如何禅师确执禅定成佛正因、非余度耶？然诸圣教说智胜成佛正因，余皆助缘。即如《华严经》第十三云：文殊师利问智首菩萨言，佛子，于佛法中智为上首。（何以故？）",

 "《大无量寿经》上卷偈云：布施调意，戒忍精进，如是三昧，智为上首。准此经文，智为第一。如何偏赞禅定为胜？故博学者辩才无碍，寡闻者辞理俱滞。何不摧伏人我，听所未闻、屈节于师，咨量未悟？贡高我慢、不肯禀承，",

 "空腹高心、发言违教，于人无耻、邪不愧佛。然诸禅师不顾圣教，胸臆自断、不可依信。禅师复言：造像有为功德、非成佛因者，此亦非理，违圣教量。佛有诚言备在诸经，殷勤称赞造像功德，灭过现殃，",

 "来成正觉。如何卒暴违佛言教，不许为因证菩提耶？问曰：若能为因感菩提果，凭何典诰而得知耶？答曰：诸经总说，略引二部证成此义。即如《造像经》上卷云：若复有人，能于我法未灭尽来造佛像者，",

 "于弥勒初会皆得解脱。若有众生非但为己而求出离、为欲得无上菩提造佛像者，当知此则为三十二相之因，能令其人速致作佛。《造像经》下卷复云：尔时弥勒菩萨摩诃萨白佛言：世尊，如佛所说，于佛法中，",

 "犯波罗夷不名为生。或复有人作斯罪已，发心忆念诸佛功德而造佛像，于佛法中得再生否？又于今生第二、第三、第四生中获证法否？佛告弥勒菩萨言：弥勒，譬如有人身被五缚，若得解脱，如鸟出网，",

 "至无碍处。此人亦尔，若发信心、念佛功德而造佛像，一切业障皆得消除，于生死中速出无碍。弥勒，当知乘有三种，所谓声闻乘、独觉乘及以佛乘；此人随于何乘而起愿乐，即于此乘而得解脱。",

 "若但为成佛、不求余报，虽有业障而得速灭，虽在生死而无苦难，乃至当证无上菩提、获清净土、具诸相好，所得寿命常住无尽。下文又云：善男子，假使如前微尘等数舍利弗等所有智慧，不及如来一念之智。",

 "何以故？如来于念念中，常能出现过前尘数三昧、解脱、陀罗尼等种种无量胜功德故。诸佛功德，一切声闻、辟支佛于其名字亦不能知。是故若有清信之心造佛形像，一切业障莫不除灭，所获功德无量无边，",

 "乃至当成阿耨多罗三藐三菩提，永拔众生一切苦恼。《法华经》第一〈方便品〉下偈云：若人为佛故，建立诸形像，刻雕成众相，皆已成佛道；或以七宝成，鍮石赤白铜、白镴及铅锡、铁木及与泥，或以胶漆布，严饰作佛像，如是诸人等，皆已成佛道；彩画作佛像，百福庄严相，自作若使人，皆已成佛道；乃至童子戏，若草木及笔，或以指爪甲，而画作佛像，如是诸人等，渐渐积功德，具足大悲心，皆已成佛道。",

 "若欲具引诸经，恐烦纸墨。依斯两教，足明优劣。故知信心造像功德无涯，克证菩提、断除诸难，依经敬造、必至涅槃；若取谬言，婴缠生死，比未闻教，轻佛重人。今见经文，那不回向？禅师复言：",

 "书写经律著相虚妄、非成佛因者，此语非善，违害圣教，欲陷众生堕邪见网。必其书写有损无益者，何故世尊苦劝众生剥皮折骨令写经律？《菩萨戒》云：若佛子，常应一心受持读诵大乘经律，剥皮为纸，",

 "刺血为墨、以髓为水、折骨为笔，书写佛戒；树皮、谷纸、绢素、竹帛，亦悉书持；常以七宝、无价香华、一切杂宝为箱，盛经律卷。若不如法供养者，犯轻垢罪。下文又云：若佛子，皆以信心受戒者，若国王、王子、",

 "百官、四部弟子，自恃高贵、破灭佛法，戒律明作，制法制我四部弟子，不听出家行道，亦复不听造立形像、佛塔、经律；立统制众、安籍记僧，比丘、菩萨地立、白衣高座，广行非法如兵奴之法——而菩萨正应受一切人供养，",

 "而反为官走使，非法非律。若国王、百官好心受佛戒者，莫作是破三宝之罪；而作破法者，犯轻垢罪。准此两节戒文：若不剥皮刺血书写经律，犯轻垢罪；制不令书，亦犯轻垢罪。故知信心书写，当祈解脱，",

 "与作碍缘，必招来苦。《法华经》第四〈法师品〉云：若善男子、善女人，于《法华经》乃至一句，受持、读诵、解说、书写，种种供养经卷——华香、缨络、末香、涂香、烧香、缯盖、幢幡、衣服、伎乐，合掌恭敬，是人一切世间应所瞻奉，",

 "应以如来供养而供养之。当知此人，（阙）相既不殊，还同虚妄。由此理故，为证菩提所修诸行，虽皆取相而非虚妄，必能为因证涅槃故，不同妄情计度分别、我我所执、颠倒虚妄。问曰：修菩萨行，",

 "虽皆取相、必能为因而非妄者，何故《金刚般若》《楞伽》等经云「凡所有相皆是虚妄」？今言有相非虚妄者，与此圣教岂不相违？答曰：诸圣教中说虚妄者，有其四义：第一理事相对说虚妄，第二生死离系因果相对说虚妄，",

 "第三凡圣相对说虚妄，第四有无相对说虚妄。第一理事相对说虚妄者，理真事妄。何以故？理即圆成实性，无为法故、凝然常故、无去来故、无增减故、无生灭故、体坚实故、无变易故；事即依他起性，有为法故，",

 "缘生法故、有增减故、有生灭故、如坏幻故、有变易故。所以将事望理，理真事妄，此即有体虚妄，非如兔角。第二生死离系因果相对说虚妄者，离系因果真、生死因果妄。何以故？因真故果真，因妄故果妄，",

 "因果相感法尔如是。生死果妄、离系果真。何以故？生死果报轮回不定、得失无恒；离系之果得而不失、证而无退。无恒故妄，无退故真。所以因随于果，真妄必同；果从于因，理齐虚实。若将生死，",

 "望于离系，生死因果虽有体而虚妄，离系因果绝（阙）锁而故实。离系果者，即菩提涅槃，更无别物；果唯无漏，因通有漏。菩萨有二：顿、渐别故——顿悟菩萨地前有漏，渐通无漏，七地已前通漏无漏，八地已去无漏相续。",

 "第三凡圣相对说虚妄者，凡妄圣真。何以故？凡夫颠倒，不能了知常与无常、生死涅槃、青黄赤白、男女等法本无名字、随世假立，迷情计实、寻名执著、强生分别，境分违顺便有憎爱，二心而起无量烦恼，",

 "随二心生、无明厚重，不了假名、依之执实、造生死业。菩萨不尔，远离颠倒，了达一切常与无常、生死涅槃、青黄赤白、男女等法本来无名；欲起言说、呼召诸法，随顺世俗假立名字，了知名法，",

 "互不相属。何以故？一切诸法离于言论、说不及故，但为遮诠假立名目，令知彼此而无杂乱。炽然说法度脱众生，广立名目、开张善恶，指有涅槃、令厌生死，劝遣精进、断恶修善；知立假名、表诠诸法，",

 "依名取解而无封执。封执既无，憎爱不生；烦恼不有，烦恼既亡，虚妄心断；虚妄心息，名之为圣。所以将凡望圣，凡见虚妄，非圣所解；同凡所见，亦虚妄也。经言：虚妄但约妄心，以心妄见、不称境知，",

 "说彼妄见、名为虚妄；不可令彼一切诸法随妄见心总皆虚妄。若言诸法定随妄心虚妄无者，妄心疑杌为人鬼，杌非虚妄，彼既不尔、此云何然？故知不可以心妄故令境皆妄。第四有无相对说虚妄者，无妄有真，",

 "何以故？无即遍计所执性，有即依他起性。然依他起法缘生幻有，法从缘生、缘从法有，缘法和合可有形段、可有作用，而知有物。即如遍计所执之我，空无有物，依彼五蕴迷情妄执、计有实我异于五蕴，",

