 "德行阶劫故也，亦云修行时节入伽罗陀位。无相行受持一切法者，还成上常以无相忍中也。就第四地中，明二句经文：从初至「灭三界一切见」，明对治方便行；二、从「亦以七阿僧祇劫」至「常不离心」，明成就行德。",

 "复次尔炎圣觉达菩萨者，此四地大士顺忍下品，不施持戒多闻转增、威德炽盛，名为炎地。逆五见流者，四地大士修道品等观，不存能解能入，诸见不起，故云逆五见流。集无量功德者，（阙）道品行戒定慧备成无缺，",

 "故云集无量功德。住须陀洹位者，经云秦言观明炎地。常以天眼乃至身通观者，五通义如前释。灭三界一切见者，结上逆五见流。亦以七阿僧祇劫者，结上集无量功德行。五神通乃至常不离心，结上五通。就五弟地中，",

 "有二句经文：从初至「即入斯陀含位」，明对治方便行；二、从「复集行八阿僧祇劫」至「不去心」，明成熟行德。复次缘达菩萨于顺道忍者，五地大士顺忍中品功德力盛，一切诸魔不能沮坏，故名难缘地。以四无畏者，",

 "用无畏智观境，故云以四无畏智观、解那由他谛。内论者，经云一者显示正因果、二者显示所作不坏、不作不来，故云内论。外道论者亦有二种：一者能屈他论、二者自申己义，故云外道论。药方论者，有四种：",

 "一者显示善知病、二者显示病因、三者显示能除已起之病、四者显示已除之病令不重起，故云药方论。工巧论者，显示种种世业，如金铁师、木师等，及余种种明处，故云巧论。咒术论者，显示巧便言辞，",

 "故言咒术。我是一切智人者，如是菩萨求五明处，为无上菩提、大智众具究竟满，故名为一切智人。释一切智无畏、灭三界痴等烦恼。我相已尽者，释漏尽无畏智。地地中有所出，故名出道者，名无漏出要道也。",

 "释尽告道无畏。有所不出，故名障道者，名烦恼障也，释障道无畏。逆三界疑者，欲明五地菩萨烦恼微薄也。修集无量功德者，相微行备、能度障难，早入难胜地，故云集无量功德、入斯陀含位。复行八阿僧祇劫中，据行阶劫也。",

 "行诸陀罗尼门者，用总持行也。常行无畏观、不去心者，结成上四无畏观，已化物（阙）。就第六地中有二句经文：从初至「一相无相而无二」，明对治方便行；二、从「证阿那含」至「一切佛国土」，明成熟行德。复次常现真实、住顺忍中者，",

 "明六地大士证顺忍上品，故云住顺忍中。现前地者，《毗婆沙》云：障魔事，以菩萨道法皆现在前，故云名现前地。作中道观者，法界因缘、寂灭无二，故云作中道观。尽三界集因、集业一切烦恼者，因缘集故谓之有，",

 "非曰有是有；因缘散故谓之无，非曰有是无，无有无无故，云尽三界集因、集业一切烦恼。故观非有非无，一相无相而不二者，非有有、非无无，故云非有非无；亦无一相、无异相，故云一相无相而无二。",

 "证阿那含位者，秦言薄流现前地也。复以九阿僧祇劫集照明中道者，行之阶劫，作十种照十二因缘观，故云复以九阿僧祇劫集照明中道故。乐力生一切佛国土者，现无现量身、入诸佛土、教化众生，故言乐力生一切佛国土故。",

 "复次玄达菩萨者，《毗婆沙》云：去三界远、近法王位，故云玄达菩萨。十阿僧祇劫中者，修道时劫，亦可行之阶劫也。修无生法乐忍者，证无生忍下品故也。灭三界习因业果者，无碍智观三界二习色身果报，尽无遗余，",

 "故云灭三界习因业果，故住最后身。功用究竟，此身最终，故云住后身中。无量功行皆成就者，明此菩萨与无功用作其因行，众德圆备，故云无量功行皆成就。尽智、无生智、五分法身皆满足者，功中用极也。住第十地者，",

 "前三后七，故云十地。罗汉者，秦言过三界远行地也。常行三空门者，无有十相名为无相，于二十五有不作愿求故云无愿，无二十五有故曰空也；门者，体通无碍，名之为门。百千万亿三昧具足者，功德聚林、调直定心，",

 "皆悉备满也。弘化法藏者，功用已竟、无相无为，以真法藏化利无穷，故言弘化法藏。复次等觉者，三道中无学之如，故云等觉。住无生忍中者，住无生忍中品也。心心寂灭者，解脱相也；而无相者，体寂灭也。",

 "无身身者，法身相也；无知知者，般若相也。而用心乘于群方之方者，圣智无智、万品俱照，释上无知知。淡泊住于无住之住者，法身无像、殊形并应，释上无身身。在有常修空、处空常万化者，冥拥无谬、动与事会，",

 "释上无相相；双照一切法者，圣心平等、照无二也。知是处非处，乃至十力观者，十力义如前释。而能住摩诃罗伽位者，秦云变化生不动地。化一切国土众生者，以无功用心，如一切众生形，故云化一切国土众生。",

 "千阿僧祇劫行十力法者，行之阶劫也。心心相应、常入见佛三昧者，运运寂灭，自然流入萨婆若海，故云心心相应常入见佛三昧。复次惠光神变者，明九地菩萨其惠转明、调柔增上，故云惠光神变。住上上无生忍者，",

 "是无生忍上品也。灭心心相者，心习已尽、无明亦除，故言灭心心相。法眼见一切法者，无法不见也。三眼者，总举三眼：色者明无明、见障外色也；空者惠眼鉴也；见者肉眼障内也。以大愿力者，佛藏变通藏，",

 "以一心中一时行，故言以大愿力。常生一切净土者，明严土化物也。万阿僧祇劫集无量佛光三昧者，明行之阶劫也。而能现百万乃至诸佛神力者，无量大千世界中作佛形也。住婆伽梵位者，秦言惠光妙善地。",

 "亦常入佛华三昧者，结上三昧乃至诸佛神力也。就十地中有三句经文：从初至「而未能等无等」者，明法说；二、从「譬如有人」至「无不斯了」，明设喻；三、从「住理尽三昧」至「佛惠三昧」，明合喻。就法说中，有六子句经文：",

 "从初至「金刚台」，明行相阶劫、证后学心；二、从「善男子」至「不名为见」，明照理未周；三、从「所谓见者」至「所知见觉」，明佛见理周尽；四、从「顶三昧」至「不见不觉」，释上第二见理未周；五、从「唯佛顿解不名为信」，释成第三见理周尽；",

 "第六、从「渐渐伏」至「无等等」，释成初句行之阶劫。复次观佛菩萨住寂灭忍者，明佛及菩萨同用此忍也。从习忍至顶三昧者，明三贤十圣也。皆名为伏一切烦恼者，明三贤菩萨伏而非断；从初地至十地，亦伏亦断。",

 "唯佛顿断也。而无想信者，是征名轻毛人也。灭一切烦恼无碍道也，生解脱智也者，解脱道也。照第一义谛者，举其境界；不名为见者，见理未周故不名为见。所谓见者是萨婆若者，明种智圆备、见理周尽。",

 "是故我从昔来常说唯佛所知见觉者，结上萨婆若也。惠离起灭者，明缘知也；以能无生灭者，真证智也。此心若灭者，除烦恼障累；无不灭者，除智障也。入理尽金刚三昧、同真际、等法性者，行体固坚、一相无相也。",

 "而未能等无等等者，未能全同佛也。「善男子如是诸菩萨」者，总举，始从习种终至法云菩萨，非一也。皆能一切十方诸如来国土中教化众生者，明十三法师皆能随力随分教化众生。正说者，教道清净也；正义者，证道清净。",

 "受持读诵者，摄法修相，亦清净解达。实相者，向明四行理用相应也，结其实用，故云等无有异。就外护行中，有六句经文：一、从「佛告波斯匿王」至「解其义理」，明以大法总付诸王，不委凡庶；二、「大王吾今所化」",

 "至「七难也」，明劝诸王弘通大法、光扬三法，能除七难、获得七福德；三、从「大王」至「事帝释」，明经理深重，说供养法用，劝王受持；四、从「天王吾今五眼」至「七难火起」，明国王弘经咸得贤圣镇国、七难不起；五、从「大王若未来世」",

 "至「而供养之」，明佛使五大菩萨护其国土，劝立形像而供养之；六、明三宝可遵，应别付嘱十六国王。「佛告波斯匿王：我当灭度后、法灭尽时」者，明其时（阙）事须（阙）护也。「受持乃至皆由此般若波罗蜜」者，明其利益功能。",

 "「大作佛事」者，寂而常用故，言大作佛事。「是故付嘱诸国王」乃至「故不付嘱」者，明道托时兴、非威不举，宜凭外护，故付诸王、不付四部众也。「汝当持读诵解其义理」者，正劝诸王受持解说，故言受持读诵、解其义理。",

 "就第二句中，有二子句经文：从初至「帝王欢喜」，略总举灭除诸难，以劝于时；二、从「云何为难」至「为七难也」，广明七难，表以事劝。七难中前二，天道失度，表现于上；次四，地义殊易，事变于下；后之一难，",

 "人情暴乱，伤害于世，特宜受持以消不祥。日月失度者，君臣不和、迭相障闭，君无正化之力、臣无传正之能，是以应勤讲说此经，为一难也。二十八宿失度，乃至各各变现、四方诸集，所以暴乱者，良由正教不行于四方也。",

 "「大火烧国」已下，明民之失行，同感此难，不得遍在君臣。南方主礼，礼以防性，性逸过度，火难起也。北方主智，智能判疑，饮酒过度，水难起也。东方主仁，仁以养生，杀害过度，风难起也。中央是土，",

 "土主于信，妄语过度，木石燋然、五谷不登，地难起也。西方是金，金主于义，取与不节，是以贼难起也。此五其致浩博，且略举其要，以对七难。是明七要，欲令兴护之者识达违顺，中若不实，外绝滋茂。",

 "是以就般若以彰七要。第三句中有二子句经文：一、从「大王」至「亦名龙宝神王」，明难般若利益功能；二、从「告大王」至「如事帝释」，正明所修行法。菩萨为一切众生心识之神本。七要者，初一明本实，下七就实彰行。",

 "就七中，前四自利行，后三利他行。「一切国王之父母」者，明方便妙惠，故云父母；「亦名神符」者，明二智与教道相称；「亦名壁鬼珠」者，明对治行也；「如意珠」者，欲明由对治故显实证；「护国珠」者，摄伏行也；「天地镜」者，",

 "示果过行也；「龙实宝神王」，利润成就行也。「幡等皆云九」者，彰其因行也。「七宝案以经置上」者，明七方便行必依教也。「若王时行、常放其前」者，明依教修行，前句辨法用、此明真修。如此（阙）异足一百步、是经常放千光明者，",

 "略举十地，一地有百，故云放千光明。令千里内七难不起、罪过不生者，明对治行也。「若王住时作七宝帐」者，行成处彰、住随分行、圆阴已之能，故曰帐也。「七宝高坐」者，与法空相应，名为坐。余句类而可知。如事父母、",

 "如事帝释者，一供养行也。「大王，我五眼明见三世，乃至得为帝王主」者，明佛五眼鉴达因果、善恶达顺，应侍（阙）世，方堪制御纲领、摄伏天下，特劝护持如经。「得为帝王主，故是為一切圣人」乃至「作大利益」者，明诸仁王等。",

 "若修至德之行、感圣在于国土、利润世间，如经作大利故。「若王福尽时」乃至「七难必起」者，明诸国王行行求世礼、纵情放逸、不顺圣法，故灾难必起也。「大王，若未来世」乃至「而供养之」者，明诸王等若能专心拥护三宝，",

 "佛之威神令五忍菩萨演化护国，得大利益，如经受持三宝者，我使五大菩萨往护其国。故「大王，吾今三宝付嘱汝等」乃至「受持般若波罗蜜」者，明如来应别付嘱十六国王，观令受持流通行化。就第三分中，有六子句经文：",

 "一、明大众阿须轮王厌世多难，愿不受生；二、明十六国王弃国重位，遵修妙行；三、明十八梵天修三乘同观、入定发通、散花供养；四、明其余诸众既登圣果，深入禅定，用神通花供养于佛；五、明十千菩萨兴大悲心，",

 "救济三世苦恼众生，愿令同证无边三昧；六、明复有十亿菩萨行登穷学、证真法性、成正觉果。大众闻佛说七可畏，身毛为竖者，明对治交竞。愿不生彼国者，行愿既立、舍本所居，是以国事付弟出家者，",

 "后资于前，故名付弟，是利他义也。更修缘进、日出家修道，四大四色缘出相者，八胜处观，观心彰胜，故云出相四大四色。不用识空者，十一切入也。世忍初地相者，伏忍五忍之初，故言初地相。第一义谛九地相者，",

 "六地明般若波罗蜜为第一义；九地相者，前三是坚忍，从欢喜地至现前，故言九地相也。舍凡夫身者，舍忍伏，故言舍凡夫身。入六地身者，七地身，是三界功用相心之身，七地终心，故须舍之，如经舍七报身。",

 "入八法身：八地至十地，八地九地皆有上中下寂灭忍上下，故言入八法身。有解入八法身者，八地以上清净菩提、无功用行，真无学道，故云入八法身。证一切行者，释上入义；般若波罗蜜者，显究竟道是真证法。",

 "十八梵天、阿须轮王得三乘观、同无生境者，明三乘同观空无生理也，如经得三乘观同无生境。复散花供养者，色界诸梵等入深妙定，发神通花供养也。初供养者，总列，革下九种花，从入定以彰花名。入空处",

 "定通发智，以不思议花供养于佛。下八种花名，皆因定发通、现不思议行义，故言三十七品花而散佛上。又解：空花乃至三十七品花者，尽是伏忍中九行，习性、道种，一中有三为九。及九百亿大菩萨众者，总举十地。",

 "言九言亿者，彰因义未足。其余一切证道迹果者，六地已还，皆是方便行未具足故，云道迹。心空花者，七地行心；树下八地行；下二花九地十地而散佛者，因趣果也。及一切众者，行无不集。十千菩萨者，据位彰十，",

 "据行彰千。念来世众生证觉者，缘进成就，从妙觉三昧至一切行三昧，皆是十地以还讫伏忍，摄是因行，故与三昧之称。复有十亿现成正觉者，始彰果德。释秀许。",

 "就此品中，有五分经文：从初至「化一切众生」，说流通利益分；二、从「后五浊恶世」至「将灭不久」，明灭法之相；三、从「大王怪乱五道」至「正法不久」，举七诫观修，令识患舍离分；四、从「十六国王」至「当如佛教」，明诸国王奉受持分；五、从「尔时大众」竟经，明时大众普持正法分。",

 "「佛告波斯匿王：我诫敕汝」者，明如来诫敕月光王弘护三宝也。「吾灭度后八十年」者，正法之中四百二十年、后八十年也。「八百年」者，像法之中有一千年，后二百年有法灭之相也。「八千年」者，千五百后亦有遗文，",

 "在外道典籍中，犹有利益也。「无三宝信男信女」者，是千五百年后也。「付嘱国王四部弟子」者，事在正像法中也。教能显理，名开空法道。又解：开空法道者，性照圆旨、法无不通，故言开空法道。修七贤行者，",

 "习种前七方便是行善故，言修七方便；十善行者，是集善根，众生是正善故，言行十善。「后五浊恶世」已下，明法灭之相。五浊世者：一劫浊、二烦恼浊、三见浊、四命浊、五众生浊。七众八部详共作制者，",

 "正是法灭之相也。有七恶事：一不听出家行道、二不得造立佛像塔形、三立统官制众、四安籍记僧、五比丘地立白衣高坐、六放兵奴为比丘、七受别请法。问曰：佛在世时亦有兵奴出家，何故后世放兵奴出家，",

