 "「世尊！我今因佛力故，得见无量寿佛及二位菩萨，未来众生，当怎样观无量寿佛及二位菩萨？」佛告韦提希：「欲观彼佛者，当起想念，于七宝地上作莲花想，令其莲花一一叶作百宝色。有八万四千脉，犹如天画；",
 "一一脉有八万四千光，了了分明，皆令得见。花叶小的，纵横二百五十由旬；这样莲花有八万四千大叶，一一叶间，有百亿摩尼珠王以为映饰。一一摩尼珠放千光明，其光如盖，七宝合成，遍覆地上。释迦毗楞伽摩尼宝以为其台；",
 "这莲花台，以八万金刚甄叔迦宝、梵摩尼宝、妙真珠网，以为交饰。于其台上，自然而有四柱宝幢，一一宝幢如百千万亿须弥山；幢上宝缦如夜摩天宫，又有五百亿微妙宝珠以为映饰。一一宝珠有八万四千光，一一光作八万四千异种金色，一一金色遍其宝土，处处变化，各作异相；",
 "或为金刚台，或作真珠网，或作杂花云，于十方随意变现，施作佛事，这就是花座想，名第七观。」佛告阿难：「如此妙花，是本师法藏比丘愿力所成，若欲念彼佛者，当先作此妙花座想。作此想时不得杂观；",
 "都应一一观之，一一叶，一一珠，一一光，一一台，一一幢，皆令分明，如于镜中自见面像。此想成者，灭除五百亿劫生死之罪，必定当生极乐世界。作此观者，名为正观。若是他观，名为邪观。」佛告阿难及韦提希：",
 "「见此事已，次当想佛。为什么呢？诸佛如来是法界身，遍入一切众生心想中；所以你们心想佛时，此心即是三十二相、八十随形好。是心作佛，是心是佛。诸佛正遍知海，从心想生，所以应当一心系念，谛观彼佛、多陀阿伽度、阿罗呵、三藐三佛陀。",
 "想彼佛者，先当想像。闭目开目，见一宝像，如阎浮檀金色，坐彼华上。像既坐已，心眼得开，了了分明，见极乐国七宝庄严，宝地、宝池、宝树行列，诸天宝缦弥覆树上，众宝罗网满虚空中。见如此事，极令明了，如观掌中之物。",
 "见此事已，又当更作一大莲华在佛左边，如前莲华等无有异。又作一大莲华在佛右边，想一观世音菩萨像坐左华座，也放金光如前无异。想一大势至菩萨像坐右华座。此想成时，佛菩萨像皆放妙光；其光金色，照诸宝树。",
 "一一树下也有三莲华，诸莲华上各有一佛二菩萨像，遍满彼国。此想成时，行者当闻水流、光明及诸宝树、凫雁、鸳鸯皆说妙法。出定、入定恒闻妙法。行者所闻，出定之时忆持不舍，令与修多罗（经）相合。若不合者，名为妄想，若与经合者，名为粗想见极乐世界。",
 "这就是想像，名第八观。作此观者，除无量亿劫生死之罪，于现身中得念佛三昧。作此观者，名为正观。若是他观，名为邪观。」佛告阿难及韦提希：「此想成已，次当更观无量寿佛身相光明。阿难当知！无量寿佛身，如百千万亿夜摩天阎浮檀金色。",
 "佛身高六十万亿那由他恒河沙由旬；眉间白毫右旋宛转，如五须弥山。佛眼清净如四大海水，清白分明。身诸毛孔演出光明，如须弥山。彼佛圆光如百亿三千大千世界；于圆光中，有百万亿那由他恒河沙化佛；",
 "一一化佛，也有众多无数化菩萨以为侍者。无量寿佛有八万四千相；一一相中，各有八万四千随形好；一一好中又有八万四千光明；一一光明遍照十方世界，念佛众生摄取不舍。其光相好及与化佛，不可具说；",
 "但当忆想令心明见。见此事者，即见十方一切诸佛，以见诸佛故名念佛三昧。作此观者，名观一切佛身，以观佛身故也见佛心。诸佛心者大慈悲是，以无缘慈摄诸众生。作此观者，舍身他世，生诸佛前，得无生忍。",
 "所以智者应当系心谛观无量寿佛。观无量寿佛者，从一相好入，但观眉间白毫，极令明了。见眉间白毫相者，八万四千相好自然当见。见无量寿佛者，即见十方无量诸佛；得见无量诸佛故，诸佛现前授记。",
 "这就是遍观一切色想，名第九观。作此观者，名为正观。若是他观，名为邪观。」佛告阿难及韦提希：「见无量寿佛了了分明已，次也应当观观世音菩萨。此菩萨身长八十亿那由他恒河沙由旬，身紫金色，顶有肉髻，项有圆光，圆光各面百千由旬。",
 "其圆光中有五百化佛，如释迦牟尼。一一化佛，有五百菩萨，无量诸天，以为侍者。举身光中五道众生，一切色相都在其中显现。顶上毗楞伽摩尼妙宝，以为天冠。其天冠中有一立化佛，高二十五由旬。观世音菩萨面如阎浮檀金色；",
 "眉间毫相备七宝色，流出八万四千种光明；一一光明，有无量无数百千化佛；一一化佛，无数化菩萨以为侍者，变现自在满十方界。臂如红莲花色，有八十亿微妙光明，以为璎珞；其璎珞中，普现一切诸庄严事。",
 "手掌作五百亿杂莲华色；手十指端，一一指端有八万四千画，犹如印文。一一画有八万四千色；一一色有八万四千光，其光柔软普照一切，以此宝手接引众生。举足时，足下有千辐轮相，自然化成五百亿光明台。",
 "下足时，有金刚摩尼花，布散一切莫不弥满。其余身相，众好具足，如佛无异，唯有顶上肉髻及无见顶相，不及世尊。这就是观观世音菩萨真实色身相，名第十观。」",
 "佛告阿难：「若欲观观世音菩萨当作此观。作此观者不遇诸祸，净除业障，除无数劫生死之罪。如此菩萨，但闻其名，获无量福，何况谛观！若有欲观观世音菩萨者，当先观顶上肉髻，次观天冠。其余众相也次第观之，悉令明了，如观掌中。作此观者，名为正观。",
 "若是他观，名为邪观。」佛告阿难及韦提希：「次观大势至菩萨。此菩萨身量大小也如观世音，圆光各面二百二十五由旬，照二百五十由旬。举身光明照十方国，作紫金色。有缘众生皆悉得见。但见此菩萨一毛孔光，即见十方无量诸佛净妙光明，所以号此菩萨名无边光。",
 "以智慧光普照一切，令离三涂，得无上力，所以号此菩萨名大势至。此菩萨天冠有五百宝莲华；一一宝华有五百宝台。一一台中，十方诸佛净妙国土广长之相，都在其中显现。顶上肉髻如钵头摩花。于肉髻上有一宝瓶，盛诸光明，普现佛事。",
 "其余诸身相如观世音，等无有异。此菩萨行时，十方世界一切震动，当地动处各有五百亿宝花。一一宝花庄严高显，如极乐世界。此菩萨坐时，七宝国土一时动摇。从下方金光佛刹，乃至上方光明王佛刹，于其中间无量尘数分身无量寿佛，分身观世音、大势至，皆悉云集极乐国土，侧塞空中坐莲华座，演说妙法，度苦众生。",
 "作此观者，名为观见大势至菩萨；这就是观大势至色身相。观此菩萨者名第十一观，除无数劫阿僧祇生死之罪；作是观者不处胞胎，常游诸佛净妙国土。此观成已，名为具足观观世音及大势至。作此观者，名为正观。",
 "若是他观，名为邪观。」佛告阿难及韦提希：「见此事时当起想作心，自见生于西方极乐世界，于莲华中结跏趺坐，作莲华合想，作莲华开想。莲华开时，有五百色光来照身想；眼目开想，见佛菩萨满虚空中，水、鸟、树林及与诸佛，所出音声，皆演妙法，与十二部经合。",
 "若出定时忆持不失。见此事已，名见无量寿佛极乐世界。这就是普观想，名第十二观。无量寿佛化身无数，与观世音及大势至，常来至此行人之所。作此观者，名为正观。若是他观，名为邪观。」佛告阿难及韦提希：",
 "「若欲至心生西方者，先当观于一丈六像在池水上。如先前所说，无量寿佛身量无边，不是凡夫心力所及。然而彼如来宿愿力故，有忆想者必得成就。但想佛像得无量福，何况观佛具足身相！阿弥陀佛神通如意，于十方国变现自在。",
 "或现大身满虚空中；或现小身丈六八尺。所现之形皆真金色，圆光化佛及宝莲花，如上所说。观世音菩萨及大势至，于一切处身同众生，但观首相，知是观世音，知是大势至，这二位菩萨助阿弥陀佛，普化一切。",
 "这就是杂想观，名第十三观。作此观者，名为正观。若是他观，名为邪观。」佛告阿难及韦提希：「凡生西方有九品人。上品上生者，若有众生愿生彼国者，发三种心，即便往生。哪三种？一者、至诚心。",
 "二者、深心。三者、回向发愿心。具三心者必生彼国。又有三种众生，当得往生。哪三种？一者、慈心不杀，具诸戒行。二者、读诵大乘方等经典。三者、修行六念，回向发愿生彼佛国。具此功德，一日乃至七日，即得往生。",
 "生彼国时，此人因精进勇猛故，阿弥陀如来与观世音及大势至，无数化佛，百千比丘，声闻大众，无量诸天，七宝宫殿，观世音菩萨执金刚台，与大势至菩萨到行者前。阿弥陀佛放大光明，照行者身，与诸菩萨授手迎接。",
 "观世音、大势至与无数菩萨，赞叹行者，劝进其心。行者见已，欢喜踊跃。自见其身乘金刚台，随从佛后，如弹指顷，往生彼国。生彼国已，见佛色身众相具足，见诸菩萨色相具足。光明宝林，演说妙法。",
 "闻已即悟无生法忍。经须臾间历事诸佛，遍十方界，于诸佛前次第受记。还至本国，得无量百千陀罗尼门，这就是上品上生者。「上品中生者，不必受持读诵方等经典。善解义趣，于第一义心不惊动，深信因果，不谤大乘；",
 "以此功德，回向愿求生极乐国。行此行者命欲终时，阿弥陀佛与观世音及大势至，无量大众，眷属围绕，持紫金台到行者前，赞言：『法子！你行大乘，解第一义，所以我今来迎接你。』与千化佛一时授手。",
 "行者自见坐紫金台，合掌叉手，赞叹诸佛，如一念顷，即生彼国七宝池中。此紫金台如大宝花，经宿即开。行者身作紫磨金色，足下也有七宝莲华。佛及菩萨俱放光明，照行者身，眼即开明。因先前宿习，普闻众声，纯说甚深第一义谛。",
 "即下金台，礼佛合掌赞叹世尊。经于七日，应时即于阿耨多罗三藐三菩提，得不退转。应时即能飞至十方，历事诸佛，于诸佛所修诸三昧。经一小劫得无生法忍，现前受记，这就是上品中生者。「上品下生者，也信因果，不谤大乘，但发无上道心，以此功德，回向愿求生极乐国。",
 "那行者命欲终时，阿弥陀佛及观世音并大势至，与诸眷属持金莲华，化作五百化佛，来迎此人。五百化佛一时授手，赞言：『法子！你今清净，发无上道心，我来迎你。』见此事时，即自见身坐金莲花。坐已花合，随世尊后，即得往生七宝池中。",
 "一日一夜莲花乃开，七日之中乃得见佛。虽见佛身，于众相好心不明了，于三七日后乃了了见。闻众音声，皆演妙法。游历十方，供养诸佛。于诸佛前闻甚深法，经三小劫得百法明门，住欢喜地。这就是上品下生者。",
 "这就是上辈生想，名第十四观。作此观者，名为正观。若是他观，名为邪观。」佛告阿难及韦提希：「中品上生者，若有众生受持五戒，持八戒斋，修行诸戒，不造五逆，无众过恶；以此善根，回向愿求生於西方极乐世界。",
 "行者临命终时，阿弥陀佛与诸比丘，眷属围绕，放金色光到其人所，演说苦、空、无常、无我，赞叹出家得离众苦。行者见已，心大欢喜。自见己身坐莲花台，长跪合掌为佛作礼。未举头顷即得往生极乐世界，莲花寻开。",
 "当华敷时，闻众音声赞叹四谛，应时即得阿罗汉道，三明、六通、具八解脱；这就是中品上生者。「中品中生者，若有众生，若一日一夜持八戒斋，若一日一夜持沙弥戒，若一日一夜持具足戒，威仪无缺。以此功德，回向愿求生极乐国。",
 "戒香薰修，如此行者命欲终时，见阿弥陀佛与诸眷属放金色光，持七宝莲花到行者前，行者自闻空中有声，赞言：『善男子！如你善人，随顺三世诸佛教故，我来迎你。』行者自见坐莲花上，莲花即合，生于西方极乐世界。",
 "在宝池中，经于七日莲花乃敷。花既敷已，开目合掌，赞叹世尊。闻法欢喜，得须陀洹，经半劫已成阿罗汉；这就是中品中生者。「中品下生者，若有善男子、善女人，孝养父母，行世仁义，此人命欲终时，遇善知识为其广说阿弥陀佛国土乐事，也说此藏比丘四十八大愿。",
 "闻此事已，随即命终。譬如壮士屈伸臂顷，即生西方极乐世界。生经七日，遇观世音及大势至，闻法欢喜得须陀洹。过一小劫，成阿罗汉。这就是中品下生者。这就是中辈生想，名第十五观。作此观者，名为正观。",
 "若是他观，名为邪观。」佛告阿难及韦提希：「下品上生者，或有众生作众恶业，虽不诽谤方等经典，如此愚人，多造恶法，无有惭愧，命欲终时遇善知识，为赞大乘十二部经首题名字。以闻如此诸经名故，除却千劫极重恶业。",
 "智者又教合掌叉手，称南无阿弥陀佛。称佛名故，除五十亿劫生死之罪。那时彼佛，即遣化佛、化观世音、化大势至，到行者前，赞言：『善哉！善男子！你称佛名故诸罪消灭，我来迎你。』说完这话，行者即见化佛光明，遍满其室，见已欢喜，即便命终。",
 "乘宝莲花，随化佛后，生宝池中，经七七日莲花乃敷。当花敷时，大悲观世音菩萨，及大势至菩萨，放大光明，住其人前，为说甚深十二部经。闻已信解，发无上道心。经十小劫，具百法明门，得入初地；",
 "这就是下品上生者；得闻佛名、法名及闻僧名，闻三宝名即得往生。」佛告阿难及韦提希：「下品中生者，或有众生，毁犯五戒、八戒及具足戒，如此愚人，偷僧祇物，盗现前僧物，不净说法，无有惭愧，以诸恶法而自庄严。",
 "如此罪人，以恶业故应堕地狱。命欲终时，地狱众火一时俱至，遇善知识以大慈悲，即为赞说阿弥陀佛十力威德，广赞彼佛光明神力，也赞戒、定、慧、解脱、解脱知见。此人闻已，除八十亿劫生死之罪。",
 "地狱猛火化为凉风，吹诸天华。华上皆有化佛菩萨，迎接此人。如一念顷，即得往生七宝池中莲花之内，经于六劫，莲花乃敷。当华敷时，观世音、大势至，以梵音声安慰彼人，为说大乘甚深经典。闻此法已，应时即发无上道心。",
 "这就是下品中生者。」佛告阿难及韦提希：「下品下生者，或有众生作不善业，五逆、十恶，具诸不善。如此愚人以恶业故，应堕恶道，经历多劫，受苦无穷。如此愚人临命终时，遇善知识，种种安慰，为说妙法，教令念佛，彼人苦逼不遑念佛。",
