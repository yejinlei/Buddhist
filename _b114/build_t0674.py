 "佛说：「譬如商人在大海中所乘之船破坏，溺水而死。楞迦主！愚痴之辈，在我法中出家受戒却不能善护，多有毁破，沦于诸恶趣，当知也是如此！」「世尊！有破戒不修梵行，却装作清净梵行的容仪；或破戒后舍戒还俗，此辈舍身有得生善趣的，其譬喻如何？",
