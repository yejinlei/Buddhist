 "「不能。世尊！为什么呢？香体无色可显，不可执持，没有同似，无表无住，怎能见它的量、色等呢？」「楞迦主！你意如何？难道因为你不能见香体量色，它就是断相？」毘毘产说：「不是的。世尊！若是断相，怎么可以嗅知？",
 "」佛说：「正是如此。楞迦主！识体若断，即无生死了别之相。楞迦主！当知识体至妙清净，而被客染之所染污，即所谓无明、渴爱、熏习、业等。如虚空界至妙清净，而被烟、云、尘、雾四染所染。楞迦主！识体净妙无色无量、无所执碍，客染秽现也是如此！",
 "为什么呢？以实智观察，毕竟无有众生可得，无命者、无生者、无丈夫、无富伽罗、无知者、无视者、无想者、受者、作者、闻者，乃至无色、受、想、行等。楞迦主！以实智谛观，诸法自性皆不可得，都是和合而生，没有异性。",
 "楞迦主！应当这样修学众生贞实微妙，不要趣向空旷的生死有野。什么是众生贞实？即所谓逮得证契摩诃若那（大智）。」那时世尊说偈：「被业牵转者，未具八支道；脱业获无漏，才为世上利。」那时毘毘产又对佛说：",
 "「世尊！众生界中无量无边如恒河沙，得以渡越三有广大深海，或以声闻乘渡、或以独觉乘渡、或有证契无上摩诃若那成等正觉，无际无穷无量无数；将来也是如此，以三乘渡而得涅槃，无量无边如恒河沙，而众生界不增不减。",
 "世尊！我见此情，不知所为，如废业者一般。」佛说：「楞迦主！不要废业。为什么呢？众生界无始无终，虚空界、法界也是如此。所以楞迦主！当知众生界不可说增、不可说减，此三有广大生死深海的众生，已渡当渡无量无边，而众生界无增无减，如虚空界无增无减，无初中后。",
 "而虚空界普遍一切，无障、无劳、无作、无分别。同样，楞迦主！众生界若初若中若后皆不可得。若得证契圣法，则众生界终而无尽减，然而有得渡者。为什么呢？众生界法尔如是，无始无终。」毘毘产说：「世尊！",
 "什么是生死有海？」佛说：「楞迦主！生死有海犹如大海。」毘毘产说：「什么是佛大师之教？」佛说：「诸佛教法当知如船。」又问：「什么是出家具法比丘？」佛说：「具法比丘如商人乘船。」又问：「什么是奉持大师教戒无缺？",
 "」佛说：「爱法、奉法、知足、护戒，遵从大师之教谨慎守护无缺，如修理船只，关缀牢固，什物备足，商人乘之欲渡大海。」又问：「什么是善知识？」佛说：「善知识者，如那船师将运此船。」又问：「什么是八正支力？」",
 "佛说：「八圣正支如正信之风，持船速进。」又问：「什么是禅通、三昧、三摩钵底？」佛说：「禅通、三昧、三摩钵底犹如宝洲。」又问：「什么是七菩提分？」佛说：「七菩提分如七姓宝。」又问：「得七菩提分、证契摩诃衍者，又当如何？",
 "」佛说：「譬如商人取得七姓宝，恣意满足，成为大豪富。楞迦主！得七菩提分、证契摩诃衍，无上修行安隐成佛，当知也是如此。善哉出家，在如来之教。」那时世尊说偈：「诸有苦蒙密，缠缚于众生；拯己及他人，断彼有苦缚。",
