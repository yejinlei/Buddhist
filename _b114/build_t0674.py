 "」那时世尊从顶放出青、黄、赤、白、颇梨、银、紫俱胝那由他百千种种杂色无边光明，散照无数诸佛土后，又收摄光相入于顶中。那时长老大目乾连从座而起，偏袒右肩，右膝着地，合掌曲躬，以偈问道：「胜德世依非无因，开显无边净光网；",
