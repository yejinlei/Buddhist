 "积修佛之真法，以祈无上之果。往昔修禅定，寂静调伏心；四禅与五通，无色等皆达。正思三摩提，无漏定圆满；昔时修般若，满足无漏智。了知诸法无性，幻伪假诳惑；无我无众生、寿者、养育者。生者因业而转，烦恼网相连续；",
 "欲界常不净，四染烦恼俱。众生界清净，乃知烦恼之本；得实清净，才见众生之始。施、戒、忍、进、定、般若等超越；以何义开显？是方便及智度。无边胜福聚，大进正觉尊；勤修身语意业，今获佛之真果。我今稽首礼拜，世界之大依父；",
 "愿我于未来，当得佛之正觉。」毘毘产主颂佛完毕，以无量种种上妙华鬘，烧香、涂香、末香，衣服、伞盖、幢幡，笙鼓众杂音乐，歌唱颂赞。与他的部属以最上尊重，如法至诚，一同供养佛及诸声闻、诸菩萨众。那时毘毘产对佛说：",
 "「世尊！我想稍稍请问如来、应、正等觉，愿垂听许。」佛告毘毘产：「随你所问，当如你心为你解说。」毘毘产主蒙佛听许，即对佛说：「世尊！众生（梵音萨埵，旧译为众生或有情）——众生是什么义？」佛告楞迦主说：",
 "「众生，是因为有性想众和合的缘故，即所谓地、水、火、风、空、识、名色、界、入、缘起及因业果，会合相对而生，犹如芦束，有人执之为我。或说：众生，生者、养育者、丈夫者，或称富伽罗、或称摩那婆、或称知者、或称视者、或称作者、受者、想者。",
 "楞迦主当知，这些都是众生想。」毘毘产又对佛说：「世尊！那些众生以什么为根？止住于何处？又依何流运？」佛说：「一切众生以无明为根，止住于爱，随业流运。」毘毘产说：「世尊！业有几种？」佛说：「楞迦主！",
 "业有三种、三相。哪三种？即：身业、语业、意业。哪三相？即：善相、不善相、善不善相。」毘毘产说：「世尊！众生为何死后又再受生？为何舍身又取新身？」佛说：「楞迦主！众生的身死识迁，随业风运，受已作业之果，善及不善、善不善等。",
 "如业所引而取身报，或受卵生、或受胎生、湿生、化生，都是业风所运、不劳而至。」毘毘产说：「世尊！众生死后受中阴身，新身尚未受，那如何安住？」佛说：「楞迦主！你意如何？如种子生芽，是先种子灭而后芽生？",
 "还是先芽生而后种灭？还是种灭经久之后芽才生？」毘毘产说：「世尊！不是种灭已后才芽生，不是芽生已后才种灭，生灭同时，无先无后。」佛说：「正是如此。楞迦主！不是旧身后识灭已，而新身初识生；也不是新身初识生已，而旧身后识灭，生灭同时，无先无后。",
 "楞迦主！如吉弥虫行走，头有所至，身总随之，一处不移，换步才去。同样，先识托身，识总随之，一托不离，死时才迁舍。」毘毘产说：「若是这样，有中阴吗？」佛说：「楞迦主！如卵生众生弃身托卵，以业风力在卵之中凝结无知，至卵成熟时识才有觉。",
 "为什么呢？业法就是如此。以业力之故，卵生众生熟时未至便无所觉知；又转轮王及转轮王子，以福业之故受身之时，不为胎秽所污，不与胎秽和杂，因无胎秽之染，多化生。或者胎生，便有胎卵不染胎秽，熟时已至，剖卵而出。",
 "楞迦主！应当以这些来表明中阴。」毘毘产说：「世尊！识的量如何？是什么形色？」佛说：「楞迦主！识无限量，无色无形，不可显现，无碍无似，无住无表。」毘毘产说：「世尊！识体若无限量、无色、无形不可显现，无碍、无似、无住、无表，岂不是断相吗？",
 "」佛说：「不是的。楞迦主！我今以譬喻开晓你心，当令你悟解。比如你在自己的宫中，处在堂殿之上，婇女妓乐、部属侍奉围绕，床座卧具敷设舒适，种种妙好以庄严自身。那时无忧大园，花草树木敷荣，众花舒放，或和风调吹、或猛风暴激，无忧林之香流入宫殿。",
