 "如下文说「此彼岸不度，故名般若波罗蜜」。《金鼓经》说「生死涅槃皆妄见，能度无余，故名波罗蜜」。此四义中，第一、第三因中说果，是有财释。第二、第四说其已到，是持业释。若以此大慧度之名目能诠，是依主释。",
