 "所以此经说「已说当说」，当说即是当有之音、已说即是曾有之声。问：菩萨现能闻于曾当，佛岂不能令声至今？若能令至，不离前难，重生逆理，不应理。答：谁说诸佛不能令至？但说闻至非般若力。应知诸佛法轮音声，遍于三世无所不至，能至所至不可得。",
 "如《华严经》说「譬如章文字，悉入一切数，所入无所入，法轮亦如是。如来转法轮，三世无不至。所转无所转，求之不可得。」虽去来音至于今现，而非重生，也非过理。为何？佛知三世长远之劫，即是极促一念之顷，而不令劫促也不令念长，所以应知彼声至今，无重生逆理过失。",
 "如彼经说「无量无数劫，即是一念顷，亦不令劫短，究竟刹那法。」且止乘论，还述本宗。生大人故名为大，四种大人皆从般若而得生。如论说「一切世间中，十方三世诸佛是第一大。次有菩萨、辟支佛、声闻，此四大人皆由般若波罗蜜生」",
