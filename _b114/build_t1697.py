 "第二、释慧义：解了义是慧义，能了一切所知境界。无知义是慧义，有所知者不知实相。破坏义是慧义，坏一切法可言性相。不坏义是慧义，不坏假名而证实相。远离义是慧义，永离一切取著相。",
 "不离义是慧义，证会一切诸法相。又次无离无不离义是般若义，于一切法都无所离、无所不离。无坏无不坏义是般若义，于一切法永无所坏、无所不坏。无知无不知义是般若义，由得无所知无所不知。",
 "无义无非义义是般若义，不得一切义不得非义。如是等义，如论广说。如是十种般若之义，若约境智非一之义，观照名慧是持业释，实相名慧是依主释。若依能所无二之门，也是一实相般若，也是持业释。问：",
 "若彼般若之名此土译言慧者，何故论说此二不称？如下文说「不亦称者，称名智慧。般若定实相甚深极重，智慧轻薄，所以不能称。又般若多、智慧少，所以不能称。又般若利益处广，未成能与世间果报、成已与道果报。",
 "又究竟尽知故名称，般若波罗蜜无能称知，若常若无常、若实若虚、若有若无，如是等不可称义应知。」答：此论文意正明智慧之名不称般若之体，非说般若之称不当智慧之名。为何？文称名智慧者，是举能称名为智慧。",
 "般若甚深极重者，是显般若之体离言绝虑。智慧轻薄者，是明般若之名不离言虑，所以此名不能称体。又般若多智慧少者，般若之体无量无边，所知所证无限量；智慧之名有限有量，能称能知唯一名。",
 "所以少名不称多体。次说般若利益处广者，是明般若之体利益处广，智慧之名所不能诠，所以说不可称。次说究竟尽知故名称者，是明智慧之体名称于尽知，而般若体都无所知，谓常无常、虚实、有无如是一切不可得，所以说不可称。",
 "又解尽知体相，所以能以名称其体相。而般若相无能知者，常无常等不可得。由此道理，故不可称。以此四义解不可称，是显名体不得相称。问：般若之体无所知，尽知之名不得称，则如前释「无知义是慧义」",
 "，这名叫可称般若之体？答：无知之名也不称体，直是遮诠，不能表示。但遮于知，非表于无。问：若这样，甚深极重之言，是举其体，故能表示。能表示故，非不可称。若甚深言也不称，何谓此言是举体？",
 "答：甚深等言也是遮诠，但遮浅薄不得深，所以此言也不称体。然而论主意向般若体而发此言，就般若名说轻薄言，为显此意故说举体，非说甚深之言能称般若之体。问：若如是，前以十义释般若名，皆不称实般若之体，也不称于般若之业，怎能说是持业释？",
 "答：般若非然，故不当诸名；而非不然，故能当诸名。又持业释，且是假说非谓实然，故不相违。第三、释到彼岸义：到彼岸义乃有众多。依此经论，略出四义：一者、从生死此岸到涅槃彼岸，故名到彼岸。",
 "如论解释说「三乘之人以是般若到彼岸涅槃，灭一切忧苦，以是义故名波罗蜜」。二者、从有相此岸到无相彼岸，故名到彼岸。如论解释说「是般若波罗蜜等，以色心二法推求破坏、不得坚实，以是义故名波罗蜜」",
