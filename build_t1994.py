def to_baihua(text):
    s=cc.convert(text)
    reps=[('師云：','师说道：'),('乃云：','于是说道：'),('上堂云：','师上堂说道：'),
          ('上堂：','师上堂说道：'),('僧問：','有僧问道：'),('問：','有僧问道：'),
          ('進云：','僧又问道：'),('師乃云：','师于是说道：'),
          ('良久云：','沉默片刻后，师说道：'),('上堂，','师上堂，'),
          ('喫','吃'),('箇','个'),('個','个'),('爾','你'),('麼','么'),
          ('者裏','这里'),('者箇','这个'),('與麼','这么'),('恁麼','如此'),
          ('作麼生','如何'),('祇','只'),('陞座','升座'),('拕','拖'),
          ('揑','捏'),('裏','里'),('𭣟','盲'),('𨁝','跳'),('𩥇','辊')]
    for k,v in reps: s=s.replace(k,v)
    return s

