def build_modern(i):
    section = '【' + TITLES[i] + '】'
    body = p0_protected if i == 0 else paras[i]
    return section + '【义解】' + YIJIE[i] + '【正文】' + body

translations = []
for i in range(59):
    translations.append({
        'section': '【' + TITLES[i] + '】',
        'original_preview': paras[i],
        'modern': build_modern(i),
    })

for i, t in enumerate(translations):
    m = t['modern']
    assert m.startswith('【'), f'seg{i+1} not start with 【'
    assert '【义解】' in m and '【正文】' in m, f'seg{i+1} missing 义解/正文'
    yi = m.index('【义解】'); zw = m.index('【正文】')
    assert zw > yi and len(m[zw + 4:].strip()) > 0, f'seg{i+1} 正文为空'
    # ⟪⟫ 成对
    assert m.count('⟪') == m.count('⟫'), f'seg{i+1} ⟪⟫ 不成对'

