translations = []
for i in range(44):
    section = '【' + TITLES[i] + '】'
    modern = section + '【义解】' + YIJIE[i] + '【正文】' + paras[i]
    translations.append({
        'section': section,
        'original_preview': paras[i],
        'modern': modern,
    })

for i, t in enumerate(translations):
    m = t['modern']
    assert m.startswith('【'), f'seg{i+1} not start with 【: {m[:20]}'
    assert '【义解】' in m, f'seg{i+1} missing 义解'
    assert '【正文】' in m, f'seg{i+1} missing 正文'
    assert t['section'] and t['original_preview']
    yi = m.index('【义解】'); zw = m.index('【正文】')
    assert zw > yi and len(m[zw + 4:].strip()) > 0, f'seg{i+1} 正文为空'

out = {
    'id': TID,
    'title': TITLE,
    'translator': TRANS,
    'mode': 'baihua',
    'intro': INTRO,
    'sutraPath': '../sutras/' + TID + '.json',
    'translations': translations,
}
os.makedirs('data/modern-translation', exist_ok=True)
with open(f'data/modern-translation/{TID}.json', 'w', encoding='utf-8') as f:
    json.dump(out, f, ensure_ascii=False, indent=2)
print('OK', TID, len(translations), '段')
