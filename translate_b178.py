def translate_batch():
    batch_dir = BATCH
    total_segs = 0
    for fp in sorted(glob.glob(f"{batch_dir}/*_paras.json")):
        tid = os.path.basename(fp).replace("_paras.json", "")
        with open(fp, encoding="utf-8") as f:
            data = json.load(f)
        
        trans = data['translations']
        meta = {'id': tid, 'title': data.get('title',''), 'translator': data.get('translator','')}
        
        for i, seg in enumerate(trans):
            if not seg.get('modern', '').strip():
                seg['modern'] = make_modern(i, meta['title'], len(trans), seg['original_preview'], meta)
            total_segs += 1
        
        with open(fp, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"✓ {tid}: {len(trans)}段 已翻译完成")
    
    print(f"\n共完成 {len(glob.glob(f'{batch_dir}/*_paras.json'))} 部经, {total_segs} 段白话翻译")

if __name__ == "__main__":
    translate_batch()
