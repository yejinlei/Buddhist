def render(tid):
    task = json.load(open(os.path.join(TASK, tid+".json"), encoding='utf-8'))
    out = {"id":tid,"title":task['title'],"translator":task['translator'],"translations":[]}
    mods = M[tid]
    for i, seg in enumerate(task['translations']):
        out['translations'].append({"section":"","original_preview":seg['original_preview'],"modern":mods[i]})
    json.dump(out, open(os.path.join(OUT, tid+".json"),"w",encoding='utf-8'), ensure_ascii=False, indent=2)
    print(f"{tid:8s} {task['title'][:30]:30s} {len(mods):2d}段 精译完成")

