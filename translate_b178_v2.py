def translate_all():
    fixed = 0
    for fp in sorted(glob.glob(f"{BATCH}/*_paras.json")):
        tid = os.path.basename(fp).replace("_paras.json", "")
        with open(fp, encoding='utf-8') as f:
            data = json.load(f)
        meta = {'id': tid, 'title': data.get('title',''), 'translator': data.get('translator','')}
        trans = data['translations']
        for i, seg in enumerate(trans):
            new_modern = make_modern(i, len(trans), seg['original_preview'], meta)
            if new_modern and not new_modern.startswith("【待译】"):
                seg['modern'] = new_modern
                fixed += 1
        with open(fp, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"✓ {tid}: {len(trans)}段 已重译")
    print(f"\n共修正{fixed}段")

if __name__ == "__main__":
    translate_all()
