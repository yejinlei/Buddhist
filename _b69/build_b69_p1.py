# -*- coding: utf-8 -*-
import json, os, re
ROOT = '/home/user/workspace/13511660557912876654/buddhist-ontology'
OUT  = os.path.join(ROOT, 'data','modern-translation')
TASK = os.path.join(ROOT, 'data','baihua-tasks')

def build(tid, intro, mods, mode='baihua'):
    sk = json.load(open(os.path.join(TASK, f'{tid}.json'), encoding='utf-8'))
    segs = sk['translations']
    assert len(mods) == len(segs), f'{tid}: {len(mods)} vs {len(segs)}'
    out = {
        'id': tid,
        'title': sk['title'],
        'translator': sk['translator'],
        'mode': mode,
        'intro': intro,
        'sutraPath': f'sutras/{tid}.json',
        'translations': []
    }
    for i,s in enumerate(segs):
        m = mods[i]
        assert m.startswith('【') and '【义解】' in m, f'{tid}段{i+1}体例错: {m[:30]}'
        out['translations'].append({
            'section': s.get('section',''),
            'original_preview': s['original_preview'],
            'modern': m
        })
    with open(os.path.join(OUT, f'{tid}.json'),'w',encoding='utf-8') as f:
        json.dump(out,f,ensure_ascii=False,indent=2)
    print(f'{tid} OK {len(segs)}段')

