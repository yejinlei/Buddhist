 "諸佛經法平等而無有差異，有德無德、內事外事、有世間無世間、已度者未度者、已脫愛欲未脫愛欲。涅槃也平等無有差異，有在一邊，無有在一邊，有與無有恰好在中間，這就是智慧的中間本源。」佛告訴迦葉：「我為你們說法。從生至死，此身所出生之處，苦與癡在一邊、黠慧在一邊，無癡無黠恰好在中間，這就是智慧的中間本源。",
 "」佛告訴迦葉：「空不造作法，法本無空；無相不造作法，法本無相；無願不造作法，法本無願；無死生不造作法，法本無死生，死生無出生、無滅、無處所。無形不造作法，法本無形，應當隨順這本法，這就是中間。觀本法而不自分別、不把身解作空，空便捨棄空中的空，本自空、將來空、現在空。",
 "」佛告訴迦葉：「人寧可執著愚癡大如須彌山，稱之為有，其過失還不足掛齒；人若執著於空、說有個空，其過失極大。若執著愚癡者，明白空理還能得脫；執著空者卻不能得脫。」佛告訴迦葉說：「譬如有人患病，遇到良醫給他藥，藥入腹中卻不運行。迦葉，你的意思如何？",
 "這人能痊癒嗎？」迦葉回答說：「很難。」佛說：「外道其餘的修行者明白空便能得脫，執著空者則不得脫，譬如有人畏懼虛空，啼哭著教人去驅除虛空。」佛告訴迦葉：「這人能驅除虛空嗎？」迦葉說：「不能驅除。」佛說：「正是如此，迦葉！若沙門、婆羅門畏懼虛空，這樣的人也是空言、卻又畏懼空，這種人是狂人，沒有兩樣。",
 "」佛告訴迦葉說：「譬如畫師自己畫出鬼神之像，回過頭來卻自己害怕。譬如未得道之人，對於色聲香味，因此墮於死生之中、不曉法理。譬如木中出火，反而燒了木頭，從觀想得到黠慧卻反燒自身。譬如幻師變化出人，那人反過來把幻師吃了，色聲香味之對也是如此從中而出，念頭所噉、噉於空，並無其他奇特。",
 "」佛告訴迦葉：「譬如燈炷的光明，並不自己想：『我要追逐黑暗、除去黑暗』，然而燈炷照耀，也不知黑暗去了何處。正是如此，智黠並不念：『我要除去愚癡、得到智黠』，也不知愚癡去了何處。這智黠無所從來，也沒有能持來者，這燈炷的光明與黑暗，都是空、不可得以執持。",
 "這智黠、這愚癡，兩者都是空，無所執持。譬如大屋小屋，百年乃至千年，從未在其中點燃燈火，其後各自在其中點燃燈火。迦葉！你的意思如何？這黑暗在其中千年，難道我強力也不能使它出來嗎？」迦葉白佛說：「不會的。黑暗雖然久在其中，見到火光，不敢停留便會即刻離去。",
 "」佛說：「正是如此，迦葉！菩薩在數千巨億萬劫之中，身處愛欲、被欲所覆蓋，聽聞佛經、一念向善，罪業便即刻消盡。燈炷的光明，就是佛法中的智黠之明，黑暗般的愛欲便即刻消盡。譬如虛空之中不長穀實，地裏下種才生長穀實；同樣，涅槃之中不生菩薩，用糞肥治其地、穀種得潤澤而生，在愛欲之中才生菩薩。",
 "」佛告訴迦葉：「譬如曠野之中或山上，不生長蓮花及優鉢花；菩薩也不從眾阿羅漢、辟支佛之法中生出。譬如大池水的污泥之中，生長蓮花、優鉢花；菩薩之法也從愛欲之中生出。譬如四大海安住不動；菩薩在三界功德之中，得以潤澤、成就菩薩道。",
 "譬如蠹蟲吃芥子，所吃只是那麼一點空；羅漢、辟支佛的智慧也只不過如此。譬如麻油，把一根頭髮破作百分，取其中一分浸在油麻中，能滴出幾滴呢，羅漢、辟支佛的智慧就是這樣；而如十方虛空所到之處，菩薩了知佛的智慧就是這樣。譬如轉輪聖王有千子，卻沒有一個兒子具有轉輪聖王之相，雖有那麼多的兒子，都不在嫡子之數中；",
 "有羅漢數千巨億萬人，也不在佛的嫡子之數中，其中沒有一個菩薩，佛雖有那麼多羅漢，也不足以稱為佛子。譬如轉輪聖王的正夫人與貧窮人私通，從中生子。」佛告訴迦葉：「這應當算轉輪聖王的兒子嗎？」迦葉回答佛說：「不算。",
 "佛說：「正是如此，迦葉！雖然有羅漢從佛法中生出，這不是佛子，不能與菩薩相比。為什麼呢？因為菩薩不使佛法斷絕的緣故。譬如轉輪聖王與青衣私通，其後生子，具足成就轉輪聖王之相，雖從青衣所生，仍然是轉輪聖王的兒子。正是如此，菩薩雖然在生死之中、修行之力尚少，終究會成為佛子。",
 "譬如轉輪聖王的夫人懷胎七日，終當成就轉輪聖王之相。諸天都能徹視見到腹中的胞胎，雖然轉輪聖王的兒子眾多、卻沒有轉輪聖王之相，諸天說：『終究不如供養腹中七日的胎子。』發心菩薩也是如此，其中便已在修佛道，諸天心中念道：『雖有羅漢數千萬億、豪貴尊勝，也不如供養發心菩薩。』",
 "』譬如摩尼寶珠，即使有水精寶石大如須彌山，也不如一颗摩尼珠；初發心菩薩之眾，是阿羅漢、辟支佛所不能及的。譬如轉輪聖王有了年幼的兒子，諸小王、旁臣都向他行禮；初發心菩薩也是如此，諸天、帝釋、梵天、世間之人、龍、鬼神都向他行禮。譬如大山，各種藥草都從其山頂生出，也沒有主人，隨有病的人取用、各種病都能治癒；",
 "菩薩也是如此，手持智慧之藥，以平等之心治癒十方天下之人、生死老病。譬如月初生之時人人都向它行禮，月圓滿時卻沒有人向它行禮；若有信佛之人，在佛法中菩薩發起道意，若有信佛之人，大多向菩薩行禮。為什麼呢？因為佛是從菩薩而成的緣故。譬如有智慧的人，不會捨棄月亮而去向星宿行禮；",
 "高尚之人也是如此，不會捨棄菩薩而向羅漢行禮。譬如天上天下共同修治一颗水精石，終究不能得到摩尼珠；一切自守持戒、修禪三昧，智黠的羅漢雖多，也不能坐在佛樹之下、不能成佛。」那時佛告訴摩訶迦葉菩薩：「為了十方之人，菩薩因此作功德；為了十方之人，菩薩因此作功德，不自誇貢高，菩薩常常應當教導十方之人、治癒他們的病。",
 "什麼是治癒他們的病？貪婬者以觀想為藥，瞋恚者以平等心為藥，愚癡者以十二因緣為藥；疑惑不信者以空為藥；欲界、色界、無色界，若想覺悟這些，以無相為藥；我所與非我所，以及愛欲所念，以無願為藥。四種顛倒各自有藥，什麼是各自的藥呢？",
 "一是執常者以無常為藥，二是執樂者以苦為藥，三是以我所之教對治非我所為藥，四是執身者以觀想為藥。四意止以身心為念，這就是藥；四意斷斷除一切惡，這就是藥；四神足觀念合會成身、以空捨為藥；五根、五力，以念功德對治不信、懈怠為藥；",
 "七覺意入於法黠，這就是藥；外道及不信者以八正道為藥。這就是各各分別的藥。」佛告訴迦葉：「若閻浮提之中，或醫者、或醫者的弟子，乃至最尊的醫王充滿三千國土，或醫王滿於其中，即使有那麼多的醫王，也不能治癒外道及不信者，因為他們不知當用何等法藥來治癒。",
 "菩薩這樣想：『不用世間之藥治人的病，應當用佛法之藥治人的病。』什麼是佛法之藥？隨其因緣，在黠慧之中無我、無人、無壽、無命，信解空而得度脫，於空與無空聽聞而不恐不懼，以精進推究念心：什麼樣的心入於婬？什麼樣的心入於瞋怒？什麼樣的心入於愚癡？",
 "是過去、當來、今現在的心入於其中嗎？過去已盡、當來未至、今現在無所住。」佛告訴迦葉說：「心無色、無視、無見。」佛告訴迦葉說：「諸佛也不見心，因為心本無所有、無所因，自己造作這因緣，自己得到這死生。心遠行而至、獨自而行，心如流水之上生出泡沫、須臾即滅，心如天空突降暴雨、來得沒有定期，愛欲也是如此、來得沒有定期。",
 "心如飛鳥、獼猴，不肯停留在一個地方，心所依止也不肯停留一處。譬如畫師各自敷設色彩、心也各各不同，如此隨行而有所作為。譬如國王在眾人之中為上，心在諸功德之中也無上。譬如蒼蠅停在糞上、自以為清淨，心也是如此，入於愛欲之中卻自以為清淨。心如怨家，把人拋置到惡道之中、沒有期限。",
 "譬如拿著灰土來築城，把無常當作有常。譬如拿著魚鉤去釣魚而有所得，心把我所當作非我所。心如盜賊，所修的功德反成自辱。譬如在斜坡上上下下，心須臾之間有愛、須臾之間有憎。心如怨家，只是窺伺可乘之機，心常常想聞香。譬如彩畫的瓶子盛滿屎尿，又有什麼奇特，而心卻喜愛它的味道。",
 "譬如奴僕隨從主人差遣，心卻樂於應對。譬如飛蛾自己投入燈火之中。」佛告訴迦葉：「心，尋求它卻了不可得，雖然不可得、這便是無有；雖然無有、因之而無所生；雖然無所生、也無所出；雖然無所出、也無所壞；雖然無所壞、也沒有死也沒有生；雖然無所生無所死、本來就無因緣；死生雖然本無因緣，無生也就無願；雖然無願、也無所執持；雖然無所執持，這就是羅漢的滅度，這羅漢的滅度沒有戒禁可言。",
 "若死若生，若計度所作之罪，本來就了無所有，這無死無生就是羅漢的滅度；羅漢的滅度也沒有身行、沒有口行、沒有心行，這滅度沒有差異。為什麼呢？因為諸經同一味的緣故，這滅度都平等如虛空，這滅度恰好無所攀附，也沒有我所，也不是非我所；這滅度真實而本無所謂真諦，這滅度本自清淨、沒有愛欲的瑕疵穢垢；本滅遠離本滅，這滅度依次至於涅槃，這滅度無盡，本來無有所生；這滅度安穩、用以至於涅槃，所以安穩就是這滅度。",
 "常滅、常經、無本，這滅度好好地離去、本來無死無生。」佛告訴迦葉說：「自己求辦自身之事，不要憂慮外事。將來後世的比丘之輩，譬如拿土塊擲向狗，狗只追逐土塊、不追人。當來的比丘也是如此，想在山中空閑之處，常常想得到安穩快樂，卻不肯向內觀照自身。這樣便是不曉色、耳、鼻、舌、身，從什麼因緣能得到解脫呢？",
 "從此入城乞食，若到了聚落城邑，見到色聲香味的細軟可愛、想要得到，便為此在山中墮落衰敗；若多少持戒卻不向內觀照，死後便生到天上，從天上又來下生世間，從此以後不離三惡道。」",
 "佛告訴迦葉說：「比丘如狗逐塊那樣，別人罵他他也罵人，別人打他他也打人，不能制伏自心的人也是如此。譬如調馬師，馬有奔突不馴的，應當屢屢調教、久後便調伏馴良；比丘時時以法觀照、制伏調柔自心，也不見其惡，也是如此。譬如人患咽喉疼痛，整個身體都為之疼痛；人心繫縛於我所、非我所，隨順外道也是如此。」",
 "佛告訴迦葉說：「沙門有二種事會墮入牢獄：一是口稱我所，二是向人求取、想得到供養。沙門又有二種事被纏縛。哪二種呢？一是修學外道，二是多欲積聚衣被及袈裟、鉢器。沙門又有二種事中途斷絕。哪二種呢？一是與在家白衣交好，二是見到好持戒的沙門反而憎恨。沙門又有二種事墮於垢濁之中。",
 "哪二種呢？一是常常繫念愛欲，二是喜歡交結知心之友。沙門又有二種事執著。哪二種呢？自己有過失不肯悔改，反而記念他人的惡。沙門又有二種事墮入泥犁之中。哪二種呢？一是誹謗經道，二是毀壞戒律。沙門又有二種事。哪二種呢？",
 "一是全然犯戒，二是在法中沒有所得。沙門又有二種事應當慚悔。哪二種呢？一是不應行之事卻強自披著袈裟；二是自身不持戒，反而要持戒的比丘來承事自己。沙門又有二種病難以治癒。哪二種呢？一是心邪亂，二是有人行菩薩道卻去阻斷他。",
 "佛告訴迦葉：「沙門為什麼正稱作沙門？有四種事稱作沙門。哪四種呢？一是形貌衣著像沙門，二是外表像沙門、內心卻懷著偷惰虛偽，三是求取虛名、自誇貢高，四是行持不犯、是真正的沙門。什麼是形貌衣著像沙門呢？剃頭剃鬚，穿著袈裟、手持鉢器，心不正、不持戒，只想作惡、喜歡修學外道，這就是形貌衣著像沙門。",
 "為什麼說外表像沙門、內心懷著偷惰虛偽呢？緩步而行，緩步而出、緩步而入，學外道的粗惡，在山間搭草屋為廬，內心沒有正信、執著於我、執著於我所；其中有因受苦而正直誠信的人，他反而心生嫉妒。什麼是求取虛名呢？偷惰地持戒、讓他人稱譽，偷惰地學經、讓他人稱譽，偷惰地置身僻靜之處、讓人稱譽，卻不自我剋責、不求度脫，只是偷惰虛偽。",
 "什麼是行持不犯的真正沙門？不吝惜壽命、不惜損身，何況去求取歸依、遺贈的供養呢。若有比丘修守空之行，常勸人歡喜追隨，並且完全見到諸法清淨本無瑕穢，自己成就黠明、不從他人那裏領受黠明，對佛法也不執著，何況執著於色？也沒有結縛者、也沒有解脫者，本來就不見涅槃，也沒有死生、也沒有涅槃，這就是真正的沙門。",
 "」佛告訴迦葉：「至誠的沙門常常應當這樣想：應當效法真正的沙門，不要效法那求虛名、諂媚欺詐的沙門。譬如貧窮之人號稱大富，只是得到富的名聲、其實一無所有。」佛告訴迦葉：「這人應得算有這個名分嗎？」迦葉說：「不應得。」佛說：「正是如此，迦葉！雖然有沙門之名，卻不行沙門之法，也如同貧人自稱大富。",
 "譬如人被水溺沒、反而渴得要死，沙門也是如此，誦經雖多、才能雖高，卻不去除情欲，在情欲之中渴得要死，因而墮入泥犁、禽獸、薜荔之中。譬如醫者裝滿一整器藥，卻不能治好自己的病，雖然誦經多卻不持戒，也是如此；譬如人患病得到王家的藥，自己不加護理而致死，雖然誦經多卻不持戒，也是如此。",
