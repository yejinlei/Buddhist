 "所以本颂说：现量除分别，其余比量从所说的因而生。此中「现量除分别」，是说若有智于色等境远离一切种类、名言、假立、无异、诸门的分别，由不共缘而现现各别转起，所以名为现量。所以说颂：有法并非只有一相，诸根也不能对一切境都行，唯有内证、离于言说，是色根的境界。",
 "意地意识也有离诸分别、唯是证行而转的现量。又在贪等烦恼的诸自证分、诸修定者离于教的分别，都是现量。又此中没有别的量果，因为即此体而似义生起之故、似有作用之故，假说为量。若在贪等的诸自证分也是现量，为什么此中除去分别智呢？并不遮止此中的自证现量，因为自证无分别之故。",
 "但在此中若还了知其余境分，就不名现量。由此就说忆念、比度、希求、疑智、惑乱智等，于粗爱等都不是现量，因为它们随先前所受而分别转起之故。如是一切世俗有之中，瓶等、数等、举等、有性、瓶性等的智都是似现量，因为在实有法上作其余行相，假合其余义而分别转起之故。",
 "已说现量，应当说比量。「余所说因生」，是说此智是前现量智之余，从如所说的能立因而生，是缘彼所立之义。这有两种：即对于所比宗审观察的智，从现量生或从比量生；以及忆念此因与所立宗不相离的念，由此成就前言举说之力，忆念因同品定有等之故。",
 "这是近及远的比度因之故，都名为比量，这是依作具、作者而说的。应当这样了知：悟他的比量也不能离开此比量而得成就能立。所以说颂：一事有多法，相并非一切都能行于此；唯由简别其余，表示定能随逐。如是能相者，也有众多法，唯不越于所相，能表示而非其余。",
 "为什么此中与前面的现量差别建立呢？为了显示二门：此处也应当对于其比果说为比量，彼处也应当对于其现因说为现量，二者都不遮止。已说能立及似能立，应当说能破及似能破。颂说：能破是阙等言，似破是谓诸类。此中「能破阙等言」，",
 "是说前面所说的阙等言词的诸分过失。彼一一言都名为能破，因为彼一一能显示前宗不是善说之故。所说「似破谓诸类」，是说同法等相似的过类名为似能破，因为彼等大多对于善比量为迷惑他人而施设之故。不能显示前宗不善，因为彼等非理而加以破斥之故，以及在能破之处而施设之故。",
 "因为它们都是彼过类之类，所以说名过类。若对于非理而立的比量中如是施设，或者是不了知比量的过失，或者正是为了显示彼过失之门，就不名过类。颂说：为了示现异品的缘故：由同法而异立，是同法相似；其余，由异法而异立。分别与差别名分别相似。应一成无异，即无异相似。显所立的余因，名可得相似。",
 "难于义、别疑因，所以说名犹豫相似。说异品义之故、非所爱，名义准相似。此中「示现异品故，由同法异立，同法相似」，是说颠倒成立所以名为异立，这是依作具、作者而说。同法即是相似，所以名同法相似，因为它是一切摄立中相似的过类之故。",
 "说「相似」是不男声，即中性词，因为与能破相应之故、或随顺结颂之故。同法相似怎能成为能破？因为在所作中说能作之故、转生起之故，作如是说。后面随所应当也这样宣说。现在此中由同法喻颠倒成立，所以说名同法相似。如有人成立「声是无常，勤勇无间所发性故」，",
 "这本是以虚空为异法喻。有人却显示虚空为同法喻，说虚空无质碍等故，立「声为常」。这样，即此所说的因中，瓶本应作为同法，而对方却把异品虚空说为同法，因此说为同法相似。「余由异法」，是说异法相似是前面同法相似之余。示现异品，由异法喻颠倒而安立；二种喻中如前安立瓶为异法，所以说为异法相似。",
 "「分别差别名分别」，前面说示现等故，现在说分别差别故，应当知道这是分别同法的差别。即如前面说瓶为同法，于彼同法有可烧等差别义之故，那么瓶应是无常；而声不是可烧，声应是常。因为不可烧等有差别之故，由此分别颠倒所立，所以说名分别相似。",
 "所说「应一成无异」，因为示现同法前面已说之故，由此同法与彼应当成一之故。彼者是谁？因为再没听到别的方便之故、相邻近之故，应当知道是宗。「成无异」，是成就无异的过失。即由此言的义可以了知之故，不说它的名是谁与谁共成无异。因为不别说之故，即此一切与彼一切共成无异。",
 "如有人说：若见瓶等有同法之故，就令其余法也无别异，一切瓶法于声应皆具有，那么一切更互相对的法同而应成一性。此中抑止成无别异的过失，也为了显示瓶与声的差别，与前面的分别相似差别不大，所以应当别说。对方若以「勤勇无间所发」成立「无常」，",
 "想显示二者都是非毕竟性，就成宗因无别异的过失。抑止此而令成无别异性，所以说名无异相似。有人说此因如能成立所成立法，也能成立此相违法。由于其无别异，所以说名无异相似。「显所立余因，名可得相似」，是说若显示所立宗法之外有余因可得，这就说名可得相似。",
 "即如有人说：如前成立「声是无常」，这勤勇无间所发不是正因，因为在电、光等法上由现见等其余因可得无常成立之故。因为若离此因而得有彼所立，此因就不是彼所立之因。又有人对此别作方便，说此不是彼无常的正因，因为它不遍之故。如说「丛林皆有思虑，有睡眠故」。",
 "「难义别疑因，故说名犹豫」，因为与过类相应，所以用女声即阴性词来说。此中分别宗义的别异，因成不定，所以说名犹豫相似；或者又分别因义的别异，所以名犹豫相似过类。即如有人说：如前成立「声是无常，勤勇无间所发性故」，",
 "现见勤勇无间所发，或者是显、或者是生，所以成为犹豫：现在所成立的，是显的还是生的？所以不应以这样的因来证无常之义。「说异品义故非爱，名义准」，即如有人说：若以勤勇无间所发说声是无常，按义准则应是：若非勤勇无间所发，诸电、光等应都是常。",
 "以上如是名为义准相似。应当知道此中略去了后句，所以只名叫犹豫相似、义准相似。又由什么义，此同法相似等的相似过类，不同于因明师所说的次第呢？因为似破相同之故。颂说：由此同法等过类，多疑故与彼似破相似。「多」字是为了显示或有的异难，以及为了显示似不成因的过失。此中前四种过类与我所说的譬喻方便完全不相符，姑且随顺世间的譬喻方便，虽然不显示因是决定性，然而摄其体，所以作这样说。",
 "因为用不定的同法等因来成立自宗，方便地说他人也有此法，由此便成似共不定，或者又成似相违决定。若说这只是为成立自宗，为什么把它不定得名能破呢？并非即说此言以为能破，而是难对方不定的言词，说名不定能破。因为在能诠之中说所诠之故，没有这个过失。",
 "其余之处也应当这样安立。若所立的量有不定过，或者又以决定的同法等因有所成立，就名为能破。因为这些难的缘故，若现见之力强，比量不能遮遣其性。如有人成立「声非所闻，犹如瓶等」，因为现见声是所闻之故，不应以声是所闻性来遮遣无常，并非只是不见就能遮遣之故；",
 "若不是这样，现量也应当遮遣声是常。第二种无异相似是似不成因的过失。彼以本无而生起，增益所立，为作宗因成一性的过失之故。此以本无而生起为极成因法，证声灭后无。若即以此安立，可以成为能破。第三种无异相似成立违害所立，因为难于成立故成为似能破，由于可烧等不决定之故；",
 "若这些是决定的，可以成为相违。可得相似的所立不定，所以成为似能破；若所立的因于常法上也有，可以成为能破。第二种可得虽然是不遍，但由于其余类无此因之故，是似不成过；若所立法无，可以名为能破，并非在此中想立一切皆是无常。犹豫相似，是说以勤勇无间所发能成立灭坏，若以生起增益所立而作不定过，这是似不定；",
 "若对于所立不起分别，只是简别因是生起而作难，这是似不成。因为在此中不想只说生来成立灭坏，其实若生、若显二者全都灭坏，并非不定之故。义准相似，是说以颠倒不定而作难，所以是似不定。若非勤勇无间所发者立为常、无常，或者只有勤勇无间所发者无常而非其余，可以成为能破。",
 "颂说：若因有至不至、有三时之难，作非爱言，即至非至相似、无因相似，是名似因阙，即似因的缺失。「若因至不至，三时非爱言，至非至、无因」，是说对于至、不至作非爱之言：若能立的因至所立宗而成立，则因与宗无差别之故，因就应不是所立，如池水与海水相合无有差异。又若因不成，就应不是相至；",
 "所立若已成立，这是谁的因？若能立的因不至所立宗，则不至之因与非因无差别之故，应不能成因。这名为至非至相似。又对于三时作非爱之言：若能立的因在所立之前，那时还没有所立，这是谁的因？若说因在后，所立已成，那又何必需要因？若因与所立是同时，因与有因者都不能成就，如牛的两角同时并立。",
 "以上如是名为无因相似。此中如同前面所说次第有异，是由于二者都名为似因阙之故。为什么呢？因为它们非理地诽拨一切因之故。此中是什么道理呢？只以不至与非因相同之故，虽然与因相相应相符合也不名为因。这样又是什么道理呢？只以在所立之前不得因名之故，就说它非能立。又此中有自害过，因为遮遣相同之故。",
 "如上，暂且对于言因及慧智所成立之中有似因阙，对于义因之中有似不成，因为它们非理地诽拨诸法之因之故。如前面二种因，对于义所立二者都不是所作、能作性之故，不应合于正理；若以正理而诽拨时，可以名为能破。颂说：说前未说无因故，应无有所立，名无说相似。",
 "颂说：生相似、无生相似也是这样。所作性异于少分而显所立不成，就名所作相似。多分如似宗那样说。「说前因无故，应无有所立，名无说相似」，即有人说：如前所立，若由此因证声无常性，那么此因未说之前都无所有；因无有之故，声应不是无常。",
