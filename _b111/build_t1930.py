 "智少了一分，文中从简而依因位，所以说八人。第五、薄地，体察破斥欲界六品思惑，所以名为薄，即是斯陀含果。第六、离欲地，断除欲界九品思惑，不再来欲界，即是阿那含果，所以说离欲。第七、已办地，三乘进而断除色界、无色界八九七十二品思惑，即是罗汉果，名为已办，声闻行至此极。",
 "第八、支佛地，虽同断见思，但福厚根利，能除去习气。第九、菩萨地，从初发心缘无生四谛发菩提心，到第六、七地从空入假，「假」指化道，「空」即空观，道观双流，誓扶习气还生三界，用道种智游戏神通，净佛国土、或就众生，三乘根机成熟，即坐道场。",
 "用一念相应的智慧进而断除余习及界内无知，得一切种智，名第十佛地。转无生四谛法轮，化三乘之众入无余涅槃，如火烧木不再有灰炭，如香象渡河到达河底。所以经说：「诸法实性相，三乘亦皆得，而不名为佛。」三乘观行也有四门，现在也约有门说明十法成乘：",
 "第一明观境，即六道的阴、入，能观与所观都如幻如化。第二、明发心，二乘缘真而自行，菩萨体察幻化，兼为他人与乐拔苦，譬如镜像。第三、安心定慧，前面虽止观并空如空，而安立二法。第四、破法遍，用幻化之慧破幻化的见思。第五、识通塞，虽知苦、集、十二缘生及六蔽等都是如幻如化，也以幻化的道、灭、十二缘灭及六度等来通，节节检校都如幻如化。",
 "第六、道品调适，以不可得之心修三十七品。第七、对治，体察三藏法的无常、苦、空、如幻而对治。第八、识次位，了达乾慧等十地的因果，三人殊途而不谬乱混滥。第九、令安忍乾慧、外凡的内外诸障而入性地。第十、速令内凡性地不执著相似法爱，而入八人见地证真，其余三门也是这样。",
 "广说如大本。通教完毕。第三、说明别教，这是就界外独属菩萨之法。教理、智断、行位、因果，区别于前面二教、区别于后面的圆教，所以名为别。《涅槃经》说：「四谛因缘有无量相，非诸声闻、缘觉所知。」诸大乘经广明菩萨历劫修行，行位次第互不相摄，都属此教。",
 "《华严经》明十住、十行、十回向为贤，十地为圣，妙觉为佛。《璎珞经》明五十二位，前面加十信。《仁王经》不论等觉，只有五十一位。《金光明经》只列出十地与佛果。《胜天王经》只明十地。《涅槃经》明五行十功德。",
 "既然是界外菩萨的行位，随机利益，岂能定说？现在约《璎珞经》总明七位：一十信、二十住、三十行、四十回向、五十地、六等觉、七妙觉。最初十信，十心之中以信为本，所以说十信。十心是：一信、二念、三精进、四慧、五定、六不退、七回向、八护法、九戒、十愿，即是外凡伏忍之位。",
 "住、行、向三者都属内凡柔顺忍之位。第二、明十住，即习种性，从信入住而修习，从假入空，断界内见思，所以名习种。一发心、二持地、三修行、四生贵、五方便具足、六正心、七不退、八童真、九法王子、十灌顶。",
 "第三、明十行，是性种性。从十住的空性而入十行的假性，名性种性。一欢喜、二饶益、三无瞋恨、四无尽、五离痴乱、六善现、七无著、八尊重、九善法、十真实。第四、明十回向，是道种性，修中道观，伏界外之惑，所以名道种。",
 "一救护众生、二不坏、三等一切诸佛、四遍至一切处、五无尽功德藏、六随顺一切坚固平等善根、七等观一切众生、八真如相、九无缚无著解脱、十入法界无量。第五、明十地，是圣种性，证得中道观，所以名为圣。",
 "一欢喜、二离垢、三明地、四焰地、五难胜、六现前、七远行、八不动、九善慧、十法云，这十地破界外十品无明，再破一品入于等觉，再破一品入于妙觉，始终只破十二品无明，才与圆教第二行齐等。以我之因作为你之果，教门权巧而示位高者，譬如边疆未平静时，以高位名目来定爵论功，其实际的官职则低。",
 "此教缘无量四谛发菩提心，苦、集、灭、道都是无量之相，若论自行则随一门竖入，化他则始终横破之故。十住自行从假入空，用生、无生观六界空。十行入假，广集四四十六门之法。了知十界是假，回向于后心，灭九界之假，证入佛界之中。",
 "地前缘修两种观，经过无量劫，作为中道的方便。登地后三观现前，与圆教初住无二无别，名为证道。若有根机宜闻地上历别之说，也就作「一地不知二地」之说，所以诸大乘经或明七地之前仍居方便位。这便是始终约教而不同，缘修的地前相对初地名为教道。",
 "暂且就自行的四门之中，有门所修的十法成观：第一明境，缘于登地中道妙有之境而为所观，超出空有之外。第二、明发心，缘此妙有而起四弘誓，所以《华严经》说：「菩萨不为一人、一国、一界微尘之人，乃为法界众生发菩提心。」",
 "第三、安心，既然发心已毕，安心进行，修习诸定慧，定爱而慧策。第四、破法遍，用妙有之慧遍破空、有。第五、识通塞，次第三观为通，见、思、尘沙、无明为塞。辗转检校，令塞转通。第六、道品调适，三十七品是菩萨的宝炬，陀罗尼、念处破颠倒；",
 "正勤、如意能生五根；五力必定增长七觉、八正；定慧均平入三解脱门，证中道无漏。第七、对治助开，用前面的藏、通二教助开妙有实相中道。第八、知次位，善能了达七位，终究不会说自己叨居至极的上圣。第九、安忍，策进十信之位入于十住，令远离违顺、强软二贼。",
 "第十、无法爱，策进三十心令入十地，若爱著相似之法，名为顶堕。其余三门也是这样，广说如大本。别教完毕。其次简略说明圆教。圆就是圆妙。《华严经》法界广大，《净名经》入不二法门，《般若经》最上之乘，《涅槃经》一心五行等，都是圆妙之法。",
 "这些圆妙同是一理别无他，但兼带半字、满字教，方便覆蔽真实，旨趣仍然隐晦。现在随顺佛意，收卷方便归于真实，开显的圆教粗略陈述纲要，即以《法华经·分别功德品》末说明本迹流通。如来灭后，五品之人闻经辗转传说，起观行成就，作为凡地措心之首。经说：",
 "「又复如来灭后，若闻此经而不毁呰，起随喜心，从法会而出，到聚落田里，为父母宗亲随力演说。如此辗转，至第五十人闻而随喜，其福超过四百万亿那由他恒河沙等众生令得罗汉，百千亿分不及其一。」这就是初随喜品；",
 "经说：「何况读诵受持之人。」即第二品；经说：「若有受持读诵为他人说。」即第三品；经说：「况复有人能持此经，兼行布施、持戒、忍辱、精进、一心、智慧，是兼行六度。」即第四品；经说：「若人读诵为他人说，复能持戒、忍辱无瞋，精进勇猛得诸深定，智慧问答，则是具行六度。",
 "」即第五品。初品之初的校量不可测度，其余四品非凡夫小乘所能了知。略如经文所说，不能具述。最初说随喜，是随喜妙法。法就是心法以及众生法、佛法，此法即心、此心即法，三者无有差别，凡圣一如。如即是实相，实相遍相百界三千，百界三千无非实相。",
 "所以经说：「诸法实相，即指诸佛的权实之法，所谓如是相、性、体、力等，即百界三千。」妙心体具，具不出心，犹如金体具足众器，具不出金，所以名具心。以此而为妙，妙心是境，妙智是观，观、境不二，能照能遮。",
 "所说的境，具备三谛。具心即空，是真谛之境；具心即假，是俗谛之境；具心即中，是中道第一义谛。知真即空观；知俗即假观；知中即中观。常境无相，常智无缘，无缘而缘，无非三观；无相而相，三谛宛然。",
 "初心有此了知，庆己庆人，所以名随喜，即是第五十人。法会之初闻说即五品之初，观念不间断，所以有差异。一一品中以五悔为本，所以弥勒在因位时没有别的苦行，只是修五悔，日夜六时没有须臾间断，而成等正觉。其次以圆解观心，修行五悔，再加读诵，善言妙义，与心相会，如膏油助火。",
 "这时心观更加明利，名第二品。其次以增品胜心修行五悔，再加说法，转化其内解，导利前人。因为广济之故，化功归于自己，心倍胜于前，名第三品。其次以增进心修行五悔，旁行六度，因福德力之故，加倍助益观心，更一重深入前进，名第四品。",
 "其次以圆心修行五悔，正行六度，自行化他，事理具足，心观无碍，转胜于前不可比喻，名第五品。这五品都属于外凡之位，假名为五品。既转明静，豁然入于闻慧，通达无滞，深信难动，即入十信，是六根清净的内凡之位。",
 "见思之惑自然任运先除，如冶炼铁作器，粗垢先尽。所以《仁王般若经》说：「十善菩萨发大心，长别三界苦轮海。」与三藏教、通教的佛果位齐等，与别教十回向齐等。信的名称虽同于别教，但人与行的深浅永远不同，住、行、向、地也是这样。",
 "圆教贤位完毕。其次说明圣位。四十二品都破界外微细无明，初入十住，破十品无明，证圆佛性，开佛知见。所以《华严经》说：「初发心时便成正觉，真实之性不由他悟。」即此之意。证得初一位即能分身百佛世界，为十界之像普现色身，随机设化。",
 "二住以后，十位各加于前，乃至妙觉不可说界，本高迹下，普现三昧。其次入十行，再破十品，示佛知见。其次入十回向，再破十品，悟佛知见。其次入十地，进破十品，入佛知见。竖论虽然如此，横论则一一都具备开示悟入佛知见。",
 "其次破一品入等觉，后破一品入妙觉。妙觉无上，无可再论。始终理体平等，所以名圆；约事则仍有差别，于是分诸位。譬如湿性，冰水无异，融冰成水，初后宛然。应说明六即，方能彰显圣理。圆性恒常周遍，众生与佛都如，理即佛性，如理而知；",
 "名字佛性，如理了知而修观，刹那无间；观行佛性，获得清净六根；相似佛性，破界外之惑证真；初住乃至等觉，四十一位分证佛性；妙觉一位智断俱圆，究竟佛性。因理同所以称「即」，因事异所以分「六」，故名六即。如诸大教中有「即」之名义者，如生死即涅槃、烦恼即菩提等，都要判以六即，方能免于滥与非。",
 "问：《华严经》说：「初发心住便成正觉」，为何还须再经其余诸位呢？答：正觉分证成就，名为成正觉，并非初发心即成就究竟正觉。譬如暗室分为四十二分，一炷之灯即名室明，岂可等同于二、三乃至四十二炷？若了达此喻，则一成一切成，不失初后，明昧宛然，应当知晓。",
 "圆教之人于四门中，位位十法浅深有差异，现在暂且总明十法的名相：第一、观不思议境，指观一念所具之心即无作四谛，了达此具心无非众生，生、佛一如，涅槃无二，即苦谛、灭谛不可思议。了达此具心无非烦恼，烦恼即般若，即集谛、道谛不可思议。",
 "惑与智相即，因果岂有差别？一一无非空假中，境即空所以方便净，即假所以圆净，即事所以性净。三净一心中得，名大涅槃。所以《净名经》说：「一切众生即大涅槃」，名不思议境。境法非一所以名广，无非实相所以名高。所以《法华经》说：",
 "「其车高广」。第二、发真正菩提心，缘前面的实境而起四弘誓。缘前面的苦境发誓度众生，所以《法华经》说：「未度者令度。」缘前面的集境发誓断烦恼，所以《法华经》说：「未解者令解。」了达惑即智，则法门无尽誓愿知，所以《法华经》说：",
 "「未安者令安。」生死即涅槃，则佛道无上誓愿成，所以《法华经》说：「未得涅槃者令得涅槃。」四谛是所缘之境，四弘是能发之誓。誓若无境名为狂愿，境不发誓名为顽谛。依谛发心，远离邪、小、偏、伪的过失，所以名真正。",
 "所以《法华经》说：「又于其上张设幰盖」等。第三、巧安止观，体察境即法界，法界寂然名「止」，止即是定。寂然而常照名「观」，观即是慧。这就是总安。若分止观以逗合四悉檀之机，名为别安。或总或别无非圆观，所以名善巧。所以《法华经》说：",
 "「安置丹枕」，即车内的枕。第四、破法遍，以圆三观遍破三惑，惑与智俱圆，一心中破，名破法遍。所以《法华经》说：「其疾如风。」第五、识通塞，苦、集、无明、见、思、尘沙为塞；道、灭、无明灭即空、即假、即中等为通。",
 "是通就须护持，有塞就须破除，于通生起塞也是这样。节节检校名识通塞，即车外的枕。第六、道品调适，无作七科一一调试，随宜而入。四念为本，双非枯荣。其余各品以此类推，无非中道，名道品调适。所以《法华经》说：「有大白牛」",
 "等。第七、对治助开，若正道多障，圆理不开，须修事相之助。事即五停心及三藏六度等，事成而理显，事理都如，名为合行。所以《法华经》说：「又多仆从」等。第八、知次位，令无上慢。第九、能安忍，策进五品而入十信。",
 "第十、无法爱，策进十信入证初住。所以经以总譬：乘此宝车游于四方，乃至直至道场等。因此知道中下根人修观，十法都须具备。上根人体察境界含摄诸法，或一、或二、或三不定，内外作受无不都是如此。大车无量，言语岂是徒然施设？以法对譬，出自一家，本迹所归，圆理无二。",
 "不别而别，位位增益明利，广说如其余文，非此处所能具述。依文判义，或四或八，目击而道存。再引《涅槃经》证成其理，所以第六卷说：「凡夫如乳，须陀洹如酪，斯陀含如生酥，阿那含如熟酥，阿罗汉、辟支佛、佛如醍醐。」",
 "《大论》说：「声闻经中称阿罗汉名为佛地，所以三人同是醍醐。」这是譬喻三藏教的五味。《涅槃经》第三十二卷说：「众生如杂血乳，须陀洹、斯陀含如净乳，阿那含如酪，阿罗汉如生酥，辟支佛如熟酥，佛如醍醐。",
 "」这是譬喻通教的五味。辟支佛侵除习气，稍胜于声闻，所以与菩萨同为熟酥。佛正习俱尽名为醍醐。《涅槃经》第九卷说：「众生如牛新生，血乳未分别。声闻如乳，缘觉如酪，菩萨如生熟酥，佛如醍醐。」这是譬喻别教的五味。十信轻毛菩萨如杂血乳。",
 "九住以前断通教见思名为乳，比拟声闻。十住稍深所以比拟辟支佛如酪。十行、十回向如生酥熟酥。十地之初已名为佛，所以如醍醐。《涅槃经》第二十七卷说：「雪山有草名为忍辱，牛若食者即成醍醐。」草譬喻八正道，能修八正道即见佛性，这是譬喻圆教不历四种味即成醍醐。",
