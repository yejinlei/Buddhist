 "『我是佛子。』第二，因为爱惜身命而持戒多；第三，常常自己心中念道：『我是沙门。』第四，持戒常常想胜过其余比丘。」「舍利弗！又能取一盂水放入海中，在海水中搅动捞取，第二天早晨去取原来那盂水而离开。舍利弗尚且能如此，何况佛！目揵连被人殴打却不飞走，是因为不能得神足的缘故。",
 "为什么不能得神足之用呢？因为罪业尚未了毕的缘故。」佛说：「沸迦沙王行到十二门，又回头，也不知道自己身中的六分；能秉持心意修行道法，却不知道身生起意、意生起身，不能分别这些。佛知道他可以度化，便前去与他同宿，王却不知道这就是佛。佛问：『王修行什么法、喜好什么道？』",
 "』（王听了）汗毛直竖。佛为他解释身中之事皆空，他于是便得道；但未能完全断尽，不得阿罗汉。」佛说：「诸位修行者应当知道，意能得道。」佛说：「从前末利满台学经二十四年，得到五言之解、去除垢下而弃离，也不再忧愁。为什么呢？因为他宿命中曾值遇五百佛，全都通达众经，只是闭藏经道、不肯教人。",
 "后来患病二十四天，临死时才悔悟，呼唤人来教授他人。因为有这一福的缘故而懂五言，何况能具足地教人呢，所得福德不可计量（「末利满台」，他本作「朱利盘特」）。」佛说：「从前有位栴那比丘得病，佛派舍利弗前去与他一起分卫乞食。舍利弗趁机问他：『你的眼睛可有所识知吗？",
 "』栴那回答说：『眼无所识，只见色；识生起身、身生起识，病缘对至所以有病，身也不知死。假使身死，地、水、火、风、空都应当灭，只是意识迁移受生罢了。』」「佛派舍利弗行乞经过淫女之家，女子便关门布置，对舍利弗说：『你不与我共行淫欲的话，就应当进入这大火之中。",
 "』舍利弗回答说：『我宁可进入这火中，也不与你共行淫欲；淫欲使人堕入恶道，没有出离之时。』天神便下来救他。佛说：『人只是不能守戒罢了，若能守戒，终究不必担忧被邪道所中。』」佛说：「从前有一位比丘坐禅行道，佛的弟弟难陀饮酒醉了，屡次来到他身边唱歌嬉戏。",
 "比丘对佛说：『我想避开他离开。』佛说：『不必，这难陀如今将要得道迹。』佛便派阿难前往他家，摩诃迦叶跟在后面。舍利弗为他讲经，目揵连示现神足，难陀便生欢喜，当即得到道迹。佛说比丘行道，只要能坚定心意，何必忧愁不得道呢？",
 "比丘听佛说这番话，欢喜意解，便得阿罗汉。」佛的姑母之子名叫须那察多，随侍佛八年，便生起念头：「与我兄弟一同修行，而佛独自端正，有三十二相。」便生出恶意。他跟随在佛身后，扫去佛的足迹，不让人见到佛的相好，又在人群中说佛并无道行，只不过是言语能迎合人的心意罢了。",
 "舍利弗、阿难听了，便忧愁不乐。佛说：「须那察多不是在说我坏话，而是在称扬佛的功德罢了。说他言语迎合人心，是因为人的心意多病、多谄曲的缘故。」佛对舍利弗说：「须那察多不去计较，只是瞋恨罢了。为什么不计较？因为佛有三十二相、光明、神足，只是为了降伏邪道的缘故。",
 "」佛屡次教诲告诫须那察多，而正直真实的话在他看来却像邪恶相对的诅咒，所以他才瞋恨。」佛有一位姑姊，年老时亲手用金缕织成袈裟，拿来奉献给佛。佛不接受。她于是又说：「佛应当哀怜我的缘故，接受它让我得福。」阿难对佛说：「可否为我代她接受它？」佛对阿难说：",
 "「让她拿去布施给众比丘僧吧。我也是比丘僧中的一员，不如布施给众人，后世会成为得度的因缘。今世相见欢喜的人，都是前世的亲属善知识。怎么知道呢？因为相见时心意开解的缘故。」佛说：「世间人相待，只以薄为苦、不以厚为苦。」佛说：「最初侍奉佛的人名叫弥喜，其次名须那察多，其次名阿难。",
 "」佛告诉诸比丘：「我年纪老了，想要一个人来侍奉我。」舍利弗、摩诃迦叶、目揵连等，各自都愿侍奉佛。佛说：「不行。」摩诃迦叶、目揵连因入禅思惟，知道佛想要阿难，便唤阿难说：「你应当侍奉佛。」阿难说：「我不敢侍奉佛，我不能侍奉佛。",
 "」目揵连说：「你不得不侍奉佛。」阿难说：「应当听许我四件事：第一，佛剩余的衣物我不愿接受；第二，佛剩余的饭食我不用；第三，若有人请佛、诸比丘不去，我也不去；第四，佛坐禅思道时，我应能自在出入。」佛说：「很好，听许你所愿。",
 "」于是阿难便侍奉佛，因此唯有阿难能随时问佛。」佛的弟子阿那律、难提、金毘罗三人共同静坐，自己思惟七件事：第一，少欲得道，多欲不得道；第二，知足得道，不知足不得道；第三，精进得道，不精进不得道；第四，守住六衰使其不起得道，不守六衰、放任使其生起者不得道；",
 "第五，自我护持得道，不自我护持不得道；第六，守意得道，不守意不得道；第七，智慧得道，无智慧不得道；共同思惟这七件事。当时他们离佛六十里。佛那时在坐禅，当即知道三人所念，便移意前往、坐在三人面前说：「善哉！善哉！我再告诉你们一件事：",
 "不念恋家欲的得道，念恋家欲的不得道。」于是三人欢喜，当即证得菩萨。」佛对阿难说：「人的眼睛所见，达四十二万由旬。怎么知道呢？日月离地有四十二万由旬，人的眼睛能看见日月，因此知道眼所见之广。十方广远之处，日月有亿亿万倍之多，譬如大海中的沙子，亿亿万倍，不能计量得知。",
 "人所做的善恶殃福，即前后所作的殃福，亿万之数不可再计。一切善恶的关键都在命尽之时：作恶的遇恶处，作善的得善处，殃福都是预先注定的，有所归处也都是预先注定的。有父母、兄弟、妻子得道便止息，不得道就不断绝。」佛说：「调达只教人作福，不教人修行道法；",
 "佛则教人作福、持戒、守意，直到得道才止。调达自己心中生念：『我应当在国王阿阇世那里示现神足，王随从我，其余的人也都当随从我；我便化作一头白象，独自出入宫中。』又化作一个小孩，端正无比，便爬上国王的膝上，国王非常喜爱他。国王见调达所作如此，心里便认为调达胜过佛，国王便听从调达所说的话，王的官吏、人民以及未得道的沙门，全都随国王到调达那里问事。",
 "调达便到佛那里说：『佛年纪老了，可以不必再教导诸弟子了。』调达便呼唤舍利弗离开，以及诸沙门离开。调达愚痴贪心、有这种恶意，因此失去了神足。」佛说：「愚痴之人所作颠倒，不是诸佛法。调达自己心中念道：『我应当飞去，人们见我飞，都会随顺侍奉我。",
 "』于是想飞走，却不能再飞了。调达不能自己觉察已失神足之时，正好有位行平等心的婆罗门，从第一天上下来告诉舍利弗：『调达已经失去神足了。』」佛对舍利弗说：「调达想要唤你同去，只会让他罪上加罪。」佛对那位天神说：「调达未得神足之时，我就知道他将会失去它。",
 "何况到如今呢？」佛说：「人不应当贪，调达只因贪的缘故，失去了神足。」佛说：「阿罗汉有两类：一类名叫舍沫，只忧念自身得道，便想度世而去；第二类随护众生，都能度脱。」佛与阿罗汉同行三十七品经，譬如灯火，佛计较了知有几种事，知道它的本末，守持而灭除它；",
 "阿罗汉不计较本末，直接灭除它。佛譬如顺着一棵树从根到梢，分别了知；阿罗汉的修行，譬如从未端到根本。从本到末的人，计较本空；不知空的人，不得道。」佛说：「阿罗汉有盛阴而没有五阴的执著，所有的都显现，只是不执著罢了；有色、痛痒、思想、识，而无生死。",
 "」佛说：「阿罗汉有所作为而默然，因为得阿罗汉有三种相：第一，不再犯身、口、意；第二，三毒灭尽；第三，衣服饮食不用做得好，只为灭除饥寒之意。有这三种因缘，便能变化自在，心意不执著；一旦衰失，便不得自在。」佛说：「心意只应当分别六衰，不应当执著，执著便不得道。",
 "」佛说：「阿罗汉飞行时有两种因缘，令人看不见：第一，怕人见了便多作供养；第二，怕恶人嫉妒他。」佛说：「示现神足又有两种福：第一，人见他飞行，便精进念道；第二，从人受施，使人得大福之用；所以示现神足。因为心意欢喜的缘故便得大福。",
 "」佛说：「有位罗汉名叫憍梵钵，已得阿罗汉道，却反而像牛一样反刍。」弟子问佛：「为什么？」佛说：「这位比丘前世宿命之时，七百世作牛，今世得道，余习未尽的缘故。」佛对比丘说：「应当忆念身无常。」有一位比丘当即回答佛说：",
 "「我忆念无常，人在世间最多大约五十岁。」佛说：「不要说这种话。」又有一位比丘说：「大约三十岁。」佛又说：「不要说这种话。」又有一位比丘说：「大约十岁。」佛说：「不要说这种话。」又有一位比丘说：「大约一岁。」佛又说：",
 "「不要说这种话。」又有一位比丘说：「大约一个月。」佛又说：「不要说这种话。」又有一位比丘说：「大约一天。」佛又说：「不要说这种话。」又有一位比丘说：「大约一个时辰。」佛又说：「不要说这种话。」又有一位比丘说：「大约一呼一吸之间。",
 "」佛说：「正是如此。」佛说：「呼气出去不再回来，就属于后世了；人的性命只在呼吸之间罢了。」佛对诸比丘说：「聚会共坐之时，只应当说法的语言；不能说法的人就赶快闭目静声，守意善听，可以由此得道。」诸比丘听佛说这番话，欢喜意解，当即得阿罗汉道。",
 "佛说：「比丘进入他人的屋舍时，应当像手在空中无所挂碍一样，心意也无所执著；耳朵听到可意之声是执著，听到不可意之声也是执著。」有一位比丘对佛说：「可意与不可意都是执著，那怎样才能得道呢？」佛说：「比丘心意开解，悟空而都无所执著，这才相应于菩萨行。」诸比丘听了这番话，都欢喜踊跃，当即得无生法忍。",
 "佛说：「有一位比丘在山中静坐，叹息。有一个人问比丘：『你修行道法，为什么叹息？』比丘回答说：『我在地狱中时，受五毒极为痛苦；如今得生为人，又能见到佛的经戒，却还不能得道，怕死后又再堕入那恶道之中，所以叹息啊！』作比丘的既忧念俗人，又忧念经戒，也忧念自身，善的心意不能常得。",
 "或有因缘来时，便念恋妻子、钱财，这就是堕入恶道。」佛说：「有一位比丘到优婆夷家乞食，顺便为她讲经。优婆夷便长跪流泪；比丘讲经讲到半夜，优婆夷长跪不起。比丘说：『我出行讲经，从未见过有人精进到这般地步。』优婆夷回答说：",
 "『我家有一头驴，叫到半夜便死了，所以流泪罢了。』」佛说：「人讲经不在于多，只问能否解慧罢了。」有一位比丘听佛说这件事，便去问佛说：「请为我说一个要法，让我得道。」佛说：「不是你的东西不要取，是你的东西便取。」",
 "于是，比丘便自己思惟：「天下万物都不是我所有的，唯有善才是自家之物。」于是，比丘便对佛说：「我已解悟。」佛说：「解悟了这个便是道了。」当时有一位比丘听佛说这番话，便去问佛：「舍利弗得到这个了吗？」佛说：「舍利弗完全得到。",
 "」比丘说：「舍利弗为什么骂我，又拿袈裟拂我的脸？」佛说：「叫舍利弗来问他。」舍利弗说：「我没有恶意。之所以骂你，是想让你修忍辱；之所以拿袈裟拂脸，是想让你的眼、耳、鼻、口清净的缘故。」佛对比丘说：「这是舍利弗以善巧方便所作的。",
 "」于是比丘欢喜，当即得阿罗汉道。」佛说：「从前有一个人去责难比丘说：『人死时识、念、思想、所知都灭，修行道法得定意时所知也灭，这有什么差别呢？』比丘回答说：『都灭，但人死命尽而神不灭，随所行之业受生，只是微细而不可便见；所得不同——行善的升天，作恶的入渊，这就是差别。",
 "』」佛说：「有一位比丘到优婆夷家乞食，见她容貌端正美好，比丘便生起邪念，随之而起。优婆夷便取饭具给他，比丘却舍弃而去：『我不应受人的布施。』优婆夷便对他说：『你已有悔意，可以接受布施。』优婆夷再三相告，比丘便接受了。」",
 "佛说：「譬如人有恶便觉察，罪即消灭。比丘受施，没有罪。」佛告诉诸弟子：「能计较观空、制伏心意，如弹指之顷，即可得道。」佛说：「有一位比丘打坐得了定意。有一位优婆塞见他坐的地方不平，便牵他起来，指示他安稳之处。这位优婆塞后来五百劫都不得安隐。",
 "为什么呢？因为断了他道念的缘故。」佛告诉诸弟子：「有人在讲经时，千万不要中途打断，打断讲经的罪重得不可计量。」佛说：「有比丘修行道法得到初禅，自己说：『我得道迹；初禅之福，上生第七天上、寿一劫；得二禅，自己计较以为得斯陀含；第三禅之福，上生十五天、寿八劫；",
 "得四禅，自己计较以为我得阿罗汉。如今我为什么不能生到第十九天上、寿十六劫？』说完这话，便说：『佛是两舌妄语罢了。』当即从天上堕入地狱之中，不知不觉失了天上的寿命，便受地狱之罪。譬如世间人得到珍宝，一日之间被大火燃起全部烧毁；人生起恶意，便会横烧善意（「斯陀含」以下，诸本都脱落了生天寿劫与得三禅等文字）。",
 "」佛说：「人的善恶相随，没有能够解脱的办法，唯有得道才能离俗罢了。」佛说：「日中之后不食有五种福：第一，少淫；第二，少睡；第三，得一心；第四，没有下风；第五，身体安隐也不生病。所以，沙门、道士知道这福而不食。",
 "洗澡漱口，有三种因缘：第一，是怕指甲下有垢的缘故；第二，抓痒随合心意；第三，是杀跳蚤蚊虫的缘故；也是想让心意清净、无欲，又不污染经法。这些只是能除去外垢，心中念恶却不能除去。作学道之人，第一应当以清净心为本，心是法的根本，心正则行正，行正则合于道。",
 "」佛说：「从前有位沙弥与师父同行，见地上有金子，便悄悄取起来。他对师父说：『快走，这地方无人，很可怕。』师父说：『只因有金子的缘故，才让你害怕罢了。』于是弃金而去，便不再害怕。弟子便向师父行礼说：『我愚痴、无所知，如今已经丢弃，便不再为此而恐惧。",
 "』」佛告诉诸弟子：「学道之人贪求道法如沙弥贪求金子一样，何必忧愁不得道！」佛说：「有比丘学道，跟从师父受持经法却不精进。师父教他取几升牛马粪便来烧，烧到天黑也烧不尽。师父取来大石，拿到地狱中，用火烧它当即变成灰。弟子大惊，长跪问师父：『这是什么火？",
