 "结集大乘，召集诸菩萨及大罗汉无量无边，各自称说某甲经「我从佛闻」。须菩提说：金刚般若，我从佛闻。以此文为证，故知如此。"
 "然而佛法说无我，为何称「我」？解释说：理虽无我，而不坏假名；若不言「我」，则也无从说「闻」，",

 "教化之道便会断绝。所以……借「我」而说「我」，如人以金换铜，买卖本自如此，人不会见笑；世俗谛中假名说「我」，"
 "智者不以为怪。闻者耳根不坏，声音在可闻之境，意欲作闻之相，因缘和合，应当说是耳闻，为何说我闻？解释说：虽无神主，",

