 "一、就佛而解，二、就理而解。就佛解者：说明三世诸佛所说无异，故名为「如」；因同说之故，得名为「是」。正因诸佛同说，所以可信。"
 "就理解者：说明诸法实相古今不异，故名为「如」；因如实相而说，得名为「是」。既是如理之言，不增不减，",

 "决定可信，所以说「如是」。其次是「我闻」，解释能闻之人。应当问：其中称「我」的是谁？又佛法说无我，为何称我？"
 "又本当是耳闻，为何说我闻？解释说：其中称「我」者，若就别传而言，则是须菩提；若就通途而言，是阿难自称我闻。然而如来所说，",

 "有三乘法藏，传持法藏之人也有三种：一名阿难陀，此方名为欢喜，持小乘法藏；二名阿难陀拔陀，此方名为欢喜贤，持中乘法藏；"
