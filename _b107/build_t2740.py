 "「汝于三乘当何悉求」，又……若以小乘化我，即为声闻等。这里也是如此：因法不同，所以立三名。此义出自《阇王忏悔经》。"
 "这三人之中，前二人有亲闻的部分，也有传闻的部分，所以《千结集》中，阿难升座说偈云：「佛初说法时，尔时我不见。」",

 "「如是展转闻：佛游波罗奈，为五比丘说四谛法轮。」所以不能说前二人都是亲闻。第三阿难，则可说是常闻。"
 "所以《涅槃经》说：「阿难多闻士，自然能解了，是常及无常。」或称他得觉性三昧，一切皆常闻。由此可知，是阿难自称「我」。"
