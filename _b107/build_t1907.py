 "为什么呢？「由彼故空」，那（遍计）实是无；「于此而空」，此（依他、圆成）实是有；由此道理才可说为空。若说一切都无所有，那么在何处、是何者、由何而名为空呢？也不应说「由此于此」即说为空；所以名为恶取空者。」乃至广说。暂且止住这些旁论，还归本宗，持犯轻重的略相已如前说。",
 "其次第二、说明持犯的浅深，是承前所说的赞毁之戒，以显示持犯浅深之相。如《多罗戒本》说：「常代众生受加毁辱，恶事自向己，好事与他人。若自赞扬己德，隐藏他人好事，令他受毁辱者，是为波罗夷罪。」依这一段文，作浅深二解。",
 "怎么说呢？下等之士听了，只齐于言句而取其解，认为自毁赞他必定是福业，自赞毁他定为犯罪。如此一向随言取义，想要修那福，福行少而罪业多；想要舍那罪，却除一罪而反失三福，这就叫做浅识持犯的过失。上等之士听了则掬取解其意趣，举一隅便以三隅类推而变通，就一段文每每用四句来判，因此审察辨别，无所混淆。",
 "无福而被遗弃、无罪而被辨说，这就叫做深解持犯之德。所谓用四句来判：或有自毁赞他是福、自赞毁他是罪；或有自毁赞他是罪、自赞毁他是福；或有或者毁赞、或者赞毁，或是罪、或是福；或有非毁赞、非赞毁，或是福、或是罪。第一句：如有人深愍众生受辱，想把他所受的辱引向自己，把自己所应受的荣推给他人，此意的自毁赞他，是福；",
 "若想要自己领受其荣、令他受辱，此意的自赞毁他，是罪。第二句：如知道时世风俗所习，多憎恶自赞毁他的人，每每敬重自谦扬他的人。又知道毁谤对方，对方必定也诋毁我；我若称赞他，他也会回赞我。由此知解的缘故，巧求自高，而自毁赞他，这就是重罪。",
