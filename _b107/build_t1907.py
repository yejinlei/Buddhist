 "又有一类人，禀性质直，想要开导世间众人，使之识善别恶、舍罪修福。因这志愿的缘故，直言无所偏邪，见自己的恶就必定诋毁，闻他人的善就随即赞叹，觉察自己的德就仍加褒扬，知道对方的罪就径直贬斥。前者（诳伪之人）的毁赞扬抑，直是诳谄之罪；后者（质直之士）的呰叹褒贬，都是忠直之福。",
 "第四句：如有高士，天性弘懿，放旷心神、包含质朴，不知其端倪，混同祸福而归于一体，忘却彼我而为无二，其心神常乐于游于此处，所以也不自毁赞他，也不自扬抑彼。又有下愚之人禀性钝朴，不知是非、难以分别菽麦，不识善之为善、不解恶之为恶，其意常昏，因忘却憎爱的缘故，也无自谦美他，也无自褒贬他。后者是下愚浑钝之罪，前者是上智纯朴之福。",
 "这就是用四句来判别罪福。依前两句，则福业变作重患，罪行反成大善；寻后两句，则诳语与忠谈无别，上智与下愚同迹。由此可知，行者持犯的要领，只应微细省察自己的得失，不可动辄评判他人的德与患，持犯浅深的意趣就是如此。第三、明究竟持犯：虽依如前所说的法门，能识轻重的性、兼知浅深之状，然而对戒相不能如实解了，对罪与非罪未能离于二边的人，便不能究竟持戒而无犯，不能趣向清净戒波罗蜜。",
 "原因何在呢？戒不自己生起，必定依托众缘，所以决定没有自相。即缘不是戒，离缘也没有戒，除去即、除去离，也得不到中间。如此求戒，永远不是有，可以说因自性不成就而依托众缘；但也不是没有戒，不像兔角那样没有因缘。如说戒相，罪相也是这样；如戒、罪之相，人相也是这样。",
 "若在这其中，依据「不是有」而见为全都无的人，虽自谓无犯，却永远失去戒，因为他诽拨戒的唯事之相。又在这其中，依据「不无」而计执为有（戒）的人，虽说是能持，然而持即是犯，因为他违逆戒的如实之相。菩萨修戒则不是这样：虽不计执有能持、所持，却不诽拨戒的唯事，所以终究没有失戒的大过。",
 "虽不见无罪与非罪，却不违逆戒的实相，所以永离犯戒的细罪。由此以巧便深智的方便，永远忘却三轮、不堕二边，方才趣向具足戒波罗蜜。如经中说：「罪、非罪不可得故，应具足戒波罗蜜。」《戒本》说：「戒光从口出，有缘、非无因，非色、非心、非有、非无、非因果法，诸佛之本原，菩萨之根本。",
 "」这里所说戒光，是为了显示戒与光无二无别，因为明净与杂染同一味的缘故，所以借助戒光来显示戒的实相。戒无自性，必定藉于他缘，所以叫有缘。有缘这话，不是依据「是有」而说，而是直接显示不无其所从之因，所以说非无因。这非无因的戒性，不是质碍、也不是缘虑，所以说非色非心。",
 "虽非色心，而离开色心，又永不可得。虽不可得，却并非无戒，所以说非有非无。虽非无戒，而离果无因、离因无果，所以说非因果法。戒作为因性虽不可得，而诸佛之果必藉戒因，所以说诸佛的本原；戒作为果性虽不可得，而戒须藉菩提心之因，所以说菩萨的根本。",
 "问：戒相如此，甚深难解，理解尚且困难，何况修行？由此可知，如前所说的行相，唯是大地菩萨所修，不关新发意（初发心）之人所行。答：经中有正答，如你所问之言：菩萨从初发意以来，常行无所得法。因无所得法，所以修布施、持戒，乃至因无所得法，所以修智慧。",
 "这答的意思是：假使那行，因未曾修而难以行持。若现在不修，因现在不习，将来也不修，如此久久，就更增其难。所以要令其从初发心起便仰习其难，习行渐渐增长，转而成为易行，这就是新行发趣的大意。究竟持犯，略明如此。仰依圣典了义之文，粗述戒藏开要之门，普为法界燃一盏灯，愿将此传灯周遍十方。",
