 "而无有所不至之处；法无彼此，能显殊方，实则无去无来，而相无不现，所以说「能至十方」。「劝发咨请」「受持」者，是正兴对治、摄教诠相应；行摄胜进之法，在己永固不迁，所以说「受持」。「法轮」者，是实相真诠、显斑缘因。「常以大心」者，是中实显用、旷周法界。",
 "「供养佛」者，是秘密缘起、妙寂解脱，充满萨婆若海，与圆觉之道相应无二，所以说「供养佛」。此明思、修二惠。「常能修习」者，是第三次明业坚固，其中有三：初总学三业；第二从「其身普示」以下别释三业；第三从「一切菩萨」以下总结三业。",
 "「所行事业」者，是备集而明其为一；「其身普示」者，是体无不斑现；「其音遍国」者，是教无不障；「明见三世」者，是自体真明无不朗照；「具足修集」者，是行无不集、德无不达。「如是诸菩萨功德」者，是第四显明广坚固。「无量」者，穷尽深实际。",
 "「无边」者，旷周法界；「于无数劫说不能尽」者，菩萨行德广大，非证不能宣说，所以说「说不能尽」。「其名曰」以下，其次解第。德者之名有三种解释：一是依化教，随众生所宜闻的相应或不相应者，如说于正语中安置随语之义，如以想断结，想实不能断结。",
 "要以惠才能断，如佛说但观想能除贪欲，是于正义中安置随义之语，如以惠断烦恼，这才是正义之语。此菩萨之名也是这样，如观世音菩萨，随善众生而彰其德号，而菩萨的实德不必正如此，此明语中置义；然而即菩萨实德，此明正义语。二者，若依理教，是依义之语。",
 "知味、衣味，知义寄事，表义随相，知实以彰菩萨实德之故。三者，若依行教，意欲明人即显示于法，闻者解法也就是知人之意欲、明法晓示；于人闻者解人，也就知法。如同维摩诘名为无垢称，即知不可思议无障碍解脱法门；但闻普贤菩萨，即知法界行法门。",
 "文殊师利、天女等，都是妙惠行之法门；金刚藏等，也是要明菩萨之行，皆广大如法界、究竟如虚空、平等无二，显示自体真实圆奥之法门。所以称金刚藏等菩萨之名各不相同者，解云：大判有五种：一是因缘立名，如《菩陀波论》中菩萨名为常啼菩萨。",
 "他本作小儿时，父母常以萨陀波论称之；今得菩萨，常哀伤众生，所以说「常啼菩萨」。二者本修行法门，如弥勒菩萨：昔为国王时，到僧伽蓝中，见诸比丘坐禅皆有光明，唯有其中一比丘光明独胜，即问比丘：修何三昧，光明殊胜超过众比丘？",
 "比丘答言：我修慈三昧藏，这是众善之本，所以殊胜。国王因此即发愿：愿我未来世中常修慈三昧，今日得佛，即名「慈氏」。又如燃灯佛，昔作国王之女，在高楼上见一比丘到里巷中乞油，即问比丘乞油何为？比丘言：我供佛。因此即发愿。",
 "愿未来常以灯明供佛，今日得佛，号曰定光；若据本因，名为燃灯。三者自利修入、对治不同；四者德摄益、随化缘差别，如多能之匠随用立名；五者自体法门，皆体会法界，以彰因行不同。德穷海奥，名金刚藏菩萨。",
 "利润无穷，名曰宝藏，如宝之利可用；自体因行入法界，如莲华藏；妄想熏修，明其断离，不以断为胜要，不断烦恼而入涅槃之性，离于非缘之饰，故名「胜藏」。所以《维摩经》说：譬如胜登乃可为勇；如是菩萨兼除一切生老病死，是菩萨之谓。",
 "此菩萨于一切烦恼违烦而得无障碍，所以说为「胜」。「曰藏」者，无为之行能除生死之暗，所以说「曰藏」。「圆藏」者，有为缘集、不舍世间之行，即暗而明，故名「圆藏」。「净圆藏」者，自体世间即暗而常明，于净中胜出，所以说「净圆藏」。「照一切世间庄严藏」者：",
 "自体之内明、圆净大智，尔炎殊流，所以说「照一切世间」；巧妙殊特，所以说「庄严」；德能出生，所以说「庄严」，故名之为「藏」。自体因行，名「菩萨」。「解脱月菩萨」者，是解行终心之菩萨，尚未成实证，是教所被之人请法发起之首，故独标其名。",
 "「如是菩萨」者，是第三大段，其次明德者之数。「无量」者，是位穷有际；「无边」者，是行周法界；「阿僧祇」者，是出于……（缺字）之限；「不可思议」者，明体非分别、离于分别；「不可称」者，释无量深重不可称；「不可量」者，释无边广大不可量。",
 "「无有分齐」者，……（缺字）阿僧祇不可说者，释体非分别、非一一；「不可说」者，释离于分别、明非异异。追寻其义未必如此。如《华严经·阿僧祇品》说：尔时心王菩萨问：云何阿僧祇、不可量、无分齐、无周边、不可数、不可称量、不可思议、不可说？",
 "佛告心王菩萨言：百千百千为一拘梨，拘梨拘梨为一不变，不变不变名一那由他，那由他那由他为一鞞婆逻，鞞婆逻鞞婆逻名一作，作作名一胜，来来名一胜，胜胜名一复次，复次复次名一阿婆罗，乃至受受等有一百重之数。",
 "然后才到阿僧祇，阿僧祇之后又有二十四重之数。这都是诸佛菩萨法界行用之法，乃是一行之旷周，岂可用这些相状来解释、说其无有行数之相呢？若据起相成义，也无妨碍。所以世尊为心王菩萨以偈颂说：不可言说不可说，不可言说诸劫中。",
 "说不可说不可尽，此明自体法门。不可言说微尘中，悉有众生不可说，皆共赞叹普贤之德，犹尚不能令其穷尽，此明行用德备之法门。于彼一一毛道中，有不可说清净佛刹，以不可说庄严之具，庄严彼彼诸佛刹，明理融缘起、真性集用之法门。",
 "于彼一一异色中，放妙光明不可说；于彼一一光明中，出宝莲华不可说，此明智慧法门。于彼一一宝莲华中，有……（缺字）宝叶不可说；于彼一一宝华叶中，有微妙色不可说，此明……（缺字）因行法门。金刚宝藏如须弥，清净具足而庄严。",
 "……（缺字）一一须弥中，有不可说不可说，明功德法门；于彼一一梵音中，有……（缺字）可说清净轮；于彼一一法轮中，是不可说修多罗，明真诠法门。此皆明法界行用之差别相状。以上世尊以长行答心王菩萨，据修对治、行集在缘之故，分数之相差别，故有百千等数。",
 "下面以偈颂作答，是据自体法界法门、行用广大旷周法界之故，所以说有不可说不可说等，岂可用名相来等待它呢？若依三教：此菩萨之数，若据化教，则直是其事、无所表彰；若依行教，则悉是菩萨自体法门之法。「种种佛国土」者，有三种世间来，所以说「种种」。",
 "「集」者，菩萨行备、圆德相著，所以说「集」。「金刚藏菩萨而为上首」有二义：一是位穷行标、德盖大众，故为之上首；二是一切菩萨行德之体实，所以说为之上首。又为之上首者，是宗旨兴发、事由其人之故，故标之而为说法；显化益之时，彰之于初，所以说「金刚藏菩萨而为上首」。（末有「宝藏写」字样，为写经人之题记。）",
