 "第三、弥勒一人，名为「摄德成因相」，即摄前面的行德作为证入的正因，与前面的成证不同，所以开出二位。"
 "第四、后文殊一人，名为「智照无二相」，即行成究竟、朗悟在怀，照见前面的解行唯一实大智，更没有前后明昧等差别。",

 "第五、普贤一人，名为「显因广大相」，即始觉与大智现前，遍周法界，没有一处不到、无不普遍包容摄入。"
 "第四、境智圆融，又就前面诸人中总束为二：文殊是能证之大智，即前面的解、行等；二是普贤，是所证之法界，即前面所信、所入的。",

 "为什么呢？因为文殊当于般若位，普贤当于法界门。何以见得？"
 "师说「三藏（法师）言：有经作如是说。又考案此经中的意义、文势，深深有此意。"
 "又古来尊德既然判定后文殊名为智照无二相，所以知道前面的诸位善知识总归是后文殊一人」。"
 "所以后文说「善财还经一百一十城，又回到文殊」；",

 "说的就是这个意思。又文中说「文殊师利教我相算等法」，又说「长者说：文殊师利忆念力的缘故」等，"
 "又后文说「善男子！文殊师利是你的善知识，能令你得生如来家，长养善根、积功德聚，乃至满足大愿、净诸法门，都是由于文殊师利的威神力」；",

 "等。智既已圆满、得以证得法界，所以因行圆满，普贤居于后。"
 "所以后文说「我于一一毛孔中现佛境界，谛观察」等，又说「你且观我清净法身」等。"
 "解释说：既然令观清净法身，可知善财见普贤，就是证得法界。"
 "又总束为一，即境与智冥然契合、没有差别，所以后文殊更没有身相。",

 "为什么这样呢？因为最初见文殊，就是善财信心的开始；后来不见，就是善财智满的终了；中间诸位善知识都是善财修行的次第。"
 "因为善财障尽惑除、从未起念，所以返照自心，唯有初心，并无别异。后来不见文殊，含有所要思惟之意。"
 "所以经中说「从文殊师利智慧所起」；",

 "等，又论中说「始觉同本觉，无始觉之异」，说的就是这个。"
 "第五、泯同果海，是说因行圆满、没入果海之中，离始离终，圆满具足众德，亡言绝虑，唯与证相应。"
 "如此卷展无碍、同时随说为门，终究没有前后，所以卷展有这种无碍，难以表述。",

 "应当依文去思惟。所以经中说「如是真佛子，甚深微妙义，众生欲思量，迷乱心发狂」，说的就是这个。"
 "第四、问答取文，也有二：一是问答会违，二是结劝修学。"
 "第一、问答会违：问：前面既然说摩耶会合前面的诸缘为其真实，何以会合之后仍有十人不同呢？",

 "答：会合之后仍有十人，这是显示缘起实德借「十」来表无尽。"
 "为什么呢？因为不离摩耶，都是摩耶的实德，即寄于前面五位、三世界同修而至于究竟。"
 "所以经中说「我是一切诸佛之母，一切诸佛皆从我生」等。"
 "也可以表示诸位即异而融熔，卷舒无碍，所以一一诸位即辨成佛，用意存于此。",

 "问：摩耶无体，只是会合前面诸位而成身。其余诸人也是如此，为何不全具十呢？"
 "答：只就摩耶中具此十人来说，即是前面一一一人都具足。为什么呢？因为摩耶就是把前面诸人总合为一身。"
 "因为一一一人即是摩耶，摩耶即是一一一人，所以如今独说摩耶中具足，有意如此。",

 "问：摩耶即是前面的诸人，既说此具足则余者也具足；那么也可以说诸人即是后面的摩耶，为何不说是前具后不具？"
 "答：摩耶是总，余者是别，只要总具足，别也就具足。为什么呢？别未究竟，总则究竟。"
 "若未究竟，别的无从可别，怎么能具足呢。所以摩耶中具足，即是余人中亦具足。",

 "问：八会之中，为何升天四会都说「不起菩提树及自会而升其余」等，为何人中三会不说「不起此而升彼」呢？"
 "答：这有二意，一是据解、二是约行。初「解」中又三：一是近，二是远，三是总。"
 "初、近，因为人中三处同在人间接，就地而言没有差异，法尔相摄。",

 "这不待言说，所以不说「不起此而升彼」。"
 "二、远，因为人、天类别不同、又悬隔有别，相摄难以了知，所以带着前面而说明赴向后面，这就是缘起无碍、诸会同时。"
 "三、总，以总摄别，别在总中，升降虽然不同，都说不离觉树。互相融遍的门自有差别，虽去至彼中却恒在此处。",

 "为的是表显、生起众生的理解，所以说「不起此而升彼」。"
 "二、就「行」而言又有二：一是申明义理，二是解释防难。"
 "初者，升天等会据「解」而言，是托处所说，解满则行、证没有差别，所以后面二会不加论说。又不与人天之类相同，有意如此。"
 "二者，因为「信」自己并无正对的位次，所以在两处都不说。",

 "问：上面说善财到了后文殊即说智满返照、唯有初心更无异者，何以经中明说善财经历诸位呢？"
 "答：经历诸位有二种。一是约「教」的行布而言，所以有次第位次、节级不同，善财历位据此而论；"
 "二是约「义」而言，因为大缘起法界同时具足、没有次位前后等，那么善财一生就依此而说。",

 "如今以两义合辨，则历位不离初心、一生未曾移动多劫，经所明的具备此意。"
 "所以经中说「一念即无量劫，无量劫即一念」等。"
 "如今若以教摄义而言，这就名为「同教一乘」；若以义摄教而言，这就名为「别教一乘」。"
 "然而善财历位不离初心，是依据此而说的。",

 "问：何以末后善知识更没有「指后」及「结说」等呢？"
 "答：结会文殊，因行已究竟，指归后位即是证入融通，见一即一切、理体圆满，所以更没有指后结说。"
 "所以经中说「善财于普贤菩萨相好、支节、诸毛孔中，见不可说不可说世界海诸佛充满，一一如来以不可说不可说大菩萨众作为眷属」；",

 "等。第二、结劝修学，上面所述此经中的少分意趣，如同以管窥天；其余态势多端，不知其涯际。"
 "尽未来劫穷究，誓要修行究竟，唯愿舍身受身、常生此会。"
 "如善财心中念：一切世界经历终尽而起火，乃至六天全被烧尽，也定要入此劫火中去求法。"
 "誓愿如铠甲，心念真实。若有信心归向、修学，速证菩提，随分见闻，必成坚固种子，应当发起大欢喜，自庆难得遭遇。",

 "所以经中说「善财，你应发起大欢喜，不久当得大果报。菩萨于无量劫修行，你今一生全都具得。"
