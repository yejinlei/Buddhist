"【破斋堕饿鬼地狱】世尊，唯愿如来为我解说，破斋者堕何处地狱？佛告迦叶：破斋者堕饿鬼地狱，其中饿鬼身长五百由旬，其咽如针，头如太山，手如龙爪，朝食三千，暮食八百，一呼三万驱。破斋之人入此地狱，受其大苦。复离此地狱，绕其太山，山犹如绯色驱。【义解】此段明「破斋」（破坏斋戒）者堕饿鬼地狱之相：身长咽细、头大如太山、手如龙爪，虽食多而不得饱。饿鬼为六道之一，为悭贪破戒之报。",

