"【食鸡肉之报】食鸡肉者当堕地狱，三人共偿，倍半相迎，同入地狱。迦叶菩萨白佛言：世尊，实如圣教，实如圣教。迦叶菩萨白佛言：世尊，唯愿如来为我解说，不饮酒、不食肉者得几所福？佛告迦叶：假使有人以象、马、牛、羊、琉璃、珍宝、璎珞、国城、妻子持用布施。【义解】此段先明食鸡肉者共偿入狱之报，继而转入「不饮酒、不食肉者得几许福」之问——下段即以此问展开福德校量的层层比较。为便于统摄，此段小标题取「食鸡肉之报」。",

