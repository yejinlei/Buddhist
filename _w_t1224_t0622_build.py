def pieces_with_quote_state(seg, in_quote):
    pieces = []
    cur_is_quote = in_quote
    cur = ""
    for ch in seg:
        if ch == "「":
            if cur:
                pieces.append((cur_is_quote, cur)); cur = ""
            cur_is_quote = True
            cur = "「"
        elif ch == "」":
            if cur_is_quote:
                cur += "」"
                pieces.append((True, cur)); cur = ""
                cur_is_quote = False
            else:
                if cur:
                    pieces.append((False, cur)); cur = ""
                pieces.append((True, "」"))
                cur = ""
                cur_is_quote = False
        else:
            cur += ch
    if cur:
        pieces.append((cur_is_quote, cur))
    return pieces, cur_is_quote


def build(tid, titles, yijie):
    src = json.load(open(os.path.join(ROOT, "data/baihua-tasks", tid + ".json"), encoding="utf-8"))
    src_tr = src["translations"]
    assert len(src_tr) == len(titles) == len(yijie), (tid, len(src_tr), len(titles), len(yijie))
    out_tr = []
    in_quote = False
    for i, seg in enumerate(src_tr):
        op = seg["original_preview"]
        if tid == "t1224":
            ps, in_quote = pieces_with_quote_state(op, in_quote)
            body = "".join(t if q else cc.convert(t).replace("\n", "") for q, t in ps)
        else:
            body = cc.convert(op).replace("\n", "")
        if tid == "t1224":
            import re as _re
            body = _re.sub(r'」(?=[\u4e00-\u9fff])', '」。', body)
        if tid == "t0622" and i == 0:
            body = body.replace("安世高译闻如是：", "安世高译。闻如是：").replace("一时佛游", "一时，佛游", 1)
        modern = "【" + titles[i] + "】" + body + "【义解】" + yijie[i]
        out_tr.append({
            "section": titles[i],
            "original_preview": op,
            "modern": modern,
        })
    out = {
        "id": src["id"],
        "title": src["title"],
        "translator": src["translator"],
        "mode": src["mode"],
        "intro": INTRO[tid],
        "sutraPath": "../sutras/" + tid + ".json",
        "translations": out_tr,
    }
    dst = os.path.join(ROOT, "data/modern-translation", tid + ".json")
    with open(dst, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    # stats
    print("===", tid, "segs", len(out_tr))
    print("intro len", len(INTRO[tid]))
    bad = []
    for i, t in enumerate(out_tr):
        m = t["modern"]
        yl = len(m.split("【义解】", 1)[1]) if "【义解】" in m else 0
        if not m.startswith("【") or "【义解】" not in m or m.endswith("【义解】") or m.rstrip().endswith("【义解】"):
            bad.append(("struct", i))
        if not (40 <= yl <= 160):
            bad.append(("yijie_len", i, yl))
        if t["section"] != titles[i]:
            bad.append(("section", i))
        if '"' in m or "'" in m:
            bad.append(("quote", i))
    print("bad:", bad)


