# ---------- 工具：佛号/真言段判定 ----------
def is_nanwu_block(t):
    return t.count("南無") >= 3

def is_mantra_block(t):
    # 含大量梵咒特征字
    mantra_chars = set("唵吽嚩曩怛囉拏鉢哆娑賀唧嚕彌枳帝惹隷尼野麼曳訶伽俱佉左陵誐馱引二合")
    hits = sum(1 for c in t if c in mantra_chars)
    if hits / max(len(t),1) > 0.25 and ("唵" in t or "曩謨" in t or "娑嚩" in t):
        return True
    # 出现真言特征标记：「（引）」「（二合）」
    if "（引）" in t and ("娑嚩" in t or "唵" in t or "曩謨" in t):
        return True
    if "（二合）" in t and ("娑嚩" in t or "唵" in t or "曩謨" in t) and t.count("。") <= 2:
        return True
    return False

