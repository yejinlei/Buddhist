def build_modern(sid, data, hand_map):
    title = data["title"]
    trans = data["translations"]
    total = len(trans)
    for i,item in enumerate(trans):
        orig = item["original_preview"]
        if i in hand_map:
            item["modern"] = hand_map[i]
            continue
        if is_nanwu_block(orig):
            item["modern"] = f"【圣号持诵·第{i+1}段】【义解】以下为佛菩萨圣号，名号功德不可思议，应恭敬称念，原文照录：\n{orig.strip()}"
        elif is_mantra_block(orig):
            item["modern"] = f"【真言陀罗尼·第{i+1}段】【义解】以下为陀罗尼真言，真言为佛秘密语，总持无量功德，不可翻译，依原文持诵：\n{orig.strip()}"
        else:
            # 通用白话
            if i == 0:
                small_title = "【法会缘起·译经题记】"
                yi = "【义解】这一段交代译经因缘与法会发起："
