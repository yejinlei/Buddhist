# ============ 通用文白转换（轻量润色，保留所有固定术语） ============
# 译例：不把所有"曰"硬换成"说"，而是根据上下文自然化；故事叙述部分改为白话流畅表达；
# 对话保留"某某说""答道""问道""说道"等口语化形式；术语全部保留。

TRANSLATOR_PREFIX = re.compile(r"^(吳|吴|晉|晋|東晉|东晋|西晉|西晋|失譯|失译|後漢|后汉|宋|梁|唐|姚秦|元魏|高齊|高齐|陳|陈|隋)[\s\S]{0,20}(譯|译)\s*$")

# 咒文/陀罗尼：以梵文音写为主、夹杂音注的段落照录
def is_mantra(text):
    # 特征：含有多个音注术语、且无语助词
    notes = sum(1 for m in ["二合","引","反切","半音","上声","去声","长声","平声","短声","引","二","半"] if m in text)
    chinese_chars = len(re.findall(r'[\u4e00-\u9fff]', text))
    # 如果含大量音注或较短且含咒文关键词，判为咒语
    if any(k in text for k in ["陀羅尼","陀罗尼","呪曰","咒曰","眞言","真言"]):
        return True
    return False

def wenyan_to_baihua(text):
    """文言文→白话（保留佛教术语）"""
    if not text.strip():
        return text
    # 如果是咒语/陀罗尼，照录
    if is_mantra(text) and len(text) < 200:
        return text
    # 阙文□保留
    # 译者题注行保留
    s = text
    # 常见句式白话化（不替换术语）
    repl = [
        # 序分
        ("聞如是：", "我是这样听闻的："),
        ("如是我聞：", "如是我闻："),
        ("如是我闻，一時", "如是我闻。一时"),
        ("聞如是，一時", "我是这样听闻的。那时"),
        ("一時，", "那时，"),
        ("一時佛", "那时，佛"),
        # 对话动词
        ("佛言：", "佛说："),
        ("佛告諸比丘：", "佛告诉诸位比丘说："),
        ("佛告諸比丘，", "佛告诉诸位比丘，"),
        ("佛告諸沙門：", "佛告诉诸位沙门说："),
        ("佛告阿難：", "佛告诉阿难说："),
        ("佛告阿難，", "佛告诉阿难，"),
        ("阿難白佛言：", "阿难对佛说："),
        ("阿難白佛：", "阿难对佛说："),
        ("世尊告曰：", "世尊告诉大家说："),
        ("世尊告曰", "世尊说"),
        # 时间、叙事
        ("昔者", "往昔"),
        ("昔者菩薩", "往昔，菩萨"),
        ("往昔菩薩", "往昔，菩萨"),
        ("爾時，", "那时，"),
        ("於是", "于是"),
        ("即自", "当即"),
        ("尋後", "随后"),
        ("尋即", "随即"),
        ("尋", "随即"),
        ("輒", "就"),
        ("便", "就"),
        ("俱", "一起"),
        ("咸", "都"),
        ("皆", "都"),
        ("悉", "全部"),
        ("靡不", "无不"),
        ("覩", "看见"),
        ("睹", "看见"),
        ("愍", "怜悯"),
        ("愴", "悲怆"),
        ("豈", "难道"),
        ("何謂", "什么是"),
        ("何謂也", "这是什么意思呢"),
        ("何以故", "为什么呢"),
        ("所以者何", "为什么呢"),
        ("云何", "如何"),
        ("爾乃", "这才"),
        ("然則", "这样的话"),
        ("猶", "犹如"),
        ("猶若", "就好比"),
        ("譬如", "譬如"),
        ("譬", "好比"),
        ("遂", "于是就"),
        ("竟", "终了"),
        ("訖", "完毕"),
        ("白", "票告"),
        ("啟", "启奏"),
        ("稽首", "稽首"),
        ("五體投地", "五体投地"),
        ("卻", "退下"),
        ("适", "刚好"),
        ("俄", "一会儿"),
        ("斯須", "须臾之间"),
        ("尋路", "沿路"),
        ("將", "将"),
        ("寧", "宁可"),
        ("勿", "不要"),
        ("莫", "不要"),
        ("弗", "不"),
        ("毋", "不要"),
        ("未甞", "未曾"),
        ("未常", "未曾"),
        ("未嘗", "未曾"),
        ("嘗", "曾经"),
        ("恒", "恒常"),
        ("常", "常常"),
        ("甞", "尝"),
    ]
    for a,b in repl:
        s = s.replace(a,b)
    # 把'曰'替换成'说道：'，但要小心"號曰"（名叫）、"名曰"、"偈曰"等
    s = re.sub(r'(?<![名號偈銘])曰：', '说道：', s)
    s = re.sub(r'(?<![名號偈銘])曰', '说道', s)
    # 处理"號曰X"→"号叫X/名字叫X"
    s = s.replace("號曰", "名叫")
    s = s.replace("号曰", "名叫")
    s = s.replace("名曰", "名叫")
    # 标点润色：原文大量无引号，这里不强行加，只做语气词柔化
    # "也""矣""焉""乎"等语气词处理：
    # 不在替换中强删，保留文白夹杂可读性。
    return s

def make_modern(title, yijie, baihua):
    return f"【{title}】\n【义解】{yijie}\n【白话】\n{baihua}"

