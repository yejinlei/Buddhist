    # 章首
    if i == 0:
        return "法会缘起·六度总纲", PARAMITA_DESC["序分"] + "本段为序分：佛在王舍国鹞山与大比丘、菩萨众集会，菩萨阿泥察寂心听法，世尊因此开演菩萨六度万行乃成佛正因。"
