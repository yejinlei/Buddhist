 "尽见之后，应广教骨观。若见白骨满一天下者，宜教大乘；若所见近者，宜教小乘。教他注意观鼻头，忆想人身肌肉都是父母精气不净所成；其次观齿白，人身之中唯有此白骨而已。若见齿长、或额上发白者，即观骨，令身皆白，远近如上。",
 "此人随其根器深浅，若教时不能立刻见白骨者，就教他如常的九想观，令其修习一月或一秋，一定要见到白骨才可前进。若见众生，就教他观慈心观法；教他熟观白骨，若见其余之物，应当对那人说：「这也好，暂且放下此事，只观白骨。」假若长久观白骨，便说：",
 "「我身中觉得煖。」便教他继续观。见煖觉已，安稳和悦者，这是煖法。其次应当教他以意解开白骨，令骨节节解散。若见其余之物，便令他暂且放下，只观白骨解离。久久观之，若说：「我头顶上有火出。」便教他再观；说：「我常常见头顶上有火出。",
 "」身中安乐、没有乱想，这是顶法。其次教他注意，令骨白净后，分散飘落在地，如雪在地，或如烂土，其上或有白光、种种异物。教他再观。若说：「继续见如此，身中快乐。」应当对他说：「你本来所爱的人，试忆念，与他做世间之事。",
 "」他观后说：「我忆念那个人，见他只是变成脓血不净，非常可恶。」其次教他观身如草束，或如空皮囊。若说：「我见自身如干草束，或如空皮囊，有火把它烧尽，乃无有我。」便教他再观：「你的意念起时从何处起？灭时从何处灭？观之。",
 "」观者要说：「我见念头忽起时从意而起，灭时从鼻头而灭。鼻头灭时，身中和静，不觉有我，了了分明。」教他观头顶，说：「我见身长大，头顶出水满于身中，令其极满，又从脐中流出，流到前地。」水出既尽，再教他重新下水，令身粗大。",
 "若说：「我见身大，水满其中，出之水成大池。」便教他以酥灌顶，令入身中。若说：「我以酥灌顶，便觉身广大。」教他谛观。若说：「观须臾之间，见皮火起，火便炽然满身中，以水灭之，令火灭尽，快得苏息。」",
 "教他系意观池。答说：「我见池中自然有树，树生甘果。」见此后，若有众生来饥饿求索，观者见之，便教他即起慈心，随即自观己身。若说：「我观自身尽是脓血流出在地，众生见之便取来吃，吃足之后各自向四方而去。",
 "」教他自观身及观他身。若说：「便见众多饿鬼来到身边，为饥饿所逼，命如丝发。」即教他以慈心以身布施。若说：「我以身布施，令他们得以充足。」再教他更观。若说：「我见无数众生绕身四边。」若见此事，应教他自观身。",
 "若说：「我自见身不净脓血在地，众生见之便取来吃。」他们饱足之后，教他谛观：「我见忽然火起，烧诸罪人及其己身，池中所有之水也都烧尽。」再教他谛观所见之处。若说：「我见众生及池中水、己身，全都平复如故。」",
 "观众生及其己身。若说：「我见自身流出乳汁、流下在地，众生见之却不能食，是因罪重之故。」便教他以慈心观。若说：「我须臾之间，乳化为脓，众生饥饿急切便来吃它；饱足之后，便见脚底火起，烧诸众生，忽然灭尽。」行人见此等事之后，应教他自发誓愿，更不受生。",
 "教他接着观前面的池。若说：「我观见水池，池中莲花、树枝叶茂盛。见此事后，自身入水，在树丛边坐，自观身中火出、满于池中；须臾之间忽然火起，自烧己身及众生，池水都尽。」接着教他更观。若说：「我见池中忽然有树生出，枝叶茂盛，长出甘果。",
 "行人见之，向树食果；饱足之后，身心明净、安稳快乐。」教他净观此池及其己身。若说：「须臾之间都已干枯。」行者见这破坏之相，心怀恐怖，即来白师。师应教他作「身为苦本」观，令他观身如泡沫。若说：「我见自身如泡沫，及身出骨，出后便以手摩，如面平以为地。",
 "」接着又教他观身如气囊。若说：「我自观如气囊，即变骨出，其骨微细，摩以涂地，其地青色。」再教他观身。若说：「我观自身微尘，及身出骨，其骨极黑，摩以为地。」教他自观身及观于地。答说：「我观那池中蛇出，身赤如火，蛇来逼身，便变为火，自烧其身。",
 "这样反复七次。座中自然有水洒下，蛇身即灭。」再教他还观身及观于地。若说：「我观须臾之间自然光出，高大明好。」接着又观身。若说：「我觉和适，心意快乐，无有懈息，自然之光来遍满全身。」反复七次教他自观身。若说：",
 "「我便自见头顶上有光，似如云盖，其色如银。」具足此事，应于初道，也叫观火竟。其次观水大，教他观身中何处有水。若说：「身中尽是水。」便教他更观。若说：「我见水在眼中现」者是好。若不著，便问：「你观头以上，水从何处出？",
 "」若说：「我见水从眼中出，又不堕地，眼如水沫，头中也满。」师当问：「你见水怎么样？出时都有什么相？」答说：「我见头中不温不冷。」这很好。若说水是温的，当知非真，再教他更观，一定要令水不温不冷，才是真相。",
 "教他观咽、胸以下至腹中，令见水满，但莫令水入于臂、脚之中。水要呈颇梨（玻璃）之色。若觉水是温的，那才是真，其余非真。其次观身中通于臂、脚。若说：「我见都是皮囊之相，又见水满于舍宅及床座之处。」这水若是冷的，那才是真，其余非真。",
 "若能广见水者，很好。其次观水大从何处消尽。若说：「我见水从我身中消尽，唯有空皮，或如草束，火起烧尽了无有我。」观水大竟。其次观火大，教他观脐的四周何处有火。若说：「我见脐上火起。」或说从鼻中出、或说从口中出、或说从眼耳中出者，便教他再观。",
 "答说：「我见鼻中出五色光，其状如丝，身中不温不冷。」这是一法，教他再观。若说：「我见火从顶上出，或说从下道（下身）出。」便教他再观。说：「我见火在头上如云盖之状，或说在下方如云之状，身澹愉安稳。」这是一法，教他再观身。",
 "说：「我见火从脐中出，喻如莲花，其色如金。」这很好，便教他观身中火。若说：「我行、坐常常见火，不只在坐时。行时也见火，似如有人持火而行，常在我前大明。这应会让他人觉得奇怪，而他人实在不见，而我身常温。」这是一法，教他更久地观。",
 "说：「我见大海水中有摩尼珠，其珠焰出如火。」此珠也是一法。观火大法竟。其次观风大，此风大其性细微，非条疏所能解，所以不列出。此四大是坐禅根本的所由之处，虽然多见其余诸相，终须归向此四种观。再次初教观佛，先教他坐定其意，不令外念及诸缘使人。",
 "然后将他带到好的佛像前，令他谛观像的相好分明。然后安坐，教他以心目观此像的相好。若说：「我见像分明。」是第一事。教他自观身，令身安坐，再教他还观佛。若说：「我见一佛至十佛，都令明了。」是第二事。",
 "教他谛观自身，渐渐安稳，再教他还观佛。若说：「我见十佛至二十佛明了。」是第三事。教他自观身，令身转安净，再教他还观佛。若说：「我见二十佛至五十佛，明了如前。」是第四事。教他自观身，令意转细，再教他还观佛。若说：「我见五十佛至百佛，相好如前。",
 "」是第五事。教他自观身，令心转细，再教他还观佛。若说：「我见百佛至千佛，明了如前。」是第六事。教他自观身，令心转细，再还教他观佛。若说：「我见二百佛至四百佛，明了胜前。」是第七事。教他自观身，令心转细，再教他还观佛。",
 "若说：「我见四百佛至八百佛，相好转明。」是第八事。教他自观身，令心转细，再教他观佛。若说：「我见八百佛至千佛。」是第九事。从一佛至千佛，谛观相好、极为分明之后，再自观身不净脓血，即教他作不净观；若见白骨，即作白骨观。",
 "若见苦痛众生，即作慈心观；若不见此事，便还观一佛，至心恳恻、求哀忏悔。这是初学人观佛之法。若趣向住地，应广观佛。若说：「我见一佛至百千万乃至众多佛，相好明了。」是第十事。教他观自身，令身明净，再教他还观佛，发大誓愿、心生供养。",
 "说：「我见无量诸佛，于佛前自然有花，便取来供养，悉令周遍。」是第十一事。教他自观身，令身明净，再教他观佛。若说：「我如前见后，心生欢喜。」便教他至心观佛、念欲供养。若说：「我见自然有花树踊出，上生种种杂色之花，自然有人取此好花与我，供养散于诸佛之上，普使周遍，花故不尽。",
 "」是第十二事。其次教他于佛边坐，自观己身极为明净，再教他观，从东方开始，令意念东行、见无数佛，意念疲倦才止息。是第十三事。",
 "教他于前境界中依次东行。若说：「我意东行，见无数佛满于虚空、没有边际，意念疲倦才止息。又再旋转意念东行，一定要到有阻碍才停住，南西北方也都如此。",
 "」是第十四事。教他自观身中肢节都已明了。若说：「我见了。」便教他还观佛的足下。若说：「我见佛足下放出杂光明，然后还至四方，一切诸佛都在光上的莲花之中。」是第十五事。",
 "教他发起观佛的喜心，谛观足下。若说：「我见佛足下光出，至于大地，没有边际。",
 "」便教他乘此光而观。若说：「我见苦痛众生无量无边，光所照之处全都安乐。」是第十六事。教他观自身，令其再转明净，教他观一佛的脐中。若说：「我见佛的脐中光出，遍至四方极远之处，一切诸佛都上光而住。」是第十七事。",
 "教他接着循光而观。若说：「我见无量之人于光中显现，都受快乐。」是第十八事。教他自观身，令其极明净，再教他还观一佛的两乳。若说：「我见佛的两乳中自然光出，遍至四方，一切诸佛都在光上。」是第十九事。再教他循光而观。若说：",
 "「我见此光中有无量之人，都受快乐。」是第二十事。教他自观身、见身极明，再教他还观一佛的眉间。若说：「我见光从眉间而出，大如斗许，渐渐粗大，便向上而去，踊在空中。」教他循光而观，是随何光而上？意念疲倦才止息，又再循去。",
 "若说：「我循去，上至无极，到达光的尽头。」是第二十一事。第二十二事原本缺漏。教他循此花佛，从东方开始。若说：「我见光著，有无量细微之光都如所观。这光的尽头有化佛满于东方，中间相距或五步。」教他继续东行而观。",
 "若说：「我行时见无量佛，意念疲倦才止息。」教他继续观至极远之处，更见其余之相，乃至南西北方也都如此。是第二十三事。",
 "」是第二十四事。教他观此所供养之花。若说：「我见花堕落者，在佛边便成花帐，行伍次第严好微妙，全都如此。如是一切诸佛，都在帐中坐在其床上。」是第二十五事。",
 "」是第二十六事。教他观自身。若说：「我见自身粗大，喻如聚光。」再教他还观佛，次第作礼悉令周遍，仰观于盖。若说：「我见上方花盖之中，有花台向下，七宝所成，其中有花下坠，以手承接取来。」教他散于诸方供养诸佛，悉令周遍。",
 "是第二十七事。教他向佛作礼、求愿已毕，教他至心于佛边坐。若说：「我坐须臾之间，见地自然踊出七宝之台，色妙香好，便取来供养一切诸佛。」是第二十八事。教他自观身、极令明净，再教他于佛边坐，观所供养之花。",
 "若说：「我见此花在佛足下，便成琉璃之座；次第行伍，佛坐其上，中间道路全都由妙宝所成，端直无比。」是第二十九事。教他自观身。若说：「我见身中更有小身，两重而现，内见外明净。」再教他还观佛。若说：「我见一切诸佛来入一佛身中而不迫窄。",
 "」是第三十事竟。观佛之事甚多，略出三十事以教行者。以下初教慈心观法：先教他忏悔，净身口意，至心恳恻发弘誓愿，然后教他安坐，以心目自观己身。若说：「我见自身。」便观他身。若说：「我见众生苦痛在前，足下火然，成为火坑，焚烧诸罪人，身体脓烂、血流成池，高声大唤、苦痛无量。",
 "又见四方有城围绕。」这名为初事。教他发大愿、生怜悯心，谛观众生。若说：「我见罪人为火所逼，投入脓血池，池中脓血便应变为火坑，焚烧诸罪人，苦痛无量，共同号哭、无有宁息之处。」是第二事。教他谛观，莫怀恐怖，誓心救济，教他一人一人地代受，乃至众多。",
 "若说：「我一人一人地代受，将他们置于坑上，令得苏息。」是第三事。教他谛观。若说：「我见诸城门中有无量之人，来投火坑、又受苦痛，我代他们令其出离，带到安稳之处。」是第四事。教他谛观。若说：「我见诸门中来人不绝，受无量苦。",
 "我以慈心之力，便以自身之手扪摸此门，门便破尽，四壁尽破。」是第五事。教他以慈心观之。若说：「我见诸治罪之人心生怜悯，泪下如雨，以手接取，洒散于火坑，火随即灭尽。」是第六事。教他更观。说：「见火已灭，唯有脓血盛满大坑，自身出水注入池中，池血消尽、其水澄清。",
 "」是第七事。教他谛观。若说：「我见池中生大花树，众生见此树便来取它。」教他令众生饮之、洗浴，令身清净。是第八事。教他登上花台之上。若说：「我上花台之后，见下方众生又想上来，即挽他们上来、置于花叶之中。其花狭小、不能容受，我以手摩，令花广大，得以容受。",
 "」是第九事。教他自观身明净之后。若说：「我又见诸罪人饥饿须食，生怜悯心，即在身边便有饮食，我便给他们，悉令饱足、使得休息，众人都说离苦得乐。」是第十事。教他谛观。「花台增长，有数重出，我便循上至第二重，身安坐已，便唤下方之人全都上到花台，快得安住。",
 "我生悲心，于是在花上所须之物、饮食充饱，我以慈心即为他们说法：『你们因宿世作毒火烧人房屋等种种恶业，今受此报。你们可忏悔，灭除宿罪。』」是第十一事。教他生善心，再登华台。若说：「我上重之后，下方众人也都上来，所须之物给与他们，令无所乏；又为他们说法，说天上人间、五道报应，令其心开意解。",
 "」是第十二事。教他循花而上。若说：「我已于花上，为下方重层诸人又想上来者，我都令其上。又生喜心观此花中，便有自然金银珍宝、衣裳饮食所须之物，全都给与他们。天上的种种伎乐自然而至，随其意所欲受快乐之后，便为他们说法：『你们善心初生，果报随之而至，封受此果报。",
 "』」是第十三事。教他增长喜心，乘华而上。若说：「已上华台之顶，在下方诸人心生欢喜，随后而上，尽到华顶。」又教他观花。若说：「我见华顶，见华顶生出大甘果，香味具足。便告诉众人说：『树上有果，可以取食。』他们便如所言，食得充足，都说快乐。",
