"之所以如此，都失于真。然而一切皆幻、虚妄不实。知幻是幻，守真抱一，不染外物，清虚太一，哪里有什么失？亡心丧意，体离众疾。一相不生，寂静凶吉，吉尚且不随，凶能何为？吉凶之事，二俱无依。那入道之径，内虚外净，如水凝澄，万象光映。",
"其意不沈、其心不浮，不出不入，湛寂自如。内外不干、识物不关，各任其一，又何用言？那火不待日而热、风不待月而凉，坚石处水、天瞽犹光，明暗自尔、乾湿同方，物尚且不相借，何况道呢？王以万有为人，人归于王、王依于人，合者同一，其名叫佛，三界独尊，觉了无物，非作而作，所作已毕。",
"天人之师，正遍知悉，权应形事，引导众疾。理静虚无，光超慧日，普照十方，上同下吉。不欲异人、不欲异尘、不欲异义、不欲异因，平等不二，圆通一身，可以说是大象之真。其理难见，假设方便，数数诘问言论，任物而现。",
"那欲于外的是尘、欲于内的是身、欲闻的是心，取尘的为欲界、依形身的为色界、依计心的为无色界，灭此三者，名叫道谛。谛灭的，就是道。然而这道，是权而非正。虚啊妄啊，三界不实；幻啊梦啊，六道无物。不遣一法、不得一法，不修一法、不证一法，性净天真，这才叫大道啊。",
"因此遍观天下，无非真人。谁得此理，同其一伦？其学者希少、其得者精微，可以说是渺漠而难知。其知者为师、其化者为夷，无心动作，作而无为；无为而为，无所不为，和光任物，物无所羁。那天地之内、宇宙之间，中有一宝，秘在形山。",
"识物灵照，内外空然，寂寞难见，其号称玄玄。巧出紫微之表、用在虚无之间，端化不动，独而无双。声出妙响、色吐华容，穷覩无所，寄号空空。只留其声、不见其形；只留其功，不见其容。幽显朗照，物理虚通，森罗宝印，万象真宗。",
"其为也形、其寂也冥，本净非莹，法尔圆成。光超日月、德越太清，万物无作，一切无名。转变天地，自在纵横；恒沙妙用，混沌而成。谁闻不喜？谁闻不惊？如何以无价之宝，隐在阴入之坑？哀哉哀哉！",
"它是自己轻忽。悲哉悲哉！晦暗何由而明？那宝焕焕煌煌，朗照十方，寂然无动，应用堂堂，应声应色、应阴应阳。奇特无根，虚湛常存，瞬目不见、侧耳不闻。其本也冥、其化也形，其为也圣、其用也灵，可以说是大道之精。",
"其精甚真，是万物之因，凝然常住，与道同伦。所以经说「随其心净则佛土净。」任用森罗，其名叫圣。那入离、那出微，知入离外，尘无所依；知出微内，心无所为。内心无所为，诸见不能移；外尘无所依，万有不能羁。",
"万有不能羁，想虑不奔驰；诸见不能移，寂灭不思议，可以说是本净、体自离微。据入故名离、约用故名微，混而为一，无离无微。体离不可染，无染故无净；体微不可有，无有故无依。因此用而非有、寂而非无，非无故非断、非有故非常。",
"那性离微者，非取非舍、非修非学，非本无今有、非本有今无，乃至一法不生、一法不灭，非三界所摄、非六趣所变，非愚智所改、非真妄所转，平等普遍，一切圆满，总为一大法界应化之灵宅，迷之者就历劫而浪修，悟之者就当体而凝寂。",
"那妄有所欲的，不观其离；妄有所作的，不观其微。不观其微的，就内兴恶见；不观其离的，就外起风尘。外起风尘之故，外为魔境所乱；内兴恶见之故，内为邪见所惑。既内外缘生，真一之宗隐没。所以迷离妄染的，就是所谓凡夫；",
"迷于染而妄离的，就是所谓二乘；达于本性离的，就是所谓菩萨；了了见知三乘无异的，就是所谓平等真佛。然而至理幽邃，不是言说可显、不是相示可知。那想示其相，就迷其无相；想显其说，就迷其无说。然而想不说不示，又难以通其义，所以玄道离微、至理难显。",
"那所以说离的，是因为体不与物合，也不与物离。譬如明镜光映万象，然而那明镜不与影合，也不与体离。又如虚空，合入一切无所染著，五色不能污、五音不能乱、万物不能拘、森罗不能杂，所以叫它离。所以说微的，是因为体妙无形、无色无相，应用万端而不见其容、含藏百巧而不显其功，视之不可见、听之不可闻，然而有恒沙万德，不常不断、不离不散，所以叫它微。",
"因此离微二字，是道的枢要。六入无迹叫离、万用无我叫微，微就是离、离就是微，只是就那根事而作两个名，其体是一。那修道者，无不断烦恼求菩提、弃小乘窥大用，然而妙理之中都没有这些事。体离的本无烦恼可断、无小乘可弃，体微的无菩提可求、无大用可窥。",
"为什么呢？因为没有一法可相应的缘故。因此圣人，不断妄、不证真，可以说是万用而自然了。那求法者为无求，所以无名之朴也将不欲，这可以叫妙觉。那离微，不是妄识之所识、不是邪智之所知。什么叫妄识？就是六识。什么叫邪智？",
"就是二智。因此体真一之故，非二智所知；体无物之故，非六识所识。没有一法从外而来，没有一法从内而出，又没有少法和合而生，可以叫太清、可以叫真精。体离一切诸见，所以不可以意度；体离一切限量，所以不可以言约。",
"因此维摩默然、如来寂寞，虽说种种诸乘，都是方便开示悟入佛之知见。那知者知离、见者见微，所以经说「见微名为佛，知离名为法。」因知离之故，就不与一切烦恼合；因见微之故，就不与一切虚妄俱。无虚妄之故，真一之理就显；",
"无烦恼之故，就明莹自然。那离微之义，非一非二，不是言说可显、要以深心体解，朗照现前，对境无心、逢缘不动，勿忘离微之道。逐识奔驰、口说心违，理将不实。可以说是无昼无夜、无静无喧，专一不移，才能契会。",
"若妄有所取、妄有所舍、妄有所修、妄有所得的，都不入真实，背离离微之义，坏大道之法。那真者之所以不合求，是因为外无所得；那实者之所以不合修，是因为内无所证。只要无妄想，离微之道就显。那离是虚、微是冲，冲虚寂寞，所以叫离微。",
"那圣人之所以无妄想，是因为达于离；之所以有奇特之用，是因为了于微。微故无心、离故无身，身心俱丧，灵智独存，绝于有无之域、泯于我所之居，法界自然，煌煌盛用而无生。所以圣人处无为而化行，不言之教冥然应合。",
"寂寞无人，因此含通大象、包入万物，譬如虚空普遍周备。那迷者无我却立我，则内生我倒。内生我倒之故，圣理不通。圣理不通之故，外有所立。外有所立，就内外生碍。内外生碍，就物理不通，于是妄起诸流，混于疑照、万象沉没，真一之宗混乱、诸见竞兴，这就成为流浪。",
"所以制作离微之论，显示体性幽玄，学者深思，就可知虚实了。那色法如影、声法如响，只以影响来指陈，不足封为真实，所以指非月、言非道。会道亡言、见月亡指，因此迷离的就成为诸魔，爱取诸尘、乐著生死；那迷微的就成为外道，非分推求、横生诸见。",
"那诸见的根本，不出有无。什么叫有？就是妄有所作。什么叫无为？就是观察无所得。因此因有无二见，就起种种诸见。诸见既起，就邪见不真，所以名为外道。那生死的根本，就是所谓存亡。身存为生、身亡为灭，计著妄想、取外境界，具足身见，爱那未来殊胜生处、受妙果报，所以叫它魔。",
"若体解离的，一切不著，无所染爱，就超魔境界。若体解微的，一切寂静，没有妄想，就超外道种种邪见。所以经说「微妙甚深离自性」。因此微没有见、离没有著，无见无著，寂灭为乐。什么叫苦？因不了微之故，就内有所思；不了离之故，就外有所依。",
"外有所依之故就贪、内有所思之故就缘，缘贪既起，就为魔境所使，昼夜煌煌无有暂止，具受尘劳，所以叫苦。什么叫乐？因了微之故，就内无所思；因了离之故，就外无所依。外无所依之故就无贪、内无所思之故就无缘，无缘之故就不为万有所拘，以及诸尘劳所使，清虚寂寞，无所系缚，自性解脱，所以叫乐。",
"那离是理、微是密。什么叫理？不离开一切物。什么叫密？显用藏术。又离是空、微是有。空故无相、有故形量，因此非有非空，是万法之宗；非空非有，是万物之母。出之无方、入之无所，包舍万有而不为事、应化万端而不为主，因此小室宽容，一念多通，非心所测、非意所识，可以说住不思议解脱之力。",
"什么叫不思议？因为体是离微。什么叫解脱？因为无所羁。离是法、微是佛，和合不二名为僧。所以三名一体、一体三名，混无分别，归本无名。又离是容、微是用，容故含垢、用故无侣，无侣之故就妙化常行、含垢之故就万有能处。",
"又无眼无耳叫离、有见有闻叫微。无我无造叫离、有智有用叫微。无心无意叫离、有通有达叫微。又离是涅槃、微是般若，般若故繁兴大用、涅槃故寂灭无余，无余故烦恼永尽、大用故圣化无穷。",
"若人不达离微的，纵然苦行头陀、远离尘境，断贪恚痴、伏忍成就，经无量劫终不入真实。为什么呢？都是因为依正所行、住有所得之故，不离颠倒梦想、恶觉诸见。若又有人体解离微的，虽近有妄想习气以及现行烦恼，然而数数觉知离微之义，此人不久就入真实无上道。",
"为什么呢？因为了正见根本之故。又所说的离，是对六入。所说的微，是对六识。若混六为一，寂静无物，非五四三、非九八七，只是圣人应机设教、对治执著不同，究竟理中都没有名字。譬如虚空，离数非数、离性非性，非一非异、非境非离境，不可言说，过于文字、出于心量，没有去来、没有出入。",
"那经论，无不就那凡情、破那根量，种种方便都不住于形事。若不住形事，就不须一切言说，以及离微之义。所以经说「随宜说法，意趣难解。」虽说种种诸乘，都是权接方便助道之法，然而不是究竟解脱涅槃。",
"譬如有人于虚空中画作种种色象，以及作种种音声。然而那虚空实在没有异相，也没有受入变动。所以知道诸佛化身以及说法也是这样，于实际中都没有一异。因此天地含离、虚空含微，万物动作变化无为。那神中有智、智中有通，通有五种、智有三种。",
"哪五种通？一是道通、二是神通、三是依通、四是报通、五是妖通。什么叫妖通？狐狸老变、木石之精，附傍人身，聪慧奇特，这是妖通。什么叫报通？鬼神逆知诸天变化，中阴了生、神龙变化，这是报通。什么叫依通？",
"约法而知、缘身而用，乘符往来、药饵灵变，这是依通。什么叫神通？静心照物，宿命既持，种种分别都随定力，这是神通。什么叫道通？无心应物、缘化万有，水月空华、影象无主，这是道通。什么叫三智？一是真智、二是内智、三是外智。",
"什么叫外智？分别根门、识了尘境，博览古今、该通俗事，这是外智。什么叫内智？自觉无明、断割烦恼，心意寂静、灭有无余，这是内智。什么叫真智？体解无物、本来寂静，通达无涯、净秽无二，所以叫真智。因此真智、道通不可名目，其余所有的都是邪伪。",
"伪就不真、邪就不正，惑乱心生，迷于体性。因此深解离微，达那诸有自性本真，出于群品。那知有邪正、通有真伪，若不是法眼精明，难以辨明。所以俗间多信邪伪、少信正真，大教偃行、小乘现用，所以知道妙理难显。",
"那离是无身、微是无心，无身故大身、无心故大心，大心故就周万物、大身故应备无穷。因此执身为身的就失其大应、执心为心的就失其大智，所以千经万论无不说离身心，破那执著才能入真实，譬如金师销鑛取金才能作器用。",
"若执有身的就有身碍，身碍之故法身就隐于形壳之中。若执有心的就有心碍，心碍之故真智就隐于念虑之中。所以大道不通、妙理沉隐，六神内乱、六境外缘，昼夜惶惶未有休息。那不观其心的不见其微、不观其身的不见其离，若不见离微就失其道要。",
"所以经说「佛说非身，是名大身。」也是这样。这叫破权归实、坏假归真。譬如金师销金为器，灭相混融以通大冶。说大冶的，就是大道。这大道冶中，造化无穷流出万宗，若成若坏体无增减，所以经说「有佛无佛，性相常住。",
"」所以说融相，只因愚夫著有相、畏无相。所以说相，是为破那外道著于无相、畏有相。所以说中道，是想令有相无相无二。这都是破执除疑，言语并非尽理。若又有人了相无法、平等不二，无取无舍、无此无彼、也无中间，就不假圣人言说，理自通达。",
"那以相为无相的，就是即相而无相，所以经说「色即是空，非色灭空。」譬如水流，风击成泡。即泡是水，非泡灭水。那以无相为相的，就是即无相而相，经说「空即是色，色无尽也。」譬如坏泡为水，水就是泡，非水离泡。",
"那爱有相畏无相的，不知有相即无相。爱无相畏有相的，不知无相即是相。因此有相及无相，一切都在其中了。觉者名佛，妄即不生，妄若不生，就本真实。那无相之相叫离，离体无相。相即无相叫微，微体非无相。",
"因此为道者，生而不喜、死而不忧。为什么呢？以生为浮、以死为休，以生为化、以死为真。所以经说「起唯法起，灭唯法灭。」又这法者各不相知，起时不言我起、灭时不言我灭。那大智无知、大觉无觉，真际理空不可名目，所以涅槃大寂、般若无知，圆满法身一切限量相寂灭。",
"那本际，就是一切众生无碍涅槃之性。为什么忽然有这样妄心以及种种颠倒？只因一念迷。又此念从一起，又此一从不思议起。不思议就是无所起，所以经说「道始生一」，一是无为。「一生二」，二是妄心，因知一之故就分为二。",
"「二生阴阳」，阴阳就是动静，以阳为清、以阴为浊，所以清气内虚为心、浊气外凝为色，就有心色二法。心应于阳，阳应于动；色应于阴，阴应于静。静就与玄牝相通，天地交合之故，所谓一切众生都禀受阴阳虚气而生。",
"因此由一生二，二生三，三就生万法。既缘无为而有心，又缘有心而有色，所以经说「种种心色」。因此心生万虑、色起万端，和合业因，就成三界种子。那之所以有三界，是因为以执心为本。迷真一之故，就有浊辱生其妄气。",
"妄气澄清为无色界，就是所谓心。澄浊现为色界，就是所谓身。散滓秽为欲界，就是所谓尘境。所以经说「三界虚妄不实，唯一妄心变化。」那内有一生，外就有无为；内有二生，外就有有为；内有三生，外就有三界。",
"既内外相应，就生种种诸法以及恒沙烦恼。若一不生就无无为，若有人说：「我证无为。」就是虚妄。若二不生就无有为，若有人说：「我证有为。」就是虚妄。若三不生就无三界，若有人说：「定有三界。」",
"」就是虚妄。所以经说「有有即苦果，无有即涅槃。」诸声闻人取证无为，还有有余；乃至十地菩萨，都有住地无明微细障。所以以一为无为，以二为有为，以三为三界。说无为的，有两种：一是证灭无为、二是性本无为。",
"说证灭无为的，就是一切圣人修道断障，体如如。所以经说「一切贤圣皆以无为法而有差别。」性本无为的，就是本来法尔，非修非证，非人所合、非法所契，人法本空、体净真谛。所以经说「实相之理，非有为非无为、不此岸不彼岸不中流。",
"」因此非有为之故就不可修学、非无为之故就不可灭证，若有修有证的，就不是性本无为。所以经说「一切法以不生为宗。」宗若不生就无无生，无生不生不可为证。为什么呢？若有证就有生，若无证就无生，依于本太冥。",
"那不生的就是本际，不出不没犹如虚空无物可比。只是一切有为之法虚妄不实，缘假相依而有存亡，穷其根趣还归本实际。只是一切众生失本，外求伶俜辛苦修习，累劫而不悟真。因此将本求末，末妄非真；将末求本，本虚非实。",
"那本就不合求。为什么呢？本就是不求本，譬如金不求金。末就不合修。为什么呢？妄不求妄，譬如泥团不可成金。那身心之法虚假不实，俗人多以修身心而觅道的，如同那泥团而觅金。若约身心即是道，圣人何故说离身心？",
"所以知道不是道。若本真的也不合修。为什么呢？因为没有二法。那圣人生而不有、死而不无，没有妄想取舍之心，所谓万生万死公正无私，法尔自然中无我造。只是那愚夫妄想内起惑心、种种见生，所以非真实，不能明了。",
"然而那本际自性清净，微妙甚深、体无尘垢，所以千圣万贤种种言论，都是化说，于真非真、说化非化。因此本际无名而名于无名、本际无相而名于无相，名相既立妄惑就生，真一之理沉、道宗之事隐。因此无名之朴通遍一切，不可名目，过量限界，一体无二。",
"所以经说「森罗及万象，一法之所印。」印就是本际。然而本际之理，无自无他、非一非异，包含一气、该入万有。若又有人自性清净含一而生，中无妄想，就是圣人。然而实际中也无圣人法如微尘许而有异。",
"若又有人自性清净含一而生，中有妄想、自体浊乱，就是凡夫。然而实际中也无凡夫法如微尘许而有异。所以经说「佛性平等广大难量。」凡圣不二一切圆满，咸备草木周遍蝼蚁，乃至微尘毛发莫不含一而有。",
"所以经说「了能知一，万事毕也。」因此一切众生都一乘而生，所以叫一乘。若迷之故就异、觉之故就一。经说「前念是凡，后念是圣。」又说「一念知一切法」。因此一即一切、一切即一，所以说一切以一法之功而成万象。",
"所以经说「一切若有，有心即迷。一切若无，无心即遍十方。」所以真一万差、万差真一，譬如海涌千波，千波即海，所以一切皆一无有异。那说一的，是对那异情。异既非异，一也非一。非一不一，假号真一。",
"那真一，不是名字所说。因此非一见一，若有所见就有二，不名为真一。又不名为知一，若一知一就名为二，也不名为一。若有所知就有无知，有知不知就有二。因此大智无知而无不知，炽然常知。",
"常知无知，假号为知，非我非所、非心非意。那有为之数法，就有所知；若无为法，犹如虚空没有涯际，就无知不知。那圣人所以说知的，是为有心有数、有为有法，所以可知。所以说无知的，是为无心无数、无为无法，所以不可知。",
"若以有知知于无知，没有这个道理。譬如有人终日说空，只是人在说空，不是空在说。若以那知知无知，也是这样。那圣人所以或说我知的，都是对迷约事，破病除疑，实在没有二者知与无知。所以说无知的，是为那愚夫不了真一，著我我所，妄计能知所知，所以说无知无分别。",
"那愚夫闻已就学无知，犹如痴人不能分别。因此圣人因那虚妄，就说如来了了知见，不是不知。愚夫闻已就学有知，由有有知就有知碍，也叫虚知也叫妄知，这样的知转非道。所以经说「众生亲近恶知识，长恶知见。」",
"」为什么呢？那些外道前知未来、后知过去、中知身心，身心不净，所以不免生死。那一切学无知的，都弃有知而学无知，无知的就是知，然而自己不觉知。又有弃无知而学有知的，知就有觉，有觉之故心生万虑、意起百思，还不离苦。",
"那知二见都不能当体虚融、如理冥契，于是不能入真实。那真实者，离知无知，过一切限量。那见就有方、闻就有所、觉就有心、知就有量，不了本际无方无所无心无量，就没有见闻觉知。所以真一无二，而现不同。",
"或又有人念佛佛现、念僧僧现，只是那非佛非非佛而现于佛，乃至非僧非非僧而现于僧。为什么呢？因为那念心希望显现之故，不觉自心所现。圣事缘起，一向为外境界而有差别，实非佛僧而有异。所以经说「彼见诸佛国土及以色身而有若干，其无碍慧无若干」",
"「」譬如幻师，于虚空中以幻术力化作种种色象。那幻人痴故，说那空中先有此事。那念佛僧也是这样，于空法中以念术力化作种种色相，起妄想见。所以经说「心如工伎儿，意如和伎者。五识为伴侣，妄想观伎众。」",
"」譬如有人于大冶边，自作模子方圆大小，自称愿那金汁流入我的模子以成形像。然而熔金任成形像，那真实融金非像非非像而现于像。那念佛僧也是这样。大智融金的，就是譬喻如来。法身模子的，就是譬喻众生。希望得佛，所以以念佛和合因缘起种种身相。",
"然而那法身非相非非相。什么叫非相？本无定相。什么叫非非相？缘起诸相。然而法身非现非非现、离性无性、非有非无、无心无意，不可以一切度量。只是那凡夫随心而有，就生见佛之想，一向说那心外有佛，不知自心和合而有。",
"或有一向说心外无佛，就是谤正法。所以经说「圣境界离于非有非无，非所称量。」若执著有无的，就是二边，也是虚妄。为什么呢？妄生二见，乖违真理之故。譬如有人于金器藏中，常观金体，不覩众相。虽覩众相，也是一金。",
"既不为相所惑，就离分别，常观金体无有虚谬。譬喻那真人也是这样，常观真一，不覩众相。虽覩众相，也是真一，远离妄想无有颠倒，住真实际，名叫圣人。若又有人于金器藏中，常覩众相不覩金体，分别善恶，起种种见，而失于金性，便有诤论。",
"譬喻那愚夫也是这样，常观色相男女好丑，起种种差别，迷于本性执著心相，取舍爱憎起种种颠倒，流浪生死受种种身，妄想森罗隐覆真一。因此怀道君子、通明达人，观察甚深远离群品，契合真一与理相应。",
"那真一难说，约喻以陈，究竟道宗非言可示。那眼作眼解就生眼倒，眼作无眼解就生无眼倒，都是妄想。若执有眼的就迷其无眼，由有眼之故就妙见不通。所以经说「无眼无色。」又有迷眼作无眼的，就失其真眼，如生盲人不能辨色。",
"所以经说「譬如根败之士，其于五欲不能复利。」诸声闻人也是这样。唯有那如来得真天眼，常在三昧，悉见诸佛国土。不以二相之故，就不同凡夫有所见；悉能见之故，就不同声闻无所见。那二见者妄见有无，然而真一之中体非有无，只是妄想虚立才得有無。",
"那圣人说我了了见、或说不的，只是为破病之故说见不见。然而真一理中离见不见，过量限界、度凡圣位，所以能了了见，不是虚妄。因此非色法之故，就非肉眼所见；非证法之故，就非法眼所见；唯有佛眼清净非见非不见，了了而见。",
"不可思议不可测量，凡夫绝分、二乘如芥子、菩萨如罗縠，所以知道佛性难以可见。虽然如此，所以经说「佛性普遍，无问凡圣。」只要自身中体会真一，何用外觅？昼夜深思内心自证，所以经说「观身实相，观佛亦然。」",
"」那观身实相的，就是一相。一相，就是空相。只因空无相，就非垢非净、非凡非圣、非有非无、非邪非正，体性常住不生不灭，就是本际。为什么如来法身眼耳鼻舌乃至身意诸根互用？因为体真一，以无有限量无有分剂之故。",
"即法身虚通，一切无碍。为什么凡夫眼耳诸根不通、于是没有互用？因为妄想分别界隔诸根，精神有量，分剂不通，真一之理迷，于是没有互用。所以经说「凡夫想识惑妄不通，执著根尘而有种种差别。」因此圣人通达真一，没有妄心界隔根尘，所以能同用，没有心量。",
"那什么叫真一？因为真无异。无异之故万物含一而生，就是那万物也为一。为什么呢？因为本一之故，就没有二。譬如檀生檀枝，终不是椿木。然而那真一而有种种名字，虽有种种名字终同一义，或叫法性、法身、真如、实际、虚空、佛性、涅槃、法界，乃至本际、如来藏。",
"而有无量名字，都是真一异名，同生一义。原来前三品也是这样。为什么叫广照品？就是所谓智鉴宽通、慧日圆照，包含物理、虚洞万灵，所以说广照。什么叫离微品？就是所谓性该真理、究竟玄源，实际冲虚、本净非染，所以说离微。",
"什么叫本际品？就是所谓天真妙理、体莹非修，性本虚通、含收万物，所以说本际品。因此合前三品，一义该收、出用无穷，总名宝藏。所以阐发森罗之义府、论述识物之根由，虚洞太清、阴符妙理，圆满的体合真一、了达的密悟玄通，所以明法界之如如、显大道之要。",
