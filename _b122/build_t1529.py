"身处波罗提木叉，有五种解脱、三种障对治、二种不应作不作。一是他求放逸障，此障对治，如经说「节身」之故。二是内资无厌足障，此障对治，如经说「时食」之故。三是共相追求障，此障对治，如经说「清净自活」",
"之故。四是自性止多事，如经说「不得参预世事」之故。五是自性尊重、不作轻贱事，如经说「不得通致使命」之故。后二句显示不应作不作。怎样五种身解脱？一是外缘身解脱；二是内缘身解脱；三是自相缘身解脱；",
"四是众事缘身解脱；五是远离异方便缘身解脱。五种解脱中，初句是总，余句是别应知。口处波罗提木叉，有二种邪语不应作不作。一是依邪法语，有二种不应作：一、邪术恼众生语；二、依邪药作世辩不正语。",
"如经说「咒术仙药」之故。二是依邪人语，也有二种不应作：一是与族姓同好，多作鄙呓语；二是亲近族姓，多作我慢语。如经说「结好贵人亲厚媟慢皆不应作」之故。意处波罗提木叉，有六句说三种障，对治三种不应作不作：",
"一是多见他过障，犯自净心之故，此对治，如经说「当自端心」之故；二是邪思惟障，不能自度下地之故，此对治，如经说「正念求度」之故；三是于受用众具中无限无厌足障，此对治，第五句，于四供养知量知足之故。",
"此供养有二种：一是于身分中供养，就是饮食衣服卧具汤药供养身分之故；二是于心分中供养，就是不共心供养、无厌足心供养、二事相违心供养、等分心供养。此四种心供养，是痴乱众生常受用之故、不知节量之故；",
"若入三昧分的知量之故、若入道分的知足之故。三种不应作不作，一、不污净戒，不受持心垢之故，如经说「不得包藏瑕疵」之故；二是远离无缘显己胜行、令他邪解之故，如经说「显异惑众」之故；三是远离贪覆心、贮积众具之故，如经说「趣得供事不应蓄积」",
"之故。已说从根本戒，次说根本戒与从戒俱解脱、能生诸功德之故。经说：这则略说持戒之相。戒是正顺解脱之本，所以名叫波罗提木叉。依因此戒，得生诸禅定及灭苦智慧。论说：从戒是戒相之故，不可广说显示，略说应知，如经说「这则略说持戒之相」",
"之故。戒是正顺，这句显示从戒义之故。于此彼处说从有二种：一是从根本戒；二是从根本所起成就戒。从根本戒，是显示顺根本无作波罗提木叉，如前已说之故。从根本所起成就戒，是显示后际解脱因，中际从戒生之故，如经说「解脱之本」",
"之故。戒是解脱体、能正度之故，如经说「所以名叫波罗提木叉」之故。这句显示能度身口意恶、彼岸成就三业解脱之故。能生诸功德，是显示有色解脱功德、无色解脱功德，那二相顺相违解脱功德都从彼生之故，如经说「依因此戒得生诸禅定及灭苦智慧」",
"之故。次说劝修戒利益之故。经说：所以比丘！当持净戒，勿令毁缺。若人能持净戒，这则能有善法；若无净戒，诸善功德都不得生。所以当知戒是第一安隐功德住处。论说：怎样劝修戒利益？此中有五种劝：",
"一是劝不失自体，如经说「当持净戒」之故；二是劝不舍方便，如经说「勿令毁缺」之故；三是劝远离诸过身口意业、常集功德之故，如经说「若人能持净戒这则能有善法」之故；四是劝知多过恶于身口意中、一切时不能生功德之故，如经说「若无净戒诸善功德皆不得生」",
"之故；五是显示持戒菩萨于所修行三种戒中有这样的得失，我当住安隐处、不住不安隐处之故，如经说「所以当知戒为第一安隐功德住处」之故。这正显示劝修利益胜义之故。已说修集对治邪业功德，次说对治修集止苦功德。",
"此中苦有三种：一是根欲放逸苦；二是多食苦；三是懈怠睡眠苦。这三种苦，三昧乐门对治应知。怎样根欲放逸苦对治？经说：你们比丘！已能住戒，当制五根，勿令放逸入于五欲。譬如牧牛之人执杖看守，不令纵逸犯人苗稼。",
"若放纵五根，非只五欲，将无崖畔不可制。也如恶马不以辔制，将牵人坠于坑陷。如被劫害，苦止一世；五根贼祸，殃及累世。为害甚重，不可不慎。所以智者制而不随，持之如贼不令纵逸。假使放纵他，也都将不久见其磨灭。",
"论说：根放逸苦，是苦因、苦果之故，依戒净三昧方便摄念对治之故，如经说「已能住戒当制五根」之故。为什么只说五根？是显示色非色别之故。又示意根中有五根，二种对治之故。哪二种？一是动念对治之故；二是不动对治之故，戒念护根利益相似法之故，如经说「勿令放逸乃至犯人苗稼」",
"之故。身戒清净之故，种种色不放逸，牧牛相似法之故。正念成就之故，种种心不行，执杖相似法之故。以戒念成就之故，三昧方便及正受功德无减无失之故，不犯苗稼相似法之故。又示无戒念失上上损心之故，气分成就难对治之故，如经说「若纵五根非只五欲，将无崖畔不可制」",
"之故。次说无对难对治，恶马相似法之故，如经说「也如恶马不以辔制，将牵人坠于坑陷」之故。又示过重相似不相似，又因果深苦无量世之故，显示先际中慎之故，如经说「如被劫害，苦止一世；五根贼祸，殃及累世。",
"为害甚重，不可不慎」之故。前说戒念护，今说智护之故。智者三昧观之故，彼是三昧重障之故，如经说「所以智者制而不随」之故。护彼如害命者，相似法之故，如经说「持之如贼不令纵逸」之故。重者既如此，轻者怎样制？",
"此中轻者，是细相习障之故，于此处有时则有、无时则无之故，不作意起之故，如经说「假使放纵」之故。势无自立之故，如经说「也都将不久」之故。性是无对不相见之故，如经说「见其磨灭」之故。此中怎样立见？显示依见时说之故，彼无见故灭见故。",
"次说欲放逸苦对治。经说：这五根，心为其主，所以你们当好制心。心之可畏，甚于毒蛇、恶兽、怨贼、大火、越逸，未足喻。动转轻躁，但观于蜜不见深坑。譬如狂象无钩、猿猴得树，腾跃踔踯难可禁制。当急挫之，无令放逸。",
"放纵此心的，丧人善事；制之一处，无事不办。所以比丘！当勤精进折伏你心。论说：此中欲苦，是心性差别之故，也是苦因苦果之故，显示种种色苦依彼而有之故，如经说「这五根心为其主」之故应知。自他生过之故、勤遮之故，如经说「所以你们当好制心」",
"之故。为什么勤遮？显示此心是三昧障法之故。什么是三昧相？怎样是障法相？三昧相有三种：一是无二念三昧相；二是调柔不动三昧相；三是起多功德三昧相。障法相也有三种：一是心性差别障；二是轻动不调障；",
"三者失诸功德障。心性差别障，如经说「心之可畏，甚于毒蛇恶兽怨贼大火越逸，未足喻也」之故。此中差别，是贪等四种差别之故。修无二念三昧的，于此差别处可畏应知，四种譬喻相似法之故，又示不相似法大可畏之故。",
"轻动不调障，如经说「动转轻躁」如是等之故。此中动转，是显示诸根中转识动之故。又速疾之故，猿猴相似法之故。但观于蜜的，是显示有翳不见未来之故。深坑，是障碍义之故。此障碍有二种：一是生处障碍；二是修一切行时困苦不能成就障碍，狂象相似法之故。",
"急挫，是显示抑入无动处之故。无令放逸，是显示摄入调伏聚之故。失诸功德障，如经说「放纵此心丧人善事」之故。无二念三昧相，如经说「制之一处」之故。起多功德三昧相，如经说「无事不办」之故。调柔不动三昧相，如经说「当勤精进折伏你心」",
"之故。已说根欲苦对治，次说多食苦对治。经说：你们比丘！受诸饮食当如服药，于好于恶勿生增减，趣得支身以除饥渴。如蜂采花但取其味不损色香。比丘也是这样，受人供养趣自除恼，无得多求坏其善心。譬如智者筹量牛力所堪多少，不令过分以竭其力。",
"论说：多食，是三昧障之故。食有二种。哪二种？一是身食；二是心心数法食。若多段食，难止息之故、去禅定远之故。此心心数法食，是欲界相违法中方便对治之故。又有第一义心三昧中尽之故，成就无食三昧之故。",
"这二种三昧，有六种功德成就。哪六种？一是受用对治功德成就；二是平等观功德成就；三是究竟对治功德成就；四是显示平等观功德相似成就；五是不虚受功德成就；六是知时功德成就。这六种功德显示成就二种三昧。",
"第一、第五、第六功德成就，显示少食三昧之故；其余三种功德成就，显示无食三昧之故。受用对治功德成就，如经说「你们比丘受诸饮食当如服药」之故。平等观功德成就，如经说「于好于恶勿生增减」之故。究竟对治功德成就，如经说「趣得支身以除饥渴」",
"之故。这显示平等法身摄平等观，究竟无饥渴之故。显示平等观功德相似成就，如经说「如蜂采花，但取其味不损色香，比丘也是这样」之故。此中不损，是显示非坏法观之故。不虚受功德成就，如经说「受人供养趣自除恼」",
"之故。知时功德成就，如经说「无得多求坏其善心」之故。多求，是显示心心数法多、三昧功德不现前之故。筹量牛力等，是示知时相似法之故。显示知时有二种：一是方便时计校之故；二是成就时相应之故，示多食过之故。",
"已说多食苦对治，次说懈怠睡眠苦对治。经说：你们比丘！昼则勤心修集善法无令失时，初夜后夜也勿有废，中夜诵经以自消息，无以睡眠因缘令一生空过无所得。当念无常之火烧诸世间，早求自度勿睡眠。",
"诸烦恼贼常伺杀人甚于怨家，安可睡眠不自惊悟？烦恼毒蛇睡在你心，譬如黑蚖在你室睡，当以持戒之钩早摒除他。睡蛇既出乃可安眠，不出而睡是无惭人。惭耻之服，于诸庄严最为第一。惭如铁钩，能制人非法。",
"所以比丘！常当惭耻勿得暂替。若离惭耻，则失诸功德。有愧之人则有善法；若无愧的，与诸禽兽无相异。论说：懈怠睡眠苦对治，是以不疲惓思惟对治之故。此中为什么懈怠、睡眠共说障法？显示懈怠，是心懈堕之故。",
"睡眠，是身闷重之故。这二相顺共成一苦之故，五种定障中共说之故。此中起睡眠有三种：一、从食起；二、从时节起；三、从心起。若从食及时节起的，是阿罗汉眠，因他不从心生之故，无所盖之故。这三种睡眠中，初二种以精进对治，无有时节之故，无始来未曾断之故，又示圣道难得之故，如经说「你们比丘！",
"昼则勤心修习善法无令失时，初夜后夜也勿有废，中夜诵经以自消息，无以睡眠因缘令一生空过无所得」之故。其余修多罗，显示第三从心起睡眠对治之故。此中对治有二种：一是思惟观察对治，观诸生灭坏五阴之故，如经说「当念无常之火烧诸世间」",
"之故。又示求禅定智慧度所度之故，如经说「早求自度勿睡眠」之故。又观察阴界入等常害之故，此中可畏、求自正觉之故，如经说「诸烦恼贼常伺杀人甚于怨家，安可睡眠不自惊悟」之故。二是净戒对治，就是禅定相应心戒之故，六种境界心安住自心之故，可畏如蛇相似法之故，如经说「烦恼毒蛇睡在你心，譬如黑蚖在你室睡」",
"之故。净心戒对治之故，如经说「当以持戒之钩早摒除他」之故。又示远离之故、安隐之故，如经说「睡蛇既出乃可安眠」之故。次说下地相似安隐无对治之故，如经说「不出而眠是无惭人」之故。又示治法胜，能令自地清净庄严，也令他地无过之故，如经说「惭耻之服，于诸庄严最为第一。",
"惭如铁钩，能制人非法」之故。此中最胜、胜余戒庄严之故。「所以比丘」等为明何义？显示劝修胜庄严之故、常修之故。又示远离的，损自地之故，如经说「若离惭耻则失诸功德」之故。又示有无得失之故，如经应知。",
"已说修集对治止苦功德。次说修集对治灭烦恼功德，此中有三种障对治，示道义应知。经说：你们比丘！若有人来节节肢解，当自摄心不令瞋恨，也当护口勿出恶言。若纵恚心，则自妨道失功德利。忍之为德，持戒苦行所不能及。",
"能行忍的，乃可名为有力大人。若他不能欢喜忍受恶骂之毒如饮甘露的，不名入道智慧人。为什么？瞋恚之害，破诸善法、坏好名闻，今世后世人不喜见。当知瞋心甚于猛火，常当防护无令得入，劫功德贼无过瞋恚。",
"白衣受欲，非行道人，无法自制瞋犹可恕；出家行道无欲之人而怀瞋恚，甚不可。譬如清冷云中而霹雳起火，非所应。论说：此中初障对治，是瞋恚烦恼障对治之故，显示堪忍道之故。修行菩萨住堪忍地中，能忍种种诸苦恼之故，无轻重对治之故，如经说「你们比丘！",
"若有人来节节肢解，当自摄心无令瞋恨」之故，这示幻化法身成就之故。又口行清净常作软语之故，如经说「也当护口勿出恶言」之故。又说自他利道德障法之故，如经说「若纵恚心则自妨道失功德利」之故。显示功德智慧二种心行净之故，校量胜诸眷属行之故，如经说「忍之为德，持戒苦行所不能及」",
"之故。此中行者三昧功德苦对治之故，三种业清净。及校量胜相，示行安苦道应知。次说真如观清净，显示安乐道之故，成就观智大人力之故，如经说「能行忍者乃可名为有力大人」之故。又显示不入丈夫力成就的，无智慧观之故，依相违显胜应知，如经说「若他不能欢喜忍受乃至智慧人也」",
"之故。此中不欢喜，是无信入观之故。恶骂之毒，是示无生法门相中不如法受之故。甘露，是示无生法自体相相似法之故。此中道，是示智慧自体之故。又说患过事常护之故，如经说「为什么」如是等之故。此中诸善法，是自利智慧相之故。",
"好名闻，是利他善法名称功德之故。人不喜见，是自他世无可乐果报之故。此中防护有二种。哪二种？一是护自善法如防火，相似法之故；二是护利他功德、防护贼，相似法之故。又示世间功德违顺法中有受用之故，未毕竟相违之故，如经说「白衣受欲，非行道人，无法自制瞋犹可恕」",
"之故。此中无法，是无白净法对治之故。次示出世间道，于世间受用二法中一向相违之故，如经说「出家行道无欲之人而怀瞋恚，甚不可也」之故。其余显示道分中不应有，相似法之故，如经说「譬如清冷云中霹雳起火，非所应也」",
"之故。次说第二烦恼障对治道。经说：你们比丘！当自摩头，已舍饰好著坏色衣、执持应器以乞自活，自见如是，若起憍慢当疾灭他。增长憍慢尚非世俗白衣所宜，何况出家入道之人为解脱之故，自降其身而行乞。",
"论说：第二烦恼障对治道，是显示自无尊胜心成就，轻贱身心行之故、远离贡高烦恼之故。此中有七句行远离：一是于上上尊胜处，最先折伏之故，常应自知之故，如经说「你们比丘当自摩头」之故。二是于余处庄严不受用之故，如经说「已舍饰好」",
"之故。三是于衣服处对治为好之故，如经说「著坏色衣」之故。四是自己受用具常自持之故，如经说「执持应器」之故。五是于内外受用事，不作余生过方便之故及自调伏之故，如经说「以乞自活」之故。六是智慧成就常自观察之故，如经说「自见如是」",
"之故。七是对治成就远离微起之故，如经说「若起憍慢当疾灭他」之故。其余明何义之故，显示校量？自降伏的，不应起憍慢之故，障碍先后际功德之故，如经说「增长憍慢尚非世俗」如是等之故。次说第三障对治。经说：你们比丘！",
"谄曲之心与道相违，所以宜应质直其心。当知谄曲但为欺诳，入道之人则无是处。所以你们宜当端心，以质直为本。论说：第三障对治，是显示根本直心，远离谄曲烦恼障之故，于口意中自违违他之故，如经说「你们比丘！",
"谄曲之心与道相违」之故。又示违道障对治之故，如经说「所以宜应质直其心」之故。又相违法，道分时中不应有之故，如经说「当知谄曲但为欺诳，入道之人则无是处」之故。此中欺诳，是心口俱时不实用之故。其余显示直心，是道心本之故，如经说「所以你们宜当端心以质直为本」",
"之故。已说修集世间功德分，次说修集出世间大人功德分。大人功德分有八种，一切大人常用此以自觉察之故，长养成就方便毕竟之故。经说：你们比丘！当知多欲之人，多求利故苦恼也多；少欲之人无求无欲则无此患。",
"直尔少欲尚应修集，何况少欲能生诸功德。少欲之人则无谄曲以求人意，也不为诸根所牵。行少欲的、心则坦然无所忧畏，触事有余常无不足。有少欲的则有涅槃。这叫少欲。论说：此中第一大人，成就无求功德，知觉多欲过之故。",
"此中说所知觉有五种相：一是知觉障相，就是烦恼业苦三种障之故，如经说「你们比丘！当知多欲之人多求利故苦恼也多」之故，这示回转不息之故。二是知觉治相成就，远离三种妄想之故，如经说「少欲之人无求无欲则无此患」",
"之故。三是知觉因果集起相，成就无量行之故，如经说「直尔少欲尚应修集，何况少欲能生诸功德」之故。四是知觉无诸障毕竟相，三障毕竟之故，如经说「少欲之人则无谄曲以求人意，也不为诸根所牵」之故。五是知觉果成就相，般若等三种功德果成就之故，如经说「行少欲的心则坦然无所忧畏，触事有余常无不足，有少欲的则有涅槃，这叫少欲」",
"之故。又说第二大人知觉功德。经说：你们比丘！若欲脱诸苦恼，当观知足，知足之法就是富乐安隐之处。知足之人，虽卧地上犹为安乐；不知足的，虽处天堂也不称意。不知足的虽富而贫，知足之人虽贫而富。",
"不知足的常为五欲所牵，为知足者所怜愍。这叫知足。论说：第二大人知觉功德，成就知足行之故，对治苦因果之故，如经说「你们比丘！若欲脱诸苦恼当观知足」之故。此中恼，是显示烦恼过从苦生之故。又说清净因果成就治法之故，如经说「知足之法就是富乐安隐之处」",
"之故。若如此，二种知觉怎样差别？此中显示初知觉的，远离他境界事之故；知足的，于自事中远离之故。又三种差别，显示知足不知足之故。一是于何等何等受用差别之故；二是于何等何等事受用差别之故；",
"三是于何等何等法中无自利有自他利差别之故。如经说「知足之人，虽卧地上」如是等，如经应知。次说第三大人远离功德。经说：你们比丘！若求寂静无为安乐，当离愦闹独处闲居。静处之人，帝释诸天所共敬重，所以当舍己众他众，空闲独处思灭苦本。",
"若乐众的则受众恼。譬如大树众鸟集之，则有枯折之患。世间缚著没于众苦，如老象溺泥不能自出。这是远离。论说：第三大人远离功德，此中三门摄义应知。一是自性远离门，体出之故；二是修习远离门，方便出之故；",
"三是受用诸见门，常缚之故。自性远离门，显示四种对治：一是我相执着障，此障对治，如经说「你们比丘！若求寂静无为安乐」之故。此中寂静，是示法无我空之故。无为，是无相空之故。安乐，是无取舍愿空之故。",
"二是我所障，五众乱起无次第之故，此障对治，如经说「当离愦闹」之故。三是彼二无相障，此障对治，如经说「独处闲居」之故。四是无为首功德障，因他天可重法之故，此障对治，如经说「静处之人，帝释诸天所共敬重」",
"之故。修习远离门，远离我我所不复集生之故，如经说「所以当舍己众他众」之故。方便慧成就，如法如住之故，如经说「空闲独处」之故。善择智成就，远离起因之故，如经说「思灭苦本」之故。受用诸见门，乐集我我所生起自他心境相恼之故，如经说「若乐众的则受众恼」",
"之故。诸见集生，生已自害，大树相似法之故，如经说「譬如大树众鸟集之，则有枯折之患」之故。又示无出离相烦恼业染生之故，老象溺泥相似法之故，如经说「世间缚著没于众苦，如老象溺泥不能自出，这是远离」之故。",
"次说第四大人不疲惓功德。经说：你们比丘！若勤精进则事无难的，所以你们当勤精进，譬如小水常流则能穿石。若行者之心数数懈废，譬如钻火未热而息，虽欲得火、火难可得。这叫精进。论说：此中不疲惓，是显示不同外道精进之故，于一切法一切行善趣之故，成就不退转之故，如经说「你们比丘！",
"若勤精进则事无难者」之故。以能成就不退，须修习长养之故，如经说「所以你们当勤精进」之故。又以譬喻显示不休息，精进成就有力之故，如经说「譬如小水常流则能穿石」之故。次说懈怠过，不能常精进念处退失，不成就心慧之故，依譬喻显示应知，如经说「若行者之心数数懈废」",
"如是等之故。次说第五大人不忘念功德。经说：你们比丘！求善知识、求善护助，无如不忘念者。若有不忘念的，诸烦恼贼则不能入。所以你们常当摄念在心，若失念的则失诸功德；若念力坚强，虽入五欲贼中不为所害。",
"譬如着铠入阵则无所畏。这叫不忘念。论说：第五大人不忘念功德，是显示是一切行上首之故，能破无始重怨之故。此中一切行者，略说三种：一是求闻法行，如经说「你们比丘求善知识」之故。二是内善思惟行，如经说「求善护」",
"之故。三是求如法修行，如经说「求善助」之故。又示此等行中为首为胜之故，如经说「无如不忘念者」之故。能遮无始重怨、不害三种善根之故，如经说「若有不忘念的，诸烦恼贼则不能入」之故。烦恼，是示心相中惑乱之故，贼是从外集生过之故。",
"又示劝修令初后念成就，显示遮无始终心之故，如经说「所以你们常当摄念在心」之故。无始终之故，失念成就多过之故，如经说「若失念的则失诸功德」之故。又成就多功德，随顺世间门集诸行之故，如经说「若念力坚强，虽入五欲贼中不为所害」",
"之故。念力强之故，勇健无畏，入阵相似法之故，如经说「譬如着铠入阵则无所畏，这叫不忘念」之故。次说第六大人禅定功德。经说：你们比丘！若摄心的心则在定，心在定故能知世间生灭法相，所以你们常当精勤修集诸定。",
"若得定的心则不散。譬如惜水之家善治堤塘。行者为智慧水之故，善修禅定令不漏失。这名叫定。论说：大人禅定功德，就是八种禅定等，因摄念生之故，如经说「你们比丘！若摄心的心则在定」之故。怎样摄心能生禅定？",
"显示摄遍所行处，心行对治缘之故。次及中软取事，心行对治缘之故。此三种缘处对治成时，则近禅定之故。禅定成就，有方便果用之故，如经说「心在定故能知世间生灭法相」之故。又懈怠无修集，方便障之故，如经说「所以你们常当精勤修集诸定」",
"之故。此中懈怠有三种：一是不安隐懈怠；二是无味懈怠；三是不知恐怖懈怠。怎样修集一一对治？显示精进修集节量食卧及调阿那波那之故。精勤修集觉知诸定，有通慧功德及尽苦原之故，大希有事之故。精进修集观察生老病死苦及四恶趣苦，我未能离之故，是这三障对治之故。",
"又修习功德成就，无所对治之故，如经说「若得定的心则不散」之故。又以譬喻示善修功德，上上增长之故，如经应知。次说第七大人智慧功德。经说：你们比丘！若有智慧则无贪着，常自省察不令有失，这则于我法中能得解脱。",
"若不这样的，既非道人又非白衣，无所名。实智慧的，就是度老病死海坚牢船，也是无明黑暗大明灯，一切病者之良药，伐烦恼树之利斧。所以你们当以闻思修慧而自增益。若人有智慧之照，虽是肉眼而是明见之人。",
"这叫智慧。论说：此中智慧功德，于真实义处障及世间事处障能远离之故，如经说「你们比丘！若有智慧则无贪着」之故。于一切时常修心慧之故，因他难得之故，如经说「常自省察不令有失」之故。又示难得能得，于第一义处远离之故，如经说「这则于我法中能得解脱」",
"之故。又示非自性慧不入出世及世间中之故，非施设之故，如经说「若不这样的，既非道人又非白衣，无所名」之故。又以四种譬喻，显示四种功德。闻思修证之故，如经应知。说实智慧，是示实能对治之故。于四种功德中，第四功德自利益最胜义之故。",
"又四种修学功德，于分内处而有觉照之故，如经说「若人有智慧之照，虽是肉眼而是明见人，这叫智慧」之故。已说长养方便功德，次说大人成就毕竟功德。经说：你们比丘！若种种戏论其心则乱，虽复出家犹未得脱。",
"所以比丘！当急舍离乱心戏论。若你欲得寂灭乐的，唯当速灭戏论之患。这叫不戏论。论说：大人成就毕竟功德，是显示自性远离非对治法之故，四种差别智障法分别可分别之故，如经说「你们比丘！若种种戏论其心则乱」",
"之故。修道智非自性之故，如经说「虽复出家，犹未得脱」之故。其余二句劝修远离，成就无戏论之故。一是有对相远离，有彼彼功德相之故，如经说「所以比丘！当急舍离乱心戏论」之故。二是无对相远离，无彼彼功德相之故，如经说「若你欲得寂灭乐的，唯当速灭戏论之患」",
"之故。示现行成就体性异之故，如经说「这叫不戏论」之故。已说成就出世间大人功德分，次说显示毕竟甚深功德分。经说：你们比丘！于诸功德常当一心，舍诸放逸如离怨贼。大悲世尊所欲利益皆已究竟，你们但当勤而行之。",
"若于山间若空泽中、若在树下闲处静室，念所受法勿令忘失，常当自勉精进修之，无为空死后致有悔。我如良医知病说药，服与不服，非医咎。又如善导导人善道，闻之不行，非导过。论说：显示毕竟甚深功德，有二种毕竟，显示二种甚深功德之故。",
"一是如来分别说法毕竟功德，显示非分别说法甚深功德常说之故。二是修行菩萨修世间功德毕竟，显示其余甚深功德常修之故。这二种修行功德如上，一一种中各修二种功德应知。此中常修功德，是第一义心修之故，如经说「你们比丘！",
"于诸功德常当一心」之故。远离一心相似相违行如怨之故，如经说「舍诸放逸如离怨贼」之故。无限齐大悲常利益限齐毕竟之故，如经说「大悲世尊所欲利益皆已究竟」之故。又广说常修功德，有七种修相：一是怎样修？",
"显示常勤行之故，如经说「你们但当勤而行之」之故。二是于何处修？示无事处之故，如经说「若于山间若空泽中，若在树下闲处静室」之故。三是何所修？示修真实无二念法之故，如经说「念所受法」之故。四是何故修？修令现前之故，如经说「勿令忘失」",
"之故。五是以何方便修？如经说「常当自勉精进修之」之故。六是于相似法处苏息，远离上上心之故，如经说「无为空死」之故。七是于晚时自知有余悔不及事之故，如经说「后致有悔」之故。又广说如来分别说法功德毕竟，显示二种毕竟相：",
"一是说化法毕竟相应无余之故，如经说「我如良医知病说药，服与不服，非医咎」之故。二是与念毕竟度法相应无余之故，如经说「又如善导导人善道，闻之不行，非导过」之故。此中服与不服等，显示如来于二种毕竟中无过失之故，不负众生世间法之故。",
"次说显示入证决定分。经说：你们若于苦等四谛有所疑的，可疾问之，无得怀疑不求决。那时世尊如是三唱，人无问者。为什么？众无疑之故。这时阿㝹楼驮观察众心而白佛言：世尊！月可令热、日可令冷，佛说四谛不可令异。",
"佛说苦谛实苦不可令乐；集真是因更无异因；苦若灭的就是因灭，因灭故果灭；灭苦之道实是真道更无余道。世尊！这些比丘于四谛中决定无疑。论说：入证决定，是显示于所证法中成就决定无所疑之故。此中有三门摄义，显示决定无疑：",
"一是方便显发门；二是满足成就门；三是分别说门。方便显发门，是显示于诸实法处显发之故，因彼法是修行者当观察及依之起行之故，如经说「你们若于苦等四谛」之故。于四谛中有作无作法，显示有疑无疑分齐之故，如经说「有所疑的可疾问之，无得怀疑不求决」",
"之故。疾问，是示二种将毕竟之故，如向已说二种毕竟事之故。无得怀疑，是于见无作谛处及修行有作谛处，那二相违处皆不得疑之故。满足成就门，有三种显示：一是显示法轮满足成就三转实法之故，如经说「那时世尊如是三唱」",
"之故。二是显示证法满足成就，如经说「人无问者」之故。三是显示断功德满足成就，如经说「为什么？众无疑之故」。分别说门，是显示彼众上首知大众心行成就决定，又了知所证实义之故，分别说彼彼事答如来之故。",
"如经说「这时阿㝹楼驮观察众心」如是等之故。日月冷热，是示于四谛中违顺观行不可异之故。实苦不可令乐，是以佛说之故，苦乐各实不变异之故。更无异因，是示苦灭各自因之故，又示灭道同是自性观之故。决定，是苦乐因果入行决定之故。",
"无疑，是无异无余义之故。已说显示入证决定分，次说分别未入上上证，为断疑分。经说：于此众中所作未办的，见佛灭度当有悲感。若有初入法的，闻佛所说即皆得度。譬如夜见电光即得见道。若所作已办、已度苦海的，但作是念：",
"世尊灭度一何疾哉。论说：分别未入上上证，有三种分别，显示未入上上法之故。一是于有作谛修分时中未入上上法之故，如经说「于此众中所作未办的，见佛灭度当有悲感」之故。二是于无作谛见道时中速决定之故，显示不同修分法之故，去上上法转远之故，如经说「若有初入法的，闻佛所说即皆得度」",
"之故。又以譬喻显示见道速决定义应知，如经说「譬如夜见电光即得见道」之故。三是于那二相违无功用无学道中，于上上法界有微细疑之故。又有异义，于自地中见佛速灭之故。如经说「若所作已办、已度苦海的，但作是念：",
"世尊灭度一何疾哉」之故。次说为断彼彼疑之故。经说：阿㝹楼驮虽说众中皆悉了达四圣谛义，世尊欲令此诸大众皆得坚固，以大悲心又为众说：你们比丘勿怀悲恼。若我住世一劫会亦当灭，会而不离终不可得。",
"自利利人法皆具足，若我久住更无所益。应可度者，若天上人间皆悉已度；其未度者，都也作得度因缘。自今以后，我诸弟子展转行之，则是如来法身常在而不灭。论说：此中断疑，是断彼胜分疑之故，于自地中先所成就之故，如经说「阿㝹楼驮虽说众中皆悉了达四圣谛义」",
"之故。又令上上成就，于彼所得究竟不退之故，是如来悲心淳至之故，不护上上法之故，如经说「世尊欲令此诸大众皆得坚固，以大悲心又为众说」之故。怎样说？说有为功德，自他俱灭之故。自他，是说听差别之故。如经说「你们比丘勿怀悲恼。",
"若我住世一劫会亦当灭，会而不离终不可得」之故。又说法门常住不灭之故，如经说「自利利人法皆具足」之故。又说他利事毕竟，无复所作之故，如经说「若我久住更无所益」之故。又于彼彼众中自利事毕竟，无复所作之故，如经说「应可度者，若天上人间皆悉已度」",
