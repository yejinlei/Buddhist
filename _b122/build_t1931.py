 "名称虽不同，其实只是见思二惑而已。首先解释见惑，有八十八使：一、身见；二、边见；三、见取；四、戒取；五、邪见（以上为利使）；六、贪；七、瞋；八、痴；九、慢；十、疑（以上为钝使）。此十使历经三界四谛之下，增减不同，合成八十八：即欲界苦谛下十使具足；",
 "集谛、灭谛下各有七使，除去身见、边见、戒取；道谛下有八使，除去身见、边见。四谛下合为三十二。上二界（色界、无色界）四谛之下，其余皆同欲界，只是于每一谛下除去瞋使，所以一界各有二十八，二界合为五十六，加上前面的三十二，合为八十八使。",
