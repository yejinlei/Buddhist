 "其次说明通教：通于前之藏教，通于后之别、圆，故名通教。又从当教得名，谓三乘之人同以无言说道、体色入空，故名通教。依《大品经》，乾慧等十地即是此教的位次。一、乾慧地，因未有理水而得此名，即外凡位，与藏教的五停心、总相念、别相念等三位齐。",
