 "以上见思二惑虽有不同，总是藏教实有的集谛。三、灭谛，即灭除前面的苦、集，显示偏真之理；因灭而会真，所灭并非真谛。四、道谛，略说则是戒、定、慧，广说则是三十七道品。此三十七道品合为七科。一、四念处：一、观身不净（色蕴）；二、观受是苦（受蕴）；",
