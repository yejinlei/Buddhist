 "若是利根菩萨，不只见空，兼见不空，不空即是中道。分二种：即但中、不但中。若见但中，则由别教来接；若见不但中，则由圆教来接。所以说「通后」。问：于何位受接？进入何位？答：受接之人三根不同。若上根，于三地、四地被接；",
 "中根之人，于五地、六地；下根之人，于七地、八地。所接之教，真似不同：若于似位被接，即别教十回向、圆教十信位；若于真位受接，即别教初地、圆教初住。问：此藏、通二教，同是三乘，同断四住，同出三界，同证偏真，同行三百由旬，同入化城，为何要分二？",
 "答：诚如所问，然而同而不同：所证虽同，大小巧拙却永远有别。此二教都是界内教。藏教是界内的小、拙——不通于大所以是小，析色入空所以是拙。此教三人，虽在当教内有上中下的差别，但比望通教三人则一概是钝根，所以必须析破。通教则是界内的大、巧——大是指大乘初门，巧是指体色入空；虽当教中三人有上中下之别，但比望藏教则一概为利。",
 "问：教既是大乘，为何还有二乘之人？答：朱雀门中何妨庶民出入？所以人虽有小，教定是大。大乘兼摄小乘，渐引入实，岂不巧妙？般若、方等部内的共般若等，即此教。略明通教完毕。其次说明别教：此教明界外独菩萨之法，其教理、智断、行位、因果，别于前二教，别于后之圆教，故名别。",
 "《涅槃》说：「四谛因缘有无量相，非声闻、缘觉所知。」诸大乘经广明菩萨历劫修行，行位次第互不相摄，这些都是别教之相。《华严》明十住、十行、十回向为贤，十地为圣，妙觉为佛；《缨络》明五十二位；",
 "《金光明》只出十地与佛果；《胜天王》明十地；《涅槃》明五行。这些经增减不同，是因界外菩萨随机利益，岂能定说。然而位次周足，莫过于《缨络经》，所以今依它略明菩萨历位断证之相。以五十二位束为七科：信、住、行、向、地、等、妙。",
 "又合七为二：初凡、二圣。就凡又分二：信为外凡；住、行、向为内凡，也叫贤。约圣也分二：十地、等觉为因；妙觉为果。大分如此，下面细释。初言十信：一、信；二、念；三、精进；四、慧；五、定；六、不退；七、回向；八、护法；九、戒；十、愿。",
 "此十位伏三界见思烦恼，故名伏忍位（外凡），与藏教七贤位、通教乾慧地、性地齐。其次说明十住：一、发心住（断尽三界见惑，与藏教初果、通教八人地、见地齐）；二、治地；三、修行；四、生贵；五、具足方便；六、正心；七、不退（以上六住断尽三界思惑，得位不退，与藏、通二佛齐）；",
 "八、童真；九、法王子；十、灌顶（以上三住断界内尘沙、伏界外尘沙，前二不知名目），也叫习种性，用从假入空观，是真谛之理，开慧眼、成一切智，行三百由旬。其次说明十行：一、欢喜；二、饶益；三、无违逆；四、无屈挠；五、无痴乱；六、善现；七、无著；八、难得；九、善法；十、真实（断界外尘沙惑），",
 "也叫性种性，用从空入假观见俗谛，开法眼、成道种智。其次说明十回向：一、救护众生离众生相；二、不坏；三、等一切诸佛；四、至一切处；五、无尽功德藏；六、入一切平等善根；七、等随顺一切众生；八、真如相；九、无缚无著解脱；十、入法界无量（伏无明、习中观），",
 "也叫道种性，行四百由旬，居方便有余土（以上三十位为三贤，也叫内凡；从八住至此，为行不退位）。其次说明十地：一、欢喜（从此用中道观破一分无明，显一分三德，乃至等觉，俱名圣种性），此是见道位，又是无功用位，百界作佛，八相成道，利益众生，行五百由旬，初入实报无障碍土，初入宝所；",
 "二、离垢地；三、发光地；四、焰慧地；五、难胜地；六、现前地；七、远行地；八、不动地；九、善慧地；十、法云地（以上九地，地地各断一品无明，证一分中道）。更断一品入等觉位，也叫金刚心，也叫一生补处，也叫有上士。",
 "更破一品无明，入妙觉位，坐莲华藏世界七宝菩提树下大宝华王座，现圆满报身，为钝根菩萨众转无量四谛法轮，即此佛。有经论说：「七地以前名有功用道，八地以上名无功用道，妙觉位但破一品无明」，",
 "这些都是约教道而说。有处说：「初地断见，从二地至六地断思，与罗汉齐」，这是借别教的位名，来名通教的位次。有说：「三贤十圣住果报，唯佛一人居净土」，这是借别教的名，来说明圆教的位次。如此之类甚多，须细知当教断证之位：至何位断何惑、证何理。以此去判诸教、诸位，无不通达。",
 "略明别教完毕。其次说明圆教：圆名圆妙、圆满、圆足、圆顿，故名圆教。所谓圆伏、圆信、圆断、圆行、圆位、圆自在庄严、圆建立众生，诸大乘经论所说佛的境界，不共三乘位次，总属此教。《法华》中开、示、悟、入四字，配对圆教的住、行、向、地。",
 "此四十位，《华严》说：「初发心时便成正觉，所有慧身不由他悟，清净妙法身，湛然应一切。」这是明圆教四十二位。《维摩经》说：「薝卜林中不嗅余香，入此室者，唯闻诸佛功德之香。」又说：「入不二法门。」",
 "《般若》明最上乘；《涅槃》明一心五行。又经中说：「有人入大海浴，已用一切诸河之水。」又说：「娑伽罗龙注车轴之雨，唯大海能受，余地不堪。」又说：「捣万种香为丸，若烧一尘，具足众气。」如此之类并属圆教。",
 "今且依《法华》《缨络》略明位次，有八：一、五品弟子位（外凡，出《法华经》）；二、十信位（内凡）；三、十住位（圣初）；四、十行；五、十回向；六、十地；七、等觉（是因位之末）；八、妙觉（是果位）。初、五品位：一、随喜品。",
 "经中说：「若闻是经而不毁訾，起随喜心。」问：随喜何法？答：妙法。所谓妙法，即此心。妙心之体具足，如如意珠；心、佛及众生，是三无差别。此心即空、即假、即中，常境无相，常智无缘。无缘而缘，无非三观；",
 "无相而相，三谛宛然。初心之人知此，庆己庆人，故名随喜。内以三观观三谛之境，外以五悔勤加精进，助成理解。所谓五悔，有二：一、理；二、事。理忏者，如说：「若欲忏悔者，端坐念实相，众罪如霜露，慧日能消除。」",
 "即此义。所谓事忏，是昼夜六时三业清净，对着佛像披陈过罪：从无始以来至于今生，凡所造作的杀父、杀母、杀阿罗汉、破和合僧、出佛身血，以及邪淫、偷盗、妄言、绮语、两舌、恶口、贪瞋痴等，如此五逆十恶及余一切，皆随意发露，不再覆藏，尽除旧恶而不造新恶。",
 "若能如此，则外障渐除、内观增明，如顺流之舟更加桨棹，岂不迅速到达所止之处？修圆行者也是如此：正观圆理，以事行相助，岂不迅速到达妙觉彼岸？不要见此说便以为是渐次之行，以为圆顿无须如此之行，这就大错了！哪里有天然弥勒、自然释迦？",
 "若初闻「生死即涅槃、烦恼即菩提」「即心是佛」，便以为不动即到、不加修习便成正觉，那么十方世界尽是净土，所触所对无非觉者。如今虽然理上是佛，这只是理即，也是素法身，没有庄严，何关修证？我等愚辈初闻即空，便废弃修行，不知「即」之由来——鼠唧鸟空之讥广在经论，当寻究而深思。",
 "二、劝请：劝请十方诸如来留身久住、济度含识。三、随喜：随喜称赞诸善根。四、回向：所有称赞之善，尽回向菩提。五、发愿：若无发心，万事不成，所以须发心以导前四者。这就是五悔。以下诸位直至等觉，总用五悔，不再重出，依此类推可知。",
 "二、读诵品：经中说：「何况读诵受持之者。」谓内以圆观，再加读诵，如膏助火。三、说法品：经中说：「若有受持读诵，为他人说。」内解转胜，能导利前人，化功归于自己，心倍胜于前。四、兼行六度：经中说：",
 "「况复有人能持是经，兼行布施」等。因福德力之故，观心倍增。五、正行六度者：经中说：「若人读诵，为他人说，复能持戒」等，谓自行化他，事理具足，观心无碍，转胜于前，不可比喻。此五品位，圆伏五住烦恼，是外凡位，与别教十信位相同。",
 "其次进升六根清净位，即是十信。初信断见惑、显真理，与藏教初果、通教八人地见地、别教初住齐，证位不退。其次从二信至七信，断尽思惑，与藏、通二佛、别教七住齐，三界苦集断尽无余。所以《仁王》说：「十善菩萨发大心，长别三界苦轮海。」",
 "解释说：十善者，各具十善。若是别教十信，是伏而不曾断，所以定属圆信。然而圆教行人本不期望断见、思、尘沙，意在入住断无明、见佛性；譬如冶炼铁器，粗垢先去，并非本所期望，其意在于成器。器未成时粗垢自然先落，虽见其先落，此人并无一念欣喜之心。",
 "为什么呢？因未遂其所望之故。圆教行人也如此，虽非本所期望，却自然先落。永嘉大师说：「同除四住，此处为齐。若伏无明，三藏则劣。」即指此位。解释说：四住，只是见、思二惑——见惑为一，名见一切处住地；",
 "思惑分三：一、欲爱住地，欲界九品思；二、色爱住地，色界四地各九品思；三、无色爱住地，无色界四地各九品思。此之四住，三藏佛与六根清净之人同断，所以说「同除四住」。所说「若伏无明，三藏则劣」者：无明即界外障中道之别惑，三藏教只论界内通惑，连无明之名尚且不知，何况伏断？",
 "所以说「三藏则劣」。其次从八信至十信，断尽界内外尘沙惑，假观现前，见俗谛之理；开法眼，成道种智，行四百由旬。与别教八、九、十住及行、向位齐，是行不退。其次入初住，断一品无明，证一分三德，即解脱、般若、法身。",
 "此三德不纵不横，如世间的伊字三点、天主的三个眼睛，现身百界，八相成道，广济群生。《华严经》说：「初发心时便成正觉，所有慧身不由他悟。清净妙法身，湛然应一切。」解释说：初发心，是初住之名；便成正觉，是成八相之佛，这是分证果，即此教的真因。",
 "若说是成妙觉，就大错了。若是那样，二住以上诸位便徒然施设。若说是重说（重复），佛便有烦重之过。虽有位位各摄诸位之言，又说发心、究竟二者不别，但须知所摄之由，细识不二之旨——龙女便成正觉、诸声闻人受当来成佛记莂，都是此位成佛之相。",
 "慧身即般若德，是了因性开发；妙法身即法身德，是正因性开发；应一切即解脱德，是缘因性开发。如此三身皆开发于本有，所以说「不由他悟」。中观现前，开佛眼，成一切种智，行五百由旬到宝所，初居实报无障碍土，是念不退位。",
 "其次从一住至十住，各断一品无明，增一分中道，与别教十地齐。其次入初行，断一品无明，与别教等觉齐。其次入二行，与别教妙觉齐。从三行以后，别教之人尚且不知其名字，何况伏断？因为别教只破十二品无明。",
 "所以以我家的真因，为你们的极果。只因教愈是权、位愈是高；教愈是实、位愈是下。譬如边地未宁，借职则高；待定爵论勋，其位实低。所以权教虽称妙觉，其实只当实教中的第二行。其次从三行以后至十地，各断一品无明、增一分中道，即断四十品惑。",
 "更破一品无明，入等觉位，这是一生补处。进而破一品微细无明，入妙觉位，永别无明父母，究竟登临涅槃山顶。诸法不生，般若不生，不生不生，名大涅槃。以虚空为座，成清净法身，居常寂光土，即圆教佛之相。",
 "然而圆教位次若不以六即来判，则多有滥同上圣之虞，所以须以六即判位。如说「一切众生皆有佛性」「有佛、无佛性相常住」，又说「一色一香无非中道」等言，总是理即；其次从善知识及经卷闻见此言，为名字即；",
 "依教修行，为观行即（五品位）；相似解发，为相似即（十信）；分破分见，为分证即（从初住至等觉）；智断圆满，为究竟即（妙觉位）。约修行位次从浅至深，所以名为「六」；约所显理体，位位不二，所以名为「即」。",
 "所以深识「六」字则不生上慢，委明「即」字则不生自屈，可归可依，当思之择之。略明圆教位完毕。然而依上述四教修行时，各有方便与正修，即二十五方便、十乘观法。若教教各别说明，其文稍繁；义意虽异，名数不别，所以今总明，可以意知。",
 "所谓二十五方便，束为五科：一、具五缘；二、诃五欲；三、弃五盖；四、调五事；五、行五法。初明五缘：一、持戒清净。如经中说：「依因此戒，得生诸禅定及灭苦智慧，是故比丘应持净戒。」有在家、出家、大小乘的不同。",
 "二、衣食具足。衣有三种：一者如雪山大士，随所得衣蔽形即足，不游人间，因堪忍力成就之故；二者如迦叶等聚集粪扫衣，及只蓄三衣，不积蓄其余长物；三者多寒国土，如来也允许在三衣之外蓄百一众具。食也有三种：一者上根大士深山绝世，菜根草果随得资身；",
 "二者常行乞食；三者檀越送食、僧中净食。三、闲居静处：不作众事名「闲」，无愦闹之处名「静」。处有三种，依衣食之例可知。四、息诸缘务：息生活、息人事、息工巧技术等。五、近善知识，有三种：一、外护善知识；二、同行善知识；三、教授善知识。",
 "第二、诃五欲。一、诃色：谓男女形貌端正庄严——修目高眉、丹唇皓齿，及世间宝物、玄黄朱紫种种妙色等。二、诃声：谓丝竹环佩之声，及男女歌咏之声等。三、诃香：谓男女身香，及世间饮食之香等。四、诃味：谓种种饮食肴膳美味等。",
 "五、诃触：谓男女身分柔软细滑，寒时体温、热时体凉，及诸好触等。第三、弃五盖：谓贪欲、瞋恚、睡眠、掉悔、疑。第四、调五事：谓调心不沉不浮，调身不缓不急，调息不涩不滑，调眠不节不恣，调食不饥不饱。",
 "第五、行五法。一、欲：愿离世间一切妄想颠倒，愿得一切诸禅定智慧门之故。二、精进：坚持禁戒，弃除五盖，初中后夜勤行精进之故。三、念：念世间欺诳、可轻可贱，禅定智慧、可重可贵。四、巧慧：筹量世间之乐与禅定智慧之乐，得失轻重等。",
 "五、一心：念慧分明，明见世间可患可恶，善识禅定智慧功德可尊可贵。此二十五法为四教的前方便，所以应当具足。若无此方便，世间禅定尚且不可得，何况出世间的妙理？然而前面所明之教既渐顿不同，方便也有差异，依何教修行，临时审量即可。",
 "其次说明正修十乘观法，也是四教名同而义异。今且说明圆教，其余诸教依此类推。一、观不思议境：谓观一念心具足无减的三千性相、百界千如；即此之境即空、即假、即中，更无前后，广大圆满，横竖自在。所以《法华经》说：",
 "「其车高广」（上根正观此境）。二、真正发菩提心：谓依妙境发无作四弘誓愿，悲悯自己、悲悯他人，上求下化。所以经说：「又于其上张设幰盖。」三、善巧安心止观：谓体达前之妙理恒常寂然名为定，寂而常照名为慧。",
