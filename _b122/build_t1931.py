 "两名不同，行位无别。此人断三界见思，与声闻相同，更能侵除习气，所以位在声闻之上。其次说明菩萨位：从初发心，缘四谛之境，发四弘誓愿，修六度之行。一、未度者令度，即众生无边誓愿度，此缘苦谛之境；二、未解者令解，即烦恼无尽誓愿断，此缘集谛之境；",
