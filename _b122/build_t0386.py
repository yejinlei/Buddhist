"」那时佛告诉长老阿难：「你莫忧愁，莫再啼哭，莫大叫唤、搥胸、哽咽、闷绝、躄地。为什么呢？世间生者是有为法，会归于无常；想让这法不失不坏而恒常安住的，没有这个道理。」那时，世尊种种说法，安慰劝喻、示教利喜，嘱付法藏已，默然而住。",
"那时，世尊又作这样的念：「阿难比丘被忧愁之刺深入其心，我如今当拔除他这忧愁之刺。」告诉阿难说：「你如今想见未来之事吗？我见来世如同观现在，当为你宣说。」那时，阿难偏袒右肩、右膝著地，合掌向佛、顶礼佛足而禀白佛说：",
"「大德世尊！当为我说，如今正是时候。我闻法已，当奉受持、广宣流布。」佛告诉阿难：「谛听至心，我如今当说。阿难！未来之时有诸破戒比丘，身著袈裟游行城邑，往来聚落、住在亲里家中，他们非比丘又非白衣，畜养妇妾、产育男女；",
"又有比丘住在婬女家；又有比丘婬比丘尼；又有比丘贮畜金银，造作生业以自活命；又有比丘通致使命、以自活命；又有比丘专行医药以自活命；又有比丘围碁六博以自活命；又有比丘为人卜筮以自活命；又有比丘为人咒彼死尸令起、遣杀怨家以自活命；",
"又有比丘为人诵咒驱遣鬼神，多取财物以自活命；又有比丘专行杀生以自活命；又有比丘住僧伽蓝，私自费用佛法僧物以自活命；又有比丘内实犯戒、外示护持，受人信施；又有比丘虽不破戒而心怀悭惜，衣服、饮食，以及鄙吝众僧之物，不给客僧；",
"又有比丘虽不破戒，却悭惜众僧房舍、床座，不给客僧；又有比丘虽不破戒，为诸檀越供养礼拜而多得财利，其心不想让其余比丘受人信施，只想自己受用；又有比丘实非罗汉，却常诈称得罗汉果，想让人知道我是罗汉；",
"又有比丘多受檀越四事供养，内无实德、唯增贪心，只为活命、不为修道；又有比丘兴办商贾以自养活；又有比丘专行偷盗以自养活；又有比丘畜养象、马、驼、驴、牛、羊，乃至买卖以自养活；又有比丘贩卖奴婢以自养活；",
"又有比丘屠杀牛、羊以自养活；又有比丘受募入阵、征战讨伐、多杀众人以求勋赏；又有比丘穿逾墙壁、盗他财物以自活命；又有比丘专行劫夺、攻破城邑及与聚落以自活命；又有比丘毁坏佛塔、取其宝物以自活命。",
"像这样无量的地狱因缘，舍命之后都堕地狱。「阿难！譬如师子命绝身死，无论在空中、地上、水中、陆地，所有众生都不敢吃那师子的身肉，唯有师子身中自生的诸虫，还自噉食师子之肉。阿难！我的佛法不是别的所能破坏，是我法中的诸恶比丘犹如毒刺，破坏我三阿僧祇劫积行勤苦所集的佛法。",
"阿难！譬如有人入于大海，到宝渚中多取宝物放在船上，想渡大海却在中途沉没。佛之正法如同那宝船，将来破戒的诸恶比丘多乐造作种种恶业，灭我佛法、沉没不现。",
"阿难！如来所有正法的名味句义，所谓修多罗、祇夜、鞞迦曷罗、伽陀、忧陀那、尼陀那、阿波陀那、伊帝鼻利多伽、阇多迦、裴富略、阿浮陀达摩、优波提舍，这十二部经都被恶比丘所毁灭，那些人等，乐作文章、绮饰言辞。",
"多有这样诸恶比丘，破坏我佛法。」那时阿难禀白佛说：「世尊！将来之世，会有这样的破戒诸恶比丘出生吗？」佛说：「如是，如是！阿难！未来之世当有这样诸恶比丘出现于世，虽披法服、剃除须发，却破坏我佛法。」",
"」那时阿难作这样的念：「凭佛力之故，可以让我见到未来之世的这种事吗？」那时，如来以神通力，即令阿难都见到未来诸恶比丘，以儿子坐在膝上、把妇女放在身旁。又见到种种非法之事。那时，阿难见此事已，心中大怖畏、身毛皆竖，即禀白佛说：",
"「世尊！如来速入涅槃，如今正是时候，何必见这未来之世这样的恶事？」佛告诉阿难：「你意如何？如来刚才所说诸恶比丘的恶业报果，难道是其余之人所能知道的吗？」阿难禀白佛说：「世尊！唯有如来，才能知道这未来之世的诸恶业报。」",
"」佛说：「善哉，善哉！阿难！确实如你所说，唯有如来才能知道。阿难！你如今可曾见佛未涅槃时有诸恶比丘围绕如来、为他说法吗？」阿难禀白说：「没有这样的事。」佛说：「阿难！善哉，善哉！如你所说。如来现在实在没有这样的诸恶比丘围绕如来、佛为说法。",
"」佛说：「阿难！未来之世，多有在家白衣得生天上，多有出家之人堕于地狱、饿鬼、畜生。」又告诉阿难：「善恶之业终究不会败亡。我于过去曾作商主，入于大海，为活多人之故手杀一人，以此业缘乃至成佛，犹尚身受金锵之报。」",
"」那时，帝释天王与三十三天众，疾至佛所，顶礼佛足、退住一面。炎摩天王与百万亿炎摩天众，疾至佛所，顶礼佛足、退坐一面。删兜率陀天王与百万亿删兜率陀天众，疾至佛所顶礼佛足、退坐一面。化乐天王与百万亿化乐天众，疾至佛所，顶礼佛足、退坐一面。",
"他化自在天王与百万亿他化自在天众，疾至佛所，顶礼佛足、退坐一面。那时，毘摩质多罗阿修罗王与百万亿阿修罗众，疾至佛所，顶礼佛足、退坐一面。那时，娑伽罗龙王与百万亿龙众，疾至佛所、顶礼佛足退坐一面。",
"都于一念、一刹那、一无虚律多顷之间，诸天、阿修罗、迦楼罗、乾闼婆、紧陀罗、摩睺罗伽等，于虚空中遍满十二由旬，都为最后见如来之故。那时，佛告诉阿难：「这道场的菩提树最胜殊妙，过去诸佛都于此处证阿耨多罗三藐三菩提。",
"未来诸佛也于此处的阿耨多罗三藐三菩提。现在我身又于此处的破十八亿魔军得阿耨多罗三藐三菩提。阿难！我如今不久当般涅槃。再者，阿难！蓝比尼园最胜最妙，是佛如来最后生处。再者，阿难！",
"摩耶夫人是大福德，乃能生出人中之宝。再者，阿难！净饭国王是大福德，乃作一切众生中最胜宝之父。再者，阿难！毘舍离城、比嗜离国最胜最妙，王舍大城摩伽陀国最胜最妙，七庵婆罗树处也妙，瞿耽摩若尼俱陀树处也胜也妙，裴啰多豆啰多豆啰尼憩处也胜也妙；",
"力士生地，乃是过去转轮圣王解下宝天冠、在此安置辟支佛塔之处，是我焚身最胜妙之地。再者，阿难！这阎浮提最胜好处，众生在其中乐贪寿命，所以我如今在此涅槃。我于三阿僧祇劫所集之法不久当灭。」",
"付嘱法已，告诉阿难说：「我如今与你可往诸国。」阿难唯然受如来教。那时世尊至波波城，所应度者都已度讫。又往诸国教化无量百亿那由他众生，都成就已。那时，阿难随从佛行，这样次第至摩伽陀国道场菩提之树，世尊绕树作六匝已，即于树下结跏趺坐。",
"佛告诉阿难：「如来不久，后十五日当般涅槃。」那时，诸天、阿修罗、迦楼罗、乾闼婆、紧那罗、摩睺罗伽等，作这样的念：「如来不久于十五日当般涅槃，我们都当最后礼拜。」",
"而如来者离贪、瞋、痴。这三界处是众生出生之处，于三界中而此欲界，是诸众生修习三恶业，又造人身及与天业、色界无色界业，乃至非想非非想业。」说完这话，佛从座起。即时此地六种震动，无量百千万亿那由他诸天，于虚空中忧愁啼哭，这样说：",
"「像这样的众生中之宝，不久当灭。」随天竺三藏那连提耶舍译。那时，世尊离菩提树。毘沙门王与百万亿夜叉之众，同时举声悲啼雨泪、以手拭泪，而说偈言：「如来容色甚微妙，超胜众生无比者；如是庄严殊特身，不久之间当灭度。」",
"」那时，帝释天王又与百千亿三十三天众，同时举声悲泣雨泪、以手拭泪，而说偈言：「如来面相正圆满，形色殊胜于日月；一切人天应供者，我等不复得瞻见。」那时，须焰摩天王与百万亿须焰摩天众，同时举声悲泣雨泪、以手拭泪而说偈言：",
"「人中精进最雄猛，威力能破诸魔军；苷蔗种中释师子，今为无常所食噉。」那时，删兜率陀天又与百万亿删兜率陀天众，同时举声悲泣雨泪、以手拭泪，而说偈言：「见者无厌如药王，出世犹如大明灯；如是智眼今灭度，世间当复皆闇冥。」",
"」是时，化乐天王又与百万亿化乐天众，同时举声悲泣雨泪、以手拭泪，而说偈言：「安步不动胜师子，面貌圆满过月形；更不履行于此地，千辐相迹不复见。」是时，魔王他化自在天王，心大欢喜、安隐快乐，又与百万亿他化自在天众，疾至佛所、合掌向佛，",
"而说偈言：「诸恶众生已调伏，大粗犷尽永无余；何故犹住于世间，唯愿如来速涅槃。」是时，大梵天王瞋责那魔王，这样说：「咄哉！魔王大恶众生。诸佛如来是最胜宝，你如今为何想令世尊速入涅槃？」",
"那时，大梵天王又与百万亿诸梵天众，同时举声悲泣雨泪、以手拭泪，而说偈言：「于此现在及未来，梵天世界余天处；初未曾见如佛身，清净满足端严面。」那时，毘摩质多阿修罗王又与百万亿阿修罗众，同时举声悲泣雨泪、以手拭泪，而说偈言：",
"「佛色功德无有量，无有能尽其边际；利益修罗及余趣，今若灭度世间空。」是时，娑伽罗龙王与百万亿诸龙众等，同时举声悲泣雨泪、以手拭泪，而说偈言：「伊罗钵象数满千，不比如来一节力；如是大力雄猛者，今为无常所破坏。」",
"」是时，毘留勒叉天王与百万亿鸠槃荼众，同时举声悲泣雨泪、以手拭泪，而说偈言：「南无大觉妙莲花，从彼清净戒池生；示现无常不久相，今当倾坠永寂灭。」是时，毘沙门天王与百万亿夜叉众，同时举声悲泣雨泪、以手拭泪，而说偈言：",
"「如来面形如满月，光明照曜犹日轮；如是不久住于世，示为无常所吞食。」是时，毘沙门天王与百万亿夜叉众，同时举声悲泣雨泪、以手拭泪，而说偈言：「佛身金色最殊妙，三十二相自庄严；不久当为无常力，破坏清净大牟尼。」",
"」那时，提头赖吒天王与百万亿龙众，同时举声悲泣雨泪、以手拭泪，而说偈言：「如来身色甚希有，于三界中无有比；如是不久当灭度，为彼无常之所羂。」那时，大夜叉将名般脂迦与百万亿夜叉众等，同时举声悲泣雨泪、以手拭泪，而说偈言：",
"「佛声殊胜逾梵天，出过迦陵频伽声；如来不久当涅槃，不复更闻甘露法。」那时，夜叉大将名般遮罗与百万亿夜叉众等，同时举声悲泣雨泪、以手拭泪，而说偈言：「世尊金色光明身，功德庄严满月面；眉间白毫殊特相，我今最后归命礼。」",
"」那时，大夜叉将摩尼跋陀罗与百万亿夜叉众等，同时举声悲泣雨泪、以手拭泪，而说偈言：「三十有二上妙相，八十种好自庄严；当为无常金刚主，摧碎大圣牟尼尊。」那时，大夜叉将富那跋陀与百万亿夜叉众等，同时举声悲泣雨泪、以手拭泪，而说偈言：",
"「过去世中一切佛，及以未来诸世尊；大力释种师子王，无常师子之所害。」是时，大夜叉将摩俟利地迦与百万亿夜叉众等，同时举声悲泣雨泪、以手拭泪，而说偈言：「我今最后见牟尼，于是不复更奉觐；",
"最后礼佛千辐轮，丘墟悉平脚足者。」是时，大夜叉将佉陀罗迦与百万亿夜叉众等，同时举声悲泣雨泪、以手拭泪，而说偈言：「咄哉大恶无常相，破坏一切诸众生；如是众生无上宝，亦入寂灭不久住。」是时，大夜叉将名金毘罗与百万亿夜叉众等，同时举声悲泣雨泪、以手拭泪，而说偈言：",
"「我今归依礼佛树，生于持戒大地中；乃为无常之斧钺，不久斫倒大牟尼。」那时，大夜叉将娑多姞利与百万亿夜叉众，悲泣雨泪、以手拭泪，而说偈言：「眉间白毫相，照曜如月轮；目净如青莲，希有不复见。」",
"」那时，地神天与百万亿夜叉众，悲泣雨泪、以手拭泪，而说偈言：「我今礼雄猛，人中最殊胜；两足中最上，南无大牟尼。」那时，菩提树天悲泣雨泪、以手拭泪，而说偈言：「此处破魔王，及破魔眷属；大牟尼不久，无常魔所灭。」",
"」那时，祇林神悲泣雨泪、以手拭泪，而说偈言：「祇神林当空，竹林亦如是；无常坑极深，如来入不现。」那时，金刚密迹与百万亿夜叉众，悲泣雨泪、以手拭泪，而说偈言：「如是最胜城，亦是大丰地；舍释迦种姓，当向何方所。」",
"」那时，蓝毘尼林神悲泣雨泪、以手拭泪，而说偈言：「净饭国王先已灭，摩耶夫人亦灭度；如来今欲入涅槃，如是寂灭不可见。」那时，迦毘罗城神疾至佛所，悲泣雨泪、宛转在地，这样说：「如来涅槃何其太速，世尊涅槃何其疾哉！",
"世间眼灭。」而说偈言：「蓝毘尼园佛生处，长大在于迦毘城；其光出过于千日，今最后见更不见。」那时，菩提树神与诸天、阿修罗、迦楼罗、紧陀罗、摩睺罗伽，于虚空中出大音声，悲啼号哭而这样说：",
"「佛是众生最胜之宝，不久当没。」那时，世尊出于梵音，而告诉诸天、阿修罗、迦楼罗、乾闼婆、摩睺罗伽众说：「你们莫啼，莫作异语，莫生忧恼以手椎胸令心迷闷。哪有世间受生者，因缘和合的有为法而得久住？",
"若想强令无常之法不灭坏的，没有这个道理。」那时，世尊示教利喜诸天、阿修罗、迦楼罗、乾闼婆、摩睺罗伽等生欢喜已，是时诸天乃至摩睺罗伽等，右绕世尊、还向本处。佛告诉阿难：「我昔于那阿波罗龙王处，记罽宾国，我涅槃后其国炽盛、安隐丰乐如郁怛罗越，佛法炽盛、多有罗汉住于彼国，也有无量如来弟子。",
"这阎浮提所有罗汉都往彼国，犹如兜率天处。如来所有名身、句身，谓：修多罗、祇夜、鞞迦曷罗那、伽他、优陀那、尼陀那、阿波陀那、伊帝鼻利多剑伽、阇多迦、裴富略、阿浮陀达摩、优波提舍，那些罗汉，结集如来十二部经，广造诸论。",
