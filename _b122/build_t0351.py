"譬如三十三天游于杂园观，一切乐具都同等；迦叶！菩萨以至诚清净，为一切众生方便同等，都没有高下差异。譬如有毒，因咒药之故不能为害；迦叶！菩萨的结毒，因智药之故不能为害。譬如城邑有种种粪壤，能饶益田用；",
"迦叶！菩萨因结缚而学萨芸若（一切智）之用。所以迦叶！菩萨欲学此宝严经者，应当正观诸法。什么是正观？就是真实观诸法。什么是真实观诸法？就是不观我、人、寿命，这就是中道真实观法。「再者迦叶！真实观者，就是不观色有常无常，也不观痛、想、行、识有常无常，这就是中道真实观法。",
"再者迦叶！什么是真实观诸法？就是不观地有常无常，也不观水、火、风界有常无常，这就是中道真实观法。「再者迦叶！有常是一边，无常是二边，这二边中间无色，不可见也不可得，这就是中道真实观法。有我是一边，无我是二边，这二边中间无色，不可见也不可得，这就是中道真实观法。",
"有真实心者是一边，无真实心者是二边，无心、无思、无意、无识，这就是中道真实观法。这样，不善法、世间法、有诤法、有漏法、有为法、有秽污法，是一边；善法、出世间法、无诤法、无漏法、无为法、白净之法，是二边，这二边中间，无所有也不可得，这就是中道真实观法。",
"有者是一边，无者是二边，这二边中间，无所有也不可得，这就是中道真实观法。「再者迦叶！我为你宣说：无明缘行，行缘识，识缘名色，名色缘六入，六入缘更乐（触），更乐缘痛（受），痛缘爱，爱缘取，取缘有，有缘生，生缘老死、苦恼、忧悲、啼泣，这样就生起大苦之阴。",
"无明已尽则行尽，行尽则识尽，识尽则名色尽，名色尽则六入尽，六入尽则更乐尽，更乐尽则痛尽，痛尽则爱尽，爱尽则取尽，取尽则有尽，有尽则生尽，生尽则老死、苦恼、忧悲都尽，这样灭大苦之阴。没有这二边，也没有二行，中间可知，这就是中道真实观法。",
"这样，行与行尽，识、名色、六入、更乐、痛、爱、取、有、生、老死与老死尽，没有这二边，也没有二行，中间可知。迦叶！这就是中道真实观诸法。「再者迦叶！中道真实观诸法者，不以空三昧观诸法空，因为诸法自空之故。",
"不以无想三昧观诸法无想，因为诸法自无想之故。不以无愿三昧观诸法无愿，因为诸法自无愿之故。不以无行观诸法无行，因为诸法自无行之故。不以无起观诸法无起，因为诸法自无起之故。不以无生观诸法无生，因为诸法自无生之故。不以如观诸法如，因为诸法自如之故。",
"这就是中道真实观法。不以无人观诸法空，因为诸法自空之故。如此本空、末空、现在世空，当令依空、莫依于人。若有人依空、倚此空者，我说这人远离此法。迦叶！宁可倚著我见积聚如同须弥，也不以憍慢、也不以多闻而倚著空见，因为这不是我所能治的。",
"譬如良医应病与药，病去而药还在。在你迦叶看来如何，这人的苦患难道能除尽吗？」回答说：「不能！世尊。」「为什么呢？因为药还在体内之故。迦叶！空能断一切见，若有人倚著空见，我所不治，也是这样。譬如有人畏惧虚空，啼泣而说：",
"『如今应当为我去掉这虚空！』在你迦叶看来如何，他能去掉吗？」回答说：「不能。世尊！」「迦叶！若畏惧空者，我说这人极为狂惑。为什么呢？众生自己造作空，而他反而怕它。譬如画师画作鬼神像，自己反而恐惧。迦叶！诸凡愚人自己造作色、声、香、味、细滑（触）之法，轮转生死而不知此法，也是这样。",
"譬如幻师，化作幻人而吞食幻师，没有真实。迦叶！修行比丘，随其所思惟的一切都虚伪，而不真实、没有坚固，也是这样。譬如二木相因，更生起火而烧那二木。迦叶！因真实观而生无漏慧根，而那慧根即烧于真实观，也是这样。",
"譬如燃灯，诸冥都除，这黑暗无所从来也无所至，不从东方、南方、西方、北方而来，也不到那里去。迦叶！智慧已生、无智即灭，这无智者，无所从来、也无所至。迦叶！灯没有这样的念：『我当除冥。』然而灯一燃起，诸冥即除，灯与闇俱空，不可获取、无作无造，也是这样。",
"譬如迦叶！百年暗室，若燃灯的话，那黑暗难道有这样的念：『我当住在此处而不离去』吗？」回答说：「不能。世尊！这黑暗必定消灭。」「迦叶！若有众生在百千劫中造作结行，以一种正观的无漏智灯，即得除尽，也是这样。譬如空中不生五谷；",
"菩萨这样，不从无为之法而生出佛法。譬如大地众秽杂糅而生出五谷；菩萨这样，在世间杂糅、结缚之中才生出佛法。譬如陆地不生莲华；菩萨这样，不从无为之法出生佛法。譬如淤泥之水生起杂莲华；菩萨这样，从邪见众生结缚之中才生出佛法。",
"譬如醍醐，能满于四海；当知菩萨造作善根，也是这样。譬如一毛破为百分，以其中一分毛去取四大海的一滴水；当知声闻造作善根，也是这样。譬如迦叶！芥子中的空；当知声闻造作善根，也是这样。譬如十方虚空；",
"当知菩萨造作善根，也是这样。譬如剎利顶生王的皇后与贱人私会，后来若生了孩子。你意如何？应当说这孩子是王子吗？」回答说：「不是。世尊！」「迦叶！这些声闻从我法界而生，然而他们一切都不是世尊之子。譬如剎利顶生大王与贱女私会，后来若生了孩子，你意如何？",
"是贱人所生，应当说这孩子不是王子吗？」回答说：「不是。世尊！这是王子。」「迦叶！虽从贱女所生，却是王子。菩萨这样，初发道心，住于生死、教化众生，而他们一切是如来之子。譬如圣王，虽有千子却没有圣王之相，圣王之意便起「无子」之想；",
"迦叶！如来虽有百千声闻弟子之众，若没有菩萨，如来之意便起「无子」之想。譬如迦叶！圣王的皇后持斋七日，生下一童子，具足圣王之相，三十三天都共同赞叹，而不称说其余年长者。为什么呢？因为童子虽小却不断绝圣王种族之故。",
"菩萨这样，初发道心，诸根未具，那些天众中曾见过佛的都共同赞叹，而不称说诸阿罗汉具八解脱。为什么呢？因为虽初发菩萨心、诸根未具，却不断绝诸佛如来种族之故。譬如有小摩尼真珠，胜过如须弥山那样的水精；菩萨这样，初发道心，出于一切声闻之上。",
"譬如迦叶！圣王皇后初生童子，一切臣属都为他作礼；菩萨这样，初发道心，一切天人都为他作礼。譬如须弥山王出生诸良药，为一切人疗治苦患，无所偏颇；菩萨这样，学智慧之药、为一切人疗治生死之患，也没有偏颇。",
"譬如礼敬初生之月，不是礼敬后来的圆满盛月；迦叶！礼敬初发意菩萨者更胜，不是再礼敬得成如来、至真、等正觉者。为什么呢？因为诸佛如来是从菩萨而生的缘故。譬如迦叶！没有舍月而礼星宿的；同样，没有舍具戒德智慧的菩萨，而去礼敬声闻的。",
"譬如迦叶！一切天人不能用（水精）水精当作摩尼真珠；声闻这样，成就一切戒清净行，却不能坐在佛树下成于无上正真之道。譬如得到摩尼真珠的人，能获其余无量百千财宝；菩萨这样，出现于世，就有无量声闻缘觉出现于世间。",
"」于是世尊告诉尊者大迦叶说：「菩萨为一切众生求修诸善根、具备众智之药，往至四方，随病所应而如实治之。迦叶！什么是如实治？就是以恶露不净治欲，以慈心治恚，以缘起治痴。以空治一切见，以无想治一切四相，以无愿治一切欲界、色无色界。",
"以四非颠倒，治四颠倒一切行；以无常治非常有常想的一切行，以苦治苦有乐想，以无我治无我有我想，以不净想治不净有净想。四意止（四念处），治计著于身、痛、心、法：身身观者不起观身的我见，痛痛观者不起观痛的我见，心心观者不起观心的我见，法法观者不起观法的我见。",
"四意断（四正断）者，都断一切不善之法，修习一切善法。四神足者，舍身心之真想。五根五力治不信、懈怠、乱念、无智。七觉者治诸法无智。圣八道者，以此慧对治一切邪道。迦叶！这就是随病所应而如实治之。迦叶！菩萨应当这样学。",
"「再者迦叶！假使三千大千国土中一切有识者，都如同耆域医王。有人问他们：『用什么方药治那种病呢？』他们终究无人能答，唯有菩萨能全数答之。所以迦叶！菩萨应当这样念：『我不应只求世间之药，应当求出世间之药。』修一切善根，这就是众智之药。",
"往至四方，随众生之病如实治之。「再者迦叶！什么是出世智药？就是因缘智、无我人寿命智，解一切诸法空的无恐怖之心。他这样观：什么是心欲？什么是怒、痴？是过去吗？是未来现在吗？若是过去，过去心已灭；若是未来，未来心还未起；",
"若是现在，现在心不住。迦叶！心在未来、不在内、也不在外，也不在两者中间。心是非色、不可见，也无对、无见、无知、无住、没有其余的倚靠。迦叶！心是一切诸佛，不已见、不当见、不今见；若一切诸佛不已见、不当见、不今见，怎么能知有所行呢？",
"只是因为颠倒想的缘故才有诸法之行。诸法如幻化之法，受种种生之故。这心像风一样远行，不可执持之故；心像流水，不可停住之故；心像灯焰，缘相续之故；心像电光，时不停住之故；这心像雾，外事秽浊之故；心像獼猴，贪一切境界之故；",
"心像画师，造种种行之故；心不得住，随众结之故；心独无侣，常乐驰走之故；这心像王，为一切法之首之故；这心像母，生一切苦之故；这心像火焰，聚散一切诸善根之故；这心像鱼钩，于苦起乐想之故；这心像梦，于无我起我想之故；",
"这心像苍蝇，于不净起净想之故；这心像冤家，所作不可信赖之故；这心像罗剎，常乐求便之故；这心像憎嫉，常乐求过之故；这心不可爱，恩爱愚痴之故；这心像贼，断一切善根之故；这心著色，如蛾投火之故；这心爱声，如军乐战鼓之音之故；",
"这心爱香，如猪乐臭秽之故；这心著味，如使人乐其余之食之故；这心爱更乐（触），如蝇乐膻腥之故。求心无有也不可得；设若无不可得者，就没有过去、未来、现在；设若没有过去、未来、现在，就超过三世；设若超过三世，这就不是有、也不是无；",
"若不是有、不是无，就是无生；若是无生，就是无性；若是无性，就是无起；若是不起，也就不灭；若不灭，就没有败坏；若没有败坏，就没有来没有去；若没有来去，就没有生死；若没有来去、没有生死，这就是无行；",
"若是无行，就是无为；若是无为，就是圣贤之性；若是圣性，就没有戒与不戒；若没有戒与不戒，就没有威仪行也没有不威仪；若没有行、没有威仪、不威仪，这就是无心、无心数法；若无心、心数法，就没有业没有报；若没有报，就没有苦没有乐；",
"若没有苦乐，就是圣贤之性；若是圣贤之性，就没有业没有作。如此性中没有造作身业，也没有造作口、意业。此性平等，没有上、中、下，也没有差别，因为一切诸法都平等的缘故。「迦叶！此性远离，因为舍身口之故；此性无为，因为顺涅槃之故；",
"此性清净，因为离于一切诸结垢之故；此性无我，因为离我作之故；此性平等，因为离虚实之故；此性真出，因为要归第一义之故；此性无不尽、至竟不起，因为常如法之故；此性乐无为，因为都同等之故；此性清洁，因为至竟无垢之故；此性非我，因为求我不可得之故；",
"此性洁白，因为至竟清净之故。「你们，迦叶！应当求于内，反而去求于外。将来之世，会有比丘驰走如犬。比丘怎么驰走如犬呢？譬如有狗被人打掷而令它怖畏，它反而跑着去追掷打的人，而不去（躲避）掷打。迦叶！将来会有沙门、婆罗门，畏惧色、声、香、味、细滑、法，却反而乐在其中而不观于内，不知从何而得离色、声、香、味、细滑、法，不知不觉便入人间，又为色、声、香、味、细滑、法而得其便。",
