"若有人挝打骂詈，他默然承受而不报复；呵责瞋怒，比丘也不回报瞋怒，只观内身：骂的是谁？打的是谁？谁在受恚责？迦叶！这样的比丘就不走如犬。譬如御者，若马放逸便能制止它；修行比丘也是这样，若心驰散，随即制止、令顺不乱。譬如绞人的绳索，必定断送其命。",
"迦叶！一切诸见中若有计我者，必定断送慧命。譬如有人，随其所缚之处便都解开；比丘这样，随其心所缚就当立即除去。「迦叶！出家学道有二重缚。是哪二种呢？一是，学世间经典；二是，执持衣钵而不精进。「再者迦叶！",
"出家学道有二坚缚。是哪二种呢？一是，见缚；二是，贪财、名誉所缚。「再者迦叶！出家学道有二法障碍。是哪二种呢？一是，狎习白衣（在家人）；二是，憎嫉师友。出家学者又有二垢。是哪二种呢？一是，任取二结；二是，到知友家而向他乞食。",
"「再者迦叶！出家学道有二雹雨。是哪二种呢？一是，诽谤正法；二是，犯戒而食信施。出家学者又有二疮。是哪二种呢？一是，观他人之短；二是，自覆己短。「再者迦叶！出家学者有二烦热。是哪二种呢？一是，藏浊而持袈裟。",
"二是，欲令有戒行者承顺于己。出家学者又有二病。是哪二种呢？一是，憍慢而不观其心；二是，毁呰学摩诃衍者。「再者迦叶！沙门称说沙门，怎样是沙门称说沙门？有四种沙门。是哪四种呢？一是，色像沙门；",
"二是，诈威仪沙门；三是，名誉沙门；四是，真实沙门。什么是色像沙门？若有沙门成就色像，剔除须发、披著法服、手持应器，但他身行恶、口意行恶，不习调御、也不守护，犯戒作恶、贪而不精进，迦叶！",
"这就是色像沙门。什么是诈威仪沙门？若有沙门成就礼节，游步正智，饮食知止足，行四圣种，不乐众聚、道俗之会，少言少睡，然而他的威仪是诈伪而不真实，不期求净心，不习止息，而有见想，对空便起如坑之想，对习行空的比丘发起怨家之想，迦叶！",
"这就是诈威仪沙门。什么是名誉沙门？若有沙门奉持禁戒，为欲令他人知道他在持戒；精进学问，为欲令他人知道他在精进学；住止山泽中，为欲令他人知道他在住山泽；少欲知足、精勤独住，为欲令他人知道；不厌至死、不求离欲、不乐尽止、不欲求道、息心梵行不为泥洹，迦叶！",
