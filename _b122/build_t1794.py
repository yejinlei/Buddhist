"「不信三尊，以邪为真。」三尊，就是佛、法、僧。「优婆塞行五事不懈退，」梵语优婆塞，此云清信男。五事，即五戒，就是不杀、不盗、不邪行、不妄语、不饮酒。懈退，是说行之不专，或中道而废。",
"「至十事必得道也。」十事，即上文十善。得道，是说精勤不退，乃证道。佛言：「人有众过而不自悔、顿止其心，罪来归身，犹水归海，自成深广，何能免离？」愚迷之人日作众罪，既无退悔，恶积于心，致百殃之及身，若众流之朝海，积彼岁时，自成深广。",
"「有恶知非，改过得善，罪日消灭，后会得道也。」夫人善自知非，能改其过，日新之善渐积，过去之恶潜消，即于后会得明道。佛言：「人愚以吾为不善，吾以四等慈护济之。」四等慈，就是慈、悲、喜、舍，叫做四无量心，以护济愚人。",
"「重以恶来者，」愚人不知恩，又以恶意来相侵。「吾重以善往。」我也以善心诫之。「福德之气常在此也，害气重殃反在于彼。」我常以德报怨，所以福德之气常在于我。彼惟以恶行重凌善人，所以害气重殃是彼自招。",
"「有愚人闻佛道守大仁慈，以恶来，以善往，故来骂佛。佛默然不答，愍之痴冥，狂愚使然。」愚人闻佛守大仁慈，就恣意恶辱骂于佛。佛即默然不答，是怜惜彼之痴愚使他如此。「骂止。」愚人止其骂。「问曰：",
"「『子！』」佛乃问他。子，是男子之通称。「『以礼从人，其人不纳，实理如之乎？』」这是佛问彼之辞。「曰：『持归。』」这是愚人答。「『今子骂我，我亦不纳；子自持归，祸子身矣。』」恶人骂止，佛问说：",
"「如你施礼于人，彼若不纳，即你所施之礼，其理如何？」愚人答说：「我自持归。」佛又告诉说：「汝今骂我，我亦不纳，你自持归，祸及汝身。」",
"「犹响应声、影之追形，终无免离，慎为恶也。」佛言：「恶人害贤者，犹仰天而唾，唾不污天，还污己身；",
"「逆风坌人，尘不污彼，还坌于身。贤者不可毁，祸必灭己也。」奸恶之人害于贤者，犹如怨天仰唾，徒污于己；逆风坌人，惟坌自身。如那害贤之人，祸终灭己。佛言：「夫人为道，务博爱。」博行爱人。",
"「博哀施，」见彼危厄，博哀而救之。「德莫大施。」是说施之德最为大。「守志奉道，其福甚大。」夫学道之人既能博爱哀施，加以精进，则其福弥大。「睹人施道，助之欢喜，亦得福报。」见彼行施奉道，而能为彼欢喜赞叹，也获福报。",
"质曰：「彼福不当减乎？」佛言：「犹如炬火，数千百人各以炬来取其火去，熟食除冥。彼火如故，福亦如之。」质曰，是求质其疑。说助之欢喜，也获其福，疑谓会减彼哀施福报。佛乃答说：「犹如一炬之火，有数千百人各以炬来求之，或熟饮食、或照冥暗，而本之一炬也不减少，所以哀施福报也犹如于此。",
"」佛言：「饭凡人百，不如饭一善人；饭善人千，不如饭持五戒者一人；饭持五戒者万人，不如饭一须陀洹；饭须陀洹百万，不如饭一斯陀含；饭斯陀含千万，不如饭一阿那含；饭阿那含一亿，不如饭一阿罗汉；",
"「饭阿罗汉十亿，不如饭辟支佛一人；饭辟支佛百亿，不如饭一佛。学愿求佛，欲济众生也。」此十等校量，是因德有大小、障有厚薄，所以饭之者福报不同。又梵语辟支佛陀，此云独觉，所以说饭百亿独觉不如饭一佛。",
"何者？因运大慈，普济群生，其福深广不可思议，而供佛之报也最大。「饭善人福最深重。」这是说饭凡世善人福也深重。「凡人事天地鬼神，不如孝其二亲，二亲最神也。」然而善人中有二种：或能事天地鬼神，或能孝养父母。",
"比量福报，不及能事亲者。佛言：「天下有二十难：贫穷布施难；」凡人贫乏，自逼饥寒，而能辍己济人，这也难了。「豪贵学道难；」豪贵恣逸，无诸苦恼，而能厌其累尘，折节求道，所以为难。",
"「判命不死难；」",
"「不」字当为「必」字，是传承之讹。若世人明达因果，决志判命，或舍命身饲其猛鸷、济彼鱼鳖，乃至忠臣烈士以死殉义，这都是难。何以知当为必字？因佛说二十难并说凡夫境界，非论不生不灭之理，其义明白。",
"又据西戎南蛮语音呼「必」为「不」。「得睹佛经难；」凡人不具信根，不忧生死，则出世之教安得见闻？「生值佛世难；」夫人若不结胜因、不修众善，则诸佛出世岂得遭遇？实知难了。「忍色离欲难；",
"」六尘之中多为情欲所惑，而能制伏妄念，防其越逸，甚为难了。「见好不求难；」彼之所好，此或于求，遂之贻贪冒之名、违之招忿戾之患，所以能不求为难。「有势不临难；」势利之人、威福之地，而能唯道是从，不形趋附，也难。",
"「被辱不瞋难；」不忍小忿则兴诤端。非理相干能以情恕，这也难。「触事无心难；」心求清净，触境而兴。若能遇事不徇物情，这为難。「广学博究难；」怠惰则陷无明，多闻则有饶益。若能广究谊理，以资智虑，这为難。",
"「不轻未学难；」凡说群生同禀真性，而以能格物俗之常情之故，不轻未学为难。「除灭我慢难；」愚冥徇情，彼我慢生，违善兴诤，无不由此，若能除灭，所以为难。「会善知识难；」感物生情，理兹染习。",
"善恶之性，由是而迁，所以知识之善者，也难了。「见性学道难；」性本澄湛，迷于妄情；道本真常，昧于爱欲。能复本而见性，背伪而学道，为难。「对境不动难；」前尘妄境致惑真性，所以悟之而寂照、对之而不动的，难了。",
"「善解方便难；」常怀大慈以视众生，种种方便以为饶益的，难了。「随化度人难；」众生之性也有利钝，能于高下之中随化而度他的，也难了。「心行平等难；」痴冥之类合尘背真，若能怨亲、彼我一皆平等，这为難。",
"「不说是非难。」两舌妄言，世尊所戒。众生无明而有差别，若能平等不构是非的，难了。有沙门问佛：「以何缘得道，奈何知宿命？」佛言：「道无形相，」真如之性与虚空等，所以说无形相。",
"「知之无益。",
"」夫知而不学与不知同，必假修证乃可得道。「要当守志行，譬如磨镜，垢去明存，即自见形。断欲守空即见道，真知宿命矣。」夫想通宿命的，当须志行清净，常在禅寂，久则尘障尽消，潜通宿命，如磨镜去垢，乃见形了。",
"苟非断欲守空，何以得证道真？佛言：「何者为善？惟行道善。」佛言何者，是因各引一设之义。惟精进行道，渐至证圣，最为善。「何者最大？志与道合大。」断诸攀缘，得无漏智，志道吻合，最为寂大。",
"「何者多力？忍辱最健，忍者无恶，必为人尊。」忍辱之人不怀仇怨，如那勇健多力之人能拒强敌，内不怀恶，终为人所尊。「何者最明？心垢除，恶行灭，内清净无瑕。」如白圭无玷、晴空绝云，是心之最明。",
"「未有天地逮于今日。」极言其远大。「十方所有未尝不见，得无不知、无不见、无不闻，得一切智，可谓明矣！」这是已证果位，得一切种智，所以于三世具正遍知，是明之至。佛言：「人怀爱欲不见道者，譬如浊水以五彩投其中，」",
"浊水譬喻染心，五欲比喻五彩，心欲相投，交错其中。「致力搅之，」浊水五彩已不可分，仍用力搅之，比喻世人妄想贪爱，发乱其五欲。「众人共临水上，无能睹其影。爱欲交错，心中为浊，故不见道。若人渐解忏悔，来近知识，水澄秽除，清净无垢，即自见形。",
"」浊水之上，虽众临之，无能睹影。爱欲交乱，真心昏惑，岂得明道？若秽浊尽去，心归清净，即自然见道。",
"「猛火著釜下，中水踊跃，以布覆上，众生照临，亦无睹其影者。心中本有三毒，涌沸在内，五盖覆外，终不见道。",
"」釜比喻染心，水踊跃比喻染心中贪、嗔、痴三毒烦恼踊跃。以布覆上，比喻凡夫被五盖蒙翳，终不得见道。五盖，就是一贪欲、二嗔恚、三痴、四掉举恶作、五昏沉睡眠，都为盖覆。「恶心垢尽，乃知魂灵所从来、生死所趣向，诸佛国土、道德所在耳。",
"」精勤坚固，渐证果位，于禅定中乃知魂灵之所从来，乃无常报尽，生诸国土，道德所在。佛言：「夫为道者，譬如持炬火入冥室中，」冥，是暗。「其冥即灭，而明犹存。」「犹」字当为「独」，犹字殊无义。",
"「学道见谛，愚痴都灭，无不明矣。」夫已见道，愚痴自灭。渐证佛智，德无不明。犹如持火入诸暗室，冥暗都灭，而明独存。佛言：「吾何念？念道。」佛训诱弟子说：「我常念道，更无杂念。」「吾何行？",
"行道。」应物利生，常行于道。「吾何言？言道。」佛所言说，惟谈于道，利益有情。「吾念谛道，不忘须臾也。」念真谛、圣道，未尝须臾忘。佛言：「睹天地，念非常；睹山川，念非常；睹万物形体丰炽，念非常。",
"执心如此，得道疾矣。」夫对天地、睹山川及万物形体，虽然丰盛，当念皆是有为生灭，终归无常。修行之人若常如此起念，即证圣必速。佛言：「一日行，」是说终一日念念修行。「常念道、行道，遂得信根，其福无量。",
"」若人于一日之中而能修习，常念于道，忆持不忘。或于一日而常行道，修习不怠。乃能成就信等诸根，得无量福。一日尚且如此，何况多日，其福弥盛。佛言：「熟自念身中四大，各自有名，都为无吾。我者寄生亦不久，其事如幻耳。",
"」有情之身，都是四大假合以成其形，仍假虚名。且地水火风名叫四大，以要言之，即骨、肉、毛、发是地，津液、精、血是水，暖触是火，四支百脉摇动是风，各以假名成此幻身。若熟念之，何者为我？",
"寄生浮世，倏忽而灭，都如幻梦罢了。佛言：「人随情欲求花名，譬如烧香，众人闻其香，然香以薰自烧。愚者贪流俗之名誉，不守道真，花名是危己之祸，其悔在后时。」凡世之人但恣情欲，惟求虚花之名，不忧生灭，不慕真实之道。",
"譬如上妙之香被人所焚，虽得远近普闻，其形质却速尽。也同愚者徒慕虚名，而丧道真，及祸至危己，悔在后时。佛言：「财色之于人，譬如小儿贪刀刃之蜜，甜不足一食之美，然有截舌之患也。」夫耽嗜财色少时快心，及恶积祸来，沉沦六趣，也如小儿刀刃之蜜，其甜味至少，徒有截舌之祸。",
"佛言：「人系于妻、子、宝、宅之患，甚于牢狱桎梏。榔档牢狱有原赦，」牢狱之苦，或值赦免。「妻子情欲虽有虎口之祸，已犹甘心投焉，其罪无赦。」夫世人为妻、子羁绊，宝、宅萦心，祸患难免，甚于牢狱。",
"佛言：「爱欲莫甚于色，色之为欲，其大无外。」世间诸欲缠缚难解的，莫甚于色，所以知色欲之过，其大无比。「赖有一矣！假其二同，普天之民无能力道者。」滋生死、障涅槃，唯色欲一端，《楞严》也说：",
"「淫心不除，尘不可出。」佛言：「爱欲之于人，犹执炬火，逆风而行，愚者不释炬，必有烧手之患。贪淫、恚怒、愚痴之毒，处在人身，不早以道除斯祸者，必有危殃，犹愚贪执炬，自烧其手也。」凡世有贪淫、恚怒、愚痴之毒处人心中，若有智者，须早以道消去，乃免危殃之祸。",
"犹如愚人不早释逆风之炬，必自烧其手。时，有天神献玉女于佛，欲以试佛意、观佛道。天神，是主天界之神。玉女，是天女。是因天想试佛之意，观佛之道如何。佛言：「革囊众秽，尔来何为？以可诳俗，难动六通。",
"去！」是遣去。「吾不用尔。」天神愈敬佛。如皮囊中贮诸秽恶，难惑六通之佛。六通，就是神境通、天眼通、天耳通、他心通、宿住通、漏尽通。因问道意，佛为解释，即得须陀洹。天既知神通不可惑乱，因问道意，佛为说法，得证初果。",
"佛言：「夫为道者，犹木在水，寻流而行，不左触岸，亦不右触岸，不为所人取，不为鬼神所遮，不为洄流所住，亦不腐败，吾保其入海矣。」木比喻于人，海比喻于道。「人为道，不为情欲所惑，」修行之人坚持戒行，不被情欲所惑，如木在流，不为二岸所触。",
"「不为众邪所诳，」正见之人坚持操行，不被众邪诳惑，如沿流之木免其人、鬼所取。「精进无疑，吾保其得道矣。」木无众滞，自至于海，如人之精进，免其诳惑，必得其道。佛告沙门：「慎无信汝意，汝意终不可信。",
"」是说当慎守正心，勿信纵邪意。若信纵之，即为烦恼牵惑。「慎无与色会，色会即祸生。」惟举色，是因色能惑乱，入生死苦海，为祸根最大。「得阿罗汉道，乃可信汝意耳。」因阿罗汉烦恼断尽，任纵其意，必不入邪见。",
"佛告诸沙门：「慎无视女人，若见无见，慎无与言。」熟视其色，当生欲情。若每见之，想如无见，仍诫勿与交言。「若与言者，敕心正行。」若不护己，为缘事故，须至言语的，即默自诫，如下文。「曰：",
"」是默语。「『吾为沙门，处于浊世，当如莲花，不为泥所污。』」若欲发言，先正其心自诫说：「我持净戒，处兹浊世，当如莲花，虽在淤泥，不为所污。」「老者以为母，长者以为姊，少者以为妹，幼者予敬之以礼。",
"」凡见女人，当作此观想，仍皆待之以其礼。「意殊当谛惟，」谛，是审，惟是思，是说当审思之。「观自头至足，自视内，」意殊，是说情炽盛，用前观想未能止息的，即想自己头至足，收视于内。「彼身何有？",
"唯盛恶露诸不净种。以释其意。」既内视，当想身中盛诸不净、秽恶之物，露泄不止，即邪意当息。彼身，是自称此身。",
"佛言：「人为道，去情欲，当如草见大火来已劫，道人见爱欲，必当远之。」",
"佛诫修道之人，去其情欲，当如枯草已被大火焚劫，是说急切速避之。",
"佛言：「人有患淫情不止，踞斧刃上以自除其阴。佛谓之曰：『若使断阴，不如断心。心为功曹，若止功曹，从者都息。』」功曹，是主者之称。从者，是功曹之从人。在上位者若严率其下，则从者自然凛惧，所以以心比喻功曹，欲情比喻从者。",
"若自净其心，欲情岂能得生。「『邪心不止，断阴何益？斯须即死。』」佛言：「世俗倒见，如斯痴人。」有淫童女与彼男誓，至期不来，而自悔说：「欲吾知尔本，意以思想生，吾不思想尔，即尔而不生。",
"」佛行道闻之，对沙门说：「记之，此迦叶佛偈流在俗间。」过去诸佛知众生罪业皆从妄想生起，妄想若息，即无诸恶。所以迦叶佛曾作此偈，流传于后。及释迦佛因行道，闻此女自悔而诵，故令沙门记之。",
"佛言：「人从爱欲生忧，从忧生畏。无爱即无忧，不忧即无畏。」夫为前境所诱，乃起爱欲。既为爱欲所惑，忧畏随之而生。若本无爱欲，即忧畏何由而至！佛言：「人为道，譬如一人与万人战，」夫一人敢敌万人，是勇猛之极。",
"譬喻修道之徒发精进、果决之志。「被甲操兵，出门欲战，意怯胆弱，乃自退走、或半道还、或格斗而死。」意怯胆弱乃是退走，以至半道而还，都比喻修行之人中路退心。格斗而死，比喻学道之人无坚刚之志，毙于诸魔。",
"「或得大胜，还国高迁。」夫将兵者或立殊勋，而施则爵赏自然超于众。「夫人能牢持其心，精锐进行，不惑于流俗、狂愚之言者，欲灭恶尽，必得道矣。」夫被精进甲，仗智慧剑，坚持戒行，魔障尽灭，证无漏智，乃得道。",
