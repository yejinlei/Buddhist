"」问：「什么叫广戒？」答说：「广戒，是说能摄身之三殃、守口之四过、捡意之三恶。身行的，若见一切众生、蚑行蠕动之类，怜悯哀伤，放而活之，随其水陆，还而安之。若见众宝珍琦、柔软细滑可意之物，虽身贫苦，也在内降伏其心，不令贪取。",
"「以及见细色脂粉的装饰，则内观朽烂脓血的臭秽，这是身之三戒。口行的，是说对方若以四过加于自己，则能觉知口的过失，报以善言和语，至诚不饰，答而化之，使其反而从己，这是口之四戒。意行的，则心习智慧，思惟生死，常住慧处，不惑于流淟。",
"「又深入道品、空无之要，别了真谛而无疑难。见善则劝，他人成则代为欢喜，这是意之三戒。所以行道之始，先于十戒，既能自为，又化他人，勤而不懈，行而不休，都无懈怠厌倦之想，所以叫广戒。」问：「什么叫广忍？」答说：",
"「广忍，是说若有人骂我，计从声音而出、音来到此，观了无形；本来音之来，出于心意，观于心意，也复无形。察心所倚，倚于四大，四大还本，则也无名、也非彼我、也非男女、也非老少，计了无主。惭辱所在，只是无形而立字。",
"「于两无之中，又也无相，计此三者，空无所有。智者散意观虑如此，则瞋恚不生，以空忍空，又于众恶，忍而不为。对境来而不起，捡心伏意，身自能如此，又教诲他人，这叫广忍。」问：「什么叫广精进？」「减于多食，不味于味；",
"「除于睡卧，惊意晨夜。远俗近道，行于众戒。坐起之法，不失其仪，无犯之行，当习于心；道品之要，汲汲乐诵，昼则勤受，夜则经行。语则应律，身口意并，从倚忆法，不离经文。坐而广说，意不以烦，开教愚顽，不以懈劳。",
"「违心反意，自达专精，身既自能，又教诲他人。这叫广精进。」问：「什么叫广一心？」「孝事父母，则一其心；尊敬师友，而一其心；断爱远俗，而一其心；入三十七品，而一其心；空闲寂寞，而一其心；在众烦乱，而一其心；",
"「多欲多诤，多作多恼，于是等处，而一其心；褒讪利失，善恶之事，于是不动摇，而一其心；数息入禅，舍六就净，而一其心。身自能行，又教他人，这叫广一心。」问：「什么叫广智慧？」",
"答说：「明士随于受身，就有三痛、六患、五蔽之垢、六十二沉吟之想、八十八难解之缚、千八百锋疮之痛。",
"「像这样的事，就用智慧一一开解了。观其所起，察其所灭；视其所病，选以何药。既总其要，令身不毁戒，意不入俗。处众爱之中，心在道品之藏；寄六患之舍，心在六净之堂；住五蔽之室，心在断灭之户；倚不固之屋，心思方便之护；",
"「坐蛇蚖之地，心念舍远之径；乘坏船之险，心图自济之路；近盛火之林，心推灌灭之安。所以明士行智慧之便，拔出生死之难；绝三界之想，就灭度之地。既自身行，又教他人，这叫广智慧，是六德之行的义理。",
"「今日得大福，令一切人疾速得逮此行。」善明当时就得四净法，一是眼净、二是身净、三是口净、四是意净，欣然低头，默思法义。于是，善明避坐长跪，启白如来说：「天尊所说，广度无极，法禁微妙，捡摄意态，伏心就净，殃垢消灭，其闻此者功德已大，何况履行，其德难以称量。",
"「天尊又说，前世非但行此六事而已，又行定意之法以及总持无底边三十七品，乃成具佛事、四无所畏、十种力、十八神妙特异之法，变化自在，所说无难，而面见诸佛，飞到十方而授一切未度者，率化度之；",
"「而坏邪藏，将导曲邪；而生于受苦之中不著、不断，以不著、不断，作因缘行，教诸惑者。如此妙德，无央数事行，何等定意能致得之？唯愿天尊！为今现在及未来者，演说其深义，令获解脱。」佛说：「善哉！",
"「善哉！你所想问的，今为你分别，具敷大要，整意善听。」就说：「受教。」佛说：「有定意法，名叫成具光明。若有人听闻此法的，若能履行一日至七日，其功德福不可譬喻。听闻此法的人，先世已供养百千亿佛，已在其座前亲闻而不疑，今生才能再值遇这成具光明定意法。",
"「如今能得修行此定，如弹指顷，就长离三恶道，功德渐满，疾速至佛。刚才所问诸事，都能成具。」善明说：「当行几事而得到这尊定？」佛说：「当净行一百三十五事，才能入此定。远身行、离口过、除意念、尽三秽、却六患、遏五蔽，十二因缘已捐尽，解结，明六十二沉吟行。",
"「愈众疮、悦众恼、舍诸大、弃骨血、避亲属、绝诸习、断于爱、无诸可无不可、铲贪垢、刈欲根、不惑流、能制疾、不我计、无不我、立四信、住四止、就四断、插五根、习五力、晓七智、履八正、入八念、八常勤，为已无勤可行，离不可行。",
"「学上智、自尊意、不贡高而柔濡、雨法雨，于一法不两计、不三想、不为无益想、无有际想、不空想、不想想、想无处、不住无处想。善惟佛知佛净、已知净而善学、心正住、不邪还、等善恶、如明冥、于明冥知俱空、不疑法、不以有净无、观有无本为一。",
"「已知一而除一，不于一而起想，勤受教、善习行、因习行入无际、习胜意、不听心、善防识、不乱转。往来三而不著、察诸性了无根、知无根不可满、以不满而自整。缕观法为同无，常住无绝无想，常无常以过上，不念人、不宥世、不著物、罢舍求，法合离了无见、身生殁皆由化、上中下知法等，于是世往后世。",
"「观二因如虚空、心无欲而常仁、行清白善诱人、知人向为反浊、于反浊而清澄、心远爱筋入火、以净火烧众垢、已尽垢寂然净、不念善不念恶、不惟好不惟丑、不念苦不念乐、于毁誉无欢怒、心调净所在入、开大藏入大法、以道律护满法、苦习审勤承行。",
"「以尽道为光曜，视一切性识起，流结冥意思止，勤求止以入道。剪三爱、除四失、增四城、离五覆、绝六慢、修六敬、具六法证、行七慧、强八力、拔九结、习九灭、十弘净为己能、十力慧已备足、十直法不复学、慧法种而常存、于三宝已能备，以法施无极尽，于诸专能备行、入无所著、入空无懈、却无吾念、无我想、无人计、无筹算、寂如灭度。",
"「这就是一百三十五事成具光明定意戒法之行。」佛说这成具光明定意戒法品时，三十万明士得到这定意功德成具，立于第十之地。善明则得无所从生法忍，五百同辈人，心欣意悦，都发无上独尊平等觉意。四十万明士都立不退还行。",
"除恶众五万人，都得无所著道。持五戒的贤士、贤女二千人，都得履迹之行。诸天在虚空中，而作音乐。叹说：「快哉！世人竟获上闻之要，那些愚暗尘埃浊秽的，今日霍然除尽。如净水洗浴尘垢，如今闻大法，心垢为之消除。",
"「愿令法轮常转，使一切疾速得逮妙慧。我等常遇天尊，所生之处不离。疾得这成具光明定意，当广宣法恩，还照流冥。如今日大会，兴立无数道本。」善明禀白佛说：「如今闻天尊这定意，净心自思，观我无黠慧之心，了不知处，于外、于内也都是这样。",
"」佛告诉善明：「譬如暗室中执炬而入，就不知暗之所在，这定意法若能履行、道品成具，就不知无黠十二牵连之所失了。善明！非但如此而已，则不见十方生死起灭之处，乃至履迹无著、因缘觉佛，乃至如来，都无见、无所想见、非见。",
"「无所想、一切清净想、止清净想、也不止清净想，这叫空见无所见。」善明禀白天尊：「为什么不止清净想就叫空见？当那时，心在何处？所见何等？」佛说：「善明！于那时，心不在内、不处外，不在于道、不在于俗，不在于有、不在于无，不在于起、不在于灭、不在于动摇之处。",
"「这心无根际、无音响，本末了索，应当这样见。这见为见、为空、为灭，为都无所有的定意之法。以此为见，明士当作这样的计念，除念就净。作这样计念的，就是应合成具光明定意之教法。这法是无所有之法，所以勉强给它立名。",
"「明士听闻此，不要惊怪不要疑惑，谛而思惟其法，不退不懈，这就是已得定意威神之护力。善明！其想学此的，当行四事，渐渐入于无见之处。」问：「什么叫四？」「一、不有身，二、不有居，三、不有世，四、不有物。",
"「能如此的话，就得入四要。」问：「什么叫四要？」答：「一是佛要、二是法要、三是空要、四是灭要。这叫四要。」佛当时叹说：「无彼无我想，亦不无黠计；十二因不著，是应成具足。这定法本无，非有住立处；",
"「哀悯世间而现其名，空行也合仪。人心并意识，这三者为起法；行此即成具足，无起无所灭。空为成具之地，生死苦断离；一切无余迹，是合定意行。世人转相倚，邪见著名法；贪有利常想，缠缚无数世。积行常缀碍，忧恼著意戚；",
"「四变如随影，往来无休息。行定无所倚，正观不著名；贪尽想得灭，解缚清净安。净行不挂惑，惑恼意了无；生老病已绝，无复往来忧。慧眼明已大，智本无边底；黠使度无极，行定乃致此。世间火星月明，日曜昆仑光；",
"「释梵殿所照之处，这定明超过其上。」佛告诉善明：「乃往昔无数劫时，有佛名叫尊伏欲王。当时佛住世寿十万岁，不在这南天竺止住，自于今北方净耀天归佛所住处就是，彼国离此三亿万佛土才能到达。尊伏欲王佛时，人寿二万岁，常有可随从弟子六十万人，明士众不可计。",
"「国民炽盛，丰饶宁静，大都贤行，戒德相高，欲贪三垢微薄。当时佛大会十方明士，普受持说这成具光明定意，便而成具佛事，在于四署之一数。那时，有位长者子名叫敏见，年五百岁，当时国人以为还是少年。敏见听闻佛大会，就启白二亲，乞求前往诣佛，观看佛的所作。",
"「父母听许他前往，即往见佛，稽首于地，礼竟正住，喜心兴盛，便脱下身上的珍琦杂宝璎珞，散于佛上；以佛神威，应时所散之物，化成花盖，到覆大眾，人人各别。佛令他就座，为说这成具光明定意法，心又增欣，当时就发愿说：",
"「『令我受生之处常遇这成具光明定意，疾能履行，不亏损戒德。』那时少年以一切宝布施，发一言之至愿，因此之故，所生之世每每得以受持。善明！你可知道那时的少年吗？就是你的此身。如今我出世，你又遇值这定意。从今以后，必不久得；",
"「得慧之后，二百劫当具成佛，号导世王。为天上天下之独尊，当化导愚冥如我今日。」善明闻佛授他封拜之名，则心净体轻，譬如琉璃水精中外洁净，一切无秽，以所置之处，并后净其心如此，当时就得十憺然法：",
"一是澹然不以所见为动，二是于诸烦劳之事澹然常足，三是于众想澹然不想，四是流俗所乐汲汲之事澹然而饱舍，五是于德不德澹然不念求、不念否，六是善法、恶法澹然不著，七是谦者、贤者澹然不望荣耀，八是敬养舍弃澹然无欢怒，九是一切如法失法澹然同其原，十是以入净寂若处不净，能以法化，澹然无著别、无厌舍之念。",
"心既如此，因而禀白说：「天尊！如今授我封拜之要，我当报恩宣开一切，令未闻者闻，未知者知，未度者度之。我生死常多，虽多、虽久不以为劳。已不著、已觉、已能整、已为不惑、已能入其被服，随因缘而示见之，我不把生死当作生死，我受佛威神已全部明了。",
"「我有同辈五百人，愿天尊加四等之大慈，勉力引入法，令疾解这成具光明定意。」于是佛微笑，都见光从佛口而出，五色炜晔，光明连接十方，那些在痛苦中的，一时得安，光还从顶入，自如常辉。侍者阿难整肃衣服避坐，叉手启白说：",
"「佛未曾无故欣笑，笑必有缘故。唯愿敷演，散告未闻。」于是阿难，就而叹说：「面部人雄之颜，眼鼻口正端；金体极软细，今笑何盛欣。方口含白齿，唇像朱火明；姿美八十种，今笑必有因。镜齿牙四十，广舌颊车方；",
"「语则香气发，今笑为谁而成？眉髭绀青色，眼睑双部当；白毫天中立，今笑唯愿闻。天眼已了朗，道眼已备通；法眼与慧眼，此四已具成。笑必有感应，启化于未成；或者当受拜决，所以笑发金颜。」佛告诉阿难：",
"「佛真不妄笑！如今善明所带的五百贤士，前世已供养二百亿佛，已在其座前，闻这成具光明慧中一百三十五行，自从初闻历经之世甚多，然而常刚猛，只在小善之数，未能伏心受持清净最妙定行。虽然如此，以闻法的功德，所生之处不在三恶处，常遇值这尊定之法。",
"「今日来会，净心听受，渐渐解释开入正谛。后来慈仁佛出世，当在那时，得到这成具光明定意。却后三十六万亿劫，都成为佛。当又以这法教化，所领国土各各有名号，有名叫幢节布耀王、其次名叫大光遍显、其次名叫大势伏恶、其次名叫猛盛威德、其次名叫流水净音、其次名叫高德普接、其次名叫景现除结、其次名叫化幻自在，名号各各如此。",
"」于是，五百贤士听闻所受的记决，欣悦踊跃，就得五无转心：一是祠祀求福之心不转为；二是一切五味的可否，都是众生之神命，终不转为害生之可口；三是正立于无上独尊之行，终不转动舍就小道；四是知这法尊贵无有与等者，勤心修行，虽有他法，只是杂异之虚而已，以法心观别终不转为；",
"「五是纵使世间有佛、无佛、法兴、法衰、有终、有绝，心在定意，不因无此三宝之故转为邪业。这叫五无转心。已得这心法之义，都上前长跪禀白天尊说：「佛哀悯我等！告其封拜成佛之名，我等当报恩。以后若所生弊恶之世，当勤修正行，奉宣尊法，开化未知，乱者正之、懈者勤之、却者勉之、倾者扶之、缺惧者补完之、冥者照之、结者解之。",
"「为杀者说夭逝之殃、为盗者说贫乞之苦、为淫者说身之祸、为谗佞欺者说灭性之患、为醉乱者说危身之变。我等今日并在佛前，誓立五愿，作明士行乃至成佛，行之无休已。愿佛哀悯我等！听我等所言。第一之愿：",
"「我作明士行，疾令身而变化周流十方。若世间无佛，四辈弟子或有知法的，说：『确实有佛，只是已灭度罢了！』俗人邪见疑网生起，不见佛有、不知法，就说：『无佛，只是虚妄罢了！若真有佛，为何不见其威神呢？』两方争论如此。",
"「当争论之时，我便当前往化度，现佛身相好照明，又化威神，在这两个争论的人前令他们看见，知道确实有佛，并告诉说：『你们不要疑惑！』这疑人即当惊喜，因而为他说法教度脱之，已便化去，如此无极。第二之愿：佛有大妙极深无量法门十二部要。",
"「佛灭度后，弟子各学一经、偏执一卷，不能遍洽，未解四说方便之等，便转相问难。或说虚、或说有，说这义应当如此、这不应如此，真知法义者的言辞相貌，不晓义者贪著名字，修饰相貌状如解达，便于众会之中，两方争论兴起瞋恚，舍善就恶。",
"「当这争论之时，我当前往现身变化，有超越于众，令众肃然，便为之断说，分别是正者。牵引经文开示，令双方都欢喜，已便化去，如此无极。第三之愿：佛灭度后，俗人外智之士，进入佛弟子大眾之中，弟子论说法义，言及众道，分邪别正，差品高下，便说：",
"「『这道在九十六种之中，佛为尊吗！佛有四神足飞行变化，天上天下无如佛之智者。』俗智之士生来不睹佛，习于邪见，信小毁大，便对佛弟子说：『你不要妄说，说佛神足飞行变化，先古以来，人的品类，没有这样的。",
"「『实在是不实之言。』当此之时，我便化作佛身相，示诸种好，现于神足，经行空中，身出火水，令诸俗人、外智之士肃然而惊，才知威神之化。于是为他说法，授以正戒，毕乃化去，如此无极。",
"「第四之愿：若有人读诵佛经，独在野室，或在山间，或于大国。尊姓长者，以及人民，没有师法，或者师不明，顽钝无所问，心用疑网。我化作道人，被服前往其所在之处，句句为他解释，本末分明，疑意权开，令入微妙而无疑难。已便化去，如此无极。",
