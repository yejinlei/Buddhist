"反过来说：「我与世间有限，我与世间无限，我与世间有限无限。」作这样说的人便是诳语。为什么呢？我与世间也不有限也不无限。』这是第四见。」",
"佛说：「诸位外道，有说有限、有说无限、有说有限无限、有说也不有限也不无限，我及世间者，都在这四见之中，不能再超过这四见之上。",
"佛都了知这更超过其上的绝妙之知。所以不讥不毁，得无为。佛了知痛痒所更之乐，了知方便所从起，不受著，佛善解。」佛说：「我所知之法，深奥深照。若有贤者弟子听闻了知，便赞叹佛。若有外道，在过去劫中见过去之事、忆念昔所生之处，于不可计之道中各乐说解其事，都在十八见中。",
"各外道互相诤论，所说各异，若有问事的人，便互相诤论、所说各异，说：『教某人应当这样，教那人应当这样，教其余人应当这样，教人应当这样、不这样。』都在四见之中。那些外道互相诤论、所说各异者是什么呢？所谓各有外道，见这样行这样，说：",
"『我不知也不见，是有后世是无后世；我不知，一切没有后世；我也不见，我所不可见、不知、不念此事，如我所说，不如其余人所说。』那人独自自语、自以为是：『我所见至诚，其余的是痴。』」",
"佛说：「受取痴邪见之人，身死堕入泥犁恶道。",
"若有沙门婆罗门，所行多知、黠慧解说，其义谛观，所语无异，名闻远方，舍弃他人的见，来到他的所在，安详如实地问他，他却不能发遣（答复）；那外道，死后堕恶道。这是第一见。第二，若有外道，了知什么呢？所谓那外道，见这样说这样：",
"『我不知是有善恶之殃福，也不知是无善恶之殃福，我也不知也不见。』若作这样的话：『有善恶之殃福我便著，无善恶之殃福我便离著，我若不著便转还受报。』若沙门婆罗门，所行多知、黠慧解说，其义谛观，所语无异，名闻远方，舍弃他人的见，来到他的所在，安详如实地问他，他不能发遣。",
