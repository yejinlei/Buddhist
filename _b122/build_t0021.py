"那些外道，了知什么呢？所谓若有外道，说：『无行、无有见，没有人念空知。』都在七见之中。那些外道，说：『无行、无有见、没有人念空』者，了知什么呢？所谓若有外道，见这样那样，认为诸我之色由四大而来，父母所生，以饮食而长养，在不是常的沐浴衣中，身死在地，骨节解散堕落，别离异处，风吹其身，破碎坏败，以后世不再生死，这样便灭尽。",
"』这是第一见。第二见，又有外道，说：『死并不是这样破败，更有我超过其上。什么是我所超过其上者？那我的色天以及欲行天，那我在死后坏败，后世不再生死。』这是第二见。第三见，若有外道，说：『我在死后并不这样坏败，更有别的我，又超过其上。",
"那我的色是无意的缘故，那我在死后坏败，后世不再生死。』这是第三见。第四见，又有外道，说：『我并不是这样死坏败，更有我超过其上。那我是谁呢？所谓那我都超过诸色想天，全都越过瞋恚想天，念种种无数虚空知之行。",
"那我若死坏败，后世不再生死。』这是第四见。第五见，又有外道，说：『我并不像这样死坏败，更有我超过其上。那我是谁呢？所谓那我都越过一切虚空知天、无数名识知天。所念所行的那个天，若不坏败之时，后世便不再生死。",
"』这是第五见。第六见，又有外道，说：『我并不这样死坏败，更有我超过其上。那我是谁呢？所谓都越过一切识知天，不再执著，名为无识知念行。那个天的我在死坏败后，后世不再生死。』这是第六见。第七见，又有外道，说：",
"『我并不是这样死坏败，更有我超过其上。那我是谁呢？所谓都越过一切无识知天。那天人无想而有想念之行。那个天的我在死坏败之时，后世便不再生死。』这是第七见。」",
"佛说：「所谓外道行灭坏之见、无行、无有想、无人念空，都在这七见之中，在这七见中不能再超过其上。",
"佛都了知这更超过其上的绝妙之知，所以不讥也不毁它，得无为。佛了知痛痒所更之乐，便了知所从起、起而现，佛无所著之意善解。我所知之法，深奥深照，都了知。若有贤者弟子听闻了知，便演说佛的功德。」佛说：「若有外道，在未来劫中见未来之事，于无数道中所说各异，都在四十四见中。",
"又有外道自己说：『如今现前念行无为，现在见无为。』若有人到他的所在，他便为之说：『现在无为。』都在五见之中。有外道，见这样，说行也是如此，他在殿舍中自图快意，以五欲自我娱乐。那人说：『我现在得无为。』这是第一见。",
"第二见，又有外道，说：『不像其余人所说有我、现在无为，更有现在得无为。什么叫现在无为？若比丘离欲、脱离恶不善之法，意念行善安乐，便得第一禅。那人灭尽，我者后世不再生死，这就是我现在得无为。』这是第二见。",
"第三见，又有沙门道人，又说：『不像其余人所，不用此我现在得无为，更有现无为，又超过其上。什么叫现在无为？那比丘灭意、内寂定，其志专一，不念也不行，三昧喜乐，便行第二禅，那人灭尽，现在得无为。』这是第三见。",
"第四见，又有沙门道人说：『不像其余人所说，不用此我现在得无为，更有现无为，又超过其上。什么叫现在无为？若有比丘，喜离婬妷、悦观行，常寂悦，身行如贤者，所观行常安，便行第三禅。』这是第四见。第五见，又有沙门道人说：",
"『不像其余人所说，不用此现在得无为。更有现在无为，又超过其上。什么叫现在无为？若有比丘，断乐断苦，没有昔时的可意不可意，也不苦也不乐，常奉清净，便行第四禅。那人在现在得无为灭尽，以后世不再生死。",
"』这是第五见。」",
"佛说：「所谓有沙门道人，说现在无为、见现在无为、念现在无为的，都在这五见之中，不能再超过这五见之上。佛都了知这更超过其上的绝妙之知。所以不讥也不毁，得无为。佛了知痛痒所更之乐，方便了知所从起而现，佛无所著之意善解，我所知之法，深奥深照，我都了知。",
"若有贤者弟子听闻了知，便演说佛的功德。」佛说：「那些外道，念常见常，为人说：『我与世间有常。』在这四见之中的，因为他们不知、不见、示现的缘故，所以不得道行精进。乃须知这是习因缘、不习因缘，因此而成因缘，因此而不成因缘，不得其处。",
"」佛说：「那些外道说上中行、各现各自为人说世间有常，在这二见之中的，因为他们不知不见、不得道行精进。乃须知这是习因缘、不习因缘，因此而成因缘，不得其处。」佛说：「若有外道，各念常见常、各为人说，我与世间有常，在这四见之中的，因为不知不见之故不得道。习因缘、不习因缘，因此因缘而成，因此因缘而不成，不得其处。",
"」佛说：「那些外道，有说有限，又说无限，有说有限无限，又说也不有限也不无限，我及世间，在这四见之中的，因为不知不见、不得道行精进。乃须知这是习因缘、不习因缘。因此因缘而成，因此因缘而不成，不得其处。",
"」佛说：「那些外道互相诤论、所说各异，在这四见之中的，因为不知不见之故，不习道行精进。乃须知这是习因缘、不习因缘。因此因缘而成，因此因缘而不成，不得其处。」佛说：「那些外道，说想行想，为人说：『我与世间有想。』",
"在这十六见之中的，因为不知不见之故，不得道行精进。乃须知这是习因缘、不习因缘。因此因缘而成，因此因缘而不成，不得其处。」佛说：「那些外道，念无想、见无想，为人解说我与世间无想，在这八见之中的，因为不知不见之故，不得道行精进。",
"乃须知这是习因缘、不习因缘。因此因缘而成，因此因缘而不成，不得其处。」佛说：「那些外道，也不念想也不无想，为人说：『我与世间无想。』在这八见之中的，因为不知不见之故，不得道行精进。乃须知这是习因缘、不习因缘。",
"因此因缘而成，因此因缘而不成，不得其处。」佛说：「那些外道说灭坏，常为人说：『我与世间灭坏。』在这七见之中的，因为不知不见之故，不得道行精进。乃须知这是习因缘、不习因缘。因此因缘而成，因此因缘而不成，不得其处。",
"」佛说：「那些外道，说现在无为、见现在无常，为人说现在无为，在这五见之中的，因为不知不见之故，不得道行精进。乃须知这是习因缘、不习因缘。因此因缘而成，因此因缘而不成，不得其处。」佛说：「若有外道，在过去劫中见过去之事，于无数道各各异，在十八见中。",
"那些外道，在未来劫中见未来之事，于无数道中所说各异，在四十四见之中，合起来都在六十二见之中，往来其中，在那里面安住，在其中出生、俱会而行，在网中生死、不能得出。」佛说：「譬如工捕鱼师，或者捕鱼的弟子，拿着细目网下到小泉中，下网后就前住或坐，那人念说：",
"『水少，众鱼浮游，都上网来。』往来的鱼都在网中不能得出。」佛说：「就是这样，那些外道，在过去劫中见过去之事、识昔时之行，于无数道中所说言各各异，在十八见的；若有外道，在未来劫中见未来之事、念说未来之事，于无数道中所说各异，在四十四见中的；都在六十二见中往来，在其中安住、在其中生死、俱合会而行，在罗网中不能得出。",
"」佛说：「比丘！佛身都已断除诸著，常在其处安住。诸天及人民都得以见到，佛般泥洹后便不能见。」佛说这部经时，三千大千世界六次震动。那时，那耶和留比丘，在佛前站立，用扇扇佛。于是贤者那耶和留，长跪叉手禀白佛说：",
"「从没有过的天中天！这部经深，竟如此深照。天中天！这部经叫什么名字？怎样受持其名？」佛告那耶和留：「拘楼秦佛、如来、无所著、等正觉说这部经时，名为『法网』；迦叶佛、如来、无所著、等正觉说这部经时，名为『见网』",
"；如今我也说这部经，名为『梵网』。」佛这样说。诸位比丘都欢喜，上前向佛作礼而去。",
