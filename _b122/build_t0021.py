"第三，若外道，断除爱欲，精进行寂，即如形像入三昧定意，忆念过去未来八十劫之事，那人便说：『我与世间有常。为什么呢？我知过去、未来劫的成败之时。』那人便忆念过去、未来之智，这是第三见。第四，若有外道，精进寂一心，行断恶行，即如形像入三昧定意，忆念寂根住于痴念。",
"那人自己为世人说：『有常。为什么呢？我不知过去劫的成败之时，也不知未来劫的成败之时。』这是第四见。所谓外道，说常见常、自己为世人说有常的，都在四见之中，不能再超过其上。如来都了知，这更超过其上的微妙之知，所以不呵责它，离于呵责而得无为。",
"如来了知痛痒所更之乐灭尽，了知其所从起，佛以无所受之意善解。」佛说：「我所解之法，深奥深照，若有贤者弟子听闻便会赞叹佛。那些外道，在过去劫中见过去之事、忆念过去之事，于无数道中各乐说知其中之事，都在十八见中。",
"那些外道是怎样呢？所谓在过去劫中见过去之事、忆念过去之事，于无数道中各乐说知其中之事。若有外道，各说常见常、各自为世人说有常，都在四见中。那些外道是怎样呢？所谓说常见常、为世人说常。劫坏败之时，下面的众生便上生到第十二阿卫货罗天（光音天）。",
"劫坏败之时，那些天人福德薄，命尽展转下生。有梵天在上方虚空中出生，便在那里成为大尊，梵天自己说：『我造作一切事，我在其上最尊，为一切作父，解义在千人之上。』那梵天自己念说：『要从哪里才能得到人出生到这里呢？』刚一発意，其余下面的众生便立即生到那里。",
"那时那梵天，因此生起见而说：『都是我变化造作出这些人的。』那些人也各自生起见说：『梵天都是变化造作出我们的。为什么呢？梵天先生，我们后生，所以是他化我们的。』那先生的梵天，最为端正好洁，威神巍巍。其余诸天，随法福德薄的，命尽都渐渐下生人间，行精进，离爱欲，行一心，即如形像入三昧定意，忆念往昔所生之处。",
"那人说：『上面先所生的梵天得以常在，终究不转移也不死。常在尊上的梵天，变化造作出我们，不是非常、不转移、不死。』这就是说常而非实，这是第一见。第二，若有外道，那有梵天，発见这样说：『那些色法、痛痒、思想、行、识，这些法是常，也不转移不死；那些地种、水种、火种、风种、空种，这些是非常、不坚固。",
"』那些梵天人，禄相福德薄的，终亡来下生人间。那人精进，离爱欲，一心，即如形像入三昧定意，忆念往昔梵天。那人说：『那些色法、痛痒、思想、行、识，那些法是常、坚固；这人间的地种、水种、火种、风种、空种，这些法是非常、无坚固、有终亡。",
"』这是第二见。第三，若有外道，说些什么呢？所谓有天名叫几陀波屠，在其上互相娱乐，快乐之后，便不再念身病、著于床。那人法禄相福德薄，终亡下生人间，那人行精进，离爱欲，一心，即如形像入三昧定意，忆念往昔所生之处，那人便说：",
"『那些天人互相娱乐快乐者，得以常在，不动转、不终亡。这人间的互相娱乐，非常、无坚固、有终亡。那些天有常，这人间无常。』这是第三见。第四，若有外道所说，有天名叫散提，他们居在上方共同止顿，平齐相向，生瞋恚便离开本座，那些天人禄相福薄的，终亡下生人间。",
"那人行精进，离爱欲，一心，即如形像入三昧定意，忆念往昔所生天上，那人说：『那些天共同止住、互相娱乐者，得以常在、坚固、不终亡。我生人间，是非常、无坚固、有终亡。那些天有常，我人间无常。』这是第四见。」",
"佛说：「诸位外道，各各所说有常、各各为世人说有常的，都在四见之中，不能超过这四见。佛都了知这更超过其上的绝妙之知，所以不讥也不毁，得无为。佛了知痛痒更乐，了知方便所从起、起而见，佛以无所受之意善解，佛所知之法，深奥深照，我都了知。",
"若有贤者弟子听闻了知，便赞叹如来。若有外道，在过去劫中见过去之事、忆念昔时之行，于不可计之道中各乐说解知其事，都在十八见中。那些道人了知什么呢？所谓有外道说：『我在此自然而生，不是从他方来生。』忆念无所从生之见，所谓本无世间，如今有世间。",
"都在二见之中。那些外道了知什么呢？所谓说：『我在此自然而生，不是从他方来生。』忆念无世间、如今有世间者，有天名叫无想，入于没有思想、没有痛痒。那些天人若念思想，禄相福德便薄尽，终亡来下生世间。那人行精进，离爱欲，一心定意，即如形像入其三昧，不能再忆念昔时所从来生。",
"那人便说：『本来没有世间，如今刚有世间。我昔时无，如今自然生。』这是第一见。第二，若有外道，意念痴，那痴人念说：『本来没有世间，如今刚有世间。我本无，如今自然生有。为什么呢？我本无，如今自然生有，这就是本无世间。",
"』这是第二见。那些外道所说的、所谓我本无所从来生、忆念无所从生之见、所谓本无世间今刚有世间的，都在这二见之中，这二见不能再超过。佛都了知这更超过其上的绝妙之知。所以不讥也不毁，得无为。佛了知痛痒所更之乐，了知方便所从、起而见，佛以无所受之意善解。",
"」佛说：「我所知之法，深奥深照，我都晓了。若有贤者弟子听闻了知，便赞叹佛。若有外道，在过去劫中见过去之事、忆念昔时之行，于可计之道中各乐说解知其事，都在十八见中。有外道，一人说我所见有崖底，一人说我所见无崖底，一人说我所见有崖底无崖底，一人说我所见不有崖底也不无崖底，都在这四见之中。",
"那些外道了知什么呢？所谓若有外道，行这样，自己为世人说有限，我所说至诚，其余的是痴妄之言。自己为世人说无限，作这样说：『有人说，我与世间有限无限，我与世间也不有限也不无限者，后来也是虚妄之语，作这样说的人便是诳语。",
"为什么呢？我所见世间有限。』这是第一见。第二，若有外道，了知什么呢？所谓说我所行所见无限，所谓知我与世间无限。那外道，见这样、行这样，所谓我与世间无限，那人说：『我与世间无限，我至诚，其余的是痴。",
