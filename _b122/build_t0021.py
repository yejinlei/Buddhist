"佛说：「若有外道，也不是有想也不是无想而行，也不是有想也不是无想而见，也不是有想而行也不是有想而见，都在这八见之中，不能再超过这八见之上。佛都了知这更超过其上的绝妙之知，所以不讥也不毁，得无为。",
