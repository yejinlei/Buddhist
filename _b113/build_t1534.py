 "又往昔作堅鉀時，一正遍知正像法中勤苦持戒，如是八萬四千之身，如是阿僧祇那由他百千苦惱我皆作來，我以悕求一切智智，為欲利益一切眾生。然而我不曾退菩提心，不墮大乘、不捨本願、不緩大鉀，於菩薩業不生怯弱，不曾捨離檀波羅蜜、不曾捨離尸波羅蜜、不曾退墮羼提波羅蜜、不曾破壞毘梨耶波羅蜜、不曾放捨禪波羅蜜、不疲倦修般若波羅蜜，不捨攝法修行一切菩薩之道，具足清淨不錯不謬，堅住一切菩薩之地不倦，一切菩薩三昧三摩跋提，教諸眾生發菩提心不生疲倦。",
 "聚集一切菩提分法非不得恩，發行一切菩薩之行堅住不退心，常欲滿一切菩薩諸願法門不生畏懼，聚集修行一切功德不生怯弱。為什麼？一切世間最勝之處，一切所有學與無學辟支佛智，所不能證、所不能入、不能觀察。",
 "此佛法名彼不易得，若小功德和集修行則不能得，因小善根者不能得故。如此若人有此宗願「我當成佛」，所以翹勤修行精進，如功德法聚集修行，我於此處悕望欲得」。因此義故，佛說此經。以何義故名世尊者，彼義今說。",
 "所說世尊，是供養義。又有餘義，如菩提心憂波提舍所說應知。何故世尊遊毘舍離大林精舍而不餘處者，彼義今說。如此設難則不相應，隨在何處彼一切處皆有此難，若在餘處也不離此難。更有餘義，如菩提心憂波提舍所說應知。",
 "以何因緣而說如此三種具足、不多不少者，彼義今說。因有三分相對之義。以此三種，對治貪嫉、破戒、愚癡：以施具足對治貪嫉，以戒具足對治破戒，以聞具足對治愚癡。又示現三種福德：施具足示施福德，戒具足是正行福德，聞具足示修福德。",
 "又有義：一切眾生隨順淳熟施、戒具足，一切眾生既淳熟已然後能聞，聞已觀察、相應淳熟。如此隨順一切眾生淳熟相應，所以說三。又有義：二種具足。一切佛法聚集住處得不亂法，依止不亂則聞具足，如法正覺一切佛法皆具足得。",
 "如是一切佛法聚集住處，因此因緣所以說三。是只有三種具足，還是更有餘法具足？彼義今說。如此三種總攝具足。若佛廣說無量具足，皆此中攝。如大海慧修多羅中彼說「世尊！菩薩所有一切具足、福德具足，智具足攝，應如是知。",
 "為什麼？世尊！菩薩若修福德具足，以此因緣尊勝富貴，又能令他尊勝富貴」。智具足故口說善語，一切眾生聞者歡喜。彼施與戒是福德具足，聞智具足如此無違。何故菩薩名種姓者，彼義今說。有師說：",
 "有四種家，是如來生處。如偈說：諦、捨、寂靜、慧，此四真勝家，正遍知家生，師說言種姓。又善方便是菩薩父，般若波羅蜜是菩薩母。如彼無垢名稱經說「般若菩薩母，方便以為父，一切眾導師，無不由是生」",
 "。菩薩般若波羅蜜者，因持故如母。方便生者，如父生子。如父母故，說言種姓。如此種姓，是父母二種相似義故。又奢摩他、毘婆舍那，如此種姓生正遍知。一切姓中此門第一，一切善法是姓是門，如經中說。",
 "佛正法中二法雙行，奢摩他是父，毘婆舍那是母，彼二法是種姓。偈說：毘婆舍那母，奢摩他為父，生一切菩薩；因毘婆舍那、奢摩他等故，有一切正覺。又有義：諸佛菩薩現前正住三昧、大悲，此二法是如來種姓，因此二法生於如來。",
 "諸佛菩薩現前正住，三昧為父、大悲為母。又如佛菩薩現前正住，三昧為父、忍為菩薩母，此是種姓。偈說：佛菩薩現前，正住三昧父，若大悲戒忍，是菩薩之母。此偈明何義？說菩薩種姓之義。以何義故名具足者？",
 "彼義今說。推覓眾物、處處將來，舉掌積聚、計校備辦、增益和集，故名具足。又眾法和集之義故名具足。又有義：荷擔菩提故名具足。如外道齋大會具足，初取羊等將來營辦。如此菩提如前具足，後菩提覺。",
 "又多法說名具足，如藥和集乃得成散，如此具足。又有義：前種姓法堅持不失，復向彼岸。如大船舶，先和集已後向寶洲。又有義：正圓非邪如觀察耳，如此之義故名具足。又常修一切勝行，故名具足。",
 "又具足者，欲得出過、荷負重擔、出到度義。荷負重擔，是不懈怠義、三界過義，故名具足。又具足者，平等集修、平等負修、平等行修、平等起修、平等作修、平等持修、平等拄修、平等養修，故名具足。等養修者，於諸眾生猶如醫師，消息病者療治眾病。",
 "等負修者，六波羅蜜，如乘船舶。等行修者，如大乘說。等起修者，菩薩修學如學射等，先正足住。等作修者，巧作一切菩薩諸業，如巧作師。等持修者，常、無常等，如稱平等。等拄修者，一切菩薩能拄法舍，如堂粗柱。",
 "等集修者，一切白法如蜜蜂集。如此等義，故名具足。又自田義、若和合義，若或多義、若別異義，若或廣義、若寬博義，若或勝義，若堅固義、若牢固義，若和集義、若和合義，若或物義、若或財義，若或取義、若積聚義，若或慚義、若或愧義，故名具足。",
 "何故名施？彼義今說。若破貪貧得大富樂、福德具足，是故名施。施有幾種？彼義今說。略有三種。何等為三？一是資生施；二是無畏施；三是法施。資生施者，即飲食等種種捨施，彼資生施色香味勝、淨潔如法，遠離貪垢、無吝垢。",
 "離貪垢者，心不狹小，如此捨施，自手多施。無吝垢者，不存富樂，如此捨施。無畏施者，即能救濟師子、虎、黿、王、賊、水等諸畏。何者是法施？倒說法者為之正說，次第學句教彼正取，廣說則有無量種種，聖無盡意說不可量。",
 "菩薩施業，即菩薩須食與食，即是布施一切眾生色力壽命安樂辯才。又菩薩施，心濁等過皆悉遠離。彼濁心施有十四種：一是心濁；二是先妬；三是嫉心；四是慢心；五是不減慢；六是瞋心；七是簡擇；",
 "八是疑心；九是惱害；十是亂心；十一是先名；十二是依准上法選日時等次第行施；十三是懈怠；十四是先為報力。如此等法能染心故，名為濁心。心體有濁，故名為濁。先妬施者，得富樂少，眷屬不愛。",
 "先嫉施者，雖得富樂，不樂勝報、唯喜下劣，坐臥床敷止宿等處、食飲富樂貪著不離。先慢施者，雖得富樂，生下劣姓、心不正直。先不減慢而布施者，後受報時依他得活，如事王人、伎兒使卒誑惑之人，防邏戍護種種驅使，平准市官當門守戶，放牧畜獸承事太子，下賤官人恐嚇他等，博戲等人捔力相撲。",
 "如此種種廣設方便強力取物，又有踴躍劫賊之人，如此等業以自利益。先瞋施者，後得大力畜生等身，師子虎豹蛇蟒熊羆猴等中生。簡擇施者，後得報時，治生田業作子林子，若種林人作林等人，得少果報以自存活。",
 "先疑施者，後得果報富樂不常。先惱施者，雖得富樂，生夷人中若隘狹處，若災㜸地邊地生等。亂心施者，得富樂少或不得果。先名施者，雖得富樂，得財富已而復喜失。依准上法選日時等次第施者，雖受富樂，勤苦難得。",
 "懈怠施者，後受富樂，雖得而不常。先為報施，後雖得報，難得而少。如此初過，菩薩如是皆悉觀察，既觀察已自心清淨，淨心生已遠離濁心，離濁心已正信相應、悲等功德相應和合，自手施與。先信布施得好方處，種姓、力、色、受勝富樂、眷屬自在，名聞辯才、安樂色命，他不欺陵，為人讚歎第一自在，勝坐臥處止宿等處、堂舍莊嚴、飲食衣服塗香眾香、色聲味觸，得如此等富樂住處。",
 "何故名戒？彼義今說。若能寂靜非法律儀、惡不善法，能生善道、能得三昧，如是名戒。戒有幾種？彼義今說。略有三種，即律儀戒、攝善法戒、攝眾生戒。所謂戒、律儀戒者，菩薩正取七眾律儀，即比丘、比丘尼、式叉摩那、沙彌、沙彌尼、優婆塞、優婆夷戒。",
 "出家、在家，如此次第皆律儀所攝。何者是菩薩攝善法戒？菩薩所有善法及戒皆正聚已，然後修集大菩提善。若身、若口、若意等善，如此略說攝善法戒。又菩薩何所依止？依戒住戒，然後修聞，次修思惟，後奢摩他、毘婆舍那專一樂行。",
 "如尊長前正面言語，先禮拜已後起合掌，時時常爾。如此時時對尊長敬重供給，常於病者悲心供給，若聞善語讚言善哉，於功德人說實功德，生如是心普為十方。如彼十方一切眾生一切福德勤心隨喜，喜心生已然後口說。",
 "於他一切犯觸己者皆能忍受。一切所修身口意善，皆悉願取阿耨多羅三藐三菩提。時時種種供養三寶，一切種種設供養已，口發正願，相應精進常護善分，身不放逸、口誦學句、意念發行，藏護根門、食惟知足，初夜後夜覺寤相應。",
 "親近善人、依善知識，自識己錯，犯過識知，見已知改。犯佛菩薩諸福德人，盡心懺悔。如此等分攝取善法，得善法已守護增長。若如此戒，是名菩薩攝善法戒。何者是菩薩攝眾生戒？彼要略說有十一種，此義應知。",
 "何等十一？一是種種饒益眾生，種種因緣同事相應。二是眾生病不病等，種種諸苦供給伴等。三是世間出世間義，如彼法說，先示方便、先示道理。四是報眾生恩，不忘恩報，隨所宜護、隨報供給。五是師子虎王水火賊等，種種畏處護諸眾生。",
 "六是諸親善友亡失富樂、憂悲殃罪，能為除遣。七是貧窮苦惱乞丐眾生，一切所須皆悉給與，行善之人依正捨法功德攝取。八是先語問訊，後語問訊應時而往。九是若他呼喚取食飲等，世間饒益彼此往來。",
 "以要言之，一切所有不饒益事、不可愛行，皆悉捨離，心隨順轉。十是自實功德心生歡喜，公白正取、畢竟唱說以潤益心。若治若擯、若罰若黜，或時驅遣，諸如此等不善處擯，令住善處相應饒益。十一是以神通力示地獄等毀呰不善，令入佛法教化眾生，令其歡喜得未曾有。",
 "又聖者無盡意說六十七種，即於一切諸眾生所不起惱害，如是等故。又菩薩藏修多羅中，廣說無量如來戒故。又此戒無量無邊功德和集，如是功德今說少分，即戒名出家人戒。如大富人身少喜樂，於善法中增長如母、於惡法中能護如父，如在俗人有財物故，一切饒益皆悉成就。",
 "出家人戒也是如此，正導如是，如人正行則無衰損，如善人所報恩具足，如世間人愛惜身命，又如勝智世所讚歎，如慎重王語。求解脫人護戒也如此，欲求解脫當歸依佛，欲生善道當歸依戒。安身之本，戒是第一知識。",
 "遇惡善友不捨戒也如此，欲自利益至死不捨。如女慚愧世人莊嚴，如人勝行不諂為最，如梵行中見柔和勝，如欲大貴不幻為本，如不放逸多饒功德。欲證勝法依觀察得，如近善友初中後時，悕望學人時節如海不可得過。",
 "如諸眾生依地而住，依戒住持一切勝法。如水能潤一切種子，戒能津潤善法種子，如火成根，如風能令分分開張，如行住之物空為無障。欲證果人，戒如堅瓶、戒如寶藏，如隨所欲。如得之牛如食資糧，如人因杖得行住等。",
 "如息依命、如命慧勝。如國有王人所依止，如軍有將，功德軍眾戒是統將。如婦女人一切樂行皆因夫主，如行道人所有資糧，若行天道戒是資糧。如曠野行主將善導，行善法者戒是前導。如大海船，若人方便渡生死海，以戒為船。",
 "如病大藥，煩惱病者戒為良藥。如戰鬪處所有器杖，共魔王戰以戒遮防。如潤親友不可得捨，戒是賢聖。如大闇中燈為照明，未來大闇以戒為燈。如過度河等因橋而渡，出三惡道諸方便中戒最為大。如清涼舍能離大熱，煩惱大熱戒能清涼。",
 "如怖畏者歸依健兒執刀杖者，畏惡道人戒是歸依。菩薩之人如住實家，善凡夫人如自己物。菩薩之人如住捨家，行道之人如所行道。菩薩之人如住家家，得果之人能為他說。菩薩之人如住慧家，不動之人平坦清淨。",
 "如諂捨直、如貪捨施，如嫉心人捨不嫉心，如幻偽人心不觀察，如沉審人捨離高心，如謹慎人捨放逸過。如王有眼，無眼闇人非其境界。八聖道分解脫相應，不觀察人去之甚遠。如阿羅漢愛涅槃法，如人自愛。",
 "如佛出世次第善轉，如住正法則住果證。如佛世尊利益自他，如僕事主物時方處皆須相應。如人獲得須陀洹果則心安隱。如得良時造作不悔。如菩薩願終得解脫。如良善田種善種子生長廣收。如時方則因緣具足，智色愛樂自多受用。",
 "如善根熟則有勢力。如自善行自心歡喜。如人無罪，此世來世則無所畏。如勇健人所依正行，戒如正行、善喜自修。如修慈者善心安樂，如修喜者心常慶悅，如修悲者心則正信，如修捨者心常隨順。四種正法如實諦信，如世間法障礙寂靜隨順樂行。",
 "如因聞故則得辯才。如巧語人則無所畏，如智明人則有名稱，如善語人不可破壞，如法順法能成就證，得明解脫正覺之人正道如幢。如有智人則能修禪，如伴修道，如健因緣則無所畏。如山饒寶饒功德寶，如海住處多饒。",
 "希有如來弟子，戒如大海，是入道行如信得果。如覺知者依道理行，雖曰無水猶能洗浴，無根莖葉而生香物。不穿不瑩，非金非寶非是真珠而是莊嚴，雖非境界而能生於後世樂報，世間人天修羅魔梵一切沙門婆羅門等之所讚歎。",
