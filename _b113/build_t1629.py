 "由此道理，雖一切分皆能為因顯了所立，然唯一分且說為因。如此略說宗等及似，即此多言說名能立及似能立。隨其所應，為開悟他而說此能立及似能立。為自開悟唯有現量及與比量，彼聲、喻等攝在此中，故唯二量。",
 "由此能了自、共相故，非離此二別有所量、為了知彼更立餘量。所以本頌說：現量除分別，餘所說因生。論說：此中「現量除分別」者，即若有智於色等境遠離一切種類、名言、假立、無異、諸門、分別，由不共緣現現別轉，故名現量。",
 "所以說偈頌：有法非一相，根非一切行，唯內證離言，是色根境界。論說：意地也有離諸分別、唯證行轉。又於貪等諸自證分、諸修定者離教分別，皆是現量。又於此中無別量果，因即此體似義生故、似有用故，假說為量。",
 "若於貪等諸自證分也是現量，為何此中除分別智？不遮此中自證現量，因無分別故。但於此中了餘境分，不名現量。由此即說憶念、比度、悕求、疑智、惑亂智等，於鹿愛等皆非現量，因隨先所受分別轉故。如此一切世俗有中，瓶等、數等、舉等、有性、瓶性等智皆似現量，於實有中作餘行相，假合餘義分別轉故。",
 "已說現量，當說比量。「餘所說因生」者，即智是前智，餘從如所說能立因生，是緣彼義。此有二種：即於所比審觀察智，從現量生或比量生；及憶此因與所立宗不相離之念，由此成前舉所說力，念因同品定有等故。",
 "是近及遠比度因故，俱名比量，此依作具、作者而說。如此應知，悟他比量也不離此得成能立。所以說偈頌：一事有多法，相非一切行；唯由簡別餘，表定能隨逐。如是能相者，亦有眾多法，唯不越所相，能表示非餘。",
 "論說：為何此中與前現量別異建立？為現二門，此處也應於其比果說為比量，彼處也應於其現因說為現量，俱不遮止。已說能立及似能立，當說能破及似能破。偈頌說：能破闕等言，似破謂諸類。論說：此中「能破闕等言」",
 "者，即前所說闕等言詞諸分過失。彼一一言皆名能破，由彼一一能顯前宗非善說故。所說「似破謂諸類」者，諸同法等相似過類名似能破，由彼多分於善比量為迷惑他而施設故。不能顯示前宗不善，由彼非理而破斥故，及能破處而施設故。",
 "是彼之同類，說名過類。若於非理立比量中如此施設，或不了知比量過失，或即為顯彼過失門，不名過類。偈頌說：示現異品故：由同法異立，同法相似；餘，由異法。分別、差別名分別。應一成無異。顯所立餘因，名可得相似。",
 "難義別疑因，故說名猶豫。說異品義故，非愛，名義准。論說：此中「示現異品故：由同法異立，同法相似」者，顛倒成立故名異立，此依作具、作者而說。同法即是相似，故名同法相似，一切攝立中相似過類故。",
 "所說相似者，是不男聲，能破相應故、或隨結頌故。如何同法相似能破？於所作中說能作故、轉生起故，作如是說。後隨所應也如此說。今於此中由同法喻顛倒成立，所以說名同法相似。如有人成立「聲是無常，勤勇無間所發性故」",
