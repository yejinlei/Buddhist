 "為什麼？若無一，十即不成，但十仍非一。其餘門也如此，依例可知。所說向下去中也有十門：一是十。為什麼？緣成故。乃至十是十中一。為什麼？若無十，一即不成，但一仍非十。其餘也如此。生變如此，勘當即知。",
 "一一錢中具足十門，如本末兩錢中具足十門。其餘八錢中，依例可解。問：現說一者，為何一中名為十？答：大緣起陀羅尼法若無一，一切即不成。定知如此之相。如所說一者，非自性一，緣成故一。乃至十者，非自性十，緣成故十。",
 "一切緣生法，無有一法有定相、有自性。無自性故即不自在，即生不生生。不生者，即是不住義。不住義，即是中道。道義，即通於生與不生。故龍樹說：「因緣所生法，我說即是空，亦說為是假名，亦是中道義。",
 "」即是此義。中道義，是無分別義。無分別法不守自性，故隨緣無盡，也是不住。所以當知，一中十、十中一，相容無礙，但仍不相是。現一門中具足十門，故明中智，一門中有無盡義。如一門，其餘也如此。",
