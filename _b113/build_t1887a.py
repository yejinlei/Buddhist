 "，即是此義。所以聖者隨遍計而建立三性，且安窮心，漸漸以後現三無性，覺悟夢中之人。此即聖者的大善巧。問：如《攝論》說「遍計所執，凡夫境界；依他真實，聖智境界。」為何聖者隨遍計呢？答：遍計諸法顛倒而有，所以論說「凡夫境界，畢竟空故，無所可對。",
 "」所以論中說非聖境界，並非說智空非聖境界。所以聖者慈悲方便，隨眼病而說空華，有何妨難？正義在此。依他起相從因緣生，無有自性、離二邊過，與無我同。圓成實性平等之法，圓融彼此不可分別，本來一味，因此之故分別不及。",
 "所以論說「聖智境界」。別意如此。若就實說，三種自性皆是凡夫境界。為什麼？隨性說事而安立三種自性，即是聖智境界。為什麼？隨智顯理，非安立故。所以經中也有處在三性以外不立三無性，也有處在三性以外別立三無性。",
 "為什麼？隨情安立、約解門，故別立三無性；隨智顯理、約行門，故三以外不立三無性。尚且在二以外無有真實，何況三性以外別有三無性。所以得知無相等智現前畢竟無法可對，唯在中道。因此須解教立之所由。",
 "問：如上所言，證分之法與緣起分法，有何差別？答：別，也不別。其義如何？證分之法是約實相說，唯是所證。緣起分法為從眾緣生，無有自性，與本不異，所以不別。問：若如此，以自所證為眾生說，與末不異。",
 "尋常差別嗎？答：得其義，若所證在言，與末不異；言說在證，與本不異。與本不異故，用而常寂；說而不說，與末不異故。寂而常用，不說而說，不說而說故，不說即非不說；說而不說故，說即非說，說即非說故，說即不可得。",
 "不說即非不說故，不說即不可得；二俱不可得故，二俱不相妨。因此之故，說與不說等無差別、生與不生等無差別、動與不動等無差別。一切差別相對的法門，依例如此。所以經說「有為無為一切諸法，有佛無佛性相常住，無有變異」",
 "，即是此義。也可說正說法中，言說以外更無別義，以言為義；正義法中，正義以外更無別言，以義為言。以義為言故，言無非義；以言為義故，義無非言。義無非言故，義即非義；言無非義故，言即不言。",
 "言即非義故，二俱不可得，所以一切法本來在中道。中道，是通於言與非言。為什麼？諸法實相不在言中，因離名性；言說法不在真性，因在機益，名無真性。離名性故，名而無名。名而無名故，以名求實，實不可得。",
 "名無真性故，名而無我同，故名性不可得。因此之故，二俱不可得。唯證所知，非餘境界。所以經說「一切諸法，唯佛所知，非我境界。」問：前後兩義有何差別？答：前義可別，以本末相即，相即相融而顯中道。",
 "後義以名義互為客，顯示無我義。所顯道理不離能詮方便之別，此即本末相資、名義互客，開啟眾生令致自無名真源，能化所化宗要在此。問：此義義當頓教宗，為何在此說？答：如上所說，說與不說等無差別。",
 "為什麼？總是實德故，無有妨難。且為護分別，順三乘說，這是智者的勝妙能。如上證分及緣起分義，當論中義大教大。背反分別，得無分別，名為無緣。順理不住，故名善巧。如說終行、得聖者意，故名為捉。",
 "如意如前。歸家，是證本性。家是何義？陰覆義、住處義。所謂法性真空，是覺者所住，故名為宅。大悲善巧蔭覆眾生，名為舍。此義在三乘，一乘方為究竟。為什麼？應法界故，所謂法界陀羅尼家及因陀羅家、微細家等，這是聖者所依住，名為家。",
 "隨分，是未滿義。資糧，是助菩提分，如下經〈離世間品〉中二千答等。第二明得益。陀羅尼，是總持，如下數十錢法中說。實際，是窮法性。中道，是融二邊。坐床，是攝一切。安在法界十種涅槃廣大寶床，攝一切故，名為坐床。",
 "寶，是可貴。床，即攝之義。十種涅槃，如下經〈離世間品〉說。舊來不動，是舊來佛義。所謂十佛，如《華嚴經》：一是無著佛，安住世間成正覺；二是願佛，出生；三是業報佛，信；四是持佛，隨順；",
 "五是化佛，永度；六是法界佛，無處不至；七是心佛，安住；八是三昧佛，無量無著；九是性佛，決定；十是如意佛，普覆。為何說十數？為顯多佛。此義是諸法之真源、究竟之玄宗，甚深難解，宜當深思。",
 "問：具縛有情、永斷菩薩未成福智，以何義故舊來成佛？答：菩薩未斷不名成佛，菩薩斷盡、福智成竟，自此以後名為舊來成佛。問：斷惑如何？答：如《地論》說「非初非中後，前中後取故。云何斷？如虛空，如是斷故。",
