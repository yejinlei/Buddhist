 "《華嚴經》說：「廣大悲雲遍一切，捨身無量等剎塵，以昔劫海修行力，今此世界無諸垢。」說的是眾生妄執，念念遷流，名之為苦。菩薩教令了蘊空寂、自性本無，所以說離苦。問：「眾生無邊、苦業無邊，為何菩薩而能普代眾生受苦？」",
