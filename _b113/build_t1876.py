 "「於不堅堅覺，深住於顛倒，離煩惱所惱，得最上菩提。」以上明四種行德竟。自此以下攝用歸體入五止門。五止門，說的是依前能行四德之行，當相即空，相盡心澄而修止。所說的入，是性相俱泯、體周法界，入無入相，名為入。",
 "《華嚴經》說：「如來深境界，其量等虛空，一切眾生入，而實無所入。」又準《入佛境界經》說：「入諸無相定，見諸法寂靜。常入平等故，敬禮無所觀。」這是一切眾生本來無不在如來境界之中，更無可入。",
 "如人迷惑，把東當作西，乃至覺悟之後，西即是東，更無別的東可入。眾生迷惑，說妄可捨、說真可入；乃至覺悟以後，妄即是真，更無別的真可入。此義也是如此，不入而入，所以說入。為什麼？入與不入本來平等，同是法界。",
 "《起信論》說：「若有眾生，能觀無念者，」這名為入真如門。所說五止：第一是照法清虛離緣止，謂真諦之法本性空寂，俗諦之法似有即空。真俗清虛，蕭然無寄，能緣的智寂滅，所緣的境空無，心境不拘，體融虛廓，正證之時，因緣俱離。",
 "《維摩經》說：「法不屬因，不在緣故。」依此義理，所以說照法清虛離緣止。第二是觀人寂怕絕欲止，謂五蘊無主名曰寂怕，空寂無求名為絕欲。所以說觀人寂怕絕欲止。第三是性起繁興法爾止，謂依體起用名為性起，起應萬差所以說繁興，古今常然名為法爾。",
 "說的是真如之法，法爾隨緣；萬法俱興，法爾歸性。所以說性起繁興法爾止。《經》說：「從無住本立一切法。」即是此義。第四是定光顯現無念止。所謂定光，指的是一乘教中白淨寶網萬字輪王之寶珠。此寶珠體性明徹，十方齊照，無思成事，念者皆從，雖現奇功，心無念慮。",
 "《華嚴經》說：「譬如轉輪王，成就勝七寶，來處不可得，業性亦如是。」若有眾生，入此大止妙觀門中，無思無慮任運成事，如那寶珠遠近齊照，分明顯現廓徹虛空，不被二乘外道的塵霧煙雲所障蔽。所以說定光顯現無念止。",
 "第五是理事玄通非相止，謂幻相之事、無性之理，互隱互顯，所以說玄通。又理由修顯，故事徹於理；行從理起，理徹於事；互存互奪，所以說玄通。玄通，是說大智獨存體周法界，大悲救物萬行紛然，悲智雙融，性相俱泯。",
 "所以說理事玄通非相止。上來明五止竟。自此以下依止起觀。問：「準上義理，依之修行，足為圓滿，為何更要入止觀兩門呢？」答：「《起信》說：『若修止者，對治凡夫住著世間，能捨二乘怯弱之見；若修觀者，對治二乘不起大悲狹劣之過，遠離凡夫不修善根。",
 "』以此義故，止觀兩門，共相成助，不相捨離。若不修止觀，無由得入菩提之路。《華嚴》說：譬如金翅鳥，以左右兩翅鼓揚海水令其兩闢，觀諸龍眾命將盡者而搏取之。如來出世也是如此，以大止妙觀而為兩翅，鼓揚眾生大愛海水令其兩闢，觀諸眾生根成熟者而度脫之。",
 "依此義故，要修止觀。」問：「止觀兩門既為宗要，凡夫初學未解安心，請示迷徒令歸正路。」答：「依《起信論》說：『若修止者，住於靜處，端坐正意。不依氣息，不依形色，不依於空，不依地水火風，乃至不依見聞覺知。",
 "一切諸想隨念皆除，也遣除想。以一切法本來無想，念念不生、念念不滅，也不隨心外念境界；然後以心除心，心若馳散，即當攝來令歸正念。』常勤正念唯心識觀，一切魔境自然遠離。凡夫初學，邪正未分，魔網入心欺誑行者，又無師匠諮問可憑，依四魔功將為正道，日月經久邪見既深，設遇良緣終成難改，沈淪苦海出離無由，深自察之無令暫替。",
