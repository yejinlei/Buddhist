def is_pua_char(c):
    cp = ord(c)
    return (0xF000 <= cp <= 0xF8FF) or (0xF0000 <= cp <= 0xFFFFD) or (0x100000 <= cp <= 0x10FFFD)

def fix_text(text):
    # 只处理非PUA梵字区域的普通汉字，梵字不动
    result = []
    for c in text:
        if is_pua_char(c):
            result.append(c)
        else:
            result.append(c.translate(simp_table))
    return ''.join(result)

def main():
    batch = sys.argv[1:]
    for sutra_id in batch:
        path = f"data/modern-translation/{sutra_id}.json"
        with open(path, 'r', encoding='utf-8') as f:
            data = json.load(f)
        
        for t in data['translations']:
            t['modern'] = fix_text(t['modern'])
        
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        
        print(f"已修复 {sutra_id} 的遗留繁体字")

if __name__ == '__main__':
    os.chdir(os.path.dirname(os.path.abspath(__file__)))
    main()
