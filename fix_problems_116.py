def replace_unique(s, old, new, desc):
    """唯一替换断言"""
    count = s.count(old)
    if count == 0:
        print(f"  [跳过] 未找到: {desc}")
        return s
    if count > 1:
        print(f"  [警告] 找到 {count} 处匹配: {desc}，不自动替换")
        return s
    print(f"  [修复] {desc}")
    return s.replace(old, new, 1)

