assert len(SEC) == len(YIJIE) == len(paras) == 13, f'len mismatch {len(SEC)},{len(YIJIE)},{len(paras)}'

translations = []
for i, p in enumerate(paras):
    sec = SEC[i]
    modern = f'【{sec}】【义解】{YIJIE[i]}\n【正文】\n{p}'
    translations.append({
        'section': f'【{sec}】',
        'original_preview': p,
        'modern': modern,
    })

for i, t in enumerate(translations):
    m = t['modern']
    assert m.startswith('【'), f'seg{i+1} not start with 【'
    assert '【义解】' in m and '【正文】' in m, f'seg{i+1} missing'
    yi = m.index('【义解】'); zw = m.index('【正文】')
    assert zw > yi and m[zw + 4:].strip(), f'seg{i+1} 正文为空'
    assert t['section'] and t['original_preview']

out = {
    'id': TID,
    'title': TITLE,
    'translator': TRANS,
    'mode': 'baihua',
    'intro': INTRO,
    'sutraPath': '../sutras/' + TID + '.json',
    'translations': translations,
}
os.makedirs('data/modern-translation', exist_ok=True)
with open(f'data/modern-translation/{TID}.json', 'w', encoding='utf-8') as f:
    json.dump(out, f, ensure_ascii=False, indent=2)
print('OK', TID, len(translations), '段')
