def convert(text):
    lines = text.strip().split("\n")
    title_line = lines[0].strip()
    assert title_line.startswith("【") and title_line.endswith("】"), title_line[:30]
    section = title_line[1:-1]
    yi, body = "", []
    for l in lines[1:]:
        if l.startswith("【义解】") and not yi:
            yi = l.strip()
        else:
            body.append(l)
    body_text = "".join(x.strip() for x in body)
    modern = title_line + body_text + yi
    return section, modern

