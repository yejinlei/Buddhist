def make_yijie(text):
    for pred, yj in YIJIE_RULES:
        try:
            if pred(text):
                return yj
        except Exception:
            pass
    if "偈" in text and len(text) > 40:
        return "此段為經中偈頌，以韻文重宣法義，便於讀誦受持，義趣與前後長行相應，共明如來常住、一切眾生皆有如來藏之旨。"
    if "白佛言" in text:
        return "此段為弟子向佛陀啟問稟白之事，藉以請決法義，展開問答說法。"
    if "佛告" in text or "佛言" in text:
        return "此段為佛陀對大眾或當機者開示法要，宣明一乘真常之旨。"
    return "此段為經文敘述或問答相應之文，宣說大乘一乘、如來常住、一切眾生皆有如來藏的法義。"

