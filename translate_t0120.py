def protect_terms(s):
    placeholders = {}
    for i, term in enumerate(sorted(KEEP_TERMS, key=len, reverse=True)):
        if term in s:
            key = f"\x00TERM{i}\x00"
            s = s.replace(term, key)
            placeholders[key] = term
    return s, placeholders

def restore_terms(s, ph):
    for k, v in ph.items():
        s = s.replace(k, v)
    return s

def modernize(text):
    stripped = text.strip()
    if stripped.startswith("宋天竺三藏求那跋陀羅譯") and len(stripped) <= 30:
        return stripped
    s = text
    for a,b in PHRASE_REPL:
        s = s.replace(a,b)
    s, ph = protect_terms(s)
    for a,b in WORD_REPL:
        s = s.replace(a,b)
    s = restore_terms(s, ph)
    # Minor smoothing
    s = s.replace("的的", "的").replace("了了", "了")
    return s

def build_modern(orig):
    orig = orig.strip("\n")
    if not orig.strip():
        return ""
    sub = make_subtitle(orig)
    yj = make_yijie(orig)
    body = modernize(orig)
    return f"【{sub}】\n【義解】{yj}\n{body}"

