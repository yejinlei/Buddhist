"【菩萨出家游化·结夏安居·夜自思惟】」那时，世尊说此偈已，告比丘言：「当时，毘婆尸菩萨既已出家，与那八万人离自国城，游行诸处，至一聚落结夏安居。过了这个夏安居，而自思惟：『我今为何如迷醉人游行诸处？』作此念已，心得清净，至本住舍，于夜分中又自思惟：【义解】「结夏安居」为佛教僧团于雨季三个月结界安居之制。太子安居已，静夜思惟缘起。此下为全经义理核心——逆观、顺观十二缘起。",

"【观老死苦因·从生支有】『我今何用世间富贵？众生爱著，轮回生死，苦蕴相续无有穷尽。』又再思惟：『这老死苦之因，由何缘所生而得老死？』入三摩地谛观此法，知从「生」支而有。又再思惟：『这生苦之因，由何缘所生？』入三摩地谛观此法，知从「有」支而有。【义解】逆观缘起：老死←生←有←取←爱←受←触←六入←名色←识←行←无明。「三摩地」即定。",

"【观有取爱受支】又再思惟：『这「有」苦之因，由何缘所生？』入三摩地谛观此法，知从「取」支而有。又再思惟：『这「取」苦之因，由何缘所生？』入三摩地谛观此法，知从「爱」支而有。又再思惟：『这「爱」苦之因，由何缘所生？』入三摩地谛观此法，知从「受」支而有。【义解】十二缘起之取、爱、受三支。逆观自老死推因，支支相因。",

"【观触六入名色支】又再思惟：『这「受」苦之因，由何缘所生？』入三摩地谛观此法，知从「触」支而有。又再思惟：『这「触」苦之因，由何缘所生？』入三摩地谛观此法，知从「六入」支而有。又再思惟：『这「六入」苦之因，由何缘所生？』入三摩地谛观此法，知从「名色」支而有。【义解】触、六入、名色三支。「六入」即眼耳鼻舌身意六根（六入处）；「名色」为精神（名）与物质（色）之合成。",

"【观识行无明支】又再思惟：『这名色苦之因，由何缘所生？』入三摩地谛观此法，知从「识」支而有。又再思惟：『这「识」苦之因，由何缘所生？』入三摩地谛观此法，知从「行」支而有。又再思惟：『这「行」苦之因，由何缘所生？』入三摩地谛观此法，知从「无明」支而有。【义解】识、行、无明三支。逆观至此，推至根本之「无明」，为十二缘起流转之首。",

"【顺观缘起集成大苦蕴·问灭】如是，无明缘行，行缘识，识缘名色，名色缘六入，六入缘触，触缘受，受缘爱，爱缘取，取缘有，有缘生，生缘老死、忧悲苦恼，如是集成一大苦蕴。那时，毘婆尸菩萨又再思惟：『这老死苦之因，云何得灭？』【义解】顺观十二缘起之流转门（集），明「一大苦蕴」由无明乃至老死相续集起。下转为还灭门（灭）。",

"【观生灭则老死灭·有灭则生灭·取灭则有灭】入三摩地谛观此法，知「生」灭则老死灭。又再思惟：『这「生」苦之因云何得灭？』入三摩地谛观此法，知「有」灭则生灭。又再思惟：『这「有」苦之因云何得灭？』入三摩地谛观此法，知「取」灭则有灭。又再思惟：『这「取」苦之因云何得灭？【义解】还灭门：由老死逆推，支支之灭。生灭则老死灭，有灭则生灭，取灭则有灭。",

"【观爱灭则取灭·受灭则爱灭·触灭则受灭】』入三摩地谛观此法，知「爱」灭则取灭。又再思惟：『这「爱」苦之因云何得灭？』入三摩地谛观此法，知「受」灭则爱灭。又再思惟：『这「受」苦之因云何得灭？』入三摩地谛观此法，知「触」灭则受灭。又再思惟：『这「触」苦之因云何得灭？【义解】还灭门：爱灭则取灭，受灭则爱灭，触灭则受灭。",

"【观六入灭则触灭·名色灭则六入灭·识灭则名色灭】』入三摩地谛观此法，知「六入」灭则触灭。又再思惟：『六入苦之因云何得灭？』入三摩地谛观此法，知「名色」灭则六入灭。又再思惟：『名色苦之因云何得灭？』入三摩地谛观此法，知「识」灭则名色灭。又再思惟：『这「识」苦之因云何得灭？【义解】还灭门：六入灭则触灭，名色灭则六入灭，识灭则名色灭。",

"【观行灭则识灭·无明灭则行灭·大苦蕴自不生】』入三摩地谛观此法，知「行」灭则识灭。又再思惟：『这「行」苦之因云何得灭？』入三摩地谛观此法，知「无明」灭则行灭。如是，无明灭则行灭，行灭则识灭，识灭则名色灭，名色灭则六入灭，六入灭则触灭，触灭则受灭，受灭则爱灭，爱灭则取灭，取灭则有灭，有灭则生灭，生灭则老死、忧悲苦恼灭，如是一大苦蕴而自不生。【义解】还灭门总结：无明灭乃至老死灭，「一大苦蕴」自不复生。此即十二缘起之顺逆二观，为毘婆尸佛成道之关键。",

"【颂·逆顺观缘起】」那时，世尊而说颂说：「毘婆尸菩萨，思惟老死苦，以智推彼因，何缘何法生？入定审谛观，知从生支起，乃至行苦因，知从无明有。复观从何灭？无明灭行灭，乃至老死尽，苦蕴悉皆无。」【义解】颂重宣逆观（推因）与顺观（还灭）之缘起观，明无明灭则老死尽、苦蕴悉无。",

"【观五蕴生灭如幻·成正等觉·颂】」那时，世尊说此偈已，告比丘言：「当时，毘婆尸菩萨又观色、受、想、行、识，生灭不住，如幻如化，无有真实，智观现前，业习烦恼一切不生，得大解脱，成正等觉。」那时，世尊而说颂说：「毘婆尸菩萨，复观蕴等法，入彼三摩地，智观现前时，惑苦业习气，一切皆不生，如飘兜罗绵，刹那不可住。【义解】观五蕴生灭如幻，智观现前，惑业烦恼不生，得大解脱而成正觉。「兜罗绵」喻极轻飘之物，刹那不住。",

"【颂·成就佛菩提·二疑得解脱·颂】成就佛菩提，涅槃吉祥果，如月大圆明，光遍十方界。」那时，世尊说此偈已，告比丘言：「当时，毘婆尸先在因位，一疑自身犹如迷醉，二疑贪等烦恼展转增多，如是思惟缘生之法，得大解脱。」那时，世尊而说颂说：【义解】颂明成佛菩提、涅槃之果，如满月遍照。毘婆尸在因地有二疑（自身如迷醉、烦恼渐增），由观缘起而得解脱。",

"【毘婆尸成道·念应何处说法·译人题重出】「彼佛如来身，难成能得成，观察缘生法，复断贪瞋痴，究竟于彼岸，成就大解脱，如日在山顶，遍照于一切。」西天译经三藏、朝散大夫、试鸿胪卿、传教大师臣法天奉诏译。那时，世尊说此偈已，告比丘言：「当时，毘婆尸佛既已成道，即作此念：【义解】颂赞毘婆尸佛难成能成、断三毒、成大解脱，如日遍照。此处原文重出译人题一行，系原经所有，照录不改。",

"【谛观满度摩城·行乞·住鹿野园·颂】『我于何处先应说法利益有情？』谛观思惟，知满度摩王所都大城，人民炽盛、机缘纯熟。作此念已，即从座起、整衣服、手执应器，次第行乞，往满度摩城，到安乐鹿野园中，暂住止息，自在无畏。」那时，世尊而说颂说：【义解】佛成道后观化机，知满度摩城机缘成熟，遂行乞入城，止住鹿野园。「应器」即钵，为比丘应量受食之器。",

"【颂·安住鹿野园·遣守门人召欠拏太子】「二足正遍知，自在行持钵，安住鹿野园，无畏如师子。」那时，世尊说此偈已，告比丘言：「当时，毘婆尸佛告守门人说：『替我前往欠拏太子及近臣帝稣噜处，我今现在安乐鹿野园中，我想与他们相见。』那时守门者听了这话，即往欠拏太子及近臣帝稣噜处，具陈上事：【义解】「二足」指人与天（或佛为二足尊）；「正遍知」为佛十号之一。佛遣守门人召太子与近臣。「欠拏」为其弟/子之名；「帝稣噜」为近臣名。",

"【欠拏太子与帝稣噜趋佛所·佛欲开示妙法】『毘婆尸佛成正觉道，往满度摩城安乐鹿野园中，我想和他们相见。』欠拏太子听了这话，与帝稣噜即乘车骑，出满度摩城，往安乐鹿野园中，到毘婆尸佛前，头面礼足，瞻仰尊颜目不暂舍。那时，毘婆尸佛欲令欠拏欢喜信受，开示妙法。【义解】二人趋佛所礼足求法。佛欲令其欢喜信受，先说施戒生天之「次第说法」。",

"【佛说施戒生天·为说四谛】佛说：『如过去诸佛所说，若能布施、持戒、精进修行，能离欲色烦恼过失，得生净天。』当时，欠拏太子、帝稣噜听了这话，心得清净，如毘婆尸正等觉之心，生正解心、不疑心、善心、软心、广心、无碍心、无边心、清净心，又为（他们）宣说苦、集、灭、道四谛法行，种种开示。【义解】佛先施戒生天之「次第说法」令心调柔，次说四谛。「净天」指清净之天界。此即佛教说法之常轨：先施、戒、生天，后四谛。",

"【二人通达四谛·心净如白㲲】当时，欠拏太子、帝稣噜通达四谛，见法、知法，得法、坚牢法、依法、住法、不动法、不舍法、不空法，譬如白㲲（细棉布）无诸尘垢，悟法之心也复如是。【义解】「见法、知法」等为初果见道之描述，喻如白㲲离垢，谓离诸烦恼而得净信。「㲲」为细棉布。",

"【二人请出家受戒】」那时，欠拏太子、帝稣噜白毘婆尸佛说：『如来、应、正等觉，我愿出家，受善逝戒。【义解】二人见法得净信，发愿出家受戒。「善逝」为佛十号之一，此「善逝戒」即佛所制之戒。",

"【佛摄受剃发受戒·现三神通·成阿罗汉·颂】』佛说：『善哉！今正是时。』即与他们剃发、受具足戒。如是，彼佛为那二人现三种神通，令发精进趣向佛慧：一现变化神通，二现说法神通，三现调伏神通。如是现已，欠拏太子、帝稣噜勇猛精进，经须臾间真智相应，断尽诸漏，成阿罗汉。」那时，世尊而说颂说：「毘婆尸世尊，说法鹿野园，欠拏、帝稣噜，俱来至佛所，即以头面礼，瞻仰而一心。开示施戒门，苦集灭道法，闻已深信受，了达无生灭，俱求于出家，即受善逝戒。复睹神通力，速发精进心，须臾诸漏尽，成就阿罗汉。【义解】佛为二人现三种神通（变化、说法、调伏），令速证阿罗汉。「诸漏」即烦恼；「阿罗汉」为断尽诸漏、不受后有之圣果。",

"【八万人闻之亦愿出家】」那时，世尊说此偈已，告比丘言：「你今谛听！满度摩城人民炽盛，宿植善本有八万人，闻欠拏太子、帝稣噜正信出家，佛为说法现通而成圣果，如是思惟：『有如是出家，如是梵行，如是说法，如是调伏，世所希有，得未曾闻，我等今者亦愿出家。【义解】八万人闻二人成道而发心。此为继太子、二人之后第三波出家众。",

"【八万人出城诣佛·佛为说法】』作此念已，那时八万人俱舍家缘，出满度摩城，往安乐鹿野园毘婆尸佛所，头面礼足，退住一面，合掌瞻仰，目不暂舍。佛为说法令生信心，佛说：『如过去诸佛所说妙法，若人布施、持戒、精进修行，能离欲色烦恼种种过失，得生净天。【义解】八万人出城诣佛，佛依常轨说施戒生天之法。",

"【八万人通达四谛·心净如白㲲】』那时八万人听了这话，心得清净，如毘婆尸佛正等觉之心，生正解心、无疑心、软心、善心、广心、无碍心、无边心、清净心，又为他们宣说苦、集、灭、道四谛法行，种种开示。那八万人通达四谛，见法、知法，得法、坚牢法、依法、不坏法、住法、不动法、不舍法、不空法，譬如白㲲离诸尘垢，他们的心也复如是。【义解】八万人闻法通达四谛、心得清净，与欠拏等二人同日证悟。",

"【八万人请出家·佛摄受现通·成阿罗汉】当时八万人俱发声言：『如来、应、正等觉摄受我等，令得出家，受善逝戒。』佛即摄受、剃发受戒，又为彼众现三神通令发精进：一变化神通，二说法神通，三调伏神通。如是现已，那时八万人勇猛精进，不久之间，漏尽意解，成阿罗汉。【义解】八万人出家受戒，佛现三神通，不久漏尽成阿罗汉。「漏尽意解」谓断尽烦恼、心开意解。",

"【颂·八万人出家成圣道】」那时，世尊而说颂说：「满度摩城内，众有八万人，闻于欠拏等，出家成圣道，俱发清净心，而来诣佛所。闻法心欢喜，速起勇猛心，合掌白世尊，愿听我出家，受持于戒律。应时为摄受，剃发而受戒，复为现神通，断尽诸结缚，如灭尸利林，炽焰永不生，成就大解脱，如是众苦依，当得灭无有。【义解】颂重宣八万人闻法出家、佛现神通、断结证果。「尸利林」喻烦恼如林被焚，炽焰永灭；「众苦依」即苦之所依（烦恼），亦当灭尽。",

"【佛度众已还城·说因缘令坚固·颂】」那时，世尊说此偈已，告比丘言：「毘婆尸佛度此众已，出安乐鹿野园往满度摩城，八万比丘也往满度摩城，到世尊前，头面礼足，于一面坐。佛即具说得道因缘，令其坚固。」那时，世尊而说颂说：「难作极难作，轮回尽轮回，如是八万人，永断众结缚，亦如帝稣噜，欠拏太子仙，精进求出家，俱获解脱果。【义解】佛还城为八万人说得道因缘，令其道心坚固。「结缚」即烦恼之缠缚。",

"【佛念遣六万二千苾芻游方·天子劝请】」那时，世尊说此偈已，告比丘言：「当时，毘婆尸佛而作此念：『这大比丘众住满度摩城，宜应减少，令六万二千比丘往诣诸方，游行聚落随意修习，经六年后归满度摩城，受持波罗提目叉。』作此念时，于虚空中有天子知佛心念，告毘婆尸佛说：【义解】佛念遣六万二千比丘游方六年，以分散徒众、各自修行。「波罗提目叉」即「别解脱戒」（梵语 pratimokṣa），为僧团半月半月说戒之戒本。",

"【佛遣六万二千人游诸聚落】『善哉！若令六万二千比丘游诸聚落随意修行，经六年后复还本国，受持波罗提目叉，今正是时。』佛即告言：『你等比丘众中，令六万二千人游诸聚落随意修行，经六年后复还本国，受持波罗提目叉。』那时六万二千人听了这话，出满度摩城，随方游止。【义解】天子随喜劝请，佛即遣六万二千比丘游方，六年为期，还受戒法。",

"【颂·调御群生·六年复归】」那时，世尊而说颂说：「无漏无等等，调御大丈夫，导引于群生，令至寂静道。今遣比丘众，最上佛声闻，六万二千众，出彼满度城，游行诸聚落，如龙大威势，随意自修行，六年复本国。」【义解】颂赞佛无漏无等、调御群生，遣声闻众游方六年而还。「无等等」谓无与等者可比，为佛之尊号。",

"【六年期满·天人告归·受持波罗提目叉】」那时，世尊说此偈已，告比丘言：「那六万二千人即时出城，往诸聚落随意修行。如是过了一年、二年，至第六年，那些比丘互相告说：『六年已满，宜归本国。』说这话时，空中天人又告说：『今正是时，归满度摩城，受持波罗提目叉。』【义解】六年期满，比丘欲归，天人复劝其还城受戒。",

"【众以神力还城·颂】于是六万二千比丘，以自神力及天威德，经须臾间至满度摩城。」那时，世尊而说颂说：「彼佛大比丘，六万二千众，游诸聚落中，随意六年满。自思欲往还，天人普告示，令归满度城，受持清凉戒。闻之大忻庆，身毛皆喜竖，即运神通力，如乘大龙象，须臾还本城，自在无所碍。【义解】众比丘以神力须臾还城。「清凉戒」即别解脱戒，谓戒能除热恼得清凉。",

