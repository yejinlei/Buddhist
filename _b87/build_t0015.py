"【伽陀·我昔为女·汝等今为承事】「『我昔为女人，具智名密行，厌女求男相，常供佛法僧。时见你三子，而修声闻行，今生於下族，为我作承事。你等今当知，我为你说实，你昔为人时，四事咸丰足。不依佛禁戒，今可怀惭耻，了心即正法，唯智者能了。我昔你同行，近佛闻正法，起信持佛戒，及供养圣众。【义解】密行天子说伽陀：我昔为女、求生男相而常供三宝；你等昔为人时四事丰足，却不依佛戒，今堕下族为我承事。「四事」谓衣食卧具医药。",

"【伽陀·我因正行成帝释子·汝行不正】我因行正行，得为帝释子，具天大威力，自知名密行，止殊胜宫殿，转女成男相。你乾闥婆子，从佛持梵行，闻佛最上法，却为承事者。我于天界中，未见事今见，修持声闻行，而生於下族。你乾闥婆子，受我密行化，你等所受生，非彼诸佛子。【义解】续伽陀：密行因正行、持戒、供僧而生天为帝释子、转女成男；三乾闥婆子虽从佛持梵行，却因贪欲堕为下族承事者。",

"【乾闥婆子答·因贪欲堕趣·今起精进】』乾闥婆子说：『天所说诚实。我等因贪欲，堕乾闥婆趣，我今起精进，唯念佛正法，知贪欲生过，断彼贪欲心。贪为烦恼缚，其力胜魔军，弃佛真实法，故不生胜天。帝释与梵王，坐于善法会，观诸天胜行，经游天界者。【义解】三乾闥婆子闻密行天子之教而悔悟，知贪欲为过、为烦恼缚，起精进断贪。",

"【乾闥婆子·行不正不获胜果】见我生下族，经游于天界，我由行不正，而不获胜果。』那时密行天，白父帝释说：『父王今当知，我佛最上尊，出现于世间，善降诸魔军，名释迦牟尼。此三乾闥婆，是彼佛之子，忘失于正念，堕乾闥婆趣。【义解】乾闥婆子自省行不正故不获胜果。密行天子乃白帝释，称此三乾闥婆本为佛之子，因忘失正念而堕此趣。",

"【三中一不正知·二归正道当生梵天】而于那三中，唯一不正知，余二归正道，常向佛菩提，而行于正法，所见诸声闻，无有能及者。彼远离所欲，能断于烦恼，唯念佛世尊，不复生余想。所有未了法，彼二悉正知，当得胜果报，而生於梵天。【义解】三乾闥婆子中，一人不正知，二人已归正道，常向菩提，远离所欲、断烦恼，当生梵天。此段为帝释疑问之所在。",

"【帝释自陈有疑·佛念其无垢·许问·二伽陀】』」世尊！我于那时闻密行天子说此偈已，我于此有所未决，故来佛所，欲伸请问。愿佛垂愍，为我宣说。」那时，世尊而作此念：「帝释天主于长夜中无懈、无废、无尘、无垢，如有所问，是真不知非作魔事，彼有所问当为宣说。【义解】帝释自陈疑问，佛以其无尘垢、真实不知而非魔事，故许为宣说。",

"【帝释问·以何为烦恼·佛答憎爱】」作此念已即说伽陀，告帝释说：「帝释今当知，你心中所乐，欲有所问义，当问我为说。」那时，帝释天主即说伽陀，白世尊说：「今蒙佛听许，如我意所乐，我今当启请，愿佛为宣说。」帝释天主说伽陀已，白佛说：【义解】佛与帝释各以伽陀问答之礼相酬，帝释乃发问。",

"【佛广明憎爱·帝释领解·复问因集】「世尊！所有天人、阿修罗、乾闥婆及诸异生等，以何为烦恼？」佛说：「以憎爱为烦恼。帝释天主！所有天人、阿修罗、乾闥婆乃至诸异生等，而作此念：『呜呼！我自于他先无侵害，也不怨枉、不斗、不诤、无诉、无讼，又不相持，云何于我返作此事？【义解】佛答「憎爱为烦恼」，并说明其表现：众生见他人加害于己而生怨憎。「异生」即凡夫。",

"【佛广明憎爱·帝释领解·复问因集】』天主！如是之事由憎爱起，憎爱起了故烦恼遂生。」帝释白说：「世尊！如是，如是，如佛所说，我今从佛了知此义，憎爱为烦恼。断于疑惑，满所乐心。」那时，帝释天主得闻佛说欢喜信受，又白佛说：【义解】佛指出憎爱为一切烦恼之源；帝释领解，断疑满愿，进而请问憎爱之因。",

"【佛答·怨亲为因·无怨亲即无憎爱·帝释复问】「世尊！此憎爱烦恼，何因何集？何生何缘？何因得有？何因得无？」佛说：「天主！此憎爱烦恼，怨亲为因，怨亲而集，从怨亲生，怨亲为缘，由怨亲故，有憎爱烦恼，若无怨亲，憎爱即无。」帝释白佛说：【义解】佛答：憎爱以「怨亲」（怨与亲之别）为因。层层推因，此为第一重。",

"【佛答·所欲为因·帝释复问所欲】「如是，如是，如佛所说。我今从佛了知此义，憎爱烦恼怨亲为因，若无怨亲即无憎爱。」又白说：「世尊！怨亲因何有？从何集？由何生？依何缘？何因得有？何因得无？」佛告帝释：「所欲为因，从所欲集，由所欲生，依所欲缘，因其所欲故有怨亲，若无所欲怨亲即无。【义解】佛答：怨亲以「所欲」（贪欲）为因。层层推因，此为第二重。",

"【佛答·疑惑为因·帝释复问疑惑】」帝释白佛说：「世尊！如是，如是，如佛所说，而那怨亲因所欲有。」又白说：「世尊！而此所欲，何因而有？从何而集？由何而生？依于何缘？何因得有？何因得无？」佛说：「帝释！所欲因疑惑有，从疑惑集，由疑惑生，依疑惑缘，因疑惑故而有所欲，若无疑惑即无所欲。【义解】佛答：所欲以「疑惑」（疑惑、迷茫）为因。层层推因，此为第三重。",

"【佛答·虚妄为因·次第相因·成大苦蕴】」帝释白说：「世尊！如是，如是，如佛所说，所欲因疑惑有。」又白说：「世尊！疑惑何因？何集？何生？何缘？而此疑惑，何因得有？何因得无？」佛告帝释：「以虚妄为因，从虚妄而集，由虚妄生，依虚妄缘，以虚妄故即有疑惑，由疑惑故致有所欲，因其所欲故有怨亲，由彼怨亲遂有憎爱，以憎爱故，乃有刀剑相持、诉讼斗诤，情生谄曲，语不真实，起如是等种种罪业不善之法，由此得一大苦蕴集。【义解】佛答：疑惑以「虚妄」为因。至此层层推因圆成：虚妄→疑惑→所欲→怨亲→憎爱→斗诤罪业，成一大苦蕴。此为全经义理之枢纽。",

"【佛明虚妄灭则苦蕴灭·帝释领解】天主！若无虚妄即无疑惑，若无疑惑即无所欲，所欲既无怨亲何有？怨亲不立憎爱自除，憎爱无故，刀剑相持、诉讼斗诤，谄曲之情、不实之语，如是等种种罪业不善之法，皆悉得灭，如是则一大苦蕴灭。」帝释白佛说：【义解】佛明还灭：虚妄灭则疑惑灭，乃至苦蕴灭。与上流转门相对，示灭苦之道。",

"【帝释问灭虚妄之法·佛答八正道】「如是，如是，如佛所说，因疑惑故则有虚妄。」又白佛说：「世尊！虚妄之法以何法灭？乃至苾芻当云何行？」佛告天主：「灭虚妄者，谓八正道。八正道者，正见、正思惟、正语、正业、正命、正精进、正念、正定，由是八法虚妄得灭。【义解】佛答：灭虚妄之法即八正道。此为全经所归之行道。",

"【佛明八正道灭虚妄·帝释问别解脱法几种】若诸苾芻行此法者，是即名为灭虚妄行。」帝释白佛说：「如是，如是。世尊！灭虚妄者是八正道。」帝释又白佛说：「世尊！所灭虚妄法，若苾芻行者，当于别解脱法中有几种法？」佛说：「天主！虚妄法者，于别解脱法中，有六种法。【义解】佛明行八正道者即灭虚妄。「别解脱法」（波罗提木叉）为比丘戒法。佛答其中有六种法（六根门）。",

"【佛答六种法·眼观色等六根·可不可观】何等为六？所谓眼观色、耳听声、鼻齅香、舌了味、身觉触、意分别法。天主！眼观于色有二种义，谓可观、不可观。不可观者，谓于一切染法境界而不可观；可观者，谓于一切善法境界而可观察。如是眼观色境，乃至意分别法，也复如是。【义解】别解脱法六种法即六根（眼耳鼻舌身意）对六境（色声香味触法）。观之则分「可观」（善法）与「不可观」（染法）。",

"【佛明可不可观之义·帝释领解】」」世尊！我今从佛了知此义，不可观者，所有眼境不善之法，若其观者，是即增长染法、损减善法。其可观者，所有眼境一切善法，若其观者，即是增长善法、损减染法。乃至意分别法也复如是。世尊！【义解】帝释领解六根对境之可观（善）与不可观（染），观善则善增染减，观染则染增善减。",

"【帝释领解·问当断几法行几法】我今从佛闻此法已，满所愿乐，断于疑惑。」又白说：「世尊！若又苾芻欲灭虚妄者，当断几法？当行几法？」佛说：「天主！若有苾芻，欲灭虚妄法者，当断三法、当行三法：一疑惑、二悕望、三无义语。【义解】帝释复问灭虚妄者当断几法、行几法。佛答当断三法：疑惑、悕望（希求）、无义语，亦当行三法。",

"【佛明三法可行不可行·帝释领解】此三种法，也有可行、有不可行。不可行者，谓于此三种不善之法，当断不行，若又行者，增不善法、损于善法；可行者，谓于此三种不善之法勤行除断，即得不善损减、善法增长。」帝释白说：「世尊！【义解】三法有可行（勤行除断）与不可行（当断不行）之别：断之则善增，行之则善损。",

"【帝释领解·问行灭虚妄者几种身】如是，如是，我今从佛了知此义。疑惑、悕望、无义语等三种之法，若又行者，损诸善法、增长不善。若又苾芻，于此三法勤行除断，即得不善损减、善法增长。」又白说：「世尊！若有苾芻，行灭虚妄法者，有几种身？【义解】帝释领解三法之义，又问行灭虚妄法者有几种身（受）。",

"【佛答三种身·适悦苦恼舍·各有二义】」佛说：「天主！若有苾芻，行灭虚妄法有三种身。三种身者，谓适悦身、苦恼身、舍身。适悦身者，有其二义，谓可行、不可行。可行者，谓诸善法；不可行者，谓诸不善法。苦恼身、舍身也复如是。」【义解】三种身即三种受：适悦（乐受）、苦恼（苦受）、舍（不苦不乐受）。各有可行（善法）与不可行（不善法）二义。",

"【帝释领解·三身善可行不善不可行·问众生同不】帝释白佛说：「世尊！如是，如是。我今从佛了知此义，若那苾芻行灭虚妄法者，于适悦身、苦恼身、舍身，于此三身诸善法等可行，诸不善法等皆不可行。」那时，帝释又白说：「世尊！所有一切众生，乐欲、忆念、色相皆悉同吗？【义解】帝释领解三身之义，进而请问众生之欲、念、色相是否相同。",

"【佛答非同·众生不知界趣差别·执痴为实】」佛说：「不也。天主，一切众生，非同一欲、非同一念、非一色相。天主！一切众生虽然各各居其界趣，也各不知界趣差别，彼由不知界趣差别，是故行于黑闇之道，返执痴法以为真实。此诸众生不知界趣种种差别，所了知者唯黑闇界，虽又了知，而也常行于黑闇道，坚执痴法以为真实。【义解】佛答：众生之欲、念、色相各不相同。因其不知界趣（各界各趣）之差别，故行于黑暗之道，执痴为实。「界趣」谓六道诸界。",

"【帝释领解·复问沙门婆罗门得梵行不】」帝释白说：「世尊！如是，如是，如佛所说，我今从佛了知此义，一切众生非同一欲、非同一念、非一色相，由彼众生不知差别，故执痴闇而为真实。」那时，帝释又白佛说：「世尊！所有一切沙门、婆罗门等，皆得究竟清净梵行吗？【义解】帝释领解众生之差别，又问一切沙门婆罗门是否皆得究竟清净梵行。",

"【佛答有二义·尽爱法者得·不尽者不得】」佛说：「不也。此有二义。天主！若那沙门、婆罗门等，不能尽彼爱法，决定不获究竟清净梵行。若那沙门、婆罗门等，有能尽彼爱法，乃得无上解脱、心正解脱，是名获得究竟清净梵行。」帝释白佛说：【义解】佛答：沙门婆罗门不尽「爱法」（贪爱）者，不得究竟梵行；能尽爱法者，方得无上解脱。「爱法」为生死根本，故须尽之。",

"【帝释领解·复问永离诸见之病】「世尊！如是，如是，如佛所说，我今从佛了知此义。若沙门、婆罗门等不尽爱法，决定不获究竟清净梵行。若有沙门、婆罗门等尽彼爱法，决定获得无上解脱、心正解脱，是名获得究竟清净梵行。」那时，帝释又白佛说：【义解】帝释领解「尽爱法」之义。此下请问永离诸见之病。",

"【佛言往昔亦有问者·帝释自述宿缘】「世尊！我今云何当得永离诸见之病使不复生？是诸见病从心识生，我此心识当复云何？我虽问佛种种之义，云何不能获圣果报，得佛、如来、应、正等觉？唯愿世尊，为我断除疑惑根本诸见之病。」佛说：【义解】帝释请问如何永离「诸见之病」（恶见、邪见）。佛乃以过去之事作答。",

"【帝释述·诸天不知法欲成佛·佛不与记莂】「天主！你知吗？于往昔时，有沙门、婆罗门也问此义。」帝释白说：「世尊！我今忆念，于一时中有大威力诸天，集忉利天善法之会。那时，会中有诸天人，不知法者辄欲成佛，以如是意告白世尊，佛察其愚闇不与记莂。【义解】帝释自述宿缘：昔有天人不知法而辄欲成佛，佛以其愚暗不予授记。「记莂」即授记，预言成佛。",

"【诸天不满所愿·本界不现·惊怖疑惑】那时，那些诸天不满所愿，心有差别，从座而起，各还本界，本界不现因遂堕落。那时，那些诸天以堕落故即大惊怖，心生疑惑，各作此念：『本界不现定知堕落，我若得见沙门、婆罗门者，即往请问：你是如来、应供、正等正觉不？【义解】诸天不满所愿，从座而起，本界不现而堕落，惊怖疑惑。「本界不现」为其天福将尽、堕落之兆。",

"【诸天问我·我答是帝释·彼求救护】』那时，那些诸天或有见我唯独经行，来诣我所而问我说：『仁者！你是何人？』我时答说：『是帝释天主。』那时，那些诸天心苦恼故，白说：『天主！岂不见我受于苦恼，以我向佛应当问法而不能问，应可归依而不归依，以差别心遂还本界，本界不现定知堕落。【义解】堕落诸天见帝释经行而问，帝释自陈身分。诸天自述其过：向佛应问法而不问、应归依而不归依。",

"【诸天誓归依·帝释说伽陀答】是故苦恼，愿见救护。天主！我从今日誓归依佛为声闻弟子。』我于那时即说伽陀，答彼天说：【义解】诸天誓归依佛为声闻弟子，帝释乃以伽陀教诫。下为伽陀。",

"【伽陀·邪念求佛心差别受苦】「『你等起邪念，所言也不正，求佛心差别，由是长受苦。或见于沙门，及彼婆罗门，经行即请问，你是正觉不？【义解】伽陀明：起邪念、求佛之心有差别者，长受苦恼。或有见沙门婆罗门便问是否正觉。",

"【伽陀·若是正觉者我归依·唯佛是世间大师】若是正觉者，我归依供养。我即问于彼，当云何供养？所问不能知，佛如实正道。时彼诸天众，心之所乐欲，心与心所法，疑惑而分别。我知彼心法，如世尊所说，我已当为说，于彼三界中，唯有佛世尊，是世间大师。【义解】续伽陀：若真是正觉则当归依，然彼等不知如实正道。帝释知彼心念，当为宣说：三界之中唯佛是世间大师（天人师）。",

