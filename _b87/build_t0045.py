"【人间百年等忉利天一日夜·生天者岂回人间】大王！譬如秽坑臭不可近，时有一人误堕其中，臭秽难堪、方便得出；身既出已，即用诸香煮水沐浴，又以涂香涂其身，身既香洁，又以殊妙迦尸迦衣及珍宝花鬘庄严其身，住于家中受其快乐。大王！于意云何？【义解】迦叶以秽坑喻人间：出秽坑者岂愿复入。「迦尸迦衣」为波罗奈出产之细软衣。",

"【天人寿命不相等·不应愚望相报】如是之人还又乐入前秽坑吗？」王说：「不也。迦叶！那秽恶坑，人所不乐。」迦叶又说：「大王！那人生天也复如是，既得生天，岂又更思还来人间？又次，大王！人间百年等忉利天是一昼夜。大王亲属修诸善法，既生天界昼夜受乐，岂又更思还来报王：我生天界昼夜受乐。【义解】迦叶以秽坑喻破之：生天者如出秽坑，不复入人间；且人间百年仅忉利天一日夜，天人不暇回报。",

"【王言未可信·何人来告汝】大王！你与天人寿命长短为相等吗？」王说：「不也。迦叶！」迦叶又说：「大王！天界人界本自悬隔，不应如愚顒望相报，然后方可信有后世。大王！那沙门婆罗门、应供、世间解，乃至后世须知实有，可以自智如实了知，不应更作无后世见。」王报迦叶：「如尊者言也未可信。何以故？所说人间百年等忉利天为一昼夜，有何人来告语于你，人间百年等忉利天为一昼夜？」【义解】王不信，迦叶乃以生盲喻继之。",

"【迦叶以生盲喻·盲人执无色相】迦叶又说：「如王所见，喻如生盲之人。何以故？生盲之人本自不见青黄赤白、细妙粗恶长短色相，便作此说：『本无如是青黄赤白、细妙粗恶长短色相。』又说：『我也不知，我也不见。』这生盲之人以己不见，便乃执说本无如是青黄赤白乃至长短色相。大王！勿同生盲执无色相。【义解】迦叶以生盲喻：盲人不见色而执言无色，如王不见来世而执言无。",

"【王言汝非善人·见我同生盲·喻不成立】」王说：「迦叶！如我意者，而那天界若实有者，我即言有，既实本无，云何令我嗔说实有？」又说：「迦叶！你非善人。何以故？我见本正，云何喻我同那生盲？迦叶！你前所说生天等事，我实不信，若信此言，如食毒药、如刃临身、如上山坠身自害其命。如是诸恶，我皆远离。」【义解】王斥迦叶之喻不当，仍执己见。",

"【迦叶说婆罗门继母贪嫉损孕喻】又次，迦叶报大王说：「我念往昔有婆罗门，家中巨富又乃耆年，唯有一子，年才十六，母即丧亡。那婆罗门不能鳏独，遂再婚娶，未久之间妻乃有妊，妻未生产，其婆罗门寻亦命终。于是其子白继母说：『家中财物金银珍宝，乃至一切受用之具，悉属于我，更无别人分我财物。』那时，那继母闻子语已，即告子说：『我今所怀是你父遗体，待其长育，与你均分。』其子时又再说其事，母起思念：『此子年幼情性痴騃，虽与深言未能分晓。』又以贪惜，欲疾产身，多設方便求于速产，日月未满，返损其孕。【义解】婆罗门遗子与继母争财；继母贪嫉、欲速产分财，反致堕胎。喻断见者因贪痴而自害。",

"【王仍不信·坚执无人无后世无化生】大王！那女人以贪嫉故返损其孕，大王！今者以愚痴故起于断见。」王又报说：「迦叶尊者！莫如前言。持戒修善及行惠施，命终之后得生天上，寿命长远常处快乐。我实不信。我今若信迦叶之语，是食毒药、是受刀剑、是坠高山自害其命。云何，迦叶！坚作此语？如我之意，定无人、无有后世、也无化生。【义解】迦叶以继母喻断见乃愚痴自害。王仍不信，坚执断见。",

"【迦叶问更有何喻·王以亲属病终喻】」又次，迦叶告大王说：「莫复有喻证于此事吗？」王说：「迦叶！我又有一喻证于此事，知无人、无有后世、也无化生。迦叶！如我亲属或染重病，我即往彼安慰问讯，命未断者还与我语说其苦恼，及命终已，无有与我说苦恼者。【义解】王别举亲属病终之喻：命终之人不复言语，故无后世。",

"【王述临终能语·命终无语·故无后世】以此可知，定无后世也无化生。」【义解】王以此喻自证无后世。",

"【迦叶说聚落人问螺喻】迦叶告说：「我念往昔有一聚落，其中人民不识螺相，也复未曾闻其螺声。忽有一人从外而来，到那聚落而便止住，此人常持一螺以为功业，每日执螺诣于圣像鸣螺供养，供养已讫又还住处。【义解】迦叶以「螺声喻」破之：螺本无情、不能言答，如命终者不能言语、不能回答。",

"【聚落人欲令螺共问答·螺无情】那时聚落中一切人民，忽闻螺声咸悉惊怪，互相谓说：『这是何声？我等众人本所不闻。』大王！那时聚落中一切人众共往螺处，问那螺说：『你从何来，可依实答，若不言实我当破你，螺知我意速说其由。』大王！那人民众，于其螺相及与螺声，本所不见、本所不闻，欲使其螺共为问答，螺既无情，岂能言答？【义解】聚落之人不识螺，欲令螺解答；螺无情不能言，如死人不能语。",

"【如王与命终人言论·岂能再言】何以故？也如大王！与命终人欲共言论，人既命尽，岂能再言。大王不应执如是见，谓无人及无后世、也无化生。」【义解】迦叶结螺喻：死人不能语，故此喻不能证无后世。",

"【迦叶说有天眼者见死此生彼·可为证】迦叶又说：「有沙门婆罗门具天眼者，以净天眼悉见于人死此生彼，受身好恶、端正丑陋，或得生天、或堕恶趣。大王！如是等事皆可为证，不应更言无有后世、也无化生。」王说：「迦叶！虽说此喻，我意未允。【义解】迦叶举具天眼者能见众生生死流转为证。",

"【王言喻未允·定无化生后世】如我之见，定无人、也无化生及无后世。」【义解】王仍不服。",

"【迦叶问更有何喻·王以治罪身软硬喻】又次，迦叶告大王说：「若如是者，又有何喻可证无人、也无后世及无化生？」王说：「尊者！譬如官吏执法理人，及其临莅自违条制，后被弹奏，王遂具知，乃敕法司将犯罪人依法断理。【义解】王别举治罪之喻：罪人命在身软、命断身硬，以死活之异证无来世。",

"【王述罪人命在柔软·命断僵硬·故无来世】王又令说：『那犯罪人可缚双手，将赴法处而苦治之，以绳系缚秤轻重，割皮削肉悬置异处。』此人命在，知其痛苦；若命已断，自无声息。又那罪人命未断时身即柔软，命既断已其身僵硬，至于轻重死活不同。尊者！我以此知定无来世，也无人、又无化生。【义解】王述：罪人命在则软、命断则硬，故身死即灭，无后世。此为王之喻。",

"【迦叶以铁丸冷热软硬喻·四大合散】」迦叶又说：「大王！于意云何？譬如铁丸也有轻重软硬之异，其铁热时体轻而软，其铁冷后体重而硬。大王！有情无情皆禀四大，以那四大有其合散，是有软硬冷热之异，勿将此理比于后世及化生等。【义解】迦叶以铁丸冷热软硬喻：身之软硬由四大合散，非关有无来世。",

"【迦叶劝知有天眼者见众生死此生彼】大王须知，实有那沙门婆罗门或具天眼者，见于众生死此生彼，乃至端正丑陋，或生天上、或堕恶趣，悉可证知，实有来世及化生等。」王说：「尊者！如你所言，未为诚信。我之意者，实无人、无有后世、也无化生。【义解】迦叶复举天眼者之证。王仍不信。",

"【王言未为诚信·定无后世（译人题重出）】」西天译经三藏、朝散大夫、试光禄卿、明教大师臣法贤奉诏译。又次，迦叶告大王说：「勿更有喻，证那无人及无后世、也无化生？」王说：「我又有一喻可证此理。尊者！譬如有人犯极重罪，近臣知已即白于王：『今有此人犯极重罪。【义解】此处原文重出译人题一行，为原经所有，照录不改。",

"【王以镬中煎煮寻觅喻】』王既知已，乃令所司捉缚罪人依法断理。法司奉命，即将罪人，缚其两手，于镬中煎煮。又宣令说：『待其糜烂彻见骨已，可于镬中以杖翻搅，子细寻觅那后世人及化生等出入之者。』法司奉命，一依王旨，至糜烂时乃于镬中翻搅寻觅，终不见有后世之人及化生等出入之者，乃至展转重重寻觅，也终不见。【义解】王喻：将罪人煎煮至糜烂，于镬中寻觅后世人、化生者而不得，故无后世。此为古印度外道之见。",

"【王述镬中寻后世人·终不见】」王说：「尊者！以此喻知，实无人、无有后世、也无化生。」【义解】王以此喻自证无后世。",

"【迦叶以梦喻·梦中园林非实】于是迦叶告大王说：「大王！譬如有人，于眠睡时梦一殊胜园林，园中乃有种种树木，花果茂盛、池沼清洁，其人梦中甚可爱乐。大王！那园林为实有吗？又复看玩及彼出入，为是实吗？」王说：「不也。迦叶！如梦所见皆非真实。」【义解】迦叶以梦喻破之：梦中园林非实有，王所执断见亦如梦境之虚妄。",

"【迦叶劝要须诚谛知有后世·不应执断见】迦叶报说：「也如大王所执断见，非为真实。大王！要须诚谛知实有人、有后世、有化生，乃至实有沙门婆罗门，具清净天眼超越世间，见诸众生死此生彼、端正丑陋，或得生天、或堕地狱。此是真实，不应更执如前断见。」【义解】迦叶以梦喻结：王所执断见如梦之非实，要须诚谛知有后世。",

"【王言重重作是说·定知无人无后世】王说：「尊者！云何重重作此说？如我意者，定知无人、无有后世、也无化生。」【义解】王仍坚执。",

"【迦叶问更有何喻·王以割皮断筋寻人喻】又次，迦叶报大王说：「又有何喻，可证无人、无有后世、又无化生？」王说：「尊者！我又有一喻以证此理。【义解】王另举一喻：割皮断筋折骨挑髓以求人及化生者而不得。",

"【王述于皮肉骨髓中寻人不获·故无化生】譬如有人执行王事自违条格，近臣奏闻，王乃具知，令付法司鞫问情实。其罪既重，宣令苦治，即使先割皮肉后断筋脉、折骨挑髓，寻觅于人及化生者。法官奉命准法施行，如王所言不敢违越，一一次第于皮肉筋脉骨髓之内，寻觅于人及化生等，始终不见有人及化生等。尊者！以此喻知，实无人、也无化生、又无后世。」【义解】王喻：于身之皮肉骨髓中寻人及化生者而不得，故无化生。此为断见之又一论证。",

"【迦叶说道人养遗儿·火灭求火喻】迦叶告说：「大王！我念昔时，有一道人住于山中。时有商人，将多车乘载于财货，近道人庵止宿而去。那时，那道人乃于明旦观其宿处，恐遗财物，果于此处见一童子，才离乳哺、未识东西，是众商人之所遗坠。道人慈愍，恐那童子饥渴所损，将归庵中如亲养育。而那道人事火为行，常专其心添续柴薪，未曾断灭，以那童子日来月往，渐渐长大，年十五六。道人思惟：『童子长大，堪可委付。』一日道人以缘事故，当入城隍，暂拋庵所，即诫童子：【义解】迦叶以「道人养遗儿、火灭求火」喻破之：如于冷灰中求火，必不可得。",

"【童子忘添火·火遂灭】『我有事缘要须暂出，庵中之火，如我每日添续柴薪，勿令断灭。』说罢便行。道人既出，童子痴騃，由贪戏玩，为贪戏故忘其事火，以无添续，火遂断灭。那时，童子见火灭已，收拾柴薪积于炉内，发言祝说：【义解】道人养童子成人，将外出，嘱其续火；童子贪玩忘添，火灭，乃积薪祈火。",

"【童子以善恶言祈火·火终不出】『你火速出，若火不出，我当坏你。』那童子苦切求哀，火终不出。火不出故，更发恶言：『火不出者，也当打你。』那时童子求火不出，心即忧怖：『道人归来，必当辱我。』住在一面思惟火事。道人事毕归还庵中，见子默坐，便知火灭，谓童子说：【义解】童子祈火不出，忧怖待道人归。",

"【道人归·教火灭须得火方然】『你贪放逸，致火灭吗？』童子答说：『我暂忘失，火已灭矣。火灭之后积薪于炉，以善恶言祈火不出。』道人说：『你甚痴騃！火若灭已，得火方然。未闻积薪于冷灰中有火自出，设你炉中积无量薪、作多方便，徒自疲劳，无由得火。【义解】道人教童子：火灭须更求火种乃可再燃，冷灰中求火必不可得。",

"【迦叶比童子求火于灰·如王执断见】』大王！而这童子于火灭后灰中求火，也如大王愚迷不回，于死尸中搜求于人及化生者，妄执无人、起于断见。大王！应须知，实有人及有化生、有于后世。」王说：「尊者！莫如此言。我或从你言有后世，必为人议。【义解】迦叶结喻：王于死尸中求人、求化生，如于冷灰求火。",

"【王恐国人议其随迦叶所化·不肯回见】何以故？今此都人便作此语：『王自昔来不信因果，常作此语，云无后世及无人、也无化生。今日却随迦叶所化。』」【义解】王恐失颜面，不肯回其见。",

"【迦叶说二商主同行·一主先行遇鬼】迦叶又说：「大王！我念往昔有二商主，皆有财宝、一国无过，后于一时相约为侣，同往他邦货鬻求利。这二商主，各集商人以为伴侣，于是各各多装车乘，排比鞍马、同日上路，行赴前程。去国既遥，艰险在近，一人商主素知此路前有艰险，告一商主说：『你今知吗？前路艰险，无人烟，商众既多，宜其预备。』【义解】迦叶以「二商主行旷野遇鬼」喻：信妖妄者受大苦。",

"【二商主集众同行·前路艰险】」二主议已，一主先行，意在少人所须易足，所有米面饮食之用，乃至柴薪皆也持去。前行之次，忽逢一人相迎而来，身大黑色、两目皆赤，顶发稀疏、衣服褴褛，驾一驴车，其状如鬼。商主问说：『仁者！前路还有饮食、柴薪等吗？』【义解】先行商主逢一黑色赤目、状如鬼之人（实为鬼），问前路有无饮食。",

"【一主先行·米面柴薪皆持去】那人答说：『前路之中甚有饮食柴薪等物，皆悉无乏，你之所载咸可弃之，免你前行为重所滞。』那时商主闻此语已，谓商众说：『你等人众咸闻所言，前路之中饮食等物既不乏少，何用赍持分外之物困于车马？』【义解】鬼妄言前路丰足，劝商主弃其所载。",

"【前行逢黑色赤目鬼·问前路有无饮食】」商主及伴皆非智人，便以所持弃之而去。行第一日至于日没，唯有旷野不逢人烟，四顾杳然，无所取给，饮食既乏，悉受饥渴，忍苦终夜，强又前进，于第二日又行至夜，但在旷野，余无所睹。商众共议前所逢者，思其相貌定知是鬼：【义解】商主信鬼言弃粮，行二日皆旷野，受饥渴之苦。",

"【鬼妄答前路丰足·劝弃所载】『我等无智，便信彼言，妖妄惑人以致如是。』至第三日，人马俱乏，悉不能进，相顾无语，待死而住。那一商主隔日而进，也逢是人相迎而来，乃问说：『前路之中还有饮食所须物吗？』那人同前一一妄说：【义解】商众悟彼是鬼，然已人马俱乏待死。后一商主隔日而行，又逢此鬼。",

"【商主信之·弃物前行·受饥渴】『饮食所须皆不乏少，何用所持重滞车马？是物可弃，你宜知之。』后一商主智慧聪明，凡所施为必先思虑，素知此路有大旷野艰险之处，度其地里险难非遥，又察是人颜貌不常、行李粗恶，或恐妖妄，不可信之，与诸商人议论而进。【义解】后一商主有智，察鬼之妖妄，不信其言。",

