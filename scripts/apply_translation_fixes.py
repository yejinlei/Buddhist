def locate(doc, loc):
    if loc == 'translator':
        return doc, 'translator'
    if loc == 'intro':
        return doc, 'intro'
    if isinstance(loc, tuple) and loc[0] == 'tr':
        _, i, key = loc
        return doc['translations'][i], key
    raise ValueError(loc)


def main():
    by_id = {}
    for pid, loc, old, new in FIXES:
        by_id.setdefault(pid, []).append((loc, old, new))
    total = 0
    for pid, items in by_id.items():
        fp = os.path.join(D, f'{pid}.json')
        doc = json.load(open(fp, encoding='utf-8'))
        for loc, old, new in items:
            obj, key = locate(doc, loc)
            assert key in obj, f'{pid} {loc} 缺字段 {key}'
            cnt = obj[key].count(old)
            assert cnt == 1, f'{pid} {loc}: 命中 {cnt} 次，预期 1 次 -> {old[:40]}'
            obj[key] = obj[key].replace(old, new)
            total += 1
        json.dump(doc, open(fp, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
        print(f'✅ {pid} 修正 {len(items)} 处')
    print(f'共修正 {total} 处')


if __name__ == '__main__':
    main()
