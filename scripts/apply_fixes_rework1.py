# -*- coding: utf-8 -*-
"""第26批返修：按 5 份独立校对报告落实高/中危及重点低位问题。
每条替换均断言唯一命中，保证幂等可复现。
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "data", "baihua-out")

def load(t):
    return json.load(open(os.path.join(D, t + ".json"), encoding="utf-8"))

def save(t, d):
    json.dump(d, open(os.path.join(D, t + ".json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)

def rep(d, i, old, new):
    m = d["translations"][i]["modern"]
    if old in m:
        assert m.count(old) == 1, f"唯一命中失败 count={m.count(old)}: {old[:40]}"
        d["translations"][i]["modern"] = m.replace(old, new)
    else:
        assert new in m, f"old/new 均未命中: {old[:40]}"

n = 0

# ---- t0102 段1：义理偏差（「我欲如是色」= 主宰自在义） ----
d = load("t0102")
rep(d, 0,
    "色就不应当生病以及遭受苦恼，也不应当想『我要色是这样，我不要色是这样』。既然不能这样随顺心情所欲，所以应当知道，色不是我；",
    "色就不会生病、不会受苦恼，也能随意令色这样、令色不这样；然而既不能如此随心所欲，所以当知：色不是我；")
save("t0102", d); n += 1

