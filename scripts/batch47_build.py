def save(tid, title, translator, intro, trans):
    obj = {
        'sutra_id': tid,
        'sutra_title': title,
        'translator': translator,
        'sutra_intro': intro,
        'mode': 'sectional',
        'translations': trans
    }
    with open(f'{OUT_DIR}/{tid}.json', 'w', encoding='utf-8') as f:
        json.dump(obj, f, ensure_ascii=False, indent=2)
    print(f'✅ {tid} {len(trans)}段')

def mk(preview, section, modern):
    return {'original_preview': preview, 'section': section, 'modern': modern}

