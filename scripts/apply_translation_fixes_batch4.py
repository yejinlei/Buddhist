def main():
    # 按文件分组载入
    cache = {}
    def load(sid):
        if sid not in cache:
            p = os.path.join(TR, sid + ".json")
            with open(p, encoding="utf-8") as f:
                cache[sid] = json.load(f)
        return cache[sid]

    applied = 0
    for sid, kind, idx, field, old, new in FIXES:
        d = load(sid)
        if kind == "top":
            cur = d[field]
        else:
            cur = d["translations"][idx][field]
        cnt = cur.count(old)
        assert cnt == 1, f"[{sid} {kind} {idx} {field}] 命中 {cnt} 次（应为 1）：{old[:40]}"
        assert new not in cur or True
        if kind == "top":
            d[field] = cur.replace(old, new)
        else:
            d["translations"][idx][field] = cur.replace(old, new)
        applied += 1

    # t2010：先改 section[2]，再把每段 modern 首标【白话】→【该段 section】
    d = load("t2010")
    assert d["translations"][2]["section"] == "违顺相争是心病"
    d["translations"][2]["section"] = "违顺相争·是心病"
    for t in d["translations"]:
        assert t["modern"].startswith("【白话】"), f"t2010 '{t['section']}' 首标非【白话】"
        t["modern"] = t["modern"].replace("【白话】", "【" + t["section"] + "】", 1)
        applied += 1
    # t2010 其它
    for idx, field, old, new in [
        (23, "modern", "眼睛若不闭上（不睡）", "眼睛若不睡（不闭合）"),
        (22, "modern", "「梦幻空华」是《金刚经》「如梦幻泡影」之意",
         "「梦幻空华」与《金刚经》「如梦幻泡影」取意相通"),
    ]:
        cur = d["translations"][idx][field]
        assert cur.count(old) == 1, f"t2010 {idx} 命中 {cur.count(old)}：{old[:30]}"
        d["translations"][idx][field] = cur.replace(old, new)
        applied += 1

    # 写回
    for sid, d in cache.items():
        p = os.path.join(TR, sid + ".json")
        with open(p, "w", encoding="utf-8") as f:
            json.dump(d, f, ensure_ascii=False, indent=2)

    print(f"完成：共应用 {applied} 处修正，涉及 {len(cache)} 个文件")

if __name__ == "__main__":
    main()
