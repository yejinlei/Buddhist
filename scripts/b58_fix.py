import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TR   = os.path.join(ROOT, "data", "modern-translation")
SUT  = os.path.join(ROOT, "sutras")

def load(tid):
    return json.load(open(os.path.join(TR, tid + '.json'), encoding='utf-8'))

def save(tid, d):
    json.dump(d, open(os.path.join(TR, tid + '.json'), 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)

def rep(d, idx, old, new, tid):
    m = d['translations'][idx]['modern']
    assert m.count(old) == 1, f'{tid} 段{idx+1} 锚点不唯一/未找到: {old[:30]!r} (count={m.count(old)})'
    d['translations'][idx]['modern'] = m.replace(old, new)

