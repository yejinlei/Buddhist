'''第47批剩余9部 + 修正t1134b —— 所有preview必须是原文连续子串（精确逐字）'''
import json, os

SUTRA_DIR = 'sutras'
OUT_DIR = 'data/modern-translation'

def load(tid):
    with open(f'{SUTRA_DIR}/{tid}.json', 'r', encoding='utf-8') as f:
        return json.load(f)

def save(tid, title, translator, intro, trans):
    obj = {
        'sutra_id': tid,
        'sutra_title': title,
        'translator': translator,
        'sutra_intro': intro,
        'mode': 'sectional',
        'translations': trans
    }
    with open(f'{OUT_DIR}/{tid}.json', 'w', encoding='utf-8') as f:
        json.dump(obj, f, ensure_ascii=False, indent=2)
    # 立即校验
    s = load(tid)
    full = ''.join([c.get('text','') for c in s.get('content',[])]).replace('\n','').replace(' ','').replace('\u3000','')
    pre = ''.join([t['original_preview'] for t in trans]).replace('\n','').replace(' ','').replace('\u3000','')
    if pre not in full:
        # 找第一处不匹配字符
        i=0
        while i<len(pre) and i<len(full) and pre[i]==full[i]: i+=1
        print(f'⚠️ {tid} 子串未命中，断点 {i} 处 pre:{repr(pre[max(0,i-5):i+5])}')
    cov = len(pre)/len(full)*100
    print(f'✅ {tid} {len(trans)}段  覆盖{cov:.1f}%')

def mk(preview, section, modern):
    return {'original_preview': preview, 'section': section, 'modern': modern}

