def load(sid):
    return json.load(open(f"data/modern-translation/{sid}.json", encoding="utf-8"))

def save(sid, d):
    with open(f"data/modern-translation/{sid}.json", "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=2)

def rep(d, old, new, where):
    """在对象中做整串替换，断言最多命中 1 次（0 次视为已应用，幂等）。"""
    s = json.dumps(d, ensure_ascii=False)
    c = s.count(old)
    if c == 0:
        return d  # 已应用
    assert c == 1, f"[{where}] 命中 {c} 次（应为1）: {old[:40]}"
    s = s.replace(old, new)
    return json.loads(s)

def set_translator(d, new, where):
    """直接改 translator 字段（避免误伤 original_preview 中的繁体原文）。"""
    d["translator"] = new
    return d

