# 各种开场句式
PATTERNS = [
    # 1. 一時，佛/婆伽婆 在/住/遊/止/處/到/至  地点
    re.compile(r'一時[，、]?\s*(?:'+BUDDHA_TERMS+r')\s*[，、]?\s*(?:與[^。；]{0,100}?(?:俱|圍遶|圍繞|大眾)[，、]?)?(?:住|在|遊|遊於|遊化|處|至|到|在於|於|至於|止|坐|詣|到於|行|行詣|從)\s*[，、]?([^，。；：、]{1,80}?)(?:，|。|；|與|，與|法|坐|為|而|時|爾時|是時|彼|，與|入|，入)', re.U),
    # 2. 爾時，世尊/佛 在/住 地点
    re.compile(r'爾時[，、]?\s*(?:'+BUDDHA_TERMS+r')\s*[，、]?\s*(?:住|在|遊|處|至|到|於|止|坐)\s*[，、]?([^，。；：、]{1,80}?)(?:，|。|；|之內|之上|敷座)', re.U),
    # 3. (如是我聞/聞如是：) 佛在X / 佛遊於X  （无"一時"）
    re.compile(r'(?:^|\n)\s*(?:'+BUDDHA_TERMS+r')\s*(?:在|住|遊|遊於|處|至|到|於|止|坐|詣|行|至|出到)\s*([^，。；：、]{1,80}?)(?:，|。|；|時|告|與|，與|為|法|，時)', re.U),
    # 4. 一時，众祐/尊者 X 在 地点
    re.compile(r'一時[，、]?\s*(?:尊者|淨命|長老|眾祐)[^，。；：]{1,20}(?:在|住|遊|止)\s*([^，。；：、]{1,80}?)(?:，|。|；)', re.U),
]

CONG_RE = re.compile(r'與([^。；]{1,180}?)(俱|俱會|俱坐|俱集|圍遶|圍繞而為說法|圍繞|而為說法|前後圍遶|恭敬圍遶|恭敬圍繞)', re.U)

def get_intro_text(content):
    if not content: return ''
    full = []
    for ch in content:
        t = ch.get('text','')
        if t: full.append(t)
    joined = '\n'.join(full)
    markers = ['如是我聞','聞如是','我聞如是']
    pos = -1
    for m in markers:
        p = joined.find(m)
        if p >= 0 and (pos < 0 or p < pos):
            pos = p
    if pos >= 0:
        return joined[pos:pos+1500]
    # 无"如是我闻"
    for ch in content[:8]:
        t = ch.get('text','').strip()
        for l in t.split('\n'):
            l=l.strip()
            if not l: continue
            head = l[:20]
            # 跳过御制序/译者序/跋
            if any(k in head for k in ['御製','聖教序','聖製','製序','述序','序贊']):
                continue
            # 跳过译者署名行
            if '譯' in head and len(head)<25 and any(k in head for k in ['三藏','沙門','法師','詔譯','奉詔']):
                continue
            # 跳过目录行
            if l.count('　')>3 or (l.count(' ') > 5 and '第一' in l[:30]):
                continue
            return l
    return content[0].get('text','')[:800] if content else ''

def normalize_place(raw):
    if not raw: return ''
    raw = raw.strip().strip('，。、；：）】)')
    # 去掉开头动词
    raw = re.sub(r'^(在|住|遊|遊於|遊化|處|至|到|於|止|坐|詣|行|行詣|從|到於|出到|為|與)', '', raw)
    raw = raw.strip()
    for k,v in PLACE_NORMALIZE:
        if k in raw:
            return v
    return raw if len(raw)<30 else raw[:30]

def parse_place(snippet):
    for pat in PATTERNS:
        m = pat.search(snippet)
        if m:
            return normalize_place(m.group(1))
    return ''

def parse_cong(snippet):
    m = CONG_RE.search(snippet)
    if m:
        return m.group(1).strip()
    return ''

def main():
    idx = json.load(open(INDEX))
    items = idx if isinstance(idx, list) else idx.get('items',[])
    results = {}
    no_intro = []
    for it in items:
        sid = it['id']; title = it.get('title','')
        fp = os.path.join(SUTRAS_DIR, f'{sid}.json')
        if not os.path.exists(fp): continue
        sj = json.load(open(fp))
        content = sj.get('content',[])
        intro = get_intro_text(content)
        if len(intro) < 10:
            no_intro.append((sid,title)); continue
        place = parse_place(intro)
        cong = parse_cong(intro)
        results[sid] = {
            'id': sid,
            'title': title,
            'translator': it.get('translator',''),
            'category': it.get('category',''),
            'place_norm': place,
            'audience_raw': cong,
            'intro_excerpt': intro[:800].replace('\n',' / '),
        }
    by_place = defaultdict(list)
    for sid,v in results.items():
        p = v['place_norm'] or '(不明地点)'
        by_place[p].append((sid,v['title']))
    print(f'有开场段：{len(results)} 部；无开场段：{len(no_intro)} 部')
    print(f'不同说法地点（归一后）：{len(by_place)} 处')
    known = sum(len(v) for k,v in by_place.items() if not k.startswith('('))
    print(f'已识别地点：{known} 部  不明：{len(by_place.get("(不明地点)",[]))} 部')
    print()
    for p,lst in sorted(by_place.items(), key=lambda x:-len(x[1])):
        if p.startswith('('): continue
        print(f'【{p}】 {len(lst)} 部')
    json.dump(results, open('ontology/dharma_assemblies_raw.json','w',encoding='utf-8'),
              ensure_ascii=False, indent=2)

if __name__ == '__main__':
    main()
