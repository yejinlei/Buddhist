import json, os, sys
TARGETS = ['t1480','t1393','t1372','t1360','t0797a','t0751b']
SUTRA_DIR = 'sutras'
OUT_DIR = 'data/modern-translation'

def load_sutra(tid):
    with open(f'{SUTRA_DIR}/{tid}.json', encoding='utf-8') as f:
        d = json.load(f)
    if isinstance(d, dict):
        c = d['content']
        text = ''.join(x.get('text','') if isinstance(x,dict) else str(x) for x in c) if isinstance(c, list) else c
        return d, text
    return None, ''

def validate(data, orig_text):
    """机械闸门：preview必须是原文连续子串，拼接覆盖>=80%，全角引号"""
    joined = ''.join(s['original_preview'] for s in data['translations'])
    miss = 0
    for ch in joined:
        if ch not in orig_text and ch not in ' \n\r\t':
            miss += 1
    # 覆盖率
    if orig_text.startswith(joined[:50]) or joined[:50] in orig_text:
        pass
    # 检查每段preview在原文中的位置
    pos = 0
    ok = True
    for s in data['translations']:
        p = s['original_preview']
        i = orig_text.find(p[:30], max(0, pos-50))
        if i == -1:
            # 放宽
            i = orig_text.find(p[:20])
        if i == -1:
            ok = False
            print(f"  ❌ 段界失败: {p[:40]}")
            break
        pos = i + len(p)
    # 半角引号
    for s in data['translations']:
        if '"' in s['modern'] or "'" in s['modern']:
            ok = False
            print(f"  ❌ 半角引号: {s['modern'][:40]}")
        if '【义解】' not in s['modern']:
            ok = False
            print(f"  ❌ 缺义解: {s['section']}")
    return ok, pos / len(orig_text) if pos else 0

def write_json(tid, data):
    with open(f'{OUT_DIR}/{tid}.json','w',encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

