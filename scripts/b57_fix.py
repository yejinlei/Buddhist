def main():
    n_ok = n_bad = 0
    for tid, items in FIX.items():
        p = os.path.join(TR, tid + ".json")
        d = json.load(open(p, encoding="utf-8"))
        for seg_i, old, new in items:
            m = d["translations"][seg_i - 1]["modern"]
            cnt = m.count(old)
            if cnt != 1:
                print("!! %s 段%d 匹配%d次: %s" % (tid, seg_i, cnt, old[:30])); n_bad += 1; continue
            d["translations"][seg_i - 1]["modern"] = m.replace(old, new)
            n_ok += 1
        json.dump(d, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("替换成功 %d, 失败 %d" % (n_ok, n_bad))

if __name__ == "__main__":
    main()
