IDS = ['t0063','t0064','t0065','t0073','t0075','t0077','t0078','t0082','t0083','t0084']


def fix_head(m):
    """把「【小标题】<真实标题>」占位符规范为「【<真实标题>】」。"""
    if not m.startswith('【小标题】'):
        return m, False
    rest = m[len('【小标题】'):]
    idx = len(rest)
    for j, ch in enumerate(rest):
        if ch in '。\n':
            idx = j
            break
    title = rest[:idx].strip()
    after = rest[idx:]
    if after.startswith('。'):
        after = after[1:]
    if not title:
        return m, False
    return f'【{title}】{after}', True


def main():
    h2s = json.load(open(os.path.join(BASE, 'data', 'hant2simp_full.json'), encoding='utf-8'))
    extra = {'婬': '淫'}
    simp = lambda s: ''.join(extra.get(h2s.get(c, c), h2s.get(c, c)) for c in s)

    data = {}
    for i in IDS:
        p = os.path.join(MT, i + '.json')
        data[i] = json.load(open(p, encoding='utf-8'))
    segmap = {i: {s['id']: s for s in data[i]['translations']} for i in data}

    applied = skipped = 0
    for i, sid, old, new in FIX:
        s = segmap[i].get(sid)
        if s is None:
            skipped += 1
            continue
        if new in s['modern'] and old not in s['modern']:
            skipped += 1          # 已改过，幂等
            continue
        assert s['modern'].count(old) == 1, f'{i}/{sid} 命中数异常'
        s['modern'] = s['modern'].replace(old, new)
        applied += 1

    h_head = 0
    for i in data:
        for s in data[i]['translations']:
            m2, ch = fix_head(s['modern'])
            if ch:
                s['modern'] = m2
                h_head += 1

    for i in data:
        for s in data[i]['translations']:
            s['modern'] = re.sub(r'(?<!\n)【义解】', '\n【义解】', s['modern'])
        data[i]['title'] = simp(data[i]['title'])
        json.dump(data[i], open(os.path.join(MT, i + '.json'), 'w', encoding='utf-8'),
                  ensure_ascii=False, indent=2)

    print(f'替换应用 {applied}，跳过 {skipped}，占位标题规范 {h_head}，标题转简体 {len(data)} 部')


if __name__ == '__main__':
    main()
