def main():
    byt = {}
    for tid, old, new in FIXES:
        byt.setdefault(tid, []).append((old, new))
    total = 0
    for tid, items in byt.items():
        p = os.path.join(TR, tid + ".json")
        d = json.load(open(p, encoding="utf-8"))
        for old, new in items:
            hit = 0
            for s in d["translations"]:
                if old in s["modern"]:
                    s["modern"] = s["modern"].replace(old, new)
                    hit += 1
            if hit != 1:
                print("!! %s 命中%d次: %s" % (tid, hit, old[:40]))
            else:
                total += 1
        json.dump(d, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("完成替换 %d 条（预期 %d）" % (total, len(FIXES)))

if __name__ == "__main__":
    main()
