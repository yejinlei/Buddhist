def main():
    os.makedirs(OUT, exist_ok=True)
    for tid, builder in [("t0132a", build_132a), ("t0150b", build_150b)]:
        data = builder()
        path = os.path.join(OUT, f"{tid}.json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"Wrote {path}")

        # Validation
        with open(path, "r", encoding="utf-8") as f:
            loaded = json.load(f)
        assert loaded["id"] == tid
        print(f"  sections: {len(loaded['translations'])}, intro length: {len(loaded['intro'])}")

        # Validate previews are substrings of original
        src_path = os.path.join(BASE, "sutras", f"{tid}.json")
        with open(src_path, "r", encoding="utf-8") as f:
            src = json.load(f)
        orig = src["content"][0]["text"]
        # Remove translator line (first line before 聞如是 or 佛在)
        lines = orig.split("\n")
        # find start
        start_idx = 0
        for i, ln in enumerate(lines):
            if ln.startswith("聞如是") or ln.startswith("佛在"):
                start_idx = i
                break
        body = "\n".join(lines[start_idx:])
        for s in loaded["translations"]:
            pv = s["original_preview"]
            # Preview may span paragraphs joined by \n in body? In the samples, preview was
            # a continuous substring without newlines. But for section with two paragraphs
            # (like 施安段 with two paragraphs joined by \n), need to check.
            # Actually in sample t0107 the preview was a single paragraph substring.
            # Let me check if pv is in body (with possible missing leading quote chars).
            # First try direct match.
            if pv not in body:
                # try replace \n in body with nothing? No, keep \n in preview too for multi-paragraphs.
                # Some previews include \n between paragraphs. Let's handle.
                print(f"  WARNING: preview not found directly, checking with newlines...")
                # remove leading 「 for matching test
                if pv.replace("\n", "") in body.replace("\n", ""):
                    print(f"    matched after whitespace normalization for: {s['section']}")
                else:
                    # Find context
                    idx = pv[:20]
                    print(f"    first 20: {idx!r}")
                    raise AssertionError(f"Preview not a substring for section {s['section']}")
        print(f"  All previews validated against source.")

if __name__ == "__main__":
    main()
