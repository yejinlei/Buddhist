def build(tid, intro, moderns):
    src = json.load(open(os.path.join(TASK, tid + ".json"), encoding="utf-8"))
    segs = src["translations"]
    assert len(segs) == len(moderns), f"{tid}: seg count {len(segs)} != {len(moderns)}"
    for s, m in zip(segs, moderns):
        assert m[0] == "【", f"{tid}: modern not start with 【"
        assert "【义解】" in m, f"{tid}: missing 【义解】"
        assert not m.rstrip().endswith("【义解】"), f"{tid}: ends with 【义解】"
        assert '"' not in m, f"{tid}: contains ascii quote"
        s["modern"] = m
    src["intro"] = intro
    out = os.path.join(OUT, tid + ".json")
    json.dump(src, open(out, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"{tid} 写入完成 段=N={len(segs)}")


for tid, (intro, moderns) in DATA.items():
    build(tid, intro, moderns)
