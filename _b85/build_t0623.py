"【请问出家证道·佛许之】唯愿圣师以无量慧照、开释未闻。」佛答道：「善哉！随你所问。如今当为你具敷大要。」眼见光贤菩萨说：「什么叫正士出家具足道证、至于萨云若（一切智）？」于是圣师告诉说：【义解】「正士」此处谓菩萨（修道者）。请问出家证得一切智之道。",

"【诸佛出家之要·降魔成道】「正士！善听，注意。诸佛出家要有起发的因缘，端坐思惟闲静、玄静通微。专心精念于道，分有所感，应感者即净居天子、梵王、自在天，便敕令帝释化现四非常（老病死）之像，因此佛说证、离欲苦难，念道清净，当处于山泽研精行禅。此意方兴，四王已下给侍所当前往贝多树，忆念先佛出家之法，以法为师、以天梵为证，信根内固，宿习六度、三十七品，具足佛事，忽然自悟，帝释便下来把剃刀授予佛手中。【义解】此段述佛出家成道的因缘：净居天子劝发、帝释化四非常之像、贝多树下成道、帝释授剃刀。",

"【剃发自誓·发刀自堕】于是菩萨左手执发、右手持刀，心中自己想：「刈除习苦之垢，植无著之根，断不退流，通泥洹（涅槃）之源。」发意已来常得去家，坚固之志心无懈倦、深不退转，信证具足、意思分明。刀还未近发，头发忽然自堕，肉髻自然而现。补处菩萨心念：【义解】「肉髻」为佛顶肉髻相。「补处菩萨」谓即将成佛（补佛处）之菩萨，即此处的释迦。",

"【净居天子授袈裟·诸佛合成一衣】「先佛出家剃发，应有袈裟法服约束此心。」正兴起此念，净居天子即授以净素天缯自然袈裟。菩萨接受后，披之于体，法服齐正。于是恒沙无量世界诸佛尽通相见，各送袈裟授与菩萨。菩萨即接受，彼此诸佛普现威神，令诸佛所送的袈裟合成一服，名叫「萨披佛头震越」。【义解】「震越」为袈裟之音译。诸佛袈裟合成一衣，象征诸佛法身平等。",

"【六年成道·戒证之相】此衣如今在梵天。之所以端坐六年以了毕宿缘，六年后夜戒证方才显现。什么叫戒证？志在闲寂山泽受法，神真操远、持戒行道，不惜寿命、捐弃身体，齐等万物、不求利养，守空行寂、常观净法，慈悲喜护（舍）四等四恩，具无盖哀、明释四禅，无瑕无秽、无黠（无慧）之念，不随他人的法，于佛法中得泥洹道。【义解】「四等」即慈悲喜舍（四无量心）；「四恩」为父母、众生、国王、三宝之恩。此段释「戒证」之义。",

"【真戒沙门·禁戒无形】这就是真戒沙门。」佛告诉说：「正士！禁戒无形，不著三界，无识、无吾、无我、无人、无命、无意、无名、无种、无化、无数、无作，无所从来、无所从去，无形无灭、无身无犯、无口无言、无心无念、无世事、无计、无事、无所住，也无有戒、无有惑，无所念、无败坏，这名叫禁戒。【义解】此段以般若空义释戒体，谓真戒无形、超乎三界与名相。",

