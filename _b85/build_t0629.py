"【题署·法会与菩萨行苦】安公（道安）说原本缺佚译者，如今附于西晋录。佛在舍卫祇洹精舍，那时与诸菩萨、无央数比丘、比丘尼、优婆塞、优婆夷，诸天王、帝释、梵天，以及阿须伦、鬼、神、龙、诸人非人，无央数众都集会而坐。佛说菩萨之法：无央劫的勤苦，地狱、禽兽、薜荔（饿鬼），一切忧劳，于十方布施金银珍宝、车马奴婢，以及妻子、头目、肌肉，都不爱惜，用来施与十方人，因为勤苦行道的缘故。【义解】本经述文殊师利探取释迦佛置于下方的钵，以此显示菩萨威神与忍辱之德。「祇洹精舍」即祇树给孤独园。「薜荔」即饿鬼。开篇赞菩萨行六度、舍身布施之勤苦。",

