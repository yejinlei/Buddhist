"【手至彼刹·彼佛说释迦文】如文殊的手，直至赖毘罗耶佛刹，刹中诸菩萨白彼佛说：「这手是什么，既不见其边，也不见其际。」赖毘罗耶佛告诉诸菩萨说：「上方无数佛刹，刹名沙诃楼陀，佛字释迦文，前面有坐着的菩萨字文殊，最尊光明、智慧难以抵挡，作变化如此。【义解】「沙诃楼陀」即娑婆世界（译为堪忍）。彼佛为诸菩萨说明此手及释迦、文殊。",

"【彼佛放光照释迦刹·菩萨问是何火】诸菩萨白佛说：「如今我们想一同得见释迦文佛及文殊。」赖毘罗耶佛即放额上千亿光明，照中央无数佛刹，一直照到释迦刹。诸菩萨问佛：「如今有这样的大火光烟出，须臾间便出火，这是地狱的泥犁之火吗？」佛说：「不要这样说，这不是泥犁之火，释迦刹名沙诃楼陀，是那里的火。【义解】「沙诃楼陀」（堪忍）之「火」喻三毒烦恼之火，非地狱之火。此段以问答引出下文。",

"【刹名堪忍之因·忍辱之问】诸菩萨问佛说：「这沙诃楼陀刹，因何名为沙诃楼陀、有这火？」佛告诉诸菩萨：「沙诃楼陀刹，是杂恶三毒：淫妷、瞋怒、愚痴充满。」诸菩萨白佛说：「沙诃楼陀刹中的诸菩萨，能忍辱不瞋怒的，这样做可以吗？」佛告诉诸菩萨：【义解】娑婆世界充满贪瞋痴三毒，故名「堪忍」；于中能忍辱者尤为难能。",

"【彼佛赞释迦刹菩萨忍辱】「释迦刹中的人，骂詈菩萨、轻易杖捶的，菩萨忍辱终不加瞋怒，慈哀十方人、想令其度脱，这都是菩萨威神所加，菩萨忍辱之恩，所以名为沙诃楼陀（堪忍）。」诸菩萨白佛说：「我们听了大为欢喜，（庆幸）得以不生到释迦刹弊恶人之处。」【义解】娑婆菩萨以忍辱慈哀度脱众生，故名「堪忍」。此段明释迦刹修行之难能可贵。",

"【戒勿轻慢·东方佛刹菩萨不如娑婆一昼夜行】赖毘罗耶佛告诉诸菩萨：「不要说这话，不合沙诃楼陀刹中诸菩萨之意。」佛说：「我为你们说，东方有佛字头意，刹名诃波离摩坻陀惹，头意佛刹中的菩萨，行六度都悉具足，却不如沙诃楼陀刹中菩萨行六度的一日一夜，念十方勤苦、欲皆使度脱。【义解】此段以东方佛刹菩萨之具足六度，反衬娑婆菩萨一昼夜修行之殊胜。",

"【火烧不伤之难喻·娑婆忍辱】为什么呢？沙诃楼陀刹中作行勤苦，譬如一佛刹败坏时火烧其刹，有人著新衣从东方来入火中，从火中到西方，其身出来而不被烧，这难不难？」诸菩萨说：「甚难。天中天！」佛说：「沙诃楼陀刹中菩萨，一日一夜所行，即使有人骂詈、轻慢之，菩萨忍辱终不瞋怒。【义解】「天中天」为佛的尊号。以著新衣行火中不烧之难，喻娑婆菩萨忍辱之难。",

"【火中不烧不及菩萨万亿分之一·欲往须先治意】譬如这人行于火中身不被烧之难，尚且不及这菩萨忍辱之难的百倍千倍万倍亿倍。」诸菩萨等二万人上前白佛：「愿想上至沙诃楼陀刹，供养释迦文佛及文殊师利菩萨等。」赖毘罗耶佛告诉诸菩萨：「若想到沙诃楼陀刹的，先调治你们的心意。【义解】众菩萨发愿往娑婆供养释迦与文殊，彼佛嘱其先调心。",

"【地受净秽不喜不瞋之喻·释迦刹菩萨急性之因】譬如大地得到香花好物不喜，得到屎尿涕唾脓血恶露也不瞋。」佛说：「我为什么为你们说这话？释迦文佛刹中有菩萨，前世大多供养诸佛的，人有急性的，心意善之事只是口头教人急行，因今世恶世的缘故。」【义解】以大地受净秽不喜不瞋，喻娑婆菩萨之安忍。并释娑婆菩萨有急性者之由。",

"【问何缘生恶世·二因缘】诸菩萨白佛说：「沙诃楼陀刹诸菩萨，前世多供养诸佛、求道甚久，为什么缘而生于沙诃楼陀弊恶人之处？」佛告诉诸菩萨：「有两种因缘，今世生于沙诃楼陀刹：本前世与释迦文佛一同行、求佛道，所以世世相随。又有菩萨，宿命有恶未尽，所以生彼恶世。」【义解】此为娑婆菩萨生恶世的二因缘：随释迦佛行、宿恶未尽。",

"【问如何除宿恶·贫病忧苦除殃】诸菩萨白佛：「如今这些菩萨生沙诃楼陀刹，以什么因缘能除去宿命之恶？」佛说：「善男子、善女人生沙诃楼陀刹，求菩萨道，生于贫家舍，以此缘故除宿命之恶。又多病的又除宿命之恶。又遭遇父母、兄弟、妻子病瘦死亡、忧愁感伤，以此缘故又除宿命的殃。又遭逢县官、恐怖、弃捐父母家室财产、亡逃忧愁，以此缘故又除宿命的殃恶。【义解】此段起列举娑婆世界种种苦难能消除宿恶，即「以苦为道」之义。",

"【续：失财、恶国、弊恶人中】若有一旦失去财业、穷厄，以此缘故又除宿命的殃恶。若在恶国中生，本来被他国所攻、败坏，奔走愁忧无聊，以此缘故又除宿命的殃恶。若生于弊恶人中，贫贱、面目丑陋，身患残疾、盲聋，与人不能相属（无所归属），父母、兄弟、妻子、宗亲都憎厌他，此人愁忧，以此缘故又除宿命的殃恶。【义解】续列失财、恶国战乱、贫贱丑陋残疾等苦，皆能除宿恶。「形癃」谓身体残疾。",

"【求师不得之愁除殃】若听闻有善道便欢喜，想求明师教告经道、开心从受，得不到明师便愁忧，以此缘故又除宿命的殃恶。若又遥遥听闻远方有师高明、智慧通达，想前往从受经学，身体病瘦、手足拘挛不可动摇，钱用乏少又无伴侣，便不能行，想之愁忧，以此缘故又除宿命的殃恶。【义解】续列求师不遇、身病无资等苦，皆除宿恶。",

"【师明徒愚·弃师悔忧除殃】若有人行求善师，想从学受经，师虽大明达、都知道要，弟子愚痴无慧、意不开解，便自己愁忧，以此缘故又除宿命的殃恶。若有善师想教弟子世间之事、开语经道，弟子愚痴不能忍辱，便弃捐师而去，后来归念师之法戒、大欢喜，心中悔恨愁忧，以此缘故又除宿命的殃恶。【义解】续列师明徒愚、弃师悔忧等情形，皆除宿恶。",

"【梦恐怖、师教悔过除殃不入地狱】若有求菩萨道者，睡卧梦见怨家持刀兵追逐恐怖，梦中恐惧，又除宿命之恶。若有菩萨道中的善男子、善女人，宿命殃恶未尽，死后当入泥犁中勤苦一劫，得到善师教其悔过一日一夜的，头痛身热诸病都悉除尽，不再入泥犁中。【义解】此段明忏悔除业之力：受善师教、悔过一日一夜，可灭一劫地狱之报。",

