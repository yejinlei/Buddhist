'」帝释天主问佛说：「怎样是菩萨行智慧？」佛回答：「微尘数的蕴、界，并没有这些蕴界的菩萨，菩萨久行应当可以了知，这是于俱胝佛所作胜缘。新学的人听闻这个就生起邪疑，或者不乐求而不学；又像有人行走在深险恶道，忽然看见边界的牧牛人。',
'如同获得安隐、得到无怖，心超出于罗汉、缘觉之地，譬如有人前往观看大海，先看见大山、大树林，见到这些所爱的祥瑞之境，就知道必定能到达大海、离得不远。菩萨如果发起最上之心，听闻这部般若波罗蜜，虽然在佛前还没有授记，这证得菩提也并非遥远。如同看见春天生长的诸草木，就知道将有花果而非遥远；如果有人手中得到这部般若，证得菩提也并非遥远，也如同女人怀有身孕，十月满足必定诞生。',
'菩萨如果听闻宝德藏，就是速成正觉的祥瑞；如果行般若波罗蜜，见色非增、非减，见法、非法如同法界，不求寂静就是般若。行者如果不思惟佛法，不思惟力足及寂静，离思、非思、无相而行，这是最上般若行。」佛告诉善现（须菩提）：「你仔细听！',
'凡夫、声闻、缘觉之地，这就是如来地，一切如一无二，他对此没有疑惑。所有的称赞都离于言说，从那位遍照如来的时候，乃至成就所作的智，住持于大金刚佛地，观察无相、安住虚空，应当知道这是不断佛种的缘故。」善现禀白佛说：「世尊！怎样是菩萨的魔事？',
'」佛说：「菩萨的魔事很多，我如今为你略作宣说。有无数魔种种变化，在书写最上般若之时，迅速离开天宫如同闪电之灭，来到世间作魔事。或者示现乐于欲说，或者不听受反而瞋恨，不说名姓及氏族，这样的魔事都应当了知。愚痴、无智、无方便，没有根哪来枝叶等？听闻般若之后却另求别的经，如同舍弃整头大象反而去求象足。',
'如同有人先得到百味之食，或者得到稻饭作为上味；菩萨先得到般若之后，却舍弃了它、乐求罗汉果。或者为了乐求利养，心著族姓、留下种迹，舍弃那正法而行非法，这是魔引诱他入于邪道。如果有人听闻这最上之法，应当对法师深深信重，法师知道是魔就不应执著，无论身体适悦还是不适悦。',
'又有无数种种魔，扰乱无数比丘众，想要求持诵这部般若，却不能获得这无价之宝。佛母般若实在难得，初心的菩萨若想乐求，如果有十方佛来摄受，一切恶魔就不能为害。（本段末另重出一行译场衔名，为经本所录的译者署名。）「如同母亲爱子、儿子患病，就会令父母心中忧恼；十方诸佛从般若生，般若的摄受也是这样。',
'过去、现在、未来三世佛，遍于十方界也是这样，都从佛母般若而生，众生的心行没有不被摄受的。这样世间的诸佛如来，乃至缘觉以及罗汉，以及般若波罗蜜，都是一味之法、离于分别。过去、现在的大智诸菩萨，各各住在这法空之行，那些菩萨如实而行，所以如来名为作佛。',
'般若的园林花、果繁盛，佛依止于此，十分适悦，十力诸根等清净的大众，乃至声闻众围绕。般若波罗蜜的高山，十力的诸佛依止于此，三涂众生都得到救度，度化之后而不起众生相。狮子依山而大吼，诸兽听了都恐惧；人中的狮子依般若而吼，外道、邪魔都惊慌恐怖。',
'如同太阳千光住在虚空，普照大地、诸相显现，法王住在般若也是这样，宣说度越爱河的妙法。色无相，受也无相，乃至想、行也是这样，识也是这样，五法相同，这法无相，是佛佛所说。于虚空中起众生相之见，虚空无相、不可得，佛说法、法不相应对，不说非有、非无之相。',
'「如果这样见一切法，一切我见都舍离，佛所行之法和声闻等，都从般若而成就。如同国王不行于国邑，而所有的王务自然办成；菩萨离相、依于般若，自然获得佛的功德之法。「如果菩萨发起坚固之心，修行最上般若行，超过声闻、缘觉之地，就能速证佛菩提。',
'如同有人想要渡越大海，所乘的船舫忽然破坏，若不依靠草木则性命不全，若能有所依附就能到达彼岸。如果有人不发坚固信心，依于般若而求解脱，就会沉溺轮回大海、没有出期，处在生老病死之中常受苦恼。如果有人有信心持般若，解悟有、无之性、得见真如，这人获得福智之财，速证最上佛菩提。',
'如同有人用坏器担水，知道它不坚牢、很快就会破坏；若用坚牢之器盛水，就不会破坏、没有忧怖。若不见具足信心的诸菩萨，远离般若之行而求退堕；能发起信心持般若，就证大菩提、超出二地。从来没有商人想入海，却不造坚固的大船舫；依着坚固的船就没有怖畏，获得许多珍宝而到达彼岸。',
'信心的菩萨也是这样，远离般若之行就远离菩提；如果修最上大智之行，当得无上菩提之果。如同百岁的老人又患病，这人不能自己行走站立，若得到左右扶持的人，就能随意行往、无所怖畏。菩萨若般若之力微劣，前往菩提之岸就不能到达；兼行最上的方便之行，就得佛菩提、没有罣碍。',
'「所有菩萨住于初地，发起信心行般若行，为了求无上菩提，亲近善友以及智者。大智的功德怎样获得？应当从般若波罗蜜。像这样一切诸佛之法，功德都从善友而得。修行六度、般若之行，一一回施于菩提，佛蕴非有、不可求，不要为初地的人这样说。',
'菩萨修行功德之海，救度世间无从度脱的人，求菩提之意远离颠倒，宣说最上之法如同电光。发起最上菩提心，不求名称、不生瞋恚，远离蕴、识、界及三乘，不退、不动、不可取。对于这样的法得到无碍，通达甚深之理、远离妄想，听闻般若生信以及教化他人，要知道这样的菩萨是住于不退。',
'那甚深之法连佛也难知，没有人能得、也不可得，为了利益众生而证菩提，这不是初心众生所能了知。众生愚痴又盲冥，乐于住在世间求取境界；法无所住、无取、无得，从无所住而生世间。「东方的虚空界无边，南方、西方、北方也是这样，乃至上下及四维，都无种种相、无分别。',
'过去、未来及现在，一切佛法及声闻，一切都如实不可得，因为不可得所以无分别。菩萨乐求这样的法，应当行方便般若行，远离种种相就是菩提，菩萨离此就无法证得。如同鸟能飞百由旬，若折了翅翼，连半由旬也飞不了；忉利天及阎浮提的人，因忘失般若而自己坠落。',
'虽然修行前五波罗蜜，经过许多俱胝那由他劫，又以广大之愿资助摄持，若远离方便，就堕于声闻之位。乐行佛智、其心平等，犹如父母看待一切，应当行利益及慈悲，常宣说善软妙好之言教。」这时，须菩提瞻仰问佛：「不退的菩萨有什么殊胜？离言、离声之相怎样宣说？',
'愿佛宣说那功德之藏。」「不住于沙门、婆罗门，以及行十善、离三涂，大智远离种种相，如同山谷的回响相应。如果想要法无碍、行化，一向善说种种言教，行、住、坐、卧四种威仪，一念观心全都通达。三业清净如同白衣（在家人），不为利养而乐法，降伏魔的境界以及教化他人，观四禅定而不安住。',
'不求名誉、没有瞋恚，乃至在家也不沾染尘垢，或者为了富贵以及脱离死命，也不沾染纤毫的欲尘。本来寂静、无所有，男女互相为业所缘；如果求清净、不退转之时，应当行最上般若行。求正遍知、其心柔顺，不求二地、远离边地，为法舍命如同须弥山，这叫做不退的菩萨。',
'「色、受、想、行、识甚深，本来寂静而无相，如同大海之深、用杖也测不到底，得般若之蕴也是这样。菩萨了知这甚深之法，安住真如之乘、不可染污，六尘、十二界其体本空，没有蕴，哪还有所得之福？如同有人思惟那染欲之境，心著女色如同眼所见，乃至日日心所行之处，菩萨的思觉也是这样。',
'如果于许多俱胝劫布施，与罗汉、缘觉持戒的人相比，都不如宣说、行持般若之法，百千万分也不及一分。如果菩萨观察般若之理，安住说法而无相，回施一切、证得菩提，那位三界之师就没有人能相等。所说成就而无相，非空、非实、不可得，如果这样行就叫觉智，得受成就之义、没有边际。',
'在一念之中了知一切法，信佛所说以及他人所说，演说俱胝那由他劫，法界不增也不减。这叫做佛波罗蜜，菩萨在其中说法，如同称名布施而心不执著，也不说自己证得无上觉。「譬如灯光从众缘而生，假借膏、油、芯、火等，光不是芯、火以及膏油，没有火、没有芯，光也不存在。',
'或者有菩萨初发心，不求无上菩提之果，岂只是不得证菩提，也得不到寂静之故。从种子生出树以及花果，没有种子则花果全无；发心不为佛菩提，修行终究远离菩提之果。从种子生出麦谷等，那果非有也非无；佛菩提果也如同幻化，远离那有性与无性。',
'譬如涓滴之水虽细微，渐次必定能盈满大器；初心为求无上之果，久修白法终究能证。行空、无相、无愿之行，不求寂静、无有行相，也如同船师善于济渡，不著两岸、也不住中流。菩萨修行无所执著，才得以受佛菩提之记；如果了知菩提并非所有，这就是行佛般若。',
'譬如在疾疫、饥馑的道路上，菩萨行于其中而没有怖畏，后人知道之后都来往来，得以没有苦恼，如同微尘。「菩萨奉行佛般若，了知本来蕴不生，佛法、众生界都空，以空三昧生起悲智。如同有人有德、力最胜，善解一切幻化之法，乃至器仗及工巧，而能一向为世间所用。',
'那人的父母、妻子以及儿女，游行远路、多有冤家，这人勇猛为众人所知，安乐还家、没有怖畏。大智菩萨为了众生，安住第一三摩地，降伏四魔、远离二乘，也不求佛菩提。譬如虚空无所有，风、水、大地都依它而住，世间众生得到快乐，而虚空无意于住与不住。',
'菩萨住空也是这样，示现世间种种之相，凭借众生的智慧以及愿力，并非那寂静、并非空之故。如果菩萨行大智之时，住于空寂静三摩地，此中不见一切相，也见不到那非相。菩萨行此解脱门，不是求寂静、不是行相，如同鸟飞虚空而往来，不住虚空、也不住地。',
'也如同有人学习射法，学了很久而不停止、经过许多年，射法久学就得到尽妙，一一箭发没有不中的。最上般若行也是这样，修习智慧及方便，直到众善都圆满，才获得最上神通力。如果比丘证得神通力，示现神变、住于虚空，行、住、坐、卧四种威仪，经过俱胝劫也不退倦。',
'住空的菩萨也是这样，修无相之行到达彼岸，行种种行、示现世间，经过俱胝劫也不退倦。如同有人经过险处遇到大风，两手举盖、心专注，这人怖畏险难而不能前行，直到没有风才前进。大智菩萨住于大悲，以智慧、方便为两只手，执持空、无相、无愿的法盖，见法而不安住于寂静。',
'如同有人求宝前往宝洲，获得珍宝、安隐还家，这人心满足而快乐，哪有眷属心中苦恼？前往空的宝洲也是这样，获得根、力、禅定之宝，菩萨不执住于欢喜之心，令诸众生远离苦恼。商人为了利益遍历各处，聚落、国城、诸里巷，虽然到达宝所也不执住，大智之人善行其道而再回来。',
'大智菩萨完全了知声闻、缘觉的解脱智，乃至佛智也不执住，何况行那有为之道？大智菩萨为了世间，住于空、无相、无愿三昧，如果得到寂静、无所执著，才可以得知无为。譬如生下的人，众人还不认识他，称他的名字，众人这才知道；菩萨如果行解脱门，对于解脱门，众人便得而知其名。',
'菩萨听闻那甚深之法，而对于诸根都能照明，住于空、无相、无愿之法，无退、无思、无授记。观三界如同梦幻，不求声闻、缘觉之地，如佛说法为世间，这叫做不退地，应当授记。了知诸众生堕入三涂，发愿于刹那灭除恶道，以真实之力灭除火蕴，这叫做不退地，应当授记。',
'诸恶的宿曜及鬼神，作种种疫病恼害世间，以真实愿力都能灭除，无我、能作的人应当授记。「我得授记不是能、所（二元），这是实愿力得到增长；如果见有授记以及能、所，这就叫执著以及少智。菩萨若有执著，魔就知道了，现出亲友之相前来扰乱，或者化作父母、七代之人，说：你名叫这佛、可以证得。',
'魔所现作无数之相，都说：『哀愍你，为你作利乐。』菩萨听了之后有所欣喜，这就叫少智、为魔所著。或者住于城隍及聚落、山林旷野寂静之处，自称己德、毁谤他人，应当知道这是少智为魔所作。虽然住于城隍聚落之中，却不求声闻、缘觉之证，此心是为了度化众生，我说这叫做菩萨。',
'五百由旬的山，险峻幽深，与诸恶兽共住多年，如果见到逼迫而生我慢，若无分别才是菩萨。菩萨住在那里为世间，得到力、解脱、三摩地，若他执著山野寂静之行，这也应当知道是那魔所作。虽然住在城隍及山野，却乐求佛菩提、远离二乘，修这样的行利益世间，一念如秤（衡量）便叫做菩萨。',
'「有大智的人依师而学，速疾得证无上正觉，也如同良医除众患，从善友学、心中无疑。菩萨行佛菩提之行，依那善友波罗蜜，这最上地能调伏，为了二种事而证菩提。过去、未来、十方佛，都行这正道、没有别的路，行佛菩提最上之行，宣说波罗蜜如同电光。',
'如同那般若空无相，了知诸法之相也是这样，了知一切法皆空，这叫做行佛般若。系著色欲及饮食，常在轮回而不休息，这是愚迷之人的颠倒之见，对于不实之法生起实有之想。譬如得到食物却怀疑有毒，以虚妄之见而不吃；愚人妄心生起我想，因我想的缘故而有生死。',
'也如同常说诸烦恼，对于诸烦恼不著其相，烦恼与清净都没有，这样的菩萨了知般若。如同阎浮提的诸众生，都发无上菩提心，于许多千俱胝劫布施、回施一切证菩提；如果又有人在一日之中奉行最上般若行，千俱胝之施也不及一分，因为行般若之功是无为之故。',
'菩萨以大悲行般若，为了度化众生故不起度生之想，恒常行乞食于国城，这样得到一切、名为大智。菩萨想要度化人、天乃至三涂极苦的众生，都使他们速到彼岸，昼夜勤行般若。如同有人想求无价之宝，必定要越过大海的种种险难，无心之间忽然获得，忧恼都除、欢喜无量。',
