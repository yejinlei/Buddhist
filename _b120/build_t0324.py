'「不要说这话，如今世尊在耆域医王的后园，为四部众讲说经道。」仁贤承佛威神，见佛在耆域后园，为四部众讲法。这时天帝释对仁贤说：「如今在作什么？」回答说：「我供佛及众。」帝释答：「不要说这话，如今如来在忉利天昼夜树下，为诸天人讲法。',
'」仁贤承佛威神，见佛在忉利天为天人说法。幻士仁贤见诸树上，枝、叶、花、实都有宝座，如来相好具足，僧众围绕，坐在诸化师子座上。四天王、帝释、梵王所化的师子座上，也都见坐如来；并且王舍城诸街里巷、馆宇，都见如来遍在诸佛世尊前，也都见仁贤悔过自陈。',
'那时，仁贤眼目所见，不再见其余，只见如来，幻士喜踊、即生善心，因为欢喜的缘故得到佛意三昧，从定意起，叉手于佛前，以偈问佛说：',
'「我本自谓，广学幻术；于阎浮利，无与等者。今日观见，佛之神足；计挍譬喻，不可为比。如今我目睹，不复见余；普见诸佛，相好庄严。所以如今我，欲问法王，何处是佛？唯愿尊说。奉事何佛？为第一供。',
'施何所佛？功德最大。何处清净？受施众祐！愿为我说，平等普见。我今首过，一切所犯；以身试佛，世雄导师。其于尊人，不行恭敬；是为自弃，不得所愿。诸天已闻，及与帝释！于是众会，一切普达。',
'我今为发，菩萨之心；用一切故，今悉度脱。今我为请，一切众生；皆使饱满，甘露安隐。令睡瞑者，疾得觉悟；逮得奇特，智慧灯明。谁能化变，如是所现？闻其所言，安定柔软。其慧无碍，导行最上；',
'彼不生心，道意最尊。愿为我说，微妙道行；为奉何尊，疾逮佛道？云何如是，为具足行？一切弟子，所不能及。无行之行，德为何类？正义云何？而谛听闻。何谓所乐，礼节经行？云何而发，所生无疑？',
'云何精进，闻受无厌？何时逮得，坚固听闻？云何为之，讲说法教？何谓光耀，法皆照人？云何施道，而得慈行？云何得立，无异之心？何谓祠祀，所在充备，于众人民，为坚固慈？云何善师？当奉习效；',
'云何恶友？而当远离。云何得往，见佛世尊！已得见值，云何供养？当学何学，得为上尊？云何精学，而得智慧？云何于戒，而为清净？云何逮得，三昧定意？何所设施，成严净行？云何舍离，非法之义？',
'云何于道，而伏其意；示现降魔，欲尘系缚？云何听受，思惟经义；其心不舍，一切众生？云何教化，人物群黎；坚固奉德，无所行处？云何于人，而不舍行；善权慈心，仁爱之迹？云何神通，而得具足？',
'何谓意志，道心尊特？云何一切，得成所愿；逮得分别，总持法忍；辩才清净，行不退转；深奥之意，解义第一？云何于是，得极过度；已得道证，微妙晓了；一切皆知，是佛道行；于道坚住，而不动转？',
'唯愿说是，上妙之义；诸通之慧，明智如海。世尊愍伤，愿为我说；我思逮得，坚固奉行。」于是佛为幻士仁贤说偈道：「其能解知，一切法化；彼则能化，亿百千佛。亦能化至，亿千佛国；所至到处，度亿群生。',
'如你仁贤！以无形色；能示现色，睹无央数。彼无有起，亦无有灭；不见有来，亦无去处。如是仁贤！其佛、正士；化现佛身，及比丘僧。无所从来，不见住处；智不思议，是佛神足。譬如所幻，因缘等一；',
'现有象马，车步行人。无有坐者，亦无所至；是颠倒事，人谓为正。诸佛如是，无有色身；亦无形像，不行无处。自见身者，求索处所；寤不觉者，除去众想。佛无色貌，离于相好；不起种姓，观不可见。',
'无有音声，及以言说；无心意识，离所思念。如佛所觉，实为以来；三世悉空，想无所起。常不生想，已见本净；彼无有法，其德皆吉。佛之所生，本净无数；无有四大，亦无荫盖。彼之所住，不动无著；',
'不能晓了，智慧之眼。如我所觉，为得见佛；其人未曾，得见世尊！见无所见，为睹导师；譬如举手，探捉虚空。如你仁贤！所见诸佛；悉为一义，当平等定。我亦如是，余佛无异；一切正慧，其相平等。',
'其戒清净，三昧平等；定意智慧，解脱平等。于是慧等，度知见事；一切诸力，佛之名德。空义平等，及道行迹；一切诸法，所住无碍。一切如幻，本净解脱；无所成就，所起严净。仁贤当知，供一佛已；',
'为已奉事，十方诸佛。于此如是，法平等故；求索若干，终不可得。一切能净，人之信施；一切所施，皆大德果。一切清净，起法平等；佛无若干，亦无差特。一切皆悉，审为是佛！有颠倒行，则不见佛。',
'如今这些诸佛，所示的形像；一切皆尽，平等无处。如你仁贤！忆念所见之佛！譬如如你所造化作。比喻观察五阴，也当如是！凡是著诸盖，以及愚痴。其是无生，不实无有；于此无处，亦无所立。此不可见，亦无有色；',
'谛观这些之后，不得久住。五阴自然，于是如幻；众生诤讼，自贪身相。无相之相，所可现相；正觉佛道，远而又远。虚妄之法，起众想之处；生众因缘，如无形之树。造发众事，若干种意；断诸受想，是为本无。',
'其知因缘，及所作为；彼即了法，逮得离欲。离欲法已，即识知如；即得见道，其眼清净。」佛说此偈时，幻士仁贤得柔顺法忍；五千人未曾发心，都发无上正真道意；二百天人远尘离垢、诸法眼净。于是佛食化饭之后，想要增益仁贤信施之德，便说偈道：',
'「如是不想报，所与者得净；一切施等具，仁贤德满足。」贤者大目揵连禀白佛说：「恳请世尊！令这化讲堂得住昼夜七日，使不灭没。」佛就以威神，令化讲堂昼夜七日住立不灭，庄严如故。这时，佛从座起，与比丘及诸菩萨、天龙、鬼、揵闼婆，前往（佛所）听受经法。',
'于是仁贤前往佛所，稽首礼足、绕佛三匝，退立叉手，禀白佛说：「恳请世尊！菩萨有几道行所可住处，能得至道场、晓了正义？」于是佛告诉仁贤：「仔细听，好好思惟！我当为你解说菩萨道场。」于是仁贤与诸大众，受教而听。',
'佛说：「菩萨有四事住于道，能得至道场：一是心常习诸通慧；二是不舍一切人；三是求功德无有厌足；四是护诸法常行精进；这就是四事，能得至道场。「又有四清净行，能得至道场：一是护戒清净；二是意性清净；',
'三是慧清净；四是所生清净；这就是四。「又有四事法，是弟子、缘觉所不能及的：一是其行过于四禅；二是其心多所入；三是行大哀于众生；四是辩才之音有若干种；这就是四。「又有四威仪行：一是乐于闲居、远离众闹；',
'二是往于彼处行慈、念众生；三是无谀谄邪行、无所至到；四是求于道行；这就是四。「又有四事，所问无碍、无能断截：一是不惜身命；二是心常欢悦；三是弃贡高；四是常奉行法；这就是四。「又有四事，所行具足：',
'一是常知时节；二是随人所喜而现教；三是常知羞惭；四是知止足；这就是四。「又有四事，意行平等：一是随人所应而恭敬教授；二是所愿以大智慧所应教授；三是不说他人长短；四是见说短者慈心向之，不怀结怨；',
'这就是四。「又有四事，名德具足、莫不闻知：一是自学深慧并施教他人；二是有来问事都能遣除他的疑惑；三是常护正法；四是佛之意力而不可尽；这就是四。「又有四事，博闻坚强：一是闻法就能解其所归；二是所闻之法乐于（受持）而不贪恋居家；',
'三是闻已广宣、都为人说；四是已闻而起贤圣解说，向于佛道之法；这就是四。「又有四事，讲说经法、名德流行：一是先办众事、后受以护法之食；二是得利养（衣被、饭食、床卧、医药）、降伏魔力；三是昼夜乐法、为诸天所护；',
'四是不轻娆他人；这就是四。「又有四事，光辉众会、身得自在：一是少于所欲；二是知止足；三是微妙柔软；四是身自奉法；这就是四。「又有四事，得明慧利、说法无异：一是拔济生死之惧；二是不希求世间供养之利；',
'三是常护他人；四是常住道愿；这就是四。「又有四事法，有反复、知报善恶：一是劝化人使他发道意；二是不失所成立之功；三是自敬念、迎当来慈；四是常诣正士、法师；这就是四。「又有四事不坏慈：',
'一是具足忍力；二是不诱娆他人眷属；三是不舍大哀；四是求脱罪福因缘、志在于道；这就是四。「又有四事习于慈行：一是常合和人；二是性行柔顺；三是其行具足；四是所有稍稍近道；',
'这就是四。「又有四事，知是恶师：一是教人为小道；二是教人坏菩萨意；三是教求名闻、增益不善之法；四是教远离功德善法；这就是四。「又有四事，与世尊诸佛共会：一是常一其心；二是常说诸佛世尊功德；',
'三是奉清净之戒；四是志性不舍本愿；这就是四。「又有四事法，称其德行、供养菩萨及如来尊、不以懈倦：一是所供养佛最尊众祐；二是其有见我者亦当效行；三是见如来道意得坚固；四是得见三十二大人之相、其功德本，使成善权；',
'这就是四。「又有四事，观经义、学菩萨戒行、得至尊上：一是过度恶道；二是常劝立善道；三是恭敬如来；四是具足所愿；这就是四。「又有四事学：一是不舍道意；二是等于一切；三是求度无极；',
'四是护无数诸佛法使不断绝；这就是四。「又有四事，行清净戒：一是奉行少事；二是解了空行；三是不犯邪见狐疑；四是无犹豫心；这就是四。「又有四事，三昧种性：一是不习土地语言；二是心清净无著；',
'三是成功德本；四是稍近佛道；这就是四。「又有四事，应清白行：一是兴诸善本；二是其心宴寂、行无所著；三是所见随其脱门；四是寂定于道义；这就是四。「又有四事，弃瑕秽心：一是恐畏生死、常专其行；',
'二是欲求解脱功德之本；三是于安隐无所造立；四是心无所起；这就是四。「又有四事，降伏其心：一是以一人之故，当来亿百千数游在生死；二是知一切人心所念，为断尘劳、随其本愿而为说法；',
'三是悉弃捐诸不善法、奉行众善、坐于道场、降伏魔兵，逮得无上正真之道；四是声告三千大千世界、为其说法；这就是四。「又有四事，降伏魔怨：一是观视幻法清净之行；二是逮得不起法忍；三是截断诸无慧之事；',
'四是已离生死、奉修正行；这就是四。「又有四事，思惟经义：一是因缘法起、不为无缘；二是兴立深法而无有人；三是观视空法而无所起；四是自然无想、悉为处寂；这就是四。「又有四事，心不舍菩萨法：',
'一是不舍本愿；二是忍于苦恼；三是不惜身命；四是不舍四恩行；这就是四。「又有四事，法开化人：一是衣食布施、应为说法；二是数数劝使坚固；三是自在安隐之业；四是立他人善本；这就是四。',
'「又有四事，安谛受法而摄奉行：一是善本虽少、心不轻念；二是常奉行安隐行；三是布施、调意、修善具足；四是奉承经义、使一切归趣安隐；这就是四。「又有四事，得入道行：一是逮得神通；二是成就正慧；',
'三是在大道心中深入无量；四是一切所造但习空行、不著解脱；这就是四。「又有四事，奉修慈心：一是救护幻化之人；二是常开导人使持法；三是度脱幻者；四是使得无为；这就是四。「又有四事，奉修哀心：',
'一是为恶道之故而作亲友，使得入道而为兴哀；二是使离恶罪、教令修善；三是教求小道者、劝发大乘；四是设行哀者，为一切众生而摄此哀；这就是四。「又有四事，行善权方便：一是一切心向道、意在前；',
'二是不舍尘劳心，何况善权方便心；三是观一切人及众邪见，悉为法器；四是见一切法悉为佛法，自然得最正觉，念行诸三昧、逮得善解脱；这就是四。「又有四事，逮神通行：一是常轻其身及本净意；',
'二是轻心自然如幻；三是所作唯造立法；四是寂然一心而无愦乱；这就是四。「又有四事，得分別法句：一是念成慧义、不为严饰；二是唯求取法而不取人，不起无所灭；三是知一切无尽、不可尽；',
'四是所说于文字无著无缚；这就是四。「又有四事，逮得总持：一是不厌博闻、常敬法师；二是常行精进、为人说经；三是晓近一切法句而不失义；四是又使入如来之法；这就是四。「又有四事，逮得法忍：',
'一是度不度者；二是解未脱者；三是一切乐法；四是不断善行；这就是四。「又有四事，逮得辩才：一是见他法师所说、不求其短；二是听采法义、不以贡高；三是不自称誉；四是见少智未学、不以轻易；',
'这就是四。「又有四事，行不退转：一是不退于婬怒痴；二是于众生之行不退转；三是于一切不善法而不退转；四是解最正觉而不退转；这就是四。「又有四事，解深义：一是晓十二因缘；二是自然解得佛道、为正谛觉；',
'三是一切法一义、其义悉空；四是悉解佛道；这就是四。「又有四事，得成所愿：一是戒忍清净；二是净除恶道；三是质朴无有谀谄；四是如善权方便、随其本行；这就是四。「又有四事，得成诸度无极不退转法：',
'一是以一波罗蜜悉入诸度无极；二是善权使一切人皆入，而一切人亦无有；三是见一切法悉为一法、离诸所欲；四是见一切佛悉为一佛，以法身故；这就是四，得成诸度无极不退转法。」佛说这些四事句时，幻士仁贤得不起法忍，欢喜踊跃在虚空之中，离地四丈九尺。',
'这时，佛见幻士仁贤心所念，便微笑。贤者阿难以偈赞佛而问说：「差特无量威，慧事逾日月；三世悉闻名，德称度无极。所知了三达，佛已逮自在；今佛何故笑？唯愿为解说。一切众生类，住立若所立；已见诸人心，人尊无所著。',
'其于下中上，如是为悉净；今佛所笑者，唯愿解说之！诸天闻其声，真陀人亦然！帝释、阿须伦！乾陀、摩睺勒！梵天亦如是，其声寂清净；彼诸所有音，终不与佛等。月所出光明，及日摩尼珠，其帝释光明，一切光及梵，其明悉蔽歇，为尽不复现；',
'佛出光明时，悉照诸佛国。已解诸深法，静然为空寂；其无有吾我，亦无有寿命。不有亦不无，悉损是二事；尊皆令世吉，所游如月光。于此唯发心，立意遵妙道；今谁于佛道，安定住正法？所以得受身，归命佛宝尊；',
