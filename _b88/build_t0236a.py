"【须菩提悲泣·佛说深法门】希有，修伽陀！佛说如是甚深法门，我从昔来所得慧眼，未曾得闻如是法门。」「何以故？须菩提！佛说般若波罗蜜，即非般若波罗蜜。」「世尊！若复有人得闻是经，信心清净，则生实相，当知是名成就第一希有功德。【义解】须菩提自叹从昔所得慧眼未曾得闻如是深法；信净生实相为第一希有。",
"【信心清净生实相·第一希有】世尊！是实相者则是非相。是故如来说名实相、实相。世尊！我今得闻如是法门，信解受持，不足为难。若当来世其有众生得闻是法门信解受持，是人则为第一希有。何以故？此人无我相、人相、众生相、寿者相。【义解】实相即非相；当来世能信解受持者，无四相，为第一希有。",
"【无四相·离一切相则名诸佛】何以故？我相，即是非相；人相、众生相、寿者相，即是非相。何以故？离一切诸相，则名诸佛。」佛告须菩提：「如是，如是！若复有人得闻是经，不惊不怖不畏，当知是人甚为希有。何以故？须菩提！【义解】四相皆非相；离一切相即名诸佛。闻经不惊不怖不畏者甚为希有。",
"【不惊不怖不畏·第一波罗蜜】如来说第一波罗蜜，非第一波罗蜜。如来说第一波罗蜜者，彼无量诸佛亦说波罗蜜，是名第一波罗蜜。须菩提！如来说忍辱波罗蜜，即非忍辱波罗蜜。何以故？须菩提！如我昔为歌利王割截身体。我于尔时，无我相、无众生相、无人相、无寿者相，无相，亦非无相。【义解】第一波罗蜜即非第一波罗蜜；忍辱波罗蜜亦然。佛昔为歌利王割截身体时，离四相。",
"【忍辱波罗蜜·歌利王割截】何以故？须菩提！我于往昔节节支解时，若有我相、众生相、人相、寿者相，应生瞋恨。须菩提！又念过去于五百世，作忍辱仙人，于尔所世，无我相、无众生相、无人相、无寿者相。是故须菩提！菩萨应离一切相，发阿耨多罗三藐三菩提心。【义解】佛昔被节节支解时若无四相则不起瞋；过去五百世作忍辱仙人亦离四相。菩萨应离一切相而发心。",
