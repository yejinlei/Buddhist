"【众生相即非相·如来真语者】何以故？如来说：『一切众生，即非众生。』」「须菩提！如来是真语者、实语者、如语者、不异语者。须菩提！如来所得法，所说法，无实无妄语。须菩提！譬如有人入闇，则无所见。若菩萨心住于事而行布施，亦复如是。【义解】众生即非众生；如来是真语、实语、如语、不异语者。心住于事而行施如入闇无所见。",
"【入闇喻·有目喻】须菩提！譬如人有目，夜分已尽，日光明照，见种种色。若菩萨不住于事行于布施，亦复如是。复次，须菩提！若有善男子、善女人，能于此法门，受持读诵修行，则为如来以佛智慧，悉知是人，悉见是人，悉觉是人，皆得成就无量无边功德聚。【义解】不住事行施如有目见色；受持读诵此法门者，如来悉知悉见，成就无量功德。",
