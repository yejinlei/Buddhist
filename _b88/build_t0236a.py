"【经有不可思议功德·为发大乘者说】须菩提！以要言之，是经有不可思议不可称量无边功德。此法门，如来为发大乘者说，为发最上乘者说。若有人能受持读诵修行此经，广为他说，如来悉知是人，悉见是人，皆成就不可思议不可称无有边无量功德聚。【义解】此经有不可思议功德，为发大乘、最上乘者说；能受持读诵广说者成就无量功德。",
"【荷担如来·乐小法者不能·四见】如是人等，则为荷担如来阿耨多罗三藐三菩提。何以故？须菩提！若乐小法者，则于此经，不能受持读诵修行，为人解说。若有我见众生见人见寿者见，于此法门，能受持读诵修行为人解说者，无有是处。【义解】受持者能荷担如来菩提；乐小法者、具四见者则不能受持解说。",
"【经在处如塔·恭敬供养】须菩提！在在处处，若有此经，一切世间天、人、阿修罗所应供养。当知此处则为是塔，皆应恭敬，作礼围绕，以诸华香而散其处。复次，须菩提！若善男子、善女人，受持读诵此经，为人轻贱。何以故？【义解】此经所在之处即为塔庙，天人应供养；受持者若为人轻贱，则先世罪业消灭。",
