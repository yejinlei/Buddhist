"【心有住则为非住·无所住心行施】何以故？若心有住则为非住。故如来说：『菩萨无所住心应行布施。』复次，须菩提！菩萨应如是行施，为利益一切众生。此众生想即是非想。如是一切众生，如来说即非众生。何以故？诸佛世尊远离一切想故。【义解】心若有住即非正住；菩萨应无所住心行施，为利益众生，众生想即非想。",
"【利益众生·众生想即非想·如来真语】须菩提！如来说实、说谛、说如、说非虚妄。复次，须菩提！是法如来所觉，是法如来所说，是法非实非虚。须菩提！譬如有人在於盲闇，如是当知菩萨堕相行堕相施。须菩提！如人有目，夜已晓时，昼日光照，见种种色。【义解】如来是真语、实语；菩萨堕相行施如盲闇，不堕相行施如有目见色。",
