"【不惊不怖不畏·第一波罗蜜】何以故？须菩提！此法如来所说，是第一波罗蜜。此波罗蜜如来所说，无量诸佛亦如是说，是故说名第一波罗蜜。复次，须菩提，是如来忍辱波罗蜜，即非波罗蜜。何以故？须菩提！昔时我为迦陵伽王斩斫身体骨肉离碎。【义解】此法即第一波罗蜜；忍辱波罗蜜即非波罗蜜。佛昔为迦陵伽王斩斫身体。",
"【忍辱波罗蜜·迦陵伽王斩斫】我于尔时，无有我想、众生想、寿者想、受者想，无想、非无想。何以故？须菩提！我于尔时，若有我想、众生想、寿者想、受者想，是时则应生瞋恨想。须菩提！我忆过去五百生中，作大仙人名曰说忍。【义解】佛被斩斫时离四想，故不生瞋；过去五百生作大仙人名「说忍」。",
