"【三十二相·非相·恒伽沙身命布施】」佛告须菩提：「若有善男子、善女人，如诸恒伽所有沙数，如是沙等身命舍以布施。若有善男子、善女人，从此经典乃至四句偈等，恭敬受持为他正说。此人以是因缘，生福多彼无量无数。」那时净命须菩提由法利疾，即便悲泣抆泪而言：【义解】以恒伽沙数身命布施，不及受持此经四句偈之福。须菩提闻法悲泣。",
"【须菩提悲泣·未曾闻如是经典】「希有，世尊！希有，修伽陀！如此经典如来所说，我从昔来至得圣慧，未曾闻说如是经典。何以故？世尊说般若波罗蜜，即非般若波罗蜜，故说般若波罗蜜。世尊！当知是人则与无上希有之法而共相应，闻说经时能生实想。【义解】须菩提叹从昔得圣慧未曾闻如是经典；闻经能生实想者与无上希有之法相应。",
