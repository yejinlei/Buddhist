def process(src_name, data, out_name):
    src = os.path.join(SRC, src_name)
    with open(src, encoding="utf-8") as f:
        obj = json.load(f)
    trs = obj["translations"]
    assert len(trs) == len(data), f"{src_name}: input {len(trs)} vs data {len(data)}"
    for i, (tr, (sec, mod)) in enumerate(zip(trs, data)):
        # sanity: section must not exceed 14 chars, modern must start with 【section】 and contain 【义解】 with text after
        assert len(sec) <= 14, f"{src_name} seg{i+1}: section too long ({len(sec)}): {sec}"
        assert mod.startswith("【" + sec + "】"), f"{src_name} seg{i+1}: modern prefix mismatch"
        assert "【义解】" in mod, f"{src_name} seg{i+1}: missing 【义解】"
        tail = mod.split("【义解】", 1)[1].strip()
        assert tail, f"{src_name} seg{i+1}: no text after 【义解】"
        assert mod.strip()[-1] != "】", f"{src_name} seg{i+1}: ends with 】"
        tr["section"] = sec
        tr["modern"] = mod
    out = os.path.join(OUT, out_name)
    with open(out, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
    return out, len(trs)

