"""批量修复校对发现的问题，仅修改modern字段，不改动original_preview"""
import json, os, re

ROOT = os.getcwd()
trans_dir = os.path.join(ROOT, "data/modern-translation")
fixed_count = 0

def fix_sid(sid, fixes):
    """
    fixes: list of (old_str, new_str, note)，每个替换断言old_str唯一存在
    """
    global fixed_count
    path = os.path.join(trans_dir, f"{sid}.json")
    with open(path, encoding="utf-8") as f:
        d = json.load(f)
    for old, new, note in fixes:
        found = 0
        for i, seg in enumerate(d["translations"]):
            if old in seg["modern"]:
                found += 1
                seg["modern"] = seg["modern"].replace(old, new, 1)
        assert found == 1, f"{sid} 替换失败: 找到 {found} 处 '{old[:30]}...'，应为1处, note: {note}"
        fixed_count += 1
        print(f"  修复 {sid} {note}")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=2)

print("开始批量修复...")

