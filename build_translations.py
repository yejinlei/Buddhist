def make_segments(text, boundaries):
    """boundaries: list of (start, end) indices in text; produce segments covering entire text."""
    segs = []
    for i, (s, e) in enumerate(boundaries):
        segs.append(text[s:e])
    assert ''.join(segs) == text
    return segs

