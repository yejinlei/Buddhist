"【十八事（续）】十二者，正使得贤善有德人，往至其所难；十三者，正使往至其所，得宜适难；十四者，正使得宜适，听问难；十五者，正使受听问，说忠政难；十六者，正使忠政，解智慧难；十七者，正使得解智慧，能受深经难；【义解】续列十八事之十二至十七（往至其所得宜适、听问、说忠政、解智慧、受深经），下段续说第十八。",

"【十八事（续结）·八处佛无那何】十八者，正使能解深经，复重难。这就是十八事，人于世间大难。有八处人，佛无那何（无奈）？一者，哑人；二者，聋人；三者，地狱中人；四者，饿鬼中人；五者，畜生中人；六者，边地不知法义；七者，长生二十八天上；【义解】结十八事（解深经后复须重行，种种难得）。次列八处人佛亦无奈（哑、聋、地狱、饿鬼、畜生、边地不知法义、生长寿天），下段续说。",

"【八处（续）·五百人言善】八者，受不精进行。这就是八处人，佛无那何。有五百人自说言：「我善。」佛言：「你当善，当随我后。」人言：「诺！」佛便行入火中，五百人皆止住，无敢随者，言善人至难得。【义解】续说第八处（受不精进行）。次记五百人自言善，佛令随行入火中，五百人皆不敢随，明「善人」至为难得。",

"【教人作善·恣心·道有七事（起）】有人问佛：「佛教人作善，何等益？」佛言：「天下人恼（苦恼），我故教之罢了！」人复言：「人有心，当恣之。」佛言：「因天下人恣心之故，我止住百劫，乃得佛道。」道有七事：一者，意喜布施不欲余；二者，但欲闻；三者，但信；四者，但持戒；【义解】佛答教人作善乃因天下人苦恼；若恣心则久滞（佛自谓因众生恣心而止百劫乃得道）。次列道有七事（喜施、欲闻、信、持戒），下段续说。",

"【道七事（续）·并修七事】五者，但欲行；六者，欲学慧；七者，但欲脱去。佛在世时得脱，转后世但学慧，复转后世但欲行，复转后世但持戒，复转后世但信，复转后世但欲闻，复转后世但欲布施。不但布施当复闻，不但闻当复信，不但信当复持戒，不但持戒当复行，不但行当复慧，不但慧当复脱去，此七事当并行。【义解】续列道七事（欲行、学慧、欲脱去）。明佛在世时得脱，后世辗转退为学慧、欲行、持戒、信、闻、施；七事当并行，不可执一。",

"【五丛残世】有五种丛残（衰退之相）：一者，上世人长寿，今世人短寿；二者，上世人端正桃花色，今世人丑恶；三者，上世人多得道，今世人不能得；四者，上世人博达，通知经要，今世人不能通知；五者，上世人安隐，今世人多疾瘦。【义解】立「五丛残」——明末世人心之五种衰退：寿短、貌丑、难得道、不通经要、多疾瘦。",

"【长寿道人布施·闻佛一言胜珍宝】这就是五丛残世。有长寿者道人，大富，财产无数，好作布施。有人言：「你作布施大多（甚多）！」道人报言：「我从佛闻，人在世间往来生死，其日不可数。今我所有布施，尚不能日用一钱，何以为多！佛说人得一切天下珍宝，不如闻佛一言。【义解】结五丛残。记长寿道人虽大富好施，自谓所施「日用不足一钱」，因生死日长而所施有限；并引佛说：得一切天下珍宝不如闻佛一言。",

"【揭鸟喻·蜂作蜜喻】何以故？徒多财产，不能离世间之故。」山中揭鸟，尾有长毛，毛有所着，便不敢复去，爱之恐拔，终为猎者所得，身坐分散而为一毛之故。人散意念恩爱、财产，不得脱苦，因贪淫之故。人治生，譬如蜂作蜜，采取众华，勤苦积日，已成，人便攻取持去，亦不得自食，适自疲极。【义解】释多财不能离世。以揭鸟爱尾毛而为猎者所得，喻人贪恩爱财产不得脱苦；以蜂采华作蜜而人取去（蜂不得自食），喻治生勤苦而自疲。",

"【聚财之苦·泥船喻·金四试】人东走西走，求是作是，合聚财宝，勤苦不可言。已命尽，他人得其财，身及得重罪，受苦不可量。人在世间，譬乘泥船渡河，当浮渡，船且坏。人身如泥船不可久，当疾行道。金有四试：一者，烧；二者，磨；【义解】明聚财勤苦、命尽财留他手、身更得罪。以身如泥船渡河（须疾渡）喻当疾行道。次举金有四试（烧、磨、锻、炼），下段续说。",

"【金四试·人四试·知人四缘·知道人四缘】三者，鍛；四者，炼。譬喻人亦有四试：一者，娆（扰）；二者，共从事；三者，色；四，为制不止。欲得人相，有四种因缘——一者，与共居；二者，共居当久；三者，当共语言；四者，共事——可以知之。有四种因缘知为道人：【义解】续金四试（锻、炼），喻人有四试（扰、共事、色、制不止）。次说知人之四缘（共居、共居久、共语言、共事），及知为道人之四缘，下段续说。",

"【知道人四缘·今世受福四因缘】一者，闻恶乱意，即时转念；二者，不说人恶；三者，自不堕论议；四者，能自护。如是知为道人自护。今世四因缘乃受福：一者，有处；二者，有时；三者，业；四者，师。人有所止，得安隐、如意，这就是处。【义解】明知道人四缘（闻恶即转念、不说人恶、不堕论议、能自护）。次列今世受福四因缘（处、时、业、师），先释「处」（所止得安隐如意），下段续说。",

"【时业师·兄弟三人持夜（起）】如人年三十当富，十五时求不可得，至三十乃得，这就是时。若人宜贾白珠亦余物，从得利，这就是业。遭得明人分别说经，心即开解，这就是师。有兄弟三人，各自谓高健无辈，共更持夜，二兄居前卧，小弟便独坐。【义解】释「时」（如年三十得富）、「业」（贾白珠等得利）、「师」（遭明人说经开解）。次记兄弟三人持夜，小弟独坐，下段以不吉虫为喻。",

"【不吉虫喻（起）】有一虫，名为不吉，来啮其髀。弟便以手指之，虫便长大，复捶益大。其人瞋恚，取虫蹙踏，自致疲极，虫益大不止，其人便止休。一夜已竟，便呼仲兄起，虫复啮之，兄复如小弟与共斗，虫更长大至屋，如是疲极，复止休。【义解】以不吉虫为喻：小弟以手指虫，虫愈长大，捶踏亦愈大，终至疲极止休。一夜后仲兄亦如是斗虫，虫更长大至屋，复止休。",

"【不吉虫喻（大兄以盆覆）】二夜竟，便呼大兄起坐，虫复啮之。大兄便持手指摩娑，虫复起，兄生意以㼜（盆）覆之，须臾极，虫便出㼜去。至明日二弟极不能复起，兄知二弟与虫共斗，便问：「何以不起？」二弟惭不敢语。兄言：「与虫共斗极耶？【义解】续记大兄遇虫，不与之斗，以盆覆之，虫须臾极而出盆去。明日二弟疲极不起，大兄乃问其故。",

"【不吉虫喻（结）·痴人得对】」弟言：「然！」兄语弟言：「后倘有不吉虫来，但以㼜覆之，不当指也！」譬喻如痴人得对，便瞋恚，从得罪。如弟与虫斗，自致疲极。黠人见对来，便避之，是得福，譬如㼜覆不吉虫。昔有道人为国王说经。【义解】结喻：对大兄之教——遇不吉虫当以盆覆，不当以指。以痴人遇对境即瞋恚招罪、如弟与虫斗自致疲极；黠人见对即避得福，如盆覆虫。下段另起国王问道人之事。",

"【国王问得道·葡萄酒喻】王言：「佛在世，多人得道。今同说佛经，人不得道。佛为持道法去耶？」道人言：「譬天下极美不过葡萄酒，饮一升便可醉，持一升水浇一升酒中，饮之不能复醉。佛在世时说经，知人意态，譬如人饮一升酒便得醉，今我辈不知是。【义解】记国王问：佛在世多人得道，今同说佛经却无人得道，佛岂将道法带去？道人以葡萄酒为喻：酒掺水则淡，喻佛在世说法知人意态（如浓酒令人醉），今人说法不知意态。",

"【应病与药·国王饭僧·浴佛高价】佛说经知人意态，应病与药之故，人多得道。」有国王饭诸比丘，天来指示王，是（此）人得阿罗汉，是（此）人菩萨，是人得道迹，是人不持戒。王悉觉知，持心正等，无有异意，诸天代其欢喜。有国王与人共争高价浴佛，王辄举高价不止。【义解】承上明佛应病与药故人多得道。次记国王供僧、天来指示各人修证，王心平等无异，诸天欢喜；及国王与人争高价浴佛之事。",

"【浴佛·阿育王塔·小王往伐】人言：「今我悉持所有财物、妻子，自身为奴婢，以浴佛。」王便不得。阿育王作八万塔，临命欲绝时，菩萨、阿罗汉有五百人共守护，更为说经，不使诸夫人得近与相见，欲令王上天之故。有小国王常起往伐。【义解】续记浴佛争价，人以尽舍财妻子乃至自身为奴而浴佛，王乃不得（不能胜过）。次记阿育王造八万塔，临终五百圣者守护说法、不令夫人近见，欲令王生天；及小国王常来侵伐之事。",

"【舍国去·遗言慈心】大王思惟言：「亡身得恶，皆从贪爱之故。我不如以国与之！」大王舍国而去，作白衣在他国，久后归故国。有人白言，王便敕左右往捕取，杀之。临当死时，呼其子嘱一言：「慎勿忘也！你勿念怨家，要当慈心！【义解】记大王思贪爱招恶，乃舍国与人、作白衣居他国；后归故国被人告发、王敕捕杀。临死嘱子一言：勿念怨家、要当慈心。",

"【不平时雨·女人请雨】」有国王治行不平，侵枉人民，受取非法，天为雨不时节。有女人言：「天雨不时节，王治行不平正之故。」王以闻知，便呼女人令请雨，以三器着地，女人愿，令雨堕中央器中，复令从一头起，则如其愿。【义解】记一国王治政不平、侵枉人民、取非法财，天乃不按时降雨。有女人言此乃王政不平所致；王呼女人请雨，以三器着地，女人如愿令雨落中央器、复从一头起。",

"【至诚故·国王欲夺人妇（起）】王问：「何因缘得是？」女人白言：「我至诚之故。」佛言：「有地乃有万物，人有至诚乃有道。」有国王出行，见一女人端正无比，王意欲杀其夫，取此女人。旁臣言：「不当杀，当享之。」王国序其夫，以金指环与之，语言：【义解】女人答请雨之验乃因「至诚」；佛言有地乃有万物、人有至诚乃有道。次记国王欲夺人妇、欲杀其夫，臣劝不杀而「享（优待）」之；王以金指环与夫并嘱，下段续说。",

"【忘环则杀·至诚得环】「忘环者杀你！」王私呼妇，令盗取环。以后，王呼问其夫环所在，夫求不知处，便敕臣杀之。令美饮食，夫恐，不敢食。人言：「你当死，何不食？」夫适欲噉鱼，因于鱼腹中得环，是至诚所至。【义解】记王以「忘环则杀」相胁、私令妇盗环，复问夫环所在欲加之罪；夫临刑食鱼，于鱼腹中得环，以此明「至诚所至」。",

"【贫穷道人·至诚不贪得宝】有道人贫穷，举十万用治生。便先持三万布施，持余钱行贾。途中为贼所抄，王便以珍宝物丐与之。有大囊、小囊，余人各取大囊去，道人自念言：「我钱少，不宜取大囊。」便取小囊去。其中悉有白珠，卖得六千万。因至诚不贪之故，得此珍宝。【义解】记贫穷道人借十万治生，先以三万布施，余钱行商途中遇贼，王以珍宝器物施与。众取大囊，道人自念钱少取小囊，囊中皆白珠，卖得六千万——以至诚不贪故得宝。",

"【盲人观象喻（起）】昔有国王征国中诸盲人，令于象厩中观象。中有持象足者，中有持象鼻者，中有持象耳者，中有持象尾者。去后共相问：「象何等类？」持象足者言：「象大如柱。」持象鼻者言：「象如绳索。」持象耳者言：【义解】以盲人观象为喻：诸盲各持象之一分（足、鼻、耳、尾），去后互问象之形类，下段续说各人异见。",

"【盲人观象喻（结）·国王伎乐】「象如簸箕。」持象尾者言：「象如大杖。」皆共诤之，盲人各自信其意。譬如人各见少所经，不了其法，自谓大解，亦如是。有国王于城外大作伎乐戏，举国中人民皆出行观。城中有一家，其父有疾不能行步，家室共扶，将令行，言：【义解】结盲人观象喻：各执一见而自以为是，喻人各见少分经法、不了其法而自谓大解。次记国王城外作伎乐，举国出观；城中一家父病不能行，家人共扶令行，下段续说。",

"【病人随化人上天（起）】「出城便止。」树下不能自致，语家中言：「你们自行观，来还乃持我归。」时天帝释化作一道人，过其边，便呼病人：「你随我去，我能令你病愈。」人闻之大喜，便起随行。释将上天至宫，见金银好物甚众多，欲从求之。【义解】续记病人于树下不能自致，令家人观罢乃持归。天帝释化道人过其边，呼病人随去令病愈；病人随至天上宫殿，见金银好物众多而起求取之意，下段续说。",

"【匃瓶得宝·跳瓶失宝】人言：「勿得，可求丐瓶。」病人因前到释所言：「我欲去，愿持此瓶丐我。」释即与之，语病人言：「中有物在，你所愿（皆满）。」病人持归，室家相对探之，转得心中所愿，金银珍宝恣意皆得。大会宗亲诸家内外，共相娱乐。【义解】记释令病人但求一丐瓶，与之并告瓶中能满所愿；病人持归，家中探瓶皆得金银珍宝，遂大会宗亲娱乐，下段续说跳瓶失宝。",

"【跳瓶失宝·弥勒尚学·阎王问】醉饱已后，因取瓶跳之：「我受你恩，令我富饶。」跳踢不止，便堕地破之，所求不复得。世间有黠人多无数，未有如弥勒者。弥勒尚复行学不厌，何况余乎？佛已得道，坐行安般守意。佛言：「我从无数世以来与（学）不厌，乃得佛。【义解】记病人醉饱后跳踢宝瓶、瓶破失宝，明得而复失。次举弥勒尚行学不厌，况余人；佛已得道仍坐行安般守意，自言从无数世学不厌乃得佛，下段续说阎王问。",

"【阎王问·尊者受辱（起）】」后世人学当那（如何）得佛道！已持戒，不复作恶。有不信意故，复犯戒，便堕地狱。阎王问之，便对言：「我不作恶。」阎王复问：「你不作恶，何为在此中？」有尊者为贼人所折辱。有人言：「何以不杀之？」【义解】承上：后人学道岂能（易）得佛。明持戒者因不信意而复犯戒、堕地狱，阎王诘问、罪人狡辩。次记尊者受贼人折辱，有人劝其杀之，下段续说。",

"【尊者答不杀·兵马具】尊者言：「我人客未具之故。」人复言：「我为你出人客。」尊者言：「不也！我兵今自具如是，二十余岁杀贼人，被病死。」人复言：「你不杀之，今反自死！」尊者言：「我兵马以（已）具。何故？痴人当入地狱，这就是兵马具。【义解】续记尊者以「人客（兵马）未具」故不杀贼人；自言二十余岁「杀贼人者被病死」；终谓：兵马已具者，乃「痴人当入地狱」——以地狱为兵具，故不杀。",

"【知一万事毕·道人夜行】」问曰：「何等为能知一万事毕？」报曰：「一者谓无意、无念，万事自毕。意有百念，万事皆失。」有道人夜行前未得道，人随其后。后人有疑悔，前人举手，五指头出火，复以钥开户，后人乃觉悟，知为道人。【义解】设问答「知一万事毕」：一即无意无念，万事自毕；意有百念则万事皆失。次记道人夜行，为令后人起信，举手出火、以钥开户，后人乃悟其为道人。",

"【六衰七衰·痴为大衰·海喻】说：「经有六衰，有人言七衰，屋舍衰独非衰耶？」佛谓人言：「我复饶你一衰，痴为大衰。何以故？人说身事，反说屋舍，这就是痴。」有人堕海中，有人教食水尽，可得步出。人言：「我已饮，后水复来！【义解】论六衰、七衰之说，佛谓痴为「大衰」——人说身事却反说屋舍即痴。次以堕海者教其饮水令尽（水复来）为喻，下段续说。",

