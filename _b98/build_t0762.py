"【三摩地想结·四念处（身·受）】能观想者，即得智慧胜利现前，是名第四三摩地想。此等名为四三摩地想。「复何名为四念处法？谓：身、受、心、法。若有比丘！观身不净，秽恶充满无有真实，如是观察，名身念处。「又复观于内外二法，所有诸受，悉皆是苦，作是观者，名受念处。【义解】结第四想（得智慧胜利现前），总名四三摩地想。次起四念处：身念处（观身不净、秽恶无实）、受念处（观内外诸受皆苦）。",

"【四念处（心·法）·四正断（一）】「又复观于心心所法，皆悉无常，作是观者，名心念处。「又复观于内外二法，于是法中，不生我想，作是观者，名法念处。如是名为四念处法。「复何名为四正断法？谓：已生恶法，当起精进勤行除断，皆悉令灭，是名第一正断之法。【义解】明心念处（观心心所法皆无常）、法念处（观内外法不生我想），结四念处。次起四正断之第一——已生恶法当精进除断令灭。",

