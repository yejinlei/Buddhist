"【如来十力（九天眼·结）】意不善业，起于邪见。由是因缘，命终之后，堕恶趣中。又复众生，身作善业，不行邪行；口作善业，不谤贤圣；意作善业，起于正见。由是因缘，命终之后，生人天界。如是等事，如来天眼，悉能观见。【义解】续明众生由意不善（邪见）命终堕恶趣，或由身口意三善、正见命终生人天；如是等事如来天眼悉能观见。",

