"【十力结·四无所畏（一）】如是十力，如来、应供、正等正觉，由十力故，于大众中，作师子吼，转大法轮。「复何名为四无所畏？谓如来、应供、正等正觉，于大众中，唱如是言：『我以自智，乘如实道，来成正觉，作师子吼，转妙法轮，无有沙门、婆罗门、天、人、魔、梵而能等者。【义解】结十力，明如来由十力故于大众中作师子吼、转法轮。次起四无所畏：第一「一切智无畏」——佛自言以自智乘如实道成正觉、转法轮，无人能等。",

"【四无所畏（二·三·四）】』是名如来一切智无畏。「如来已得安乐寂静无上胜处功德果法，诸漏已尽，种习俱亡，是名如来漏尽无畏。「如来复为诸声闻众，开示苦道，说离烦恼尽苦边际。是名如来出苦道无畏。「如来复为诸声闻，说所有障法，令彼出离。【义解】明第二「漏尽无畏」（佛已得安乐寂静无上功德、诸漏已尽、种习俱亡）、第三「出苦道无畏」（为声闻开示苦道、令离烦恼尽苦际）、第四「障道无畏」（为声闻说诸障法令出离）。",

"【四无所畏结·四禅（一·二）】是名如来障道无畏。如是名为四无畏法。「又复何名为四禅定？谓：离诸欲及诸染法，断除疑惑分别之想。是名第一离生喜乐定。「复次离欲断除分别想已，当于外法悉皆泯绝，内复寂定，摄内外法，悉皆归一。【义解】结四无所畏；次起四禅定：第一「离生喜乐定」（离诸欲染、断疑惑分别想），第二定之起（离欲断分别想、外法泯绝、内寂摄归一）。",

"【四禅（二·三·四）】是名第二定生喜乐定。「复次舍于喜乐思念之想，于身喜乐而无所受。是名第三离喜妙乐定。「复次舍苦乐法，无忧喜想，诸法清净。是名第四舍念清净定。如是名为四禅定法。「复何名为四无色定？谓：【义解】明第二「定生喜乐定」、第三「离喜妙乐定」（舍喜乐想、身乐无受）、第四「舍念清净定」（舍苦乐、无忧喜、诸法清净）；次起四无色定。",

"【四无色定（一·二·三）】修彼定，厌下色相，忻上无色，由无色故，唯有虚空，乃观虚空无有边际。作如是想，是故名为空无边处定。「复次离彼所缘空无边处已，复想能缘识亦无边，是故名为识无边处定。「复次离彼能缘识已，当复想于能缘所缘俱无所有，是故名为无所有处定。【义解】明四无色定之前三：空无边处定（厌色忻空、观空无边）、识无边处定（离空缘观识无边）、无所有处定（能缘所缘俱无所有）。",

"【四无色定结·四无量（慈）】「复次离彼无所有已，当复想于无彼粗想，不无细想，是故名为非想非非想定。如是名为四无色定。「复何名为四无量行？谓：慈无量、悲无量、喜无量、舍无量。若有比丘具大慈心，于诸有情，无怨无亲，等能与乐。【义解】明非想非非想定（无粗想而不无细想），结四无色定。次起四无量行，先明慈无量——具大慈心，于诸有情无怨无亲、平等与乐。",

"【四无量（慈·悲·喜）】如是常行慈无量心，是故名为慈无量行。「若有比丘具大悲心，于诸有情，无怨无亲，等能拔苦，如是常行悲无量心，是故名为悲无量行。「若有比丘具大喜心，于诸有情，无怨无亲，等施欢喜，如是常行喜无量心，是故名为喜无量行。【义解】明慈无量（常行与乐）、悲无量（平等拔苦）、喜无量（平等施喜）之义。",

"【四无量结·四无碍智（辞）】「若有比丘，于诸有情，无怨无亲，平等安住如是常行，是故名为舍无量行。如是名为四无量行。「复何名为四无碍智？谓：辞无碍智、辩才无碍智、法无碍智、义无碍智。辞无碍者，缘声为境，于诸音声，言辞无碍。【义解】明舍无量（平等安住）；结四无量行。次起四无碍智（辞、辩才、法、义），先明「辞无碍智」——缘声为境、于音声言辞无碍。",

"【四无碍智（辩才·法·义）】故名辞无碍智。辩才无碍者，谓：四辩七辩，凡有论难，迅捷无滞，是故名为辩才无碍智。法无碍者：缘名句文，随何教法，无所不通。是故名为法无碍智。义无碍者，缘义为境，随所诠义，无所不晓。是故名为义无碍智。【义解】明「辩才无碍智」（四辩七辩、论难迅捷无滞）、「法无碍智」（缘名句文、通于教法）、「义无碍智」（缘义为境、随诠皆晓）。",

"【四无碍结·四三摩地想（一）】如是名为四无碍智。「复何名为四三摩地想？若有比丘作如是观：我今此身，从顶至足，所有发、毛、爪、齿、皮肉、筋骨，如是种种不净之物，所共合成。譬如仓廪广积粮斛，人入其中，善能分别，是米是麦。【义解】结四无碍智；次起四三摩地想：第一想为观身不净——从顶至足皆发毛爪齿皮肉筋骨等不净物合成，如入仓廪能辨米麦。",

