"【三摩地想（二结·三）】比丘观想，亦复如是！能观想者，即得见法轻安乐味，是名第二三摩地想。「又复比丘！于三摩地，作于明想：观察如日无余暗冥。如是观察，相续不断，昼夜明暗，皆无有异，作是明想，清净无杂。譬如秋时云翳阴暗日光不现，若明眼人，观想日光，清净无杂。【义解】结第二想（得见法轻安乐味）；次起第三想——于三摩地作「明想」，观如日光无余暗冥，昼夜明暗无异，清净无杂，如秋时观想日光。",

