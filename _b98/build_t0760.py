"【不堕三道·五道黠分】三道不得（其便）故，不复堕三道，身、口、意三事尽，三道亦尽。菩萨离五道常有黠福，人死时要有五道之分，菩萨复（有）黠分，即知念远近。菩萨知分在须陀洹、斯陀含，分不在阿那含。何以故？（以）不复还之故。一佛界有三千大千天地，人生死遍其天地之间，无有（如）一发不在其中，无所不作，独未作阿惟越致、斯陀含罢了，余皆更（历）无数。【义解】明三道不逮故不堕三道，三业尽则三道尽；菩萨离五道常有黠福，死时有五道之分，知分在须陀洹、斯陀含而不住阿那含（不再还来）。末说一佛界三千大千中众生生死遍满、无所不作，独未作不退转与斯陀含。",

"【菩萨求福三行·布施二辈】佛为菩萨时有此意生：「为何等行因缘，现在得福极？」如是更得宿命之意，是从此三行：布施、从制、从合聚。布施有二辈：一，为法施，二，为物施。守身、口、识为御，守意为合聚。也从布施因缘得解断贪，从制为断瞋恚乱意，从合聚自守为断痴。【义解】明佛为菩萨时思「何行得福极」，终得宿命智，其因有三行：布施、持戒（制）、合聚（守意）。布施有法施、物施二辈；三行分断贪、瞋、痴。",

"【三行得正·布施之报】从布施也得正意，从制得正语，从合聚得意行安隐。从布施见布施之福，从制说念福，从合聚说意福。菩萨所以布施者，（令）所在五道常饶乐，与凡人有异辄得作王，智慧常有慈心，但毕罪不复更作，虽在罪（中）无作罪。【义解】明三行各得正意、正语、意行安隐，及各见其福。菩萨布施之报：所生五道常饶乐、得作王、智慧有慈心、毕罪不复造，虽在罪中而不作罪。",

"【在家菩萨·但禁恶】人间亦是如此，菩萨与妻子共居，（如）年二十五，一日生（一月）三十（日），一月（有）年三十日，百日（为）年五十一岁——菩萨但禁恶，不禁（有）家。「名乱意」者，为罪不安隐，远避去。无乱意为福，虽在家譬如在狱中，但当觉罪，不复（造）便所生在乐处，故为菩萨。【义解】明在家菩萨与妻共居亦得道，但禁恶不禁有家；乱意者远避，无乱意为福。虽在家如在狱、但当觉罪不造，故得生乐处而为菩萨。",

"【忍辱得果·餧虎·弃妻六年】人求道不忍辱、不能耐（者）（则）便（止）得须陀洹。佛前世菩萨言：「佛道难得。」一语减四十劫。以身餧饿虎，出众菩萨前九劫，为须大拏受莂，一切精进行道一切得佛。有妇（者）不得佛道。菩萨在家时有妻。何以故？得佛（者）因弃妻子六年之故乃得佛道。【义解】明不忍辱者止得须陀洹；佛前世一言「佛道难得」即减四十劫，餧虎之行超众菩萨前九劫，为须大拏受莂，精进者皆得佛。次说菩萨因弃妻子六年乃得佛道。",

"【妻子如怨家】菩萨计妻子是怨家。何以故？（以其）与人苦、益人恼、乱人意、增人罪，以随贪爱便不见道，以是故为怨家。见妻子当如见怨家之意，莫随贪爱，意起即觉，这就是觉意；所有财物、自身亦是如此。天上、天下、十方一切有火。【义解】明妻子如怨家（与人苦、乱人意、增罪，随贪爱则不见道）；见妻子应如见怨家，莫随贪爱，意起即觉，是为觉意；财物、自身亦然。末标十方一切有火（欲火），下段释。",

"【娶妇四缘·自断与他断】何以故？（以）有火（故）已。菩萨娶妇有四种因缘：一者，宿命同福，二者，毕罪，三者，应当共生男女，四者，黠人娶妇疾得道，无此四事亦不娶妇。为菩萨道，念欲断十方天下人之三毒，是故得佛道；或有行道，但欲自断三毒，故得阿罗汉。【义解】明有火（欲）故说娶妇四缘（宿福、毕罪、共男女、黠人娶妇疾得道）。次辨：为菩萨道者念断十方人之三毒故得佛，但欲自断三毒者得阿罗汉。",

"【自坏痴他坏痴·忧念十方·坏恶】菩萨自坏（断）痴，也复坏十方人之痴；阿罗汉自坏痴，不坏余人痴。菩萨多觉，多教人令得行道，这就是坏人之痴。忧念十方天下人，这就是行菩萨道；但自忧身，不念十方人，这就是阿罗汉道。菩萨坏恶，阿罗汉不坏恶。【义解】明菩萨自断痴亦断十方人之痴、多觉教人令行道，是为坏人之痴；忧念十方人行菩萨道，但自忧身不念十方人是阿罗汉道；菩萨坏恶而罗汉不坏恶，以此分判二道发心之别。",

"【教人经戒·转罗汉之由】菩萨教人经戒，令随道法，这就是坏恶；罗汉自守，故言不坏恶。菩萨自断苦，也复断十方人之苦，这就是得佛道；罗汉自断苦而不（能）断人之苦，故得罗汉。行菩萨道之所以转（退）得罗汉者，意念佛道生死不可数，所作悉当得之，意计（度）此为难，转（成）阿罗汉。【义解】续明菩萨教人经戒、断十方苦故得佛，罗汉自守、自断苦故得罗汉。次释菩萨道退转为罗汉之由：念佛道生死长远、所作难成，故退心转罗汉。",

"【菩萨四意·等无两道】复计阿罗汉不复偿罪、不复生死，直取度世而去，以此之故转向阿罗汉。无此意、无死转、不避苦，（则）要当得佛道。菩萨、阿罗汉皆从三十七品经（而）行，所以得佛者，持（有）四意（为）菩萨所常行。何等为四？一者，幸得佛业值佛识，我身要当如佛治；【义解】续释退转之由（计罗汉不复偿罪、不复生死）。次明菩萨、罗汉同从三十七品行，然菩萨得佛以常持四意，其第一为「幸得佛业值佛识，我身要当如佛治」，下段续说余三意。",

"【四意（续）·随爱堕五道·娶妇四缘】二者，常持悲意向十方，从悲意尽力未曾离，当脱十方人、非人；三者，本上头愿佛、意不转；四者，愿在世间求道护戒，教人增慧待期。有此四意故得佛，无此四意故得阿罗汉。佛等意故，无有（菩萨、罗汉）两道，随意行得（之）罢了。【义解】续说菩萨四意之第二至第四（常持悲意脱十方人非人、愿佛意不转、在世求道护戒教人增慧）。有此四意得佛、无则得罗汉；佛意平等，本无两道，惟随意行而证。",

"【随爱堕五道·娶妇四缘】随爱便为在五道不得脱，便有老、病、死、忧，为苦共合。意不随贪爱，为持水灭火；已随贪爱为持薪增火。当谛计（度），随谛得道。菩萨娶妇有四种因缘：一者，恐人言不能得妇故学道，二者，恐人言孤独无妻子故学道，三者，宿命本根未尽，四者，恶知识劝令娶妇故。【义解】明随爱则堕五道、老病死忧与苦合；不随爱如持水灭火，随爱如持薪增火，当谛观而随谛得道。次另出娶妇四缘（恐人讥、宿根未尽、恶知识劝）。",

"【断五阴不断·四无畏】菩萨也断五阴也不断。何等为断？谓断五盛阴（及）十二因缘。不断者，菩萨在经行因缘随道，这就是不断。菩萨毕罪、毕得道。菩萨有四种无所畏：一者，不取人钱，二者，不犯他人妇女，三者，不两舌，四者，不嫉妒。【义解】明菩萨断五盛阴及十二因缘，而于经行随道处不断；毕罪则毕得道。次列菩萨四无所畏（不取人钱、不犯他妇、不两舌、不嫉妒）。",

"【断三恶道·三毒起灭】菩萨断三恶道，尚在（世间）但不堕其中罢了。菩萨未起三毒；佛时无有三毒，得因缘乃有三毒。菩萨坐禅六年，临当得道，三毒俱起，淫、怒、痴使意念：「调达（提婆达多）得我妇耶？为胜我耶？当复得我财产？」意适生，即（时）息念：【义解】明菩萨断三恶道而不堕其中；佛无三毒、得缘乃起。菩萨坐禅六年临得道时，淫怒痴三毒俱起（念调达夺妇、胜我、夺财），意才生即息念，下段续说。",

"【六年苦行·日食一米一麻·攀树】「我从无数劫以来断此三恶。」何以故？复（如是）念便灭，即得道。菩萨坐禅六年，日食一米一麻，有四种因缘：一者，断贪，二者，毕罪，三者，（令）见不饿，四者，止饥。意了不食，谓人饿得道，恐人自饿死。菩萨坐行道六年，日食一米一麻，入水浴躄（倒）地而不起，天因按树枝令低，即攀之而起。【义解】承上：念「我从无数劫断此三恶」，念灭即得道。释六年日食一米一麻四缘（断贪、毕罪、见不饿、止饥），并恐人误解绝食自饿死。次叙菩萨六年苦行、浴水倒地、天按树枝令攀起之事。",

"【树下六年·四不戢】菩萨坐树下六年，虫、䗍、蚊、虻不娆（扰）者，有四种因缘：一者，本从无数世不杀生，二者，行等心，三者，诸天、鬼、神护（卫），四者，道力强，也为处（所）清净。菩萨有四种不戢（不厌足）：一者，布施不戢，二者，闻经不戢，三者，清净不戢，四者，作功德不戢。【义解】明菩萨坐树下六年虫蚊不扰之四缘（不杀生、等心、天鬼神护、道力强处净）。次列菩萨四不戢（布施、闻经、清净、作功德皆不厌足）。",

"【出家因三苦】菩萨始出家行学道，诸大人谓菩萨：「今太子居家，何故去？」太子报言：「我用三苦之故去罢了。何等为三苦？谓老、病、死。」大人复言：「老、病、死之事常（有）耳，何为去？」太子言：「得一病常（尚）不喜，当那（奈）何（况）常？」【义解】记菩萨（太子）始出家时与诸大人问答：以老、病、死三苦故出离；大人谓老病死乃常事，太子答：一病尚不喜，何况常在？",

"【生行七步·学书】」菩萨生，堕地行七步止住，举右手言：「我为天上天下师。」止不复行。菩萨为太子时，行学书到师之舍，师问言：「欲学何等？」太子言：「我欲学六十种书。」师问言：「六十种书皆何等？」太子便为师次第说。【义解】记菩萨降生行七步、自称「天上天下师」；及为太子就师学书，欲学六十种书、为师次第陈说。",

"【学书·付衣车匿】师言：「我但知一种书，不能悉知余书。」太子言：「如师所知（者）教我。」已受师教，便言：「此中少两字。」师更从受两字。师言：「太子所知乃尔（如此），何为从我学？」太子言：「虽尔（如此），当有师法。」菩萨始出家行百里，解身上衣被、珍宝，付车匿持归，白马健陟泪出舐足。【义解】续记学书之事：师仅知一种书，太子反从师受两字，示有师法之敬。次叙菩萨出家行百里，卸衣珍付车匿持归，白马健陟（犍陟）泪出舐足。",

"【车匿劝·太子答】车匿言：「莫使有如是人（发此）愿者。」太子报言：「天下痴（人），无有如你辈者。何以故？世间但有老、病、死、忧苦，当愿何等？如囚在狱中，谁有乐者？当尚未离此（苦），而复苏更愿（还入），当何时脱？譬如猎客网中之㝹（兔）得脱，宁（岂）复念还入网中，不念得脱？【义解】记车匿劝太子莫发如是愿，太子答：天下愚痴无如你辈——世间但老病死苦，有何可愿？如囚在狱、兔脱罗网，岂复愿还入？以此明其出离之志。",

"【㝹脱网不还·母终四缘】如㝹脱网，终不还归。我在家时念此日久，也从无数劫以来有此意，非独今日所致。」菩萨生已七日其母命终者，有四种因缘：一者，因怀菩萨之故，天来占视、与（其母）饭食；二者，如生死法当礼母，以菩萨尊贵之故，母七日终；【义解】承上：如兔脱网终不还。菩萨生七日而母终，有四缘，其一二为：因怀菩萨故天来占视与食；以生死法当礼母，菩萨尊贵故母七日终。下段续说余缘。",

"【母终四缘·菩萨五梦】三者，其母宿命自应尔；四者，譬如人有功当受封，便上天生。菩萨未得佛道时有五梦：一者，以须弥山作枕；二者，以地为床；三者，以手盖海水；四者，天下皆有屎，行其上不污足；五者，心前生一树上至二十七天。【义解】续说母终之三四缘（宿命应尔、如受封生天）。次列菩萨未成佛时五梦（枕须弥、地作床、手盖海水、行屎不污、心前生树上至二十七天），下段释其义。",

"【五梦释义·随女人四缘】梦枕须弥者，（谓）天上天下尊无过佛者；以地为床者，佛身长能上至二十八天；以手盖海水者，诸欲说经道无有胜佛者；行屎上不污足者，天下爱欲无能污佛心者；心前生树者，佛语上闻第二十七天上。菩萨随（近）女人有四种因缘：【义解】释五梦之兆：枕须弥→于天上天下最尊；地作床→身至二十八天；手盖海→说法无胜；行屎不污→爱欲不污心；心前生树→佛语上闻二十七天。末标随女人四缘，下段续说。",

"【随女人四缘·诸天试菩萨】一者，劝女人精进，二者，也欲使女人随行，三者，从过去无数世余罪相逢之故，四者，宿命愿欲教女人。诸天试菩萨有三种因缘：一者，当得佛不得有所贪惜；二者，设菩萨起（退）意，便谓言：「你当得佛道，何故反尔？」【义解】续说菩萨随女人四缘（劝其精进、令随行、余罪相逢、宿愿教之）。次说诸天试菩萨三缘，其一二为验其无所贪惜、令其增精进。下段续说第三缘。",

"【试菩萨三缘·六波罗蜜】」菩萨从是增精进；三者，得佛当相度，故往试之。菩萨行六波罗蜜，阿罗汉也行此六事，所以（罗汉）相不成者，阿罗汉但有檀，无有波罗蜜。「檀」者谓与（行）布施，「波罗」为度生死，「蜜」为无有极。阿罗汉但一切布施，不愿度十方，故但有檀；【义解】续说诸天试菩萨第三缘（得佛当相度故试之）。次辨六波罗蜜：罗汉亦行六事而相不成，以其但有「檀」（布施）而无「波罗蜜」——波罗为度生死、蜜为无极；罗汉但布施而不愿度十方，故唯有檀。",

"【檀波罗蜜·小豆供佛】菩萨欲度十方人、非人，故为有波罗蜜。六事皆尔。（如）佛为菩萨时，愿欲饭（供）佛，以小豆五枚着佛应器中，其一枚堕地，后得作金轮王，八十世所主四天下之地者，得四豆之福之故；其豆不入器中者，复得上（生）天（上）八月。以是故有檀波罗蜜。【义解】明菩萨因欲度十方故有波罗蜜，六度皆然。举佛昔以五小豆供佛为例：四豆入器得作金轮王八十世之福，一豆堕地复得生天八月——以此明檀波罗蜜之义。",

"【布施法物·命终四非常】菩萨布施法物与人，佛意随物行念，令受者安隐。若意生念欲得福，便念：「饥寒贫穷者当用（以）与之，皆令安隐。」这就是道法布施。与一钱物胜十千万，复有「不施与少胜多者」，因有道意令安隐之故。若人命欲绝时，意在非常、苦、空、非身，便得阿惟越致、为受莂。【义解】明以法／物布施、随念令受者安隐为道法布施；与一钱而有道意者，胜于无道意之千万施。次说人命将终时意住非常、苦、空、非身，则得阿惟越致、为受莂。",

