"【买三辈·呪愿·意定】一，为第买，二，为反覆买，三，为偿赐买。菩萨念恩故偿赐，受者也无罪。菩萨所行法当咒愿十方人民，复言当定意一心者，自意不定，也不而咒愿。何以故？用意在生死之故，自意不定，也不能意定人意。【义解】释买偈三辈（第买、反覆买、偿赐买），菩萨以念恩故偿赐而受者无罪。次明菩萨行法当咒愿十方，然须意定一心方能咒愿；意不定则不能咒愿，亦不能以意定人之意。",

