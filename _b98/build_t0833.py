"【众生界从分别起】大仙当知：有在藏中为虫啮食、有为业风之所散坏。大仙当知：树等少障，众生多碍。又复，大仙！诸众生界从分别起。大仙当知：诸众生界心心数法，处处转行皆有攀缘，此义已说。如是，大仙！诸众生界从分别起。【义解】续明：或藏中为虫啮食、或为业风散坏；树等障少、众生障多。又说诸众生界「从分别起」——众生界之心心数法处处转行皆有攀缘，故知众生界从分别而起。",

