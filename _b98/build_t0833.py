"【萤火喻·无实自在】如是，大仙！若身自在，云何后时得不自在？大仙当知：如萤火虫起如是意：『我此光明能悉普遍照阎浮提。』彼萤火虫所有光明，无有因缘能悉普遍照阎浮提。如是，一切不调御心无实自在。又复，大仙！【义解】续答：若身真自在，何以后时得不自在？如萤火虫妄念其光能遍照阎浮提，实无因缘能遍照——一切不调御之心无真实自在。",

