"【四摄·金火喻】如是，大仙！如来亦尔，以布施摄，爱语、利益、同事等摄。「又复，大仙！譬如有人置金火中，非瞋金故置之在火，为令善熟宝相应故，若宝相应则为贵价。大仙当知：以是因缘打熟明净。如是，大仙！【义解】明如来亦如涎呼蟒，以布施、爱语、利益、同事（四摄）摄化众生。又以金置火中（非瞋金，为令宝熟成贵价）为喻，明如来以劫火「打熟」众生令明净。",

"【无众生为劫火所烧】诸佛如来非无因缘放劫尽烧、非有众生劫火所烧。」尔时，大仙光明炬言：「稀有，世尊！放劫烧火，无一众生劫火所烧。」佛言：「大仙！无一众生为如来烧。又复，大仙！譬如十方雨微细雨，如来之数复多于是；【义解】明诸佛非无因缘放劫尽烧，实无众生为劫火所烧。光明炬叹稀有。佛言：无一众生为如来所烧；如十方细雨之数，如来之数更多。",

"【十地菩萨救度·众生发愿】十地菩萨亦复如是，在上而住。如是住已，皆以自手救诸众生，令使解脱。大仙当知：如是众生见诸如来及诸菩萨身色端严，如是见已，复见劫尽大火烧已，见自脱已，心生欢喜，清净心生，如是愿言：『我亦如是度诸众生、我亦如是身色端严、我亦如是身作金色。【义解】十地菩萨亦如微雨在上而住，以自手救诸众生令解脱。众生见佛及菩萨身色端严、见劫火烧而自脱，心生欢喜清净，乃发愿：我亦如是度众、身色端严、身作金色。",

"【众生获果（种种）】』众生既起如是心已，有心解脱即时证得阿罗汉者；有见劫火心生厌离，或有证得须陀洹者、或有证得斯陀含者、或有证得阿那含者、或有证得阿罗汉者、或有证得缘觉道者、或有证得无生法忍、或有得上不退地者、或有得生四天王处、或有得生三十三天、或有得生夜摩天者、或有得生兜率陀天者、或有得生化乐天者、有生他化自在天者，有生梵天、梵辅、梵众，如是次第乃至有生阿迦尼吒；【义解】众生发愿已，依根机各得解脱：或证四果、或得缘觉、或无生法忍、或不退地，或生四天王乃至他化自在天，或生梵天、梵辅、梵众乃至阿迦尼吒天。",

"【获果（续）·知恩报恩】如是，有得转轮圣王、力转轮王、天竺小王；如是，大仙！乃至刹利、若婆罗门、若长者等。大仙当知：以此方便令见如来色身相已，自见己身生大怖畏。得解脱已，知如来恩、报如来恩，亲近如来，听闻正法。【义解】或得转轮圣王、力转轮王、天竺小王，乃至刹利、婆罗门、长者等。佛以如是方便令众生见佛色身、自见己身生大怖畏，得解脱后知恩报恩、亲近如来、听闻正法。",

"【不放逸·涅槃界入】既闻法已，如法修学不放逸行，以此方便令诸众生不入恶道。「又复，大仙！乃至几许十地菩萨彼眼境界、所有地界、复过于此诸众生界，彼诸众生见生死过，一切无余涅槃界入。大仙当知：以此因缘放劫尽烧。【义解】闻法已如法修学、不放逸行，如是令众生不入恶道。乃至十地菩萨眼所境界、所有地界，过此之众生界，彼众生见生死过而皆入无余涅槃界——以此为因缘，故放劫尽烧。",

"【光明炬思惟】」尔时，大仙名光明炬心即思惟：「此释迦子——六波罗蜜具足大人、第一胜人——不唤我字，称言大仙。我自试看是一切智、非一切智；我今实知是一切智，我今应当称其实名。」尔时，大仙名光明炬既思惟已，即白佛言：【义解】光明炬心中思惟：此释迦子（六度具足之第一胜人）不称我名而称「大仙」；我曾试看其是否为一切智，今实知是一切智，应当称其实名。思惟已乃白佛。",

"【问何处和合·佛答平等和合】「大功德聚无量智者！一切智者！更为我说彼诸众生何处和合。」佛言：「大仙！当知众生无处和合、当知众生平等和合，是名和合；当知众生一乘和合，是名和合；一切皆是菩萨和合，谓在无余涅槃界处。【义解】光明炬称佛实德，复问众生「何处和合」。佛答：众生无处和合，众生「平等和合」乃名和合，众生「一乘和合」乃名和合，一切皆是菩萨和合——即于无余涅槃界处。",

"【小河入海同味·众生平等】大仙当知：众生如是无处和合。「大仙当知：譬如种种小河、大河，入大海已皆同一味。如是，大仙！诸众生界诸漏尽已皆解脱味，一切平等，菩萨和合。「又复，大仙！若诸众生生死海中而和合者，我说彼合非是和合。【义解】明众生无处和合。如小河大河入海皆同一味，诸众生界诸漏尽已皆成解脱味、一切平等，是为菩萨和合；若于生死海中「和合」，佛说彼非真和合。",

"【飞蛾业缚喻】又复，大仙！譬如飞蛾，风吹和合，离风则散。如是，大仙！诸众生界迭互业缚，行地狱行生地狱中地狱和合。大仙当知：众生如是迭互业缚，行饿鬼行生饿鬼中饿鬼和合、行畜生行生畜生中畜生和合、行人天行生人天中人天和合。【义解】以飞蛾随风聚散为喻：众生迭互业缚，行地狱行则生地狱中「地狱和合」，行饿鬼、畜生、人天行则各生其趣而「和合」。",

"【地狱来生人中相】」大仙复言：「一切自在一切智者！世间应供！更为我说，云何得知此人中生某甲众生？何处和合而来生此？」佛言：「大仙！若有众生于地狱中和合而来生人中者，迭互相见则生恶心，彼此相憎；迭互相见，或有头痛、或放大便、或失小便。【义解】光明炬问：如何得知某人从何处和合而来生此？佛答：从地狱来生人中者，相见即生恶心、彼此相憎，或见面即头痛、或放大便、或失小便。",

"【地狱相结·畜生相】大仙当知：此是地狱和合众生人中生相。人中若有如是相者，于地狱中和合而来，应如是知。」大仙复言：「世界光明一切智者！更为我说，云何得知于畜生中彼此和合来生人中，复有何相？」佛言：「大仙！【义解】结地狱来生之相。光明炬复问：畜生中彼此和合来生人中，有何相？佛乃答，下段续说。",

"【畜生相·饿鬼相】若人前身于畜生中和合而来生人中者，迭互相见则生瞋心，更求过短，常相伺便，欲为恼乱。大仙当知：此是畜生和合众生人中生相。人中若有如是相者，于畜生中和合而来，应如是知。「又复，大仙！若人前身于饿鬼中和合而来生人中者，爱乐臭气，性贪饮食，悭惜不施；【义解】从畜生来生人中者：相见生瞋、更求过短、常伺其便欲为恼乱。从饿鬼来生人中者：爱乐臭气、性贪饮食、悭惜不施。",

"【饿鬼相（续）·人道相】于饿鬼中同处来者，见其富乐则生嫉心，希望他物。大仙当知：此是饿鬼和合众生人中生相。人中若有如是相者，于饿鬼中和合而来，应如是知。「又复，大仙！若人前身于人道中异处和合复为人者，彼人相见则生染心。【义解】从饿鬼同处来者，见他人富乐则生嫉心、希望他物。从人道异处和合复为人者，相见则生染心。",

"【人道相（续）·天来相】人中若有如是相者，本于人中和合而来，应如是知。」彼大仙人问言：「世尊！若天和合退生人中，彼有何相？复云何知？」佛言：「大仙！若人前身天中和合来生人者，迭互相见乐看不舍。人中若有如是相者，本于天中和合而来，应如是知。【义解】结人道来生之相。光明炬问：天和合退生人中者有何相、云何知？佛答：从天人中来生人中者，相见乐看不舍。",

"【和合因相结·微细我】「大仙当知：众生如是和合因相。」尔时，大仙名光明炬闻佛说已，心生欢喜，而白佛言：「世尊！若有不求一切智者，如是众生一切所作空无所获。」尔时，世尊告光明炬大仙人言：「如你所问众生身内微细我者，大仙当听：【义解】结众生如是和合之因相。光明炬闻已欢喜，言：若不求一切智者，其所作皆空无所获。佛乃为说「众生身内微细我」之义。",

"【生盲喻】若有分别得众生者，彼则分别众生细我。大仙当知：譬如有人生盲无眼，有人问言：『何者白色？』于意云何？彼生盲人不曾见色，能说如是一种色不？」大仙答言：「不能说也。」佛言：「如是，如是。【义解】明若有分别得众生者，即是分别众生之「细我」。以生盲人从未见色、不能说出白色为喻——结论下段续说。",

"【不见微细我·非阴界得众生】大仙！彼生盲人眼不曾见，故不能说。我亦如是，不见众生微细内我，是故不说。「又复，大仙！眼非众生；如是，非耳、非鼻、非舌、非身、非意得众生名。又复，大仙！非五取阴得众生名，非十八界、非十二分、十二因缘得众生名。【义解】如生盲人不见色故不能说，佛亦不见众生微细内我故不说。眼乃至意、五取阴、十八界、十二分、十二因缘皆不得众生之名。",

"【非空得名·念念不住】又复，大仙！亦非内空得众生名、亦非外空、非内外空得众生名。「大仙当知：眼念不住，变异不停；如是，耳、鼻、舌、身、意等皆念不住，变异不停。如是，大仙！五阴亦尔，一念不住，变异不停。如是，大仙！【义解】明亦非内空、外空、内外空得众生名。眼乃至意、五阴皆念念不住、变异不停——如是观察，其中无众生可得。",

"【三十六物·和合假名】」三十六种不净之物皆念不住，变异不停。如是等中无众生名。「又复，大仙！色物和合数名众生。若人思量分分观察，彼不得命、不得养育富特伽耶、亦不得人摩那婆等。「大仙当知：若有众生，如来不说四圣谛法；【义解】明三十六种不净物皆念念不住，其中无众生名；「色物和合」假名众生，若分分观察则不得命、不得「富特伽耶」、不得「摩那婆」等（皆假名而已）。若执有众生，如来则不说四圣谛。",

"【无众生则是如来·光明炬发愿】若無众生，則是如來。若不知法，如和集取、如心取得。」尔时，大仙光明炬言：「世尊！我光明炬自从今日求一切智。世尊！若一大劫为一日夜，数如是日三十为月，数如是月十二为岁，数如是岁以成一劫。【义解】明若无众生（之执）则是如来；若不知法则如和集取、心取得。光明炬乃发愿：从今日起求一切智；即使以一大劫为一昼夜来计，下段续说其忍苦之誓。",

"【光明炬发愿（续）】世尊！我宁如是无边劫中常住火坑。须弥楼山高大乃至阿迦尼吒，我宁如是无边劫中在彼山上念念自堕，投身在地。如劫火烧五处炽然，我宁如是无边劫中常以如是五火自炙。世尊！我宁忍受如是等苦，而终不能舍一切智，求一切智因缘精进，我不休息。【义解】光明炬誓：宁于无边劫中常住火坑、宁在须弥山至阿迦尼吒之高处念念自堕投身于地、宁受五火自炙——宁忍受如是众苦，终不舍一切智，求一切智精进不息。",

"【诸仙发心·眉间放光】」尔时，五通诸仙人等皆近世尊，复从座起白世尊言：「我从今日求阿耨多罗三藐三菩提，如力所堪发勤精进。」尔时，世尊即于仙人如是语已，眉间放光——其光名曰毗尼婆帝。此光出已，普照十方，彼十方处一切诸佛眉间亦放如是光明。【义解】五通诸仙皆近世尊、起座发愿：从今日求无上正等正觉、随力精进。世尊于仙众发愿后，眉间放「毗尼婆帝」光，普照十方，十方诸佛眉间亦放此光。",

"【六种震动·十方雨华】毗尼婆帝光明势力，令此大地六种震动，谓震、等震，动、平等动，起、平等起，西高东下、南高北下。十方一切诸佛如来在上雨华散此佛会，天鼓妙声甚可爱乐。乾闼婆王作五分乐供养如来、赞叹世尊，风吹天香以熏如来。【义解】毗尼婆帝光势力令大地六种震动（震、动、起，各分等与平等，及西高东下、南高北下）。十方诸佛在上雨华散此佛会，天鼓妙声，乾闼婆王作五分乐供佛赞佛，天香熏佛。",

"【供养如来】菩萨欢喜，以诸璎珞掷置空中在如来上，华香、烧香、妙鬘、涂香、散种种香、种种妙衣、幢盖、缯幡供养如来。诸天欢喜，于虚空中雨曼陀罗、大曼陀罗。一切大众心生欢喜，以己所著妙好衣服用奉如来。【义解】菩萨欢喜，以璎珞掷置空中如来之上，以华香、烧香、妙鬘、涂香、妙衣、幢盖缯幡供佛；诸天欢喜，虚空雨曼陀罗华；大众欢喜，以所着妙衣奉佛。",

"【光还入顶·须菩提请】尔时，此处释迦如来毗尼婆帝光明——上去乃至遍到阿迦尼吒诸天宫殿、下去乃至阿鼻地狱——如是照已，围绕十方诸佛世尊，然后还来入世尊顶。尔时，慧命须菩提以妙伽陀请如来曰：「朝日释迦子，放光照十方，此非无因缘，唯愿为我说。【义解】毗尼婆帝光上至阿迦尼吒天宫、下至阿鼻地狱，如是照已，绕十方诸佛，还入世尊顶。慧命须菩提以偈请佛：释迦子放光照十方必有因缘，愿佛为说。",

"【请偈（续）】见人主奋迅，此众皆生疑；亦有欢喜意，清净心希望。或有人合掌，或有言善哉，唯愿如来说，除断众生疑。空中帝释王、梵王世界主，心皆生欢喜，赞叹实功德。诸天虚空中，雨种种妙华，多有诸音乐，不击自然鸣。【义解】偈续：见佛奋迅，大众生疑亦有欢喜希望者，或有人合掌、或言善哉，愿佛为说以断众疑。空中帝释、梵王皆欢喜赞叹实德；诸天虚空雨华、音乐不击自鸣。",

"【光明炬当来成佛】」尔时，世尊即告慧命须菩提言：「你须菩提！见光明炬大仙人不？须菩提！是人未来月光世界当得成佛，号毗婆尸如来、应、正遍知，此贤劫中一千如来最后如来同时出世。须菩提！若有众生闻毗婆尸如来名者，皆蒙威力——如如意珠，须者皆得。【义解】佛告须菩提：此光明炬大仙人未来于月光世界成佛，号毗婆尸如来，与贤劫千佛之最后如来同时出世。闻其名者皆蒙威力，如如意珠随须即得。",

"【众得利益·诸三昧】须菩提！八万四千诸大仙人闻此法门得不退地。须菩提！是等一切，弥勒世尊佛法之中当得十地，复三百劫生自灯明如来、应、正遍知佛之世界。「须菩提！无量菩萨闻此法门，即时皆得首楞严三昧、音声智三昧、受胜位三昧、如幻三昧、界胜三昧、慧王三昧、海藏三昧、地藏三昧、虚空藏三昧、得光明三昧。【义解】八万四千大仙人闻此法门得不退地，并于弥勒佛法中当得十地、三百劫后生于自灯明佛世界。无量菩萨闻此法门即得首楞严等十种三昧。",

"【天得无生忍·众发心】须菩提！有恒河沙亿数诸天，一切皆得无生法忍；无量比丘、比丘尼、优婆塞、优婆夷证阿罗汉。须菩提！恒河沙数天、龙、夜叉、乾闼婆、阿修罗、迦楼罗、紧那罗、摩睺罗伽、人非人等，发阿耨多罗三藐三菩提心。【义解】恒河沙亿数诸天皆得无生法忍；无量四众证阿罗汉；恒河沙数天龙八部人非人等发无上正等正觉之心。",

"【结放光·如来出舌】「须菩提！见是因缘，如来放此毗尼婆帝光明普照。」尔时，世尊怡然微笑，出自舌根遍覆己面。彼舌根中出无量色、出种种色——所谓青、黄、赤、白等色、紫颇梨色——遍至无量无边世界，然后还来入世尊足。【义解】明由此因缘，如来放毗尼婆帝光普照。世尊怡然微笑，出舌根遍覆其面，舌根中出无量种种色光（青黄赤白、紫颇梨色），遍至无量无边世界，还入世尊足。",

