"【佛说总持章句】「设此十人一心受学佛所颁宣，修是法律复为沙门，勤讽诵斯总持章句，可成道耳。何谓总持章句？「『修清澄，鲜洁句，清且凉，无所授，亦无造，无所得，遵速疾，取新生。奉精进，礼行步，勤修行，智晓了，主观察，无所起，去患难，游慕便。【义解】佛答：若此十人一心受学佛之所宣、修此法、复为沙门，勤诵此总持章句，即可成道。下即总持章句之文（修清澄、鲜洁句、清且凉……游慕便），下段续说章句余文。",

"【章句（续）·七日修·见千佛消罪】举轻便，普清净，无不净。』」佛告无怯行菩萨：「此等十人以讽诵是总持章句，而于七日修恩德无所下使无色，不怀瞋恚，安详不久游无所作，无瑕秽心平等舍所有，离五阴释不净意念佛。诸族姓子！设能如是奉遵道教，十方世界各有千佛，示现其前令自见之，剋心自责归命圣尊，罪殃可除逮成道慧。【义解】结总持章句余文。佛告：十人讽诵此章句、七日修恩德、不瞋、无瑕、心平等、舍所有、离五阴、念佛，若能如是奉教，则十方世界各有千佛示现其前，剋心自责归命圣尊，即可除罪成道。",

"【十人出家诵持·见千佛·超劫不退】诸族姓子！时闻佛教等顺法律，即舍家业出为沙门，讽诵此总持章句，如圣所诲，昼夜七日精进奉行，竟七日已，辄见十方各有千佛，分别为说消罪之业。应时皆得修普智行总持之门，超三十六劫生死之难，逮不退转，当成无上正真之道。【义解】十人闻佛教、顺法律，舍家出家、讽诵章句，昼夜七日精进；满七日后即见十方各有千佛，为之说消罪之法，应时得普智行总持门、超三十六劫生死、得不退转、当成佛道。",

"【佛示宿世人物·劝莫求他短】」佛告无怯行菩萨：「尔时，月施国王者，今现阿弥陀是；其辩积者，阿閦如来是；十长者子，今此十人族姓子是也。故，无怯行！其有志学菩萨乘者，殷勤奉修如佛所教，住于正法舍其无明，慎无伺求他人之短也。【义解】佛示宿世人物：彼时月施王即今阿弥陀佛，辩积菩萨即阿閦如来，十长者子即今此十族姓子。故劝：志学菩萨乘者应殷勤奉修如佛所教、住正法舍无明，切莫伺求他人之短。",

"【四事行严净佛道】」佛告无怯行菩萨：「有四事行，能遵修者，严净佛道。何等为四？一曰、奉行空事，常有慈心，无害众生；二曰、菩萨愍敬同学，不为轻慢；三曰、为人说法以轻惠施，无所悕望；四曰、志常专一，不怀供养衣食之心。【义解】佛说四种能严净佛道之行：一、奉行空事而常慈心不害众生；二、愍敬同学不轻慢；三、为人说法而轻施无所希望；四、志常专一、不怀供养衣食之心。",

"【四事行颂（一）】是为四。」佛时颂曰：「其志常乐笃信空无，修治清净最胜之道，犹如日光随时宣明，已得佛道所照过彼。未曾有人知其瑕阙，为人圣德普忍一切，如是清净柔顺之场，弃捐贡高堪任无量。一切所有上妙衣服，常当以施志佛道者，亦不从人悕望供养，是为佛道清净之品。【义解】佛以偈颂赞此四行：志乐笃信空无、修清净最胜道，如日光随时宣明；普忍一切、弃贡高、堪任无量；以上妙衣服施志佛道者而不望供养，是为佛道清净之品。",

"【四事行颂（二）·四事疾得佛道】以不悕冀施无量法，恒修愍哀念于众生，志性常怀恩德之义，是为严净诸佛之道。假使乐奉一切诸圣，若欲供养无欲经典，常当承事无极佛道，斯三宝者皆由中生。」佛告无怯行菩萨：「复有四事疾得佛道。【义解】颂续：不悕望而施无量法、恒修愍哀念众生、常怀恩德，是为严净佛道；欲奉诸圣、供无欲经典者，当承事佛道，三宝皆由中而生。佛更说四事速得佛道，下段续说。",

"【四事疾得佛道·颂】何谓为四：一曰、爱乐明经好于大乘；二曰、远离爱欲不习放逸；三曰、常修济贫匮供以所乏；四曰、能兴法财七业施人。是为四。」佛时颂曰：「爱乐法师，志慕大乘，远离爱欲，修清净行，愍伤厄贫，济诸危难，常以七财，施不懈道。【义解】明四事疾得佛道：爱乐明经好大乘、远离爱欲不放逸、常济贫乏、以法财七业施人。佛以偈颂重申：爱乐法师、志慕大乘、远离爱欲、愍济贫难、以七财施精进者。",

"【四事疾得佛道（四无量）】」佛告无怯行菩萨：「复有四事疾得佛道。何谓为四：一曰、常行大慈，哀诸群生；二曰、常行大哀，为之雨泪；三曰、常行大喜，和颜悦人视于众生；四曰、常行大护，救度三界生死之患。是为四。」佛时颂曰：【义解】佛说又一四种速得佛道之事，即四无量：常行大慈哀诸群生、常行大哀为之雨泪、常行大喜和颜视众生、常行大护救度三界生死。下以偈颂赞之。",

"【四无量颂】「常行于大慈，愍伤众生类，念欲成就之，如母育其子。大哀游终始，不畏诸患难。五趣如泡沫，愍之为雨泪。和颜察众生，以法而乐之，示以离众苦，无痛长安隐。委靡随五趣，方便示所宜，使度三界恼，获致无上道。【义解】颂赞四无量：大慈如母育子、大哀游生死不畏患难、见五趣如泡沫而雨泪、和颜以法乐众生、随五趣方便示宜令度三界恼——如是则获无上道。",

