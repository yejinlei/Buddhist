"【佛寺斋宿·问经之仪】在佛寺中斋宿，不得卧于沙门之绳床、榻橙、机上及被中（他人卧处），若卧皆为犯戒。人请道人（受供），道人未食时，不应问经；道人若为说，有罪。道人食毕，乃得问经道。不持戒、不行道，而居于佛寺中，不如自己投入釜中——釜中只烧一身罢了。不持戒、不行道，却在佛寺中，则烧无数身。【义解】明佛寺斋宿之威仪戒相；次明请道人问经须待食毕；并说无戒无行而居寺，受用信施如自投热釜、烧无数身。",

"【道人五因缘请不可行】道人亦应说经，人有问经者，不应相违（当为解说）。人持物品上奉道人，不应（此时）问经，其后乃得问。受物时亦不应说经，若说则有罪。道人有五种因缘，（招请）不可前往：一者，请甲不如请乙（供养有厚薄），不当行；二者，请乙不如请甲，不当行；三者，若请甲，甲言「为故（因缘）而请乙」，乙不当行；【义解】明问经、受物之仪；次列道人受请不可前往之五种因缘，下段续说。",

"【请不可行（续）·止有三辈·睡眠】四者，我从远方而来，当时不请，其后乃请，不应行；五者，若怨家不相便（与己）同里相近，或同在坐中，不当行。何以故？（盖）睡眠乃用以止（息）意之故。止有三种：一者，生死之行止；二者，道行之意不至，于生死因缘之意中止故。又喜睡眠之人喜睡眠，有三种因缘：【义解】续说受请不可行之第四、五缘；次释「止」有三辈（生死止、道行中止）；末列喜睡眠之三因缘，下段续说。",

"【睡眠三因缘·八行除睡眠】一者，多食；二者，饮；三者，忧。又有三种因缘：一者，身休息；二者，余意极（困）卧出更受意；三者，留受（睡习）之故。人睡卧之中有意、有识、有寿、有命、有喘、有息，一昼日凡三万六千五百息，小（差）完等罢了。有八种行能除睡眠：【义解】续说喜睡眠之因缘；明睡卧之中虽有识寿命息，然一昼夜不过三万六千五百息；末标八行除睡眠，下段续说。",

"【八行除睡眠·身口意空得福得罪】一者，少食；二者，坐；三者，立；四者，经行；五者，诵经；六者，视星；七者，洗面；八者，观骨。若不解（犹困）当念诸善事，意已转，当自还（守）物（所缘）。欲得福道、定意之故，得念余事，已则自解。有身得福，有口意得福，有空得福；【义解】列举除睡眠之八行（少食、坐、立、经行、诵经、视星、洗面、观骨）；次说身、口意、空三种得福，下段续说。",

"【空得福得罪·口意罪】亦有身得罪，亦有口意得罪，亦有空得罪。「空得福」者，谓梦中得金银、珍宝、豪贵、富乐，这就是空得福。「空得罪」者，梦中有人来杀人，或侵扰人，这就是空得罪。以口教人作恶，或劝人杀人，后来因缘横遭他人捶打，这就是坐于口之罪（及）意；【义解】续说身、口意、空三种得罪；举例释明「空得福」（梦中得财宝）、「空得罪」（梦中杀人侵人）；并说口教人作恶、劝人杀人者，现世横遭捶打。",

"【意罪·梦之因缘】自作因（恶）为缘，（致）为他人所伤杀，这就是意罪。人之所以有善恶之梦者：（如）欲饮食而无有物，但有意念，便因（此）梦好饮食。意欲杀人，便因梦有人来杀之。皆有因缘，或前世、或后世、或现世。后夜（上夜）之梦者，（应验于）朝暮现在之事。梦中所为之善恶，皆是意所作，其所对之境也俱是意。【义解】明自作恶因致被伤杀者为意罪；次释梦之因缘——意有所欲，则因梦见其事，或应前世、后世、现世，皆意所作。",

"【意与见无异·死后坐住·堕龙四缘】譬如有人径直取一物观视已，便藏去之。虽（后来）不见（其物），意念即来，与见之无异。前世所作，便自与今世之意作对。人死后又坐起（而不即坏）者，因生时喜作鬼以恐吓人；或（于）世间得病之时，语边上人「呼我觉（醒）」。以是之故，已死复起坐住。堕入龙中有四种因缘：【义解】明意想留存如见物，前世所作与今世之意相对；次说人死后仍坐起之因（生前喜作鬼吓人、病时令人呼觉）；末标堕龙四因缘，下段续说。",

"【堕龙四果·角罪彩衣罪】一者，多布施；二者，多瞋恚；三者，轻易（轻慢）人；四者，自贡高坐。这就是四事（能令）作龙。其上头（第一）一事得福（得龙之福报），后三事得龙身（得龙之形）。《律经》说：诸畜生有角者，是前世喜著头角、横叉以为美，得角之罪，受畜生身。或有异色者，是为著彩衣、怀恶意，贪以为好，故得此罪。【义解】明堕龙四因缘（施、瞋、轻人、贡高），施得龙福、余三得龙身；次引《律经》说畜生有角、异色各由前世所好之罪。",

"【鹦鹉朱唇·女人长裙·身疮之罪】鹦鹉有赤唇、赤足者，是前世喜著彩衣、涂朱唇。（如）女人喜著长裙，后世堕入雉、鸐（长尾之鸟）中而成长尾，皆是过世（前世）所喜，今世因之而得此形。人与畜生身体多疮者，是前世以木竹刺生鱼、畜生之口，故今世得此罪报。若人、畜生（彼此）视见，有欢喜者、有瞋恚者，是前世相与为善，今世相见便喜；【义解】明畜生之色形皆由前世所好（朱唇彩衣得赤唇、长裙得长尾）；次说身多疮者由前世刺伤鱼畜之口；末说相见喜嗔系于前世善恶之缘。",

"【前世善恶相见喜嗔·畜生恶喜】前世（相与）不可（不善）之故，今世相见不喜。作畜生（者，以）恶（业）为福，得食便喜，这就是「恶喜」。谓其人前世作恶已便喜，故得此（受食而喜之）福。畜生不得美食，有三种因缘：一者，不曾习（不习惯）；二者，善福已尽；三者，罪使之自然。畜生也欲求色、声、香、味、细滑，也自相与语，只是不能如人语罢了。【义解】续明相见喜嗔系前世善恶；释「恶喜」（前世作恶而喜，今生受食便喜）；并说畜生不得美食三缘，及畜生亦有五欲、能相语而不同人语。",

"【女人有须·鱼鳖无声·猕猴业】女人有须者，是前世从羊中、鸡鹜之来（而受此身），以此之故有须。鱼鳖无声者，是前世断人语头之故。鱼生（胎）不即生，乃七日后乃生；着于草木在干燥之处四五十岁，得水乃生。其所以多子者，因作恶之人多，罪同者俱生。好瞋恚、嫉妒、痴、淫，行此四者，堕猕猴之中；【义解】说女人有须（由羊鸡之报）、鱼鳖无声（断人语头）、鱼之久置待水而生、多子（恶多同业），及行瞋嫉痴淫者堕猕猴。",

"【猕猴业（续）·倡伎杀祠·劫衣之殃】作事不安谛（不谨慎）者，也堕猕猴之中。人好作倡伎（歌舞戏乐），后世堕入鸟、虫、猕猴之中。喜学杀（生）祠祀者，后世堕入羊中。何以故？（以其如）断人头、剥皮、解（肢）。或前世喜劫人，解取人之衣被，故得此殃。虫（如蚕）也是前世劫人、解取人衣被，令人寒冻趋火；【义解】续说猕猴业（不安谛、倡伎）；次说喜杀祠祀堕羊、劫人衣被及虫（蚕）受吐丝自冻之殃，皆由前世夺人衣被。",

"【愚痴喜杀作猪等·驴长耳】故（虫）自己先受此殃，吐丝自冻，入汤火中而死。愚痴喜杀者，后世作猪。惊怖人者，后世作鹿。多贪嗜美（味）者，后世作蝇。好捶打人者，后世作驴。其所以长耳者，是（前世）好挽（揪）人之耳。畜生好搏击人耳，或（因）前世（为）征卒。何以故？一卒传令，余卒皆作声（相和）；【义解】续说虫（蚕）吐丝自冻之殃；次列愚痴喜杀作猪、惊怖人作鹿、贪美作蝇、捶人作驴，并释驴长耳由挽人耳（如传令相和）。",

"【负债作牛·牛破蹄马完蹄】一驴鸣，余驴亦鸣（相和）。（前世）负债不偿者，作牛。牛之所以破蹄者，有二因缘：一者，负债；二者，好著木屐以为美。马之所以完蹄者，有二因缘：一者，负债；二者，好著木舄（木鞋）以为美。有六人共为伴侣，俱堕地狱之中，同在一个釜中，皆欲诉说本（所造之）罪：【义解】明负债不偿者作牛、作马；牛破蹄、马完蹄各由负债及著木屐木舄之好；末引出六人共堕狱釜、各欲说罪之事。",

"【六人共堕地狱釜·佛笑目连问】一人说：「沙」，二人说：「那」，三人说：「持」，四人说：「涉」，五人说：「姑」，六人说：「陀罗」。佛见之便笑，目连问佛何以笑？佛言：「有六人为伴，共在地狱釜中，各欲自说，而汤沸踊跃，不能得再（次）语，各出一语便复沉没。【义解】承上，佛为目连说六人共堕狱釜之由：彼等各欲自说本罪，而沸汤踊跃，一语即没，不能再说；其吐字之音各有所指，下段方解其语意。",

"【六人各说本罪（沙那持涉）】第一人说「沙」者：（其意谓）世间六千亿万岁，在地狱中只当一日，何时方能尽（此罪）？第二人说「那」者：（谓）无有期限，也不知当何时得脱。第三人说「持」者：（谓）咄咄！当用此生来治理生计，如此而不能自制其意，过世（前世）我所（贪求）多少而不知厌足。第四人说「涉」者：（谓）我治理生计极为至诚，却也令我的财产归属他人，我（因此）得受苦痛。【义解】承上，佛为解说六人所吐之语音：一沙、二那、三持、四涉，各表狱中无尽、无期、贪治生不知足、勤治生而财产归他之慨，下段续说第五、六。",

"【六人各说本罪（姑陀罗）·佛说四关】第五人说「姑」者：（谓）谁当保我从地狱中得出，便不复违犯道禁，得上生天界受天下之乐？第六人说「陀罗」者：（谓）此事上头（当初）本不为心所计度，譬如驱车失了大道，误入邪道而折损车辐，悔已无所复及。」佛说四关：从世间上至第六天为「死关」，从第七天上至十八天为「空关」，从十九天上至二十三天为「非常关」，从二十五天上至二十八天为「出关」。【义解】续说第五人「姑」、第六人「陀罗」之语意；次立「四关」：死关（至六天）、空关（七至十八天）、非常关（十九至二十三天）、出关（二十五至二十八天）。",

"【出四关·三界分齐】出于此四关，即为「出要」。极福不过二十八天，极恶不过阿鼻泥犁，其余之殃罪，皆有多少不等。从一事便生三毒，从三毒便有三恶道；若无三恶道，人亦皆得道。从阿鼻大泥犁至六天同为一界；从七天上至十九天同行四等心（慈悲喜舍），又为一界；【义解】明出四关即出要；极福、极恶各有其极；三毒生三恶道，无恶道则皆得道。次分界：泥犁至六天为一界，七至十九天（行四等心）为一界，下段续说。",

"【三界次第·欲色无色界】从二十五天（行）非常、苦、空、非身，上至二十八天，又为一界。不脱二十八天、三毒未尽者，复下作人，往来三界，欲求出要，应当灭（其）思想。从阿鼻摩诃泥犁上至第六天为欲界；从七天上至十九天为色界；从二十五天上至二十八天为无有色界——无有思想，亦有思想。【义解】续说二十五至二十八天（观非常苦空非身）为一界；明三毒未尽者仍下生为人、往来三界，求出要当灭思想。次立三界：欲界（泥犁至六天）、色界（七至十九天）、无色界（二十五至二十八天）。",

"【生死界无为界·三界三处】从阿鼻泥犁以上至二十八天为生死界；过二十八天，为无为界。断贪淫，乃到色界；断瞋恚，堕无思想界；断愚痴，乃到要出（究竟出离）。三界有三处：一者，从阿鼻泥犁上至六天，为贪淫处；二者，从七天上至十九天，名为行色著；【义解】明生死界（泥犁至二十八天）与无为界（过二十八天）；断贪、瞋、痴各到色界、无色界、究竟出。次立三界三处（贪淫处、行色著），下段续说。",

"【三处·贪欲喜色·三活】三者，除（初）四天，上至阿那含，从二十五天上至二十八天，无有思想亦有思想，名为行无有色。这就是三处，堕生（死）、死转而行色著。譬如火光但可见，不可得执持。在贪欲处，在喜色处，这就是三处。从泥犁、畜生、饿鬼，贪淫色当出向（而求脱），三活（三有之生）在（其）愿。【义解】续说三界三处之第三（行无色）；以火光可见不可持喻行色著；并明从三恶道贪淫色者当求出离，三有之生系于其愿。",

"【道要三本·二十八天不脱三因缘】何等为道要？有三本：有恶本，有善本，有道本。地狱、畜生、饿鬼，这就是恶本；从人中上至第六天，这就是善本；从第七天以上出十二门，这就是道本。已到二十八天而不得脱者，有三种因缘：一者，贪；二者，有痴；【义解】立「道要三本」：恶本（三途）、善本（人中至六天）、道本（七天以上出十二门）；并明到二十八天仍不得脱之三因缘（贪、痴、意），下段续说。",

"【出十二门·断三毒·阿那含】三者，有意。故不得脱。已出十二门，应当愿「无有意」。三毒不断、不上（得）脱者，以其未尽之故。二十八天何以（得至）？先身本在世间之时，不贪身、散意之故，断外七事；上（至）第六天受福，断内三事。上十八天上，从二十一天为四处，属阿那含。【义解】续说第三因缘「有意」；明出十二门当愿无意、三毒不断则不得脱；并释得至二十八天之由（不贪身、断内外事），及二十一天以上四处属阿那含（不还果）。",

"【十善十恶生处不同·细微善恶】行十善有生第一天上者，有生第六天上者，作善有多少，故（所生）不同处。行十恶有入地狱者，有入畜生、饿鬼者，作恶有轻重，故不同处。行善又得恶（报），行恶又得善（报），善中有小恶，恶中有小善，微细而不可见。善中无小恶，亦不再堕恶中；【义解】明十善、十恶随所作多少轻重而生处不同；并说善恶交杂、大小相含，微细难见；善中无小恶者不复堕恶，下段续说。",

"【恶中无小善·化生因缘】恶中无小善，也不得（从恶）而出。极恶极恶不过阿鼻泥犁，极善不过二十八天，以不觉知微细之意故，不得脱。一切从行十善得生天上人中。天人之所以化生者，本在世间之时不向（贪）色，觉知恶露不净，由此得化生；若（心）向于（色）意，便当更受女子胞胎。【义解】续明恶中无小善者不出离；极恶、极善各有其极，不觉微意则不得脱。次说行十善生天人、天人以不向色、觉不净而化生，向色则受胎生。",

"【诸天化生五缘·命欲绝持意】诸天得化生，有五种因缘：一者，不近女人；二者，意不起；三者，不愿小儿；四者，喜独坐；五者，不用世间。不贪身，也得化生。人命欲绝之时，当持（其）意，念（其）息；意者，系着于喘息，有时（而住）。从第一天以上，是（以）意息观身有三十二物者，计（数之）：【义解】明诸天化生五缘（不近女、意不起、不愿儿、喜独坐、不用世间）；次说临命终时当持意念息，及观身三十二物之起，下段续说。",

"【观身三十二物·四大】发、毛、齿、骨、皮、肉、五藏，此十一事属于地；泪、涕、唾、脓、血、肪、髓、小便，此七事属于水；温热、注（润）、消食，此二事属于火；风有十二事。此三十二物皆从地、水、火、风而出。何等为地？人生从谷之精气，谷为地，意为种，精气为水，两（者）便合，故生身。【义解】列举身中三十二物及其属地、水、火、风之数；并释「地」（谷精气）、「水」（精气）和合生身之理。",

"【一衣一食养气·身非身】求一衣、一食，是为养（其）气，护（此）主人之身。（此身）本无之故，灭尽无常。得道者，便知身非身，念身不久，终当死败。意为人（之）种，便（当）守意一心。愚痴之人不能守护魂魄神，只养四大（四柯），为色味所欺，谓身为我，计（度）而不知其恶，一切从身而起身、食、贪味，便堕于苦，往来生死而不得脱。【义解】明一衣一食只为养身护命，此身本无、灭尽无常；得道者知身非身；愚人养护四大、执身为我，从饮食贪味而堕苦、轮回不脱。",

