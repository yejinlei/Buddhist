"【劫烧·一切智】少有分是无常、少有分是常。若如是者，是诸如来则亦不成为实语者。若一切无常，无为法中不可思量者，是故如来得名一切智。」尔时，大仙人闻是语已，回首顾语自诸弟子言：「你知之不？此瞿昙者，真成是于一切智也。【义解】劫尽不烧则法界有常、无常二分，如是则如来不成实语者；一切法无常、无为法中不可思量，故如来得名一切智。威灯光闻已，回顾弟子赞叹：此瞿昙真是一切智。",

"【劫烧为方便·受摄受】」尔时，世尊复更重告大仙人言：「若劫尽时一切大地不被烧者，不得分别此是初时、此是末时，亦复不知好丑业果、善恶等报。你当知之：此劫烧时焚荡尽者，是诸如来大方便力之所为也。所有众生若能闻信劫当烧尽、洞皆燃者，尔数众生诸如来边受诸摄受。【义解】佛告：若劫尽时大地不烧，则不能分别初末之时、不知好丑善恶业报。故劫烧焚尽乃如来大方便力所为——众生闻信劫当烧尽者，即于如来边受诸摄受。",

"【蟒蛇喻·金火喻】你当知之：如大蟒蛇身分所有眼、耳、口、鼻，以毒力故，悉能摄受一切飞走杂类众生。应知如来亦复如是，以布施、爱语、利行、同事法『毒力』故，悉能摄受调伏一切诸众生也。大仙人！又如有人以其金鋌置在火中——不以瞋恨置于火中，以不熟故欲令成熟——为欲成就真宝物故、为令价大得多财故，置金火中连椎交打、柔软清净。【义解】如大蟒蛇之眼耳口鼻以毒力能摄受一切飞走众生，如来亦以四摄法（布施、爱语、利行、同事）之「毒力」摄受调伏一切众生。又如以金置火（非瞋金，为令熟成宝）连椎交打令柔软清净。",

"【众生因劫烧调伏·仙人问】如是，一切诸众生辈莫不皆因诸佛如来放劫尽烧而得调伏。如是劫尽大地烧时，实无众生受苦恼者。」大仙人言：「世尊！稀有。可得劫尽火焚烧然大地坏时，无一众生受苦恼者？」佛言：「不也。大仙人！【义解】明一切众生皆因如来放劫尽烧而得调伏——劫尽大地烧时，实无一众生受苦恼。威灯光叹稀有、问是否无一众生受苦，佛乃答，下段续说。",

"【十地菩萨救度】诸佛如来不令一众生受逼切恼。何以故？大仙人！譬如十方微细雨渧，彼诸雨渧宁为多不？」大仙人言：「甚多。世尊！」佛言：「大仙人！诸佛如来、十地菩萨倍多于彼。当尔劫尽大地烧时，于上虚空中以慈悲智慧身手解救众生，不令有苦而触身也。【义解】佛明诸佛不令一众生受逼恼。以十方微细雨滴为喻（甚多），佛与十地菩萨倍多于彼——劫尽大地烧时，于虚空中以慈悲智慧身手解救众生，不令有苦触身。",

"【众生见佛发愿·获益】所以者何？以彼诸佛如来、一切菩萨，妙身广大、相好端严，众生见者无不欢喜，生正信心，唱如是言：『我等愿于未来世中皆得成就如是除拔，还得成就如是形色、如是相好端严之身。』当于是时，又有心解脱已，得阿罗汉果者；【义解】释何以能救：佛与菩萨妙身广大、相好端严，众生见者无不欢喜、生正信心，发愿未来成就如是拔济与端严之身。当时或得心解脱、证阿罗汉果，下段续说。",

"【获益（续）】或有厌离心生，得须陀洹果、斯陀含、阿那含果证者；或复有得无生法忍者、有得不退转地者；有得生于四天王天上者，有得生于忉利天上、夜摩天上、兜率天上、化乐天上、他化自在天上者，略说乃至有得生于阿迦腻吒天上者。【义解】续明获益：或证四果、得无生法忍、得不退转地，或生四天王天乃至忉利、夜摩、兜率、化乐、他化自在天，乃至阿迦腻吒天。",

"【获益（续）·知恩报恩】「当于是时，所有一切大转轮圣王、小转轮王，及诸方域粟散小王、大仙人等，乃至刹利大家、大婆罗门、大富长者，如是次第以见如来妙色之身。复见己身于大恐怖生死海中得解脱故，生大踊跃欢喜之心，于如来边起知恩心、起报恩心。【义解】续明：一切转轮圣王、小王、大仙人乃至刹利婆罗门长者，次第见如来妙色身；又见自身于大恐怖生死海中得脱，生大欢喜，于如来边起知恩报恩之心。",

"【不放逸·入涅槃者倍多】于如来边听受法已，各各皆于十业道中作不放逸行，以是方便力因缘故，于十恶道中速得舍离。「当于是时，所得十地大菩萨者，以此菩萨眼道所及照了之处大地微尘，彼等微尘虽复甚多，而彼时节诸众生界，乃至知于烦恼体性污染不净，从于无为涅槃道中入彼无余涅槃道者，倍多于彼。【义解】闻法已各于十业道作不放逸行、速离十恶道。十地菩萨眼道所及处大地微尘虽多，而彼时入无余涅槃之众生界更多——以明度生之广。",

"【结·众仙惊怪】你今当知：诸佛如来为如是等大利益故，方便显示劫烧尽也。」尔时，一切大仙人等闻是语已，生惊怪心：「呜呼奇哉，甚大稀有！大德释子向者唤我为大仙人、发我寿命，我时虽闻如是之事，犹谓非真一切智也；【义解】佛结：诸佛如来为如是等大利益故，方便显示劫烧尽。诸仙闻已惊怪：大德释子先前唤我为大仙人、说出我寿命，我时虽闻犹谓非真一切智。",

"【众仙称实·问聚集】今以世间难中之难具足施已，我今始知释子真是一切智也。我于今者以于真实名号称之。」尔时，一切大仙人等即发是言：「大功德聚者！无边大智者！知一切智者！我见众生持业星流各各别异，何处得成真实聚集？【义解】诸仙谓：今以世间难中之难具足施已（证验已足），始知释子真是一切智，乃以真实名号称之；并请问：见众生持业星流各各别异，何处得成真实聚集？",

"【佛答真聚集】唯愿世尊为我解说，令得开悟。」尔时，世尊即告大仙人言：「你大仙人！当知无有时、方、亦无处所令得众生真聚集也。大仙人！惟平等中众生得聚集、一乘道中众生得聚集、菩萨地中众生得聚集、无余涅槃界中众生得聚集。【义解】佛答：无有时、方、处所令众生真聚集；唯于「平等中」「一乘道中」「菩萨地中」「无余涅槃界中」众生得聚集。",

"【众流归海一味·解脱味】你今当知：如有众流、河泉、渠渎，一切川源皆归大海，入大海已得一味住，谓一咸味无差别也。大仙！你今当知：所有众生界若得漏尽者，一切彼处于解脱味中会一味住。你今当知：我虽说言烦恼平等中众生得聚集者，亦非聚集也。【义解】如众流河泉皆归大海、入海成一咸味无别；众生界若得漏尽者，皆于解脱味中会一味住。佛谓虽说「烦恼平等中众生聚集」，亦非真聚集。",

"【业风缚·蚊虫喻】所以者何？譬如大风旋起，吹诸蚊虫一切聚集；若风定已，各各星散。如是，诸类一切众生各各皆为业风缚故，或堕地狱中彼辈得聚集；业风缚故，或时饿鬼中彼辈得聚集；或在畜生中，彼辈得聚集；如是等。【义解】如大风旋起吹蚊虫聚集、风定则散；一切众生为业风所缚，故或于地狱、饿鬼、畜生中各各「聚集」——此皆非真聚集。",

"【仙人问聚集相】」仙人复言：「一切识一切智者！愿为我说：若有如是如是等辈已于先世俱人中生，共同聚集，今日现在云何可知？乃至一切——若在畜生、若在饿鬼——已于先世曾聚集者，云何可知？愿为解说。」佛言：【义解】威灯光请问：若诸众生先世于人中共聚，今现在云何可知？乃至先世在畜生、饿鬼曾聚集者云何可知？佛乃答，下段续说。",

"【地狱中来相】「大仙人！所有众生，若先世时共地狱中曾聚集者，于现在世若相见时，心不欢喜、生瞋结恨，或时头痛、或复失禁大小便利，当知是辈已于先世地狱之中曾聚集相。若有如此相貌现时，应当觉知：『彼与我身决定已曾于地狱中一处居来。【义解】从地狱中来者，相见时不欢喜、生瞋结恨，或头痛、或失禁大小便利——即先世曾于地狱中共聚之相。见此相即应觉知：彼与我曾于地狱一处同居。",

"【畜生中来相】』」时大仙人复白佛言：「一切能人证大寂者！一切智者！更为我说：若先世中曾在畜生共千万身一处来者，云何可知？」佛告大仙人：「若彼等辈生人中者，各相见时结成瞋怨，常觅其便：『我当何处觅得其便？【义解】威灯光更问：先世于畜生中共处来者云何可知？佛答：从畜生来生人中者，相见结成瞋怨、常觅其便（寻隙恼害）。",

"【畜生相（续）·饿鬼相】』是名相貌在畜生中一处同居多身之相，应知：『决定我已共彼在畜生中一处居来。』「若饿鬼中一处居来者，常乐臭秽，复多贪食息，设欲与他，心不去离，生悭贪着；或复见彼富贵势力，心生嫉妒，常复欲得彼人财物。【义解】结畜生来相。从饿鬼来者：常乐臭秽、贪食、悭贪不舍，见他人富贵则生嫉妒、欲得其财物。",

"【饿鬼相（续）·人道相】见是相时，决定知彼与我同在饿鬼之中一处居来。「若有先世同在人中共一处者，于现世中若相见时更生欲心。」尔时，威灯光大仙人复白佛言：「若先世时共在天中同一处者，今世人中若相见时云何可知？【义解】结饿鬼来相。先世同在人中来者，相见生欲心。威灯光更问：先世共在天中者，今世人中相见云何可知？下段佛答。",

"【天中来相·大仙欢喜】」佛言：「大仙人！若有先世共天中生，现在人中若相见时，各以眼道远相摄取，共相眷爱。若有是相，决定天中共聚集来。若以如是相观察者，得知众生聚集相也。」尔时，大仙人闻是语已，欢喜踊跃，生希有心，即白佛言：【义解】佛答：先世共在天中者，今人中相见各以眼道远相摄取、共相眷爱——即天中共聚之相。以此相观察，得知众生聚集之相。威灯光闻已欢喜踊跃、生稀有想而白佛。",

"【众生大虚诳·内体微细】「世尊！我今始知彼众生辈成实可言大虚诳也，云何迷没不求修学萨婆若也？」尔时，世尊更复重告大仙人言：「你向问我内众生体有几微细者，大仙人！若有众生体可得者，彼众生体可得作分微细、长短。【义解】威灯光叹：始知众生辈实可称「大虚诳」，何故迷没不求修学一切智？佛乃答其「内众生体微细」之问：若有众生体可得，方可分其微细长短。",

"【生盲喻】你今当知：譬如有人从生盲瞽，复有一人问彼人言：『人者！白色为似何者？』于你意云何？彼既不见，可得说言此色如是、如是色也？」仙人答言：「彼人既不明了见色，何敢如此决定判也？」佛言：「如是，如是。【义解】以生盲者为喻：有人问生盲者「白色像什么」，彼既不见色，岂能说其色相？威灯光答：彼不明见色，岂敢决定判说。佛即印可。",

"【凡夫如生盲·非阴界得名】大仙人！是诸凡夫人，如似生盲者，不见众生体，不可言道：『如是众生微细内体、长短、粗涩。』「复次，大仙人！眼非众生，耳、鼻、舌、身、意等亦非众生，有为阴分亦非众生，十八界、十二因缘亦非众生，众生名字亦不可得，亦非内空、外空、内外空得名众生也。【义解】凡夫如生盲，不见众生体，故不可说其微细内体长短粗细。眼乃至意、有为阴分、十八界、十二因缘皆非众生，众生名字亦不可得，亦非内空外空内外空得名众生。",

"【假名暂时不合】所以者何？大仙当知：眼即假名，暂时不相合故；耳、鼻、舌、身、意等假名，暂时不相合；五阴法假名，暂时不相合；三十六种不净之物一切假名，暂时不相合。如是等无有众生而可得也，亦非色等诸尘共相和合故有。【义解】释上义：眼乃至意、五阴、三十六种不净物皆「假名，暂时不相合」——如是等中无众生可得，亦非色等诸尘和合而有。",

"【诸法非众生·如来知是法】众生色等诸尘各各别异、分张离散，彼等诸法亦非众生。非命、非养育，无主、无人亦无有我，皆不可得。「复次，大仙人！若有众生者，是诸如来则不应说四种四谛法；以实无有众生性故，是故一切诸佛如来得是诸法，如是随顺、如是修行，得如来身。【义解】明众生色等诸尘各各别异离散，彼诸法亦非众生，非命非养育、无主无人无我，皆不可得。若实有众生，如来则不说四谛；以实无众生性，诸佛乃得是法、随顺修行而得如来身。",

"【威灯光发大誓】」尔时，威灯光大仙人为欲求得一切智故，发大弘誓，作如是言：「世尊！设我今者，有大火坑，尽其劫际应处其中；复有大山犹如须弥，其山岩峻，高远峙立，乃至上到阿迦尼吒天，于彼时中，我身在上自坠而下；【义解】威灯光为求一切智，发大弘誓：设今有大火坑，我宁尽劫处其中；复有须弥大山高至阿迦尼吒天，我宁于彼自坠而下；下段续说其誓。",

"【发大誓（续）】复有大火，其聚犹如劫尽时火，如是等火猛焰炽然，五热炙身。其日长远，一日时分等于一劫。如此劫时，以三十日持作一月、满十二月以为一年，如是时节尽彼劫际，修此苦行，欢喜甘受，终不因是暂舍精进，而不求于一切智也。【义解】威灯光誓：宁受劫尽大火五热炙身；纵一日等于一劫、以三十日为月十二月为年、尽彼劫际修此苦行，欢喜甘受，终不因此暂舍精进、不求一切智。",

"【诸仙发心·眉间放光】」尔时，威灯光大仙人作是语时，于大会中所有一切五通仙人皆悉从坐恭敬而起，合掌向佛作如是言：「世尊！我等诸仙从今已去皆各勇猛勤力精进，所欲求于阿耨多罗三藐三菩提。」是诸仙辈作此言已，尔时，世尊即从眉间放诸光明，其光名曰无能降伏者；【义解】威灯光发愿时，会中一切五通仙皆起座合掌白佛：从今已去皆勇猛精进，求无上正等正觉。诸仙发言已，世尊从眉间放光，名曰「无能降伏者」。",

"【六种震动】十方一切诸佛世尊眉间白毫放诸光明亦复如是。当于是时，以佛光明力因缘故，是诸大地六种震动，所谓动、遍动、等遍动，踊、遍踊、等遍踊，觉、遍觉、等遍觉，起、遍起、等遍起，震、遍震、等遍震，吼、遍吼、等遍吼；【义解】十方诸佛眉间白毫亦放此光。以佛光明力故，大地六种震动——动、踊、觉、起、震、吼，各分遍、等遍。",

"【震动相·十方雨供】东踊西没、西踊东没、南踊北没、北踊南没、中踊边没、边踊中没，乃至上下踊没亦复如是。尔时，十方诸佛世尊于虚空中，在于释迦如来佛上雨种种华、种种妙香、种种天乐，随心所爱令众见闻。复有乾闼婆王并及无量诸天众等，皆悉作于五种音乐以乐如来，复于一切诸乐音中出于种种赞叹之声歌咏如来。【义解】大地震动之相（东踊西没等）。十方诸佛于虚空中、释迦佛上雨种种华香天乐；乾闼婆王与无量诸天作五种音乐以乐如来，并于乐音中出赞叹歌咏之声。",

"【天香微风·菩萨雨供】是诸天香又有微风徐徐而动，吹是香气叆叇垂布，于如来前遍覆虚空。复有十方诸来菩萨摩诃萨等一切大众，踊跃欢喜，各于佛上雨种种花、种种璎珞、种种珍宝、种种杂香、种种花鬘、种种涂香、种种末香、种种衣服、种种幡盖，诸如是等无量无边供养之具，供养如来。【义解】天香为微风所吹、缭绕垂布遍覆虚空。十方来菩萨及大众踊跃欢喜，各于佛上雨种种花、璎珞、珍宝、杂香、花鬘、涂香、末香、衣服、幡盖等无量供具供养如来。",

