"【究竟·毘焰字门】乃至般若波罗蜜如一之故，一切法如一；般若波罗蜜究竟之故，一切法也究竟。」佛告金刚手菩萨：「若有人于此般若波罗蜜，听闻受持读诵忆念，彼人得入究竟清净菩萨行位，一切盖障究竟不生，即得名为「持金刚如来」。【义解】续说般若波罗蜜与一切法如一、究竟。明闻持者入究竟清净菩萨位、盖障不生，名持金刚如来。",

