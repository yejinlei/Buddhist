"【唵字门·平等调伏一切如来】」那时平等调伏一切如来，说「金刚手调伏一切众生正智藏般若波罗蜜经」。说：「一切众生平等之故瞋也平等；一切众生调伏之故瞋也调伏；一切法平等之故瞋也平等；一切众生平等之故金刚也平等。你的意思如何？为菩提之故，如是调伏一切众生。【义解】平等调伏一切如来说正智藏般若：众生平等则瞋平等、众生调伏则瞋调伏、法平等则瞋平等、众生平等则金刚平等，为菩提故如是调伏众生。",

"【憾字门·住一切法平等如来】如是所说一切法行，摄入秘密『憾』字义门。」那时住一切法平等如来，说「最上一切法平等般若波罗蜜经」。说：「一切平等之故，般若波罗蜜也平等；一切利之故，般若波罗蜜也利；一切法之故，般若波罗蜜也法；一切业之故，般若波罗蜜也业。【义解】诸法摄于憾字门。住一切法平等如来说：一切平等、利、法、业，故般若波罗蜜亦平等、利、法、业。",

