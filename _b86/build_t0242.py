"【娑字门·菩萨住轮回度生】如是所说一切法行，摄入秘密『娑𨩻』字义门。「再者，金刚手菩萨！彼大菩萨乃至住在轮回，也作一切利益度诸众生。一住方便智慧，所作事业都得清净，贪欲烦恼都不能侵，如莲在水淤泥非染，自在安乐坚固不退。【义解】诸法摄于娑𨩻字门。明大菩萨虽住轮回而度众生，以方便智慧，业清净、烦恼不侵，如莲出淤泥。",

