"【四心喻（二）】又初发心能过声闻地，行道心能过辟支佛地，不退转心能过不定地，一生补处心安住定地。又初发心如学初章，行道心如学第二章，不退转心如能以章为用，一生补处心如通达深经。又初发心从因生，行道心从智生，不退转心从断生，补处心从果生。【义解】续以过地、学章、从因生等喻四心。",

"【四心喻（三）】又初发心因势力，行道心智势力，不退转心断势力，补处心果势力。又初发心如病者求药，行道心如分别药，不退转心如病服药，补处心如病得差（愈）。又初发心法王家生，行道心学法王法，不退转心能具足学法王法，补处心学法王法能得自在。【义解】续以势力、病者求药、法王家生等喻四心。",

"【定光明主问略道】」那时大众中，有天子名定光明主，不退转于无上正等正觉。定光明主天子语文殊师利法王子说：「何等是菩萨摩诃萨略道？以此略道疾得无上正等正觉。」文殊师利说：「天子！菩萨摩诃萨略道有二，以此略道疾得无上正等正觉。【义解】定光明主问菩萨的「略道」（简捷之道）。文殊答略道有二。",

"【略道二·方便与慧】何等为二？一是方便，二是慧。摄善法名为方便，分散诸法名为慧；又方便名为随众生行，慧名不转一切法相；方便名待应众生心，慧名不待一切法；方便名和合诸法，慧名舍离诸法；方便名起因缘，慧名灭因缘；【义解】略道二：方便与慧。以多组对比显方便与慧之别（摄善/分散、随众生/不转、和合/舍离、起因缘/灭因缘）。",

"【方便与慧（续）·二道】方便名知分别诸法，慧名不分别法性；方便名庄严佛土，慧名庄严佛土无所分别；方便名知众生诸根利钝，慧名不得众生；方便名能至道场，慧名能得一切佛法。「天子当知，菩萨摩诃萨又有二道，以此二道疾得无上正等正觉。【义解】续以诸对比显方便与慧。次说菩萨又有二道。",

"【二道：助道断道等】何等为二？一是助道，二是断道。助道者五波罗蜜，断道者般若波罗蜜。「又有二道。何等为二？一是有系道，二是无系道。有系道者五波罗蜜，无系道者般若波罗蜜。「又有二道：一是有量道，二是无量道。【义解】二道：助道（五波罗蜜）、断道（般若波罗蜜）；有系道（五度）、无系道（般若）；有量道、无量道。",

"【智道断道·随智勇行问】有量道者取相分别，无量道者不取相分别。「又有二道：一是智道，二是断道。智道者，初地至七地；断道者，八地至十地。」那时，会中有菩萨名随智勇行，问文殊师利法王子说：「什么叫菩萨义？什么叫菩萨智？【义解】有量道取相分别，无量道不取相分别；智道为初地至七地，断道为八地至十地。随智勇行菩萨请问「菩萨义」与「菩萨智」。",

"【义名无用·智名有用】」文殊师利说：「善男子！义名无用，智名有用。什么叫义名无用？义是无为，无为法于法无用、非用。又义者，非染相、非离相，此义于法无用、非用。又义不增不减，于法无用、非用。天子，什么叫智？【义解】文殊释：义是无用（无为），智是有用。「义」指理体，「智」指照用。",

"【智是忍道·十智】智是忍道，是心所用而非无用。所以，智名有用非无用。智功归于断，所以智名有用非无用。智能善知五阴、十二入、十八界、十二因缘、是处非处，所以智名有用非无用。「再者，天子，诸菩萨有十智。何等为十？【义解】释智为忍道、心所用、功归于断、善知诸法，故名有用。下说菩萨十智。「五阴、十二入、十八界」即蕴、处、界三科。",

"【十智·十发（起）】一是因智，二是果智，三是义智，四是方便智，五是慧智，六是摄智，七是波罗蜜智，八是大悲智，九是成就众生智，十是不著一切法智。「再者，天子！诸菩萨有十发。何等为十？一是身发，欲令众生身业清净之故；【义解】列菩萨十智。次说菩萨十发（十种发起）。",

"【十发（续）】二是口发，欲令众生口业清净之故；三是意发，欲令众生意业清净之故；四是内发，一切内物不贪著之故；五是外发，欲令众生住正行之故；六是智发，具足佛智之故；七是慈发，念一切功德庄严之故；八是众生成熟发，守护智慧药之故；【义解】续列十发（口、意、内、外、智、慈、众生成熟发）。",

"【十发（末）·十行】九是有为智发，具足定聚之故；十是无为智发，心不著三界之故。「再者，天子！诸菩萨有十行。何等为十？一是波罗蜜行，二是摄行，三是慧行，四是方便行，五是大悲行，六是求助慧法行，七是求智法行，八是心清净行，九是观诸谛行，十是一切所爱无贪著行。【义解】十发之末（有为智发、无为智发）。次列菩萨十行。",

"【十思惟尽】「再者，天子！诸菩萨又有十思惟尽。何等为十？一是思惟事尽，二是思惟受尽，三是思惟法尽，四是思惟烦恼尽，五是思惟见尽，六是思惟邪尽，七是思惟爱尽，八是思惟不著尽，九是思惟结使尽，十是思惟著道场行尽。【义解】列菩萨十思惟尽（事、受、法、烦恼、见、邪、爱、不著、结使、著道场行皆尽）。",

"【十治法（一至五）】「再者，天子！诸菩萨又有十治法。何等为十？一是治悭贪心，雨布施雨之故；二是治破戒心，三法清净之故；三是治瞋恚心，修行慈忍之故；四是治懈怠心，求佛法无厌之故；五是治不善觉观心，得禅定解脱自在之故；【义解】列菩萨十治法之前五（治悭贪、破戒、瞋恚、懈怠、不善觉观）。「三法清净」指身口意三业清净。",

