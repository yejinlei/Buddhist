"【十种尸罗波罗蜜】「又有十种尸罗波罗蜜。何等为十种？离八难为首尸罗波罗蜜，建立佛法为首尸罗波罗蜜，超越声闻辟支佛地为首尸罗波罗蜜，净身业为首尸罗波罗蜜，净口业为首尸罗波罗蜜，净意业为首尸罗波罗蜜，庄严心为首尸罗波罗蜜，人世界清净为首尸罗波罗蜜，一切愿求满足为首尸罗波罗蜜，不害为首尸罗波罗蜜。【义解】说十种戒波罗蜜（以离八难、建立佛法、超越二乘乃至不害为首）。「八难」即三恶道、盲聋喑哑、世智辩聪、佛前佛后等八种障难。",

