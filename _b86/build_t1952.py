"【形相庄严·三谛圆融】头戴宝冠，冠中有化佛菩萨。左手执开敷莲华，正当华台上画如意宝珠；右手作说法相。天妙衣服，珠宝耳饰、环钏、七宝璎珞种种庄严，身放众光。修者依此圣相系念观察。当知此相从心想生，如虚空华本来无有。此相与心元是观音妙净明体，空华即假、本无即空、妙体即中，三谛圆融、非一非异，不可得而思议。【义解】详述圣像（宝冠、化佛、莲华、宝珠、说法手、璎珞光明）；并以天台三谛（假、空、中）观此相：空华是假、本无是空、妙体是中，三谛圆融不二。「系念观察」即心系于相而观察。",

"【性具诸法·感应之理】不但圣相如此，说法也都如此，都因众生本性具足诸法，所以能随缘发生；菩萨修证诸法，所以能普门示现。诸法虽异，空与中相同。若只异而不同，就失感应之理；若只同而不异，就失感应之事。失于理者，如冰炭之不可相合……【义解】由性具（众生本具）与修证（菩萨所证）说明感应之由。理（空、中）事（假）须双备，偏理或偏事皆失感应。「冰炭不可合」喻事理乖违则不能感应。",

"【事理双备·经题释义】失于事者，如谷响之不能召（物）也。事理既备，感应乃成。又须知三谛之法，即是明咒所诠之义，所以义净译为「无障碍观自在莲华如意宝轮王陀罗尼」。说「无障碍」，即菩萨具三谛之智、无三惑之障。观自在，即用此智观照众生而得自在，这是以能说之人来命名所说之咒罢了。【义解】明事理双备方成感应。释经题：「无障碍」指具三谛智、无三惑（见思、尘沙、无明）之障；「观自在」以能说之人（菩萨）命名所持之咒。",

"【莲华如意宝轮·三德之喻】莲华，生而有实，譬法身德本来具足。如意，是珠。经说「雨妙珍宝，犹如意树」。如意宝珠，譬解脱德能生诸法。宝轮，有摧伏之力，譬般若德能破诸法。又莲华出水离染清净，譬般若。【义解】以莲华、如意珠、宝轮三物，配法身、解脱、般若三德而释题。「如意树」「如意珠」皆能随愿雨宝；「摧伏」即摧破降伏。",

