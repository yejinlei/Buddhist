"【本迹不二·应随于机】本与迹虽殊，无不是随真如之体起应化之用。其体如镜，其用如像，所以真如不自现应，应之在机，也犹如镜不自成像，成像在于形。再说机有胜劣、应有大小，应之大者身长八十万亿那由他由旬（如《十六观经》所说）【义解】以镜与像为喻，明真如之体（镜）与应化之用（像）的关系，及「应之在机」之理。「八十万亿那由他由旬」极言报身之大，出《观无量寿经》（《十六观经》）。「那由他」「由旬」皆古印度数量、长度单位。",

