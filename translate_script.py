        yijie = "【义解】此段叙述佛陀来到法堂之后，知而故问比丘们刚才在议论什么，比丘们如实禀白自己讨论的世界成坏议题；佛陀首先赞叹大众能以正信出家，集坐时行二种贤圣事业——讲论法义与圣默然，印可大众的论议如法，应允为大众开示世间成、住、坏、空的因缘。"
        vernacular = "佛陀当即起身来到讲堂，在大众之前敷设座位，俨然而坐，就座而坐之后，知而故问诸位比丘说：“你们刚才聚会坐在这里，在议论什么事呢？”诸位比丘共同禀白佛陀说：“大德世尊！我们吃完饭之后，在讲堂上共同议论：‘真是稀有难得啊，这天地世间是如何破坏，又是如何成就，坏已还成、成已安住的呢？’我们只是在共同议论这件事罢了。”佛陀告诉诸位比丘说：“善哉善哉！你们能以正信出家学道，聚集一处应当修二种贤圣事业：一是讲论法义，二是贤圣默然。你们既然想听闻世间成坏的因缘，就好好谛听，善思念之，我当为你们次第演说。”诸位比丘禀白说：“唯然世尊，我们乐意听闻。”"
