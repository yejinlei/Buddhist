        vernacular = "佛言：“诸比丘！须弥山半高四万二千由旬处，有四大天王所居宫殿；须弥山上有三十三天宫殿，是帝释所居；三十三天向上一倍，有夜摩天；夜摩天向上一倍，有兜率陀天；兜率天上有化乐天；化乐天上有他化自在天；他化自在天上有梵身天；他化自在天和梵身天中间，有魔波旬宫殿；梵身上有光音天，光音上有遍净天，遍净上有广果天，广果上有不粗天，中间有无想众生天；不粗上有不恼天，不恼上有善见天，善见上有善现天，善现上是阿迦尼吒天，再向上就是无色界诸天：无边空处、无边识处、无所有处、非想非非想处天，这些都是众生的住处，众生随业往来生灭于此，不出这个范围，这就是娑婆世界。”"
