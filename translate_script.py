        if "大樓炭經" in sutra_title:
            vernacular = f"{first_line}\n闻如是：\n一时，佛陀游化在舍卫国祇树给孤独园，与大比丘众千二百五十人俱。当时，诸位比丘吃完饭之后，都聚集在讲法堂上，坐下之后共同议论道：“真是稀有难得啊！我们所居住的这个天地世界，是如何形成的？又会如何破坏？坏灭之后又如何重新成立？成立之后又如何安住呢？”佛陀以天耳远远听到了比丘们饭食之后在讲堂共同议论这件事。"
        else:
            vernacular = f"{first_line}\n如是我闻：\n一时，薄伽梵在舍婆提城迦利罗石室，与大比丘众俱。当时诸位比丘食后聚集在常说法堂，坐定之后各自生起心念，共同议论道：“真是稀有难得啊！现在这个世间，众生所居住的国土天地，是如何成立的？如何散坏？坏灭之后如何重新成立？成立之后又如何安住呢？”当时世尊独自在静室之中，以超过常人的清净天耳，听到了比丘们食后聚集在法堂共同作这样的希有言论。世尊听了之后，在晡时从禅定出，从石室起身，前往法堂。"
        return f"{title}\n{yijie}\n\n白话翻译：\n{vernacular}"
