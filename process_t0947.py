task_dir = os.path.join(base_dir, "baihua-tasks")
out_dir = os.path.join(base_dir, "modern-translation")

def process_file(tid, translator_func):
    in_path = os.path.join(task_dir, f"{tid}.json")
    out_path = os.path.join(out_dir, f"{tid}.json")
    with open(in_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    translator_func(data)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"Processed {tid}, output to {out_path}")

