"【義解】佛告寶網童子：善哉！善哉！汝所問辯才甚為微妙，多所憂念、多所安隱，愍傷諸天及十方人，乃能質問如來如斯深義。童子諦聽、善思念之，吾當為汝分別解說。童子與大眾受教而聽。",
"【義解】佛說：童子當知，東方離此有佛世界名為「解君」；從此以東，過如恒河沙等佛土，又過從下水際至三十三天所積塵數——若有一士夫自然而出，一一數諸世界塵，每過若干億百千垓佛土乃著一塵。",
"【義解】佛言：童子！如此比類，復以前法數諸佛剎土又著一塵，長遠久迥無限無量不可稱計，虛空亦不能容此諸塵之數；若將諸塵漸漸舉移悉令窮盡，於汝意云何？寧有人能思惟計數、稱量算計彼士夫所移塵數之遠近多少否？",
"【義解】寶網答曰：無人能知，天中之天！若有人欲分別識說此譬喻、曉了其義，尚不能通達譬喻本身，何況能算其數？佛語童子：彼士夫所移諸塵，一一著處皆為佛界，下至水際、上至三十三天，滿其中塵國土之數。",
"【義解】彼時復有第二人出，取彼一塵，復如前人所計塵數，越若干不可稱載億百千垓佛土乃更著一塵。佛言：族姓子，以是比類，所過東方長遠無際，又取一塵過如前數，復著一塵。",
"【義解】以是比類，其人所過之處，天所不覆、地不能載，越不可計量億百千垓佛土，爾乃得至「解君」世界。彼中有佛，名「寶光月殿」，號「妙尊音王如來、至真、等正覺、明行成為、善逝、世間解、無上士、道法御、天人師、佛、世尊」，今現在說法。",
"【義解】族姓子及族姓女學菩薩乘者，聞彼佛名而不懷猶豫，信佛道眼、得聞名號，所生之處作轉輪聖王；若佛興世常得相見，供養無央數佛，淨修梵行、獲致神通，進退獨步、總持自在，得觀如來、覩恒沙等平等正覺，超越生死若干億劫如恒沙，心常安靜未曾忘失，恒志無上正真之道，不為塵埃所染，身如鉤鎖、住一處得四事自在，體如紫金、三十二相莊嚴，得八種梵音，棄八難、常得閑靜。",
"【義解】世尊觀此義已說頌：若聞世吼（佛）名而心不狐疑、篤信佛法明者，則為真眾祐；常為轉輪王、輒值見諸佛、遇即供養無量；恒修梵行、神通獨步、執轉總持、得覩諸佛路。",
"【義解】偈續：常得覩諸佛如恒河沙，超越生死億劫；以志佛道故心未曾忘，宣說世吼名為眾宣傳；成轉輪聖王、住一處得自在，體紫金色、具三十二相；若聞佛號、聲如梵天、棄八難、五體歸禮。",
"【義解】偈續：不障塞佛道、未曾懷瞋恨者，由聞佛名不懷猶豫故；若奉最勝號、精勤七日，其人眼得清淨，未捨肉眼而能普見清淨、睹無數佛如恒河沙。佛告寶網：若菩薩及凡夫聞彼佛名殷勤精思、遙自歸供養，悉能聞十方佛所說、目皆親見、僉信樂之。",
"【義解】彼人前世曾供養無央數佛，方得聞諸如來名，聞即識念本所遊歷，能為眾生說往世本末名號、志願誓願，能見他眾生根原來處；究竟佛道心懷悅豫，如日出永無塵翳，所睹極曠，棄除八難鬪諍，心常和雅閑靜。",
"【義解】若有篤信佛道者，於和合離別皆不怵惕；縱使前世犯諸罪釁應墮惡趣燒炙劫數，小遇頭痛即眾殃消除；火不能燒、風不能中、國王不能加害；聞如來名未曾生盲、目不痛瞎、不聾不瘂、不僂不跛。",
"【義解】諸龍、鬼神、阿須倫、餓鬼、魘鬼、人與非人不能犯觸，諸魅、暴鬼、神龍、地祇莫不愛樂。假使執持諸佛名者，功德如是不可稱計。",
"【義解】佛說頌：目皆見諸佛、咸能供養之，聞所說即受、其人皆信樂；宿命所經歷、供養無數佛，一聞彼佛名一切悉識念，並能為人說其本名號；復覩他眾生能究竟佛道，生歡喜心、棄八難、除諍訟，所生常閑靜；信名者心不結、棄憒鬧。",
"【義解】偈續：縱犯無間罪應受若干劫殃，一時頭痛眾罪畢除；不為火所災、不為風所中、王不能加害；未曾生盲、不聾亦不瘂，奉最勝號者手腳不缺；鬼神、揵沓和、餓鬼、惡神聞如來名，人毒咒不行。",
"【義解】偈續：諸魅、羅剎、諸天、諸龍，若奉此最勝名，皆共愛敬之。佛復告童子：若有聞彼佛名者，疾得三昧、決諸狐疑、不著音聲，志無生法、勞勳億千；末世信樂此法者功德如是。",
"【義解】若聞導師滅度後之名，善宣法訓、執持講說，誦懷人中尊所演經典、修淨行、備諸佛行，臨壽終時心不亂，即能覩見億垓諸佛、聞所說法皆能受持；既自修立又開化眾生，聞不挑其短而悉化之令住佛道，其人奉持諸佛名者，堪應供養諸佛大聖。",
"【義解】又能信吾身從佛之教、常自歸命，永得解脫、不墮地獄；其信佛慧者即是歸吾身，若誹謗者即是魔官屬；五趣所遊眾生，世尊悉濟令立一乘。如來一毛孔即能演出恒河沙光明，以度脫眾生。",
"【義解】佛說頌：不疑音聲句者疾得三昧，興暢億功勳皆由聞佛名；後末世奉持此經道、聞世吼名心不猶豫；滅度諸正覺若頒宣法教，聞導師名而能奉持分別。",
"【義解】偈續：則為具奉行諸佛所演法，能致尊嚴淨、眾聖所應宜；臨壽終時即見億垓佛，皆能啟受諸佛所說法；既自修立復化億眾生，所聞不虛耗、普建諸佛道，則為悉奉持一切諸佛教。",
"【義解】偈續：信吾真聖目即是供養諸佛、歸命諸最勝、永度諸惡趣；信佛慧者是從吾教，若好佛道法為隨大聖教；若誹謗正法皆是魔官屬；五趣眾生所有毛孔之數，世尊皆能濟之入一乘道。",
"【義解】佛告童子：如來一毛孔演出恒沙光明威神，若有信此者，於一世中得覩見億數佛；若聞此法王所說不懷結網，亦當成佛如我今日；若隨順講說此經，最後世希有信者；如恒沙數士夫世界，佛一光明悉遍照，佛土不可思議。",
"【義解】設能計此一切諸數，滿中珍寶以施如來，不如加聞佛名心懷欣豫，當逮不可思議慧；數數思念諸導師尊，其功德福不可稱計；佛光明照十方、身如寶合成；聞佛名不狐疑者，即得無生法忍、口氣馥芬名香遠聞，宣持佛名功德不可稱量。",
"【義解】佛說頌：從一毛孔中世吼聖威神演出光明如恒河沙；若信諸佛無量光者，一世覺了、逮見億載佛；若聞此經、法王所歎、省之不疑，當逮佛道如我今日。",
"【義解】偈續：若應時聞說此經、末世為人分別說者，如恒沙數菩薩世界，佛一光明照耀若干佛土；一切共計佛土不可思議，滿中紫金以奉世護，不如聞佛名坦然歡喜——是福最為無限。",
"【義解】偈續：常能數數念至真等正覺者，無能究盡其功德；其身所演光如寶煌煌，聞佛名不沈吟者逮法忍、口氣香馥如天栴檀，皆由宣佛名。佛告寶網：若人聞佛身毛孔所演光明暉照開化眾生，心中悅豫，在所生處常得侍佛不離在側，猶如阿難今日侍佛，亦如子孫親里骨肉。",
"【義解】奉行佛道而見世明、歡喜無量、恭恪不可稱限；見佛已具足奉事，獲福如是。孰聞佛名而不敬承？唯魔官屬、迷惑外道方不信耳。童子！適見佛即自歸命此經法者，末世亦當歸之。",
"【義解】若能執在身手、心思口誦，曾於過去佛所聞說此尊經義、殷勤供養者，此經卷自然歸於彼人手中，法王所詠所建立、誓願至誠後世必獲；若以一心奉無數佛，不如信此經典之要——福不可量，勝於供佛，感容貌端正、勇猛無畏、功德殊異、財富無數、志意堅強、三十二相莊嚴吉祥，莫不宣暢。",
"【義解】佛說頌：若聞佛身諸毛孔光明、佛名能導化眾生者，世世所生常為佛侍者，如阿難侍我聞法輒受持，為子為親屬奉修菩薩道，當見世光明、歡喜無有量。",
"【義解】偈續：得見最勝味、愛敬不可稱，具足承事、常致妙道慧；誰聞導師名而不敬承？唯有魔官屬、外道不篤信；長者子寶網覩佛即奉養，末世經法歸彼掌；本從佛聞此尊經、供養自歸者，自然歸其手。",
"【義解】偈續：法王所說當受此妙卷、建立正願後世自然獲；若一心供事不可計佛，不如信此經——功德過於彼；顏貌常端正、功勳無畏、財富意堅強、相好自莊嚴。佛告童子：若族姓子、族姓女今聞此經，於後末世得值此法，受持讀誦為人演說者，得見百千佛所轉法輪、咸悉供養。",
"【義解】然後末世不疑道眼者，前世已奉無數佛；聞佛名篤信明目、護正法順佛教、聞名號造佛形像。愚癡暗塞之人聞世尊名懷毒誹謗者，億百千劫盲冥無目；若於無數劫鬪亂眾生、誹謗此經，其罪過於彼，以故說是。",
"【義解】後世值遇者，無得懷疑、不信佛慧，當以香華、雜香勤心供養，奉上衣服；從聞經者恭恪安隱庠序。寶網童子以衣食奉如來、心不離佛；佛滅度後，諸天神靈住於虛空而雨天花，供養聞此經好喜愛樂、一心無猶豫者。",
"【義解】佛說頌：若於後末世得聞此經、受持諷誦為人說者，供養百千佛所轉法輪；末世不疑佛教者，往昔無數劫已奉養諸護世；若聞佛名信樂順正法、從佛教化、聞此經法者，當作佛形像。",
"【義解】偈續：愚癡暗塞誹謗佛名者，億劫盲冥無眼目獲殃；若於無數劫鬪亂別離人、誹謗此經，其罪過於彼；將來世以故說斯義，無得狐疑佛無上慧，以名香種種華、雜香好衣服殷勤供養。",
"【義解】偈續：以安和諸飲食、柔軟妙供具，童子寶網數數奉上如來；爾時諸天人揚大音聲，諸天雨眾花遙散供養聞此經者。佛告寶網：此經多所安隱，猶如困疾值得良醫療治其病，風寒熱氣無不除愈。",
"【義解】菩薩亦復如是，聞彼佛名殷勤精進，則婬、怒、癡病皆得消盡。時無央數天人來集空中雨栴檀香；梵天億數及童子聞此經名與如來號，歡喜踊躍、善心生焉，口宣無上義：我等末世當為比丘，志強無畏，以此經在郡國、城郭、縣邑頒宣、隨佛教行。",
"【義解】假使遠在億百千里，亦當往啟受，不以遙遠為患難；當請諸天人、龍神、阿須倫、健沓惒、迦樓羅、真陀羅、摩睺勒、人非人等，為說經義、以道法飽滿。諸天悅豫、空中散華墮落如雨，各讚言：法王一音普告佛土，顯無為、愍眾生，周遍佛土如恒沙，十方亦然。",
"【義解】童子寶網覆諸佛國，若見大雄（佛）無有懈倦；世尊顧眄為分別說：莫疑佛法如來無量——佛眼無限普施安隱，佛慧無際達知三世、無所不通為諸法中王；五陰無堅固、四大亦如是；勿著音聲色痛想行識五陰，曉了此者知無要；思惟如來所說，疾得總持志不迷荒；諸法本淨空無吾我、無所悕望無有疋儔，如來如是。",
"【義解】佛說頌：無央數諸天億千住虛空雨栴檀香，億載梵天亦散供養；聞此寶網經、讚歎勸助如來，心喜口宣無上義；我等後末世為勇猛比丘，於城郭縣邑宣說此經。",
"【義解】偈續：當順佛教平等覺吉祥，雖遠至億由旬亦當頒宣，請會天人、諸龍、真陀羅、人非人，以法施飽滿；天人歡喜心和悅安、雨眾花同音嗟歎；法王境界普遍佛土，釋師子人尊一毛光照，導人興愍；世尊一出舌覆億佛土如恒沙，十方各照億佛土。",
"【義解】偈續：大雄告曰：童子寶網及犁車國人、六十眷屬侍佛，顧眄而告言：無得疑佛法、如來不可量；無能限佛眼、佛施一切安，佛慧無央普流三世；世尊靡不通達、解諸經典，五陰無堅固為人中導所說。",
"【義解】偈續：四大所變無得著音聲，當解色陰、痛痒想念行識皆無真要；別五陰如是順如來命，速得總持心不忘；諸法本淨虛無無吾我、無諍無所念，此從如來教。",
"【義解】佛告童子：南方去此如前譬喻，過倍此數一切諸塵，更復越彼七十二億百千垓不可計會佛土之倍，有世界名「雜種寶錦」，彼有佛名「樹根花王」，現在說法；彼佛為如來、至真、等正覺、明行成為、善逝、世間解、無上士、道法御、天人師、佛、世尊，所演經法初、中、竟皆善。",
"【義解】若族姓子、族姓女聞彼佛名，不懷疑結、信吾道眼，則於現世至德具足，逮受五法：一曰盡除吾我，所生之處常值佛世；二曰獲尊勢為轉輪聖王；三曰逮總持法、執御經典、誠信百千；四曰成三十二大人之相，至成佛道眾行備悉；五曰逮得五通無所蔽礙。是為五法。",
"【義解】復有五事逮得神通：一曰天眼徹視，見十方麁細大小、學無學聲聞緣覺乃至世尊超越眾相；二曰天耳徹聽，聞萬億地獄餓鬼燒炙飢渴、畜生之惱、天上人間苦樂好惡，十方佛所說經典皆悉聞之；三曰身能飛行遍諸佛國，如日現水雖現往來而無周旋；四曰能知一切眾生心念善惡好醜、有志無志、有漏無漏、有心無心、慕俗樂道悉皆知之；五曰自知宿命，並見眾生無數劫事、過去未來現在靡不通達悉識念之。",
