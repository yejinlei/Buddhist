#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""样式篡改检测脚本。
检查：
1. pages/sutras.html 经目页是否由 build_sutras_index.py 生成（含 AUTO-GENERATED 标记）
2. 根目录 tXXXX.html 经页是否由 build_sutra_pages.py 生成（含 AUTO-GENERATED 标记）
3. pages/tXXXX.html 经页是否由 build_sutra_pages.py 生成
4. 是否还有旧简陋固定 CSS（_rebuild_pages 遗留的 #8b0000 820px 居中样式）残留
5. welcomeCount 数字是否为真实已译数量
6. 三个已作废脚本是否被重新启用
"""
import os, re, sys
from pathlib import Path

ROOT = Path("/home/user/workspace/13511660557912876654/buddhist-ontology")
TRANS = ROOT / "data" / "modern-translation"
OUT_ROOT = ROOT
OUT_PAGES = ROOT / "pages"

BAD_CSS_SIG = 'max-width: 820px'  # _rebuild_pages 生成的简陋样式标志
BANNED_SCRIPTS = ["_rebuild_pages.py", "_rebuild_sutras_page.py", "render_all_pages.py"]
INDEX_MARK = "AUTO-GENERATED by build_sutras_index.py"
PAGE_MARK = "AUTO-GENERATED by build_sutra_pages.py"

def main():
    errors = []
    warnings = []

    # 1. 作废脚本检查
    for s in BANNED_SCRIPTS:
        p = ROOT / s
        if p.exists():
            content = p.read_text(encoding="utf-8", errors="ignore")
            if "sys.exit" not in content and "已作废" not in content:
                errors.append(f"作废脚本 {s} 已被重新启用！请立即停用。")

    # 2. 真实已译数量
    real_count = sum(1 for f in os.listdir(TRANS) if f.endswith(".json") and f != "tree.json")

    # 3. 经目页
    sp = OUT_PAGES / "sutras.html"
    if not sp.exists():
        errors.append("pages/sutras.html 不存在")
    else:
        shtml = sp.read_text(encoding="utf-8", errors="ignore")
        if INDEX_MARK not in shtml:
            errors.append("pages/sutras.html 不是由 build_sutras_index.py 生成，疑似被篡改")
        if BAD_CSS_SIG in shtml and "tailwind.min.css" not in shtml:
            errors.append("pages/sutras.html 使用了简陋固定CSS")
        m = re.search(r'id="welcomeCount">(\d+)</span>', shtml)
        if m:
            n = int(m.group(1))
            if n != real_count:
                errors.append(f"pages/sutras.html 中welcomeCount={n}，但真实已译 {real_count} 部，数字不匹配")
        else:
            warnings.append("pages/sutras.html 中未找到 welcomeCount 数字")

    # 4. 根目录经页
    bad_root = []
    miss_root = []
    for fn in os.listdir(TRANS):
        if not fn.endswith(".json") or fn == "tree.json": continue
        tid = fn[:-5]
        p = OUT_ROOT / f"{tid}.html"
        if not p.exists():
            miss_root.append(tid)
            continue
        c = p.read_text(encoding="utf-8", errors="ignore")
        if PAGE_MARK not in c:
            bad_root.append(tid)
        elif BAD_CSS_SIG in c:
            # 新样式不使用820px固定宽度
            bad_root.append(f"{tid}(残留旧CSS)")
    if miss_root:
        warnings.append(f"根目录缺少 {len(miss_root)} 部经页: {miss_root[:5]}{'...' if len(miss_root)>5 else ''}")
    if bad_root:
        errors.append(f"根目录 {len(bad_root)} 部经页样式异常: {bad_root[:10]}{'...' if len(bad_root)>10 else ''}")

    # 5. pages/ 经页
    bad_pages = []
    miss_pages = []
    for fn in os.listdir(TRANS):
        if not fn.endswith(".json") or fn == "tree.json": continue
        tid = fn[:-5]
        p = OUT_PAGES / f"{tid}.html"
        if not p.exists():
            miss_pages.append(tid)
            continue
        c = p.read_text(encoding="utf-8", errors="ignore")
        if PAGE_MARK not in c:
            bad_pages.append(tid)
    if miss_pages:
        warnings.append(f"pages/ 下缺少 {len(miss_pages)} 部经页: {miss_pages[:5]}{'...' if len(miss_pages)>5 else ''}")
    if bad_pages:
        errors.append(f"pages/ 下 {len(bad_pages)} 部经页样式异常（多为旧简陋样式残留）: {bad_pages[:10]}{'...' if len(bad_pages)>10 else ''}")

    # 报告
    print(f"真实已译：{real_count} 部")
    print(f"根目录经页：{sum(1 for f in os.listdir(OUT_ROOT) if re.match(r't\d+[a-z]*\.html$',f))} 个")
    print(f"pages/ 经页：{sum(1 for f in os.listdir(OUT_PAGES) if re.match(r't\d+[a-z]*\.html$',f))} 个")
    print()
    if errors:
        print(f"❌ 发现 {len(errors)} 个错误：")
        for e in errors: print(f"  - {e}")
    else:
        print("✅ 所有经页样式正常，无篡改")
    if warnings:
        print(f"⚠️  {len(warnings)} 个警告：")
        for w in warnings: print(f"  - {w}")
    return 1 if errors else 0

if __name__ == "__main__":
    sys.exit(main())
