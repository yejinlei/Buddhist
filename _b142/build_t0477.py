 "「计执诸乐与众苦，犹如行走于虚空；若能思惟这样的行，这才叫心得解脱。有身则言『我』，那法也虚无；若不执有『我』，则所知无所有。这些人不执想于『命』，不能穷究本末；以虚无之想为真实，是智慧微少者的迷惑。我与寿命，本净而无所有；这都是愚冥者的行为，计执本净为『有』。",
 "「佛道不可思议，不念著『有』；若听闻深妙之法，却不能领受奉持。从没有宣说这样经法的人——法不可证得，所说的也无所获。坐在佛树下，因此成就道慧；若不得道慧，也就无所知。佛道与慧场，也没有言说；凡夫怀着期望之想，仰慕佛所演说的法。",
 "「这才是真实的教法，是佛所宣说的深妙义；若其意所觉甚深，反而成了魔所行之事。若有人得以听闻这佛所说的经典，却不能解悟经之义味，便为诸法所遮护。菩萨极为勤苦，却不求道的安隐；于此没有道的觉悟，这两件事都无相。其心应当依慕于此；『有』是佛所说，『是何』『此云何』，都是执著于颠倒之业。",
 "「若有人过于苦恼，又极执著于深妙之法，各各称扬高呼，赞叹佛的不可思议。」佛又告诉善思：「学这法的人应当修习深奥的经典，不可志存那些杂句多辞、无益之义，否则不能成就正真无极大慧；深远之法才叫优奥，这才应于法、叫做无得。众生堕于邪见，不能行此；若不依三昧，就难以解悟利义。",
 "「慧无境界，无慧也是如此；应当了知这际非智慧所行。佛在往昔宿世听闻这深法，因而解悟寂净，心无所著。若有人听闻这经典而得欣悦欢喜，那是他曾在无数佛所修行、立下功德，才能领受于心怀、讽诵奉行，以此化导他人，宣播于十方。」",
 "佛又告诉善思童子：「菩萨应当修习这样的弘誓。世人所在之处常怀恐畏，而勤学至真者不应当心怀畏惧；若因畏难而退却，就应当作这样的解悟，宣说奉行，才能入于道慧。」善思向前对佛说：「是的，我信乐；这是世俗所不信的，唯独笃厚无穷，心志旷达如虚空，永远无所仰慕。」佛又对善思说：「若菩萨大士志求深妙之法，这些正士以这样的方便随顺如来之教，则于道法无所诤讼；因为不诤讼，一切诸法便没有恐怖，皆不可断。",
 "「一切诸法了知本无，心志无所仰慕，便入于道慧。若有人听闻『一切法有』，不以为怖；若说『无』，也不以为惧。于有、无之法，不以增损去听闻：诸法相应、诸法不相应、诸法精进、诸法懈怠。解悟这一切十方诸法，是智慧所归趣之处。若无所趣，或又不能解悟『诸法有念』『诸法无念』，也不恐怖。",
 "「诸法有为、诸法无为，诸法有界、诸法无界，诸法欣喜、诸法无喜，都不恐怖；一切诸法既非有为、也非无为，一切诸法本有所有、本无所有，诸法寂然、诸法愦乱，都不恐怖；诸法颠倒、无有颠倒，诸法虚无、真实无为，都不恐怖。",
 "「诸法一切有戒、无戒，有明、无明，有名、无名，有兴、无兴，有畏、无畏，有生、无生，有死、无死，都不恐怖；诸法有道、诸法无道，诸法有度、或不灭度，诸法是、非，都不恐怖。为什么呢？因为诸法皆空，虚无不真，犹如幻、化、泡沫、芭蕉、影、响、野马。",
 "「如同梦中所见，本无从来、去无所至；犹如虚空，忽现云雾、尘烟灰等，依托虚空而现却不能染污虚空，忽然便灭，虚空自然也没有所净。有道、无道，是世俗的慧明；若能普解自然，便无所执著。了知『无所了』，才应于道慧、无上正真，无所恐畏、心不怀惧。",
 "」佛于是说偈：「诸法无所有，自然虚而不真；那自然虚无，这相便是灭度。诸法无所诤，这也是无所有；因为了知诸法『无』，通达『不有』的自然。所诤讼的诸法，这也是无所有；因为了知法虚无，就解悟『不诤讼』。诸法无所有，本净永无形；本净不可得，也没有所忘失。",
 "「断除一切诸法，所以叫做明智；这叫做永坏，也示现无所坏。诸法无所灭，计度也没有起立；也没有许多所坏，法也不可得。诸法本虚无，也不可得见；假使无所得，又方便示现为『有所有』。诸法无所有，因缘从相对而生；『所有』与『无所有』，都宣说于经典。",
 "「诸法能相应，示现无所诤；不诤即自然，究竟无形。诸法无所应，无作、不灭度；如是不可得，常离于诸数。诸法不可得，也没有过去；甚哉，永无实，这才叫本真际。诸法都悦豫，也不可悦喜；若法不可得，那也无言说。",
 "「诸法无放逸，二者都无所有；自然无可取，这就是深妙之相。诸法不可知，无我而自然；因为解悟『无志求』，便至于『自然』之号。无为无所乐，那也是无所有；因为有无明之业，所以称名为『无为』。若念著于诸法，究竟不可见；这其实是真实之言，所以名叫『意念』。",
 "「不念著诸法，无住、无所归；了知此『无众生』，这才称名『法中法』。一切法犹如幻，那幻无所有；因为法无明的缘故，所以宣说生死。诸法无形貌，这就是自然之义；如果没有诸法，则解脱也无解脱。假立名号称『境界』，自然无境界；愚冥者所依止执著，所以名叫『部界』。",
 "」佛又告诉善思：「色、痛、想、行、识，本自空无所有；眼、耳、鼻、口、身、心，本自空无所有；地、水、火、风，本自空也没有形；都因因缘和合而成，犹如五件事，合成一座屋宅。什么叫做五？一是材木，二是瓦草，三是土堑，四是人工，五是泥水；以这五件事，才成为屋。",
 "「本来各自分开时都没有『屋』的名称；因缘和合而成，身体也是如此。五阴因缘相对便有四大，因此名叫『身』。地水火风各自因缘来合，犹如房屋的四柱四壁都因缘会合，合成、散坏都无住处。犹如梦中看见屋宅城郭、树木华实、流水田地、犁牛种种，种下五谷，各随时生长，主人用心获得它来自给。",
 "「心识为无明所覆，不通达一切三界皆空，因而依止期望营求，便生出意识；十二因缘牵连，往来周旋，轮转无有边际，劳困神识，沉迷五趣没有懈怠休息之时。不能解悟本空如梦中所见，醒来不知身在何处、归于何处。直到成等正觉，才了知五趣本无住处，独步无畏。」",
 "佛于是说偈：「色、痛、想、识空，眼、耳、鼻、口、意本寂无所有，地、水、风、火各异；了知诸界得自在，宣说无部之章，所说的上佛土，其境是灭度之想。诸法各有形，本来也无合会；不了知空寂，其本无有身。无得、不可及，从因缘相对而合成；无获、不可致，又示现期望所得的『生』。",
 "「在那里不修戒，也不犯禁；无行也无有戒，这就是诸法之相。诸法无所有，因无明而生；因为有无明之法，便造作明达之智。诸法假立有名，这名也是无所有；假立名号而无有法，才叫做灭度。所起无所生，因示现而有五阴；那阴无所见，因此称名为『有所现』。",
 "「所有无住处，因变化而示现有法；法离生死之业，长无生死之难。如幻师化现形象，愚冥者谓真有人；『所有』与『无所有』，明者不为此迷惑。法生无所生，智者不作此计度；诸法皆悉空，愚者不解此理。法一旦有所生，便当有终没；其生及病死，若能舍此则无所畏。",
 "「诸法一切空，法也无所归；善思应当了知于此，这是佛所演说的法。正觉无所作，则不可及；若不得道之处，才见三界之事。若期望贪想佛道，就不求正觉；若其行志存于道，则永不造作『无想』。生死本自然，不观自然之法；自然无所有，这就是『无为想』。",
 "「究竟无所生，所说的不可得；因为行无明之业，所以示现无为法。因为怀来众义，诸法便自然；那些都无所生，便没有诤讼之事。他们无不奉行所宣说的深妙之法，为令一切生起，菩萨行于悲悯。」这时善思以偈回答世尊：「佛兴出现于世，都是为了悲悯我们；身被疑网所缠，故宣说这法义。",
 "「佛出世间不可思议，为具足兴起变化，以破坏魔罗之网，宣说断除六十二见；为断绝生死之本，因而坐于佛树下，永无沉吟犹豫，宣说消解众想之执著；解畅虚伪之业，能仁灭除诸见，以大勇猛为世间，断除我众的狐疑。」这时世尊告诉善思童子：「菩萨所行从未虚妄，多所救护，以恩德加济，没有诤讼，除去众瑕、一切无秽，悲悯众生、行深远之义，不怀期望之想；知世间无坚固，消去贪欲，以无贪欲而蠲除众结，常行平等之心加于众生，心志不虚妄；大慈之行『法不可得』，修大义之吼不舍精进，心行至真不失勤业，没有娆害，奉行忍辱而不诤讼，不见有可睹之物，昼夜尊行。",
 "「善思一心舍离懈怠，成就道行；定意正受，其心寂静；修习善慧，于一切诸法永无所得；行无所畏，心不怯弱；显发道心，行无挂碍；成就如来十种之力。应当以什么行而至于殊特之业，尊崇其至慧、奉事无与伦比者，游于十方诸佛世界，行无挂碍、度脱一切。」",
 "」这时佛说偈：「行无虚妄之业，这是诸菩萨之言，因奉事于解脱门，不畏各种障碍之行。『无行』即是正行，这是菩萨之业；若能解悟此行，就无所贪求。以法救摄众生，是诸菩萨所宣说；其『无所得』之义，此行是无上。若言『我行道法』，就住于颠倒；因为住颠倒之业，便有所畏。",
 "「假使有诤讼，却不见诤讼的所在，明者作这样的通达，行于无上之乘。这乘无所畏，大乘最无极；畏与无所畏，这也是无放逸。一切无所有，在众行中最胜；假使了知一切虚静，他便行于无上之道。此行甚为微妙，救护一切法，所济也深远，消除众期望之想。",
 "「所行邈远玄妙，二者都无住处；若能了知本际，便不依倚念著于法。法永无众垢，也不离垢而去；这法本自清净，却能反过来宣说舍离贪欲；又示现邪逆，爱欲不坚固，不转文字之业，这句子是无上。不执著犹如幻，这就是无言教；因为舍弃颠倒之行，便没有诤讼之意。",
 "「一切众生之行，其实不可得；若能了知于此，此行才是善教。众生因无明，所以名叫黎庶；众生之法也是如此，这道便是无上。其念与众生，永远不可得，这就是第一慈，赞叹此慈乃无极；这叫世间大施，这才是大士；常仰慕欣乐放舍，这才叫慧道心。",
 "「即使不得法，诸法虚无而不实，说菩萨明达，这才叫好布施；解悟法不可得，便无所恐畏；没有可尊之法，才叫布施。法之貌不可获，佛法不可思议；这戒无所犯，诸法无所著；佛土不可思议，这里不见诸界；于戒不期望贪想，这是诸菩萨所赞叹的。",
 "「能安忍诸众生，一切不可得，这是佛所教训诲示之法，是第一忍。」佛又告诉善思：「色空不可得，痛、想、行、识空也不可得；所谓空者，色就是空，更无别的空；痛、想、行、识空，更无别的空；四大、五阴、十八诸种、三界本空，十二因缘『无』就是空，更无别的空。",
 "「现世、度世，有为、无为，四大皆空，更无别的空。色如聚沫、痛痒如泡、思想如芭蕉、生死如梦、识如幻、三界犹如变化、五趣如影——之所以如影，是因为从因缘相对而生。三界的本末，欲界、色界及无色界，都是心意所为，犹如画师在素壁板上作画，因缘和合而成。",
 "「犹如飞鸟飞行于空中，菩萨也是这样，行无期望之想，周旋到达十方；犹如日宫殿行于虚空，不染众冥，菩萨也是这样，独步三界、心无所著；去除淫、怒、痴三毒的幽暗，犹如莲华生于泥中而不与泥合，菩萨也是这样，处在生死之中，成最正觉，心净如空，永无所著、度脱一切。」",
 "」佛这时说偈：「其心不可得，就没有诤讼；若不得众生，这就是第一忍。菩萨离于懈怠，其志无所行，永无所勤修，才叫最精进。其身及心意，所遣直正无邪，菩萨无所说，是第一精进；若有懈怠者，菩萨化导建立之，无心、无所行，住于第一精进。",
 "「其心不可得，内外无所著；若心不可及，这就是定意。心常自勤修，自然无所有；无思、无正受，才叫证得三昧；之所以说『定意』，是因为能作这样的行，安住而名为自然，这是第一定意。不知慧之所在，何者是自然法？自然与慧，二者都无所有。",
 "「这法不可得，此识行于正法；不以识知法，自然无所有。若有人了悟此行，菩萨之意便坚强，行第一之义，为世间所无所趣向。众会无与伦比，为众宣说佛法；这些人虽游化居止，却无众生之期望想。」佛又告诉善思：「一切诸法犹如幻化，幻化本空、悉无所有；迷惑的愚俗自计己身及他人，都当作『有所有』，因此沉沦五趣；敢于了知这一切的，便都无所畏。",
 "「诸法本末没有内外，因为了知如此，心不怯弱。不以为难『三界三界悉空』；若有菩萨了知这本无，便独步三世而无所难，通达生死犹如虚空，无形、本也无名；一切诸法也是如此，无形无名。由于无明的缘故而驰逸三界，轮转无有边际，犹如五事依托虚空却不能染污虚空。",
 "「因为自然的缘故，心本自清净；只是权巧未即解悟，便有三毒，被五阴、六衰客尘所遮蔽；虽有是非，却不染污本净之心。心一旦开达，畅悟三世皆空，便入于大道。」佛这时说偈：「众生犹如幻，那幻无所有；所宣说如此者，就永无所畏。己身与他人，二者都虚无寂灭；因为能了知于此，就永无所畏。",
 "「其内及外之法，不计度有所在；不以怯弱之心，不以为难世俗。诸法无所障碍，犹如旋于虚空；所至如虚空，这法即自然。若能了知于此，菩萨便无所畏，分别一切法，解了众生之行；他不得众生，其法都是如此；因为剖析诸界，诸界都无所有。",
 "「这叫做入道之行，这叫无上之道；因为达到这殊胜之业，便知众生心行。诸界及众生，二者都无所有；因为念彼如此，便了达一切法。其内及外之事，没有合会期望之想，以此『不除之法』，才叫真本际。这法不可思议，才叫佛法；这一切都无所有，也全都无所成。",
 "「所行能如此，计度而『无人』，以无为之慧，才叫佛慧。这乘是大乘，普遍安护一切，永不畏此世间——而世间也无所有。其在于世界，普世一切界，菩萨无所行，求于无上之慧；这法甚深远，佛法不可思议；若法无可获，这就是接近佛道。",
 "「其佛及经法，这一切都无；若有人这样修行，就得近于佛道。因为这样修行的人，俗人无与为侣；其心无所著，他才近于佛道。」佛又告诉善思：「若有菩萨大士听闻这深经，或读诵受持、讽诵，心不恐怖，善于披上弘誓之铠，心如金刚，便速近佛树、坐于道场，近佛境界、得亲至真，入无碍解脱门，观于无为、无合会之处，到达十方诸佛世界，建立修习大慈无盖道哀，成就十八不共诸佛之法，三世最尊、智慧譬如日月，德无与伦、慧过虚空，道明巍巍不可比喻，证得无边圣、无见顶相。",
 "「若有人听闻这无量的雅正典籍，以这深经为人宣说而信乐者，他过去世曾见诸佛，也不可计数。又不轻慢、戏笑它的人，佛以预见观其人之本，早已信受此经，如来久已见之。若不信乐修习这经典，听了却调笑戏弄，那便是外道异学、诸魔官属、放逸之人。",
 "「信这法的人是佛弟子，佛便是其师、亲自成就他，为他剃除须发而作沙门；不信的人则是外道邪业，属九十六种反逆道法。」佛这时说偈：「见佛坐于树下，行于真道场，若不信佛道，这慧便不可得。那无挂碍之法，究竟不可得；了知法无住处，这就叫解脱。",
 "「意入于圣慧，是一切法之王；诸法及道慧，并非佛所宣说。有为及无为，是愚者所发的期望之想；诸菩萨无想，诸佛大圣明。普遍观察这世间，世间悉不可得；用来晓了世间者，这也是无住处。佛圣及众生，于此没有期望之想；那无思想者，善哉，其慈无上。",
 "「假使众生界如此，法界也如此，这才称之为『菩萨无所著』。因为观见于悲哀，那悲哀无形貌；那悲哀以无貌，不是愚者所能了知之行。五事在虚空，不有、也无住处；一切世俗都是如此，这才是无上之哀。那无上正法，才叫佛法；这不贪著世间，就是自然之法。",
 "「护世者所照，其色无所有；因为这本无色之法，才叫『无见顶』。虚空没有边际，普遍平坦不可获，这是佛之正法，名叫『无能观』。其慧不可及，这是无上大道；慧因为不可得，所以没有坚固。此岸与彼岸，所见或不见，若深解而不行于此，那便是『非想』之求。",
