 "生起大欲、远离恶友，亲近善友、随其所欲。常修殊胜之道、亲近趣向者，常修悲心、安住四摄；常好坚固安住菩提心，佛的功德之聚便不难获得。「善男子！菩萨具足四法，不舍一切智心。哪四种？信佛功德、修集佛智、见佛神通、不断佛种。",
 "这就叫四法。」而说颂：「信解佛德之后，勤修积集佛智；见佛神通之后，勤加守护佛种。修行这样的法，不舍菩提心；随其所见诸佛，倍加生起精进之力。「善男子！菩萨具足四法，终究不会娆乱菩提之心。哪四种？在诸佛面前给侍、从如来处闻法、常赞叹佛德、依止寂静而缘念于佛。",
 "这就是四法。」而说颂：「给侍于如来，善加尊重恭敬；若有所闻之法，闻已如说而行。常赞叹如来，信敬爱乐他；当面听闻殊胜法之后，智者依于义理。常赞叹功德——调御者（佛）于世间所有；他常勤依止，正念于诸佛。屡屡赞叹佛德，常勤观察自己之行；",
 "常乐独处静处，思念如来。善摄这样的法，修行心不散乱；这样的人得三昧，不忘菩提心。「善男子！菩萨具足四法，忆念菩提心。哪四种？我应当作一切众生的良福田、我应当宣说道法、我应当随如来的所趣而趣、我应当实知诸众生之行。",
 "这就是四法。」而说偈：「我应当作世间的殊胜福田，为趣向邪道者示以正路；善逝所趣之处我应当趣，我应当常知众生之行。菩萨大士忆念这些功德，常念菩提殊胜道心；他将速疾成为法王，得神通智、世间无与伦比。「善男子！菩萨具足四法，念一切智心。",
 "哪四种？专志念意是一切诸法之本，应当念此法本；发起一切智心是世间宝塔，应当念此宝塔。这就是四法。」而说颂：「应当专志念意，极好专念其意；这是诸法之本，一切世间之塔。常念菩提心，住意善好安住；这是十力之本，当成为天人之塔。",
 "「善男子！菩萨具足四法，炽然一切智心。哪四种？以势力通集而不失本行、圆满五根之力、身心精进而无有我、勤行精进为利益他人。这就是四法。」而说颂：「所演说的四法，炽然菩提心；若炽然智慧，便得止息烦恼。以势力及通达，如是勤加精进；",
 "安住、服膺这法之后，庄严而无懈怠。这样便不失本誓，善能安住根力；身心无有疲倦，勤进求于实身。安住这样的炽然，增长菩提心；他的智慧也如此，犹如日月增长。「善男子！菩萨有四法，劝发菩提心。哪四种？在大众中称扬赞叹菩提之心、令他人开解菩提之心、善受教诲随顺师长而发清净心、令一切烦恼不得自在。",
 "这就是四法。」而说颂：「劝导唱起道心，先安住此以为根本；必将获得一切智，这叫做知因者。这一切智心，清净而常照明；常住于此中，为世间所顶礼。常出柔软之语，速疾领受教诲；谘问诸师长，得一切智殊胜之心。本性常清净，守护菩提心；",
 "白净离烦恼，最胜而不相违。「善男子！菩萨有四法，显示菩提心。哪四种？这是我所住处、安住此已而开示显说、了知此心有无量功德、也为他宣说这样的事。这就是四法。」而说颂：「善住于所住之处，菩萨安住于此之后；称扬这样的法，即菩提之妙心。",
 "道心功德无量，发起与称扬等同；称扬之后便修行，这是称扬者所得。「善男子！菩萨有四法，教人修菩提心。哪四种？即不粗犷、言说柔软、没有粗涩、颜色和悦。这就是四法。」而说偈：「柔软解说义理，常无粗犷；和颜安住这法，他便是教人修菩提心。",
 "「善男子！菩萨有四法，以菩提心、善根为首。哪四种？成就圆满相好、开门大施；修净佛土、行种种布施；净于智慧、常伏骄慢；满足智慧、修集多闻。这就叫四法。」而说颂：「常开门大施，他便到达相好之岸；善好种种布施，这样当有净土。",
 "常无骄慢，恒求积集佛智；积集多闻而无满足，这样便得锐利智慧。这样的殊胜妙相，以方便生起道根；这是巧心所转，积集先前诸功德。「善男子！菩萨有四法常喜乐。哪四种？喜乐见佛。见其余菩萨精进殊胜者而生喜乐，作这样说：『我当何时满足受记？",
 "』受于无上菩提道记：『我当何时在诸众生前作诸佛事？』于佛的智慧生喜乐心。这就是四法。」而说颂：「我当何时现见佛？他生喜乐欲见佛；见其余菩萨殊胜精进者，生喜欲修此精进。我当何时圆满功德之聚？得授殊胜之记、证得菩提；",
 "以殊胜智慧在某一方作法王，菩萨常生这样的喜欲。我何时于世间作佛事？得神通智而到彼岸；名闻普遍、十方供养，菩萨常生这样的喜欲。「善男子！菩萨有四法不喜乐。哪四种？不喜以不实功德获得称誉与诸利养；不喜获得帝释、梵天、护世及人天的富乐；",
 "不喜一切声闻、缘觉（之道）；不喜一切外道所获得的殊胜供养之事。这就是四法不喜乐。」而说颂：「不喜名声与大利养，对于身、命、财也是如此！不喜帝释、梵天及护世，这些邪有全都是无常。不喜声闻及缘觉，唯除生起殊胜大乘之心；不喜世间禅定及外道，不喜身见及边见。",
 "「善男子！菩萨有四法，守护一切智心。哪四种？如说而住、如作而说、于诸众生其心平等、于善法生极欲之心。这就是四法。」而说颂：「如说、如住、如作而说，等心待众生、极欲于道；善能安住这四种殊胜之法，常护道心而不忘失。",
 "「善男子！菩萨有四法，是所应作。哪四种？修集多闻、思念多闻、宣说所闻、不退寂静。这就是四法。」而说颂：「他常勤积集未闻之法，常修念、思惟多闻；常勤为人宣说多闻，常勤修行以求得禅。「善男子！菩萨有二法，安定一切智心而行布施。",
 "哪两种？专意念定；布施而舍、不望果报。这就是二法。」而说颂：「以欢喜心而施与，施已生喜而不望报；一切悉舍、趣向菩提，以定心布施之后证得菩提。「善男子！菩萨有二法，以一切智为首修持净戒。哪两种？于诸众生无侵害之心、于毁戒者所生大悲之心。",
 "这就是二法。」而说颂：「不生毁害之心，平等布施上中下；倍加增长悲心，对于恶逆的众生。「善男子！菩萨有二法，以一切智为首修行忍辱。哪两种？自己舍弃己乐、施与他乐。这就是二法。」而说颂：「不求自己的安乐，常为利益安乐他人；",
 "这样便有如此的忍辱，以佛菩提为道。「善男子！菩萨有二法，以一切智为首修行精进。哪两种？以菩提心为首、不舍诸众生。这就是二法。」而说颂：「修行一切白净之法，以上求佛道之心为首；不见我、不见众生，精进而不毁减。「善男子！菩萨成就二法，以一切智为首修行禅定。",
 "哪两种？以方便入于禅定、以本愿之力而出。这就是二法。」而说颂：「勇健者常起，智者行于禅定；降伏诸结使，恒常欲得禅。以本愿力持而出，当为世间导师；有这样的功德，便获得禅定。「善男子！菩萨成就二法，以一切智为首而有智慧。",
 "哪两种？自己远离诸见、为了断除一切众生之见而修行智慧。这就是二法。」而说颂：「他远离诸见，修利众生；有殊胜之智现前，以智安隐行道。「善男子！菩萨成就四法，而有方便。哪四种？慈愍众生而作为救护、大悲真实而无疲倦、喜乐于法而生欢喜、舍离烦恼而无怯弱。",
 "这就是四法。」而说颂：「修慈而无瞋恚，起悲而无疲倦；以法生欢喜，舍烦恼而无难。「善男子！菩萨有四法无厌。哪四种？多闻无厌、积德无满、阿练若处（寂静处）无满、回向无满足。这就是四法。」而说颂：「求闻无满、积福如此，阿练若处无满足；",
 "福德回向无满足，菩萨有这样四种无厌。「善男子！菩萨有四法无足。哪四种？这菩萨忆念过去佛，作这样的念：『这些佛等都修集最胜菩提，我如今为何不修集？』忆念未来佛：『我也入在此数之中。』忆念现在佛，念这佛时而作这样的念：",
 "『这些佛等都现前了知一切诸法。』在这些念中而无所怯弱。这就是四法。」而说颂：「忆念过去佛，无怯之心增长；那些佛得殊胜之道，我为何不能得？忆念未来善逝，我在此数之中；无怯而倍加精进，我必定在此数之中。忆念现在导师，本行菩萨道之时；",
 "我应当断除诸结，证得寂灭菩提。解了一切诸法，所住如其所欲；终究不生怯心，倍加生起好胜精进。「善男子！菩萨有四法，不退转大乘。哪四种？其心如地、其心如水、其心如火、其心如风。这就是四法。」而说颂：「其心如地如水，心也如风如火；",
 "作与不作同等，不得道也不退转。「善男子！菩萨有四法，解知无我。哪四种？这菩萨作这样的念：『诸众生界，我应当尽知这些众生的心行。』『诸众生界，我应当尽知这些众生的诸根而为他们说法。』『诸众生界，我应当断除一切烦恼而为他们说法；无量的佛智，我们应当觉了，其实并非我身能觉此法，也不是我心。",
 "』『是我的诸善根能觉此法，无有我者，才名为菩萨！』这就是四法。」而说颂：「众生界的种种心，所行不可思议；烦恼与虚妄分别，妄想生起是非。佛智也是如此，无量不可思议；不是我的能力所能解了佛智。诸结使与此相违，无色而不可见；",
 "我应当尽皆除断，显示解脱之道。「善男子！菩萨有四法，无有怯弱。哪四种？回向诸善根、修习方便慧、修习信进念力、信无上道。这就是四法。」而说颂：「善喜悦充润，慧方便如众香；信、精进、念、力，这样便有解脱之道。这四种慧法，持法而无有厌；",
 "为厌倦者作依止，也为世间作救护。失译人名附三秦录。「善男子！菩萨有四障法，应当觉知。哪四种？毁谤正法、秘吝惜法、怀着增上慢、修无色定。这就是四法。」而说颂：「菩提心有四种，宣示名为障碍；菩萨应当觉知，应当屡屡远离。",
 "毁谤正法、多闻而怀吝惜；增上慢贡高、不善于起禅定。因此应护正法，闻已广为流布；舍除骄慢、不贡高，远离那不善的禅定。「善男子！菩萨有四法，所造速疾。哪四种？所作以智慧而非骄慢；所有善根回向菩提、不趣向下乘；",
 "对一切诸趣不生染著，若生染著则一向专为化度众生；昼夜三时常修三分，灭除过去恶业、未来不再造作。这就是四法。」而说颂：「所造以智不以慢，回向善法于上道而非下乘；智者不信于诸有，发心为利益诸众生。昼日三时、夜里也如此！",
 "以三分悔过灭除先前的恶；不造众恶、积集诸善，智者这样积集善业。「善男子！菩萨有四法极好。哪四种？不自称举、不轻慢他人、远离诸恶、舍除诸慢。这就是四法。」而说颂：「不自称举、不轻慢他人，所造诸恶悔而不作；不生骄慢及我慢，其心端直修善行。",
 "「善男子！菩萨有二法，端直速疾。哪两种？若有人问则如实而答、先前所见之事无所覆藏。这就是二法。」而说颂：「如问而演说，不藏先前所见；宁可舍弃身命，终究不说妄语。于此法正直，这就是贤善之根；他获得质直，速疾觉悟殊胜菩提。",
 "「善男子！菩萨有二法，没有谄伪。哪两种？虽多获利益而不想赞叹自己的德行、不得利养也不自称举。这就是二法。」而说颂：「虽多获利养，也不赞叹显示自己的德行；大智所不欲，这是不谄者所得。假使不得利养，这是我本来的业；不欲他人有过，勿令他的业成熟。",
 "「善男子！菩萨有二法，不望他人回报。哪两种？我应当利益一切众生，而不是众生来利益我；我应当觉知而为菩提。这就是二法。」而说颂：「我应利益众生，我荷担他们；我求无为之道，不观望他人回报。我不求有为，我求无为之道；",
 "我摄护世间，不望回报而得道。「善男子！菩萨有二法，作与不作。哪两种？对不知恩者而常供给、对知恩者而作重任。这就是二法。」而说颂：「对不知恩的众生，于他们不望回报；诸阴、界、入等，都为他作菩提之因。「善男子！",
 "菩萨有二法，是所应处。哪两种？常值遇诸佛、也常值遇菩萨乘者。这就是二法。」而说颂：「两种所应之处，此处于名称增长；得值遇诸如来，是菩萨所识知的。「善男子！菩萨有二法所不应修。哪两种？不与愿行声闻乘者而共同止住；",
 "不惊畏诸有，独处宴默。这就是二法。」而说颂：「不与（声闻）修行者，而共同止住；不惊畏诸趣，依止于宴寂之处。「善男子！这就叫初入如来密藏的根本句。菩萨若入这初根本句，这菩萨便能成就如来秘密藏法。」世尊宣说入如来密藏初句法时，六万众生及天与人发起了无上正真道心，一万菩萨证得无生法忍，五百比丘不受诸法、永尽诸漏、心得解脱。",
 "这时这三千大千世界，六种震动、大光普照，人天伎乐不鼓自鸣，人、天、阿修罗等，同声三唱这样说：「若有众生得以听闻这如来密藏法，便快得善利；若有书写、受持、读诵、如说修行，这些众生都不会失掉这样的如来秘密藏法。",
 "」这时无量志庄严王菩萨听闻如来密藏法之后，即作这样的念：「我如今应当以何等供具供养如来、应供、正遍觉？」又作这样的念：「外物容易舍、内事难以舍，我如今应当以自身奉供如来世尊！」即升上虚空而说偈：「我今奉事独觉（世尊），以自身作供养；",
 "以此无上之舍，愿令（我）如导师。以财物供养二足尊，此事并不为难；什么是希有？所谓以自身供养。我今供养无等者，以自身奉事遍眼（世尊）；为世人与人天所供养，如大智师子。」这时无量志庄严王菩萨便放身投向如来之上。正当那时，以佛的神力，有未曾有的华——异华异色，极为鲜净、极妙端严——散在如来身上。",
 "这菩萨之身既不坠地也不现于空中，这些华等到达佛身上，随即又涌起停住于虚空中，成为大华盖、覆盖四天下。这华盖中垂悬华贯、放出大光明，这光明中现出妙莲华，这莲华上有菩萨安坐，如同无量志庄严王。这些菩萨等从华台而起，顶礼佛足、同声请求说：",
 "「唯愿世尊！宣说如来秘密藏法，不要令它断绝，并护持如来密藏的眷属。」这时大德摩诃迦叶生起希有之心、赞叹未曾有，对佛说：「世尊！这无量志庄严王菩萨以身庄严供养如来，以身供养如来之后，现出这些菩萨的种种庄严之事。世尊！",
