report_content += "1. **格式检查**：modern字段以【小标题】开头、包含【义解】且义解后有完整正文白话；\n"
report_content += "2. **咒文检查**：梵文密咒/陀罗尼完整照录原字原音，未被简化、翻译、转写为简体或意译；\n"
