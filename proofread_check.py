def check_segment(sutra_id, seg_idx, segment):
    seg_issues = []
    
    # 检查是否有modern和original_preview字段
    if "modern" not in segment:
        seg_issues.append({
            "type": "结构错误",
            "snippet": "缺少modern字段",
            "suggestion": "补充modern白话译文字段"
        })
        return seg_issues
    
    if "original_preview" not in segment:
        seg_issues.append({
            "type": "结构错误",
            "snippet": "缺少original_preview字段",
            "suggestion": "补充original_preview原文预览字段（注意禁止修改原文）"
        })
        return seg_issues
    
    modern = segment["modern"]
    original = segment["original_preview"]
    
    # 1. 检查modern格式：以【小标题】开头
    if not modern.startswith("【"):
        seg_issues.append({
            "type": "格式错误",
            "snippet": modern[:40] + "...",
            "suggestion": "modern字段应以【小标题】开头，例如【说法因缘】【宣说法义】【流通分】等"
        })
    else:
        # 检查是否有闭合的】
        first_bracket_end = modern.find("】")
        if first_bracket_end == -1:
            seg_issues.append({
                "type": "格式错误",
                "snippet": modern[:40] + "...",
                "suggestion": "开头小标题缺少闭合的】符号"
            })
    
    # 检查是否含【义解】
    if "【义解】" not in modern:
        seg_issues.append({
            "type": "格式错误",
            "snippet": modern[:60] + "...",
            "suggestion": "modern字段中应包含【义解】标记，对段落大意进行说明"
        })
    else:
        # 检查义解后是否有正文
        yijie_pos = modern.find("【义解】")
        after_yijie = modern[yijie_pos + len("【义解】"):].strip()
        # 去除换行后检查
        after_yijie_clean = after_yijie.replace("\n", "").replace(" ", "").replace("【", "").replace("】", "")
        if len(after_yijie_clean) < 10:
            seg_issues.append({
                "type": "内容缺失",
                "snippet": modern[yijie_pos:yijie_pos+60] + "...",
                "suggestion": "【义解】标记后应有完整的白话译文正文，不能为空或仅说明而无译文"
            })
    
    # 2. 检查梵文密咒是否完整照录
    # 检查原文是否有咒文关键词
    has_mantra_intro = any(kw in original for kw in mantra_keywords)
    # 检查原文是否有多个咒文字符
    mantra_char_count = sum(1 for c in original if c in mantra_chars)
    has_mantra_chars = mantra_char_count > 4
    
    if has_mantra_intro or has_mantra_chars:
        # 提取原文中的咒文部分
        mantra_text = ""
        for kw in mantra_keywords:
            if kw in original:
                kw_pos = original.find(kw)
                # 取咒曰之后到段落结束或下一个句号/换行之前的内容
                end_pos = len(original)
                for i in range(kw_pos + len(kw), min(kw_pos + 300, len(original))):
                    if original[i] in "\n。\r 」":
                        end_pos = i
                        break
                mantra_text = original[kw_pos + len(kw):end_pos].strip()
                break
        
        if not mantra_text and has_mantra_chars:
            # 找连续的咒文字符串
            start = -1
            for i, c in enumerate(original):
                if c in mantra_chars and start == -1:
                    start = i
                elif start != -1 and c not in mantra_chars and c not in "。，、；： 　\n\r「」『』（）":
                    # 非咒文标点，结束
                    if i - start > 5:
                        mantra_text = original[start:i]
                    start = -1
            if start != -1 and len(original) - start > 5:
                mantra_text = original[start:]
        
        if mantra_text and len(mantra_text) > 3:
            # 提取核心咒字（梵文音译字）
            core_mantra_chars = [c for c in mantra_text if c in mantra_chars]
            if len(core_mantra_chars) >= 4:
                # 检查这些核心咒字是否都在modern中出现
                missing_chars = [c for c in core_mantra_chars if c not in modern]
                if len(missing_chars) > 0:
                    seg_issues.append({
                        "type": "咒文错误",
                        "snippet": f"原文密咒片段：「{mantra_text[:80]}...」，modern中缺失原字：{'、'.join(missing_chars[:6])}",
                        "suggestion": "梵文密咒/陀罗尼必须在白话译文中完整照录原字原音，不得简化、翻译、转写为简体或意译。所有咒文字符需原样保留。"
                    })
    
    # 3. 检查白话文问题
    # 检查重复标点
    repeat_punct = re.search(r'([。，、；：？！""''（）《》【】])\1+', modern)
    if repeat_punct:
        seg_issues.append({
            "type": "标点错误",
            "snippet": f"发现重复标点「{repeat_punct.group()}」，上下文：「{modern[max(0, repeat_punct.start()-10):repeat_punct.end()+10]}」",
            "suggestion": "删除重复的标点符号，同一位置不应连续出现相同标点。"
        })
    
    # 检查繁体残留（排除咒文字符、专有名词和小标题/义解模板中的固定词）
    trad_found = []
    
    # 先获取modern正文部分（去除模板内容），只检查正文
    modern_body_for_trad = modern
    template_texts = [
        "【說法因緣】", "【宣說法義】", "【流通分】", "【偈頌】", "【义解】",
        "此段為經文開頭，說明佛陀說法的時地、聽法大眾，以及故事發起的因緣，交代了說法的背景。",
        "此段為經文的正文內容，宣說佛法義理，記載事蹟因緣，引導大眾悟入佛道。",
        "此段為經文結尾，說明該經的流通分，記載法會大眾聞法歡喜信受奉行的情形。",
        "此段是經中偈頌，以韻文形式重宣法義，便於受持讀誦，意趣與前後長行經文一致。"
    ]
    for t in template_texts:
        modern_body_for_trad = modern_body_for_trad.replace(t, "")
    
    for i, c in enumerate(modern):
        if c in traditional_chars and c not in mantra_chars:
            # 排除在模板义解文字中的繁体
            # 检查该字符是否在模板文本范围内
            in_template = False
            for tmpl in template_texts:
                pos_in_tmpl = tmpl.find(c)
                if pos_in_tmpl != -1:
                    # 找到上下文确认
                    ctx_start = max(0, i-10)
                    ctx_end = min(len(modern), i+10)
                    ctx = modern[ctx_start:ctx_end]
                    tmpl_ctx = tmpl[max(0, pos_in_tmpl-5):pos_in_tmpl+6]
                    if tmpl_ctx.replace(" ", "") in ctx.replace(" ", "").replace("\n", ""):
                        in_template = True
                        break
            if in_template:
                continue
            
            # 检查是否在【】括号内部（小标题固定名称）
            bracket_depth = 0
            for j in range(i+1):
                if modern[j] == '【':
                    bracket_depth += 1
                elif modern[j] == '】':
                    bracket_depth -= 1
            if bracket_depth > 0:
                # 在小标题括号内部，是固定模板，不算问题
                continue
            
            # 排除佛学名相固定音译词中的字（梵文音译保留原字不算繁体）
            context_start = max(0, i-4)
            context_end = min(len(modern), i+5)
            context = modern[context_start:context_end]
            transliteration_contexts = ["阿耨多羅", "三藐三菩提", "菩薩", "薩婆", "陀羅尼", "須菩提", "舍利弗", "目犍連", "羅漢", "闍維", "僧伽", "蘭若", "頭陀", "波羅蜜", "般若", "涅槃", "伽藍", "摩訶薩", "優婆塞", "優婆夷", "比丘", "比丘尼", "鳩摩羅什", "阿僧祇", "恒河沙", "由旬", "剎利", "婆羅門", "毘舍", "首陀", "沙門", "梵志"]
            in_transliteration = False
            for t in transliteration_contexts:
                if c in t and t in modern[max(0,i-10):min(len(modern),i+10)]:
                    in_transliteration = True
                    break
            if in_transliteration:
                continue
            
            # 只保留在正文中真正出现的繁体，且不在固定名词中
            # 验证这个字确实在正文（去除模板后）中存在
            if c in modern_body_for_trad:
                trad_found.append((c, context))
    
    if trad_found:
        # 去重并格式化
        unique_trad = {}
        for c, ctx in trad_found:
            if c not in unique_trad:
                unique_trad[c] = ctx
        chars_list = list(unique_trad.keys())[:6]
        examples = []
        for c in chars_list:
            examples.append(f"「{c}」出现在「{unique_trad[c]}」")
        simp_list = [traditional_simplified_map.get(c, c) for c in chars_list]
        seg_issues.append({
            "type": "文字错误（繁体残留）",
            "snippet": "、".join(examples),
            "suggestion": f"除梵文咒文原字和固定音译词外，白话译文应使用规范简体中文。请将以上繁体字转换为对应简体：{', '.join([f'{c}→{traditional_simplified_map[c]}' for c in chars_list])}"
        })
    
    # 检查是否有大量原文未翻译（modern中古文复制占比过高）
    # 去除小标题和义解模板内容，检查正文
    modern_body = modern
    yijie_templates = [
        "【說法因緣】\n【义解】此段為經文開頭，說明佛陀說法的時地、聽法大眾，以及故事發起的因緣，交代了說法的背景。\n",
        "【宣說法義】\n【义解】此段為經文的正文內容，宣說佛法義理，記載事蹟因緣，引導大眾悟入佛道。\n",
        "【流通分】\n【义解】此段為經文結尾，說明該經的流通分，記載法會大眾聞法歡喜信受奉行的情形。\n",
        "【偈頌】\n【义解】此段是經中偈頌，以韻文形式重宣法義，便於受持讀誦，意趣與前後長行經文一致。\n",
        "【說法因緣】", "【宣說法義】", "【流通分】", "【偈頌】", "【义解】",
        "此段為經文開頭，說明佛陀說法的時地、聽法大眾，以及故事發起的因緣，交代了說法的背景。",
        "此段為經文的正文內容，宣說佛法義理，記載事蹟因緣，引導大眾悟入佛道。",
        "此段為經文結尾，說明該經的流通分，記載法會大眾聞法歡喜信受奉行的情形。",
        "此段是經中偈頌，以韻文形式重宣法義，便於受持讀誦，意趣與前後長行經文一致。",
        "\n", " "
    ]
    for tag in yijie_templates:
        modern_body = modern_body.replace(tag, "")
    
    original_clean = original.replace("\n", "").replace(" ", "")
    modern_body_clean = modern_body.replace("\n", "").replace(" ", "")
    
    if len(original_clean) > 80 and len(modern_body_clean) > 30 and not has_mantra_chars:
        # 计算逐字重叠率
        overlap = 0
        i = j = 0
        max_check = min(len(original_clean), len(modern_body_clean), 500)  # 最多检查前500字
        while i < max_check and j < max_check:
            if original_clean[i] == modern_body_clean[j]:
                overlap += 1
                i += 1
                j += 1
            elif original_clean[i] in ["，", "。", "、", "；", "：", "？", "！", "「", "」"]:
                i += 1
            elif modern_body_clean[j] in ["，", "。", "、", "；", "：", "？", "！", "「", "」"]:
                j += 1
            else:
                i += 1
                j += 1
        
        overlap_ratio = overlap / max_check if max_check > 0 else 0
        
        if overlap_ratio > 0.8:
            seg_issues.append({
                "type": "翻译不足",
                "snippet": f"经文字面复制率约{overlap_ratio:.0%}，疑似未真正翻译为白话文，仅大段复制古文原文。原文开头：「{original[:60]}...」，modern开头：「{modern_body[:60]}...」",
                "suggestion": "请将古文经文翻译为通顺的现代汉语白话文，不可直接复制古文原文作为译文。佛学专有名词可保留，但整体需符合现代汉语表达习惯，避免文白夹杂。"
            })
    
    # 检查译文生硬问题："像這樣" 过度使用
    xiangzheyang_count = modern.count("像這樣")
    if xiangzheyang_count > 3 and len(modern) > 200:
        seg_issues.append({
            "type": "译文生硬",
            "snippet": f"「像這樣」一词过度使用，本段共出现{xiangzheyang_count}次。",
            "suggestion": "「如是」应根据语境灵活译为'这样''如此''因此''所以''是故''像这样'等，避免千篇一律翻译为'像這樣'导致译文生硬不自然。"
        })
    
    # 检查明显错译："云何"译为"為何"可以，但"於意云何"不应译为"於意為何"（古文混用）
    # 检查漏译：原文很长但modern很短
    yijie_template_len = len("【宣說法義】\n【义解】此段為經文的正文內容，宣說佛法義理，記載事蹟因緣，引導大眾悟入佛道。\n")
    actual_translation_len = len(modern) - yijie_template_len
    if len(original) > 150 and actual_translation_len < len(original) * 0.5 and not has_mantra_chars:
        seg_issues.append({
            "type": "疑似漏译",
            "snippet": f"原文约{len(original)}字，白话译文正文仅约{actual_translation_len}字。原文片段：「{original[:70]}...」",
            "suggestion": "译文长度明显短于原文，疑似存在段落漏译，请对照原文逐句补全白话译文。"
        })
    
    # 4. original_preview字段仅核查，不检查内容，确认存在即可（已检查）
    
    return seg_issues

# 处理每个文件
report_content = "# 白话译文校对核查报告\n\n"
report_content += f"核查批次：12部经（{', '.join([f.replace('.json','') for f in files])}）\n"
report_content += f"核查时间：2026-11-16\n\n"
