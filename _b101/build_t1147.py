    chunks=[]; cur=[]; i=a
    while i<b:
        if flag[i]:
            c=full[i]
            if c=='（':
                j=i+1
                while j<b and full[j]!='）': j+=1
                i=j+1; continue
            if c not in '「」\n': cur.append(c)
            i+=1
        else:
            if cur: chunks.append(re.sub(r'\s+','',''.join(cur))); cur=[]
            i+=1
    if cur: chunks.append(re.sub(r'\s+','',''.join(cur)))
