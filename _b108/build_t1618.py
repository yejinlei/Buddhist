 "生義可見，故「性」訓為「生」；五分法身是生性義。如來正說，眾生信樂而生三種信：一信有真實道理、"
 "二信得五分法身功德、三自利利他德備修五分身。",

 "五分身生則顯得性，故五分法身生以此為性義。四是不壞義，此性在凡夫不染、在聖不淨，故名不壞。"
 "五是秘密藏義，親近則行淨、乖違則遠離；此法難得幽隱，故名秘密，即名藏義。生有四種：一是觸生，"
 "如男女交會而有子；",

 "二是嗅生，如牛羊等類，雌雄有欲心，雄以鼻嗅雌等根便有子。三是沙生，如雞雀等，雌雀起欲心，"
 "以身坌入塵沙之中而有卵等生子。四是聲生，如鶴、孔雀等類，有欲心聞雄鳴聲，也生卵生子。"
 "一切出卵不可食，因皆有子。",

 "分別性是無有空，因分別無法可得。依他性是不如空，如此破所執。真實性是自性空，無人法二我，"
 "是自性空。再者，分別性如空花，是極無；依他性異於空花，似幻化，非空有無；觀依他性不有不無，"
 "故能得道成聖。",

 "空無是斷見，觀空無不能得道成聖。一切煩惱別執著分別性，一切諸法欲樂觀習真實性。執著、觀習這二屬依他性。"
 "這二種法名為熏習：一煩惱種子熏習、二道種子熏習。第二熏習增長本識，因同類的緣故。",

 "本識緣如如而起四謗，是虛妄熏習。種子、煩惱同是虛妄，所以熏習能增長本識。好比甜物能增長淡味，"
 "淡也是甜性，同性故能增長。具足諸能者，明業有四種：一被作不被長，如利智之人遇惡知識起不善業是「作」，"
 "隨即追悔故「不被長」。",

 "二被長不被作，如羞慚之人隨人修行，此善被增長轉廣，不能自起其心故「不作」。三亦作亦長者，"
 "如人作善業又恒數習，此善業轉廣大。四不作不長者，即無漏善業。若轉增長生死報名為「作者」，"
