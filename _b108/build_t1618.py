 "行緣識、識緣名色、名色緣六入、六入緣觸受等是同時因。所以說是事有故是事有，是為破外道的生有義。"
 "外道說：一切眾生從自在天我有，故生死是有。內義與此不同。",

 "現在破斥：由前因生故得生。你的自在天並非能生生死的因，有是所生的，所以自在天不得是有。"
 "故不得是有，而得是有。所以佛立義：是事有即有生。你的自在天是有，卻不是能生生者，不同於內義。"
 "乃至從世性、微塵等生，也一樣。又外道立無因有果，果自然生。",

 "所以破外道：此物有是因有，故果事成立。之所以明二義，為明因緣具足故得生。若此物有故，"
 "此物有是緣；若此物生故此物生，是明因義。有分者，生處即是生因、生緣。此有分識體，是果報法，"
 "決定是自性無記。",

 "四有：從識支至六歲是生有；從七歲以上能分別生熟起貪、至未捨命是業有；死有者唯是一念，"
 "中有即中陰。就業有中，六識起三種業，善、不善、不動等三業。有為有分識所攝持，六識自謝滅，"
 "由有分識攝持之力用而相續。",

 "問：何故立有分識？一期生中常緣一境。若生人天，此識見樓觀等事報；若起六識，其用粗重覆障，"
 "則不覺得此識之用。若生惡道，此識但緣火車等；若報起六識用強，則不覺得此識之緣。"
 "若欲界六識緣欲境，凡夫不能覺知，乃至無色界也一樣。",

 "若無色界諸識滅，此有分識之用便顯現，如梨耶與意識。所謂種子，此相續變異，能感未來果報，"
 "名為種子。相續而無變異，不是種子；若只變異而無相續，也不是種子；相續與變異不相離，故成種子。"
 "如螺的白色，非一非異。",

 "若白色就是螺，螺便無三塵；若白色異於螺，則見白色便不得螺。不可說定異，因不異故，名為白螺。"
 "相續變異也如此，故成種子。緣此熏習力，本識未來得生。釋曰：緣熏習力而種子若成，本識得生；"
 "緣未來顯識，未來分別六識得生。",

 "所以生死沒有前後。若離煩惱，業則不得生。若生死有前分，則另有前分眾生處起煩惱業，感前分處；"
 "既無前分眾生起業，就沒有前分生死，故知生死無始無初。四義明無：第一「非本」，若眾生初無後有，"
 "此無不能作有之本，有二種過失：",

 "一是若無不能生後，若能生有則不是無；二是平等過失，若虛空中能生花、能生有事，才可從無生有。"
 "二者不見離欲眾生生故，生死無初：若生死初無貪欲等、後方有貪欲等，那離欲的阿羅漢等無欲也應生欲；"
 "因羅漢更不生欲，故知生死無初。",

 "三者修行梵行無用故，故生死無初：一切聖人修八聖行，為滅令不生而修梵行，離欲之人更不生滅，"
 "故知生死無初。四者生死有二種：一惡報、二善道。這善惡由善惡二因，不得無因。生死之初是善道還是惡道？",

 "若是善道，則未有善因；若是惡道，則未有惡因。離善惡二道更無第三道，故知無初。難曰：初者自然不用因緣，"
 "後者須因緣。若如此，此義不然，有二過：一即理不平等、二因果不相似。若你說生死不由因、後由因，"
 "則不平等——初後都是生死，為何一由因、一不由因？",

 "二不相似者：果也有因、因也有因，因果皆有因故得相似，若相似則能生同類。你若前無因，後也應無因；"
 "若前無因、後有因，則不能生；若能生，豆應生麥、麥也應生豆。然而並非如此，故知你所謂前為後果作因，"
 "前因不成為因。",

 "佛說偈，初句「顯識」即是梨耶，梨耶即果報識；「分別識」即是煩惱識，從果報識起煩惱識，煩惱識即陀那等。"
 "次句明從煩惱起識、識起熏習，熏習即是業功能，能轉變本識成種子識。次句從業起果報。次句總結生死輪轉。",

 "輪轉，因不定故，或因轉作果、或果轉作因。所謂「熏習有二種」以下，為顯二義：一顯生死方便名為邪、"
 "亦名違逆，二顯涅槃方便名正、亦名隨順。執著分別性者：一切諸法有三種性——一分別性、二依他性、"
 "三真實性。",

 "分別性，是名言所顯的諸法。依他性，是一切諸法因果道理所顯。真實性，是一切諸法如如之性。"
 "分別以無相為性，依他以無生為性。所謂「性」，自有五義：一是自性種類義，一切瓶衣等不離四大種類，"
 "同是四大性，是自性義。",

