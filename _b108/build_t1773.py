 "这是三难。如是相违，如何和会？此中，真谛三藏解：补处菩萨生于彼天，虽无中夭，受多死生。"
 "之所以如此，一由旬城所有芥子，百年去一乃至尽时，是一兵刀劫量，这即人间四百年为彼一日一夜；"
 "一日一夜中除四芥子，一月除百二十芥子，乃至四千年中除五十七亿六万芥子，不过二三升。",

 "然而释迦菩萨下生之时，一由旬城芥子已尽；弥勒菩萨下生之时，彼城芥子除去一半有余。"
 "故知于彼经历多死生，而于阎浮唯有一生，故说此为「一生补处」。三藏法师作如是通。"
 "若依此义通其余经论者，诸说五十余亿等文，只是理当于彼天一生之数，不说上下之间唯有尔许之年。",

 "由是道理，故不相违。若准论文，于彼天中经历多死生，自有道理。"
 "如《瑜伽论》第四卷说：四大王众天满足寿量，是等活大那落迦一日一夜；则以此三十日为一月，"
 "十二月为一岁，彼寿五百岁。如是以三十三天寿量成黑绳寿量，以时分天寿量成众合寿量，"
 "以知足天寿量成号叫寿量，以乐化天寿量成大号叫寿量，以他化自在天寿量成烧热寿量，应知亦尔。",

 "极烧热大那落迦有情寿量半中劫，无间大那落迦寿一中劫。准此而言，彼知足天满足寿量，"
 "是号叫大那落迦一日一夜；即以此三十日为一月，十二月为一岁，彼寿四千岁。如是大号叫寿量、"
 "烧热寿量转倍于前，",

 "极热半劫、无间一劫，也转倍之。然而今弥勒菩萨在知足天经历半劫有余、释迦菩萨在于彼天经历一劫有余，"
 "且经号叫天一寿量时已历彼天无数死生，何况经历半劫及一劫呢？"
 "其次第七明二世有无：慈氏出世在于贤劫，贤劫千佛诸经同说。",

 "过去未来二劫之中千佛有无，经说不同。如《观药王药上经》中，释迦佛说：我昔于妙光佛末法中出家，"
 "闻此五十三佛名。以心喜故，后转教人，乃至三千人同音赞叹、一心敬礼，即时超越无数亿劫生死之罪。",

 "其初千人者，华光佛为首、下至毗舍，于庄严劫成佛，即过去千佛。中千人者，拘留孙佛为首、"
 "下至楼至，于贤劫中次第成佛。后千人者，日光如来为首、下至须弥相佛，于星宿劫当得成佛。"
 "依此经文，三世有千佛。",

 "《大智度论》第九卷说：前九十劫有三佛，后一劫有千佛。九十劫初劫有毗婆尸佛，第三十劫中有二佛，"
 "一名尸弃、二名鞞怒婆附。第九十一劫初有四佛，一名迦罗鸠餐陀、二名迦那含牟尼佛、三名迦叶佛、"
 "四名释迦牟尼。",

 "《贤劫经》说：从拘留秦佛至九百九十九佛，共出前半劫，后有楼至佛独用半劫。楼至灭后，"
 "更六十二劫空过无佛。过尔有一佛兴，号曰净光称王，寿十小劫。过此佛后，复三百劫也空过无佛。"
 "依此经论，去来二劫应无千佛。",

 "如何和会？解：有无二说，皆实不虚。之所以如此，随机见闻有无不定，故说有无皆不相妨。"
 "问：贤劫之量，以何为限？楼至如来独用半劫，是一相续故是一寿、还是多过去故为多寿？"
 "解：《金刚力士经》说：昔有转轮圣王，千子发心，愿求作佛。",

 "王欲试其谁先得佛，于是取千筹，以香汤洗之，令千子取。得第一者最初成佛，如是至九百九十九佛，"
 "最后一子为第千佛。诸兄讥言：我等成佛，化人已尽；你后作佛，何所度呢？于是小子闻此悲泣。",

 "后复思惟：世界无边，众生不尽。我今发愿：愿我后作佛时，寿命与诸兄等，所度众生其数也同。"
 "于是地动，佛与其记。因此缘故，独用半劫。以啼泣故，名啼泣佛。于是诸兄即愿作金刚神护楼至佛。",

 "《贤劫经》中也同此说。依此经文，一寿之量等诸兄等。说「一寿」者，数多为一，一本所垂、"
 "一名出故。贤劫量者，相传说：六十四劫为一大劫，名贤劫等。之所以如此，火水风劫一周转讫合六十四，"
 "以此为限。",

 "其次第八三会增减：然而通论一化说法之会，有无数会，如何唯说而说三会度尔许呢？"
 "准度前佛所遗弟子，通论诸佛度先所遗，这也未必唯在三会，或一二会度先所遗，"
 "或有四五乃至十会。然而今释迦、弥勒二佛，齐有三会度先弟子，只是其所度有多少罢了。",

 "如《菩萨处胎经》佛语弥勒说：你生快乐国，不如我累苦；你说法甚易，我说法甚难。"
 "初说九十六亿、二说九十四亿、三说九十二亿；我初说十二、二说二十四、三说三十六。"
 "你所说的三种人，是我先所化：",

 "九十六亿人受持五戒者、九十四亿人受持三归者、九十二亿人一称南无佛者。你父梵摩净将八万四千，"
 "非我先所化，是你所开度，乃至广说。案：三会唯度小乘弟子，因皆证得阿罗汉果故。"
 "若论大乘根性之人、令得无生忍等果者，无非先佛之所化度，故不限于三四会等。",

 "于中委悉，文处当说。其次第九明发心久近：《佛本行经》第一卷说：昔有如來号曰善恩，"
 "弥勒菩萨于彼佛所最初发心。弥勒菩萨在于我前四十余劫发菩提心，然后我发道心。"
 "昔有佛名示海幢如来，我于彼佛国作转轮王，名曰牢（阙）弓，初发道心。",

 "《智度论》第二十四卷说：释迦牟尼佛与弥勒等诸菩萨同时发心，以精进力故，超越九劫。"
 "案：释迦、弥勒各有众多，同时前后皆无妨。问：论说释迦所超九劫，是大劫、还是小劫？"
 "若是大劫，同劫成佛，如何说超？",

 "若是小劫，在前一劫，如何超九？若说释迦应在弥勒之后九劫成佛，而今同在一劫成道，"
 "所以得说超九劫者，如何说同时发心？解：此中所超，准是大劫。之所以如此，说「超劫」者，"
 "并非就实行而言，但依获准示其超罢了。",

 "谓三僧祇已满之后，修相好业应经百劫，而于九十一劫修满故，说超九。论说第九十一劫中千佛出世，"
 "故知那九也是大劫。然而此二菩萨同时所发，是不定心；若论决定发心之时，弥勒发心九劫已后，"
 "释迦才发决定之心。",

 "故应在后九劫成道，而今超九同在一劫。此论是约那最初发心，故说同时发心。由是道理，不相违背。"
 "其余处所说超十二劫，准此应知。其次第十明证果前后：如《十住断结经》说：弥勒菩萨方习菩萨行吗？",

 "莫造此观。何以故？慈氏积行恒沙数劫，先以誓愿成等正觉，我方习行而在其后。"
 "案此而言，弥勒之本在先证果。然而释迦证果，经说不同。如《因果经》说：善慧菩萨功行成满，"
 "位登十地，在一生补处，生兜率天，名圣善白。",

 "《梵网经》说：我今卢舍那，方坐莲华台，周匝千华上，复现千释迦；一华百亿国，一国一释迦，"
 "各坐菩提树，一时成佛道，乃至广说。案此而言，是寄迹表本。善慧菩萨生兜率本在十地，"
 "释迦如来坐树下时本方证果。",

 "又《法华经·寿量品》说：我实成佛已来，无量无边百千万亿那由他劫，乃至广说。"
 "案此而言，释迦证果有久有近，弥勒成道例也应当如此。良由多本共垂一迹，所以异说莫不皆实。"
 "由是道理，不相违。",

