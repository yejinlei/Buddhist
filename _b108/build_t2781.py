 "洞澤無方，威若地炎，生福無盡，所以能除貪賊、見苦，隨三分生天，自在應時解脫。"
 "經曰「吾今當說救濟之法，令一切難皆離憂苦」者。述曰：此第五許說救方。如來何故須許說？"
 "正因目連既位動寒泉、啼傷隴樹，",

