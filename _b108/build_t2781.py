 "述曰：第六品真勸修，文有二節：一教供勝田，二教受供之儀。前中有五句：一標時、二修意、"
 "三示法、四美田、",

 "五顯益。此是標時。十方顯境寬，僧眾簡邪儔，十五序良時，自恣標捨行。然而三時獲果必藉良晨，"
 "人處為緣還資清眾，故德侶晏坐之末、竟歲發露之時，離縛則逆流愛河，流倫則救令速出。"
 "經曰「當為七世父母及現在父母厄難中者」，述曰：",

 "明修意也。「當為七世父母」者，酬遠恩，即七生父母。「現在」者，益近恩，即親生父母。"
 "然而親累七世，彰覆載之難違；恩及幽眾，顯含育之罔極。所以目連小志唯請近親，"
 "大聖慈寬愛及七世。經曰「具飯百味五果、汲灌盆器、香油錠燭、床臥眾具，盡施甘美貯在盆中」者，述曰：",

 "此第三示法。「具飯百味五果」者，是所獻之餚。「汲灌盆器」，是貯食之神器。「香油錠燭」，"
 "擬去暗以留光。「床臥眾具」，則止疲以息慮。然而盆由聖制、事藉功成，所以安汲灌於龍門、記燎於雷室。"
 "秦饒則皎之於前，趙玉亦佩之於後，",

 "神鳳上踴、飛蓋下垂，翻瑛八珍、盆羅百味，檀那既就、福應時臻，聰庶拔擢於知恩，"
 "也祐利於群品。經曰「當此之日，一切聖眾或在山間禪定，或得四道果」者。述曰：第四美田，"
 "具讚三德，這即定德。當此之日，即舉滅罪之良晨；",

 "一切聖眾，乃標證理之明良匠。或在山間禪定，處巖藪以練心；或得四道果，剋無內而取滅，"
 "此是定得。經曰「或樹下經行，或六通自在」者。述曰：智德也。或樹下經行者，頭陀自利之儔，"
 "即依閒以專修；或六通自在者，獲果利他之儔，",

 "即起通而益物。經曰「教化聲聞緣覺，或十地菩薩大士權現比丘，在大眾中」者。述曰：次明戒也。"
 "此句初列三人，則是有戒之人；次顯三戒，出持犯之儀。此列三人：聲聞則別脫之戒，"
 "緣覺則定隨律儀，菩薩則道共之戒。",

 "通即人人具之，別乃各守戒也。經曰「皆同一心，受鉢和羅飯，具清淨戒」者。述曰：此明三戒，"
 "出持犯之儀，此是別脫戒。「皆同一心」者，顯無散亂之失；「受鉢和羅飯」者，障無違爭之愆；"
 "「具清淨戒」者，即皎若明珠。因信施難消，",

 "如毛繩斷骨故，律功一心受食；經制具戒方消，故稱名免難尚勸一心為福利，生圓須同意。"
 "經曰「聖眾之道」者。述曰：定隨戒也。然而智依定起，非淨戒無以現前；聖託道生，"
 "終假人以顯其旨。經曰「其德汪洋」者。述曰：",

 "道隨戒也。「汪洋」者，盛貌之威儀。然而行則如王觀親，取嚴形以降魔；坐若就盤，見不動而憚法。"
 "故門外覩沙門之像，深嗟五欲之怨；城中逢馬宿之客，聞之帝而獲初果。這即威儀之益。"
 "經曰「其有此等自恣僧」者。述曰：",

 "第五顯益。文有二句：一顯大悲拔苦力、二顯大慈與樂力。「其有供養」等者，顯大悲力；"
 "「其有供養自恣」者，標良田之美；「現在」等者，出所救之重恩。恩有三品：一上恩，"
 "即現在父母親生育故；二中恩者，",

 "七世父母枝引不絕、遠資潤故；三下恩，六親眷屬，謂親戚兄弟助力成故。即《大論》說："
 "離別常人易，離別知識難；離別知識易，離別妻子難；離別妻子易，離別父母難。此證三品之親。"
 "「出三塗」等者，正顯大悲力。",

 "因積惡招殃、災及二世，修善置福、度及浚混。今說「出」者，此等應墮三塗，"
 "但為聖力所資、業果消滅；既應墮而不墮，即說不墮為出。經曰「若父母在世福樂百年」等者。述曰："
 "大慈與樂力。福樂百年，即現在樂；",

 "入天花光，即後世樂。且閻浮提上壽命極一百年，天內報宮光花影發。"
 "經曰「佛勅十方眾僧當為施主家呪願」者。述曰：自下明受供之儀，二句先教受食行、後示受食儀。"
 "先呪願者，生口業善行；禪定意者，生意業善；",

 "後受食者，生身業善。因願如御者，即有懸標之力；行類牛車，近有滅惡之功。"
 "故先遣發願，後行禪。經曰「先安在佛塔前」者。述曰：示受食儀。然而三寶次第雖有三階，"
 "就應化門宜先供佛。何者？且塔安舍利，即神變無窮，",

 "多寶靈龕乃會身分坐，故使藥王燒百福之辟、信相□古土之骸。合既聖體嶷然，寧不設盆先獻？"
 "經曰「時目連泣聲除滅」等者。述曰：第七孝子領悟。如來德澤洪流、神會義無不喜，倒懸雪苦，"
 "目連於是止悲，",

 "大眾則舞齊歡，目連則宿除哭泣。經曰「目連其母即於是日得脫一劫」等者。述曰：第八慈母蒙益。"
 "且一人之福，似掬土而遏江河；今既大眾之威，若嵐風類於業嶺。"
 "經曰「目連復白」下，第三流通分，反有三句：",

 "一啟請、二蒙讚、三正答。因孝之大也即通於神明，豈可獨敞於當時而不垂光於來業？"
 "所以目連啟請，務屬於此。文二句：一領即坐之益，賀三寶之威；二為未來傳芳，即諮疑審定。"
 "經曰「佛言」等者。述曰：",

 "蒙讚也。如來既降迹投機、惠雲乘布，但使來人有苦即法澤彌流，以彼同得宜故云「大善」。"
 "然佛猶未說類，即申疑，故云：我正欲說，你今復問。經曰「若善男子」等者。述曰：第三答也，"
 "有其五節：一教獻供、二教發願、三教常修、",

 "四教奉持、五教承命。此初也。極哉父母恩同天地，縱使血流滂沛未足酬恩，所以道門信類貴徒賤品，"
 "但當獻供即答橫恩。圓有多句：一標行孝人名、二示獻供時節，文相可解。"
 "經曰「乞願使現在父母」等者。述曰：",

 "教發願也。當願父母近年之命弗窮、資身之具恒逸，既去解支之庸，即留倚樂之安；"
 "七世尊靈長辭百苦、永去千彌寒泉，於此晨歸天靈、於即日感茲福乘，也願無窮。"
 "此即教獻供也。經曰「是佛弟子修孝順」等者。述曰：",

 "三勸常修。若勸慈行，即念念追思；若濟其親，即年年設供。這即孝盡於始終，也行極於事親。"
 "然而財於老時無用、措時為子孫故；盆於孝者無施，子宜午月恒獻故。"
 "經曰「若一切佛弟子奉持是經法」者。述曰：第四教奉持也。",

 "「奉」者信也，「持」者念也。言信即遣撥正邪，言念則深妄教之失，所以勗其信念、使教流通。"
