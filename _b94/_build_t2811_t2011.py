"【辨说无碍·空有何异途】一音演说而随类得解，巧便多慧、恒无厌惓，所设辞理没有蹇涩，名为「辨说」；所说之法没有拥滞，称之为「无碍（云云）」。「曷空有之异辙，奚广略之殊途？喻此记千□一辙，万□。」「曷」是何的意思，「辙」是途路之义。空、有之名是密意权说。【义解】此段释「辨说」与「无碍」：一音演说随类得解，巧便多慧而无厌惓，是为辨说；所说法无拥滞，是名无碍。次标「空有异辙、广略殊途」之问，转入空有广略之辨，并释「曷」「辙」之义。",

"【空有不殊·广略无二】论其究极，空有并无不同：有，是就蕴之实、约执见而说；空，是就假成、悟性非有而说。由此可知，迷悟自别，而源体之空有并非殊异。广略之言，其实也无二致：悟则四句便足，不须多求，这是「略」；迷则虽读万卷真言，仍同坠于虚妄，这是「广」。只是利钝有别，广略并无二致。「奚」是何的意思（云云）。【义解】此辨空有不殊、广略无二。有约执见而说，空约悟性非有而说，故源体空有非殊；悟则四句便足为略，迷则读万卷真言仍同坠妄为广。利钝有殊而广略无二，是会通教门之要。",

"【究本滞末·五谤之起】「究其本者，必同味于百川；滞其末者，竞纷流于五谤。」说到「究其本」，「究」是穷究，「本」是体、是亡名绝相、是真理，取「通会」为说。若得其本源，则知众流同归一海；尝大海的一滴水，便知众流之味。说到「滞其末」，「滞」是由于迷。【义解】此释「究本」与「滞末」。本者亡名绝相之真理，究本则如众流归海、尝一滴知众味；滞末则执空有教法而纷起五谤。下段引出「五谤」之名目。",

"【滞末之迷·本体离言】「末」指执著空、有教法之辈，约其偏执而说。《二夜经》云：某夜成正觉，某夜般涅槃，于此二中间，我都无所说；不说是佛说，若言如来有所说法，即为谤佛，不能解我所说义。由此可知，本体之法非言诠所及：是心欲思而虑亡。【义解】此明本体离言。引《二夜经》佛于成道至涅槃间「我都无所说」之文，谓若言如来有所说法即为谤佛；本体之法非言诠所及，心欲思而虑亡，口欲言而辞丧，不可以智知、不可以识识。",

"【本体离言·五谤名目】口欲言而辞丧，不可以智知，不可以识识。于是有僻见之流，立此五谤。五谤的名目：一是增益谤，二是损减谤，三是相违谤，四是戏论谤，五是愚废谤。这五谤一一说来：第一，说诸法为有，而法本不有，说「有」者便是增益谤，法性本空。【义解】此列五谤名目：增益、损减、相违、戏论、愚废，并逐一辨之。第一增益谤，谓法本不有而说「有」；本段即开五谤之释，下二段续辨其余四谤。",

"【五谤细辨·增益损减相违戏论】何得言有？第二，说诸法为无，而本法不无，说「无」者便是损减谤；依他性有，何得言无？第三，「亦有亦无」，而本法离有离无，这是相违谤，空、有都与理相违越。第四，「非有非无」，本法无来不有、即今不无，这是戏论谤；「非有」者说空。【义解】承上辨五谤：第二损减谤，谓依他性有而说「无」；第三相违谤，谓「亦有亦无」而本法离有离无；第四戏论谤，谓「非有非无」而本法无来不有、即今不无。此段逐条破偏执之见。",

"【五谤终说·愚痴戏论】「非无」者说有，空有不定，明知是戏论。又第一义中无有少法可得，若立一法、起于名相，皆成戏论。第五，「非以有以无」，而本法无有文字语言，若说法无名字，便是愚痴谤，翻第四而成第五。第四，说非空者是有，有并非是有；说非有者是空。【义解】此结五谤之辨。第五愚废谤，谓本法无文字语言而说「法无名字」，是愚痴谤；且「非空是有、非有是空」辗转相成，落于有无不定，皆属戏论。若如是者，明知迷愚非智。",

"【迷愚成谤·小乘漂有胜义溺空】无非是无，有非是有，还成无义；无非是无，却成有义。若是如此，便知此是迷愚之人，实非智者。「是以小乘漂于有，有部执繁兴；胜义溺于空，空诤论纷起。」说到「是以小乘漂于有」，「漂」是浮的意思，人我、法我二者都定为有，所以说「二有」。说到「胜义溺于空」。【义解】此段总结五谤之失，并转入空有两宗之弊：小乘住有，有部执繁兴；胜义溺空，空见诤论纷起。「漂」训浮，人我、法我定有为「二有」；下段释「二空」。",

"【人法二空·二无我】「溺」是沉的意思。上说的两种义都归于空，所以名为「二空」。前宗执有，后者滞空，空有相违，诤论竞起。说到「人我」，在五蕴假和合之处横加计度而认为有人，若离我、我所，便是人无我。说到「法我」，执因缘之法为实，认为生起的一切都有自性，所以称为「我」；而因缘所生之法悉皆虚妄。【义解】此释「二空」与人法二无我。「溺」训沉，前宗执有、后者滞空，故空有相违、诤论竞起。人我者，于五蕴假合处横计有人，离我我所即人无我；法我者，执因缘法有自性，而因缘生法皆虚妄，故法无我。",

"【法无我·妄境昏衢】本自不生，体无动摇，便是法无我。「尚驱妄境，未越昏衢；徒向真风，虚霑法雨。」说到「尚驱妄境」，沉空、住有都总名为「妄境」。「未越昏衢」，即黑暗之道；若起上述僻见，便未能超越沉沦。「徒向真风」，偏执之徒徒劳地趣向真宗；「风」是教化之义，如风吹草伏。【义解】此承上明因缘生法本自不生、体无动摇，是为法无我。次标「尚驱妄境、未越昏衢，徒向真风、虚霑法雨」四句：沉空住有皆名妄境，起僻见则未越沉沦；偏执之徒徒劳趣向真宗，如枯木难霑法雨。",

"【补处弥勒·阐瑜伽开一实道】背见之徒，其状如同枯木，法雨露泽也不能滋润（云云）。「故我补处弥勒，大阐瑜伽，杜两见门，开一实道。」说到「补处弥勒」，譬如世间帝王预立东宫以绍继国政，一旦王崩，便依次由东宫补位为国主。今一生补处菩萨，佛为之授记云：此后人寿八万四千岁时。【义解】此段以枯木不受法雨喻背见之徒，转出弥勒菩萨「大阐瑜伽、杜两见门、开一实道」之功。以帝王预立东宫喻补处之义，谓弥勒当人寿八万四千岁、轮王禳佉时补处成佛。下段续释弥勒名号。",

