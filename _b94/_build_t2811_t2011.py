def build(tid, intro, mods):
    src = os.path.join(ROOT, "data", "baihua-tasks", tid + ".json")
    task = json.load(open(src, encoding="utf-8"))
    tr = task["translations"]
    assert len(tr) == len(mods), "%s: %d segs vs %d mods" % (tid, len(tr), len(mods))
    for i, seg in enumerate(tr):
        m = mods[i]
        assert m.startswith("【"), "%s seg %d not start with 【" % (tid, i)
        assert "【义解】" in m, "%s seg %d missing 义解" % (tid, i)
        tail = m.split("【义解】", 1)[1]
        assert tail.strip(), "%s seg %d 义解 empty" % (tid, i)
        mt = re.match(r"^【([^】]+)】", m)
        seg["section"] = mt.group(1)
        seg["modern"] = m
        # sanity: no halfwidth quotes/ascii punctuation
        for bad in ['"', "'", ",", ".", "?", "!", ";", ":"]:
            assert bad not in m, "%s seg %d contains halfwidth %r" % (tid, i, bad)
    out = {
        "id": task["id"],
        "title": task["title"],
        "translator": task["translator"],
        "mode": task["mode"],
        "intro": intro,
        "sutraPath": "../sutras/%s.json" % tid,
        "translations": tr,
    }
    dst = os.path.join(ROOT, "data", "modern-translation", tid + ".json")
    with open(dst, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    print("WROTE", dst, "segs:", len(tr), "intro_len:", len(intro))

