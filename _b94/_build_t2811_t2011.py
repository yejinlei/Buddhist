"【劝人守心·佛与众生之别】所以说：守本真心，胜念他佛。又说：所谓「胜」，只是就修行以劝人之语，其实究竟果体平等无二。问：众生与佛的真体既同，为何诸佛不生不灭，受无量快乐、自在无碍，而我等众生却堕在生死之中受种种苦呢？答：十方诸佛悟达法性。【义解】此释「胜」只是约行劝人之语，究竟果体平等无二。次设问：众生与佛真体既同，何故诸佛不生不灭受乐自在，而众生堕生死受苦？下段以佛悟法性、众生迷真作答。",

"【佛悟法性·众生迷真】诸佛皆自然照燎于心源，妄想不生、正念不失，我所心灭，故得不受生死；不生死故，即毕竟寂灭，故知万乐自归。一切众生迷于真性，不识心本，种种妄缘、不修正念，故即憎爱之心生起；因憎爱故，则心器破漏；心器破漏故，即有生死。【义解】此答前问：诸佛悟达法性，自然照燎心源，妄想不生、正念不失，我所心灭故不受生死，即毕竟寂灭而万乐自归；众生迷于真性、不识心本，妄缘不修正念，故憎爱心起、心器破漏而有生死。",

"【有生死则诸苦现·不思议分】有生死故，则诸苦自现。《心王经》云：真如佛性没在知见六识海中，沉沦生死，不得解脱。努力领会此理：守本真心，妄念不生，我所心灭，自然与佛平等无二。问：真如法性同一无二，迷应俱迷、悟应俱悟，为何佛觉而。【义解】此结「有生死则诸苦自现」，引《心王经》真如佛性没于知见六识海之说，劝人努力领会守本真心即与佛平等。次设真如法性同一，何故佛觉而众生迷之问，为下入「不思议分」作引。",

"【不思议分·离二边入无分别智】众生昏迷？因何故如此？答：自此以上入于不思议分，非是凡夫所及。识心故悟，失性故迷；缘合即合，其说不可定。但信真谛、守自本心。故《维摩经》云：无自性、无他性，法本无生、今即无灭。此悟即离二边，入无分别智。若解此义，但于行中知法之要。【义解】此答「迷悟」之问，谓自此以上入不思议分，非凡所及；识心故悟，失性故迷，缘合即合其说不可定。引《维摩经》无自性他性、法本无生今即无灭，明此悟离二边、入无分别智，故守心为第一。",

"【守心第一·涅槃根本】守心第一。此守心者，乃是涅槃之根本、入道之要门、十二部经之宗、三世诸佛之祖。问：如何知道守本真心是涅槃之根本？答：涅槃，体是寂灭无为安乐。我心既是真心，妄想则断；妄想断故，则具正念；正念具故，寂照之智生。【义解】此总标「守心第一」，谓守心是涅槃之根本、入道之要门、十二部经之宗、三世诸佛之祖，全论由此展开四重问答。首问守本真心何以为涅槃根本，答以涅槃寂灭无为，真心断妄、正念生寂照智，故得涅槃。",

"【寂照智生·入道要门】寂照智生故，穷达法性；穷达法性故，则得涅槃。故知守本真心是涅槃之根本。问：如何知道守本真心是入道之要门？答：乃至举一手爪画佛形像，或造恒沙功德者，这只是佛为教导无智慧众生，作当来胜报之业及见佛之因。【义解】此结「寂照智生故穷达法性、得涅槃」，证守本真心是涅槃根本。次设「何知守本真心是入道之要门」之问，答谓举爪画像、造恒沙功德只是佛为无智众生作当来胜报与见佛之因。",

"【早成佛者·制心一处】若愿自己早成佛者，领会此守本真心。三世诸佛无量无边，若有一人不守真心而得成佛者，无有是处。故经云：制心一处，无事不办。故知守本真心是入道之要门。问：如何知道守本真心是十二部经之宗？答：如来于一切经中。【义解】此答入道要门：愿早成佛者，唯在守本真心；三世诸佛无量，无一人不守真心而得成佛。引经「制心一处，无事不办」为证。次设「何知守本真心是十二部经之宗」之问。",

"【十二部经之宗·随其心门入一乘】说一切罪福、一切因缘果报，或引一切山河大地、草木等种种杂物，起无量无边譬喻，或现无量神通、种种变化者，只是佛为教导无智慧众生——其有种种欲心、心行万差，是故如来随其心门，引入一乘。我既体知众生佛性本来清净，如云底之日。【义解】此答十二部经之宗：如来于一切经中说罪福因果、引山河草木为喻、现神通变化，皆为教导无智众生，随其心门引入一乘。既知众生佛性本来清净如云底之日，则但当守本真心，妄念云尽而慧日自现。",

"【妄念云尽慧日现·真学无所学】但能了然守本真心，妄念云尽，慧日即现，何须更学知见所涉的生死苦、一切义理及三世之事？譬如磨镜，尘尽则明自然现。而今于无明心中所学得的，终究不堪；若能了然不失正念，于无为心中学得者，这才是真学。虽说真学，毕竟无所学。【义解】此以磨镜尘尽明现为喻，谓于无明心中所学终不堪，唯于无为心中不失正念所学方是真学；虽名真学而实无所学。下段释「无所学」之义，谓我及涅槃二皆空故。",

"【我及涅槃二皆空·三世诸佛之祖】何以故？我及涅槃，二皆空故；更无二、无一，故无所学。法性虽空，要须了然守本真心，妄念不生，我所心灭故。《涅槃经》云：知佛不说法者，是名具足多闻。故知守本真心，是十二部经之宗。问：如何知道守本真心是三世诸佛之祖？【义解】此明真学无所学，以「我及涅槃二皆空」为据；然法性虽空，仍须了然守本真心。引《涅槃经》「知佛不说法者，是名具足多闻」，证守本真心为十二部经之宗。次设「何知守本真心是三世诸佛之祖」之问。",

"【三世诸佛之祖·千经万论守心】答：三世诸佛皆从心性中生，先守真心、妄念不生，我所心灭，然后得成佛。故知守本真心是三世诸佛之祖。上来四种问答，若欲广说，何有穷尽？我今唯望得汝自识本心是佛，是故殷勤劝汝：千经万论，莫过于守本真心。【义解】此答守本真心为三世诸佛之祖，谓三世诸佛皆从心性生，先守真心、妄念不生、我所心灭而后成佛。上来四种问答竟，劝人自识本心是佛，谓千经万论皆不过守本真心。",

"【法华大车之喻·正念察心】这是要旨。我今努力，按《法华经》指示于汝：大车、宝藏、明珠、妙药等物，汝自不取不服，穷苦奈何！领会此意：妄念不生，我所心灭，一切功德自然圆满，不假外求而归于生死之苦。于一切处正念察心，莫贪爱现在之乐而种未来之苦，自诳诳他。【义解】此按《法华经》大车、宝藏、明珠、妙药之喻劝取劝服，谓妄念不生、我所心灭则功德自圆满，不假外求。又劝于一切处正念察心，莫贪现乐而种未来之苦，勿自诳诳他而不脱生死。",

"【努力修道·初学坐禅】不能脱于生死。努力！努力！今虽无常，共作当来成佛之因，莫使三世虚度、狂丧功夫。经云：常处地狱如游园观，在余恶道如己舍宅。我等众生今现如此，不觉不知，惊怖杀人，了无出离之心，奇哉苦哉！若有初心学坐禅者。【义解】此劝修行者共作当来成佛之因，勿虚度三世、狂丧功夫，并引经常处地狱如游园观、在余恶道如己舍宅之语，叹众生不觉不知、无出离心。次转入初学坐禅者依《观无量寿经》之法。",

"【依观无量寿经·坐禅调息】依《观无量寿经》端坐正念，闭目合口，心前平视，随意近远，作一日想，守真心，念念莫住，即善调气息，莫使忽粗忽细，否则令人成病苦。夜坐禅时，或见一切善恶境界，或入青黄赤白等诸三昧，或见身出大光明。【义解】此教坐禅方法：端坐正念、闭目合口、心前平视、作一日想而守真心，善调气息不使忽粗忽细，以免成病。又述夜坐禅时所见的善恶境界、诸三昧、大光明等，为下段辨其虚幻作引。",

"【境界皆空·守本真心】或见如来身相，或见种种变化，但知摄心莫著，并皆是空，由妄想而见。《经》云：十方国土皆如虚空，三界虚幻，唯是一心所作。若不得定、不见一切境界者，也不须怪，但于行住坐卧中常了然守本真心，领会此意：妄念不生。【义解】此明坐禅所见如来身相、种种变化皆是空，由妄想而见；引经「十方国土皆如虚空，三界虚幻唯是一心作」。若不得定、不见境界亦不须怪，但当于行住坐卧中常守本真心。",

"【万法不出自心·八万四千法门】我所心灭，一切万法不出自心。所以诸佛广说，如此多言教譬喻者，只为众生行行不同，遂使教门差别。其实八万四千法门、三乘八道位体、七十二贤行宗，莫过于自心是本。若能自识本心、念念磨炼莫住者，即自见佛性。【义解】此总明一切万法不出自心，诸佛广说言教譬喻只因众生行行不同而教门有别；八万四千法门、三乘八道、七十二贤行宗皆不出自心。能自识本心、念念磨炼莫住者，即自见佛性。",

"【念念供养诸佛·捨身得无生】于念念中常供养十方恒沙诸佛，十二部经念念常转。若了此心源者，一切心义自现，一切愿具足、一切行满、一切皆办，不受后有。领会此意：妄念不生，我所心灭，舍此身已，定得无生、不可思议。努力莫造作。如此真实不妄语，难可得闻。【义解】此明见性之人念念供养诸佛、常转十二部经，了此心源则一切愿行皆办、不受后有，舍此身后定得无生。又叹如此真实不妄之语难可得闻，劝人努力而莫造作。",

"【闻行难得·无记心】闻而能行者，恒沙众中莫过有一；行而能到者，亿叉劫中希有一人。好好自安自静，善调诸根，就视心源，恒令照燎清净，勿令无记心生。问：什么叫「无记心」？答：诸摄心之人为缘外境，粗心稍稍止息，内炼真心而心未清净之时。【义解】此叹闻而能行、行而能到者极其希有，劝人自安自静、善调诸根、就视心源，勿令「无记心」生。次设「何名无记心」之问，下段作答。",

"【无记心与漏心·情诚内发】于行住坐卧中恒惩戒其意而看心，犹未能了了清净、独照心源，这便名为「无记心」，也是漏心，犹不免生死大病；何况又完全不守真心者，此人沉没生死苦海，何日得出？可怜！努力！努力！经云：众生若情诚不内发者，于三世纵然值遇恒沙诸佛，也无能为力。【义解】此答无记心：摄心之人但息粗心而未清净独照心源，即名无记心，亦属漏心，犹不免生死大病，何况全不守心者。引经谓众生若情诚不内发，虽遇恒沙诸佛亦无所能为。",

"【识心自度·勤求本心】经云：众生识心自度，佛不能度众生。若佛能度众生者，过去诸佛恒沙无量，何故我等不成佛呢？只是情诚不向内发，是故沉没苦海。努力！努力！勤求本心，勿令妄漏。过去不知，已过亦不及；今身现在，幸遇得闻妙法。【义解】此引经「众生识心自度，佛不能度众生」，谓若佛能度，过去恒沙诸佛何故我等不成佛？正因情诚不内发故沉没苦海。劝人勤求本心、勿令妄漏，珍惜今身得闻妙法之缘。",

"【守心是第一道·莫贪名利】分明相劝，决解此语，了知守心，是第一道。若不肯发至诚心、求愿成佛、受无量自在快乐，却才轰轰然随俗贪求名利，当来堕大地狱中受种种苦恼，将何所及？奈何！奈何！努力！努力！但能着破衣、餐粗食，了然守本真心。【义解】此劝人发至诚心求愿成佛，勿随俗贪求名利而堕地狱；但能着破衣、餐粗食、了然守本真心，即是第一道。下段续明佯痴守心者最省气力而有大功。",

"【佯痴守心·有力菩萨】佯装痴愚、不解言语，最省气力而能有功，这是大精进之人。世间迷人不解此理，于无明心中多涉艰辛、广修相善，望得解脱，却反归生死。若了然不失正念而度众生者，是有力菩萨。分明告语汝等：守心第一！若不勤守者，是极痴之人。【义解】此赞佯痴不解语、守本真心者为大精进人；斥世间迷人于无明心中广修相善却反归生死。又谓了然不失正念而度众生者是有力菩萨，故苦口叮咛「守心第一」，不勤守者极痴。",

"【八风吹不动·出世丈夫】不肯于现在一生忍苦，却想当来万劫受殃，任你再听也不知有何可嘱。八风吹不动者，真是珍宝之山。若知果体者，但对于万境，起恒沙作用，巧辩若流，应病与药，而能妄念不生、我所心灭者，真是出世丈夫；如来在世之日，叹其功德何可穷尽！【义解】此斥不肯现生忍苦、欲当来受殃之人，赞「八风吹不动者真是珍宝山」；若能面对万境起恒沙妙用而妄念不生、我所心灭者，是真出世丈夫，如来在世亦叹其功德不尽。",

"【我所心灭·涅槃中病】我说此语，是至心劝汝：不生妄念，我所心灭，则是出世之士。问：怎样才是「我所心灭」？答：若有一小许胜他之心，自念「我能如此」，这便是「我所心」，是涅槃中之病。《涅槃经》说：譬如虚空能容万物，而此虚空不自念言「我能含容如是」。【义解】此归「我所心灭」之旨，谓有少许胜他之心、自念「我能如此」，即是我所心，是涅槃中之病。引《涅槃经》虚空能容万物而不自念「我能含容」为喻，以明我所心灭。",

"【金刚三昧·行人三病】此喻我所心灭，趣向金刚三昧。问：诸行人有求真常寂者，只乐世间无常粗善，不乐第一义谛，真常妙善其理未见；只欲发心缘义，遂思觉心起，则是漏心；只欲亡心，则是无明昏住，又不当理；只欲不止心、不缘义，即恶取空。【义解】此结「我所心灭趣向金刚三昧」，并辨行人三病：乐世间粗善而不乐第一义谛；发心缘义而觉心起为漏心；亡心则为无明昏住；不止心不缘义则成恶取空。下段续明恶取空之失。",

"【恶取空之失·示守真心】虽受人身而行畜生行，尔时无有定慧方便，而不能解了、明见佛性，这只是行人沉没之处。若欲超登到无余涅槃，愿示真心。答：领会此意，信心具足、志愿成就，缓缓静心，我再重教于汝：好自闲静身心，一切无所攀缘，端坐正念，善调气息。【义解】此明恶取空者虽受人身而行畜生行，无定慧方便，不能明见佛性，是行人沉没之处。次示修行要法：信心具足、志愿成就、缓缓静心，闲静身心、无所攀缘、端坐正念、善调气息。",

"【观心识流动·灭十地障惑】惩戒其心，不在内、不在外、不在中间，好好如如，稳稳看熟，则了见此心识流动，犹如水流、阳焰，晔晔不住。既见此识时，唯是不内不外；缓缓如如，稳稳看熟，则反复销融，虚凝湛住，其此流动之识飒然自灭。灭此识者，乃是灭十地菩萨众中障惑。【义解】此教观心之法：令心不在内外中间，如如稳看，则见心识流动如水流阳焰、晔晔不住；既见唯是不内不外，反复销融而虚凝湛住，此流动之识飒然自灭。灭此识即灭十地菩萨众中障惑。",

"【虚凝寂淡·经证心要】此识灭已，其心即虚凝寂淡、淡泊皎洁、泰然自若，我更不能说其形状。汝若欲得者，取《涅槃经》第三卷中「金刚身品」及《维摩经》第三卷「见阿閦佛品」，缓缓寻思、细心搜捡熟看。若此经熟，实得能于行住坐卧及对五欲八风而不失此心者。【义解】此明识灭后其心虚凝寂淡、皎洁泰然，不可言状。劝人取《涅槃经·金刚身品》与《维摩经·见阿閦佛品》寻思熟看，若能于行住坐卧及对五欲八风而不失此心，即梵行已立、所作已办。",

"【梵行已立·五欲八风】是人梵行已立、所作已办，究竟不受生死之身。五欲者，色、声、香、味、触；八风者，利、衰、毁、誉、称、讥、苦、乐。此是行人磨炼佛性之处，切莫怪今身不得自在。经云：世间无佛住处，菩萨不得现用，要脱此报身。众生过去根有利钝，不可判。【义解】此释五欲（色声香味触）与八风（利衰毁誉称讥苦乐），谓此是行人磨炼佛性之处，莫怪今身不得自在。引经谓世间无佛住处菩萨不得现用，须脱此报身；众生宿根利钝不同，故成佛有一念与无量劫之别。",

