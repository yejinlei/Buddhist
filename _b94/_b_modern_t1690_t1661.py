"""Generate modern-translation JSON for t1690 and t1661 (baihua)."""
import json, os
from opencc import OpenCC

CC = OpenCC("t2s")
ROOT = "/home/user/workspace/13511660557912876654/buddhist-ontology"
OUT = os.path.join(ROOT, "data", "modern-translation")
os.makedirs(OUT, exist_ok=True)

CLOSERS = "。！？：」』、；，"


def norm(text):
    """Join soft line breaks; insert 。 where a line ends without punctuation."""
    out = []
    for ch in text:
        if ch == "\n":
            if out and out[-1] in CLOSERS:
                continue
            out.append("。")
        else:
            out.append(ch)
    return "".join(out)


def build(tid, intro, items):
    with open(os.path.join(ROOT, "data", "baihua-tasks", tid + ".json"), encoding="utf-8") as f:
        data = json.load(f)
    assert len(data["translations"]) == len(items), (tid, len(data["translations"]), len(items))
    data["sutraPath"] = "../sutras/" + tid + ".json"
    data["intro"] = intro
    for entry, (title, yijie) in zip(data["translations"], items):
        body = norm(CC.convert(entry["original_preview"]))
        entry["modern"] = "【" + title + "】" + body + "【义解】" + yijie
        entry["section"] = title
    with open(os.path.join(OUT, tid + ".json"), "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)


