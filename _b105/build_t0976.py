def clean(s):
    out = []; i = 0; n = len(s)
    while i < n:
        c = s[i]
        if c == '（':
            j = s.find('）', i + 1)
            i = (j + 1) if j >= 0 else i + 1
            continue
        if c in '「」『』' or c.isspace():
            i += 1; continue
        out.append(c); i += 1
    return ''.join(out)

