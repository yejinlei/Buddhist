def chunks_for(i, seg):
    if i in ALL:
        return [clean(seg)]
    if i in MIXED:
        return [clean(sub(seg, sa, ea)) for (sa, ea) in MIXED[i]]
    return []

MODS = []
for i, seg in enumerate(segs):
    body = TPL[i]
    ch = chunks_for(i, seg)
    assert body.count('{@}') == len(ch), (i, body.count('{@}'), len(ch), ch)
    for c in ch:
        body = body.replace('{@}', '⟪%s⟫' % c, 1)
    assert '{@}' not in body, i
    MODS.append("【%s】【义解】%s" % (TITLES[i], body))

trans = []
for i, mod in enumerate(MODS):
    import re
    m = re.match(r'(【[^】]+】)', mod); sec = m.group(1) if m else ''
    trans.append({"section": sec, "original_preview": segs[i], "modern": mod})

