def is_mantra(text):
    """判断是否为纯咒语段。"""
    mantra_chars = set("唵吽娑婆訶莎訶薩嚩曩莫怛他揭多怛他俄多阿羅訶三藐三佛陀泮吒吒婆訶訶曩莫三滿多母陀南阿缽囉底賀多捨薩喃怛姪他唵訶囉訶囉")
    # 只有含典型密咒标志且标点少
    signs = ["陀羅尼曰", "咒曰", "真言曰", "密言曰", "神咒曰", "莎婆訶", "娑婆訶", "莎訶", "泮吒", "唵", "曩莫", "薩嚩"]
    has_sign = any(s in text for s in signs)
    # 若只是提到"陀羅尼"三字作为名相（如"得陀羅尼"），不算
    if "陀羅尼" in text and not any(s in text for s in ["陀羅尼曰", "陀羅尼咒", "陀羅尼是"]):
        # 如果上下文还有大量汉语叙事，不是纯咒
        cn_ratio = sum(1 for c in text if '\u4e00' <= c <= '\u9fff') / max(len(text), 1)
        if cn_ratio > 0.9 and text.count("。") > 2:
            has_sign = has_sign and not ("得陀羅尼" in text or "陀羅尼門" in text or "陀羅尼品" in text or "陀羅尼句" in text)
    return has_sign and len(text) < 400


