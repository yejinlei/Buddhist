def translate_segment(idx, op, tid, title):
    """生成单个段的modern字段。"""
    op_stripped = op.strip()
    if not op_stripped:
        return "【闕文】\n此段原經有闕，不補。\n【義解】原經段落文字闕漏，依法不臆補，保留原狀。"
    subtitle = make_subtitle(idx, op_stripped, tid, title)
    if is_mantra(op_stripped):
        # 咒语段：原字照录
        body = f"以下為梵文密咒原字照錄（密咒不可翻譯，須依原音持誦）：\n{op_stripped}"
    else:
        body = wenyan_to_baihua(op_stripped)
        if not body.endswith("。") and not body.endswith("！") and not body.endswith("？"):
            body += "。"
    yijie = make_yijie(idx, op_stripped, tid, title)
    return f"【{subtitle}】\n{body}\n【義解】\n{yijie}"


def process_one(tid, title):
    in_path = os.path.join(BASE, "data/baihua-tasks", f"{tid}.json")
    out_path = os.path.join(OUT_DIR, f"{tid}.json")
    with open(in_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    new_translations = []
    for i, seg in enumerate(data["translations"]):
        op = seg["original_preview"]
        modern = translate_segment(i, op, tid, title)
        new_translations.append({
            "original_preview": op,
            "modern": modern,
        })
    out_data = {
        "id": data.get("id"),
        "title": data.get("title", title),
        "translator": data.get("translator"),
        "vol": data.get("vol"),
        "translations": new_translations,
    }
    with open(out_path, 'w', encoding='utf-8') as f:
        json.dump(out_data, f, ensure_ascii=False, indent=2)
    return len(new_translations), out_path


