 "所谓信者，于实、德、能深忍乐欲，心净为性，对治不信，乐善为业。谓于诸法实事理中深信忍故；于三宝真净德中深信乐故；于一切世出世善深信有力、能得能成，起希望故——这是三种信。说「心净为性」，谓此性澄清能净心等，如水清珠能清浊水，所以说心净为性。",
 "所谓精进者，于善恶品修断事中勇悍为性，对治懈怠，满善为业。谓善品修、恶品断，勇表胜进、简别诸染法；捍表精纯、简别净无记。又说勇而无怯、捍而无惧。说「满善」者，圆满了解善事名为满善。所以三根为作善，此名满善，因能满彼故。",
 "有人说：「《唯识论》说精进一法在三根之后；《百法》却在信后即说，为什么？」答：「《唯识》是立依次第，此是因依次第。因信为欲依、欲为勤依，所以此在信后便说勤，勤即精进，只是勤通三性、进唯善性所摄。",
 "」「立依」者，谓根依精进而立舍等三，所依四法建立之理须合说，故三根之后才说精进。说惭者，依自、法力崇重贤善为性，对治无惭，止息恶行为业。自、法力者，自指自身，法指教法，说我这样的身、解这样的法，岂敢作诸恶呢？",
 "说愧者，依世间力，轻拒暴恶为性，对治无愧，止息恶行为业。世人讥呵名世间力轻，有恶者而不亲近，拒恶法业而不作。说无贪者，于有、有具无著为性，对治贪著，作善为业。说「有、有具」者，上一「有」字即三有之果，有具即三有之因。",
 "说无瞋者，于苦、苦具无恚为性，对治瞋恚，作善为业。说「苦、苦具」者，苦谓三苦，苦具即苦因。无痴者，于诸事理明解为性，对治愚痴，作善为业。说轻安者，远离粗重、调畅身心、堪任为性，对治昏沉，转依为业。",
 "离重名轻、调畅身心名安，谓此能伏除障碍定之法，令所依止转安适故。说「堪任」者，有所堪可、有所任受。说「转依」者，令所依身心去粗重、得安隐故。说不放逸者，精进三根，于所修断防修为性，对治放逸，成满一切世出世善事为业。",
 "「防修」者，于所断之恶防令不起，于所修之善法修令增长。说「精进三根」者，此不放逸即四法的防修功能，并非别有体；或说：「信等也有防修功能，为何不依之立？」答：「其余六种比这四种，势用微劣，故不依立。为何偏说微劣？",
 "「因为非善根故、非遍策故。」说行舍者，精进三根，令心平等、正直、无功用住为性，对治掉举，静住为业。说「行舍」者，乃行蕴中之舍，简别受蕴之舍故。说「令心平等」等者，由舍令心离昏沉、掉举时，初心平等、次心正直、后无功用，这是初、中、后差别之位。",
 "「这也就是四法（精进三根），离彼四法，别无相用。」怎么知道别无？答：「若能令静即是四法，若所令静即是心等故。」或说：「既然就是四法，何须别立？」答：「若不别立，便隐没此能故。」说不害者，于诸有情不为损恼，无瞋为性，能对治害，悲愍为业。",
 "谓即无瞋，于有情所不为损恼，假名不害。无瞋翻对断物命，瞋不害但违损恼物之害。无瞋与乐、不害拔苦，此二者粗相差别；理实无瞋实有自体，不害依彼一分假立，为显慈悲二相别故，利乐有情彼二胜故。",
 "四、烦恼六者——这是别标章，下面别列名。一、贪，二、瞋，三、慢，四、无明，五、疑，六、不正见。说贪者，于有、有具染著为性，能障无贪，生苦为业。「生苦」者，谓由爱力取蕴生故。瞋者，于苦、苦具憎恚为性，能障无瞋，不安、恶行所依为业。",
 "「不安」者，心怀憎恚多住于苦，所以不安。慢者，恃己于他高举为性，能障不慢，生苦为业。「生苦」者，谓若有慢，于有德之人、有德之法心不谦下，由此死生轮转无穷、受诸苦故。无明者，于诸理事迷暗为性，能障无痴，一切杂染所依为业。",
 "「杂染所依」者，由无明起痴、邪定、贪等烦恼随烦恼业，能招后生杂染法故。疑者，于诸谛理犹豫为性，能障不疑、善品为业。「障善品」者，因犹豫故善不生。恶见者，于诸谛理颠倒推度，染慧为性，能障善见，招苦为业。",
 "「恶见」者多受苦故，此见有五种：即身见、边见、邪见、见取、戒禁取。此六即俱生；若开恶见成十，即分别惑。又十惑中，瞋唯不善，其余九种都通有覆、不善。（此下重出题记：天亲菩萨造，唐三藏法师玄奘奉诏译，唐慈恩法师窥基注解；）",
 "「明鲁庵法师普泰增修。」五、随烦恼二十——这是别标章，下面别列名。一、忿，二、恨，三、恼，四、覆，五、诳，六、谄，七、憍，八、害，九、嫉，十、悭，十一、无惭，十二、无愧，十三、不信，十四、懈怠，十五、放逸，十六、昏沈，十七、掉举，十八、失念，十九、不正知，二十、散乱。",
 "说忿者，依对现前不饶益境，愤发为性，能障不忿，执仗为业。「执仗」者，仗即器仗。怀忿恨者多发暴恶身表业故，是瞋之一分所摄。恨者，由忿为先，怀恶不舍，结冤为性，能障不恨，热恼为业。「热恼」者，结恨者不能含忍，恒热恼故。",
 "恼者，忿恨为先，追触暴恶，恨戾为性，能障不恼，䖧螫（毒螫）为业。说「追触」等义，谓追念往恶、触现违缘，心便恨戾，多发嚣暴、凶鄙粗言，毒螫他人故，这也是瞋之一分。覆者，于自作罪恐失利誉，隐藏为性，能障不覆，悔恼为业。",
 "说「悔恼」者，覆罪则后来必悔恼不安隐故，是贪、痴二分。若不惧当受苦而覆罪者，是痴一分所摄；若恐失利誉而覆罪者，是贪一分所摄。说诳者，为护利誉矫现有德，诡诈为性，能障不诳，邪命为业。说「矫现」等，谓矫诳者心怀异谋，多现不实的邪命事故，是贪、痴之分。",
 "谄者，谓罔冒他人故，矫设异仪，谄曲为性，能障不谄，教诲为业。说「罔他」等义，谓谄曲者为了罔冒他人，曲顺时宜、矫设方便以取他意；或藏己失，不受师友正教诲故，也是贪、痴之分。憍者，于自盛事深生染著，醉傲为性，能障不憍，染依为业。",
 "说「染依」义者，憍醉则生长一切杂染法故，这是贪之一分。不憍者，即无贪。害者，于诸有情心无慈悲，损恼为性，能障不害，逼恼为业。说「逼恼」之义，有害者逼恼他故，是瞋之一分所摄。若论害与瞋之别义，害障不害、正障于悲；",
 "瞋障无瞋、正障于慈。又瞋能断命、害但损他，这是差别。说嫉者，殉自名利，不耐他荣，妒忌为性，能障不嫉，忧戚为业。说「忧戚」义者，嫉妒者闻见他荣，深怀忧戚不安隐故，也是以瞋分为体。说悭者，耽著法财不能惠舍，秘吝为性，能障不悭，鄙畜为业，也是贪之一分。",
 "无惭者，不顾自法，轻拒贤善为性，能障于惭，生长恶行为业。说「不顾」者，谓于自法无所顾者，轻拒贤善，不耻过恶，能障碍惭、生长恶行故。无愧者，不顾世间，崇重暴恶为性，能障碍愧，生长恶行为业。",
 "说「不顾世间」等义者，谓于世间无所顾者，崇重暴恶、不耻过非，能障于愧、生长恶行故。说不信者，于实、德、能不忍乐欲，心秽为性，能障净心，堕依为业。说「堕依」者，不信之人多懈怠故。说懈怠者，于善恶品修断事中懒惰为性，能障精进，增染为业。",
 "说「增染」者，因懈怠者滋长染故。说放逸者，于染净品不能防修，纵荡为性，障不放逸，增恶损善所依为业。此放逸以什么为体？答：「懈怠三根，不能防修染净等法，总名放逸，离上四法别无体性。」或说：",
 "「那慢、疑等也有此功能，为何不依之立？」答：「慢等方四，势用微劣故，不依立。」这四法为何偏胜其余慢等？答：「因障三善根、障遍策故，其余没有此能，所以不胜。」说昏沉者，令心于境无堪任为性，能障轻安，毗钵舍那（观）为业。",
 "或说：「昏沉与痴有何区别？」答：「痴于境迷暗为性，正障无痴，而非蒙昧；昏沉于境以蒙昧为相，正障轻安而非迷暗，故二者不同。」说掉举者，令心于境不寂静为性，能障行舍，奢么他（止）为业。失念者，于诸所缘不能明记为性，能障正念，散乱所依为业。",
 "说「散乱所依」者，失念则心散乱故。此失念，有人说：「念一分所摄，是与烦恼相应的念故。」有人说：「痴一分所摄，《瑜伽》说这是痴分故，痴令失念，故名失念。」有人说：「俱一分所摄，由前二文影略而说故。」不正知者，于所观境谬解为性，能障正知，毁犯为业。",
 "「毁犯业」者，不正知者多有毁犯故。此法有人说慧一分所摄，是与烦恼相应的慧故。有人说：「痴一分所摄，《瑜伽》说这是痴分故。令知不正，名不正知。」有人说：「俱一分所摄，由前二文影略而说故。」散乱者，令心流荡为性，能障正定，恶慧所依为业。",
 "说「恶慧所依」者，谓散乱者发恶慧故。或说：「散乱、掉举有何区别？」答：「散乱令心易缘，掉举令心易解，这是所别之相。」前文说「随其烦恼分位差别、等流性故」者，义正现于此。盖忿、恨等十并失念、不正知、放逸，此十三法是根本家差别分位；若无惭、无愧、掉举、昏沉、散乱、不信、懈怠，此七法是根本家等流性故。",
 "或说：「此七既别有体，为何名等流？」答：「根本为因，此方生故，名等流。」六、不定四者——这是别标，下面列名：一、睡眠，二、恶作，三、寻，四、伺。睡眠者，令身不自在，昧略为性，障观为业（即毗钵舍那）。",
 "，谓睡眠位，身不自在，心极暗劣，不能明转故。「昧」简别在定，「略」别于醒时，令显示睡眠非无体用，有无心位假立此名，如余盖缠心相应故。说恶作者，厌恶所作之业，追悔为性，障止为业（即奢么他），此于果上假立因名，因先厌恶所作之业、后方追悔故。",
 "悔先不作，也摄于恶作。如追悔说：「我先不作如是事业，是我恶作。」有义此二各有别体，与余心所行相别故，随痴相说名世俗有。说寻伺者，寻谓寻求，令心匆遽，于意言境粗转为性。伺谓伺察，令心匆遽，于意言境细转为性。",
 "二法的业用，都以安、不安住的身心分位所依为业。所谓「意言境」者，意所取境多依名言，名意言境。或说：「寻、伺二法是假是实？」答：「都用思与慧各一分为体。若令心安，即是思分；令心不安，即是慧分。",
 "「盖因思者徐而细故，慧则急而粗故。由此可知令安则用思无慧，不安则用慧无思。若依通照大师的解释，有兼、正之分：若正用思，则急慧随思能令心安；若正用慧，则徐思随慧也能令不安。这是二者并用。」第三、色法略有十一种：",
 "说「色」者，有质碍之色、有颜色之色，所依之根唯五，所缘之境则六，即前二所现之影。这是别标章，下面别列名。一、眼，二、耳，三、鼻，四、舌，五、身，六、色，七、声，八、香，九、味，十、触，十一、法处所摄色。",
 "说「一眼」者，照瞩之义，梵云斫刍，此翻「行尽」。眼能行尽诸色境故，名为行尽。翻为「眼」者，体用相当，依唐言。二、「耳」者，能闻之义，梵云莎噜多罗戍缕多，此翻「能闻声」。数数闻此声，至可能闻之处。翻为「耳」者，体用相当，依唐言。",
 "三、「鼻」者，能嗅之义，梵云伽罗尼羯罗拏，此云「能嗅」。嗅香臭故，数数由此能嗅香臭故。翻为「鼻」者，体用兼之，依唐言。四、「舌」者，能尝义，梵云舐若时吃缚，此云「能尝」。《瑜伽论》说：「能除饥渴，数发言论，表彰呼召，谓之舌。」",
 "」通于胜义、世俗二义。翻为「舌」者，也兼体用，依唐言。五、「身」者，积聚、依止二义名身，谓积聚大造、诸根依止，梵云迦邪，此翻「积聚」，身根为彼多法依止、诸根所随，周遍积聚故名为身。翻为「身」者，体义相当，依唐言。",
 "体即是根。此五说「根」者，都有出生、增上义故，则以能造、所造八法为体，是识所依之根。说「六、色」者，眼所取故，有二十五种。即青、黄、赤、白（此四为实），长、短、方、圆、粗、细、高、低（此相状假），",
 "，正、不正、光、影、明、暗、烟尘、云雾、迥色、表色、空一显色（此分位假），这些都是方处示现义，即颜色之色。对眼识故，质碍名色，乃色之总名。说「七、声」者，四大种所造，耳根所取义故。总有五因，摄十二种声。",
 "五因者：一、相故，即耳根所取义，此一为总，余四为别。二、损益故者，立初三声，即：可意声（是益）、不可意声（是损）、俱相违声（通二）。三、因差别故者，摄次三种：因执受大种声（语等）、",
 "，因不执受大种声（树等声）、因俱大种声（手鼓等声）。四、说差别摄三者，有世所共成声，谓世俗语所摄；成所引声者，谓诸圣所说；遍计所执声者，外道所说。五、言差别摄三者，圣言量所摄声，即八种圣语——圣，是正——此八种语不出见、闻、觉、知，该于六根（以鼻、舌、身皆觉故），如应于人的问，第一见则言见，乃至第四知则言知；若不见言不见，乃至第八不知言不知，这就是圣语。",
 "若第一见言不见、不见言见，乃至第八不知言知，这也是八种非圣言。《华严钞》唯十一，以唯识加「响」，以成十二，更待参考。说「八、香」者，乃鼻之所取，可嗅义故。总有六种，即：好香、恶香、平等香、俱生香、和合香、变易香。",
 "「九、味」者，舌之所取，可尝义故。有十二种，即：苦、酸、甘、辛、咸、淡、可意、不可意、俱相违、俱生、和合、变异。说「十、触」者，身之所取，可触之义，故名为触。有二十六种，即：地、水、火、风、轻、重、涩、滑、缓、急、冷、暖、硬、软、饥、渴、饱、力、劣、闷、痒、粘、老、病、死、瘦，就是这些。",
 "初四（地水火风）乃实，其余都依四大假立。或说：「其余既是假，身识如何缘？」答：「即缘实故；既即实缘，怎么知道轻等五（轻、重、涩、滑等）是五俱意识分别的呢。」说法处所摄色者，谓过去无体之法，可缘之义。此有五种，即：极迥色，依假想观析所碍色，至极微故，名极迥色。",
 "又说：「上见虚空青、黄等色，乃是显色，若从下望之，则此显色至远而难见，故名极迥色。」说极略色者，也以假想观析须弥等俱碍之色，至极微处故。又说：「于色上分析长短、形相、粗细，以至极微故。",
 "」说「俱碍」者，乃根色等明暗等色，是所碍。定果色，谓解脱定，也即鱼、米、肉山、威仪身等，也叫定自在所生色。定即禅定，自在所生色，谓菩萨入定所现光明，及见一切色像境界，如入火光定则有火光发现等。",
 "受所引色者，谓律仪、不律仪，殊胜思种所立无表色。又受即领受，引即引取，如受诸戒品，戒是色法，所受之戒即受所引色。遍计所执色者，谓第六识虚妄计度，所变根尘无实作用，故立此名。或说其余四名色有可拟议，受之所引为何也叫色？",
 "「盖从所防发之善恶之色，以立名。此四全、一少分是假，一分乃实。」第四、心不相应行法略有二十四种：这是色心分位，依前三法一分、一位假立「得」等之名。因行法有二，此简非心，所以立其名。这是总标章，下面才别列：",
