 "」世尊告诉说：「希求名为爱；对于险恶趣并无希求，然而由于所作非福行之故，虽求善趣却生相违之果；那果生时岂是缘于爱？只应用那取为其缘。又如所说无有爱者，希求无有；在求无有之时，因造福行、不动行之故，相违之果生起。",
 "这果生时岂是缘于爱？只应说那取为其缘。由此道理，不是只有爱与有作缘。」又禀白：「世尊！若取缘有、有缘生，为什么不说取与有以为集谛？」世尊告诉说：「因为爱能造作四种业之故：一者、这爱在其自体境界的受中，能作贪味系缚之业；",
 "二者、这爱能作发起诸取之业；三者、这爱能作令先前所引的行等成为有之业；四者、这爱能作死后相续受生之业。由此因缘，只说这爱以为集谛。」又禀白：「世尊！若生老死，以名色、六处、触、受为相，对于这生身为什么显示生老死之名？",
 "世尊告诉说：「为了显示这样的生身之相，有三种苦成就苦性之故。」又禀白：「世尊！生显示什么苦？」世尊告诉说：「生显示行苦。」又禀白：「世尊！老显示什么苦？」世尊告诉说：「老显示坏苦。」又禀白：「世尊！死显示什么苦？」世尊告诉说：",
 "「死显示苦苦。」又禀白：「世尊！这样的四种生身之相，由生老死有何差别？」世尊告诉说：「就是这四种生身之相，若次第生、若属于彼生、若如是生，应当知道这叫生身生相。」又禀白：「世尊！什么叫次第生身生相？」",
 "世尊告诉说：「在其最初有下种生，从此无间有渐增生，从此无间有出胎生，从此无间有渐长生。既已成长之后，受用言说能得等生，如是品类名叫次第生。」又禀白：「世尊！这属于谁生？」世尊告诉说：「蕴、界、处生都无有我。",
 "为什么呢？因为诸蕴等渐增长之故，其性无常，即这无常法有此生相。」又禀白：「世尊！怎样而生？」世尊告诉说：「由命根之力而有暂时之住，因分限法之故，其性无常，即这无常法如是而生。就是这四种生身之相，时分变异，应当知道能作五种衰损，说名为老。",
 "」又禀白：「世尊！什么叫五种衰损？」世尊告诉说：「一者、须发衰损，因为那须发颜色衰坏之故；二者、身相衰损，因为形色、肤力都衰损之故；三者、作业衰损：发言时气往上冲、喘息急促，身体颤抖之故；站立便佝偻弯曲，因为腰脊都没有力之故；坐下便低屈，因为身体羸弱之故；行走必须按杖，因为身体虚劣之故；凡所思惟，智识愚钝，因为念惛乱之故；",
 "四者、受用衰损：对于现前的资具，受用低劣之故；对嬉戏乐于之具，一切都不能现前受用之故；对诸色根所行的境界，不能速疾明利而行、或不能行之故；五者、命根衰损：寿量将尽、邻近于死之故，遇到微少的死缘便不堪忍之故。就在这四种生身之相中，又有六种死的差别相：",
 "一者、究竟死；二者、不究竟死；三者、自相死；四者、不究竟死分差别相；五者、究竟死分差别相；六者、时死与非时死。应当知道，此中自相死者，就是说识离于身、色相灭没的差别之相。这就叫生身相中名色等相由生老死而有差别。",
 "」又禀白：「世尊！在缘起中说三种爱，一切都是生身之缘。为什么处处大多只说欲界生身？」世尊告诉说：「因为欲界生身的相最粗之故、容易显了之故、并非永得解脱而会退还之道之故。」又禀白：「世尊！如先前所说诸引缘起、诸生缘起有十二分，在这些分中，几分是能引？",
 "几分是所引？几分是能生？几分是所生？」世尊告诉说：「应当知道，在这十二分中，无明与行及识的一分，名为能引；又有一分识及名色、六处、触、受，名为所引；又有一分受、爱、取、有，名为能生；生及老死名为所生；应当知道一分名色、六处以及触、受，也叫所生。",
 "」又禀白：「世尊！这些分，无论是引是生，是一时而起？还是次第而起？」世尊告诉说：「一时而起，次第宣说。」又禀白：「世尊！这些分，若一时而起，以什么因缘先说其引、后说其生？」世尊告诉说：「必须由有引，后有才生，不是没有引之故。",
 "」又禀白：「世尊！无明也缘非理作意，为什么只说无明为缘？」世尊告诉说：「无明也引非理作意与行作缘，又从无明所生的触、受为缘而生爱，所以偏说无明为缘。」又禀白：「世尊！略由几相应当知道缘起？」世尊告诉说：「略由三相应当知道缘起：",
 "一者、由无动作而知缘起相；二者、由性无常而知缘起相；三者、由有堪能而知缘起相。」大唐三藏法师玄奘奉诏译。「再者，世尊！如其他地方说缘有四种，所谓因缘、等无间缘，以及所缘缘和增上缘。世尊！如今依什么缘说无明缘行，依什么缘说次第乃至生缘老死？",
 "」世尊告诉说：「我依诸行的总相宣说有四種缘；但在如今这义中，我只依一种增上缘说无明缘行，次第乃至生缘老死。这增上缘又有二种：一者远、二者近。」又禀白：「世尊！这增上缘怎样为远？怎样为近？」世尊告诉说：",
 "「非理作意若未生时，无明随眠能作诸行的远增上缘；已生便作近增上缘。非理作意所引的诸行，与六识身相应俱有、同生同灭，若未生时，它能作识的远增上缘；它若已生，便能作识的近增上缘。未死没时，识作名色的远增上缘；",
 "既已死没，识作名色的近增上缘。如以其识对望那名色，如是以其所引的名色对望那所生的名色，也是如此。如以名色对望那名色，如是六处对望那六处、触对望于触、受对望于受，也是如此。如以无明对望那些行、无明对望爱、爱对望于取、取对望于有，也是如此。",
 "如以其识对望那名色，以名色等对望名色等，如是以有对望生，也是如此。若在胎藏、婴孩、童子、少年之时，生能作老死的远增上缘；诸根成熟、命将尽时，应当知道能作近增上缘。」又禀白：「世尊！如那有因、有缘、有由的法门经说爱是业因，有什么密意？",
 "」世尊告诉说：「有取所摄之业以爱为因，这就是此中所说的密意。」又禀白：「世尊！这因、缘、由三种差别之义，应当怎样了知？」世尊告诉说：「诸能引发后生种子的，是其因义；若与这生作依作持、令得生起的，是其缘义；既已命终之后，导引近生、令得生起的，是其由义。",
 "如是应当了知三义的差别。」又禀白：「世尊！所谓缘起，是什么句义？」世尊告诉说：「这些分，各由自缘和合无缺、相续而起，这就叫缘起句义。」又禀白：「世尊！只有这生相续缘起？还是更有别的其他缘起？」世尊告诉说：",
 "「我说缘起，略有八门：一者、说有受用世俗境界缘起，就是说缘于眼、色而生眼识，三事和合便有其触，触为缘而有受，如是广说。二者、说有任持缘起，就是说缘于四食，诸根、大种安住增长。三者、说有食因缘起，就是说求诸谷，以田、种、水为缘而发生芽等。",
 "四者、说有一切生身相续缘起，就是说由能引、能生的诸分别，生起一切所引、所生。五者、说有一切生身依持缘起，就是说诸世界由诸因缘而施设成坏。六者、说有一切生身差别缘起，就是说由不善业、善有漏业，施设三恶趣、人天趣的差别。",
 "七者、说有清净缘起，就是说依于他音（闻法），以及依于自内如理作意，发生正见能灭无明；无明灭之故诸行随灭，广说乃至由生灭之故老死随灭。」又禀白：「世尊！如无明等次第为缘能生行等，是不是就这样次第而灭呢？」佛说：",
 "「不是。」又禀白：「世尊！为什么次第说它们的灭？」世尊告诉说：「为了显示由先前诸分不生之功能，令后来诸分获得不生之法，所以次第而说；然而并非不是为生相之灭法而有次第转起。八者、说有自在缘起，就是说以善修治静虑为缘，诸修定者随其所愿乐，如此都能成就，终无别异。",
 "这就叫我所略说的八门缘起。」又禀白：「世尊！如佛所说，因业故生，因爱故转。依什么密意作这样的宣说？」世尊告诉说：「以无明为缘，先在诸有中造作、增长种种福行或非福行或不动行，引发、摄受种种生身种子的差别。",
 "在此有中，若爱未断，由此爱之故，能令行等转成其有。有生起后有自体的功能，这样的功能不离于爱。依这个密意所以说这样的话：因业故生，因爱故转。」又禀白：「世尊！若世尊说爱是转因，为什么只说取为有之缘，而不说爱缘有？",
 "」世尊告诉说：「若离于取，有爱不能作缘、转变非福行等，令其成为有支而生诸恶趣。又若离取，诸无有爱不能作缘，转变福行、不动行等，令其成为有支，在不定地及在定地生诸善趣。所以不是只有爱为有之缘，那有支一定缘于取。",
 "」又禀白：「世尊！如《大因缘法门经》说：『你阿难陀！若在彼彼有情类中没有生，应无如是如是类生；若一切生都没有，应不施设生缘老死。』依什么密意作这样的宣说？」世尊告诉说：「依所引之生及所生之生，二种密意，作这样的宣说。",
 "又依老死的远增上缘，及依老死的近增上缘，二种密意，作这样的宣说。」又禀白：「世尊！先前已为略说缘起句义，其缘起之义还未宣说，应当怎样了知？」世尊告诉说：「诸缘起之义，略有十一种，应当这样了知：就是说，无作者义是缘起义，有因生义是缘起义，离有情义是缘起义，依他起义是缘起义，无动作义是缘起义，性无常义是缘起义，刹那灭义是缘起义，因果相续无间绝义是缘起义，种种因果品类别义是缘起义，因果更互相符顺义是缘起义，因果决定无杂乱义是缘起义。",
 "如是应当了知缘起的略义。」又禀白：「世尊！如其他经说，缘起甚深。应当怎样了知这样缘起甚深之相？」世尊告诉说：「即依十一种缘起略义，应当了知缘起五甚深相。哪五种？一、因甚深；二、相甚深；三、生甚深；四、差别甚深；五、流转甚深。",
 "应当知道，缘起甚深之相又有五种。哪五种？即相甚深、引发因果诸分甚深、生起因果诸分甚深、差别甚深、对治甚深。应当知道，缘起又有五种甚深之相。哪五种？即摄甚深、顺次甚深、逆次甚深、执取甚深、所行甚深。",
 "这叫无明等起殊胜。」又禀白：「世尊！什么叫无明转异殊胜？」世尊告诉说：「略有四种转异无明。哪四种？一者、随眠转异无明；二者、缠缚转异无明；三者、相应转异无明；四者、不共转异无明。」又禀白：「世尊！",
 "谁有什么样的转异无明，而说无明为缘生行？」世尊告诉说：「外法异生（外道凡夫）由非理作意所引的四种转异无明，以此为缘，生福行、非福行及不动行。如是所说的外法异生所有福行及不动行相应的善心，一切都是由非理作意所引的等流。",
 "内法异生（内道凡夫）若放逸者，除一种不共无明外，其余无明引发放逸，为缘生行。内法异生若不放逸、勤修学者，以及圣者有学，三种无明引发妄念作为非福之缘，然而这非福不能为缘招感三恶趣。所以这非福，我不说为无明缘行。如是所说的不共无明，内法异生虽不放逸而修学者也未能断除；诸圣者有学，应当知道已永断。",
 "又不放逸的内法异生，若造作福行及不动行，那是正法如理作意相应善心所引发，以解脱为依、回向解脱而引发的，虽然在善趣感得殊胜之生，却不是无明起增上缘，而是能作那四种无明断除的增上缘。诸圣者有学，因不共无明已永断之故，不造新业；所有故业因随眠之力未永断灭，暂时触受还吐（受而不积），如是所有无明缘行，生生渐灭、不再增长。",
 "由这个道理，应当知道内法诸有学者不缘无明而更造诸行。所以只依外法异生，我说顺次杂染缘起最为圆满，不是安住内法者的境界，这叫无明转异殊胜。」又禀白：「世尊！什么叫无明邪行殊胜？」世尊告诉说：「那四种无明，对于诸谛都能发起增益、损减二种邪行。",
 "」又禀白：「世尊！怎样名为增益、损减二种邪行？」世尊告诉说：「由四种颠倒，就是说，对非法见为是法，或对是法见为非法，或在生天解脱道中，把非方便者见为是方便、把是方便者见为非方便，这样名为增益邪行；诸有诽谤、一切邪见，这样名为损减邪行。",
 "这叫无明邪行殊胜。」又禀白：「世尊！什么叫无明相状殊胜？」世尊告诉说：「应当知道无明有二种相：一者、微细自相殊胜；二者、遍于可爱、非爱、俱非境界的共相殊胜。为什么呢？缠缚无明尚且微细难知难了，何况那所有的随眠无明；",
 "相应无明尚且微细难知难了，何况那所有的不共无明，遍于一切可爱、非爱、俱非境界，覆盖真实相、显现虚妄相，以共相而转起。其余烦恼没有这样的相，所以殊胜。其余如身见等共相烦恼，也以无明为依而转起，这叫无明相状殊胜。",
 "」又禀白：「世尊！什么叫无明作业殊胜？」世尊告诉说：「应当知道无明略有二种所作事业：一者、无明普遍能造作一切流转的所依事业；二者、无明普遍能造作一切寂止的能障事业。」又禀白：「世尊！什么叫一切流转？」世尊告诉说：",
 "「若是处转、若是事转、若如是转，我总说为一切流转。」又禀白：「世尊！是什么处转？」世尊告诉说：「对于三世的处所，由我分别而转。」又禀白：「世尊！是什么事转？」世尊告诉说：「内外六处，由我取执而转。」又禀白：「世尊！",
 "怎样而转？」世尊告诉说：「诸业异熟相续流转，由我分别、由邪分别而转。」又禀白：「世尊！什么叫一切寂止？」世尊告诉说：「一切寂止略有四种：一者、寂止所依；二者、寂止所缘；三者、寂止作意；四者、寂止果成。这叫无明作业殊胜。",
 "」又禀白：「世尊！什么叫无明障碍殊胜？」世尊告诉说：「应当知道无明障碍胜法、障碍广法。」又禀白：「世尊！无明怎样障碍胜法？」世尊告诉说：「所谓胜法，就是能摄五根令其和合，所谓慧根；障碍这个的就是无明，所以说名障碍胜法。",
 "」又禀白：「世尊！无明怎样障碍广法？」世尊告诉说：「所谓广法，就是闻所成智、思所成智、修所成智；障碍这个的就是无明，所以说名障碍广法。」又禀白：「世尊！如说无智名为无明，这只是智无就叫无明吗？」世尊告诉说：",
 "「不是只有智无就名为无明。」又禀白：「世尊！若只有智无就名为无明，这有什么过失？」世尊告诉说：「若是那样，无明就应不可安立决定的体相。为什么呢？在闻所成智的体上，没有思所成智；在思所成智的体上，没有修所成智；在一切世间修所成智的体上，没有一切出世修所成智；",
 "在出世有学智上，没有诸无学智；在无学声闻智上，没有如来等智。若如此，那就应是即智即无智，这样的无明就应不可安立决定的体相。又我在那三善根之中，说有无痴；若按痴无即名无痴，应只是痴无就叫无痴，然而并非痴无就叫无痴；所以并非明无就叫无明，而是另外有一心所有法，不了知真实，说名无明。",
 "如另有一心所有法，了知真实，说名为智；又若只是明无就名无明，那就应没有这样一切无明的十一种殊胜。所以应当知道，并非只是明无就说名无明，这叫无明障碍殊胜。」又禀白：「世尊！什么叫无明随缚殊胜？」世尊告诉说：「乃至有顶（非想非非想处）的三界有情，对于诸谛中所有的无智、随眠、随缚，未缺未减，由这些有情说名具缚。",
 "又这无智，在善趣恶趣的因果差别中，无色界有情有它的下品，色界有情有它的中品，欲界有情有它的上品，如是成就三品无明。诸有情类当来可生之处，一一法尔都有三品随缚。这是说异生；若诸圣者则渐次永断：若具有上品、中品，定有中品、下品；或有中品、下品而无上品、中品。",
 "又阿罗汉，虽然已尽诸漏、脱烦恼障，应当知道还有所知障所摄的无明随缚；这样的无明，应当知道极远地随逐有情，唯有诸佛除外，其余都被随缚。这叫无明随缚殊胜。」又禀白：「世尊！什么叫无明对治殊胜？」世尊告诉说：「有二种妙智对治无明。",
