def fix_one(tid):
    path = os.path.join(OUT_DIR, f"{tid}.json")
    with open(path, encoding='utf-8') as f:
        data = json.load(f)
    
    fixed_count = 0
    for seg in data['translations']:
        md = seg.get('modern', '')
        if '【法義宣說】' in md:
            op = seg['original_preview']
            new_sub, new_yj = refine_subtitle(op)
            if new_sub:
                # 替换小标题
                new_md = md.replace('【法義宣說】', f'【{new_sub}】', 1)
                # 替换义解
                new_md = new_md.replace(
                    "【义解】此段為經文正文，宣說佛法要義，明修行法則、因果因緣或法門功德。",
                    f"【义解】{new_yj}",
                    1
                )
                seg['modern'] = new_md
                fixed_count += 1
    
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    
    # 统计剩余
    remaining = sum(1 for seg in data['translations'] if '【法義宣說】' in seg['modern'])
    print(f"✅ {tid}: 修正 {fixed_count} 段，剩余空泛小标题 {remaining} 段")
    return fixed_count, remaining

total_fixed = 0
total_remaining = 0
for tid in IDS:
    f, r = fix_one(tid)
    total_fixed += f
    total_remaining += r

print(f"\n共修正 {total_fixed} 段小标题，剩余空泛小标题 {total_remaining} 段")
