def process_file(file_path):
    """处理单个json文件"""
    print(f"Processing {file_path}...")
    with open(file_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    # 添加译者
    data['baihua_translator'] = "白話文編譯組"
    
    # 逐段翻译
    for seg in data['translations']:
        original = seg['original_preview']
        if not seg['modern'].strip():
            seg['modern'] = translate_segment(original, data['id'])
    
    # 写回文件
    with open(file_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"Finished {file_path}, {len(data['translations'])} segments translated.")

