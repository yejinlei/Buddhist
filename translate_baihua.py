def split_text_by_sentences(text):
    """按中文句末标点分句"""
    sentences = []
    start = 0
    for i, c in enumerate(text):
        if c in '。！？；':
            sentences.append(text[start:i+1])
            start = i+1
    if start < len(text):
        sentences.append(text[start:])
    return [s.strip() for s in sentences if s.strip()]

