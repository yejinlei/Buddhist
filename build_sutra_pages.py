def main(target=None):
    OUT_PAGES.mkdir(parents=True, exist_ok=True)
    done = 0
    fail = 0
    for fn in sorted(os.listdir(TRANS)):
        if not fn.endswith(".json"): continue
        tid = fn[:-5]
        if tid == "tree": continue
        if target and tid != target: continue
        try:
            d = json.load(open(TRANS/fn, encoding="utf-8"))
            title = to_simp(d.get("title","") or "")
            trans = to_simp(d.get("translator","") or "")
            segs = d.get("translations",[]) or []
            # 根目录版（prefix=""，back_href="pages/sutras.html"）
            (OUT_ROOT/f"{tid}.html").write_text(
                build_page(tid, title, trans, segs, "", "pages/sutras.html"),
                encoding="utf-8")
            # pages/ 版（prefix="../"，back_href="sutras.html"）
            (OUT_PAGES/f"{tid}.html").write_text(
                build_page(tid, title, trans, segs, "../", "sutras.html"),
                encoding="utf-8")
            done += 1
            if done % 200 == 0:
                print(f"  已生成 {done} 部...", flush=True)
        except Exception as e:
            fail += 1
            print(f"  FAIL {tid}: {e}")
    print(f"完成：成功 {done}，失败 {fail}")

if __name__ == "__main__":
    tgt = sys.argv[1] if len(sys.argv) > 1 else None
    main(tgt)
