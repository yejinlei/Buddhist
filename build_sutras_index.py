def to_simp(s):
    if not s: return ""
    s = s.replace("菩薩","菩萨").replace("菩提薩埵","菩萨")
    s = s.replace("迦葉","迦叶").replace("阿難","阿难")
    s = s.replace("優婆塞","优婆塞").replace("優婆夷","优婆夷")
    s = t2s.convert(s)
    s = s.translate(FORCE_MAP)
    return s

def vol_of(tid):
    m = re.match(r'[tT](\d+)', tid)
    if not m: return "其他"
    n = int(m.group(1))
    if 1 <= n <= 151: return "阿含部"
    if 152 <= n <= 261: return "本缘·般若"
    if 262 <= n <= 320: return "法华·华严"
    if 321 <= n <= 397: return "宝积·涅槃·大集"
    if 398 <= n <= 847: return "经集部"
    if 848 <= n <= 1420: return "密教部"
    if 1421 <= n <= 1459: return "律部"
    if 1505 <= n <= 1563: return "释经论·毗昙"
    if 1564 <= n <= 1878: return "中观·瑜伽·论集"
    if n >= 1879: return "诸宗·史传·目录·事汇·外教·索引"
    return "其他"

def load_meta(tid):
    """优先读译文JSON的title/translator，回退到源sutras JSON。"""
    title, trans, n_seg = "", "", 0
    jp = TRANS / f"{tid}.json"
    if jp.exists():
        d = json.load(open(jp, encoding="utf-8"))
        title = to_simp(d.get("title","") or "")
        trans = to_simp(d.get("translator","") or "")
        n_seg = len(d.get("translations",[]) or [])
    if not title:
        sp = SUTRAS_DIR / f"{tid}.json"
        if sp.exists():
            sd = json.load(open(sp, encoding="utf-8"))
            title = to_simp(sd.get("title","") or sd.get("name","") or "")
    return title, trans, n_seg

