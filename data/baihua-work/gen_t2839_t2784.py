def build(tid, intro, moderns):
    with open(os.path.join(TASK, tid + ".json"), encoding="utf-8") as f:
        sk = json.load(f)
    trs = sk["translations"]
    assert len(trs) == len(moderns), (tid, len(trs), len(moderns))
    out = {
        "id": sk["id"],
        "title": sk["title"],
        "translator": sk.get("translator", ""),
        "mode": "baihua",
        "intro": intro,
        "sutraPath": "sutras/" + tid + ".json",
        "translations": [],
    }
    for i, seg in enumerate(trs):
        out["translations"].append({
            "section": seg.get("section", ""),
            "original_preview": seg["original_preview"],
            "modern": moderns[i],
        })
    path = os.path.join(OUT, tid + ".json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
    return path, len(trs)

