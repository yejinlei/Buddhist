"【精进大与舍利弗】（承上文）第二无数劫从初地至八地，修见道成就；第三无数劫从八地至无学地。譬如舍利弗行菩萨行时，有一个婆罗门向他乞眼，他便布施给对方；婆罗门得到眼后，却用脚去踩踏，舍利弗反问：为什么踩它？对方答：我要它的声音。所谓「方便大」，与上面「智大」所说相同。所谓「业大」……【义解】此段承「精进大」，以三无数劫配初地至八地（见道）、八地至无学（修道）的进程；并引舍利弗施眼被踩的典故，说明菩萨行要经得起难行苦行。「方便大」同于智大，故不再详说。以下转入「业大」。",

"【业大愿大成满】（承上文）穷尽生死之边际，能作诸佛；乘此行者能发四愿，这是「愿大」：若有一个众生不成佛，就誓不趣求无上菩提；不同于声闻不发大愿。「成就大」，是能成就十力、四无畏、十八不共法等大功德，一一如其他处所说。上来所说的「七大」之义……【义解】「业大」指尽未来际能成办佛事；「愿大」以「众生不尽、誓不成佛」的悲愿为体，远超声闻；「成就大」则能成就佛果十力、四无畏、十八不共法等功德。七大至此列举完毕，下文总结其因果关系。",

"【七大因果】（承上文）前六种为因——因为单修一种不能成就十力等，必须要修这六种；后一种（成就大）为果。所谓「四法船」，就是不捨菩提心，以及乐住于空闲，这就是了。所谓「列数」，论中自有说明。所谓「出生」，是依这四法修行能出离生死大海。所谓「号显示」，是能显示甚深法性。所谓「古今不易」……【义解】七大为因，成就大为果：前六（修行、智、精进、方便、业、愿）是能修之因，后一（成就）是所成之果。「四法船」以四法为渡生死海的舟航。「列数」「出生」「号显示」等，是对经中名目的逐项疏解。",

"【古今不易等释】（承上文）「古今不易」会合上文「常」之义：前佛、后佛都不曾改变增益，也如同十二因缘一样；「法逕」二字，也如上面一样会合。所谓「示处」，就是从「如是我闻」到「菩萨摩诃萨」这一段（原文作「魔訶薩」，当是「摩訶薩」）。所谓「于相」，就是三性，即遍计所执等。所谓「法」，是五蕴、十八界等。所谓「义」，就是能诠显这五蕴、十八界体性的所在。【义解】此处逐条疏释经中名相：以「常」义释「古今不易」，以「如是我闻……菩萨摩诃萨」标示说法之处，以三性（遍计、依他、圆成）释「相」，以五蕴十八界释「法」，以能诠之文释「义」。可见此抄重在释名释义。",

"【发起序与化缘】所谓「发起序」有两种：一是因请而发起，二是不因请而发起（原文作「識」，当是「請」）。问：为什么不广释证信序？答：证信序是诸经共有，不必再重复解释；虽然如此，现在也略作说明。所谓「佛化缘毕」，是说只度有缘，不度无缘，所以《维摩经》说：佛的威德虽然普遍，但不度无根、无泽、无□（此处原文阙一字）之人，不润泽枯木。【义解】此段释「发起序」有两类，并说明略释证信序的原因。又引《维摩经》，说明佛化度众生须待因缘：无缘者不得度，如枯木不受润泽。文中「无□」为原抄阙字。",

"【四念处一】所谓「四合处」（当为「四念处」）。「观身不净」，是说此身之上有三十六种物等种种不净，共同构成此身，所以名为不净（云云）。「观受是苦」，是说苦受、乐受、不苦不乐受，都是苦；众生不了达，执著（我执）为乐。文中「迦叶菩萨等」的「等」字，是等取弥勒、文殊等。【义解】此处开始释四念处（原文作「四合处」，当为「四念处」）。先释「观身不净」（三十六物不净）与「观受是苦」（三受皆苦，众生妄执为乐）。并说明「迦叶菩萨等」的「等」字，是兼指弥勒、文殊等大士。",

"【四念处二】「观心无常」，是说此心念念迁谢，众生不了达，执为常相。「观法无我」，是说在五蕴、十八界上，本来没有我、人、众生等；众生不了达，横加计度认为有我；只要不起如上这些颠倒之见，就能成就圣道。（「口」是「因」的意思。）所谓「梵坛」，这里叫「默槟」。所谓「杂事律」，就是根本部中下五十卷里所说的。【义解】续释后二念处：「观心无常」（念念迁谢）与「观法无我」（五蕴十八界本无我人众生）。并随文解释「梵坛」（此云默槟）、「杂事律」（出根本部中下五十卷）等名相。",

"【结集时与五比丘】所谓「结集时」，是佛涅槃之后，在王舍城七叶岩窟，聚集五百大阿罗汉；大众请阿难升座说法，生起三种疑惑；等到阿难说出「如是我闻」等语才释疑。佛最初成道时，在鹿野苑中最初度化五俱轮（五比丘）等，宣说四谛之法，三转（云云）。所谓「时方人」，就是该经中的「一时」。【义解】此段述结集因由：佛灭后于王舍城七叶窟结集，阿难升座诵出「如是我闻」，众疑始解。又述佛初成道在鹿野苑度五比丘、说四谛三转法轮之事。并释经首「一时」兼含时、方、人。",

"【时方人等释】「方」是处所；「人」是听法之众。所谓「教」，就是十二分教。所谓「理」，就是真如之性。所谓「行」，就是八圣道。所谓「果」，就是有上果、无上果等（云云）。所谓「依愿得果为如」，如布施得大福报等（云云）。所谓「废别就总」，有两种含义。【义解】此段把「时、方、人」以及「教、理、行、果」等名相一一配释：教指十二分教，理指真如，行指八圣道，果分有上、无上。「依愿得果」以布施得福为例。以下释「废别就总」。",

"【废别就总等释】（承上文）「废别就总」的第一义，是要借耳根发识、意随分别。所谓「一一陈遂成繁广」，这是假立问难说：经题之中只要安立根、意、思、识就可以了，为什么要用「我闻」？答：就义理说，安立「如是」等等便成了繁广，所以要废别就总。又问：为什么不单举一个？答：若单举一个，义用便有偏。又设问难说：若是这样，何不……所谓「无我闻」……【义解】此段以设难、作答的方式，说明经首何以用「我闻」而非单举根、识：一一别说（举根、意、思、识）即成繁广，故须「废别就总」，而「我闻」正是总括之词。",

"【立我闻与机感】（承上文）为引导外道入于佛法，所以安立「我闻」。如佛以善巧方便，为长爪梵志发问而对世尊假立「我」之称。所谓「善合时宜」，是应在食前堪受化度的，就在食前度化他；若食后堪受化度的，就在食后度化他。所谓「机感相应」，譬如清水，随容器大小，都能在其中映出月影，能现大小不同的影子。【义解】此段释经首立「我闻」的用意：为引导外道入法，随俗假立「我」（如佛对长爪梵志的方便）。又释「善合时宜」与「机感相应」——说法须应机，如清水随器现影，众生根器不同则所受法益不同。",

"【相应得益】所谓「相应得益」，是诸佛如来随众生三乘的根性，应时说法，令众生各得其益；也如医生随病之冷热而令服相应的药，病即痊愈。所谓「外典无如是能」，是说外道典籍没有如上应机设教、应病施药的能力，也没有「一时」（即一时说法普益）之说。所谓「前简说听者」，是其余部类经中简取四法。【义解】此段以「应病与药」为喻，说明佛随三乘根性说法，令各得其益；并以此反显外道典籍不能应机设教。下文转入对「说听」与「四法」的简择。",

"【唯识难与世识】所谓「后简说听者」，就是食前、食后的意思。所谓「若尔诸法应非唯识者」，是假立问难说：这《四法经》，若依大乘三宗之中，暂且属唯识宗所摄；但如上所立「一」以及「时」，是心外之法，所以此四法应非唯识。答语同于决文。所谓「世识」，就是世间、器世间（即依报世界）。【义解】此段设「诸法应非唯识」之难：《四法经》虽属唯识宗，但经中立「一」、立「时」，看似心外之法，故有人质疑它非唯识。下文以「世识」「数识」等作答。世识即世间、器世间。",

"【世数识与佛德】所谓「数识」，就是一、二、三、四。所谓「最胜尊」，就是佛。所谓「自在」，是欲界、色界、无色界三界九地中见惑、修惑等烦恼都不能系缚他，于烦恼得自在的缘故。所谓「炎猛」，是以智慧之火焚烧烦恼之薪的缘故。所谓「端严」，是因恭敬父母、师长、僧众、和尚，而获得三十二相、八十种好等。【义解】此段以「世识」（世间、器世间）、「数识」（一二三四）等答前之难，说明「一」「时」等仍是识所变，非实心外法。接着列举佛的德号：最胜尊、自在、炎猛、端严等，一一释其得名之由。",

"【吉祥与十德】所谓「吉祥」，是因亲近、恭敬、供养（佛）而都加以称赞，故具足吉祥；譬如盲者得以见、哑者得以语等（云云）。所谓「常起方便利益安乐」，是世间的利益、出世间的安乐；或说增上胜妙的安乐、决定生起的利益，反覆运用，名叫「尊贵」之义，也叫「精进」。所谓「佛具十德」，是假立问难说……【义解】此段续释佛德：「吉祥」因恭敬供养而感得（如盲见哑语之喻）；「常起方便利益安乐」兼摄世间利益与出世间安乐；「佛具十德」引出下文对佛名（薄伽梵）的问答。",

