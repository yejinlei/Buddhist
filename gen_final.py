def merge_xu(lst):
    r=[];i=0
    while i<len(lst):
        if '度無極章第' in lst[i]['chapter']:
            r.append({'chapter':lst[i+1]['chapter'],'text':lst[i]['text']+'\n'+lst[i+1]['text']})
            i+=2
        else:
            r.append(lst[i]);i+=1
    return r
filtered=merge_xu(all_chaps)
assert len(filtered)==91

def t2s(t):
    return cc.convert(t).replace('闍','阇')
def vern(t):
    s=t2s(t).replace('「','“').replace('」','”').replace('『','“').replace('』','”')
    return '\n'.join([l.strip() for l in s.split('\n') if l.strip()])

