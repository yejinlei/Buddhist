def build(fid, title, translator, intro, segs):
    src = load(fid)
    text = src["content"][0]["text"]
    paras = text.split("\n")
    last = len(paras) - 1
    translations = []
    for i, (a, b, t, body, yj) in enumerate(segs, 1):
        preview = "\n".join(paras[a:b + 1])
        if b < last:
            preview += "\n"
        modern = "【小标题】%s\n%s\n【义解】%s" % (t, body, yj)
        translations.append({
            "id": "seg%d" % i,
            "original_preview": preview,
            "modern": modern,
        })
    # 自检：拼接后须等于全文
    joined = "".join(x["original_preview"] for x in translations)
    assert joined == text, "COVER MISMATCH for %s (len %d vs %d)" % (fid, len(joined), len(text))
    out = {
        "id": fid,
        "title": title,
        "translator": translator,
        "mode": "白话",
        "intro": intro,
        "translations": translations,
    }
    path = os.path.join(OUT, fid + ".json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print("wrote", path, "segs=", len(translations), "cover_ok")


