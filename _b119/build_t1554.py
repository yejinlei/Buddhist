 "不善根有三种，即前所对治的贪、瞋、痴三者。贪，即欲界五部之贪；瞋，即五部之瞋；痴，即欲界三十四种无明，除去有身见及边执见相应的无明。如此三法是不善的自性，也能作根而生起其余不善，所以名为不善根。不安隐之义是不善之义，因能引生非爱诸有之芽；又未习学、非巧便之义是不善之义，因此能成办恶色之像，如彩画师所造不妙之像，世间称为不善。",
 "无记根有四种，即爱、见、慢、无明。爱，即色界、无色界各有五部之贪。见，即色界、无色界各有十二见，以及欲界的有身见、边执见。慢，即色、无色界各有五部之慢。无明，即色、无色界一切无明，以及欲界有身见、边执见相应的无明。这四种无记根，是自宗所许；因修静虑者有三种差别：",
 "一、爱味于上静虑者；二、执着见而味上静虑者；三、恃慢而味上静虑者。这三者都因无明之力而起。毗婆沙师建立无记根只有三种，即无记的爱、无明、慧三者。因为疑不坚住、慢性高举，都不是根法，对善、不善之义都不记别，所以名为无记。又因不能记别爱与非爱之果，所以名为无记。",
 "因不能招感异熟果之故，此无记性也能生起其余无记染法或诸无记法，所以名为无记根。结有九种，即爱结、恚结、慢结、无明结、见结、取结、疑结、嫉结、悭结。爱结，即三界之贪，是染著之相，如融化的胶漆，所以名为爱。",
 "爱即是结，所以名爱结。恚结，即五部之瞋，对有情等乐意作损苦、不予饶益之相，如辛苦之种，所以名为恚。恚即是结，所以名恚结。慢结，即三界之慢，以自己比量他人的德类差别，心恃举之相名为慢，如骄傲放逸者凌蔑他人。这又有七种：",
 "一、慢；二、过慢；三、慢过慢；四、我慢；五、增上慢；六、卑慢；七、邪慢。即因族姓、财位、色力、持戒、多闻、工巧等事，若对劣者说自己胜、或对等者说自己相等，由此令心高举，名为慢。若对等者说自己胜、或对胜者说自己相等，由此令心高举，名为过慢。",
 "若对胜者说自己胜，由此令心高举，名为慢过慢。若对五取蕴执着我、我所，由此令心高举，名为我慢。若对未证得的预流果等殊胜功德说自己已证得，由此令心高举，名为增上慢。若在大多族姓等殊胜之中说自己稍劣，由此令心高举，名为卑慢。",
 "若实际无德而说自己有德，由此令心高举，名为邪慢。如此七慢总名为慢结。无明结，即三界之无知，以不解了为相，如盲人违害光明之故，说名无明。这是遮止之语，依对治之义，如非亲友、不实等语，即是说怨家、虚诳语等。",
 "无明即是结，所以名无明结。见结，即三种见，即有身见、边执见、邪见。五取蕴中本无我、我所，却执着实有我、我所之相，这种染污之慧名有身见。身是聚集之义，有（五取蕴）而是身，所以名有身。即此五取蕴，于此起见，名有身见。即此五取蕴非常非断，于中执着有断、常二相，这种染污之慧名边执见，因为执著二边之故。",
 "若决定执着无业、无业果、无解脱、无得解脱之道，拨无实事，这种染污之慧名邪见。如此三见名为见结。取结，即二种取，就是见取、戒禁取。即对前三见及五取蕴，实际并非殊胜却执取为殊胜，这种染污之慧名见取。取是推求及坚执之义。",
 "戒，即远离诸破戒之恶禁；禁，即受持乌鸡、鹿、狗的禁戒，露形、拔发、断食、卧灰，或于妄执中生福、灭罪，在诸河池中屡屡沐浴，或食根果草菜药物以自活命，或又涂灰、拔头发等，都名为禁。这二者都不是能清净之道，却妄执取为能清净之道，这种染污之慧名戒禁取。",
 "诸婆罗门中多闻者，多执此戒禁取法以为清净之道，而他们不能获得毕竟清净，如此二取名為取结。疑结，即对四圣谛令心犹豫，如面临歧路、见到指路的草人而踌躇不决，如此对苦心生犹豫，是还是非，乃至广说。疑即是结，所以名疑结。",
 "嫉结，即对他人的胜事令心不忍，即对他人获得恭敬、供养、财位、多闻及其余胜法而心生嫉妒，这是不忍之义。嫉即是结，所以名嫉结。悭结，即对自己的法与财令心吝惜，谓我所有的不要到他人那里。悭即是结，所以名悭结。结之义即缚之义，如世尊所说：",
 "「不是眼系缚于色，也不是色系缚于眼，此中的欲贪才名为结。」如不是黑牛系缚白牛，也不是白牛系缚黑牛，乃至广说。前所说的结也就是缚，因为结之义即是缚之义之故。然而契经中又说三缚：一、贪缚，即一切贪，如爱结之相所说。二、瞋缚，即一切瞋，如恚结之相所说。",
 "三、痴缚，即一切痴，如无明结之相所说。随眠有七种：一、欲贪随眠；二、瞋随眠；三、有贪随眠；四、慢随眠；五、无明随眠；六、见随眠；七、疑随眠。这七者的个别相状，在结中已说。然而应依界、行相、部的差别，分别这七种随眠：贪着诸欲，所以名欲贪。",
 "此贪即随眠，故名欲贪随眠。这唯是欲界五部为五种，即见苦所断乃至修所断。瞋随眠也唯是欲界五部为五种。有贪随眠唯是色界、无色界各有五部、共为十种，因于内门而转之故。为遮止对静虑、无色起解脱之想，所以说上二界的贪名为有贪。慢随眠通于三界，各有五部、共十五种。",
 "无明随眠也是如此。见随眠通于三界，各有十二、共三十六种：即欲界见苦所断具足五见；见集、见灭所断唯有邪见及见取二种；见道所断唯有邪见、见取、戒禁取三种，总为十二种。上二界也是如此，共为三十六种。疑随眠通于三界，各有四部、共十二种，即见苦、集、灭、道所断。",
 "其中欲贪及瞋随眠，只有部的差别，没有界与行相的差别。有贪、疑、慢、无明随眠，有界与部的差别，没有行相的差别。见随眠兼具界、行相、部的差别。行相有别者，即我、我所，以我行相而转者名有身见。以断、常行相而转者名边执见；无行相而转者名邪见；以胜行相而转者名见取；以净行相而转者名戒禁取。",
 "微细之义是随眠之义，因为它们现起时难以觉知之故。或者随缚之义是随眠之义，即随身心之相而被缚而转，如同空中飞行之影、水中行船之随影。或者随逐之义是随眠之义，如油在麻中、腻在团中。或者随增之义是随眠之义，即对五取蕴由所缘、相应而随增之故。所谓随增，即随所缘及相应之门而增长之故。",
 "如此七种随眠，由界、行相、部的差别，成为九十八种随眠。即欲界见苦所断具足十种随眠，就是有身见、边执见、邪见、见取、戒禁取、疑、贪、瞋、慢、无明。见集所断有七种随眠，于前十种中除去有身见、边执见、戒禁取。",
 "见灭所断有七种随眠，也是如此。见道所断有八种随眠，即前七种再加戒禁取。修所断有四种随眠，即贪、瞋、慢、无明。如此欲界有三十六种随眠。色界有三十一种随眠，即于欲界三十六种中除去五部之瞋；无色界也是如此。所以共有九十八种随眠。",
 "其中八十八种是见所断，十种是修所断。三十三种是遍行，即各界中见苦、见集所断的诸见与疑，以及它们相应的不共无明；其余都不是遍行。十八种是无漏缘，即各界中见灭、见道所断的邪见、疑，以及它们相应的不共无明。这十八种缘于灭、道，所以名为无漏缘，其余都是有漏缘。",
 "此中有漏缘者，由所缘、相应而随增。无漏缘者，只对自聚由相应而随增。九种是无为缘，即界中见灭所断的邪见、疑，以及它们相应的不共无明；缘于灭谛，所以名无为缘，其余都是有為缘。十种随眠次第生起的情形：先由无明对谛不了知，即对苦不欲（不了知）乃至对道不欲。",
 "由不了知之故，其次引生疑，即听闻邪、正二品便怀犹豫：是苦非苦，乃至是道非道。从此犹豫引生邪见，即由恶友以邪闻、邪思而生邪决定：无施与、无爱乐、无祠祀，乃至广说。从此邪见有身见生，即在取蕴中拨无苦之理，便执有我或有我所。",
 "从有身见生边执见，即执我有断、常之边故。从边执见生戒禁取，即认为此边执之戒禁是能清净之故。从戒禁取引生见取，即认为能清净者是最殊胜之故。从此见取其次引生贪，即对自己的见解情生深爱之故。从此贪之后其次引生慢，即对自己的见解深生执着后，恃之而生高举、凌蔑他人之故。",
 "从此慢之后其次引生瞋，即恃着自己的见解、对他人的见解情不能忍而必生憎嫌之故，或在自己的见解取舍之位中生起憎嫌之故。十种随眠的次第如此。由三种因缘生起诸烦恼：一、未断随眠之故；二、非理作意之故；三、境界现前之故。由因、加行、境界三力而烦恼现前，这是就具足者而说。",
 "也有唯依境界力而生起的，烦乱遍恼身心相续，所以名为烦恼。这即是随眠。随烦恼，即诸烦恼也叫随烦恼。又有随烦恼，即其余一切行蕴所摄的染污心所，因为它们与诸烦恼同属一蕴所摄之故。这又是什么呢？即诳、憍、害、恼、恨、谄等，有无量种类，如圣教所说。",
 "诳，即惑乱他人。憍，即对自身所有的色力、族姓、净戒、多闻、巧辩等染著之后，令心傲逸、无所顾忌之性。害，即对他人能作逼迫，由此能行打骂等事。恼，即坚执诸有罪之事，由此不接受如理的谏诲。恨，即对忿所缘之事，数数寻思、结怨不舍。谄，即心曲。",
 "如此六种从烦恼而生。秽污之相粗，名为烦恼垢。在这六种烦恼垢中，诳、憍二种是贪的等流，因为是贪的同类之故。害、恨二种是瞋的等流，因为是瞋的同类之故。恼垢即是见取的等流，因为执着己见为胜者会恼乱自他之故。谄垢即是诸见的等流，因为诸见增多则谄曲之故。",
 "如说谄曲就是诸恶见，可见此垢及缠，并其余染污行蕴所摄诸心所法，都从烦恼而生，所以都名随烦恼。缠有十种，即惛沉、睡眠、掉举、恶作、嫉、悭、无惭、无愧、忿、覆。身心相续无堪任性名为惛沉，是昧重之义；不能任持身心相续，令心昧略，名为睡眠。",
 "这些得缠之名，唯依染污而立。掉举，即令心不寂静。厌恶所作之体，名为恶作；另有别的心所缘恶作而生，立恶作之名，是追悔之义——这是于果体上假立因名，如缘空名空、缘不净名不净。世间也以处而说依处者，如说一切村邑来等。这些立缠之名，也唯依染污。",
 "嫉、悭二者的相状，在结中已说。对诸功德及有德者令心不敬，说名无惭，即是与恭敬敌对的法。对诸罪中不见怖畏，说名无愧。能招恶趣、为善士所诃责的，说名为罪。除去瞋及害，对有情、非情令心愤发，说名为忿。隐藏自己的罪，说名为覆。",
