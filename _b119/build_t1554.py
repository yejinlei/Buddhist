 "四、非想非非想处。趣有五种：一、奈落迦（地狱）；二、傍生；三、鬼界；四、天；五、人。生有四种，即卵、胎、湿、化。地有十一种，即欲界、未至、静虑中间、四静虑、四无色，共为十一地。欲界与有顶一向是有漏，其余九地通于有漏及无漏。",
 "界、趣、生一向是有漏。智有十种，即法智、类智、世俗智、他心智、苦智、集智、灭智、道智、尽智、无生智。对欲界诸行及彼因、彼灭的加行、无间、解脱、胜进道，以及法智地中所有的无漏智，名为法智。无始以来常怀我执，如今初次见法，所以名法智。",
 "对色、无色界诸行及彼因、彼灭的加行、无间、解脱、胜进道，以及类智地中所有的无漏智，名为类智。随法智而生，所以名类智。诸有漏之慧名为世俗智，此智多在瓶、衣等世俗之事上转，所以名世俗智。这有二种：一、染污；二、不染污。染污的又有二种：",
 "一、见性；二、非见性。见性有五种，即有身见、边执见、邪见、见取、戒禁取。非见者，即疑、贪、瞋、慢、无明、忿、害等相应的慧。不染污的也有二种：一、善；二、无覆无记。无覆无记者，非是见，因为不推度之故。",
 "此慧及智，若是善的，与五识俱时，也不是见，是慧及智。若与意识俱时，是世俗正见，也是慧也是智。诸定所生之智能了知他人欲界、色界所系的一分无漏、现在的相似心心所法，名为他心智。这有二种：一、有漏；二、无漏。有漏者，能了知他人欲界、色界所系的心心所法。",
 "无漏者有两种：一、法智品；二、类智品。法智品者，了知法智品的心心所法。类智品者，了知类智品的心心所法。此智不能了知色、无为、心不相应行，以及过去、未来、无色界所系；对一切根地的补特伽罗殊胜的心心所都不能知。对五取蕴的果分有无漏智，以非常、苦、空、非我之行相而转，名苦智。",
 "对五取蕴的因分有无漏智，以因、集、生、缘之行相而转，名集智。对彼苦集之灭有无漏智，以灭、静、妙、离之行相而转，名灭智。对彼之对治、得涅槃之道有无漏智，以道、如、行、出之行相而转，名道智。有无漏智作这样的思惟：苦我已了知、集我已断、灭我已证、道我已修，以尽之行相而转，名尽智。",
 "有无漏智作这样的思惟：苦我已了知、不再更知，乃至道我已修、不再更修，以无生之行相而转，名无生智。这后二智即尽智、无生智，因不推度故非见性。他心智唯是见性，其余六智通于见性与非见性。世俗智唯有漏，他心智通有漏及无漏，其余八智唯是无漏。",
 "灭智唯以无为为缘，他心智、苦智、集智、道智唯有为缘，其余五智通于有为无为缘。苦智、集智唯有漏缘，灭智、道智唯无漏缘，其余六智通有漏无漏缘。法智在六地，即四静虑、未至、中间。类智在九地，即前六地、下三无色。",
 "他心智在四地，即四静虑。世俗智在一切地。其余六智中，法智品者在六地，类智品者在九地。忍有八种，即苦、集、灭、道法智忍，及苦、集、灭、道类智忍。此八种是能引生决定智的殊胜之慧。忍可苦等四圣谛之理，所以名为忍。在诸忍中，此八唯是观察法忍，是见及慧、非智的自性。",
 "决定之义是智之义。此八忍推度之意乐尚未止息，未能审决，所以不名为智。苦法智忍与欲界见苦所断的十种随眠之得俱灭，苦法智与彼断之得俱生。忍是无间道，智是解脱道，对治欲界见苦所断的十种随眠。如有二人，一人在舍内驱贼令出，一人关闭门户不令其再入。",
 "苦类智忍与色、无色界见苦所断的十八种随眠之得俱灭，苦类智与彼断之得俱生，其余如前所说。如此四心，能对三界的苦谛现观；对集、灭、道也各有四心，应知也是如此。这十六心，能对三界四谛现观，断除见所断的八十八种结，获得预流果。",
 "其余修所断的十种随眠，即欲界四种、色无色界各三种，共为十种。欲界的四种譬如束芦，总分为九品，即从上上乃至下下。对治它们的无间道、解脱道也有九品，即下下品之道能对治上上品随眠，乃至上上品之道能对治下下品随眠。六品断尽时获得一来果，九品断尽时获得不还果。",
 "如欲界四种总分为九品，也有九品的无间、解脱能对治之道；色、无色界各有四地，一一地中能治、所治各有九品，应知也是如此。渐次断除那八地的随眠，乃至有顶的下下品断尽时，获得阿罗汉果。四果中间所有的诸道，以及前面的见道，名为四向。",
 "随在彼果之前，即名为彼果之向。如此有八种补特伽罗，即行四向及住四果。如此向、果，由种性的差别分为六种，即钝根、利根种性的异生。若入见道十五心，则名为随信行及随法行。这二种到修道位，即从第十六心乃至金刚喻定，名为信胜解及名见至。",
 "这二种至无学位，即从初尽智乃至最后心，名为时解脱及不时解脱。而言及的心所种类差别有无量种，依心而有所以名为心所法，犹如我所。如此心所名为相应行。不相应行与此相违，即诸得等。得，即是称说有法者之因。",
 "法有三种：一、净；二、不净；三、无记。净即信等，不净即贪等，无记即化心等。若成就此法则名有法者。称说此成就之定因，名为得、获、成就。若没有得，则贪等烦恼现前时有学既无无漏心之故，应不成圣者；异生若起善、无记心时，尔时应名为已离染者。",
 "又诸圣者与诸异生都没有涅槃之得，互相相似之故，应都名为异生、或都名为圣者。然而如法王说：起得、成就十种无学法故名圣者，永断五支，乃至广说。又世尊说：比丘当知，若有成就善、不善法，我见如此诸有情类，心相续中善、不善之得增长无边。",
 "作这样的教说：你们比丘，不应较量有情的胜劣，不应妄取补特伽罗德量的浅深，乃至广说。由此可知法外定有实得。这有二种：一者未得、已失而今获得，二者得已不失名为成就。应知非得与此相违。在何法中有得、非得？在自相续及二灭中有得、非得。",
 "不在他相续，因为没有成就他人身法的缘故。不在非相续，因为没有成就非情法的缘故。也不在虚空，因为没有成就虚空者的缘故。彼虚空没有得之故，也没有非得。得有三种：一者如影随形之得，二者如牛王引前之得，三者如犊子随后之得。第一种得，多数如无覆无记法；第二种得，多数如上地殁而生欲界、结生时欲界善法的得；第三种得，多数如闻思所成慧等，除俱生之外其余的得。",
 "此中应作略毗婆沙：欲界所系的善、不善色，没有前生之得，只有俱生及随后之得；除去眼通、耳通的慧及能变化之心，并除去少分的威仪路、工巧处极数习者；其余一切无覆无记法及有覆无记的得，也应分别。表色唯有俱生得，因势力劣之故没有前后得；",
 "其余诸法一一容有前、后、俱的得。善法之得唯是善，不善法之得唯是不善，无记法之得唯是无记。欲界法之得唯是欲界，色界法之得唯是色界，无色界法之得唯是无色界。无漏法之得通于三界及无漏法。无漏法，即道谛、三种无为，因为它们都不系之故。",
 "道谛之得唯是无漏，非择灭之得通于三界，择灭之得通于色界、无色界。由道力而起的即堕于彼界，由无漏道力而起的就是无漏之故。无漏法之得总说有四种：学法之得唯是学，无学法之得唯是无学，非学非无学法之得有三种。非学非无学法，即诸有漏及无为；有漏及非择灭之得，唯是非学非无学。",
 "择灭之得分为学等：由有学道力而起者唯是学，由无学道力而起者唯是无学，由世间道力而起者唯是非学非无学。见所断法之得唯是见所断，修所断法之得唯是修所断。非所断法之得有三种，即修所断及非所断。非所断法，即道谛及无为。道谛之得唯是非所断，非择灭之得唯是修所断，因不染污、是有漏之故；择灭之得则有多种。",
 "由世间道力而起者唯是修所断，由无漏道力而起者唯是非所断。一切非得都唯是无覆无记性所摄，不像前面得那样有种种差别的意义。然而过去、未来的法一一各有三世的非得，现在法没有现在的非得，因为得与非得的性相违之故。没有现在可成就之法，因为现在法不成就之故。",
 "然而有过去、未来的非得。欲界、色界、无色界及无漏法，一一都有三界的非得。没有非得是无漏的，因为非得中有异生性之故。如说：什么是异生性？就是不获得圣法。不获得就是非得的异名。又诸非得唯是无记性，所以不是无漏。",
 "已离第三静虑之染、未离第四静虑之染，第四静虑地的心心所法灭去，有不相应法名为无想定；虽灭一切心心所法而起此定，因专为除想，所以名无想。如他心智一样，此无想定是善的、第四静虑所摄，唯在非圣者的相续中生起，因起求解脱之想而修此定之故。圣者对此如同对恶趣之想，深心厌离。此定唯是顺定受，即顺次生受。灭定则是加行得、非离染得：即已离无所有处之染，有顶的心心所法灭去，有不相应法能令大种平等相续，所以名为定灭。",
 "这属于有顶地加行善所摄，或是顺次生受、或是顺后次受、或是顺不定受。起此定后，未得异熟便入般涅槃，所以是不定受。此定能感有顶地中的四蕴异熟，因为彼有顶是无色之故。圣者能起，不是诸异生所能起，因为由圣道之力而起此定之故。圣者为得现法乐住而求起此定；异生对此怖畏断灭，因无圣道之力所以不能起。",
 "圣者对此灭定是由加行得、非离染得，唯有佛世尊对此灭定名为离染得。初尽智时已能对此定自在而起，所以名为得。诸佛功德不由加行，随欲便即现起之故。若生在无想有情天中，有法能令心心所灭，名为无想事。这是实有之物，是无想定的异熟果之故，名异熟生，无记性所摄。",
 "即广果天中有一殊胜之处，如中间静虑那样，名为无想天；生时与死时都有心想，中间则无心的缘故，建立无想之名。他们将要死时，如长睡醒来还起心想，起想之后不久便即命终，生于欲界。将要生到那里的人，必定有欲界顺后次受，因为是决定业之故。如将要生到北俱卢洲的人，必定有能感生天之业。",
 "先业所引、六处相续无间断之因，依它而施设四生、五趣，名为命根，也叫寿。所以对法说：什么是命根？即三界的寿。这有实体，能任持暖与识。如偈颂所说：寿、暖以及识，三法舍身时，所舍之身僵仆，如木无思觉。契经也说：",
 "受异熟之后名为那落迦（地狱），乃至非想非非想处应知也是如此。若离开命根便没有别的法，是根性所摄，遍在三界。一期相续无间断之时，才可依它施设四生、五趣。生在无色界，起自上地的善、染污心，或起下地的无漏心时，依什么施设？化生天趣起善、染污心时应名为死，若起无记则又应名为生。",
 "若拨无命根，就有这样大的过失。诸有情类同作事业、同乐欲之因，名为众同分。这又有二种：一、无差别；二、有差别。无差别者，即诸有情都有我爱，同资于食、乐欲相似。此平等之因，名为众同分，一一身内各别有一。有差别者，即诸有情在界、地、趣、生，以及种姓、男女、近事、比丘、学无学等种类上的差别。",
 "一一身内有同事业、乐欲的定因，名为众同分。若无此，则圣者与非圣者等世俗言说应都杂乱。诸异生性与异生同分有何差别？同乐欲等之因，说名彼同分（众同分）。异生性者，能作一切无义利之因。如契经说：比丘当知，我说愚夫、无闻异生，没有少分恶不善业是他们不能造的。",
 "又世尊说：若来人中得人的众同分，异生性在死、生之时有舍、得的含义。所以异生性与众同分是有区别的。诸法生起时有内因之力，令他们获得各自别的功能，即此内因说名为生相。所谓法生之因总有两种：一、内；二、外。内即生相，外即六因或四缘之性。",
 "若无生相，诸有为法应如虚空等，虽具外因缘也没有生起之义。或者虚空等也应有可生之义，而成有为性——这是大过失。由此可知别有生相。能引别果、暂时安住之因，说名住相。即有为法在暂住之时各有势力，能引别果令其暂时安住。",
 "这引别果势力之内的因，说名住相。若无住相，诸有为法在暂住之时，应更不能引于别果。由此可知有别的住相。老，即衰损引果之功能，令其不能重新引生别果。即有为法若无异相衰损其功能，何缘不能重新引别果？已更不再重引，若引而復引则应成无穷。",
 "若如此，又应不成刹那性。由此可知别有异相。无常，即功能损减后，令现在法趣入过去之因。即有别法名为灭相，令法从现在堕入过去世。若无此，法则应不灭，或者虚空等也应有灭之义。这四种是有为法的有为相。若有此四种有为相，便名为有为，而非虚空等。",
 "然而世尊说：有三种有为法的有为相——有为的生起也可了知，灭尽及住、异也可了知，是为令所化众生厌离有为故。如显示黑耳与吉祥俱那样，住、异二相合说为一，所以决定有四种有为相，并非就是所相的有为法体。若就是所相的有为体，则如所相体与能相为一，能相也应展转无异。",
 "若如此，则诸法灭时应生、生时应灭，或者全不生（但事实不然），因为这四种本相是有为之故。如所相之法有四种随相，即名生生乃至灭灭。然而并非无穷，因为四种本相各能相八法，而随相只能各相一法之故。即法生起时，连同其自体九法俱起：自体为一，相与随相为八；本相中的生，除去其自体而同时生其余八法。",
 "随相中的生，于九法之内只生本生，因势力劣之故。住、异、灭相应知也是如此。本相依于法，随相依于随相。法因相之故而得有作因，相因随相之故而得有作用。作用是什么呢？即生、住、异、灭。所生等者，即引果之功能。所以有为法，体虽恒有而用非常。",
 "凭借这四相、内外因力，作用得以成立。名身、句身、文身等，即依语而生，如同智带义之影像而现。能诠释自义的名、句、文，即是想、章、字的不同名称。如眼识等依眼等而生，带色等义之影像而现，能了别自境；名等也是如此。并非语言本身亲能诠释义，若语言亲能诠义，则说火时便应烧口；要依语之故，火等名才生起，由火等名来诠释火等之义。",
 "诠释，即能对所显之义生起他人的觉慧，并非与义相合，因为声有质碍之故。诸记论师所执着的常声，其理不成之故。不应离开这名、句、文三者，而执别有法能诠释于义。然而四种法似同一相：一、声；二、名；三、义；四、智。此中的名，即色等之想。句，即能究竟诠释义者，如说诸恶莫作等颂，世间也说提婆达多驱白牛来、挤取牛乳等。",
 "文，即是𧙃、壹等字。这三者各别，合集同类而说之为身。如大仙说：比丘当知，如来出世便有名身、句身、文身可了知——这是说谛实、蕴、处、界、沙门果、缘起等法的名句文身。又世尊说：如来获得彼彼名句文身——这是说如来获得彼彼不共佛法的名句文身。",
 "此中的等，即义类的差别。诸行句义，至此应知。识句义，即总相了别色等境事，所以名为识。即在色等六种境中，由眼等根伴助而起现在作用，唯总相分别色等境事，说名为识。若能分别差别之相，即名受等诸心所法，识没有那种作用，只作所依。",
 "识的作用只是在现在世有一刹那顷能有了别。这也名为意，也名为心。也是施设有情的本事，以色等境为了别之用。由根、境的差别说有六种，即名眼识乃至意识。佛在经中自己宣说其相：因能了别故建立识之名。由此可知以了别为相。",
 "前于思择有为相中，说法生之因总有两种：一、内；二、外。内即生相，外即六因或四缘之性。如今应思择：因、缘是什么？因有六种：一、相应因；二、俱有因；三、同类因；四、遍行因；五、异熟因；六、能作因。",
