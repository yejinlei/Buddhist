 "觉则不动。动就有苦，因为果不离因。二是能见相。因为依于动所以能见；不动就没有见。三是境界相。因为依于能见所以境界妄现；离见就没有境界。因为有了境界之缘，又生起六种相。哪六种？一是智相。依于境界，心中生起分别爱与不爱。",
 "二是相续相。依于智而生起苦乐，觉心起念相应不断。三是执取相。依于相续而缘念境界，住持苦乐，心中生起执著。四是计名字相。依于妄执，分别假名言相。五是起业相。依于名字，寻名取著，造种种业。",
 "六是业系苦相。因为依业受果而不自在。应当知道无明能生一切染法，因为一切染法都是不觉之相。其次，觉与不觉有两种相。哪两种？一是同相，二是异相。同相，譬如种种瓦器都同是微尘的性相；同样，无漏与无明的种种业幻都同是真如的性相。",
 "所以经中依于此真如之义，说一切众生本来常住、入于涅槃，菩提之法非可修之相、非可作之相，毕竟无所得，也没有色相可见；而有见色相的，只是随染业幻所变作，不是智色不空之性，因为智相无可见。异相，如种种瓦器各各不同；同样，无漏与无明随染幻而有差别，因为其性有染幻的差别。",
 "其次，生灭因缘，就是众生依于心，意与意识得以转起。这是什么意思？因为依于阿梨耶识而说不觉：无明不觉而起，能见、能现、能取境界，起念相续，所以说为意。此意又有五种名称。哪五种？一是名为业识，即无明之力令不觉之心妄动。",
 "二是名为转识，依于动心而能见相。三是名为现识，即能显现一切境界，犹如明镜显现色像；现识也是这样，随其五尘对至即现，没有前后，因为一切时都任运而起、常现在前。四是名为智识，即分别染法与净法。",
 "五是名为相续识，因为与念相应不断，能住持过去无量世等的善恶之业令不散失，又能成熟现在未来的苦乐等果报而无差违，能令现在已经过去之事忽然念起，未来之事不觉妄想思虑。所以三界虚妄，唯心所作，离心就没有六尘境界。",
 "这是什么意思？因为一切法都从心生妄念而生，一切分别即是分别自心，而心不见心、无相可得。应当知道世间一切境界，都依众生无明妄心而得住持；所以一切法如镜中像，无体可得，唯是心之虚妄。因为心生则种种法生，心灭则种种法灭。",
 "其次，所说的意识，就是此相续识，依于凡夫取著转深、计执我与我所，种种妄执随事攀缘，分别六尘，名为意识，也叫分离识。又叫分别事识，因为此识依于见、爱烦恼而增长。依无明熏习所起的识，不是凡夫所能知，也不是二乘智慧所能觉。",
 "就是说，依于菩萨，从初起正信发心观察，若证法身则得少分知，乃至菩萨究竟地也不能知尽，唯有佛能穷尽了知。为什么呢？此心从本以来自性清净而有无明，为无明所染，有其染心。虽有染心却常恒不变，所以此义唯佛能知。即心性常无念所以名为不变，因不通达一法界故而心不相应，忽然念起名为无明。",
 "染心有六种。哪六种？一是执相应染，依二乘解脱及信相应地而远离。二是不断相应染，依信相应地修学方便渐渐能舍，得净心地时究竟远离。三是分别智相应染，依具戒地渐离，乃至无相方便地时究竟远离。",
 "四是现色不相应染，依色自在地能离。五是能见心不相应染，依心自在地能离。六是根本业不相应染，依菩萨尽地、得入如来地时能离。不通达一法界之义，从信相应地观察学断，入净心地时随分得离，乃至如来地时能究竟远离。",
 "所说的相应义，就是心与念法有别，依于染净差别，而了知相与所缘相相同。不相应义，就是即心不觉、常无别异，不同于了知相与所缘相。又，染心之义名为烦恼碍，能障蔽真如根本智。无明之义名为智碍，能障蔽世间自然业智。",
 "这是什么意思？因为依于染心能见、能现、妄取境界，违背平等之性。因为一切法常静、没有起相，无明不觉妄与法相违；不能随顺世间一切境界的种种智。其次，分别生灭相有两种。哪两种？一是粗，与心相应。",
 "二是细，与心不相应。又，粗中之粗是凡夫境界；粗中之细及细中之粗是菩萨境界；细中之细是佛境界。这两种生灭，依于无明熏习而有，即依因、依缘。依因，是不觉之义；依缘，是妄作境界之义。",
 "若因灭则缘灭，因灭所以不相应心灭，缘灭所以相应心灭。问：若心灭了，怎么相续？若相续，怎么说究竟灭？答：所说的灭，只是心相灭，不是心体灭。如风依于水而有动相。若水灭了，那么风相就断绝、无所依止。",
 "因为水不灭，所以风相相续；唯风灭所以动相随灭，不是水灭。无明也是这样，依于心体而动，若心体灭了，则众生断绝、无所依止。因为体不灭，所以心得相续；唯痴灭所以心相随灭，不是心智灭。其次，有四种法的熏习义，所以染法与净法生起而不断绝。",
 "哪四种？一是净法，名为真如。二是一切染因，名为无明。三是妄心，名为业识。四是妄境界，即六尘。熏习之义，如世间的衣服本来没有香气，若人以香熏习，便有香气。这里也是这样：真如净法本来没有染，只因无明熏习，便有染相。",
 "无明染法本来没有净业，只因真如熏习，便有净用。熏习怎样生起染法而不断？就是说：因依于真如法而有无明，因有无明染法之因就熏习真如；因熏习而有妄心，因有妄心就熏习无明。因不通达真如法，不觉念起，现出妄境界。",
 "因有妄境界染法之缘，就熏习妄心，令其念著、造种种业，受一切身心等苦。此妄境界的熏习义有两种。哪两种？一是增长念熏习，二是增长取熏习。妄心的熏习义有两种。哪两种？一是业识根本熏习，能受阿罗汉、辟支佛、一切菩萨的生灭苦。",
 "二是增长分别事识熏习，能受凡夫的业系苦。无明的熏习义有两种。哪两种？一是根本熏习，因为能成就业识之义。二是所起见爱熏习，因为能成就分别事识之义。熏习怎样生起净法而不断？就是说：因有真如法所以能熏习无明，因熏习因缘之力，就令妄心厌离生死苦、乐于求涅槃。",
 "以这妄心有厌、求的因缘，就熏习真如。自信己之本性，了知心妄动而没有现前境界，修远离之法；因为如实了知没有现前境界，以种种方便起随顺之行，不取不念，乃至因久远熏习之力，无明就灭。因无明灭所以心没有起，因无起所以境界随灭，因因缘俱灭所以心相都尽，名为得涅槃、成自然业。",
 "妄心的熏习义有两种。哪两种？一是分别事识熏习，依于凡夫、二乘人等，厌离生死苦，随力所及，渐次趣向无上道。二是意熏习，即诸菩萨发心勇猛、快速趣向涅槃。真如的熏习义有两种。哪两种？一是自体相熏习，二是用熏习。",
 "自体相熏习，是从无始世以来，具足无漏法，备有不思议业，作境界之性。依此二义恒常熏习，因为有力量，能令众生厌离生死苦、乐于求涅槃，自信己身有真如法，发心修行。问：若是这样的义理，一切众生都有真如，都同等熏习，为什么有信、不信，有无量的前后差别？",
 "都应当一时自知有真如法、勤修方便、同入涅槃。答：真如本来是一，却有无量无边无明，因为从本以来自性厚薄不同。超过恒河沙数的上烦恼依无明而起差别，我见、爱染烦恼依无明而起差别。如是这一切烦恼，都依于无明而起，前后有无量差别，唯有如来能知。",
 "又，诸佛之法有因有缘，因缘具足才得成办。如木中的火性是火的正是正因，但若无人知晓，不借助方便而能自己烧木，那是没有的事。众生也是这样，虽有正因熏习之力，若不值遇诸佛菩萨善知识等以此为缘，而能自己断烦恼、入涅槃的，那是没有的事。",
 "若虽有外缘之力，而内心净法没有熏习之力，也不能究竟厌离生死苦、乐于求涅槃。若因缘具足，即自有熏习之力，又为诸佛菩萨等慈悲愿力所护，就能生起厌苦之心，信有涅槃，修习善根。因修善根成熟，就值遇诸佛菩萨示教利喜，才能进趣，趣向涅槃之道。",
 "用熏习，就是众生外缘之力。这样的外缘有无量义，略说两种。哪两种？一是差别缘，二是平等缘。差别缘，是此人依于诸佛菩萨等，从初发意求道之时乃至得佛，其间或见或念，或作眷属父母诸亲，或作给使，或作知友，或作怨家，或起四摄，乃至一切所作无量行缘，以生起大悲熏习之力，能令众生增长善根，令其若见若闻而得利益。",
 "此缘有两种。哪两种？一是近缘，速得度脱。二是远缘，久远得度。这近、远二缘，分别又有两种。哪两种？一是增长行缘，二是受道缘。平等缘，是一切诸佛菩萨都愿度脱一切众生，自然熏习、恒常不舍。",
 "因为同体智力，随应见闻而现作业。即众生依于三昧，才得平等见诸佛。此体、用熏习，分别又有两种。哪两种？一是未相应，即凡夫、二乘、初发意菩萨等，以意、意识熏习，依信力而能修行。",
 "因为未得无分别心与体相应，未得自在业修行与用相应。二是已相应，即法身菩萨得无分别心，与诸佛智用相应，唯依法力自然修行，熏习真如，灭除无明。其次，染法从无始以来熏习不断，乃至得佛之后则有断。",
 "净法熏习则没有断，尽于未来。这是什么意思？因为真如法常熏习，所以妄心就灭、法身显现，起用熏习，所以没有断。其次，真如自体相，一切凡夫、声闻、缘觉、菩萨、诸佛都无有增减，不是前际生、不是后际灭，毕竟常恒。",
 "从本以来，性自满足一切功德。即自体有大智慧光明义、遍照法界义、真实识知义、自性清净心义、常乐我净义、清凉不变自在义。具足如是通过恒河沙数的不离、不断、不异、不思议佛法，乃至满足无有所少之义，名为如来藏，也叫如来法身。",
 "问：上面说真如之体平等、离一切相，为什么又说其体有这样种种功德？答：虽确实有这些功德之义，却没有差别之相，等同味、唯一真如。这是什么意思？因为无分别、离分别之相，所以无二。那又以什么意义说得有差别呢？",
 "是依于业识，以生灭相来显示。怎么显示？因为一切法本来唯心，实在没有念，而有妄心，不觉起念、见诸境界，所以说为无明。心性不起，就是大智慧光明之义。若心起见，就有不见之相。心性离见，就是遍照法界之义。若心有动，就不是真实识知，没有自性，非常、非乐、非我、非净，热恼衰变就不自在，乃至具有超过恒河沙数的妄染之义。",
 "相对于此义，心性无动就有超过恒河沙数的诸净功德相义示现。若心有起，更见前法可念，就有所缺少。如是净法的无量功德，即是一心，更无所念，所以满足。名为法身如来之藏。其次，真如之用，就是诸佛如来本在因地发大慈悲，修诸波罗蜜，摄化众生。",
 "立大誓愿，尽欲度脱等众生界。也不限劫数、尽于未来，因为取一切众生如己身，而又不取众生相。这是什么意义？即如实了知一切众生以及己身真如平等、无有别异；因有如是大方便智，除灭无明、见本法身，自然有不思议业的种种之用，即与真如相等、遍一切处，也没有用相可得。",
 "为什么呢？因为诸佛如来只是法身智相之身，第一义谛没有世谛境界，离于施作，只是随众生见闻得益所以说为用。此用有两种。哪两种？一是依分别事识，凡夫、二乘心所见的，名为应身。因为不知是转识所现，所以见其从外来，执取色之分齐而不能尽知。",
 "二是依于业识，即诸菩萨从初发意乃至菩萨究竟地心中所见的，名为报身。身有无量色，色有无量相，相有无量好，所住的依报也有无量种种庄严随所示现，即无有边、不可穷尽、离于分齐之相，随其所应，常能住持、不毁不失。",
 "如是功德，都因诸波罗蜜等无漏行熏以及不思议熏所成就，具足无量乐相，所以说为报身。又凡夫所见的，是其粗色，随于六道各见不同，种种异类、不是受乐之相，所以说为应身。其次，初发意菩萨等所见的，因为深信真如法，所以少分而见，知那色相庄严等事无来无去、离于分齐，唯依心现、不离真如。",
 "然而此菩萨仍有分别，因为未入法身之位。若得净心，所见微妙，其用转胜，乃至菩萨地尽时见之究竟。若离业识则没有见相，因为诸佛法身没有彼此色相迭相见。问：若诸佛法身离于色相，怎么能现色相？",
 "答：即此法身是色之体，所以能现于色。即从本以来色心不二，因为色性即智，所以色体无形，说名智身；因为智性即色，所以说名法身遍一切处。所现之色没有分齐，随心能示十方世界，无量菩萨、无量报身、无量庄严各各差别，都无分齐而互不相妨。",
 "这不是心识分别所能知，因为是真如自在用之义。其次，显示从生灭门即入真如门。即推求五阴的色与心、六尘境界，毕竟无念，因为心无形相，十方推求终究不可得。如人迷路，以东方为西方，而方位其实不转。众生也是这样，因无明迷惑而以心为念，而心其实不动。",
 "若能观察了知心无念，就得随顺入真如门。对治邪执者，一切邪执都依于我见，若离于我则没有邪执。此我见有两种。哪两种？一是人我见，二是法我见。人我见，依于凡夫说有五种。哪五种？一是闻经中说如来法身毕竟寂寞犹如虚空，因不知这是为破执著而说，就以为虚空是如来之性。",
 "怎样对治？说明虚空相是虚妄之法、体无、不实，因为对色才有，是可见之相，令心生灭。因为一切色法本来是心，实在没有外色。若无色，就没有虚空之相。即一切境界都因唯心妄起而有，若心离于妄动，则一切境界灭，唯一真心无所不遍。",
 "这就叫如来广大性智究竟之义，不是像虚空相那样。二是闻经中说世间诸法毕竟体空，乃至涅槃、真如之法也毕竟空，从本以来自空、离一切相。因不知这是为破执著而说，就以为真如、涅槃之性唯是其空。怎样对治？说明真如法身自体不空，具足无量性功德。",
 "三是闻经中说如来之藏无有增减，体备一切功德之法。因不解其义，就以为如来之藏有色心法的自相差别。怎样对治？因为这是唯依真如之义而说，是因生灭染义而示现说差别的。四是闻经中说一切世间的生死染法都依如来藏而有，一切诸法不离真如。",
 "因不解其义，就以为如来藏自体具有一切世间的生死等法。怎样对治？因为如来藏从本以来唯有超过恒河沙数的诸净功德，是不离、不断、不异真如之义。因为超过恒河沙数的烦恼染法，唯是妄有，其性本来是无，从无始世以来未曾与如来藏相应。",
 "若如来藏体中实有妄法，而能使证会者永息妄，那是没有的事。五是闻经中说依如来藏所以有生死，依如来藏所以得涅槃。因不解其义，就以为众生有开始。因见到有始，又以为如来所证得的涅槃有其终尽，还会再作众生。怎样对治？",
 "因为如来藏无前际，所以无明之相也没有开始。若说三界之外更有众生开始生起，那就是外道经说。又如来藏没有后际，诸佛所得的涅槃与之相应也就没有后际。法我见，是依于二乘钝根，如来只为他们说人无我。因为所说并不究竟，他们见有五阴生灭之法，怖畏生死、妄取涅槃。",
