 "其中委悉，如彼广说。今作四句，略显其相：一者有法一向有漏，即诸染污心心所法等，由相应义是有漏故，而没有五种无漏相。二者有法一向无漏，即见道时心心所法等，由有自性解脱义故，而没有五种有漏相。",
 "三者有法亦有漏亦无漏，即报无记心心所法等，随眠所缚故、诸缠所离故，虽也是无漏而是苦谛，由业烦恼所生起故。四者有法非有漏，即甚深法不堕于数故。其次别明中也有二门：一有分际门、二无障碍门。有分际门者，若就诸佛所居净土，于四句中唯有二句。",
 "依有色有心门，即一向是无漏，自性相续解脱义故、远离五种有漏相。若就非色非心门，即非有漏也非无漏，非有非无故、离相离性故。若就菩萨，也有二句，恰论二智，所显净土一向无漏，道谛所摄。",
 "如《摄论》说：菩萨及如来唯识智，无相无功用，所以说清净。离一切障，无有退失，所以说自在。此唯识智，为净土体故，不以苦谛为体。乃至广说。若就本识所变之门，也是无漏，因为不是三界有漏所起，乐无漏界，所以是无漏。",
 "无明住地为缘而出，名果报土，所以是有漏。虽也是无漏而是世间，所以在无作四谛门内，为苦谛果报所摄。如经说三贤十圣住果报故。《宝性论》说：依无漏界中，有三种意生身，应知彼因无漏善根所作，名为世间。",
 "因为离有漏诸业烦恼所作世间法，也叫涅槃。依此义故，《胜鬘经》说：世尊！有有为世间、有无为世间，有有为涅槃、有无为涅槃。所以此中说意生身，乃是梨耶所变正报。正报既然如此，依报也这样，同是本识所变作。",
 "然而此梨耶所变之土，以及二智所现净土，虽为苦、道二谛所摄，而没有别体，随义不同而摄罢了。如他分别所持的秽土，得清净者就见为净，净秽虽异而没有别体。当知此中二义也是这样。这是约有分际门说。其次就无障碍门说者，应作四句：",
 "一者诸佛身土都是有漏，因为不离一切诸漏。如经说：诸佛安住三毒四漏等一切烦恼中，得阿耨菩提，乃至广说。二者凡夫身土都是无漏，因为离一切诸漏性。如经说：色无漏无系，受想行识无漏无系，乃至广说。",
 "三者一切凡圣秽土净土也是有漏也是无漏，因为前二门不相离。四者一切凡圣秽土净土非有漏非无漏，因为无缚性及脱性。如经说：色无缚无脱，受想行识无缚无脱，乃至广说。这是第四有漏无漏门。",
 "上来四门合为第一净土果毕。其次第二明净土因者，净土之因，有其二途：一成辨因、二往生因。成辨因者，说者不同。或有说者：本来无漏法尔种子，三无数劫修令增广，为此净土变现生因。如《瑜伽论》说：生那落迦，三无漏根种子成就。",
 "以此推知，也有无漏净土种子。或有说者：二智所熏的新生种子，为彼净土而作生因。如《摄论》说：从出出世善法功能生起净土。什么是出出世善法？无分别智、无分别后得所生的善根，为出出世善法。",
 "是本有的，就不是所生；既是所生，当知是新成。问：如是二说，哪个为实？答：都依圣典，有什么不实。其中委悉，如《楞伽经料简》中说。其次明往生因者，凡诸所说的往生之因，不只能感正报庄严，也得感具依报净土，只是承如来本愿力故，随感受用。",
 "不是自业因力所成辨，所以说无往生因。此因之相，经论不同。若依《观经》，说十六观；《往生论》中，说五门行。今依此经，说三辈因。上辈之因，说有五句：一者舍家弃欲而作沙门，此显发起正因方便。",
 "二者发菩提心，是明正因。三者专念彼佛，是明修观。四者作诸功德，是明起行。此观及行为助满业。五者愿生彼国，此一是愿、前四是行，行愿和合才得生故。中辈之中说有四句：一者虽不能作沙门，当发无上菩提之心。",
 "是明正因。二者专念彼佛、三者多少修善，此观及行为助满业。四者愿生彼国。前行此愿，和合为因。下辈之内说二种人，二人之中各有三句。初人三者：一者假使不能作诸功德，当发无上菩提之心。",
 "是明正因。二者乃至十念，专念彼佛，是助满业。三者愿生彼国。此愿、前行和合为因，是明不定性人。第二人中有三句者：一者闻甚深法，欢喜信乐，此句兼显发心正因，只为有别于前人，举其深信罢了。",
 "二者乃至一念念于彼佛，是助满业，为显前人没有深信故，必须十念；此人有深信故，未必具足十念。三者以至诚心，愿生彼国。此愿、前行和合为因，此就菩萨种性人说。经说如是，今此文略辨其生相。",
 "其中有二：先明正因、后显助因。经所说的正因，即菩提心。说发无上菩提心的，不顾世间富乐以及二乘涅槃，一向志愿三身菩提，这名叫无上菩提之心。总标虽然如此，其中有二：一者随事发心、二者顺理发心。",
 "说随事者，烦恼无数，愿都断之；善法无量，愿都修之；众生无边，愿都度之。于此三事，决定期愿。初是如来断德正因、次是如来智德正因、第三心是恩德正因，三德合为无上菩提之果，即此三心，总为无上菩提之因。",
 "因果虽异，广长之量齐等，等无所遗，无不包故。如经说：发心毕竟二无别。如是二心，前心难，自未得度先度他，是故我礼初发心。此心果报虽是菩提，而其华报在于净土。所以如此，菩提心量，广大无边、长远无限，故能感得广大无际依报净土、长远无量正报寿命。",
 "除菩提心，无能当彼，所以说此心为彼正因。这是明随事发心之相。所说的顺理而发心，信解诸法皆如幻梦，非有非无、离言绝虑。依此信解发广大心，虽不见有烦恼善法，而不拨无可以断可以修，所以虽愿都断都修，而不违于无愿三昧，虽愿皆度无量有情，而不存能度所度，故能顺随于空无相。",
 "如经说：如是灭度无量众生，实无众生得灭度者，乃至广说。如是发心，不可思议，这是明顺理发心之相。随事发心，有可退义，不定性人也得能发。顺理发心，即无退转，菩萨性人才得能发。如是发心，功德无边，假使诸佛穷劫演说彼诸功德，也不能尽。",
 "正因之相略说如是。其次明助因。助因多种，今且明其下辈十念。此经中说下辈十念，一言之内含二义，即显了义及隐密义。隐密义者，望第三对纯净土果而说下辈十念功德。此如《弥勒发问经》说：尔时弥勒菩萨白佛言：",
 "如佛所说阿弥陀佛功德利益，若能十念相续不断念彼佛者，即得往生。应当怎样念？佛说：不是凡夫念、不是不善念、不是杂结使念。具足如是念，即得往生安养国土。凡有十念。何等为十？一者于一切众生常生慈心，于一切众生不毁其行。",
 "若毁其行，终不往生。二者于一切众生深起悲心，除残害意。三者发护法心，不惜身命，于一切法不生诽谤。四者于忍辱中生决定心。五者深心清净，不染利养。六者发一切种智心，日日常念，无有废忘。",
 "七者于一切众生起尊重心，除我慢意，谦下言说。八者于世谈话，不生味著心。九者近于觉意，深起种种善根因缘，远离愦闹散乱之心。十者正念观佛，除去诸根。释：如是十念，既非凡夫，当知初地以上菩萨才能具足十念，于纯净土为下辈因。",
 "这是隐密义的十念。说显了义十念相者，望第四对净土而说。如《观经》说：下品下生者，或有众生，作不善业、五逆十恶，具诸不善。临命终时，遇善知识，为说妙法，教令念佛，若不能念的，应称无量寿佛。",
 "如是至心，令声不绝，具足十念，称南无佛。称佛名故，于念念中除八十亿劫生死之罪。命终之后，即得往生，乃至广说。以何等心名为至心？什么叫十念相续？什公说：譬如有人在旷野中遇值恶贼，挥戈拔剑直来欲杀。",
 "其人勤走，看要渡过一河。若不渡河，首领难全。那时只念渡河的方便。我到了河岸，是穿衣服渡、还是脱衣服渡？若穿衣渡，怕过不去。若脱衣渡，怕来不及。只有此念，更无他意，当念渡河，就是一念。此等十念，不杂余念。",
 "行者也是这样，或念佛名、或念佛相等，无间念佛乃至十念，如是至心，名为十念。这是显了十念相。今此两卷经说十念，具此隐密、显了二义。然而其中，显了十念与《观经》意稍有不同。那《观经》中不除五逆，只除诽谤方等之罪。",
 "今此两卷经中说：除其五逆、诽谤正法。如此相违，怎样会通？彼经说其虽作五逆，依大乘教得忏悔的；此经中说不忏悔的。由此义故，不相违。因缘之相略说如是。上来所说因果二门，合为第二简宗体毕。",
 "第三约人分别。其中有二：初约三聚众生分别、后就四疑众生分别。初三聚者，如下经说：其有众生，生彼国者，都住于正定之聚。为什么？彼佛土中，没有诸邪聚及不定聚。如是三聚，其相如何？此义详如《宝性论》说。",
 "彼说：略说一切众生界中，有三种众生。何等为三？一者求有、二者远离求有、三者不求彼二。求有有二种：一者谤解脱道、无涅槃性，常求住世间，不求证涅槃。二者于佛法中，阐提同位，谤大乘故。所以《不增不减经》说：若有比丘乃至优婆夷，若起一见、若起二见，诸佛如来非彼世尊，如是等人非我弟子。",
 "远离求有者也有二种：一者无求道方便、二者有求道方便。无方便者也有二种：一者多种外道，种种邪计；二者于佛法中同外道行，虽信佛法而颠倒取，如犊子等，乃至广说。有方便者也有二种，即所谓二乘。",
 "不求彼二者，即所谓第一利根众生、诸菩萨等。又彼求有众生一阐提人，及佛法中同一阐提位，名为邪定聚众生。又远离求有众生中，堕于无方便求道众生，名为不定聚众生。声闻、辟支佛及不求彼二，名为正定聚众生。",
 "论说如是。此中总判二乘菩萨为正定聚，而未分别位地分齐。齐何等位入正定聚？依何等义名正定聚？决定不退堕断善根，如是名为正定聚义。论其位而依《瑜伽》说，正定聚有二种：一者本性正定聚、二者习成正定聚。",
 "若依此而说，五种种性中菩萨种性人，从无始时来不作五逆及断善根，名为本性正定聚。其二乘性及不定性，得作五逆及断善根。断善根时堕邪定聚，善根相续后未趣入，为不定聚。已趣入时，就应分别三品：",
 "若其本来下品善根而趣入的，乃至燸法犹为不定，入顶法位才为正定。论说顶不断善根故。若其本来中品善根而趣入的，至燸法时名为正定。若其本来上品善根而趣入的，才趣入时便作正定。如《瑜伽》说：若有安住下品善根而趣入的，当知下品，名有间隙，未能无间、未善清净。",
 "若有安住中品善根而趣入的，当知中品。若有安住上品善根而趣入的，当知上品，名无间隙，已能无间、已善清净。如是是已趣入之相。又彼论说：依此下品顺解脱分善根，婆伽梵说：若具世间上品正见，虽历千生，不堕恶道。",
 "此文正明本来安住上品善根而趣入的，才入下品顺解脱分善之时便得不退，因为无间隙故。又彼论说：若时安住下成熟者，犹往恶趣。若中若上，不往恶趣。此文正明本来安住下品善根而趣入的，虽至燸法下成熟位，未得不退，故往恶趣。",
 "这是约二乘位地分别。若是不定种性人，直向大乘而趣入时，至种性位才为正定。如《起信论》说：依何等人、修何等行，得信成就，堪能发心？所谓依不定聚众生，有熏习善根力故，信业果报，能起十善，厌生死苦，欲求无上菩提，得值遇佛，亲承供养，修行信心。",
 "经一万劫，信心成就故，诸佛菩萨教令发心；或因大悲故，能自发心；或因正法欲灭，以护法因缘，能自发心。如是信心成就。得发心的，入正定聚，毕竟不退，名住如来种中，正因相应。此言名住如来种的，名已入习种性位，即是十解初发心住。",
 "上来所说，都明习成的正定聚。若其本来菩萨种性，直向大乘而趣入的，才趣入时永得不退，不由业力堕于恶趣。依此而言，入十信位便得不退，不同于前说的不定性人。如是等说，都就秽土。若就得生彼净土的，决定性二乘即不往生，不定性中三品之人，发大乘心的都得生彼，生彼之时即入正定，由外缘力所住持故。",
 "三聚分别略义如是。其次明有四疑惑众生。其中先明所疑境界，然后显其疑惑之相。所疑境者，如下文说：若有众生以疑惑心，修诸功德，愿生彼国。不了佛智，不思议智、不可称智、大乘广智、无等无伦最上胜智，于此诸智疑惑不信，然而还信罪福，修习善本，愿生彼国。",
 "此诸众生，生彼宫殿，五百岁中，不闻三宝，所以说边地，乃至广说。此言佛智，是总标句，下的四句，别显四智。不思议智者，是成所作智，此智能作不思议事，即如不过丈六之身而无能见其顶者，不增毛孔之量而遍十方世界，一念称名永灭多劫重罪，十念念德能生界外胜报。",
 "如是等事，不是下智所测，所以名为不思议智。不可称智者，是妙观察智，此智观察不可称之境，即一切法皆如幻梦，非有非无、离言绝虑，不是随逐言语者所能称量，所以名为不可称智。大乘广智者，是平等性智，此智广度，不向小乘，即游于无我故无不我，无不我故无不等摄。",
 "以此同体智力，普载无边有情，都令同至无上菩提，所以名为大乘广智。无等无伦最上胜智者，正是如来大圆镜智，方才转本识、归于心原，一切种境无不圆照，所以名为大圆镜智。此一智中有五殊胜，如解脱身二乘同得；",
 "如是镜智，正是法身，不是彼所共，所以名无等。这是第一胜。如前三智，菩萨渐得；大圆镜智，唯佛顿证，更没有余类，所以名无伦。这是第二胜。过于不思议智为最、逾于不可称智为上、宽于大乘广智为胜，这是第三、四、五胜。",
 "所以名为无等无伦最上胜智。这是显四疑所迷之境。其次明四种疑惑之相，即如有一类性非质直、邪聪我慢、薄道心之人，不了四智而起四疑：一者疑成所作智所作之事，即闻经说十念念佛得生彼国，由不了故，生疑而说：",
 "如佛经说善恶业道，罪福无朽，重者先牵，理数无差。怎么一生无恶不造，只以十念就能灭诸罪，便得生彼、入正定聚，永离三途、毕竟不退呢？又无始来起诸烦恼，系属三界而相缠缚。怎么不断二轮烦恼，只以十念就能出三界呢？",
 "为治如是邪思惟疑，所以说名不思议智，欲显佛智有大势力故，能以近为远、以远为近，以重为轻、以轻为重，虽实有此事而不是思量之境，所以只应仰信。经说：不可以自浅识思惟。若欲生信，应以事比况。譬如千年积薪，其高百里。",
 "豆许大的火烧，一日都尽。能说千年积薪，如何一日烧尽呢？又如跛者，自力勤行，要经多日才到一由旬。若寄托他船，借着风帆之势，一日之间能到千里。能说跛者之身，怎么一日到千里呢？世间船师之身，尚且能作如是绝虑之事。",
 "何况如来法王之势，而不能作不思议事呢？这是对治第一疑。第二疑者，是疑妙观察智所观之境。如经中叹佛智说：妙观察诸法非有非无，远离二边而不著中。由不了故，生疑而说：如今现见称物之时，物重就低、物轻必举。",
 "若说轻而不举、重而不低，如是说者是有言无义。因缘生法，当知也是这样。若实非无，便堕于有；如其非有，即当于无。若说非无而不得有、非有而不堕无，就同重而不低、轻而不举。故知此说是有言无实。如是称量，即堕诸边。",
