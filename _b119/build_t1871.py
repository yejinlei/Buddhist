 "如〈性起品〉，十方各有八十不可说百千亿那由他世界微尘数如来，同名普贤，现身赞叹述说，十方也这样，都说：我等诸佛为未来菩萨之故，护持此经，令久住世。第七会末，也尽十方诸佛现身前赞叹证述，同前解释所说。",
 "当知现今此经住世，都是佛力。二、常随众，如普贤等十佛世界微尘数等大菩萨众，因为是卢舍那的内眷属，所以动止常相随，周遍一切微尘道处，于华藏界助成能化、显一乘法；如舍利弗等千二百五十比丘与释迦佛也常相随，于娑婆界助佛扬化、说三乘等法。",
 "三、严会众，如诸神王、天王等众，有三十多类，一一类众各超过世界微尘数等，都是道力随缘、殊形异现，俯同世间显现随类生身，就是众生世间之身，庄严卢舍那佛的大众法会。其他宗派视为化现，为使净土显示不空。",
 "而此中是实，因为是海印三昧所现、能问能显示大法海的缘故。四、供养众，如第五会，庄严师子座，有百万亿菩萨在前立侍，又有百万亿梵王围绕，这样彼处有五十八众，一一各有百万亿数，或说无量阿僧祇等。",
 "其余各会依此类推。此等都是舍那佛所常供养的众。五、奇特众，如佛高台楼观、师子之座的诸庄严内，一一各出一佛世界尘数菩萨，即海慧等，此为如来依报所摄，以表依正无碍、人法无二。又如佛眉间出胜音等佛世界尘数菩萨，以表因果无碍，又表从证起教。",
 "六、影响众，如〈舍那品〉中，十方各十亿佛土微尘数等大菩萨来，一一各带一佛世界尘数菩萨以为眷属，一一菩萨各兴一佛世界微尘数等妙庄严云，都弥覆充满虚空，随所来方结跏趺坐。次第坐已，一切毛孔各出十佛世界微尘数等一切妙宝净光明云。",
 "一一光中，各出十佛世界尘数菩萨一切法界方便海，充满一切微尘道。一一尘中，有十佛世界尘数佛刹。一一刹中，三世诸佛都显现，念念中于一一世界各化一佛刹尘数众生。又如〈法界品〉中，十方也各尘数菩萨都来云集；且如上方大菩萨众，一切相好、一切毛孔、一切支节、一切身分、一切庄严具、一切衣服中，出卢舍那等过去一切诸佛、未来一切已受记佛未受记佛、现在十方一切世界一切诸佛及眷属云，都显现。",
 "过去所行檀波罗蜜及受者施者都显现；过去所修尸波罗蜜，乃至一切行海充满法界都显现。释：毛孔身分既摄法界，如是等类极位菩萨从他方来影响如来，不是自刹常随之众与普贤等，德位齐等。",
 "七、表法众，如诸首菩萨表说信法，因为信为行首；诸慧菩萨表十解法，因为慧能解；诸林表行；诸幢表向；诸藏表地。如是等类，都是寄诸菩萨表行位之法，或十刹尘数，或不可说等，其余依此类推。八、证法众，如诸会末都有他方同名异界大菩萨众俱来作证，现此所说决定究竟。",
 "或一一方各百万佛刹尘数等，都各如文。九、所益众，如诸会中天王、天女等是所益众。又如〈发心功德品〉中，十方虚空法界等世界中，一一各有万佛世界尘数众生，是得益众。〈性起品〉中，十方虚空法界等世界，一一各有一切佛刹微尘等众生。",
 "又说：彼一一世界中，又各有百千佛刹微尘等菩萨，都是所益。第八会初也有所益无边大众。十、显法众，如舍利弗、须菩提等五百声闻，在此法会如聋，借此反显一乘法界，由彼方显此法深广，犹如因皂以现白等。",
 "此众没有结通，因为是别而非普、是相违因。以上十类为器为模，印佛法界，以成无尽法门海。因为无限大悲周遍众生界，施化万品，仪式难量。今就通别各开十例：通而论之，或以音声、或现妙色、或以奇香、或以上味、或以妙触、或以法境、或内六根、或四威仪、或弟子人物、或一切所作都堪摄物，详如不思议品所说。",
 "其次别现言声也有十例：一如来语业圆音自说；二如来毛孔出声说法；三如来光明舒音演法，〈舍那品〉中一切如来毛孔及光明中说偈等；四令菩萨口业说法，如加普贤令说法等；五令菩萨毛孔也出音声说法，同如〈法界品〉说：于一毛孔出一切佛妙法雷音。",
 "又如《密严经》中，金刚藏菩萨遍身毛孔出声说法；六令菩萨光明也有音声说法，〈舍那品〉中诸菩萨光明中说偈等；七令诸刹海出声说法，彼品说：诸宝罗网相扣磨，演佛音声常不绝；八令一切众生都为说法，彼品说：以一切众生言音，入佛音声法门教化。",
 "九以三世音声说法；十以一切法中皆出声说法。故〈普贤行品〉颂说：佛说菩萨说，刹说众生说，三世一切说。释：佛及菩萨各有三说，其余四者各一，故为十。如音声说法有此十种，其余色香等也都各具十，都可依此类推。",
 "这就已成一百门说法。圆教微言，必穷尽法界，既尽如来无尽辩力，各遍虚空毛端刹海，又各穷尽未来际，顿说常说，时处无边，如此之教岂可限其部帙？今依准经文析为十类：一异说经，二同说经，三普眼经，四上本经，五中本经，六下本经，七略本经，八主伴经，九眷属经，十圆满经。",
 "初、异说经，如树形等世界既然不同，其中众生报类也有别，如来于彼现身立教，随彼所宜施设教法差别不同，与虚空法界等，唯如来智之所能知，不可定其色非色等、言非言等。〈舍那品〉中广明树形、河形、须弥山形，乃至一切众生形世界海，末后总结说：都是卢舍那佛常转法轮之处。",
 "释：文中只说常转法轮，不说那法轮的分齐相，因为彼处施设与此不同，所以不显示。都可依此类推，彼处也设如此法教，部类难量，不可说。二、同说经，唯在此类须弥山界，遍于虚空毛端等处，以言声说也没有尽，如〈不思议品〉说：如来一化身，转如是等不可譬喻法轮云，一切法界虚空界等世界，都以毛端周遍度量。",
 "一一毛端处，于念念中化不可说不可说佛刹微尘等身，乃至尽未来际劫。一一化佛身有不可说不可说佛刹微尘等头，一一头有不可说不可说佛刹微尘等舌，一一舌出不可说不可说佛刹微尘等音声，一一音声说不可说不可说佛刹微尘等修多罗，一一修多罗说不可说不可说佛刹微尘等法，一一法中说不可说不可说佛刹微尘等句身味身。",
 "又有不可说不可说佛刹微尘等劫，说异句身味身音声充满法界，一切众生无不闻者，尽一切未来际劫常转法轮，如来音声无异无断，不可穷尽。〈阿僧祇品〉偈也说：彼诸一一如来等，出不可说梵音声；于彼一一梵音中，转不可说净法轮。",
 "于彼一一法轮中，雨不可说修多罗；于彼一一修多罗，分别诸法不可说；于彼一一诸法中，又说诸法不可说；又复于彼说法中，说众生依不可说；又于一一毛道中，不可说劫说正法。如彼一微毛端处，一切十方亦如是。",
 "释：此中说处不是树形等，言声说教不是色香等，所以不同。只是一类无尽，不可结集，不可限其品颂多少，也不是下位所能受持。三、普眼经，如〈法界品〉中海云比丘所受持经，以须弥山聚为笔、四大海水为墨，书写一品修多罗都不可穷尽，如是等品又超过尘数。",
 "这也只是大菩萨等陀罗尼力之所受持，也不是贝叶所能书记。四、上本经，这是结集书记的上本，所以龙树菩萨往龙宫，见此《大不思议解脱经》有三本，上本有十三千大千世界微尘数偈、四天下微尘数品，就是指此。",
 "五、中本经，彼见中本有四十九万八千八百偈、一千一百品。此上二本都秘在龙宫，非阎浮提人力所能持，所以不传。六、下本经，即彼所见下本有十万偈，现传天竺，梁《摄论》中名《百千经》，即十万。",
 "《大智论》中也名此经为《不思议解脱经》，有十万偈。《西域记》说在遮俱槃国山中有此具本。七、略本经，即此土所传的六十卷本，梵本有三万六千偈，是前十万偈中的要略所出。昔晋义熙十四年，于扬州谢司空寺译出，天竺三藏法师名佛度跋陀罗，此云觉贤，是大乘三果人，姓释迦氏，甘露饭王的苗裔，曾往兜率天就弥勒问疑，详如别传。",
 "八、主伴经，即舍那佛所说《华严》虽遍法界，却与余佛所说之经互为主伴，一一主经必具无量同类眷属。如说〈性起品〉竟，十方一一各有八十不可说百千亿那由他佛刹微尘数菩萨，同名普贤，各从本国来此作证，都说……",
 "我等佛所也说此法，与此不殊。所以知道一性起修多罗，十方各有八十不可说百千亿那由他佛刹微尘数修多罗以为眷属。如一处的性起既如此，其余一切处的性起，各摄如许眷属，相与周遍法界。如性起既如此，其余会、其余品文中各有证法之数，都为眷属，依此而释可知。",
 "如此略本七处八会所摄的眷属，当知其余各本都具眷属，依此推思可见。九、眷属经，即此无尽修多罗海，一则一切，十方尘道同时恒说，下位菩萨、二乘、凡夫不能闻见。〈性起品〉说：此经不入一切众生手，唯除菩萨。",
 "又说：一切声闻缘觉不闻此经，何况受持？又说：若菩萨亿那由他劫行六波罗蜜，不闻此经、虽闻不信，这等犹为假名菩萨。释：因为彼器劣，不能闻信此通方之法，而如来以方便，随一方所遇，逐彼根机说其宜闻之法。",
 "如其余一切权教、三乘、小乘等经，既无结通十方齐说，所以不是主经，然而也与主经作殊胜方便，所以只是眷属。因此一一主经必具无量方便眷属，如《普眼经》，有世界尘数修多罗以为眷属。又如《普庄严童子所受持经》，都有尘数眷属等经，详如经说。",
 "问：此与前面的主伴经有何差别？答：略有三别：一、前经文句必与主经相同，此则不尔；二、彼必结通十方同说，此也不尔；三、彼经也有为主之义，此也不尔。所以彼经亦主亦伴，名主伴经；此则唯伴非主，名眷属经。",
 "与彼不同，分为二部。十、圆满经，即此上诸本，总混同一无尽大修多罗海。随于其中一会、一品、一文、一句都具摄一切，以及一一文句遍入一切；因为是普法无分限、圆满教法理应如此、如因陀罗网无分齐、尽佛能化无边境的缘故。",
 "〈舍那品〉偈说：一切佛刹微尘中，卢舍那现自在力，弘誓愿海振音声，调伏一切众生类。又〈法界品〉中名为圆满因缘修多罗，就是指此。无尽教海应如是知。因为义海宏深、真源渺漫，略开二类，各辨十门。",
 "先明所标之法浩汗无涯，撮为十对，用以统收：一、教义一对，即无尽言教及所诠之义。二、理事一对，即缘起事相及所依真理。三、境智一对，即所观真俗妙境及辨能观普贤大智。四、行位一对，即普贤行海及辨菩萨五位相收。",
 "五、因果一对，即辨菩萨生了等因，及现如来智断等果；也是普贤圆因、舍那满果。六、依正一对，即莲华藏界并树形等无边异类诸世界海，及现诸佛菩萨法界身云无碍依持。七、体用一对，即此经中凡举一法，必内同真性、外应群机，没有一法体用不具。",
 "八、人法一对，即佛菩萨师弟等人，显说法界诸法门海。九、逆顺一对，即文中现五热众鞞一王形虐，及现施戒顺理正修。十、应感一对，即众生根欲器感多端，圣应示现也无边，〈舍那品〉说：一切众生所乐示现云。",
 "等。然而此十对同时相应，成一缘起，无碍熔融，随有一处就具一切，是此经中所具之法。其次明所显理趣者，巧辩自在、势变多端，也举十例以现无碍：一性相无碍，二广狭无碍，三一多无碍，四相入无碍，五相是无碍，六隐显无碍，七微细无碍，八帝网无碍，九十世无碍，十主伴无碍。",
 "于前所说十对法中，一一都有此十无碍，所以就有百门千门等，依此推思。今且略于事法上辨此十例，余法依此类推，详如经中。一、一莲华叶即具此十义，即此华叶就同真性，不碍事相、宛然显现，经说：法界不可坏莲华世界海。",
 "等。这是理事一味无碍之门。二、即此华叶必普周，无有边际，而恒不坏本位分齐，这就是分即无分，广狭无碍。经说：此诸华叶普覆法界等。",
 "三、即此华叶具无边之德，不可言一；融无二相，不可言多。此一即多、多又即一，一多无二，为一华叶。经说：知一即多、多即一等。这是第三一多门。",
 "四、此一华叶必舒己遍入一切，差别法中又能摄取彼一切法令入己内，所以即舒恒摄，同时无碍。经说：以一佛土满十方，十方入一亦无余。",
 "等。这是第四相入门。五、此一华叶必废己同他，举体全是彼一切法，而恒摄他同己，全彼一切即是己体；所以己即是他、他即是己，己即是他，己不立；他即是己，他不存；他己存亡同时显现。经说：长劫即是短劫、短劫即是长劫。",
 "等。这是第五相是门。六、又此华叶既遍一切法，彼一切法也都普遍。此能遍彼，则此显彼隐；彼能遍此，则彼显此隐。此能摄彼，也此显彼隐；彼能摄此，也彼显此隐。如是此彼各有即显即隐，无有障碍。",
 "经中：东方见入正受，西方见三昧起等。这是第六隐显门。七、此华叶中全都能显现微细刹土，炳然齐现，无不具足。经说：于一尘中，微细国土庄严清净，旷然安住。又如第九回向微细处所说。这是第七微细门。",
 "八、又此华叶，一一尘中各有无边诸世界海，世界海中又有微尘，此微尘内又有世界，这样重重不可穷尽，不是心识思量的境界。如帝释殿天珠网覆盖，珠既明彻、互相影现，所现之影还能现影，这样重重不可穷尽。",
 "经说：如因陀罗网世界。《十地论》说：帝网差别者，唯智能知，非眼所见。这是第八帝网门。九、此一华叶横遍十方，竖该九世，即过去过去世、过去现在世、过去未来世。如过去世有此三世，现在、未来当知也这样。",
 "总此九世摄为一念，总别合举，名为十世，详如〈离世间品〉所说。又因为时无别体，依华而安立，华既无碍，时也如此，所以经说：过去一切劫，安置未来今；未来一切劫，回置过去世。又说：无量无数劫，能作一念顷。",
 "等。这是第九十世门。十、又此华叶理无孤起，必摄无量眷属围绕。经说：此华有世界海尘数莲华以为眷属。此经圆教所有之法，都互为主伴，具德圆满。所以见此华叶，就是见于无尽法界，不是借此别有所示；下文说：从无生法忍所起华盖。",
 "等。此一华叶既具此等十种无碍，其余一切事也都依此类推。如事中既如此，如前十对法门之中，一一都有如是十种无碍，依此可知。因为法相圆融，实有所因。因缘无量，略辨十种：一为明诸法无定相，二唯心现，三如幻事，四如梦现，五胜通力，六深定用，七解脱力，八因无限，九缘起相由，十法性融通。",
 "于此十中，随一就能令彼诸法混融无碍。初、无定相，即因为小非定小，所以能容大；大非定大，所以能入小。〈十住品〉说：金刚围山数无量，悉能安置一毛端；欲知至大有小相，菩萨因此初发心。释……",
 "此中明大非大，所以有小相。二、明一切法都唯心现，无别自体，所以大小随心回转，即入无碍。又释：谓彼心所现的毛端之处，此心于彼现大世界，大小同处，互不相碍。下文说：彼心不常住，无量难思议，显现一切法，各各不相知。",
