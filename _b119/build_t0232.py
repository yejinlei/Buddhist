 "无分别中就没有知者，若无知者即无言说，无言说之相就是非有非无、非知非不知。一切诸法也是如此。为什么呢？因为一切诸法不见处所，无决定性之故。如逆罪之相不可思议。为什么呢？因为诸法实相不可坏之故。这样的逆罪也没有本性，不生天上、不堕地狱，也不入涅槃。",
 "为什么呢？因为一切业缘都安住于实际，不来不去，非因非果。为什么呢？因为法界无边，无前无后之故。所以，舍利弗！若见犯重罪的比丘不堕地狱，清净行者不入涅槃，这样的比丘非应供、非不应供，非尽漏、非不尽漏。为什么呢？因为于诸法中安住于平等之故。",
 "」舍利弗说：「什么叫不退法忍？」文殊师利说：「不见有少法有生灭之相，名为不退法忍。」舍利弗说：「又叫什么为不调比丘？」文殊师利说：「漏尽的阿罗汉，就名为不调。为什么呢？因为诸结已尽，更无所调伏，所以名为不调。",
 "若超越心之行相，就名为凡夫。为什么呢？因为凡夫众生不随顺法界，所以名为过。」舍利弗说：「善哉，善哉！你如今为我善解漏尽阿罗汉之义。」文殊师利说：「是的，是的！我即是漏尽的真阿罗汉。为什么呢？因为我断除了求声闻之欲及辟支佛之欲，以这个因缘，名为漏尽得阿罗汉。",
 "」佛告诉文殊师利：「诸菩萨等坐道场时，觉悟阿耨多罗三藐三菩提吗？」文殊师利说：「菩萨坐于道场，并没有觉悟阿耨多罗三藐三菩提。为什么呢？因为如同菩提之相，没有少法可得，才名为阿耨多罗三藐三菩提。无相的菩提，谁能坐？也没有起者。",
 "以这个因缘，不见菩萨坐于道场，也不觉证阿耨多罗三藐三菩提。」文殊师利对佛说：「世尊！菩提即五逆，五逆即菩提。为什么呢？因为菩提与五逆，无二相之故。无学与无学者，无见与无见者，无知与无知者，无分别与无分别者，这样的相就名为菩提。",
 "见五逆之相也是如此。若说见有菩提而取证者，当知此辈即是增上慢之人。」那时，世尊告诉文殊师利：「你说我是如来，是说我为如来吗？」文殊师利说：「不是的，世尊！我是说：不是如来而称为如来吗？没有如相可名为如，也没有如来智能了知于如。",
 "为什么呢？因为如来与智，无二相之故。空才是如来，只有名字，我如何说它是如来？」佛告诉文殊师利：「你怀疑如来吗？」文殊师利说：「不是的，世尊！我观如来无决定性，无生无灭，所以无所疑。」佛告诉文殊师利：「你如今不认为如来出现于世间吗？",
 "」文殊师利说：「若有如来出现于世，一切法界也应出现。」佛告诉文殊师利：「你认为恒河沙数诸佛入涅槃吗？」文殊师利说：「诸佛一相，不可思议。」佛对文殊师利说：「是的，是的！佛是一相，是不可思议之相。」",
 "文殊师利对佛说：「世尊！佛如今住世吗？」佛对文殊师利说：「是的，是的！」文殊师利说：「若佛住世，恒河沙数诸佛也应住世。为什么呢？因为一切诸佛皆同一相，即不可思议之相。不可思议之相，无生无灭。若未来诸佛出兴于世，一切诸佛也都出世。",
 "为什么呢？因为不可思议之中，没有过去、未来、现在之相。只是众生取著，说有出世，说佛灭度。」佛对文殊师利说：「这是如来、阿罗汉、阿鞞跋致菩萨所能解。为什么呢？因为这三种人，闻甚深之法，能不诽谤也不赞叹。」文殊师利对佛说：",
 "「世尊！这样不可思议之法，谁会诽谤？谁会赞叹？」佛告诉文殊师利：「如来不可思议，凡夫也不可思议。」文殊师利对佛说：「世尊！凡夫也不可思议吗？」佛说：「也不可思议。为什么呢？因为一切心相都不可思议。」文殊师利说：",
 "「若这样说，如来不可思议，凡夫也不可思议。如今无数诸佛求于涅槃，只是白白疲劳。为什么呢？因为不可思议之法即是涅槃，平等无异之故。」文殊师利说：「是的，凡夫不可思议，诸佛不可思议。若善男子、善女人，久习善根，亲近善知识，才能了知。",
 "」佛告诉文殊师利：「你想让如来在众生中为最殊胜吗？」文殊师利说：「我想让如来在诸众生中为第一，但众生之相也不可得。」佛说：「你想让如来获得不可思议之法吗？」文殊师利说：「欲使如来获得不可思议之法，而于诸法无有成就者。",
 "」佛告诉文殊师利：「你想让如来说法教化吗？」文殊师利对佛说：「我想让如来说法教化，而这说法者及听者都不可得。为什么呢？因为安住法界之故。法界与众生，无差别之相。」佛告诉文殊师利：「你想让如来为无上福田吗？",
 "」文殊师利说：「如来是无尽福田，是无尽之相，无尽之相即无上福田。非福田、非不福田，才名为福田。没有明暗生灭等相，才名为福田。若能这样理解福田之相，深植善种，也无增减。」佛告诉文殊师利：「如何植种，才能不增不减。",
 "」文殊师利说：「福田之相，不可思议。若人于中如法修善，也不可思议。这样植种，名为无增无减，也是无上最胜福田。」那时，大地以佛的神力，六种震动，显现无常之相。一万六千人皆得无生法忍，七百比丘、三千优婆塞、四万优婆夷、六十亿那由他六欲诸天，远离尘垢，于诸法中获得法眼清净。",
 "那时，阿难从座而起，偏袒右肩，右膝著地，对佛说：「世尊！是什么因缘，使这大地六种震动？」佛告诉阿难：「我宣说福田无差别之相，所以现此瑞相。往昔诸佛也曾在此处，这样宣说福田之相，利益众生，一切世界六种震动。",
 "」舍利弗对佛说：「世尊！文殊师利实在不可思议。为什么呢！因为他所说的法相，不可思议。」佛告诉文殊师利：「是的，是的！如舍利弗所说，你所宣说的实在不可思议。」文殊师利对佛说：「世尊！不可思议不可说，思议也不可说。",
 "这样，思议与不可思议之性都不可说。一切声相，非思议也非不可思议。」佛说：「你入不可思议三昧吗？」文殊师利说：「不是的，世尊！我即是不思议，不见有心能思议者。如何说入不可思议三昧？我初发心时想入此定，如今思惟，实在无心相而入三昧。",
 "如同有人学射箭，久习便巧，后来虽然无心，因久习之故，箭发皆中。我也是如此，初学不可思议三昧，系心于一缘，若久习成就，便再无心想，恒与定俱。」舍利弗对文殊师利说：「还有更胜妙的寂灭定吗？」文殊师利说：「若有不可思议之定，你可以问：",
 "『还有寂灭定吗？』依我意解，不可思议之定尚且不可得，如何问有寂灭定呢？」舍利弗说：「不可思议定不可得吗？」文殊师利说：「思议之定，是可得之相；不可思议之定，是不可得之相。一切众生实在成就不思议定。",
 "为什么呢？因为一切心相即非心之故，名为不可思议定。所以一切众生之相及不可思议三昧之相，平等无分别。」佛赞叹文殊师利说：「善哉，善哉！你于诸佛处久植善根，净修梵行，才能演说甚深三昧。你如今安住于这样的般若波罗蜜之中。",
 "」文殊师利说：「若我安住般若波罗蜜中，能作这样的宣说，就是有想，便安住于我想。若安住于有想、我想之中，般若波罗蜜便有处所。般若波罗蜜若安住于无，也是我想，也叫处所。远离此二处，安住于无所住，如诸佛所住，安处于寂灭非思议的境界。",
 "这样的不可思议，名为般若波罗蜜的住处。般若波罗蜜之处，一切法无相，一切法无作。般若波罗蜜即不可思议，不可思议即法界，法界即无相，无相即不可思议，不可思议即般若波罗蜜。般若波罗蜜与法界，无二无别。无二无别即法界，法界即无相，无相即般若波罗蜜界。",
 "般若波罗蜜界即不可思议界，不可思议界即无生无灭界，无生无灭界即不可思议界。」文殊师利说：「如来界及我界，即是不二之相。这样修般若波罗蜜的人就不求菩提。为什么呢？因为菩提之相远离，即是般若波罗蜜之故。世尊！",
 "若知我相而不可著，无知无著就是佛所知。不可思议的无知无著，即是佛所知。为什么呢？因为知的本性没有所有之相。如何能转法界？若知本性无体无著，就名为无物。若没有物，就是无处所，无依无住。无依无住即无生无灭，无生无灭即是有为无为的功德。",
 "若这样知，就无心想。无心想者，如何当知有为无为的功德？无知即不可思议，不可思议即是佛所知，也无取无不取，不见三世去来等相，不取生灭及诸起作，也不断不常。这样知的人名为正智。不可思议之智如虚空，无此无彼，不可比类，无好恶，无等等，无相无貌。",
 "」佛告诉文殊师利：「若这样知，名为不退智。」文殊师利说：「无作之智名为不退智，犹如金锭先加以锤打才知好恶。若不治打，就无人能知。不退智之相也是如此。须于行境界中，不念不著，无起无作，具足不动，不生不灭，方才显现。",
 "」那时，佛告诉文殊师利说：「如诸如来自己宣说己智，谁能相信？」文殊师利说：「这样的智者，非涅槃法、非生死法，是寂灭之行，是无动之行，不断贪欲、瞋恚、愚痴，也非不断。为什么呢？因为无尽无灭，不离生死也非不离，不修道也非不修道。",
 "作这样理解的人，名为正信。」佛告诉文殊师利说：「善哉，善哉！如你所说，深解此义。」那时，摩诃迦叶对佛说：「世尊！在当来之世，若宣说这样甚深的正法，谁能信解、如所闻而受行？」佛告诉迦叶：「如今此会中的比丘、比丘尼、优婆塞、优婆夷，得闻此经的人，这些人等于未来世若闻此法，必能信解甚深般若波罗蜜，才能读诵、信解、受持，也能为他人分别演说。",
 "譬如长者丢失了摩尼宝，忧愁苦恼。后来若再得到，心中大为欢喜。迦叶！比丘、比丘尼、优婆塞、优婆夷等也是如此，怀有信乐之心。若不闻法就生苦恼，若得闻法时，便信解受持，常乐读诵，甚大欢喜。当知此人，即是见佛，也就是亲近供养诸佛。",
 "」佛告诉迦叶：「譬如忉利天上的波利质多罗树，花苞初出时，其中的诸天见到这树，都大为欢喜，知道此树不久必定开花。若比丘、比丘尼、优婆塞、优婆夷，得闻般若波罗蜜，能生信解，也是如此。此人不久也当开敷一切佛法。",
 "在当来之世，有比丘、比丘尼、优婆塞、优婆夷，闻般若波罗蜜，信受读诵，心中不退不没。当知此人，已在此会中听受此经，也能为人于聚落城邑广说流布。当知此人，为佛所护念。在这甚深般若波罗蜜中，有能信乐、无疑惑的善男子、善女人，都是于过去诸佛处久已修学、种植众善根的人。",
 "譬如有人用手穿珠，忽然遇到无上真摩尼宝，心中大为欢喜。当知此人必定曾经见过。迦叶！若善男子、善女人，修学其余法门，忽然得闻甚深般若波罗蜜，能生欢喜，也是如此。当知此人，曾经闻过之故。若有众生得闻甚深般若波罗蜜，心中能信受，生大欢喜。",
 "这样的人等也曾亲近无数诸佛，因为曾闻般若波罗蜜、已修学之故。譬如有人，先前曾经见过某城邑聚落，后来若听人赞叹那座城，说那里所有的园苑、种种池泉、花果林树、男女人民，都可爱乐。此人听了，就大为欢喜，更劝请对方多讲，说那城的园苑种种美好严饰，杂花池泉、多种甘果，种种珍妙、一切爱乐。",
 "此人得闻，更加欢喜。这样的人，都是曾经见过之故。若善男子、善女人，有闻般若波罗蜜，信心听受，能生欢喜，乐闻不厌，而更劝他人宣说。当知此辈，是已从文殊师利处，曾闻这样的般若波罗蜜之故。」迦叶对佛说：「世尊！",
 "若将来世的善男子、善女人，得闻这甚深般若波罗蜜，信乐听受。以此相状，当知此人也曾于过去佛所闻法修学。」文殊师利对佛说：「世尊！佛说诸法，无作无相，第一寂灭。若善男子、善女人，有能这样真实了达此义，如所闻而说，就为诸如来所赞叹。",
 "不违法相，这就是佛说，也是炽然般若波罗蜜之相，也叫炽然具足佛法，通达实相，不可思议。」佛告诉文殊师利：「我本来行菩萨道时，修诸善根，想安住于阿鞞跋致之地，就应当学般若波罗蜜。想成就阿耨多罗三藐三菩提，就应当学般若波罗蜜。",
 "若善男子、善女人，想解了一切法相，想知道一切众生心界都悉同等，就应当学般若波罗蜜。文殊师利！想学一切佛法具足无碍，就应当学般若波罗蜜。想学一切佛成阿耨多罗三藐三菩提时的相好威仪、无量法式，就应当学般若波罗蜜。",
 "想知道一切佛不成阿耨多罗三藐三菩提的一切法式及诸威仪，就应当学般若波罗蜜。为什么呢？因为在这空法之中，不见诸佛、菩提等之故。若善男子、善女人，想知道这样等相而无疑惑，就应当学般若波罗蜜。为什么呢？因为般若波罗蜜，不见诸法或生或灭、或垢或净。",
 "所以善男子、善女人，应当这样学般若波罗蜜。想知道一切法没有过去、未来、现在等相，就应当学般若波罗蜜。为什么呢？因为法界性相没有三世之故。想知道一切法同入法界、心无挂碍，就应当学般若波罗蜜。想得三转十二行法轮，也自己证知而不取著，就应当学般若波罗蜜。",
 "想得慈心遍覆一切众生而无有限齐，也不作念有众生相，就应当学般若波罗蜜。想得对一切众生不起诤论，也不取无诤论之相，就应当学般若波罗蜜。想知道是处非处、十力、无畏，安住佛智慧得无碍辩才，就应当学般若波罗蜜。",
 "」那时，文殊师利对佛说：「世尊！我观正法，无为无相，无得无利，无生无灭，无来无去，没有知者、没有见者、没有作者。不见般若波罗蜜，也不见般若波罗蜜的境界，非证非不证。不作戏论，没有分别。一切法无尽离尽，没有凡夫法，没有声闻法，没有辟支佛法、佛法。",
 "非得非不得，不舍生死，不证涅槃。非思议非不思议，非作非不作。法相就是这样。不知应当如何学般若波罗蜜？」那时，佛告诉文殊师利：「若能这样知诸法相，就名为当学般若波罗蜜。菩萨摩诃萨若想学菩提自在三昧，得此三昧后，照明一切甚深佛法，及了知一切诸佛名字，也完全了达诸佛世界，无有障碍，就应当如文殊师利所说的般若波罗蜜中而学。",
 "」文殊师利对佛说：「世尊！为什么叫般若波罗蜜？」佛说：「般若波罗蜜无边无际，无名无相，非思量，无归依，无洲渚，无犯无福，无晦无明，犹如法界，没有分齐，也无限数，这就叫般若波罗蜜，也叫菩萨摩诃萨的行处。",
 "非处也非不行处，都入于一乘，名为非行处。为什么呢？因为无念无作之故。」文殊师利对佛说：「世尊！应当如何行，才能速得阿耨多罗三藐三菩提？」佛说：「文殊师利！如般若波罗蜜所说的行，能速得阿耨多罗三藐三菩提。",
